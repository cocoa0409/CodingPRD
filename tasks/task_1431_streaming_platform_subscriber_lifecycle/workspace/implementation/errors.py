ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_UNAUTHORIZED = ("ERR_UNAUTHORIZED", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_ACCOUNT_SUSPENDED = ("ERR_ACCOUNT_SUSPENDED", 409)
ERR_OFFER_EXPIRED = ("ERR_OFFER_EXPIRED", 422)
ERR_REFERENTIAL_INTEGRITY = ("ERR_REFERENTIAL_INTEGRITY", 422)
ERR_PLAN_RULE_VIOLATION = ("ERR_PLAN_RULE_VIOLATION", 422)
ERR_HOUSEHOLD_LIMIT_EXCEEDED = ("ERR_HOUSEHOLD_LIMIT_EXCEEDED", 422)
ERR_PAYMENT_FAILED = ("ERR_PAYMENT_FAILED", 402)
ERR_OUTSTANDING_BALANCE = ("ERR_OUTSTANDING_BALANCE", 402)
ERR_WINBACK_INELIGIBLE = ("ERR_WINBACK_INELIGIBLE", 422)
