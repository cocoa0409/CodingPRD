"""Error identifier catalogue for the fire-staffing-overtime API.

Mirrors the PRD error code catalogue one-for-one, and registers the
error_id -> HTTP status mapping with the shared response validators so that
every ``validate_error`` call cross-checks the status code automatically.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    """Every error identifier the API is allowed to return."""

    # Authentication / authorisation
    UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Shape / syntax
    INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # Existence
    STATION_NOT_FOUND = "ERR_STATION_NOT_FOUND"
    FIREFIGHTER_NOT_FOUND = "ERR_FIREFIGHTER_NOT_FOUND"
    DUTY_SHIFT_NOT_FOUND = "ERR_DUTY_SHIFT_NOT_FOUND"
    VACANCY_NOT_FOUND = "ERR_VACANCY_NOT_FOUND"
    OFFER_NOT_FOUND = "ERR_OFFER_NOT_FOUND"
    LEAVE_REQUEST_NOT_FOUND = "ERR_LEAVE_REQUEST_NOT_FOUND"
    TRADE_REQUEST_NOT_FOUND = "ERR_TRADE_REQUEST_NOT_FOUND"
    RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"

    # Optimistic concurrency
    STALE_VERSION = "ERR_STALE_VERSION"

    # Lifecycle state
    SHIFT_NOT_DRAFT = "ERR_SHIFT_NOT_DRAFT"
    SHIFT_NOT_HIRING = "ERR_SHIFT_NOT_HIRING"
    SHIFT_NOT_ELAPSED = "ERR_SHIFT_NOT_ELAPSED"
    VACANCY_NOT_OFFERABLE = "ERR_VACANCY_NOT_OFFERABLE"
    OFFER_NOT_PENDING = "ERR_OFFER_NOT_PENDING"
    LEAVE_NOT_REVOCABLE = "ERR_LEAVE_NOT_REVOCABLE"
    TRADE_STATE_INVALID = "ERR_TRADE_STATE_INVALID"
    ASSIGNMENT_NOT_SCHEDULED = "ERR_ASSIGNMENT_NOT_SCHEDULED"

    # Referential / scope semantics
    STATION_SCOPE_MISMATCH = "ERR_STATION_SCOPE_MISMATCH"
    CERTIFICATION_NOT_HELD = "ERR_CERTIFICATION_NOT_HELD"
    LEAVE_ALREADY_BACKFILLED = "ERR_LEAVE_ALREADY_BACKFILLED"
    ROSTER_NOT_CONFIGURED = "ERR_ROSTER_NOT_CONFIGURED"

    # Domain rules, in validation precedence order
    PLATOON_ROTATION_VIOLATION = "ERR_PLATOON_ROTATION_VIOLATION"
    KELLY_DAY_CONFLICT = "ERR_KELLY_DAY_CONFLICT"
    DOUBLE_BOOKED_SHIFT = "ERR_DOUBLE_BOOKED_SHIFT"
    TRADE_WINDOW_CLOSED = "ERR_TRADE_WINDOW_CLOSED"
    REST_PERIOD_VIOLATION = "ERR_REST_PERIOD_VIOLATION"
    STAFFING_FLOOR_BREACH = "ERR_STAFFING_FLOOR_BREACH"
    APPARATUS_SEAT_CAPACITY_EXCEEDED = "ERR_APPARATUS_SEAT_CAPACITY_EXCEEDED"
    FLSA_WORK_PERIOD_CAP_EXCEEDED = "ERR_FLSA_WORK_PERIOD_CAP_EXCEEDED"
    NO_ELIGIBLE_CANDIDATE = "ERR_NO_ELIGIBLE_CANDIDATE"
    NO_CLOSURE_ELIGIBLE_COMPANY = "ERR_NO_CLOSURE_ELIGIBLE_COMPANY"
    CLOSURE_NOT_JUSTIFIED = "ERR_CLOSURE_NOT_JUSTIFIED"
    OT_BUDGET_WOULD_EXCEED = "ERR_OT_BUDGET_WOULD_EXCEED"


