"""Error IDs and HTTP status mapping (PRD Section 5).

Registers the mapping with the framework so validate_error() can cross-check
HTTP status codes automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_SHOWTIME_VERSION = "ERR_STALE_SHOWTIME_VERSION"
    ERR_MATINEE_WINDOW_VIOLATION = "ERR_MATINEE_WINDOW_VIOLATION"
    ERR_AUDITORIUM_DOUBLE_BOOKED = "ERR_AUDITORIUM_DOUBLE_BOOKED"
    ERR_RENTAL_FEE_INVALID = "ERR_RENTAL_FEE_INVALID"
    ERR_SEAT_NOT_ON_SHOWTIME = "ERR_SEAT_NOT_ON_SHOWTIME"
    ERR_SEAT_UNAVAILABLE = "ERR_SEAT_UNAVAILABLE"
    ERR_NO_SEATS_SELECTED = "ERR_NO_SEATS_SELECTED"
    ERR_MEMBER_DOUBLE_BOOKED = "ERR_MEMBER_DOUBLE_BOOKED"
    ERR_RENTAL_NO_SEAT_SALES = "ERR_RENTAL_NO_SEAT_SALES"
    ERR_INSUFFICIENT_WALLET_CREDIT = "ERR_INSUFFICIENT_WALLET_CREDIT"
    ERR_PAST_SHOWTIME = "ERR_PAST_SHOWTIME"
    ERR_INVALID_SPLIT_SCHEDULE = "ERR_INVALID_SPLIT_SCHEDULE"
    ERR_SHOWTIME_NOT_OVER = "ERR_SHOWTIME_NOT_OVER"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_SHOWTIME_VERSION: 412,
    ApiErrorId.ERR_MATINEE_WINDOW_VIOLATION: 422,
    ApiErrorId.ERR_AUDITORIUM_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_RENTAL_FEE_INVALID: 422,
    ApiErrorId.ERR_SEAT_NOT_ON_SHOWTIME: 422,
    ApiErrorId.ERR_SEAT_UNAVAILABLE: 409,
    ApiErrorId.ERR_NO_SEATS_SELECTED: 422,
    ApiErrorId.ERR_MEMBER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_RENTAL_NO_SEAT_SALES: 409,
    ApiErrorId.ERR_INSUFFICIENT_WALLET_CREDIT: 422,
    ApiErrorId.ERR_PAST_SHOWTIME: 409,
    ApiErrorId.ERR_INVALID_SPLIT_SCHEDULE: 422,
    ApiErrorId.ERR_SHOWTIME_NOT_OVER: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
