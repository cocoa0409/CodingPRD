"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition the mapping is registered with the framework so that
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / authorization (PRD §2.1, §5)
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_TEAM_OWNER = "ERR_NOT_TEAM_OWNER"
    ERR_NOT_ELIGIBLE_VOTER = "ERR_NOT_ELIGIBLE_VOTER"

    # Existence (PRD §2.7, §5)
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # State / concurrency (PRD §2.8, §3, §5)
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Draft / roster business (PRD §3.3, §3.4, §3.6, §5)
    ERR_PLAYER_ALREADY_DRAFTED = "ERR_PLAYER_ALREADY_DRAFTED"
    ERR_PLAYER_ALREADY_ROSTERED = "ERR_PLAYER_ALREADY_ROSTERED"
    ERR_PLAYER_NOT_ON_ROSTER = "ERR_PLAYER_NOT_ON_ROSTER"
    ERR_PLAYER_NO_LONGER_ELIGIBLE = "ERR_PLAYER_NO_LONGER_ELIGIBLE"
    ERR_PLAYER_NOT_IN_WAIVERS = "ERR_PLAYER_NOT_IN_WAIVERS"
    ERR_LINEUP_LOCKED = "ERR_LINEUP_LOCKED"
    ERR_IR_INELIGIBLE = "ERR_IR_INELIGIBLE"
    ERR_ROSTER_SHAPE_INVALID = "ERR_ROSTER_SHAPE_INVALID"
    ERR_ROSTER_FULL = "ERR_ROSTER_FULL"
    ERR_POSITION_CONSTRAINT = "ERR_POSITION_CONSTRAINT"
    ERR_POSITION_INELIGIBLE = "ERR_POSITION_INELIGIBLE"

    # Fiscal (PRD §3.3, §3.6, §5)
    ERR_FAAB_INSUFFICIENT = "ERR_FAAB_INSUFFICIENT"
    ERR_AUCTION_BUDGET_EXCEEDED = "ERR_AUCTION_BUDGET_EXCEEDED"

    # Temporal (PRD §3.6, §5)
    ERR_WAIVER_SETTLE_IN_PAST = "ERR_WAIVER_SETTLE_IN_PAST"

    # Keepers / draft (PRD §3.2, §3.3, §5)
    ERR_KEEPER_CAP_EXCEEDED = "ERR_KEEPER_CAP_EXCEEDED"
    ERR_NOT_YOUR_TURN = "ERR_NOT_YOUR_TURN"

    # Trades (PRD §3.7, §5)
    ERR_TWO_WAY_FAAB_FORBIDDEN = "ERR_TWO_WAY_FAAB_FORBIDDEN"
    ERR_TRADE_NOT_OPEN_FOR_VOTING = "ERR_TRADE_NOT_OPEN_FOR_VOTING"

    # Generic shape/range (PRD §2.9, §3.1, §5)
    ERR_VALIDATION = "ERR_VALIDATION"


# Per PRD §5 Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_TEAM_OWNER: 403,
    ApiErrorId.ERR_NOT_ELIGIBLE_VOTER: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_PLAYER_ALREADY_DRAFTED: 409,
    ApiErrorId.ERR_PLAYER_ALREADY_ROSTERED: 409,
    ApiErrorId.ERR_PLAYER_NOT_ON_ROSTER: 422,
    ApiErrorId.ERR_PLAYER_NO_LONGER_ELIGIBLE: 409,
    ApiErrorId.ERR_PLAYER_NOT_IN_WAIVERS: 422,
    ApiErrorId.ERR_LINEUP_LOCKED: 409,
    ApiErrorId.ERR_IR_INELIGIBLE: 422,
    ApiErrorId.ERR_ROSTER_SHAPE_INVALID: 422,
    ApiErrorId.ERR_ROSTER_FULL: 422,
    ApiErrorId.ERR_POSITION_CONSTRAINT: 422,
    ApiErrorId.ERR_POSITION_INELIGIBLE: 422,
    ApiErrorId.ERR_FAAB_INSUFFICIENT: 422,
    ApiErrorId.ERR_AUCTION_BUDGET_EXCEEDED: 422,
    ApiErrorId.ERR_WAIVER_SETTLE_IN_PAST: 422,
    ApiErrorId.ERR_KEEPER_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_NOT_YOUR_TURN: 409,
    ApiErrorId.ERR_TWO_WAY_FAAB_FORBIDDEN: 422,
    ApiErrorId.ERR_TRADE_NOT_OPEN_FOR_VOTING: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
