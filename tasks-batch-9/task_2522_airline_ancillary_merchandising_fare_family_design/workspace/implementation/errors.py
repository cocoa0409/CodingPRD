DEFAULT_MESSAGE = {
    'ERR_MISSING_AUTH_HEADERS': 'X-User-ID and X-User-Role headers are required.',
    'ERR_ROLE_NOT_PERMITTED': 'The acting role is not permitted for this operation.',
    'ERR_INVALID_REQUEST': 'The request payload or query parameters are invalid.',
}


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        super(ApiError, self).__init__(error_id)
        self.error_id = error_id
        self.http_status = ERROR_HTTP.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGE.get(
            error_id, error_id.replace('ERR_', '').replace('_', ' ').capitalize() + '.')


def fail(error_id, message=None):
    raise ApiError(error_id, message)


def invalid(message=None):
    raise ApiError('ERR_INVALID_REQUEST', message)
