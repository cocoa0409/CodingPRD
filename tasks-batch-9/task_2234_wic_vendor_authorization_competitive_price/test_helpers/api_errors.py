    # Optimistic concurrency
    STALE_CLAIM_VERSION = "ERR_STALE_CLAIM_VERSION"
    STALE_VENDOR_VERSION = "ERR_STALE_VENDOR_VERSION"

    # State machines
    INVALID_VENDOR_STATE = "ERR_INVALID_VENDOR_STATE"
    INVALID_CYCLE_STATE = "ERR_INVALID_CYCLE_STATE"
    INVALID_SUBMISSION_STATE = "ERR_INVALID_SUBMISSION_STATE"
    INVALID_VISIT_STATE = "ERR_INVALID_VISIT_STATE"
    INVALID_CLAIM_STATE = "ERR_INVALID_CLAIM_STATE"
    INVALID_ADJUSTMENT_STATE = "ERR_INVALID_ADJUSTMENT_STATE"
    INVALID_SANCTION_STATE = "ERR_INVALID_SANCTION_STATE"

    # Cross-entity business rules
    CLAIM_NOT_ADJUDICATED = "ERR_CLAIM_NOT_ADJUDICATED"
    CLAIM_ALREADY_PAID = "ERR_CLAIM_ALREADY_PAID"
    VENDOR_NOT_MONITORABLE = "ERR_VENDOR_NOT_MONITORABLE"
    VENDOR_TRAINING_EXPIRED = "ERR_VENDOR_TRAINING_EXPIRED"
    OPEN_SANCTION_CASE_EXISTS = "ERR_OPEN_SANCTION_CASE_EXISTS"
    VENDOR_DISQUALIFIED = "ERR_VENDOR_DISQUALIFIED"
    COMPLIANCE_BUY_NOT_WARRANTED = "ERR_COMPLIANCE_BUY_NOT_WARRANTED"
    CMP_NOT_PERMITTED = "ERR_CMP_NOT_PERMITTED"
    CMP_ELECTION_WINDOW_EXPIRED = "ERR_CMP_ELECTION_WINDOW_EXPIRED"
    ELECTION_WINDOW_OPEN = "ERR_ELECTION_WINDOW_OPEN"
    DISQUALIFICATION_NOT_AVAILABLE = "ERR_DISQUALIFICATION_NOT_AVAILABLE"
    VISIT_DATE_IN_PAST = "ERR_VISIT_DATE_IN_PAST"
    VISIT_BLACKOUT_CONFLICT = "ERR_VISIT_BLACKOUT_CONFLICT"
    DUPLICATE_OBSERVATION = "ERR_DUPLICATE_OBSERVATION"
    SUBMISSION_WINDOW_CLOSED = "ERR_SUBMISSION_WINDOW_CLOSED"
    DUPLICATE_PRICE_SUBMISSION = "ERR_DUPLICATE_PRICE_SUBMISSION"
    REVISION_LIMIT_REACHED = "ERR_REVISION_LIMIT_REACHED"
    PEER_GROUP_RETIRED = "ERR_PEER_GROUP_RETIRED"
    PRICE_SUBMISSIONS_INCOMPLETE = "ERR_PRICE_SUBMISSIONS_INCOMPLETE"
    NO_PEER_GROUP_MATCH = "ERR_NO_PEER_GROUP_MATCH"
    NO_PUBLISHED_PRICE_CYCLE = "ERR_NO_PUBLISHED_PRICE_CYCLE"
