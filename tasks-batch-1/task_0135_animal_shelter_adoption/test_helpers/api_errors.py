"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CHIP_MISMATCH = "ERR_CHIP_MISMATCH"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_STRAY_HOLD_ACTIVE = "ERR_STRAY_HOLD_ACTIVE"
    ERR_NOT_MEDICALLY_CLEARED = "ERR_NOT_MEDICALLY_CLEARED"
    ERR_KENNEL_OCCUPIED = "ERR_KENNEL_OCCUPIED"
    ERR_FOSTER_HOME_FULL = "ERR_FOSTER_HOME_FULL"
    ERR_FOSTER_COOLDOWN = "ERR_FOSTER_COOLDOWN"
    ERR_APPLICATION_CONFLICT = "ERR_APPLICATION_CONFLICT"
    ERR_DUPLICATE_CHIP = "ERR_DUPLICATE_CHIP"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CHIP_MISMATCH: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_STRAY_HOLD_ACTIVE: 409,
    ApiErrorId.ERR_NOT_MEDICALLY_CLEARED: 409,
    ApiErrorId.ERR_KENNEL_OCCUPIED: 409,
    ApiErrorId.ERR_FOSTER_HOME_FULL: 409,
    ApiErrorId.ERR_FOSTER_COOLDOWN: 409,
    ApiErrorId.ERR_APPLICATION_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_CHIP: 409,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
