"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_DELINQUENCY_DATE = "ERR_INVALID_DELINQUENCY_DATE"
    ERR_STALE_FILE_VERSION = "ERR_STALE_FILE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEADLINE_BREACHED = "ERR_DEADLINE_BREACHED"
    ERR_FILE_FROZEN = "ERR_FILE_FROZEN"
    ERR_FURNISHER_SUSPENDED = "ERR_FURNISHER_SUSPENDED"
    ERR_TRADELINE_NOT_DISPUTABLE = "ERR_TRADELINE_NOT_DISPUTABLE"
    ERR_DUPLICATE_DISPUTE = "ERR_DUPLICATE_DISPUTE"
    ERR_OVERLAPPING_INVESTIGATION = "ERR_OVERLAPPING_INVESTIGATION"
    ERR_REOPEN_LIMIT_REACHED = "ERR_REOPEN_LIMIT_REACHED"
    ERR_MISSING_CORRECTED_BALANCE = "ERR_MISSING_CORRECTED_BALANCE"
    ERR_FREEZE_OVERLAP = "ERR_FREEZE_OVERLAP"
    ERR_COMPLAINT_PREMATURE = "ERR_COMPLAINT_PREMATURE"
    ERR_INVALID_DECISION = "ERR_INVALID_DECISION"
    ERR_PAGINATION_RANGE = "ERR_PAGINATION_RANGE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_DELINQUENCY_DATE: 422,
    ApiErrorId.ERR_STALE_FILE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEADLINE_BREACHED: 409,
    ApiErrorId.ERR_FILE_FROZEN: 409,
    ApiErrorId.ERR_FURNISHER_SUSPENDED: 409,
    ApiErrorId.ERR_TRADELINE_NOT_DISPUTABLE: 409,
    ApiErrorId.ERR_DUPLICATE_DISPUTE: 409,
    ApiErrorId.ERR_OVERLAPPING_INVESTIGATION: 409,
    ApiErrorId.ERR_REOPEN_LIMIT_REACHED: 409,
    ApiErrorId.ERR_MISSING_CORRECTED_BALANCE: 422,
    ApiErrorId.ERR_FREEZE_OVERLAP: 409,
    ApiErrorId.ERR_COMPLAINT_PREMATURE: 409,
    ApiErrorId.ERR_INVALID_DECISION: 422,
    ApiErrorId.ERR_PAGINATION_RANGE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
