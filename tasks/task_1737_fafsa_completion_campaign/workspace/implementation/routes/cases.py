@bp.route("/fafsa/support-cases/<cid>/assign", methods=["POST"])
def assign_case(cid):
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["CampaignAdmin"])
    case = core.get_case_or_404(cid)
    body = validate.get_json_body(required=True)
    validate.check_fields(body, required=["specialist_id"], optional=[])
    specialist_id = validate.req_string(body, "specialist_id")
    specialist = core.get_staff_or_404(specialist_id)
    # Assignee must be ACTIVE with CASE_SPECIALIST capability
    if specialist["status"] != "ACTIVE" or "CASE_SPECIALIST" not in (specialist.get("capabilities") or []):
        errors.raise_error(errors.ERR_STAFF_LACKS_CAPABILITY, "Assignee must be ACTIVE with CASE_SPECIALIST capability")
    old_id = case.get("assigned_specialist_id")
    counts_active = case["status"] in core.ACTIVE_CASE_STATUSES
    case["assigned_specialist_id"] = specialist_id
    touch(case)
    if counts_active:
        if old_id and old_id != specialist_id:
            core.bump_case_count(old_id, -1)
        if old_id != specialist_id:
            core.bump_case_count(specialist_id, 1)
    return success_object(core.serialize(case))


def _case_action(cid, expected_from, to_status, role_check=True):
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["Specialist"])
    case = core.get_case_or_404(cid)
    if case["status"] not in expected_from:
        errors.raise_error(errors.ERR_CASE_NOT_ACTIONABLE, "Case not in a state permitting this action")
    if role_check:
        if case.get("assigned_specialist_id") is None:
            errors.raise_error(errors.ERR_CASE_UNASSIGNED, "Case has no assigned specialist")
        middleware.require_ownership(auth, case["assigned_specialist_id"])
    case["status"] = to_status
    touch(case)
    return auth, case


