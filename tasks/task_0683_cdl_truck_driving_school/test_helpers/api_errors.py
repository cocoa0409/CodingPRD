"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DOCUMENT_EXPIRED = "ERR_DOCUMENT_EXPIRED"
    ERR_PREREQ_NOT_MET = "ERR_PREREQ_NOT_MET"
    ERR_EXAMINER_CONFLICT = "ERR_EXAMINER_CONFLICT"
    ERR_EXAMINER_NOT_CERTIFIED = "ERR_EXAMINER_NOT_CERTIFIED"
    ERR_TRUCK_CLASS_MISMATCH = "ERR_TRUCK_CLASS_MISMATCH"
    ERR_TRUCK_DOUBLE_BOOKED = "ERR_TRUCK_DOUBLE_BOOKED"
    ERR_INSTRUCTOR_DOUBLE_BOOKED = "ERR_INSTRUCTOR_DOUBLE_BOOKED"
    ERR_ENROLLMENT_NOT_TRAINING = "ERR_ENROLLMENT_NOT_TRAINING"
    ERR_SESSION_NOT_ELAPSED = "ERR_SESSION_NOT_ELAPSED"
    ERR_SESSION_LOCKED = "ERR_SESSION_LOCKED"
    ERR_ENROLLMENT_NOT_TEST_READY = "ERR_ENROLLMENT_NOT_TEST_READY"
    ERR_SPONSORSHIP_CONFLICT = "ERR_SPONSORSHIP_CONFLICT"
    ERR_ENROLLMENT_NOT_PASSED = "ERR_ENROLLMENT_NOT_PASSED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DOCUMENT_EXPIRED: 409,
    ApiErrorId.ERR_PREREQ_NOT_MET: 409,
    ApiErrorId.ERR_EXAMINER_CONFLICT: 409,
    ApiErrorId.ERR_EXAMINER_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_TRUCK_CLASS_MISMATCH: 409,
    ApiErrorId.ERR_TRUCK_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_INSTRUCTOR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_ENROLLMENT_NOT_TRAINING: 409,
    ApiErrorId.ERR_SESSION_NOT_ELAPSED: 409,
    ApiErrorId.ERR_SESSION_LOCKED: 409,
    ApiErrorId.ERR_ENROLLMENT_NOT_TEST_READY: 409,
    ApiErrorId.ERR_SPONSORSHIP_CONFLICT: 409,
    ApiErrorId.ERR_ENROLLMENT_NOT_PASSED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
