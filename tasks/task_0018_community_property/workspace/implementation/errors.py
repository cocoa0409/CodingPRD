"""Custom exception class and canonical error IDs for the community property API."""


class APIError(Exception):
    """Carries an error_id (machine-readable), a human message, and an HTTP status."""

    def __init__(self, error_id: str, message: str, http_status: int):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


