class ApiError(Exception):
    def __init__(self, error_id, message=None):
        self.error_id = error_id
        self.http_status = ERROR_STATUS.get(error_id, 422)
        if message is None:
            message = DEFAULT_MESSAGES.get(
                error_id,
                "Request refused: " + error_id.replace("ERR_", "").replace("_", " ").lower() + ".",
            )
        self.message = message
        super().__init__(self.message)


def invalid(detail=None):
    if detail:
        return ApiError("ERR_INVALID_REQUEST", "Request failed validation: " + detail + ".")
    return ApiError("ERR_INVALID_REQUEST")
