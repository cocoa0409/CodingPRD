ERR_HOT_WORK_PERMIT_CONFLICT = "ERR_HOT_WORK_PERMIT_CONFLICT"
ERR_WARRANTY_EXPIRED = "ERR_WARRANTY_EXPIRED"

# --- Referential business ---
ERR_DEPENDENCY_NOT_MET = "ERR_DEPENDENCY_NOT_MET"
ERR_WORK_ITEM_NOT_IN_PROJECT = "ERR_WORK_ITEM_NOT_IN_PROJECT"

# --- Fiscal ---
