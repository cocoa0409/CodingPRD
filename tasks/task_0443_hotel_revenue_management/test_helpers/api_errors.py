"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_ROOM_TYPE_CODE = "ERR_DUPLICATE_ROOM_TYPE_CODE"
    ERR_MASTER_BAR_EXISTS = "ERR_MASTER_BAR_EXISTS"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PLAN_CLOSED = "ERR_PLAN_CLOSED"
    ERR_LOS_VIOLATION = "ERR_LOS_VIOLATION"
    ERR_MISSING_INVENTORY_DAY = "ERR_MISSING_INVENTORY_DAY"
    ERR_NOT_EVALUATED = "ERR_NOT_EVALUATED"
    ERR_OVERSELL_LIMIT_EXCEEDED = "ERR_OVERSELL_LIMIT_EXCEEDED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_RATE_NOT_PUBLISHED = "ERR_RATE_NOT_PUBLISHED"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_DUPLICATE_INVENTORY_DAY = "ERR_DUPLICATE_INVENTORY_DAY"
    ERR_CHANNEL_ALREADY_MAPPED = "ERR_CHANNEL_ALREADY_MAPPED"
    ERR_INVALID_LOS_BAND = "ERR_INVALID_LOS_BAND"
    ERR_RATE_BELOW_FLOOR = "ERR_RATE_BELOW_FLOOR"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_ROOM_TYPE_CODE: 409,
    ApiErrorId.ERR_MASTER_BAR_EXISTS: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PLAN_CLOSED: 409,
    ApiErrorId.ERR_LOS_VIOLATION: 422,
    ApiErrorId.ERR_MISSING_INVENTORY_DAY: 409,
    ApiErrorId.ERR_NOT_EVALUATED: 409,
    ApiErrorId.ERR_OVERSELL_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_RATE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_DUPLICATE_INVENTORY_DAY: 409,
    ApiErrorId.ERR_CHANNEL_ALREADY_MAPPED: 409,
    ApiErrorId.ERR_INVALID_LOS_BAND: 422,
    ApiErrorId.ERR_RATE_BELOW_FLOOR: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
