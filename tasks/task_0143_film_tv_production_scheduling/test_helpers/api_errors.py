"""Error IDs and HTTP status mapping (PRD Section 5).

Registers the map with the framework so ``validate_error()`` auto-checks the
HTTP status code corresponding to each error_id.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CROSS_PRODUCTION_REFERENCE = "ERR_CROSS_PRODUCTION_REFERENCE"
    ERR_DUPLICATE_DAY_NUMBER = "ERR_DUPLICATE_DAY_NUMBER"
    ERR_DOUBLE_BOOKED = "ERR_DOUBLE_BOOKED"
    ERR_PERMIT_WINDOW_CONFLICT = "ERR_PERMIT_WINDOW_CONFLICT"
    ERR_CREW_TIME_CONFLICT = "ERR_CREW_TIME_CONFLICT"
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_DUPLICATE_FRINGE = "ERR_DUPLICATE_FRINGE"
    ERR_BUDGET_WOULD_EXCEED = "ERR_BUDGET_WOULD_EXCEED"
    ERR_SCENE_SCHEDULE_LOCKED = "ERR_SCENE_SCHEDULE_LOCKED"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_DAILIES_FLAG_REASON_REQUIRED = "ERR_DAILIES_FLAG_REASON_REQUIRED"
    ERR_PRODUCTION_NOT_ACTIVE = "ERR_PRODUCTION_NOT_ACTIVE"
    ERR_OPEN_ASSIGNMENTS_BLOCK_WRAP = "ERR_OPEN_ASSIGNMENTS_BLOCK_WRAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CROSS_PRODUCTION_REFERENCE: 409,
    ApiErrorId.ERR_DUPLICATE_DAY_NUMBER: 409,
    ApiErrorId.ERR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_PERMIT_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_CREW_TIME_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_DUPLICATE_FRINGE: 409,
    ApiErrorId.ERR_BUDGET_WOULD_EXCEED: 409,
    ApiErrorId.ERR_SCENE_SCHEDULE_LOCKED: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
    ApiErrorId.ERR_DAILIES_FLAG_REASON_REQUIRED: 422,
    ApiErrorId.ERR_PRODUCTION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_OPEN_ASSIGNMENTS_BLOCK_WRAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
