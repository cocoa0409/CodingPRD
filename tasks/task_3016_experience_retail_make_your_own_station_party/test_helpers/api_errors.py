"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_OUTSIDE_TIME_WINDOW = "ERR_OUTSIDE_TIME_WINDOW"
    ERR_DROP_LIMIT_REACHED = "ERR_DROP_LIMIT_REACHED"
    ERR_STATION_AT_CAPACITY = "ERR_STATION_AT_CAPACITY"
    ERR_HOST_UNAVAILABLE = "ERR_HOST_UNAVAILABLE"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_GIFT_CARD_INSUFFICIENT = "ERR_GIFT_CARD_INSUFFICIENT"
    ERR_GIFT_CARD_NOT_LINKED = "ERR_GIFT_CARD_NOT_LINKED"
    ERR_REFERENTIAL_INTEGRITY = "ERR_REFERENTIAL_INTEGRITY"
    ERR_PARTY_GUEST_LIMIT = "ERR_PARTY_GUEST_LIMIT"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_OUTSIDE_TIME_WINDOW: 409,
    ApiErrorId.ERR_DROP_LIMIT_REACHED: 409,
    ApiErrorId.ERR_STATION_AT_CAPACITY: 409,
    ApiErrorId.ERR_HOST_UNAVAILABLE: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_GIFT_CARD_INSUFFICIENT: 409,
    ApiErrorId.ERR_GIFT_CARD_NOT_LINKED: 409,
    ApiErrorId.ERR_REFERENTIAL_INTEGRITY: 409,
    ApiErrorId.ERR_PARTY_GUEST_LIMIT: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
