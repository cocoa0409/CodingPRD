    ERR_CERT_SCOPE_MISMATCH = "ERR_CERT_SCOPE_MISMATCH"

    # Money last of all (priority 46)
    ERR_BUDGET_CEILING_EXCEEDED = "ERR_BUDGET_CEILING_EXCEEDED"


