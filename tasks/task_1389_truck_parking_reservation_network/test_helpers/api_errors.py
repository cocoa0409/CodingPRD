    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SITE_ESCALATED = "ERR_SITE_ESCALATED"
    ERR_WINDOW_IN_PAST = "ERR_WINDOW_IN_PAST"
    ERR_WALKIN_NOT_TODAY = "ERR_WALKIN_NOT_TODAY"
    ERR_WINDOW_TOO_LONG = "ERR_WINDOW_TOO_LONG"
    ERR_WINDOW_INVALID = "ERR_WINDOW_INVALID"
    ERR_CHECKIN_WINDOW_NOT_OPEN = "ERR_CHECKIN_WINDOW_NOT_OPEN"
    ERR_CHECKIN_GRACE_ELAPSED = "ERR_CHECKIN_GRACE_ELAPSED"
    ERR_REOPEN_WINDOW_EXPIRED = "ERR_REOPEN_WINDOW_EXPIRED"
    ERR_STALL_WINDOW_CONFLICT = "ERR_STALL_WINDOW_CONFLICT"
    ERR_DRIVER_WINDOW_CONFLICT = "ERR_DRIVER_WINDOW_CONFLICT"
    ERR_EXTENSION_CONFLICT = "ERR_EXTENSION_CONFLICT"
    ERR_DRIVER_SUSPENDED = "ERR_DRIVER_SUSPENDED"
    ERR_DRIVER_NOT_AUTHORIZED = "ERR_DRIVER_NOT_AUTHORIZED"
    ERR_FLEET_SUSPENDED = "ERR_FLEET_SUSPENDED"
    ERR_SITE_CAPACITY_FULL = "ERR_SITE_CAPACITY_FULL"
    ERR_AMENITY_CAPACITY_EXCEEDED = "ERR_AMENITY_CAPACITY_EXCEEDED"
    ERR_DUPLICATE_WAITLIST_ENTRY = "ERR_DUPLICATE_WAITLIST_ENTRY"
    ERR_DUPLICATE_STALL_NUMBER = "ERR_DUPLICATE_STALL_NUMBER"
    ERR_STALL_NOT_RESERVABLE = "ERR_STALL_NOT_RESERVABLE"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
