"""Error IDs and HTTP status mapping (PRD §5).

The mapping is registered with the framework at import time so that
validate_error() auto-checks HTTP status codes without each test passing
them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # ---------- Auth / authorization (PRD §2.1, §2.7) ----------
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_INVALID_ROLE = "ERR_INVALID_ROLE"
    ERR_ROLE_FORBIDDEN = "ERR_ROLE_FORBIDDEN"

    # ---------- Existence / not-found (PRD §2.5, §2.7) ----------
    ERR_CYCLE_NOT_FOUND = "ERR_CYCLE_NOT_FOUND"
    ERR_REVIEW_CASE_NOT_FOUND = "ERR_REVIEW_CASE_NOT_FOUND"
    ERR_CALIBRATION_SESSION_NOT_FOUND = "ERR_CALIBRATION_SESSION_NOT_FOUND"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # ---------- State conflicts (HTTP 409) ----------
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CYCLE_NOT_OPEN = "ERR_CYCLE_NOT_OPEN"
    ERR_PINNED_REVIEW_STALE = "ERR_PINNED_REVIEW_STALE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_PIP_ALREADY_EXISTS = "ERR_PIP_ALREADY_EXISTS"

    # ---------- Business rules (HTTP 422) ----------
    ERR_GOAL_WEIGHTS_INVALID = "ERR_GOAL_WEIGHTS_INVALID"
    ERR_PEER_FEEDBACK_INSUFFICIENT = "ERR_PEER_FEEDBACK_INSUFFICIENT"
    ERR_REVISION_LIMIT = "ERR_REVISION_LIMIT"
    ERR_SELF_FEEDBACK_FORBIDDEN = "ERR_SELF_FEEDBACK_FORBIDDEN"
    ERR_FACILITATOR_CONFLICT = "ERR_FACILITATOR_CONFLICT"
    ERR_APPROVER_IS_MANAGER = "ERR_APPROVER_IS_MANAGER"
    ERR_PROMO_BLOCKED_BY_PIP = "ERR_PROMO_BLOCKED_BY_PIP"
    ERR_PROMO_STEP_INVALID = "ERR_PROMO_STEP_INVALID"
    ERR_BELL_CURVE_VIOLATED = "ERR_BELL_CURVE_VIOLATED"
    ERR_BELL_CURVE_TARGET_INVALID = "ERR_BELL_CURVE_TARGET_INVALID"
    ERR_CALIBRATION_COVERAGE = "ERR_CALIBRATION_COVERAGE"
    ERR_PIP_NOT_ELAPSED = "ERR_PIP_NOT_ELAPSED"
    ERR_EMAIL_TAKEN = "ERR_EMAIL_TAKEN"
    ERR_MERIT_BUDGET_EXCEEDED = "ERR_MERIT_BUDGET_EXCEEDED"
    ERR_EQUITY_POOL_EXHAUSTED = "ERR_EQUITY_POOL_EXHAUSTED"
    ERR_TIME_WINDOW_INVALID = "ERR_TIME_WINDOW_INVALID"

    # ---------- Generic schema (HTTP 400) ----------
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 — Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_INVALID_ROLE: 401,
    ApiErrorId.ERR_ROLE_FORBIDDEN: 403,
    ApiErrorId.ERR_CYCLE_NOT_FOUND: 404,
    ApiErrorId.ERR_REVIEW_CASE_NOT_FOUND: 404,
    ApiErrorId.ERR_CALIBRATION_SESSION_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CYCLE_NOT_OPEN: 409,
    ApiErrorId.ERR_PINNED_REVIEW_STALE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_PIP_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_GOAL_WEIGHTS_INVALID: 422,
    ApiErrorId.ERR_PEER_FEEDBACK_INSUFFICIENT: 422,
    ApiErrorId.ERR_REVISION_LIMIT: 422,
    ApiErrorId.ERR_SELF_FEEDBACK_FORBIDDEN: 422,
    ApiErrorId.ERR_FACILITATOR_CONFLICT: 422,
    ApiErrorId.ERR_APPROVER_IS_MANAGER: 422,
    ApiErrorId.ERR_PROMO_BLOCKED_BY_PIP: 422,
    ApiErrorId.ERR_PROMO_STEP_INVALID: 422,
    ApiErrorId.ERR_BELL_CURVE_VIOLATED: 422,
    ApiErrorId.ERR_BELL_CURVE_TARGET_INVALID: 422,
    ApiErrorId.ERR_CALIBRATION_COVERAGE: 422,
    ApiErrorId.ERR_PIP_NOT_ELAPSED: 422,
    ApiErrorId.ERR_EMAIL_TAKEN: 422,
    ApiErrorId.ERR_MERIT_BUDGET_EXCEEDED: 422,
    ApiErrorId.ERR_EQUITY_POOL_EXHAUSTED: 422,
    ApiErrorId.ERR_TIME_WINDOW_INVALID: 422,
    ApiErrorId.ERR_VALIDATION: 400,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
