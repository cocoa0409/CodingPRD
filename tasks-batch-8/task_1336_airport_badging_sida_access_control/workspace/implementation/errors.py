class ApiError(Exception):
    """An error carrying the catalog error_id, a message, and an HTTP status."""

    def __init__(self, error_id: str, message: str, http_status: int | None = None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        if http_status is None:
            http_status = ERROR_STATUS.get(error_id, 400)
        self.http_status = http_status


def raise_err(error_id: str, message: str):
    raise ApiError(error_id, message)
