"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_POSTURE_BLOCKED = "ERR_POSTURE_BLOCKED"
    ERR_SAFETY_INSPECTION_MISSING = "ERR_SAFETY_INSPECTION_MISSING"
    ERR_OVERNIGHT_PERMIT_REQUIRED = "ERR_OVERNIGHT_PERMIT_REQUIRED"
    ERR_FIRE_SAFETY_CELL = "ERR_FIRE_SAFETY_CELL"
    ERR_UTILITY_CAPACITY_EXCEEDED = "ERR_UTILITY_CAPACITY_EXCEEDED"
    ERR_THEME_MISMATCH = "ERR_THEME_MISMATCH"
    ERR_OBJECTION_WINDOW_CLOSED = "ERR_OBJECTION_WINDOW_CLOSED"
    ERR_DOCK_SLOT_OVERLAP = "ERR_DOCK_SLOT_OVERLAP"
    ERR_RESOURCE_CONFLICT = "ERR_RESOURCE_CONFLICT"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_GROUP_INVALID = "ERR_GROUP_INVALID"
    ERR_RELOCATION_TIER_MISMATCH = "ERR_RELOCATION_TIER_MISMATCH"
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"
    ERR_DISPUTE_RESOLUTION_INVALID = "ERR_DISPUTE_RESOLUTION_INVALID"
    ERR_FLOOR_PLAN_LOCKED = "ERR_FLOOR_PLAN_LOCKED"
    ERR_BOOTH_ALREADY_ALLOCATED = "ERR_BOOTH_ALREADY_ALLOCATED"


# Per PRD §5 Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_POSTURE_BLOCKED: 409,
    ApiErrorId.ERR_SAFETY_INSPECTION_MISSING: 409,
    ApiErrorId.ERR_OVERNIGHT_PERMIT_REQUIRED: 422,
    ApiErrorId.ERR_FIRE_SAFETY_CELL: 422,
    ApiErrorId.ERR_UTILITY_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_THEME_MISMATCH: 422,
    ApiErrorId.ERR_OBJECTION_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_DOCK_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_RESOURCE_CONFLICT: 409,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_GROUP_INVALID: 422,
    ApiErrorId.ERR_RELOCATION_TIER_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_INPUT: 422,
    ApiErrorId.ERR_DISPUTE_RESOLUTION_INVALID: 422,
    ApiErrorId.ERR_FLOOR_PLAN_LOCKED: 409,
    ApiErrorId.ERR_BOOTH_ALREADY_ALLOCATED: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
