def raise_err(code, message):
    error_id, status = code
    raise ApiError(error_id, status, message)


def not_found(what="resource"):
    raise_err(ERR_NOT_FOUND, f"The requested {what} does not exist.")


def validation(message):
    raise_err(ERR_VALIDATION, message)


def invalid_state(message):
    raise_err(ERR_INVALID_STATE, message)


def already_terminal(what="resource"):
    raise_err(ERR_ALREADY_TERMINAL, f"The {what} is in a terminal state; no further transitions are permitted.")


def posture_forbids(message):
    raise_err(ERR_EVENT_POSTURE_FORBIDS, message)
