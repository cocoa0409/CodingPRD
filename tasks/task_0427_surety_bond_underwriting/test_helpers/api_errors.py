"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INDEMNITY_REQUIRED = "ERR_INDEMNITY_REQUIRED"
    ERR_REFERRAL_REQUIRED = "ERR_REFERRAL_REQUIRED"
    ERR_SINGLE_LIMIT_EXCEEDED = "ERR_SINGLE_LIMIT_EXCEEDED"
    ERR_AGGREGATE_LIMIT_EXCEEDED = "ERR_AGGREGATE_LIMIT_EXCEEDED"
    ERR_TREATY_CAPACITY_EXCEEDED = "ERR_TREATY_CAPACITY_EXCEEDED"
    ERR_TREATY_CLOSED = "ERR_TREATY_CLOSED"
    ERR_PROGRAM_SUSPENDED = "ERR_PROGRAM_SUSPENDED"
    ERR_OPEN_CLAIM_EXISTS = "ERR_OPEN_CLAIM_EXISTS"
    ERR_LOSS_EXCEEDS_PENAL_SUM = "ERR_LOSS_EXCEEDS_PENAL_SUM"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INDEMNITY_REQUIRED: 409,
    ApiErrorId.ERR_REFERRAL_REQUIRED: 409,
    ApiErrorId.ERR_SINGLE_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_AGGREGATE_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_TREATY_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_TREATY_CLOSED: 409,
    ApiErrorId.ERR_PROGRAM_SUSPENDED: 409,
    ApiErrorId.ERR_OPEN_CLAIM_EXISTS: 409,
    ApiErrorId.ERR_LOSS_EXCEEDS_PENAL_SUM: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
