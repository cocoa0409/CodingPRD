    DUPLICATE_SELLER_EMAIL = "ERR_DUPLICATE_SELLER_EMAIL"
    DUPLICATE_POLICY_CODE = "ERR_DUPLICATE_POLICY_CODE"
    ACTION_ALREADY_EXISTS = "ERR_ACTION_ALREADY_EXISTS"
    APPEAL_ALREADY_EXISTS = "ERR_APPEAL_ALREADY_EXISTS"
    POA_ALREADY_OPEN = "ERR_POA_ALREADY_OPEN"
    POA_REVISION_LIMIT = "ERR_POA_REVISION_LIMIT"

