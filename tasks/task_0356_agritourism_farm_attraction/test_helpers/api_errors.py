"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can auto-check HTTP status codes from the error_id alone.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FARM_NOT_OPEN = "ERR_FARM_NOT_OPEN"
    ERR_WINDOW_TIME_INVALID = "ERR_WINDOW_TIME_INVALID"
    ERR_EMPTY_PARTY = "ERR_EMPTY_PARTY"
    ERR_WINDOW_SOLD_OUT = "ERR_WINDOW_SOLD_OUT"
    ERR_WINDOW_VERSION_STALE = "ERR_WINDOW_VERSION_STALE"
    ERR_WAIVER_INCOMPLETE = "ERR_WAIVER_INCOMPLETE"
    ERR_GUARDIAN_REQUIRED = "ERR_GUARDIAN_REQUIRED"
    ERR_PASS_NOT_VALID = "ERR_PASS_NOT_VALID"
    ERR_GROUP_WINDOW_MISMATCH = "ERR_GROUP_WINDOW_MISMATCH"
    ERR_PASS_ALREADY_REVOKED = "ERR_PASS_ALREADY_REVOKED"
    ERR_PUMPKIN_ALREADY_WEIGHED = "ERR_PUMPKIN_ALREADY_WEIGHED"
    ERR_CHECKOUT_NOT_FINALIZED = "ERR_CHECKOUT_NOT_FINALIZED"
    ERR_GROUP_NOT_REVISABLE = "ERR_GROUP_NOT_REVISABLE"
    ERR_NO_ACTIVE_POLICY = "ERR_NO_ACTIVE_POLICY"
    ERR_POLICY_ALREADY_ACTIVE = "ERR_POLICY_ALREADY_ACTIVE"
    ERR_WINDOW_CANCELLED = "ERR_WINDOW_CANCELLED"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_PASS_OVERLAP = "ERR_PASS_OVERLAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FARM_NOT_OPEN: 409,
    ApiErrorId.ERR_WINDOW_TIME_INVALID: 422,
    ApiErrorId.ERR_EMPTY_PARTY: 422,
    ApiErrorId.ERR_WINDOW_SOLD_OUT: 409,
    ApiErrorId.ERR_WINDOW_VERSION_STALE: 412,
    ApiErrorId.ERR_WAIVER_INCOMPLETE: 422,
    ApiErrorId.ERR_GUARDIAN_REQUIRED: 422,
    ApiErrorId.ERR_PASS_NOT_VALID: 422,
    ApiErrorId.ERR_GROUP_WINDOW_MISMATCH: 422,
    ApiErrorId.ERR_PASS_ALREADY_REVOKED: 409,
    ApiErrorId.ERR_PUMPKIN_ALREADY_WEIGHED: 409,
    ApiErrorId.ERR_CHECKOUT_NOT_FINALIZED: 409,
    ApiErrorId.ERR_GROUP_NOT_REVISABLE: 409,
    ApiErrorId.ERR_NO_ACTIVE_POLICY: 409,
    ApiErrorId.ERR_POLICY_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_WINDOW_CANCELLED: 409,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_PASS_OVERLAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
