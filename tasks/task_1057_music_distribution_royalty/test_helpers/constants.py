def isrc(n: int, prefix: str = "USTST26") -> str:
    """Build a unique 12-alphanumeric recording code for a test."""
    return f"{prefix}{n:05d}"[:12].ljust(12, "0")


def upc(n: int) -> str:
    """Build a unique 12-digit barcode for a test."""
    return f"{n:012d}"
