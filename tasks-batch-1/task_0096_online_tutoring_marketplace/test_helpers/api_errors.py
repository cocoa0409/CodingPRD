"""Error identifiers and their HTTP status codes (PRD Section 5).

Registers the mapping with the framework so validate_error() can cross-check
the HTTP status that accompanies each error_id automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Request / auth
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"

    # Not found
    ERR_TUTOR_NOT_FOUND = "ERR_TUTOR_NOT_FOUND"
    ERR_SUBJECT_NOT_FOUND = "ERR_SUBJECT_NOT_FOUND"
    ERR_CREDENTIAL_NOT_FOUND = "ERR_CREDENTIAL_NOT_FOUND"
    ERR_SUBJECT_TAG_NOT_FOUND = "ERR_SUBJECT_TAG_NOT_FOUND"
    ERR_PARENT_NOT_FOUND = "ERR_PARENT_NOT_FOUND"
    ERR_STUDENT_NOT_FOUND = "ERR_STUDENT_NOT_FOUND"
    ERR_BOOKING_NOT_FOUND = "ERR_BOOKING_NOT_FOUND"
    ERR_SESSION_NOT_FOUND = "ERR_SESSION_NOT_FOUND"
    ERR_SETTLEMENT_NOT_FOUND = "ERR_SETTLEMENT_NOT_FOUND"
    ERR_REFUND_CASE_NOT_FOUND = "ERR_REFUND_CASE_NOT_FOUND"

    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TUTOR_NOT_REINSTATABLE = "ERR_TUTOR_NOT_REINSTATABLE"

    # OCC
    ERR_STALE_REFUND_CASE_VERSION = "ERR_STALE_REFUND_CASE_VERSION"

    # Business: credential / subject gating
    ERR_SUBJECT_REQUIRES_CREDENTIAL = "ERR_SUBJECT_REQUIRES_CREDENTIAL"
    ERR_TUTOR_NOT_VERIFIED = "ERR_TUTOR_NOT_VERIFIED"
    ERR_TUTOR_SUBJECT_NOT_APPROVED = "ERR_TUTOR_SUBJECT_NOT_APPROVED"

    # Business: temporal
    ERR_BOOKING_TIME_INVALID = "ERR_BOOKING_TIME_INVALID"
    ERR_TUTOR_TIME_CONFLICT = "ERR_TUTOR_TIME_CONFLICT"
    ERR_STUDENT_TIME_CONFLICT = "ERR_STUDENT_TIME_CONFLICT"
    ERR_REFUND_WINDOW_CLOSED = "ERR_REFUND_WINDOW_CLOSED"

    # Business: negotiation / amounts
    ERR_OFFER_OUT_OF_BOUNDS = "ERR_OFFER_OUT_OF_BOUNDS"
    ERR_NEGOTIATION_ROUNDS_EXHAUSTED = "ERR_NEGOTIATION_ROUNDS_EXHAUSTED"
    ERR_AMOUNT_OUT_OF_RANGE = "ERR_AMOUNT_OUT_OF_RANGE"
    ERR_RESCHEDULE_LIMIT_REACHED = "ERR_RESCHEDULE_LIMIT_REACHED"

    # Business: fiscal
    ERR_INSUFFICIENT_WALLET_BALANCE = "ERR_INSUFFICIENT_WALLET_BALANCE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_TUTOR_NOT_FOUND: 404,
    ApiErrorId.ERR_SUBJECT_NOT_FOUND: 404,
    ApiErrorId.ERR_CREDENTIAL_NOT_FOUND: 404,
    ApiErrorId.ERR_SUBJECT_TAG_NOT_FOUND: 404,
    ApiErrorId.ERR_PARENT_NOT_FOUND: 404,
    ApiErrorId.ERR_STUDENT_NOT_FOUND: 404,
    ApiErrorId.ERR_BOOKING_NOT_FOUND: 404,
    ApiErrorId.ERR_SESSION_NOT_FOUND: 404,
    ApiErrorId.ERR_SETTLEMENT_NOT_FOUND: 404,
    ApiErrorId.ERR_REFUND_CASE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_TUTOR_NOT_REINSTATABLE: 409,
    ApiErrorId.ERR_STALE_REFUND_CASE_VERSION: 412,
    ApiErrorId.ERR_SUBJECT_REQUIRES_CREDENTIAL: 409,
    ApiErrorId.ERR_TUTOR_NOT_VERIFIED: 409,
    ApiErrorId.ERR_TUTOR_SUBJECT_NOT_APPROVED: 409,
    ApiErrorId.ERR_BOOKING_TIME_INVALID: 422,
    ApiErrorId.ERR_TUTOR_TIME_CONFLICT: 409,
    ApiErrorId.ERR_STUDENT_TIME_CONFLICT: 409,
    ApiErrorId.ERR_REFUND_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_OFFER_OUT_OF_BOUNDS: 422,
    ApiErrorId.ERR_NEGOTIATION_ROUNDS_EXHAUSTED: 409,
    ApiErrorId.ERR_AMOUNT_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_RESCHEDULE_LIMIT_REACHED: 409,
    ApiErrorId.ERR_INSUFFICIENT_WALLET_BALANCE: 402,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
