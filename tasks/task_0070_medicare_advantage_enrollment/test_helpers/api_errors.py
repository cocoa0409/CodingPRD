"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PERIOD_BENEFICIARY_MISMATCH = "ERR_PERIOD_BENEFICIARY_MISMATCH"
    ERR_WRONG_PERIOD_TYPE = "ERR_WRONG_PERIOD_TYPE"
    ERR_ENROLLMENT_LOCKED = "ERR_ENROLLMENT_LOCKED"
    ERR_OUTSIDE_ENROLLMENT_WINDOW = "ERR_OUTSIDE_ENROLLMENT_WINDOW"
    ERR_GI_WINDOW_EXPIRED = "ERR_GI_WINDOW_EXPIRED"
    ERR_NOT_FIVE_STAR = "ERR_NOT_FIVE_STAR"
    ERR_DRUG_COVERAGE_CONFLICT = "ERR_DRUG_COVERAGE_CONFLICT"
    ERR_PART_A_REQUIRED = "ERR_PART_A_REQUIRED"
    ERR_PART_B_REQUIRED = "ERR_PART_B_REQUIRED"
    ERR_PLAN_RETIRED = "ERR_PLAN_RETIRED"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"
    ERR_MISSING_SOURCE_EVENT_DATE = "ERR_MISSING_SOURCE_EVENT_DATE"
    ERR_PERIOD_OVERLAP = "ERR_PERIOD_OVERLAP"
    ERR_MEDIGAP_OVERLAP = "ERR_MEDIGAP_OVERLAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PERIOD_BENEFICIARY_MISMATCH: 422,
    ApiErrorId.ERR_WRONG_PERIOD_TYPE: 422,
    ApiErrorId.ERR_ENROLLMENT_LOCKED: 409,
    ApiErrorId.ERR_OUTSIDE_ENROLLMENT_WINDOW: 422,
    ApiErrorId.ERR_GI_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_NOT_FIVE_STAR: 422,
    ApiErrorId.ERR_DRUG_COVERAGE_CONFLICT: 409,
    ApiErrorId.ERR_PART_A_REQUIRED: 409,
    ApiErrorId.ERR_PART_B_REQUIRED: 409,
    ApiErrorId.ERR_PLAN_RETIRED: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
    ApiErrorId.ERR_MISSING_SOURCE_EVENT_DATE: 422,
    ApiErrorId.ERR_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_MEDIGAP_OVERLAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
