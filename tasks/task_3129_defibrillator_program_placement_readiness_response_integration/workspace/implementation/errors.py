def raise_err(spec, message: str):
    raise ApiError(spec[0], spec[1], message)


def not_found(resource: str = "resource"):
    raise_err(ERR_NOT_FOUND, f"{resource} not found")


def invalid_request(message: str):
    raise_err(ERR_INVALID_REQUEST, message)


def invalid_state(message: str):
    raise_err(ERR_INVALID_STATE, message)
