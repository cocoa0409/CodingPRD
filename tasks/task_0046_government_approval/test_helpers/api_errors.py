"""Error IDs and HTTP status mapping (PRD §5).

The mapping is registered with the framework so validate_error()
auto-checks HTTP status codes when an error_id is asserted.
"""
from __future__ import annotations

from enum import Enum
from typing import Dict

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # PRD §5 Error Code Catalogue
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_REVIEW_OUT_OF_ORDER = "ERR_REVIEW_OUT_OF_ORDER"
    ERR_CORRECTION_EXPIRED = "ERR_CORRECTION_EXPIRED"
    ERR_MAX_ROUNDS_REACHED = "ERR_MAX_ROUNDS_REACHED"
    ERR_ESCALATION_NOT_PERMITTED = "ERR_ESCALATION_NOT_PERMITTED"
    ERR_CERTIFICATE_ALREADY_REISSUED = "ERR_CERTIFICATE_ALREADY_REISSUED"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_MATERIAL_MISSING = "ERR_MATERIAL_MISSING"
    ERR_MATERIAL_TYPE_MISMATCH = "ERR_MATERIAL_TYPE_MISMATCH"
    ERR_EFORM_INCOMPLETE = "ERR_EFORM_INCOMPLETE"
    ERR_CHANNEL_NOT_ALLOWED = "ERR_CHANNEL_NOT_ALLOWED"
    ERR_DEFICIENCY_INVALID = "ERR_DEFICIENCY_INVALID"
    ERR_DEFICIENCY_UNRESOLVED = "ERR_DEFICIENCY_UNRESOLVED"
    ERR_DEPENDENT_TEMPLATE_UNPUBLISHED = "ERR_DEPENDENT_TEMPLATE_UNPUBLISHED"
    ERR_TIME_LIMIT_INVERSION = "ERR_TIME_LIMIT_INVERSION"
    ERR_ROUTING_INVALID = "ERR_ROUTING_INVALID"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"


# Mapping per PRD §5.
HTTP_STATUS_CODES: Dict[str, int] = {
    ApiErrorId.ERR_AUTH_MISSING.value: 401,
    ApiErrorId.ERR_FORBIDDEN.value: 403,
    ApiErrorId.ERR_NOT_FOUND.value: 404,
    ApiErrorId.ERR_INVALID_STATE.value: 409,
    ApiErrorId.ERR_VERSION_CONFLICT.value: 409,
    ApiErrorId.ERR_REVIEW_OUT_OF_ORDER.value: 409,
    ApiErrorId.ERR_CORRECTION_EXPIRED.value: 409,
    ApiErrorId.ERR_MAX_ROUNDS_REACHED.value: 409,
    ApiErrorId.ERR_ESCALATION_NOT_PERMITTED.value: 409,
    ApiErrorId.ERR_CERTIFICATE_ALREADY_REISSUED.value: 409,
    ApiErrorId.ERR_DUPLICATE_RESOURCE.value: 409,
    ApiErrorId.ERR_MATERIAL_MISSING.value: 422,
    ApiErrorId.ERR_MATERIAL_TYPE_MISMATCH.value: 422,
    ApiErrorId.ERR_EFORM_INCOMPLETE.value: 422,
    ApiErrorId.ERR_CHANNEL_NOT_ALLOWED.value: 422,
    ApiErrorId.ERR_DEFICIENCY_INVALID.value: 422,
    ApiErrorId.ERR_DEFICIENCY_UNRESOLVED.value: 422,
    ApiErrorId.ERR_DEPENDENT_TEMPLATE_UNPUBLISHED.value: 422,
    ApiErrorId.ERR_TIME_LIMIT_INVERSION.value: 422,
    ApiErrorId.ERR_ROUTING_INVALID.value: 422,
    ApiErrorId.ERR_VALIDATION_FAILED.value: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
