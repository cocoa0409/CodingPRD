DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Authentication required",
    "ERR_UNAUTHORIZED": "Role not permitted for this operation",
    "ERR_VALIDATION": "Request payload failed validation",
}


class ApiError(Exception):
    """A refusal carrying its catalogue identifier and HTTP status."""

    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize()
        )


def fail(error_id, message=None):
    raise ApiError(error_id, message)
