"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth + envelope — PRD §2.1, §2.3
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = (
        "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    )
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_INVALID_FREEZE_PIN = "ERR_INVALID_FREEZE_PIN"

    # Existence — PRD §2.7
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # Cross-consumer reference — PRD §2.7
    ERR_CROSS_CONSUMER_REFERENCE = "ERR_CROSS_CONSUMER_REFERENCE"

    # State machine — PRD §2.6, §3.13
    ERR_INVALID_STATE_TRANSITION = "ERR_INVALID_STATE_TRANSITION"

    # Dispute lifecycle — PRD §3.2, §3.3, §3.4
    ERR_NO_SUPPORTING_DOCUMENTS = "ERR_NO_SUPPORTING_DOCUMENTS"
    ERR_DUPLICATE_ACTIVE_DISPUTE = "ERR_DUPLICATE_ACTIVE_DISPUTE"
    ERR_FRIVOLOUS_DISPUTE = "ERR_FRIVOLOUS_DISPUTE"
    ERR_DISPUTE_DEADLINE_PASSED = "ERR_DISPUTE_DEADLINE_PASSED"
    ERR_FURNISHER_LATE = "ERR_FURNISHER_LATE"
    ERR_REAGE_PROHIBITED = "ERR_REAGE_PROHIBITED"
    ERR_REPORT_FROZEN = "ERR_REPORT_FROZEN"
    ERR_REPORT_HAS_OPEN_DISPUTES = "ERR_REPORT_HAS_OPEN_DISPUTES"

    # Regulatory — PRD §3.10
    ERR_NOT_ESCALATABLE = "ERR_NOT_ESCALATABLE"
    ERR_COMPLAINT_ALREADY_OPEN = "ERR_COMPLAINT_ALREADY_OPEN"
    ERR_DISPUTE_NOT_RECLOSED = "ERR_DISPUTE_NOT_RECLOSED"

    # Freeze / lock / inquiry — PRD §3.11, §3.12
    ERR_FREEZE_ALREADY_ACTIVE = "ERR_FREEZE_ALREADY_ACTIVE"
    ERR_LOCK_ALREADY_ACTIVE = "ERR_LOCK_ALREADY_ACTIVE"
    ERR_HARD_INQUIRY_BLOCKED_BY_FREEZE = (
        "ERR_HARD_INQUIRY_BLOCKED_BY_FREEZE"
    )
    ERR_HARD_INQUIRY_BLOCKED_BY_LOCK = "ERR_HARD_INQUIRY_BLOCKED_BY_LOCK"

    # Reports — PRD §3.9
    ERR_NO_FREE_REPORTS_REMAINING = "ERR_NO_FREE_REPORTS_REMAINING"


# PRD §5 Error Code Catalogue — http status per error_id.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_INVALID_FREEZE_PIN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE_TRANSITION: 409,
    ApiErrorId.ERR_NO_SUPPORTING_DOCUMENTS: 422,
    ApiErrorId.ERR_CROSS_CONSUMER_REFERENCE: 422,
    ApiErrorId.ERR_DUPLICATE_ACTIVE_DISPUTE: 409,
    ApiErrorId.ERR_FRIVOLOUS_DISPUTE: 409,
    ApiErrorId.ERR_DISPUTE_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_FURNISHER_LATE: 409,
    ApiErrorId.ERR_REAGE_PROHIBITED: 409,
    ApiErrorId.ERR_REPORT_FROZEN: 409,
    ApiErrorId.ERR_REPORT_HAS_OPEN_DISPUTES: 409,
    ApiErrorId.ERR_NOT_ESCALATABLE: 409,
    ApiErrorId.ERR_COMPLAINT_ALREADY_OPEN: 409,
    ApiErrorId.ERR_DISPUTE_NOT_RECLOSED: 409,
    ApiErrorId.ERR_FREEZE_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_LOCK_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_HARD_INQUIRY_BLOCKED_BY_FREEZE: 409,
    ApiErrorId.ERR_HARD_INQUIRY_BLOCKED_BY_LOCK: 409,
    ApiErrorId.ERR_NO_FREE_REPORTS_REMAINING: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
