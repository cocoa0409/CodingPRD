def context():
    """Extract and validate the acting principal.  Returns (user_id, role)."""
    user_id = request.headers.get("X-User-ID")
    role = request.headers.get("X-User-Role")
    if not user_id or not str(user_id).strip():
        raise ApiError("ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER")
    if not role or role not in ROLES:
        raise ApiError("ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER")
    return str(user_id).strip(), role


def authorize(role, op_key):
    allowed = OPS_BY_ROLE.get(role, [])
    if op_key not in allowed:
        raise ApiError("ERR_INSUFFICIENT_PERMISSIONS")


def guard(op_key):
    """Validate auth headers and role authorization for `op_key`."""
    user_id, role = context()
    authorize(role, op_key)
    return user_id, role