    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_POLICY_NOT_EDITABLE = "ERR_POLICY_NOT_EDITABLE"
    ERR_POLICY_NOT_ACTIVE = "ERR_POLICY_NOT_ACTIVE"
    ERR_POLICY_NOT_BILLABLE = "ERR_POLICY_NOT_BILLABLE"
    ERR_STALE_POLICY_VERSION = "ERR_STALE_POLICY_VERSION"
    ERR_DUPLICATE_COVERAGE_TYPE = "ERR_DUPLICATE_COVERAGE_TYPE"
    ERR_COVERAGE_INCOMPLETE = "ERR_COVERAGE_INCOMPLETE"
    ERR_INVALID_TERM = "ERR_INVALID_TERM"
    ERR_TERM_OVERLAP = "ERR_TERM_OVERLAP"
    ERR_LOSS_OUTSIDE_TERM = "ERR_LOSS_OUTSIDE_TERM"
