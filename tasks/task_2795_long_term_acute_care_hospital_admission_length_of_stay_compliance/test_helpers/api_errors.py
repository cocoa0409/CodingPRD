"""
The error catalogue: every declared `error_id` and the HTTP status it must carry.

Importing this module registers the mapping with the framework validators, so a plain
`validate_error(response, ApiErrorId.ERR_PERIOD_CLOSED)` also checks that the response
carried HTTP 409 without the test having to restate the number.

Note the two statuses that surprise people: `ERR_SEGREGATION_OF_DUTIES` is a 403,
because it is an authorization refusal about who the caller is, while every other
business refusal in the same family is a 422; and the two staleness errors are 412,
not 409.
"""

