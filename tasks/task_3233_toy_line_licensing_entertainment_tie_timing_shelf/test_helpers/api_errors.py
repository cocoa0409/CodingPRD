"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework at import time so ``validate_error`` can
cross-check HTTP status codes automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SAFETY_GATE = "ERR_SAFETY_GATE"
    ERR_CONFIDENTIALITY_BREACH = "ERR_CONFIDENTIALITY_BREACH"
    ERR_CONSTRAINT_VIOLATION = "ERR_CONSTRAINT_VIOLATION"
    ERR_REVIEW_WINDOW_OVERLAP = "ERR_REVIEW_WINDOW_OVERLAP"
    ERR_FACTORY_CAPACITY_EXCEEDED = "ERR_FACTORY_CAPACITY_EXCEEDED"
    ERR_SHELF_OVERFLOW = "ERR_SHELF_OVERFLOW"
    ERR_SHIPMENT_OVERSOLD = "ERR_SHIPMENT_OVERSOLD"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SAFETY_GATE: 422,
    ApiErrorId.ERR_CONFIDENTIALITY_BREACH: 422,
    ApiErrorId.ERR_CONSTRAINT_VIOLATION: 422,
    ApiErrorId.ERR_REVIEW_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_FACTORY_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_SHELF_OVERFLOW: 422,
    ApiErrorId.ERR_SHIPMENT_OVERSOLD: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

set_error_http_status_map(HTTP_STATUS_CODES)
