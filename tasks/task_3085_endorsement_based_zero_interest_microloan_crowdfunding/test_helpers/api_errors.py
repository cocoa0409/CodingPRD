"""Error IDs and HTTP status mapping (PRD §5 error catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_BORROWER_RESTRICTED = "ERR_BORROWER_RESTRICTED"
    ERR_ACTIVE_APPLICATION_EXISTS = "ERR_ACTIVE_APPLICATION_EXISTS"
    ERR_UNDERWRITING_ACCEPTANCE_QUOTA = "ERR_UNDERWRITING_ACCEPTANCE_QUOTA"
    ERR_TRUSTEE_SUSPENDED = "ERR_TRUSTEE_SUSPENDED"
    ERR_TRUSTEE_LIMIT_EXCEEDED = "ERR_TRUSTEE_LIMIT_EXCEEDED"
    ERR_SCORE_TOO_LOW = "ERR_SCORE_TOO_LOW"
    ERR_QUORUM_NOT_MET = "ERR_QUORUM_NOT_MET"
    ERR_MIN_CONTRIBUTION = "ERR_MIN_CONTRIBUTION"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_OVERFUND = "ERR_OVERFUND"
    ERR_APPLICATION_NOT_FUNDED = "ERR_APPLICATION_NOT_FUNDED"
    ERR_TIMING_MISMATCH = "ERR_TIMING_MISMATCH"
    ERR_INVITE_NOT_PENDING = "ERR_INVITE_NOT_PENDING"
    ERR_SCHEDULE_ALREADY_FINAL = "ERR_SCHEDULE_ALREADY_FINAL"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_BORROWER_RESTRICTED: 409,
    ApiErrorId.ERR_ACTIVE_APPLICATION_EXISTS: 409,
    ApiErrorId.ERR_UNDERWRITING_ACCEPTANCE_QUOTA: 409,
    ApiErrorId.ERR_TRUSTEE_SUSPENDED: 409,
    ApiErrorId.ERR_TRUSTEE_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_SCORE_TOO_LOW: 409,
    ApiErrorId.ERR_QUORUM_NOT_MET: 409,
    ApiErrorId.ERR_MIN_CONTRIBUTION: 422,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 422,
    ApiErrorId.ERR_OVERFUND: 422,
    ApiErrorId.ERR_APPLICATION_NOT_FUNDED: 409,
    ApiErrorId.ERR_TIMING_MISMATCH: 409,
    ApiErrorId.ERR_INVITE_NOT_PENDING: 409,
    ApiErrorId.ERR_SCHEDULE_ALREADY_FINAL: 409,
}

# Flat names so tests can write e.g. ERR_OVERFUND directly.
for _member in ApiErrorId:
    globals()[_member.name] = _member.value

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
