"""Error IDs and HTTP status mapping (PRD 5).

Registers the mapping with the framework so ``validate_error()`` auto-checks the
HTTP status code for each error id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_DATE_WINDOW = "ERR_INVALID_DATE_WINDOW"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_AUDIT_NOT_APPROVED = "ERR_AUDIT_NOT_APPROVED"
    ERR_SCOPE_NOT_INSTALLED = "ERR_SCOPE_NOT_INSTALLED"
    ERR_NOT_WAP_ELIGIBLE = "ERR_NOT_WAP_ELIGIBLE"
    ERR_BASELINE_TEST_REQUIRED = "ERR_BASELINE_TEST_REQUIRED"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_SCOPE_INCOMPLETE = "ERR_SCOPE_INCOMPLETE"
    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_DWELLING_WINDOW_CONFLICT = "ERR_DWELLING_WINDOW_CONFLICT"
    ERR_CREW_CAPACITY_EXCEEDED = "ERR_CREW_CAPACITY_EXCEEDED"
    ERR_REBATE_BUDGET_EXCEEDED = "ERR_REBATE_BUDGET_EXCEEDED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_DATE_WINDOW: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_AUDIT_NOT_APPROVED: 409,
    ApiErrorId.ERR_SCOPE_NOT_INSTALLED: 409,
    ApiErrorId.ERR_NOT_WAP_ELIGIBLE: 409,
    ApiErrorId.ERR_BASELINE_TEST_REQUIRED: 409,
    ApiErrorId.ERR_SOD_VIOLATION: 409,
    ApiErrorId.ERR_SCOPE_INCOMPLETE: 409,
    ApiErrorId.ERR_CREW_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_DWELLING_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_CREW_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_REBATE_BUDGET_EXCEEDED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
