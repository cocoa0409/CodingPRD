def err_unauthenticated(message="Missing or unknown X-User-Role, or missing X-User-ID"):
    return ApiError(ERR_UNAUTHENTICATED, message, 401)


def err_forbidden(message="Role not permitted for this endpoint"):
    return ApiError(ERR_FORBIDDEN, message, 403)


def err_not_found(message="Referenced identifier does not exist"):
    return ApiError(ERR_NOT_FOUND, message, 404)


def err_validation(message="Request validation failed"):
    return ApiError(ERR_VALIDATION, message, 400)
