    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VALIDATION_ALREADY_SENT = "ERR_VALIDATION_ALREADY_SENT"
    ERR_CEASE_COMMUNICATION = "ERR_CEASE_COMMUNICATION"
    ERR_VALIDATION_HOLD = "ERR_VALIDATION_HOLD"
    ERR_OUTSIDE_CALL_WINDOW = "ERR_OUTSIDE_CALL_WINDOW"
    ERR_POST_CONVERSATION_COOLDOWN = "ERR_POST_CONVERSATION_COOLDOWN"
    ERR_CADENCE_EXCEEDED = "ERR_CADENCE_EXCEEDED"
    ERR_TIME_BARRED = "ERR_TIME_BARRED"
    ERR_SETTLEMENT_BELOW_FLOOR = "ERR_SETTLEMENT_BELOW_FLOOR"
