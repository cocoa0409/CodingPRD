"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so ``validate_error()`` auto-checks
the HTTP status for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_DONOR_MISMATCH = "ERR_DONOR_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CAMPAIGN_NOT_ACTIVE = "ERR_CAMPAIGN_NOT_ACTIVE"
    ERR_CAMPAIGN_FROZEN = "ERR_CAMPAIGN_FROZEN"
    ERR_PAYOUT_ON_HOLD = "ERR_PAYOUT_ON_HOLD"
    ERR_BENEFICIARY_NOT_VERIFIED = "ERR_BENEFICIARY_NOT_VERIFIED"
    ERR_WITHDRAWAL_NOT_READY = "ERR_WITHDRAWAL_NOT_READY"
    ERR_GOAL_INVALID = "ERR_GOAL_INVALID"
    ERR_WINDOW_INVALID = "ERR_WINDOW_INVALID"
    ERR_AMOUNT_BELOW_MIN = "ERR_AMOUNT_BELOW_MIN"
    ERR_INSUFFICIENT_AVAILABLE = "ERR_INSUFFICIENT_AVAILABLE"
    ERR_SLOT_CONFLICT = "ERR_SLOT_CONFLICT"
    ERR_PAYOUT_COOLDOWN = "ERR_PAYOUT_COOLDOWN"
    ERR_DUPLICATE_TEAM_MEMBER = "ERR_DUPLICATE_TEAM_MEMBER"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_DONOR_MISMATCH: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CAMPAIGN_NOT_ACTIVE: 409,
    ApiErrorId.ERR_CAMPAIGN_FROZEN: 409,
    ApiErrorId.ERR_PAYOUT_ON_HOLD: 409,
    ApiErrorId.ERR_BENEFICIARY_NOT_VERIFIED: 409,
    ApiErrorId.ERR_WITHDRAWAL_NOT_READY: 409,
    ApiErrorId.ERR_GOAL_INVALID: 422,
    ApiErrorId.ERR_WINDOW_INVALID: 422,
    ApiErrorId.ERR_AMOUNT_BELOW_MIN: 422,
    ApiErrorId.ERR_INSUFFICIENT_AVAILABLE: 402,
    ApiErrorId.ERR_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_PAYOUT_COOLDOWN: 409,
    ApiErrorId.ERR_DUPLICATE_TEAM_MEMBER: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
