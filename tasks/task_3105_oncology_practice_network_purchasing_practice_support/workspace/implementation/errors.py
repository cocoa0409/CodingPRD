"""Error identifiers and the API exception type.

Every error_id below is taken verbatim from the scaffold's error catalog (S1.6)
and the PRD's error catalogue (S5). HTTP statuses are the ones the catalog pairs
with each identifier.
"""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = http_status if http_status is not None else HTTP_FOR.get(error_id, 400)


