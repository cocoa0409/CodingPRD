"""Error catalogue (PRD section 5).  67 error identifiers with their HTTP codes."""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 422)
        self.message = message or DEFAULT_MESSAGES.get(error_id, error_id)


def fail(error_id, message=None):
    raise ApiError(error_id, message)


def message_for(error_id):
    return DEFAULT_MESSAGES.get(error_id, error_id)


