    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Sailing / inventory gating
    ERR_SAILING_NOT_BOOKABLE = "ERR_SAILING_NOT_BOOKABLE"
    ERR_SAILING_NOT_DEPARTABLE = "ERR_SAILING_NOT_DEPARTABLE"
    ERR_SAILING_NOT_DEPARTED = "ERR_SAILING_NOT_DEPARTED"
    ERR_NO_INVENTORY = "ERR_NO_INVENTORY"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
