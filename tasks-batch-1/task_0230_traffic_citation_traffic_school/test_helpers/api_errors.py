"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NO_CHARGES = "ERR_NO_CHARGES"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"
    ERR_HAS_PAYMENTS = "ERR_HAS_PAYMENTS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_NOT_YET_LATE = "ERR_NOT_YET_LATE"
    ERR_PENALTY_ALREADY_APPLIED = "ERR_PENALTY_ALREADY_APPLIED"
    ERR_INVALID_HEARING_DATE = "ERR_INVALID_HEARING_DATE"
    ERR_CONTINUANCE_LIMIT = "ERR_CONTINUANCE_LIMIT"
    ERR_ALREADY_CONTESTED = "ERR_ALREADY_CONTESTED"
    ERR_SCHOOL_INELIGIBLE = "ERR_SCHOOL_INELIGIBLE"
    ERR_FINE_UNPAID = "ERR_FINE_UNPAID"
    ERR_SCHOOL_DEADLINE_PASSED = "ERR_SCHOOL_DEADLINE_PASSED"
    ERR_INSTALLMENT_TOO_SMALL = "ERR_INSTALLMENT_TOO_SMALL"
    ERR_HOLD_CONDITION_UNMET = "ERR_HOLD_CONDITION_UNMET"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NO_CHARGES: 409,
    ApiErrorId.ERR_OVERPAYMENT: 409,
    ApiErrorId.ERR_HAS_PAYMENTS: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_NOT_YET_LATE: 409,
    ApiErrorId.ERR_PENALTY_ALREADY_APPLIED: 409,
    ApiErrorId.ERR_INVALID_HEARING_DATE: 409,
    ApiErrorId.ERR_CONTINUANCE_LIMIT: 409,
    ApiErrorId.ERR_ALREADY_CONTESTED: 409,
    ApiErrorId.ERR_SCHOOL_INELIGIBLE: 409,
    ApiErrorId.ERR_FINE_UNPAID: 409,
    ApiErrorId.ERR_SCHOOL_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_INSTALLMENT_TOO_SMALL: 409,
    ApiErrorId.ERR_HOLD_CONDITION_UNMET: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
