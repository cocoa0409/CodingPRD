"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can
auto-check HTTP status codes against the PRD-declared status.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth / Authz (PRD §2.1)
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_CONFLICT_OF_INTEREST = "ERR_CONFLICT_OF_INTEREST"

    # Existence (PRD §2.6)
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # State / concurrency
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_DUPLICATE_BID = "ERR_DUPLICATE_BID"
    ERR_BID_ALREADY_EVALUATED = "ERR_BID_ALREADY_EVALUATED"
    ERR_PROJECT_FROZEN = "ERR_PROJECT_FROZEN"
    ERR_PLAN_HAS_ACTIVE_PROJECT = "ERR_PLAN_HAS_ACTIVE_PROJECT"

    # Business safety
    ERR_SUPPLIER_BLACKLISTED = "ERR_SUPPLIER_BLACKLISTED"

    # Business temporal
    ERR_DEADLINE_PASSED = "ERR_DEADLINE_PASSED"
    ERR_QUERY_WINDOW_CLOSED = "ERR_QUERY_WINDOW_CLOSED"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"

    # Business referential / constraint
    ERR_PLAN_ITEM_NOT_PUBLISHED = "ERR_PLAN_ITEM_NOT_PUBLISHED"
    ERR_WEIGHTS_INVALID = "ERR_WEIGHTS_INVALID"
    ERR_TENDER_VERSION_MISMATCH = "ERR_TENDER_VERSION_MISMATCH"
    ERR_COMMITTEE_SIZE_INVALID = "ERR_COMMITTEE_SIZE_INVALID"
    ERR_CONTRACT_INCONSISTENT = "ERR_CONTRACT_INCONSISTENT"
    ERR_AMENDMENT_EXCEEDS_CAP = "ERR_AMENDMENT_EXCEEDS_CAP"
    ERR_BID_EXCEEDS_CEILING = "ERR_BID_EXCEEDS_CEILING"

    # Generic
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_CONFLICT_OF_INTEREST: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_BID: 409,
    ApiErrorId.ERR_BID_ALREADY_EVALUATED: 409,
    ApiErrorId.ERR_PROJECT_FROZEN: 409,
    ApiErrorId.ERR_PLAN_HAS_ACTIVE_PROJECT: 409,
    ApiErrorId.ERR_SUPPLIER_BLACKLISTED: 403,
    ApiErrorId.ERR_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_QUERY_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_INVALID_TIME_WINDOW: 422,
    ApiErrorId.ERR_PLAN_ITEM_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_WEIGHTS_INVALID: 422,
    ApiErrorId.ERR_TENDER_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_COMMITTEE_SIZE_INVALID: 422,
    ApiErrorId.ERR_CONTRACT_INCONSISTENT: 422,
    ApiErrorId.ERR_AMENDMENT_EXCEEDS_CAP: 409,
    ApiErrorId.ERR_BID_EXCEEDS_CEILING: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
