"""Error IDs and HTTP status mapping — PRD §5.

The mapping is registered with the framework at import time so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1, §2.9
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    # Existence — PRD §2.7
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    # State — PRD §3, §2.9
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FORM_ALREADY_SIGNED = "ERR_FORM_ALREADY_SIGNED"
    ERR_DUPLICATE_INITIAL_FORM = "ERR_DUPLICATE_INITIAL_FORM"
    # Business — PRD §3.3, §3.5, §3.4
    ERR_INVALID_FORM_LINEAGE = "ERR_INVALID_FORM_LINEAGE"
    ERR_DOCUMENT_LIST_RULE = "ERR_DOCUMENT_LIST_RULE"
    ERR_DOCUMENT_CATEGORY_MISMATCH = "ERR_DOCUMENT_CATEGORY_MISMATCH"
    ERR_DOCUMENT_EXPIRED = "ERR_DOCUMENT_EXPIRED"
    ERR_SECTION2_DEADLINE_MISSED = "ERR_SECTION2_DEADLINE_MISSED"
    ERR_CASE_ALREADY_OPEN = "ERR_CASE_ALREADY_OPEN"
    ERR_IDEMPOTENT_REPLAY = "ERR_IDEMPOTENT_REPLAY"
    ERR_TNC_DEADLINE_PASSED = "ERR_TNC_DEADLINE_PASSED"
    ERR_EVERIFY_SUBMISSION_LATE = "ERR_EVERIFY_SUBMISSION_LATE"
    ERR_STEM_EXTENSION_LATE = "ERR_STEM_EXTENSION_LATE"
    # OCC — PRD §2.5
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    # Pagination — PRD §2.3
    ERR_PAGINATION = "ERR_PAGINATION"
    # Generic validation — PRD §5
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 — Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FORM_ALREADY_SIGNED: 409,
    ApiErrorId.ERR_DUPLICATE_INITIAL_FORM: 409,
    ApiErrorId.ERR_INVALID_FORM_LINEAGE: 422,
    ApiErrorId.ERR_DOCUMENT_LIST_RULE: 422,
    ApiErrorId.ERR_DOCUMENT_CATEGORY_MISMATCH: 422,
    ApiErrorId.ERR_DOCUMENT_EXPIRED: 422,
    ApiErrorId.ERR_SECTION2_DEADLINE_MISSED: 409,
    ApiErrorId.ERR_CASE_ALREADY_OPEN: 409,
    ApiErrorId.ERR_IDEMPOTENT_REPLAY: 200,
    ApiErrorId.ERR_TNC_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_EVERIFY_SUBMISSION_LATE: 409,
    ApiErrorId.ERR_STEM_EXTENSION_LATE: 422,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_PAGINATION: 400,
    ApiErrorId.ERR_VALIDATION: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
