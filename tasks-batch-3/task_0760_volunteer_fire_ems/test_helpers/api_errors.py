"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so ``validate_error()`` auto-checks the
HTTP status code that accompanies each ``error_id``.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_MEMBER_NOT_FOUND = "ERR_MEMBER_NOT_FOUND"
    ERR_CERTIFICATION_NOT_FOUND = "ERR_CERTIFICATION_NOT_FOUND"
    ERR_STATION_NOT_FOUND = "ERR_STATION_NOT_FOUND"
    ERR_APPARATUS_NOT_FOUND = "ERR_APPARATUS_NOT_FOUND"
    ERR_EQUIPMENT_NOT_FOUND = "ERR_EQUIPMENT_NOT_FOUND"
    ERR_MAINTENANCE_WINDOW_NOT_FOUND = "ERR_MAINTENANCE_WINDOW_NOT_FOUND"
    ERR_DUTY_SHIFT_NOT_FOUND = "ERR_DUTY_SHIFT_NOT_FOUND"
    ERR_DUTY_ASSIGNMENT_NOT_FOUND = "ERR_DUTY_ASSIGNMENT_NOT_FOUND"
    ERR_INCIDENT_NOT_FOUND = "ERR_INCIDENT_NOT_FOUND"
    ERR_TURNOUT_NOT_FOUND = "ERR_TURNOUT_NOT_FOUND"
    ERR_CAMPAIGN_NOT_FOUND = "ERR_CAMPAIGN_NOT_FOUND"
    ERR_DONATION_NOT_FOUND = "ERR_DONATION_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_MEMBER_NOT_RESPONSE_ELIGIBLE = "ERR_MEMBER_NOT_RESPONSE_ELIGIBLE"
    ERR_APPARATUS_NOT_AT_STATION = "ERR_APPARATUS_NOT_AT_STATION"
    ERR_APPARATUS_OUT_OF_SERVICE = "ERR_APPARATUS_OUT_OF_SERVICE"
    ERR_SHIFT_OVERLAP = "ERR_SHIFT_OVERLAP"
    ERR_MAINTENANCE_OVERLAP = "ERR_MAINTENANCE_OVERLAP"
    ERR_SHIFT_FULL = "ERR_SHIFT_FULL"
    ERR_INSUFFICIENT_TRAINING_HOURS = "ERR_INSUFFICIENT_TRAINING_HOURS"
    ERR_NFIRS_INCOMPLETE = "ERR_NFIRS_INCOMPLETE"
    ERR_DUES_OVERDUE = "ERR_DUES_OVERDUE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_MEMBER_NOT_FOUND: 404,
    ApiErrorId.ERR_CERTIFICATION_NOT_FOUND: 404,
    ApiErrorId.ERR_STATION_NOT_FOUND: 404,
    ApiErrorId.ERR_APPARATUS_NOT_FOUND: 404,
    ApiErrorId.ERR_EQUIPMENT_NOT_FOUND: 404,
    ApiErrorId.ERR_MAINTENANCE_WINDOW_NOT_FOUND: 404,
    ApiErrorId.ERR_DUTY_SHIFT_NOT_FOUND: 404,
    ApiErrorId.ERR_DUTY_ASSIGNMENT_NOT_FOUND: 404,
    ApiErrorId.ERR_INCIDENT_NOT_FOUND: 404,
    ApiErrorId.ERR_TURNOUT_NOT_FOUND: 404,
    ApiErrorId.ERR_CAMPAIGN_NOT_FOUND: 404,
    ApiErrorId.ERR_DONATION_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_MEMBER_NOT_RESPONSE_ELIGIBLE: 409,
    ApiErrorId.ERR_APPARATUS_NOT_AT_STATION: 409,
    ApiErrorId.ERR_APPARATUS_OUT_OF_SERVICE: 409,
    ApiErrorId.ERR_SHIFT_OVERLAP: 409,
    ApiErrorId.ERR_MAINTENANCE_OVERLAP: 409,
    ApiErrorId.ERR_SHIFT_FULL: 409,
    ApiErrorId.ERR_INSUFFICIENT_TRAINING_HOURS: 422,
    ApiErrorId.ERR_NFIRS_INCOMPLETE: 422,
    ApiErrorId.ERR_DUES_OVERDUE: 402,
    ApiErrorId.ERR_STALE_VERSION: 412,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
