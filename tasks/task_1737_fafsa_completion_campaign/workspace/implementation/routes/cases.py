@bp.route("/fafsa/checklist-items/<iid>/waive", methods=["POST"])
def waive_item(iid):
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["Specialist"])
    item, checklist = _item_and_checklist(iid)
    if checklist["status"] == "ARCHIVED":
        errors.raise_error(errors.ERR_CHECKLIST_ARCHIVED, "Item operations blocked when checklist is ARCHIVED")
    if item["status"] != "PENDING":
        errors.raise_error(errors.ERR_ITEM_NOT_PENDING, "waive requires PENDING")
    if not item["waivable"]:
        errors.raise_error(errors.ERR_ITEM_NOT_WAIVABLE, "Item is not waivable")
    # Acting specialist holds a non-terminal case for this senior
    found = False
    for c in store.support_cases.values():
        if (
            c["senior_record_id"] == checklist["senior_record_id"]
            and c["assigned_specialist_id"] == auth.user_id
            and c["status"] in core.NON_TERMINAL_CASE_STATUSES
        ):
            found = True
            break
    if not found:
        errors.raise_error(errors.ERR_CASE_NOT_FOUND_FOR_SPECIALIST, "Acting specialist has no non-terminal case for this senior")
    item["status"] = "WAIVED"
    touch(item)
    core.reevaluate_checklist_status(checklist)
    return success_object(core.serialize(item))


