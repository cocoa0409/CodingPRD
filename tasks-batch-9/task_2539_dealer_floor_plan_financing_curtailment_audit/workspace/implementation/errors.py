"""Error catalogue of PRD section 5.  The identifier is the contract; the HTTP
status code is derived from it and never varies by endpoint."""


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        super(ApiError, self).__init__(error_id)
        self.error_id = error_id
        self.message = message or DEFAULT_MESSAGES.get(error_id, error_id)
        self.http_status = HTTP_STATUS.get(error_id, 400)


