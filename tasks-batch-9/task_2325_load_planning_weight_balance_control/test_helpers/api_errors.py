"""Error identifiers and their HTTP statuses for the load planning API.

Importing this module registers the error -> HTTP status mapping with the
framework validators so that ``validate_error(response, ApiErrorId.X)`` can
check the status code without the test having to repeat it.
"""

from __future__ import annotations

