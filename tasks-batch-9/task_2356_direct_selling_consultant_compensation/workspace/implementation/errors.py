DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Both X-User-ID and X-User-Role headers are required.",
    "ERR_UNAUTHORIZED": "The acting role is not authorised for this endpoint.",
    "ERR_FORBIDDEN_RESOURCE": "The acting caller does not own the addressed resource.",
    "ERR_VALIDATION": "The request shape is invalid.",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize() + "."
        )
