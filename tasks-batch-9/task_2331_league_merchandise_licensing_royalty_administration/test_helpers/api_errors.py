    CHANNEL_LINE_RETAILER_MISMATCH = "ERR_CHANNEL_LINE_RETAILER_MISMATCH"
    CHANNEL_NOT_AUTHORIZED = "ERR_CHANNEL_NOT_AUTHORIZED"

    # Fiscal lines
    PERIOD_OUTSIDE_TERM = "ERR_PERIOD_OUTSIDE_TERM"
    MG_BELOW_FLOOR = "ERR_MG_BELOW_FLOOR"
    ADVANCE_BELOW_FLOOR = "ERR_ADVANCE_BELOW_FLOOR"
    ADVANCE_OVERPAYMENT = "ERR_ADVANCE_OVERPAYMENT"
    DEDUCTION_LIMIT_EXCEEDED = "ERR_DEDUCTION_LIMIT_EXCEEDED"
    CLOSEOUT_LIMIT_EXCEEDED = "ERR_CLOSEOUT_LIMIT_EXCEEDED"
    CLOSEOUT_NOT_PERMITTED = "ERR_CLOSEOUT_NOT_PERMITTED"
    SETTLEMENT_OUT_OF_RANGE = "ERR_SETTLEMENT_OUT_OF_RANGE"

    # Uniqueness, overlap, capacity
    DUPLICATE_REPORT_PERIOD = "ERR_DUPLICATE_REPORT_PERIOD"
    DUPLICATE_AGREEMENT = "ERR_DUPLICATE_AGREEMENT"
    TERRITORY_EXCLUSIVITY_CONFLICT = "ERR_TERRITORY_EXCLUSIVITY_CONFLICT"
    OFF_PRICE_CAPACITY_EXCEEDED = "ERR_OFF_PRICE_CAPACITY_EXCEEDED"
    RETAILER_WINDOW_CONFLICT = "ERR_RETAILER_WINDOW_CONFLICT"

    # Distribution interlocks
    DISTRIBUTION_ALREADY_CLOSED = "ERR_DISTRIBUTION_ALREADY_CLOSED"
    PENDING_REPORTS_BLOCK_DISTRIBUTION = "ERR_PENDING_REPORTS_BLOCK_DISTRIBUTION"
    EMPTY_DISTRIBUTION_POOL = "ERR_EMPTY_DISTRIBUTION_POOL"

    # Audit and temporal
    AUDIT_SCOPE_NOT_ACCEPTED = "ERR_AUDIT_SCOPE_NOT_ACCEPTED"
    GRANT_WINDOW_INVALID = "ERR_GRANT_WINDOW_INVALID"
    PERIOD_NOT_ENDED = "ERR_PERIOD_NOT_ENDED"
    AUDIT_WINDOW_EXPIRED = "ERR_AUDIT_WINDOW_EXPIRED"
    QUARTER_ALREADY_CLOSED = "ERR_QUARTER_ALREADY_CLOSED"
    CLOCK_BACKWARD = "ERR_CLOCK_BACKWARD"


