def test_preparer_cannot_hire_an_employee_but_may_read_employees(api):
    """PRD §2.1: "When the acting role is not among the roles listed for the
    endpoint being called, the request is rejected with `ERR_FORBIDDEN_ROLE`
    (HTTP 403)."
    PRD §2.1: "A `BenefitsAdmin` owns workforce data: hires, wage updates, hours
    of service, leaves, transfers, terminations, rehires and offers of coverage."
    PRD §4: "| GET | `/ale-reporting/employees` | List employees, filterable by
    member and employment status | ComplianceOfficer, Preparer, FilingAgent,
    BenefitsAdmin |"

    Design: Corner/RBAC/preparer_cannot_create_employee_records
    """
    ctx = fixtures.determined_ale_group_with_employee(api)
    member_id = ctx["member"]["id"]

    refused = api.create_employee(
        f.employee_payload(
            member_id, full_name="Ghost Hire", ssn_last4="0000", hire_date="2025-02-01"
        ),
        PREPARER_1,
    )
    validate_error(refused, ApiErrorId.ERR_FORBIDDEN_ROLE, 403)

    rows, meta = validate_paginated(api.list_employees(PREPARER_1))
    assert meta["total_count"] == 1, (
        f"expected the single benefits-admin hire to survive, got "
        f"{meta['total_count']} employees after the refused preparer hire"
    )
    assert rows[0]["id"] == ctx["employee"]["id"], (
        "the preparer's list read must return the employee the benefits admin hired"
    )


def test_preparer_cannot_amend_an_employee(api):
    """PRD §2.1: "When the acting role is not among the roles listed for the
    endpoint being called, the request is rejected with `ERR_FORBIDDEN_ROLE`
    (HTTP 403)."
    PRD §3.3: "The admin may later amend `w2_box1_wages_cents`,
    `hourly_rate_cents`, `monthly_salary_cents` and `measurement_method_override`;
    each amendment re-resolves `effective_measurement_method` and increments the
    employee's `version`."

    Design: Corner/RBAC/preparer_cannot_create_employee_records
    """
    ctx = fixtures.determined_ale_group_with_employee(api)
    employee = ctx["employee"]

    refused = api.update_employee(
        employee["id"], {"w2_box1_wages_cents": 500000}, PREPARER_1
    )
    validate_error(refused, ApiErrorId.ERR_FORBIDDEN_ROLE, 403)

    after = fixtures.read_employee(api, employee["id"])
    assert after["w2_box1_wages_cents"] == 0, (
        "the refused preparer amendment must leave the default wage figure of 0 "
        f"in place, got {after['w2_box1_wages_cents']}"
    )
    assert after["version"] == employee["version"], (
        f"expected version {employee['version']} to be unchanged by a refused "
        f"amendment, got {after['version']}"
    )


def test_preparer_may_run_the_employee_full_time_recompute(api):
    """PRD §3.5: "Either a `BenefitsAdmin` or a `Preparer` can run the recompute
    for one employee on demand; it also runs automatically whenever a statement is
    generated or regenerated."
    PRD §3.5: "The recompute writes `full_time_months`, `full_time_month_count`,
    `measured_average_hours`, `ft_source_by_month` and `last_recomputed_at` on the
    employee, and refreshes `full_time_flag`, `ft_source` and `assessable` on the
    coverage lines of the employee's non-voided statement."
    PRD §3.3: "A new hire starts `ACTIVE` with a null `termination_date`, a null
    `open_leave_type`, `full_time_month_count` of 0, empty `full_time_months`, a
    null `measured_average_hours` and a null `last_recomputed_at`."
    PRD §3.5: "`full_time_months` is the ascending list of the months that survive
    as full time, `full_time_month_count` is its length, and `ft_source_by_month`
    is the twelve source labels in calendar order starting with January, each one
    of `LOOK_BACK_STABILITY`, `MONTHLY_ACTUAL`, `LNAP` or `NOT_EMPLOYED`."

    Design: Corner/RBAC/preparer_cannot_create_employee_records
    """
    ctx = fixtures.determined_ale_group_with_employee(api)
    employee = ctx["employee"]
    assert employee["last_recomputed_at"] is None, "a new hire starts un-recomputed"

    recomputed = validate_success(
        api.recompute_employee_full_time(employee["id"], PREPARER_1), 200
    )
    assert recomputed["last_recomputed_at"] is not None, (
        "the preparer's recompute must actually stamp `last_recomputed_at`, not "
        "merely be admitted"
    )
    assert len(recomputed["ft_source_by_month"]) == 12, (
        "the recompute writes the twelve source labels in calendar order, got "
        f"{recomputed['ft_source_by_month']!r}"
    )


