"""Error IDs and HTTP status mapping per the Error Code Catalogue."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ASN_MISMATCH = "ERR_ASN_MISMATCH"
    ERR_LOT_NOT_ACTIVE = "ERR_LOT_NOT_ACTIVE"
    ERR_ZONE_MISMATCH = "ERR_ZONE_MISMATCH"
    ERR_NO_BIN_AVAILABLE = "ERR_NO_BIN_AVAILABLE"
    ERR_BIN_FROZEN = "ERR_BIN_FROZEN"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_LOT_NOT_PICKABLE = "ERR_LOT_NOT_PICKABLE"
    ERR_LOT_NOT_SHIPPABLE = "ERR_LOT_NOT_SHIPPABLE"
    ERR_LOT_HAS_OPEN_PICKS = "ERR_LOT_HAS_OPEN_PICKS"
    ERR_POSTURE_FROZEN = "ERR_POSTURE_FROZEN"
    ERR_WAVE_OVERLAP = "ERR_WAVE_OVERLAP"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_INPUT: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ASN_MISMATCH: 409,
    ApiErrorId.ERR_LOT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ZONE_MISMATCH: 409,
    ApiErrorId.ERR_NO_BIN_AVAILABLE: 409,
    ApiErrorId.ERR_BIN_FROZEN: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_LOT_NOT_PICKABLE: 409,
    ApiErrorId.ERR_LOT_NOT_SHIPPABLE: 409,
    ApiErrorId.ERR_LOT_HAS_OPEN_PICKS: 409,
    ApiErrorId.ERR_POSTURE_FROZEN: 409,
    ApiErrorId.ERR_WAVE_OVERLAP: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
