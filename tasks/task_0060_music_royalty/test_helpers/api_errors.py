"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_WORK_FROZEN = "ERR_WORK_FROZEN"
    ERR_POOL_HAS_FROZEN_DISTRIBUTIONS = "ERR_POOL_HAS_FROZEN_DISTRIBUTIONS"
    ERR_DISTRIBUTION_NOT_FORFEITABLE = "ERR_DISTRIBUTION_NOT_FORFEITABLE"
    ERR_MINOR_REQUIRES_GUARDIAN = "ERR_MINOR_REQUIRES_GUARDIAN"
    ERR_MINOR_PAYOUT_BLOCKED = "ERR_MINOR_PAYOUT_BLOCKED"
    ERR_PLAYBACK_SIGNATURE_INVALID = "ERR_PLAYBACK_SIGNATURE_INVALID"
    ERR_PLAYBACK_RANGE_INVALID = "ERR_PLAYBACK_RANGE_INVALID"
    ERR_DUPLICATE_BATCH = "ERR_DUPLICATE_BATCH"
    ERR_DUPLICATE_IDENTIFIER = "ERR_DUPLICATE_IDENTIFIER"
    ERR_COCREATOR_SUM_INVALID = "ERR_COCREATOR_SUM_INVALID"
    ERR_SHARE_SUM_INVALID = "ERR_SHARE_SUM_INVALID"
    ERR_AGENCY_BINDING_INAPPLICABLE = "ERR_AGENCY_BINDING_INAPPLICABLE"
    ERR_AGENCY_BINDING_OVERLAP = "ERR_AGENCY_BINDING_OVERLAP"
    ERR_RULE_WEIGHTS_INVALID = "ERR_RULE_WEIGHTS_INVALID"
    ERR_RULE_NOT_EFFECTIVE = "ERR_RULE_NOT_EFFECTIVE"
    ERR_BELOW_MIN_PAYOUT = "ERR_BELOW_MIN_PAYOUT"
    ERR_DUPLICATE_CYCLE = "ERR_DUPLICATE_CYCLE"
    ERR_RESOLUTION_INVALID = "ERR_RESOLUTION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_WORK_FROZEN: 409,
    ApiErrorId.ERR_POOL_HAS_FROZEN_DISTRIBUTIONS: 409,
    ApiErrorId.ERR_DISTRIBUTION_NOT_FORFEITABLE: 409,
    ApiErrorId.ERR_MINOR_REQUIRES_GUARDIAN: 422,
    ApiErrorId.ERR_MINOR_PAYOUT_BLOCKED: 422,
    ApiErrorId.ERR_PLAYBACK_SIGNATURE_INVALID: 403,
    ApiErrorId.ERR_PLAYBACK_RANGE_INVALID: 422,
    ApiErrorId.ERR_DUPLICATE_BATCH: 409,
    ApiErrorId.ERR_DUPLICATE_IDENTIFIER: 409,
    ApiErrorId.ERR_COCREATOR_SUM_INVALID: 422,
    ApiErrorId.ERR_SHARE_SUM_INVALID: 422,
    ApiErrorId.ERR_AGENCY_BINDING_INAPPLICABLE: 422,
    ApiErrorId.ERR_AGENCY_BINDING_OVERLAP: 409,
    ApiErrorId.ERR_RULE_WEIGHTS_INVALID: 422,
    ApiErrorId.ERR_RULE_NOT_EFFECTIVE: 422,
    ApiErrorId.ERR_BELOW_MIN_PAYOUT: 422,
    ApiErrorId.ERR_DUPLICATE_CYCLE: 409,
    ApiErrorId.ERR_RESOLUTION_INVALID: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
