"""Error catalogue and the ApiError exception.

Every error id declared by the PRD error catalog (82 codes) maps to its HTTP
status here.  Handlers raise ApiError(<code>) and app.py renders the envelope.
"""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status or HTTP_STATUS.get(error_id, 400)
        self.message = message or MESSAGES.get(error_id, error_id)


