def unauthenticated(msg="Missing or malformed X-User-Role / X-User-ID headers"):
    return ApiError(ERR_UNAUTHENTICATED, 401, msg)


def unauthorized_role(msg="Role not permitted for this endpoint/action"):
    return ApiError(ERR_UNAUTHORIZED_ROLE, 403, msg)


def validation(msg="Malformed request"):
    return ApiError(ERR_VALIDATION, 400, msg)


def not_found(error_id: str, msg: str = ""):
    return ApiError(error_id, 404, msg or error_id)
