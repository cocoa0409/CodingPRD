"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / context
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"

    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FLIGHT_NOT_FOUND = "ERR_FLIGHT_NOT_FOUND"

    # Request validation
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # State / transitions
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Cross-entity preconditions
    ERR_FLIGHT_NOT_FINALIZED = "ERR_FLIGHT_NOT_FINALIZED"
    ERR_POLICY_INACTIVE = "ERR_POLICY_INACTIVE"
    ERR_BATCH_NOT_APPROVED = "ERR_BATCH_NOT_APPROVED"
    ERR_CLAIM_NOT_APPROVED = "ERR_CLAIM_NOT_APPROVED"
    ERR_BATCH_FLIGHT_MISMATCH = "ERR_BATCH_FLIGHT_MISMATCH"
    ERR_BATCH_ALREADY_DISPATCHED = "ERR_BATCH_ALREADY_DISPATCHED"
    ERR_TICKET_NOT_BOUND = "ERR_TICKET_NOT_BOUND"
    ERR_TICKET_LOCKED_BY_CLAIM = "ERR_TICKET_LOCKED_BY_CLAIM"

    # Eligibility / temporal / fiscal
    ERR_WAITING_PERIOD_NOT_MET = "ERR_WAITING_PERIOD_NOT_MET"
    ERR_CLAIM_NOT_ELIGIBLE = "ERR_CLAIM_NOT_ELIGIBLE"
    ERR_QUOTA_EXHAUSTED = "ERR_QUOTA_EXHAUSTED"
    ERR_RESERVE_DRIFT = "ERR_RESERVE_DRIFT"

    # Idempotency
    ERR_DUPLICATE_EVENT = "ERR_DUPLICATE_EVENT"
    ERR_DUPLICATE_PNR = "ERR_DUPLICATE_PNR"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_SOD_VIOLATION: 403,

    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FLIGHT_NOT_FOUND: 404,

    ApiErrorId.ERR_INVALID_REQUEST: 400,

    ApiErrorId.ERR_INVALID_STATE: 409,

    ApiErrorId.ERR_FLIGHT_NOT_FINALIZED: 409,
    ApiErrorId.ERR_POLICY_INACTIVE: 409,
    ApiErrorId.ERR_BATCH_NOT_APPROVED: 409,
    ApiErrorId.ERR_CLAIM_NOT_APPROVED: 409,
    ApiErrorId.ERR_BATCH_FLIGHT_MISMATCH: 409,
    ApiErrorId.ERR_BATCH_ALREADY_DISPATCHED: 409,
    ApiErrorId.ERR_TICKET_NOT_BOUND: 409,
    ApiErrorId.ERR_TICKET_LOCKED_BY_CLAIM: 409,

    ApiErrorId.ERR_WAITING_PERIOD_NOT_MET: 409,
    ApiErrorId.ERR_CLAIM_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_QUOTA_EXHAUSTED: 409,
    ApiErrorId.ERR_RESERVE_DRIFT: 409,

    ApiErrorId.ERR_DUPLICATE_EVENT: 409,
    ApiErrorId.ERR_DUPLICATE_PNR: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
