"""Error catalog for the Product Certification Followup API.

Every error identifier the PRD declares, mapped to the HTTP status the PRD
section 5 catalogue fixes for it. Registering the mapping with the shared
validators lets ``validate_error`` cross-check the status automatically, so a
test only has to name the identifier it expects.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map

__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]


class ApiErrorId(str, Enum):
    """Declared error identifiers (PRD section 5)."""

    # Authentication and authorization (PRD 2.8 stages 1-3).
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED_ROLE = "ERR_UNAUTHORIZED_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Existence and generic request shape (stages 4 and the standalone 400 rule).
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # Optimistic concurrency (stage 5).
    ERR_STALE_VERSION = "ERR_STALE_VERSION"

    # State admissibility (stage 6).
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"
    ERR_MANUFACTURER_SUSPENDED = "ERR_MANUFACTURER_SUSPENDED"
    ERR_STANDARD_NOT_ACTIVE = "ERR_STANDARD_NOT_ACTIVE"
    ERR_SAMPLE_NOT_ACCEPTED = "ERR_SAMPLE_NOT_ACCEPTED"
    ERR_PROJECT_NOT_EVALUABLE = "ERR_PROJECT_NOT_EVALUABLE"
    ERR_CERTIFICATION_NOT_ACTIVE = "ERR_CERTIFICATION_NOT_ACTIVE"
    ERR_LICENSE_NOT_ACTIVE = "ERR_LICENSE_NOT_ACTIVE"
    ERR_FIELD_EVALUATION_NOT_PASSED = "ERR_FIELD_EVALUATION_NOT_PASSED"

    # Compliance gates at decision points (stage 7).
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_SAFETY_PROTOCOL_NOT_PASSED = "ERR_SAFETY_PROTOCOL_NOT_PASSED"

    # Cross-reference coherence (stage 8).
    ERR_CATEGORY_STANDARD_MISMATCH = "ERR_CATEGORY_STANDARD_MISMATCH"
    ERR_UNKNOWN_PROTOCOL_CODE = "ERR_UNKNOWN_PROTOCOL_CODE"
    ERR_UNKNOWN_COMPONENT_SLOT = "ERR_UNKNOWN_COMPONENT_SLOT"
    ERR_FINDING_CERTIFICATION_MISMATCH = "ERR_FINDING_CERTIFICATION_MISMATCH"
    ERR_MISSING_REQUIRED_SLOT = "ERR_MISSING_REQUIRED_SLOT"
    ERR_DUPLICATE_COMPONENT_SLOT = "ERR_DUPLICATE_COMPONENT_SLOT"

    # Temporal rules (stage 9).
    ERR_STANDARD_EDITION_OVERLAP = "ERR_STANDARD_EDITION_OVERLAP"
    ERR_INSPECTION_DATE_PAST = "ERR_INSPECTION_DATE_PAST"
    ERR_INSPECTION_GAP_VIOLATION = "ERR_INSPECTION_GAP_VIOLATION"

    # Aggregate / structural rules (stage 10).
    ERR_MANDATORY_PROTOCOL_FAILING = "ERR_MANDATORY_PROTOCOL_FAILING"
    ERR_RECIPROCITY_NOT_GRANTED = "ERR_RECIPROCITY_NOT_GRANTED"
    ERR_OPEN_CRITICAL_FINDINGS = "ERR_OPEN_CRITICAL_FINDINGS"

    # Quota rules (stage 11).
    ERR_INVALID_LABEL_QUANTITY = "ERR_INVALID_LABEL_QUANTITY"
    ERR_LABEL_QUOTA_EXCEEDED = "ERR_LABEL_QUOTA_EXCEEDED"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED_ROLE: 403,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ALREADY_TERMINAL: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_MANUFACTURER_SUSPENDED: 409,
    ApiErrorId.ERR_STANDARD_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SAMPLE_NOT_ACCEPTED: 409,
    ApiErrorId.ERR_PROJECT_NOT_EVALUABLE: 409,
    ApiErrorId.ERR_CERTIFICATION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_LICENSE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_FIELD_EVALUATION_NOT_PASSED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_SAFETY_PROTOCOL_NOT_PASSED: 409,
    ApiErrorId.ERR_CATEGORY_STANDARD_MISMATCH: 422,
    ApiErrorId.ERR_UNKNOWN_PROTOCOL_CODE: 422,
    ApiErrorId.ERR_UNKNOWN_COMPONENT_SLOT: 422,
    ApiErrorId.ERR_FINDING_CERTIFICATION_MISMATCH: 422,
    ApiErrorId.ERR_MISSING_REQUIRED_SLOT: 422,
    ApiErrorId.ERR_DUPLICATE_COMPONENT_SLOT: 422,
    ApiErrorId.ERR_STANDARD_EDITION_OVERLAP: 409,
    ApiErrorId.ERR_INSPECTION_DATE_PAST: 422,
    ApiErrorId.ERR_INSPECTION_GAP_VIOLATION: 409,
    ApiErrorId.ERR_MANDATORY_PROTOCOL_FAILING: 409,
    ApiErrorId.ERR_RECIPROCITY_NOT_GRANTED: 409,
    ApiErrorId.ERR_OPEN_CRITICAL_FINDINGS: 409,
    ApiErrorId.ERR_INVALID_LABEL_QUANTITY: 400,
    ApiErrorId.ERR_LABEL_QUOTA_EXCEEDED: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
