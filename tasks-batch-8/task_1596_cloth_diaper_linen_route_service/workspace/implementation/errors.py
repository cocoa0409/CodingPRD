class ApiError(Exception):
    def __init__(self, error_id, status, message):
        super().__init__(message)
        self.error_id = error_id
        self.status = status
        self.message = message


def bad_request(message):
    return ApiError(ERR_INVALID_REQUEST, 400, message)
