"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth / existence
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_ROLE_FORBIDDEN = "ERR_ROLE_FORBIDDEN"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # request shape
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_CROSS_SHOW_REFERENCE = "ERR_CROSS_SHOW_REFERENCE"
    # state
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # temporal
    ERR_TIMING_NOT_ALLOWED = "ERR_TIMING_NOT_ALLOWED"
    ERR_SHOW_TIME_CONFLICT = "ERR_SHOW_TIME_CONFLICT"
    # posture / safety
    ERR_POSTURE_BLOCKED = "ERR_POSTURE_BLOCKED"
    # contract
    ERR_COUNTER_LIMIT_REACHED = "ERR_COUNTER_LIMIT_REACHED"
    # seating / quota
    ERR_SECTION_SOLD_OUT = "ERR_SECTION_SOLD_OUT"
    ERR_TABLE_TOO_SMALL = "ERR_TABLE_TOO_SMALL"
    ERR_TABLE_UNAVAILABLE = "ERR_TABLE_UNAVAILABLE"
    ERR_WRONG_SECTION_KIND = "ERR_WRONG_SECTION_KIND"
    ERR_SERVER_OVERLOADED = "ERR_SERVER_OVERLOADED"
    ERR_NO_SERVER_ASSIGNED = "ERR_NO_SERVER_ASSIGNED"
    # settlement / fiscal
    ERR_MINIMUM_NOT_MET = "ERR_MINIMUM_NOT_MET"
    ERR_SETTLEMENT_EXISTS = "ERR_SETTLEMENT_EXISTS"
    ERR_SHOW_NOT_ENDED = "ERR_SHOW_NOT_ENDED"
    # guest list
    ERR_GUEST_LIST_NOT_LISTED = "ERR_GUEST_LIST_NOT_LISTED"
    # pagination
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_ROLE_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_CROSS_SHOW_REFERENCE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TIMING_NOT_ALLOWED: 409,
    ApiErrorId.ERR_SHOW_TIME_CONFLICT: 409,
    ApiErrorId.ERR_POSTURE_BLOCKED: 409,
    ApiErrorId.ERR_COUNTER_LIMIT_REACHED: 409,
    ApiErrorId.ERR_SECTION_SOLD_OUT: 409,
    ApiErrorId.ERR_TABLE_TOO_SMALL: 409,
    ApiErrorId.ERR_TABLE_UNAVAILABLE: 409,
    ApiErrorId.ERR_WRONG_SECTION_KIND: 409,
    ApiErrorId.ERR_SERVER_OVERLOADED: 409,
    ApiErrorId.ERR_NO_SERVER_ASSIGNED: 409,
    ApiErrorId.ERR_MINIMUM_NOT_MET: 409,
    ApiErrorId.ERR_SETTLEMENT_EXISTS: 409,
    ApiErrorId.ERR_SHOW_NOT_ENDED: 409,
    ApiErrorId.ERR_GUEST_LIST_NOT_LISTED: 409,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
