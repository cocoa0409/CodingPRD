"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ITEM_NOT_ON_CONTRACT = "ERR_ITEM_NOT_ON_CONTRACT"
    ERR_OUT_OF_COVERAGE = "ERR_OUT_OF_COVERAGE"
    ERR_PRE_EXISTING_EXCLUDED = "ERR_PRE_EXISTING_EXCLUDED"
    ERR_ITEM_LIMIT_EXCEEDED = "ERR_ITEM_LIMIT_EXCEEDED"
    ERR_SCHEDULED_IN_PAST = "ERR_SCHEDULED_IN_PAST"
    ERR_TECHNICIAN_DOUBLE_BOOKED = "ERR_TECHNICIAN_DOUBLE_BOOKED"
    ERR_OPEN_CLAIMS_BLOCK_CANCEL = "ERR_OPEN_CLAIMS_BLOCK_CANCEL"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PACKAGE_RETIRED = "ERR_PACKAGE_RETIRED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ITEM_NOT_ON_CONTRACT: 422,
    ApiErrorId.ERR_OUT_OF_COVERAGE: 422,
    ApiErrorId.ERR_PRE_EXISTING_EXCLUDED: 422,
    ApiErrorId.ERR_ITEM_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_SCHEDULED_IN_PAST: 422,
    ApiErrorId.ERR_TECHNICIAN_DOUBLE_BOOKED: 422,
    ApiErrorId.ERR_OPEN_CLAIMS_BLOCK_CANCEL: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PACKAGE_RETIRED: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
