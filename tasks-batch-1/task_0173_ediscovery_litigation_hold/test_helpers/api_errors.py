"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_BATCH_NOT_COMPLETED = "ERR_BATCH_NOT_COMPLETED"
    ERR_CUSTODIAN_NOT_ACKNOWLEDGED = "ERR_CUSTODIAN_NOT_ACKNOWLEDGED"
    ERR_PRIVILEGED_DOCUMENT = "ERR_PRIVILEGED_DOCUMENT"
    ERR_DOCUMENT_NOT_UNIQUE = "ERR_DOCUMENT_NOT_UNIQUE"
    ERR_SCOPE_DATE_OVERLAP = "ERR_SCOPE_DATE_OVERLAP"
    ERR_DUPLICATE_CUSTODIAN_EMAIL = "ERR_DUPLICATE_CUSTODIAN_EMAIL"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_HOLD_HAS_NO_CUSTODIANS = "ERR_HOLD_HAS_NO_CUSTODIANS"
    ERR_VALIDATION_OUT_OF_RANGE = "ERR_VALIDATION_OUT_OF_RANGE"
    ERR_BATCH_NOT_FULLY_REVIEWED = "ERR_BATCH_NOT_FULLY_REVIEWED"
    ERR_EMPTY_BATCH = "ERR_EMPTY_BATCH"
    ERR_EMPTY_PRODUCTION_SET = "ERR_EMPTY_PRODUCTION_SET"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_BATCH_NOT_COMPLETED: 409,
    ApiErrorId.ERR_CUSTODIAN_NOT_ACKNOWLEDGED: 409,
    ApiErrorId.ERR_PRIVILEGED_DOCUMENT: 422,
    ApiErrorId.ERR_DOCUMENT_NOT_UNIQUE: 422,
    ApiErrorId.ERR_SCOPE_DATE_OVERLAP: 409,
    ApiErrorId.ERR_DUPLICATE_CUSTODIAN_EMAIL: 409,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_HOLD_HAS_NO_CUSTODIANS: 409,
    ApiErrorId.ERR_VALIDATION_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_BATCH_NOT_FULLY_REVIEWED: 409,
    ApiErrorId.ERR_EMPTY_BATCH: 409,
    ApiErrorId.ERR_EMPTY_PRODUCTION_SET: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
