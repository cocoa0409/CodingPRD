"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks the
HTTP status code that accompanies each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_DONOR_MISMATCH = "ERR_DONOR_MISMATCH"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_BATCH_RECALLED = "ERR_BATCH_RECALLED"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_FRIDGE_VERSION_CONFLICT = "ERR_FRIDGE_VERSION_CONFLICT"
    ERR_FRIDGE_NOT_OPERATIONAL = "ERR_FRIDGE_NOT_OPERATIONAL"
    ERR_TEMP_UNSAFE = "ERR_TEMP_UNSAFE"
    ERR_ALLERGEN_LABEL_REQUIRED = "ERR_ALLERGEN_LABEL_REQUIRED"
    ERR_USE_BY_PASSED = "ERR_USE_BY_PASSED"
    ERR_STEWARD_SUSPENDED = "ERR_STEWARD_SUSPENDED"
    ERR_STEWARD_NOT_ASSIGNED = "ERR_STEWARD_NOT_ASSIGNED"
    ERR_PICKUP_WINDOW_INVALID = "ERR_PICKUP_WINDOW_INVALID"
    ERR_SHIFT_OVERLAP_FRIDGE = "ERR_SHIFT_OVERLAP_FRIDGE"
    ERR_STEWARD_DOUBLE_BOOKED = "ERR_STEWARD_DOUBLE_BOOKED"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_NO_PORTIONS = "ERR_NO_PORTIONS"
    ERR_BUDGET_EXCEEDED = "ERR_BUDGET_EXCEEDED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_DONOR_MISMATCH: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_BATCH_RECALLED: 409,
    ApiErrorId.ERR_OFFER_EXPIRED: 409,
    ApiErrorId.ERR_FRIDGE_VERSION_CONFLICT: 412,
    ApiErrorId.ERR_FRIDGE_NOT_OPERATIONAL: 409,
    ApiErrorId.ERR_TEMP_UNSAFE: 422,
    ApiErrorId.ERR_ALLERGEN_LABEL_REQUIRED: 422,
    ApiErrorId.ERR_USE_BY_PASSED: 422,
    ApiErrorId.ERR_STEWARD_SUSPENDED: 409,
    ApiErrorId.ERR_STEWARD_NOT_ASSIGNED: 409,
    ApiErrorId.ERR_PICKUP_WINDOW_INVALID: 422,
    ApiErrorId.ERR_SHIFT_OVERLAP_FRIDGE: 409,
    ApiErrorId.ERR_STEWARD_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_NO_PORTIONS: 409,
    ApiErrorId.ERR_BUDGET_EXCEEDED: 402,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
