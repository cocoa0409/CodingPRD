"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_AGREEMENT_OR_SITE_RETIRED = "ERR_AGREEMENT_OR_SITE_RETIRED"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_NO_SUBSTITUTE = "ERR_NO_SUBSTITUTE"
    ERR_ROUTE_WINDOW_OVERLAP = "ERR_ROUTE_WINDOW_OVERLAP"
    ERR_STATION_WINDOW_CONFLICT = "ERR_STATION_WINDOW_CONFLICT"
    ERR_CERTIFICATION_BLOCKED = "ERR_CERTIFICATION_BLOCKED"
    ERR_QUANTITY_OUT_OF_BOUNDS = "ERR_QUANTITY_OUT_OF_BOUNDS"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_ROUTE_EMPTY = "ERR_ROUTE_EMPTY"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_AGREEMENT_OR_SITE_RETIRED: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_NO_SUBSTITUTE: 422,
    ApiErrorId.ERR_ROUTE_WINDOW_OVERLAP: 422,
    ApiErrorId.ERR_STATION_WINDOW_CONFLICT: 422,
    ApiErrorId.ERR_CERTIFICATION_BLOCKED: 422,
    ApiErrorId.ERR_QUANTITY_OUT_OF_BOUNDS: 422,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 422,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_ROUTE_EMPTY: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
