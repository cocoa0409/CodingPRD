"""Error IDs and HTTP status mapping (Online Proctoring PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_REFERENCE_MISMATCH = "ERR_REFERENCE_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EXAM_CLOSED = "ERR_EXAM_CLOSED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_LOCKDOWN_NOT_VERIFIED = "ERR_LOCKDOWN_NOT_VERIFIED"
    ERR_OUTSIDE_TEST_WINDOW = "ERR_OUTSIDE_TEST_WINDOW"
    ERR_PROCTOR_DOUBLE_BOOKED = "ERR_PROCTOR_DOUBLE_BOOKED"
    ERR_CANDIDATE_OVERLAP = "ERR_CANDIDATE_OVERLAP"
    ERR_PROCTOR_OVERLOADED = "ERR_PROCTOR_OVERLOADED"
    ERR_SESSION_IN_PROGRESS = "ERR_SESSION_IN_PROGRESS"
    ERR_NOT_VOIDED = "ERR_NOT_VOIDED"
    ERR_EMPTY_REPORT = "ERR_EMPTY_REPORT"
    ERR_CHECKIN_TOO_EARLY = "ERR_CHECKIN_TOO_EARLY"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_REFERENCE_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EXAM_CLOSED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_LOCKDOWN_NOT_VERIFIED: 409,
    ApiErrorId.ERR_OUTSIDE_TEST_WINDOW: 422,
    ApiErrorId.ERR_PROCTOR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CANDIDATE_OVERLAP: 409,
    ApiErrorId.ERR_PROCTOR_OVERLOADED: 409,
    ApiErrorId.ERR_SESSION_IN_PROGRESS: 409,
    ApiErrorId.ERR_NOT_VOIDED: 409,
    ApiErrorId.ERR_EMPTY_REPORT: 422,
    ApiErrorId.ERR_CHECKIN_TOO_EARLY: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
