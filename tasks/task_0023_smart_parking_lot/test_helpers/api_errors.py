"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # --- Auth / RBAC / existence ---
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_BAD_REQUEST = "ERR_BAD_REQUEST"

    # --- Concurrency / state ---
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # --- Space / Reservation ---
    ERR_SPACE_OCCUPIED = "ERR_SPACE_OCCUPIED"
    ERR_SPACE_NOT_BOOKABLE = "ERR_SPACE_NOT_BOOKABLE"
    ERR_RESERVATION_OVERLAP = "ERR_RESERVATION_OVERLAP"
    ERR_NO_SPACE_AVAILABLE = "ERR_NO_SPACE_AVAILABLE"
    ERR_INVALID_RESERVATION_WINDOW = "ERR_INVALID_RESERVATION_WINDOW"

    # --- Vehicle / Card ---
    ERR_VEHICLE_HAS_OPEN_VIOLATIONS = "ERR_VEHICLE_HAS_OPEN_VIOLATIONS"
    ERR_VEHICLE_ALREADY_BOUND = "ERR_VEHICLE_ALREADY_BOUND"
    ERR_VEHICLE_NOT_BOUND = "ERR_VEHICLE_NOT_BOUND"
    ERR_CARD_BINDING_LIMIT = "ERR_CARD_BINDING_LIMIT"
    ERR_CARD_EXPIRED = "ERR_CARD_EXPIRED"
    ERR_INVALID_CARD_TRANSFER = "ERR_INVALID_CARD_TRANSFER"

    # --- Fiscal / safety / audit ---
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_REFUND_WINDOW_EXPIRED = "ERR_REFUND_WINDOW_EXPIRED"
    ERR_PHOTO_REQUIRED = "ERR_PHOTO_REQUIRED"
    ERR_EXEMPT_VEHICLE = "ERR_EXEMPT_VEHICLE"
    ERR_REASON_REQUIRED = "ERR_REASON_REQUIRED"
    ERR_DUPLICATE_EXTERNAL_REF = "ERR_DUPLICATE_EXTERNAL_REF"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_BAD_REQUEST: 400,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SPACE_OCCUPIED: 409,
    ApiErrorId.ERR_SPACE_NOT_BOOKABLE: 409,
    ApiErrorId.ERR_RESERVATION_OVERLAP: 409,
    ApiErrorId.ERR_NO_SPACE_AVAILABLE: 409,
    ApiErrorId.ERR_INVALID_RESERVATION_WINDOW: 422,
    ApiErrorId.ERR_VEHICLE_HAS_OPEN_VIOLATIONS: 409,
    ApiErrorId.ERR_VEHICLE_ALREADY_BOUND: 409,
    ApiErrorId.ERR_VEHICLE_NOT_BOUND: 409,
    ApiErrorId.ERR_CARD_BINDING_LIMIT: 409,
    ApiErrorId.ERR_CARD_EXPIRED: 409,
    ApiErrorId.ERR_INVALID_CARD_TRANSFER: 422,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 402,
    ApiErrorId.ERR_REFUND_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_PHOTO_REQUIRED: 422,
    ApiErrorId.ERR_EXEMPT_VEHICLE: 422,
    ApiErrorId.ERR_REASON_REQUIRED: 422,
    ApiErrorId.ERR_DUPLICATE_EXTERNAL_REF: 409,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
