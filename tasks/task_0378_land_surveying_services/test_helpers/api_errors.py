"""Error IDs and HTTP status mapping (PRD §5).

Registers the error_id -> HTTP status map with the framework so validate_error()
auto-checks the HTTP status code whenever an error_id is asserted.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_ROLE_MISMATCH = "ERR_ROLE_MISMATCH"
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
    ERR_SEAL_NOT_LICENSED = "ERR_SEAL_NOT_LICENSED"
    ERR_CLOSURE_OUT_OF_TOLERANCE = "ERR_CLOSURE_OUT_OF_TOLERANCE"
    ERR_TITLE_NOT_CLEAR = "ERR_TITLE_NOT_CLEAR"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_INSTRUMENT_UNAVAILABLE = "ERR_INSTRUMENT_UNAVAILABLE"
    ERR_INSTRUMENT_OUT_OF_CALIBRATION = "ERR_INSTRUMENT_OUT_OF_CALIBRATION"
    ERR_DUPLICATE_ASSET_TAG = "ERR_DUPLICATE_ASSET_TAG"
    ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"
    ERR_DUPLICATE_CHILD = "ERR_DUPLICATE_CHILD"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_ROLE_MISMATCH: 422,
    ApiErrorId.ERR_SEGREGATION_VIOLATION: 422,
    ApiErrorId.ERR_SEAL_NOT_LICENSED: 422,
    ApiErrorId.ERR_CLOSURE_OUT_OF_TOLERANCE: 422,
    ApiErrorId.ERR_TITLE_NOT_CLEAR: 422,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_CREW_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_INSTRUMENT_UNAVAILABLE: 409,
    ApiErrorId.ERR_INSTRUMENT_OUT_OF_CALIBRATION: 422,
    ApiErrorId.ERR_DUPLICATE_ASSET_TAG: 409,
    ApiErrorId.ERR_PAYMENT_EXCEEDS_BALANCE: 422,
    ApiErrorId.ERR_DUPLICATE_CHILD: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
