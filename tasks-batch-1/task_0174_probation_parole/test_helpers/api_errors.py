"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can cross-check
the HTTP status automatically from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INCOMPLETE_LSIR_DOMAINS = "ERR_INCOMPLETE_LSIR_DOMAINS"
    ERR_INVALID_OVERRIDE = "ERR_INVALID_OVERRIDE"
    ERR_OFFICER_ROLE_MISMATCH = "ERR_OFFICER_ROLE_MISMATCH"
    ERR_DUPLICATE_KEY = "ERR_DUPLICATE_KEY"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_LEVEL_TOO_LOW_FOR_CONDITION = "ERR_LEVEL_TOO_LOW_FOR_CONDITION"
    ERR_WINDOW_NOT_CLOSED = "ERR_WINDOW_NOT_CLOSED"
    ERR_CHECKIN_WINDOW_OVERLAP = "ERR_CHECKIN_WINDOW_OVERLAP"
    ERR_TRANSFER_ALREADY_OPEN = "ERR_TRANSFER_ALREADY_OPEN"
    ERR_SUPERVISEE_CLOSED = "ERR_SUPERVISEE_CLOSED"
    ERR_NOT_ELIGIBLE_FOR_TERMINATION = "ERR_NOT_ELIGIBLE_FOR_TERMINATION"
    ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"
    ERR_OUTSTANDING_BALANCE = "ERR_OUTSTANDING_BALANCE"
    ERR_TRANSFER_BLOCKED_HIGH_RISK = "ERR_TRANSFER_BLOCKED_HIGH_RISK"
    ERR_STALE_SUPERVISEE_VERSION = "ERR_STALE_SUPERVISEE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INCOMPLETE_LSIR_DOMAINS: 422,
    ApiErrorId.ERR_INVALID_OVERRIDE: 422,
    ApiErrorId.ERR_OFFICER_ROLE_MISMATCH: 422,
    ApiErrorId.ERR_DUPLICATE_KEY: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_LEVEL_TOO_LOW_FOR_CONDITION: 409,
    ApiErrorId.ERR_WINDOW_NOT_CLOSED: 409,
    ApiErrorId.ERR_CHECKIN_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_TRANSFER_ALREADY_OPEN: 409,
    ApiErrorId.ERR_SUPERVISEE_CLOSED: 409,
    ApiErrorId.ERR_NOT_ELIGIBLE_FOR_TERMINATION: 409,
    ApiErrorId.ERR_PAYMENT_EXCEEDS_BALANCE: 422,
    ApiErrorId.ERR_OUTSTANDING_BALANCE: 409,
    ApiErrorId.ERR_TRANSFER_BLOCKED_HIGH_RISK: 409,
    ApiErrorId.ERR_STALE_SUPERVISEE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
