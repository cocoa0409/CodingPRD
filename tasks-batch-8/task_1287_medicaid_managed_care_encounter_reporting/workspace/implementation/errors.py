def missing_context(msg="X-User-ID or X-User-Role header missing/malformed, or role not declared"):
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, msg, 400)


def forbidden(msg="Role not permitted on endpoint"):
    return ApiError(ERR_FORBIDDEN_FOR_ROLE, msg, 403)


def invalid_request(msg="Malformed body, missing required field, or invalid value"):
    return ApiError(ERR_INVALID_REQUEST, msg, 400)


def not_found(msg="Referenced id does not exist"):
    return ApiError(ERR_NOT_FOUND, msg, 404)


def invalid_state(msg="Target resource state does not allow the requested transition"):
    return ApiError(ERR_INVALID_STATE_TRANSITION, msg, 409)


def stale_version(msg="Expected version does not match current version"):
    return ApiError(ERR_STALE_VERSION, msg, 412)
