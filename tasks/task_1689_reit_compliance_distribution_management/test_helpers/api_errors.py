"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_QUARTER_LOCKED = "ERR_QUARTER_LOCKED"
    ERR_CROSS_REIT_REFERENCE = "ERR_CROSS_REIT_REFERENCE"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_QUARTER_OVERLAP = "ERR_QUARTER_OVERLAP"
    ERR_REIT_SUSPENDED = "ERR_REIT_SUSPENDED"
    ERR_FIVE_FIFTY_BLOCKED = "ERR_FIVE_FIFTY_BLOCKED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_REQUIREMENT_NOT_POSTED = "ERR_REQUIREMENT_NOT_POSTED"
    ERR_DECLARATIONS_OPEN = "ERR_DECLARATIONS_OPEN"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SNAPSHOT_EMPTY = "ERR_SNAPSHOT_EMPTY"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_QUARTER_LOCKED: 409,
    ApiErrorId.ERR_CROSS_REIT_REFERENCE: 422,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_QUARTER_OVERLAP: 409,
    ApiErrorId.ERR_REIT_SUSPENDED: 409,
    ApiErrorId.ERR_FIVE_FIFTY_BLOCKED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_REQUIREMENT_NOT_POSTED: 409,
    ApiErrorId.ERR_DECLARATIONS_OPEN: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SNAPSHOT_EMPTY: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status codes.
set_error_http_status_map(HTTP_STATUS_CODES)
