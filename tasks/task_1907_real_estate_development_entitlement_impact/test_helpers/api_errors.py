"""Error IDs and their HTTP status codes (PRD 5 Error Code Catalogue).

Registering the map with the framework lets validate_error() cross-check the
HTTP status automatically for every asserted error.
"""
from enum import Enum
from typing import Dict

from prd_bench_local_runner.testing.validators import set_error_http_status_map


