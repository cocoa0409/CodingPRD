"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_USER_CONTEXT = "ERR_MISSING_USER_CONTEXT"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SELF_APPROVAL = "ERR_SELF_APPROVAL"
    ERR_TRAVELER_SUSPENDED = "ERR_TRAVELER_SUSPENDED"
    ERR_ADVANCE_PURCHASE_VIOLATION = "ERR_ADVANCE_PURCHASE_VIOLATION"
    ERR_TRAVELER_DOUBLE_BOOKED = "ERR_TRAVELER_DOUBLE_BOOKED"
    ERR_RATE_UNAVAILABLE = "ERR_RATE_UNAVAILABLE"
    ERR_CREDIT_UNAVAILABLE = "ERR_CREDIT_UNAVAILABLE"
    ERR_POLICY_VIOLATION = "ERR_POLICY_VIOLATION"
    ERR_VENDOR_CAPACITY_EXCEEDED = "ERR_VENDOR_CAPACITY_EXCEEDED"
    ERR_APPROVAL_REQUIRED = "ERR_APPROVAL_REQUIRED"
    ERR_APPROVAL_RANK_TOO_LOW = "ERR_APPROVAL_RANK_TOO_LOW"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_USER_CONTEXT: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SELF_APPROVAL: 403,
    ApiErrorId.ERR_TRAVELER_SUSPENDED: 409,
    ApiErrorId.ERR_ADVANCE_PURCHASE_VIOLATION: 409,
    ApiErrorId.ERR_TRAVELER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_RATE_UNAVAILABLE: 409,
    ApiErrorId.ERR_CREDIT_UNAVAILABLE: 409,
    ApiErrorId.ERR_POLICY_VIOLATION: 409,
    ApiErrorId.ERR_VENDOR_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_APPROVAL_REQUIRED: 409,
    ApiErrorId.ERR_APPROVAL_RANK_TOO_LOW: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
