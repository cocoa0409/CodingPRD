class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_NOT_RESOURCE_OWNER = ("ERR_NOT_RESOURCE_OWNER", 403)
ERR_VALIDATION = ("ERR_VALIDATION", 422)
ERR_INVALID_DELINQUENCY_DATE = ("ERR_INVALID_DELINQUENCY_DATE", 422)
ERR_STALE_FILE_VERSION = ("ERR_STALE_FILE_VERSION", 412)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_DEADLINE_BREACHED = ("ERR_DEADLINE_BREACHED", 409)
ERR_FILE_FROZEN = ("ERR_FILE_FROZEN", 409)
ERR_FURNISHER_SUSPENDED = ("ERR_FURNISHER_SUSPENDED", 409)
ERR_TRADELINE_NOT_DISPUTABLE = ("ERR_TRADELINE_NOT_DISPUTABLE", 409)
ERR_DUPLICATE_DISPUTE = ("ERR_DUPLICATE_DISPUTE", 409)
ERR_OVERLAPPING_INVESTIGATION = ("ERR_OVERLAPPING_INVESTIGATION", 409)
ERR_REOPEN_LIMIT_REACHED = ("ERR_REOPEN_LIMIT_REACHED", 409)
ERR_MISSING_CORRECTED_BALANCE = ("ERR_MISSING_CORRECTED_BALANCE", 422)
ERR_FREEZE_OVERLAP = ("ERR_FREEZE_OVERLAP", 409)
