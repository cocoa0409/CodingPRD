"""Error IDs and HTTP status mapping for the Shared Office API (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks HTTP status.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_UNKNOWN_ROLE = "ERR_UNKNOWN_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_ENTITY_MISSING = "ERR_REFERENCED_ENTITY_MISSING"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_RESERVATION_CONFLICT = "ERR_RESERVATION_CONFLICT"
    ERR_INVALID_RESERVATION_STATE = "ERR_INVALID_RESERVATION_STATE"
    ERR_INVALID_BILL_STATE = "ERR_INVALID_BILL_STATE"
    ERR_INVALID_LEASE_STATE = "ERR_INVALID_LEASE_STATE"
    ERR_INVALID_VISITOR_STATE = "ERR_INVALID_VISITOR_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_ACCESS_POSTURE_DENIES = "ERR_ACCESS_POSTURE_DENIES"
    ERR_TENANT_MISMATCH = "ERR_TENANT_MISMATCH"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"
    ERR_RESERVATION_GRANULARITY = "ERR_RESERVATION_GRANULARITY"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_HAS_OPEN_RESERVATIONS = "ERR_HAS_OPEN_RESERVATIONS"
    ERR_HAS_DRAFT_BILLS = "ERR_HAS_DRAFT_BILLS"
    ERR_EMPTY_BILL = "ERR_EMPTY_BILL"
    ERR_BILL_HAS_OPEN_RESERVATIONS = "ERR_BILL_HAS_OPEN_RESERVATIONS"
    ERR_INVALID_VISITOR_WINDOW = "ERR_INVALID_VISITOR_WINDOW"
    ERR_PAGINATION_OUT_OF_RANGE = "ERR_PAGINATION_OUT_OF_RANGE"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_UNKNOWN_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_ENTITY_MISSING: 404,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_RESERVATION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_RESERVATION_STATE: 409,
    ApiErrorId.ERR_INVALID_BILL_STATE: 409,
    ApiErrorId.ERR_INVALID_LEASE_STATE: 409,
    ApiErrorId.ERR_INVALID_VISITOR_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 422,
    ApiErrorId.ERR_ACCESS_POSTURE_DENIES: 422,
    ApiErrorId.ERR_TENANT_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_TIME_WINDOW: 422,
    ApiErrorId.ERR_RESERVATION_GRANULARITY: 422,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_HAS_OPEN_RESERVATIONS: 422,
    ApiErrorId.ERR_HAS_DRAFT_BILLS: 422,
    ApiErrorId.ERR_EMPTY_BILL: 422,
    ApiErrorId.ERR_BILL_HAS_OPEN_RESERVATIONS: 422,
    ApiErrorId.ERR_INVALID_VISITOR_WINDOW: 422,
    ApiErrorId.ERR_PAGINATION_OUT_OF_RANGE: 400,
}


# Register with framework so validate_error() auto-checks HTTP status from this map.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
