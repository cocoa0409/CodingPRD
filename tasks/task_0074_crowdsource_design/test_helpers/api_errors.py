"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # ---- auth / authz (PRD §2.1, §5) ----
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    # ---- existence (PRD §2.7, §5) ----
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    # ---- state / concurrency (PRD §2.5, §5) ----
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    # ---- business safety / temporal / constraint / fiscal (PRD §5) ----
    ERR_ORIGINAL_DECLARATION_REQUIRED = "ERR_ORIGINAL_DECLARATION_REQUIRED"
    ERR_REVIEWER_CONFLICT_OF_INTEREST = "ERR_REVIEWER_CONFLICT_OF_INTEREST"
    ERR_REVIEWER_NOT_QUALIFIED = "ERR_REVIEWER_NOT_QUALIFIED"
    ERR_REVIEWER_CAPACITY_EXCEEDED = "ERR_REVIEWER_CAPACITY_EXCEEDED"
    ERR_MODIFY_WINDOW_CLOSED = "ERR_MODIFY_WINDOW_CLOSED"
    ERR_REVIEW_WINDOW_CLOSED = "ERR_REVIEW_WINDOW_CLOSED"
    ERR_TIMELINE_TOO_TIGHT = "ERR_TIMELINE_TOO_TIGHT"
    ERR_STAGE_OVERLAP = "ERR_STAGE_OVERLAP"
    ERR_SUBMISSION_LIMIT_REACHED = "ERR_SUBMISSION_LIMIT_REACHED"
    ERR_RUBRIC_WEIGHTS_INVALID = "ERR_RUBRIC_WEIGHTS_INVALID"
    ERR_CRITERION_SCORES_INVALID = "ERR_CRITERION_SCORES_INVALID"
    ERR_TRANSFER_SCOPE_INVALID = "ERR_TRANSFER_SCOPE_INVALID"
    ERR_SIGNATURE_OUT_OF_ORDER = "ERR_SIGNATURE_OUT_OF_ORDER"
    ERR_COPYRIGHT_NOT_REGISTERED = "ERR_COPYRIGHT_NOT_REGISTERED"
    ERR_PRIZE_POOL_MISMATCH = "ERR_PRIZE_POOL_MISMATCH"
    ERR_PRIZE_AMOUNT_INVALID = "ERR_PRIZE_AMOUNT_INVALID"
    ERR_QUORUM_NOT_MET = "ERR_QUORUM_NOT_MET"
    ERR_DISPUTE_WINDOW_CLOSED = "ERR_DISPUTE_WINDOW_CLOSED"
    ERR_DISPUTE_PENDING = "ERR_DISPUTE_PENDING"
    ERR_REVIEWER_ALREADY_ASSIGNED = "ERR_REVIEWER_ALREADY_ASSIGNED"
    ERR_STAGE_ALREADY_PUBLISHED = "ERR_STAGE_ALREADY_PUBLISHED"
    ERR_DUPLICATE_IDEMPOTENCY_KEY = "ERR_DUPLICATE_IDEMPOTENCY_KEY"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_SIGNATURE_OUT_OF_ORDER: 409,
    ApiErrorId.ERR_DISPUTE_PENDING: 409,
    ApiErrorId.ERR_REVIEWER_ALREADY_ASSIGNED: 409,
    ApiErrorId.ERR_STAGE_ALREADY_PUBLISHED: 409,
    ApiErrorId.ERR_DUPLICATE_IDEMPOTENCY_KEY: 409,
    ApiErrorId.ERR_ORIGINAL_DECLARATION_REQUIRED: 422,
    ApiErrorId.ERR_REVIEWER_CONFLICT_OF_INTEREST: 422,
    ApiErrorId.ERR_REVIEWER_NOT_QUALIFIED: 422,
    ApiErrorId.ERR_REVIEWER_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_MODIFY_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_REVIEW_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_TIMELINE_TOO_TIGHT: 422,
    ApiErrorId.ERR_STAGE_OVERLAP: 422,
    ApiErrorId.ERR_SUBMISSION_LIMIT_REACHED: 422,
    ApiErrorId.ERR_RUBRIC_WEIGHTS_INVALID: 422,
    ApiErrorId.ERR_CRITERION_SCORES_INVALID: 422,
    ApiErrorId.ERR_TRANSFER_SCOPE_INVALID: 422,
    ApiErrorId.ERR_COPYRIGHT_NOT_REGISTERED: 422,
    ApiErrorId.ERR_PRIZE_POOL_MISMATCH: 422,
    ApiErrorId.ERR_PRIZE_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_QUORUM_NOT_MET: 422,
    ApiErrorId.ERR_DISPUTE_WINDOW_CLOSED: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
