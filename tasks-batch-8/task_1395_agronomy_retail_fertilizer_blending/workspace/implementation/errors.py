def unauthenticated(msg="Missing/malformed X-User-ID or X-User-Role, or unrecognized role"):
    return ApiError(ERR_UNAUTHENTICATED, msg, 401)


def forbidden(msg="Role not permitted for this operation"):
    return ApiError(ERR_FORBIDDEN_ROLE, msg, 403)


def validation(msg="Request validation failed"):
    return ApiError(ERR_VALIDATION_FAILED, msg, 400)


def not_found(msg="Resource not found"):
    return ApiError(ERR_RESOURCE_NOT_FOUND, msg, 404)


def stale(msg="Stale version"):
    return ApiError(ERR_STALE_VERSION, msg, 412)


def invalid_transition(msg="Invalid state transition"):
    return ApiError(ERR_INVALID_TRANSITION, msg, 409)


def business(error_id: str, http_status: int, msg: str):
    return ApiError(error_id, msg, http_status)
