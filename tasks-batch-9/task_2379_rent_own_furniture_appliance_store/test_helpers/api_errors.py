def expected_status_for(error_id: str) -> int:
    """Return the documented HTTP status for one error identifier."""
    try:
        return ERROR_HTTP_STATUS[error_id]
    except KeyError:  # pragma: no cover - guards typos in test code
        raise AssertionError(f"{error_id} is not a documented error identifier")
