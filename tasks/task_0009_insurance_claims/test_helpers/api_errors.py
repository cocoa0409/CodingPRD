"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Authentication & Authorization
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Resource Not Found
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Validation
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"

    # Concurrency / Idempotency
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_DUPLICATE_CLAIM_INTAKE = "ERR_DUPLICATE_CLAIM_INTAKE"
    ERR_APPEAL_ALREADY_EXISTS = "ERR_APPEAL_ALREADY_EXISTS"
    ERR_PAYOUT_ALREADY_EXISTS = "ERR_PAYOUT_ALREADY_EXISTS"
    ERR_INVESTIGATION_ALREADY_OPEN = "ERR_INVESTIGATION_ALREADY_OPEN"

    # Business / domain
    ERR_POLICY_INACTIVE = "ERR_POLICY_INACTIVE"
    ERR_LOSS_OUTSIDE_POLICY_PERIOD = "ERR_LOSS_OUTSIDE_POLICY_PERIOD"
    ERR_REPORTING_WINDOW_EXCEEDED = "ERR_REPORTING_WINDOW_EXCEEDED"
    ERR_ADJUSTER_SPECIALTY_MISMATCH = "ERR_ADJUSTER_SPECIALTY_MISMATCH"
    ERR_REPAIR_SHOP_BLACKLISTED = "ERR_REPAIR_SHOP_BLACKLISTED"
    ERR_PHOTOS_REQUIRED = "ERR_PHOTOS_REQUIRED"
    ERR_ESTIMATE_REQUIRED = "ERR_ESTIMATE_REQUIRED"
    ERR_DOCUMENT_AUTHENTICITY_FAILED = "ERR_DOCUMENT_AUTHENTICITY_FAILED"
    ERR_FRAUD_HOLD = "ERR_FRAUD_HOLD"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_COVERAGE_LIMIT_EXCEEDED = "ERR_COVERAGE_LIMIT_EXCEEDED"
    ERR_NEGATIVE_NET_PAYOUT = "ERR_NEGATIVE_NET_PAYOUT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,

    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_CLAIM_INTAKE: 409,
    ApiErrorId.ERR_APPEAL_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_PAYOUT_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_INVESTIGATION_ALREADY_OPEN: 409,

    ApiErrorId.ERR_VALIDATION_FAILED: 400,
    ApiErrorId.ERR_INVALID_PAGINATION: 400,

    ApiErrorId.ERR_POLICY_INACTIVE: 422,
    ApiErrorId.ERR_LOSS_OUTSIDE_POLICY_PERIOD: 422,
    ApiErrorId.ERR_REPORTING_WINDOW_EXCEEDED: 422,
    ApiErrorId.ERR_ADJUSTER_SPECIALTY_MISMATCH: 422,
    ApiErrorId.ERR_REPAIR_SHOP_BLACKLISTED: 422,
    ApiErrorId.ERR_PHOTOS_REQUIRED: 422,
    ApiErrorId.ERR_ESTIMATE_REQUIRED: 422,
    ApiErrorId.ERR_DOCUMENT_AUTHENTICITY_FAILED: 422,
    ApiErrorId.ERR_FRAUD_HOLD: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 422,
    ApiErrorId.ERR_COVERAGE_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_NEGATIVE_NET_PAYOUT: 422,
}


# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
