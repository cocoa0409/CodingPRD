"""Error catalogue and the ApiError exception (PRD section 5)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or DEFAULT_MESSAGES.get(error_id) or _humanise(error_id)


def _humanise(error_id):
    """Turn ERR_PATIENT_NOT_FOUND into 'Patient not found.' for readability."""
    words = error_id.split("_")
    if words and words[0] == "ERR":
        words = words[1:]
    if not words:
        return error_id
    text = " ".join(words).lower()
    return text[:1].upper() + text[1:] + "."


