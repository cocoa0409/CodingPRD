"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_BOOKING_RELEASED = "ERR_BOOKING_RELEASED"
    ERR_BOOKING_NOT_CLASSIFIED = "ERR_BOOKING_NOT_CLASSIFIED"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VISITOR_NOT_APPROVED = "ERR_VISITOR_NOT_APPROVED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_SECURITY_LEVEL_MISMATCH = "ERR_SECURITY_LEVEL_MISMATCH"
    ERR_GENDER_MISMATCH = "ERR_GENDER_MISMATCH"
    ERR_BED_DOUBLE_BOOKED = "ERR_BED_DOUBLE_BOOKED"
    ERR_VISIT_OVERLAP = "ERR_VISIT_OVERLAP"
    ERR_HOUSING_UNIT_FULL = "ERR_HOUSING_UNIT_FULL"
    ERR_INSUFFICIENT_FUNDS = "ERR_INSUFFICIENT_FUNDS"
    ERR_NOT_RELEASE_ELIGIBLE = "ERR_NOT_RELEASE_ELIGIBLE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_BOOKING_RELEASED: 409,
    ApiErrorId.ERR_BOOKING_NOT_CLASSIFIED: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VISITOR_NOT_APPROVED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_SECURITY_LEVEL_MISMATCH: 409,
    ApiErrorId.ERR_GENDER_MISMATCH: 409,
    ApiErrorId.ERR_BED_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_VISIT_OVERLAP: 409,
    ApiErrorId.ERR_HOUSING_UNIT_FULL: 409,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS: 402,
    ApiErrorId.ERR_NOT_RELEASE_ELIGIBLE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
