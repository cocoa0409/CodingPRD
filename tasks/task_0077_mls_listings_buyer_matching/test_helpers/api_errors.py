"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_LISTING_AGENT = "ERR_NOT_LISTING_AGENT"
    ERR_NOT_BUYER_AGENT = "ERR_NOT_BUYER_AGENT"
    ERR_DUAL_AGENCY_FORBIDDEN = "ERR_DUAL_AGENCY_FORBIDDEN"
    ERR_AGENT_SUSPENDED = "ERR_AGENT_SUSPENDED"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NOT_YOUR_TURN = "ERR_NOT_YOUR_TURN"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_OVER_BUDGET = "ERR_OVER_BUDGET"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_NO_LOCKBOX = "ERR_NO_LOCKBOX"
    ERR_LOCKBOX_DISABLED = "ERR_LOCKBOX_DISABLED"
    ERR_LOCKBOX_HAS_SHOWINGS = "ERR_LOCKBOX_HAS_SHOWINGS"
    ERR_SHOWING_CONFLICT = "ERR_SHOWING_CONFLICT"
    ERR_BAD_TIME_WINDOW = "ERR_BAD_TIME_WINDOW"
    ERR_SHOWING_NOT_OVER = "ERR_SHOWING_NOT_OVER"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_LISTING_AGENT: 403,
    ApiErrorId.ERR_NOT_BUYER_AGENT: 403,
    ApiErrorId.ERR_DUAL_AGENCY_FORBIDDEN: 422,
    ApiErrorId.ERR_AGENT_SUSPENDED: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NOT_YOUR_TURN: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_OVER_BUDGET: 422,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_NO_LOCKBOX: 409,
    ApiErrorId.ERR_LOCKBOX_DISABLED: 409,
    ApiErrorId.ERR_LOCKBOX_HAS_SHOWINGS: 409,
    ApiErrorId.ERR_SHOWING_CONFLICT: 409,
    ApiErrorId.ERR_BAD_TIME_WINDOW: 422,
    ApiErrorId.ERR_SHOWING_NOT_OVER: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
