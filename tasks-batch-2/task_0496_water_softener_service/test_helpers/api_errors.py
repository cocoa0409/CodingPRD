"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CAPACITY_MISMATCH = "ERR_CAPACITY_MISMATCH"
    ERR_ZONE_MISMATCH = "ERR_ZONE_MISMATCH"
    ERR_INSUFFICIENT_SALT = "ERR_INSUFFICIENT_SALT"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_SERVICE_GAP_VIOLATION = "ERR_SERVICE_GAP_VIOLATION"
    ERR_ROUTE_FULL = "ERR_ROUTE_FULL"
    ERR_RENTAL_NOT_ALLOWED = "ERR_RENTAL_NOT_ALLOWED"
    ERR_SUPERSEDE_NOT_VOID = "ERR_SUPERSEDE_NOT_VOID"
    ERR_INVOICE_CLOSED = "ERR_INVOICE_CLOSED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CAPACITY_MISMATCH: 422,
    ApiErrorId.ERR_ZONE_MISMATCH: 422,
    ApiErrorId.ERR_INSUFFICIENT_SALT: 422,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_SERVICE_GAP_VIOLATION: 409,
    ApiErrorId.ERR_ROUTE_FULL: 409,
    ApiErrorId.ERR_RENTAL_NOT_ALLOWED: 422,
    ApiErrorId.ERR_SUPERSEDE_NOT_VOID: 422,
    ApiErrorId.ERR_INVOICE_CLOSED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
