"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can cross-check
the HTTP status of every error response automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_REFERENCED_RESOURCE_NOT_FOUND = "ERR_REFERENCED_RESOURCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_CONTRACT_VERSION = "ERR_STALE_CONTRACT_VERSION"
    ERR_STALE_EXCHANGE_VERSION = "ERR_STALE_EXCHANGE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CONTRACT_FROZEN = "ERR_CONTRACT_FROZEN"
    ERR_CREDITING_KIND_MISMATCH = "ERR_CREDITING_KIND_MISMATCH"
    ERR_ALLOCATION_INCOMPLETE = "ERR_ALLOCATION_INCOMPLETE"
    ERR_BENEFICIARY_SHARES_INCOMPLETE = "ERR_BENEFICIARY_SHARES_INCOMPLETE"
    ERR_FUTURE_DATE_OF_DEATH = "ERR_FUTURE_DATE_OF_DEATH"
    ERR_PAYOUT_OPTION_ARITY = "ERR_PAYOUT_OPTION_ARITY"
    ERR_BELOW_MINIMUM_PREMIUM = "ERR_BELOW_MINIMUM_PREMIUM"
    ERR_INSUFFICIENT_ACCUMULATION = "ERR_INSUFFICIENT_ACCUMULATION"
    ERR_INVALID_COST_BASIS = "ERR_INVALID_COST_BASIS"
    ERR_SEGMENT_TERM_OVERLAP = "ERR_SEGMENT_TERM_OVERLAP"
    ERR_CREDIT_PERIOD_OVERLAP = "ERR_CREDIT_PERIOD_OVERLAP"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_CONTRACT_VERSION: 412,
    ApiErrorId.ERR_STALE_EXCHANGE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_CONTRACT_FROZEN: 409,
    ApiErrorId.ERR_CREDITING_KIND_MISMATCH: 422,
    ApiErrorId.ERR_ALLOCATION_INCOMPLETE: 409,
    ApiErrorId.ERR_BENEFICIARY_SHARES_INCOMPLETE: 409,
    ApiErrorId.ERR_FUTURE_DATE_OF_DEATH: 422,
    ApiErrorId.ERR_PAYOUT_OPTION_ARITY: 422,
    ApiErrorId.ERR_BELOW_MINIMUM_PREMIUM: 422,
    ApiErrorId.ERR_INSUFFICIENT_ACCUMULATION: 409,
    ApiErrorId.ERR_INVALID_COST_BASIS: 422,
    ApiErrorId.ERR_SEGMENT_TERM_OVERLAP: 409,
    ApiErrorId.ERR_CREDIT_PERIOD_OVERLAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
