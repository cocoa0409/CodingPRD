# Rank-Seat compatibility (PRD §3.2)
def rank_seat_compatible(rank: str, seat: str) -> bool:
    if rank == "CAPTAIN":
        return seat == "CAPTAIN"
    if rank == "FIRST_OFFICER":
        return seat == "FIRST_OFFICER"
    if rank in {"PURSER", "FLIGHT_ATTENDANT"}:
        return seat in {"PURSER", "FLIGHT_ATTENDANT"}
    return False
