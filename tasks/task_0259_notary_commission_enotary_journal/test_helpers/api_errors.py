"""Error IDs and HTTP status mapping (PRD 5).

Registering the map with the framework lets validate_error() auto-check the
HTTP status from the error_id, so tests need only name the expected error.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    # existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # request well-formedness
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION = "ERR_VALIDATION"
    # state
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # OCC
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # domain business rules
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
    ERR_ENOTARY_NOT_AUTHORIZED = "ERR_ENOTARY_NOT_AUTHORIZED"
    ERR_NO_SIGNER = "ERR_NO_SIGNER"
    ERR_NO_DOCUMENT = "ERR_NO_DOCUMENT"
    ERR_NO_NOTARIZED_DOCUMENT = "ERR_NO_NOTARIZED_DOCUMENT"
    ERR_CREDENTIAL_NOT_VERIFIED = "ERR_CREDENTIAL_NOT_VERIFIED"
    ERR_CREDENTIAL_ALREADY_VERIFIED = "ERR_CREDENTIAL_ALREADY_VERIFIED"
    ERR_SIGNER_NOT_VERIFIED = "ERR_SIGNER_NOT_VERIFIED"
    ERR_BOND_BELOW_MINIMUM = "ERR_BOND_BELOW_MINIMUM"
    ERR_BOND_NOT_ACTIVE = "ERR_BOND_NOT_ACTIVE"
    ERR_FEE_EXCEEDS_CAP = "ERR_FEE_EXCEEDS_CAP"
    ERR_RENEWAL_OUT_OF_GRACE = "ERR_RENEWAL_OUT_OF_GRACE"
    ERR_RISK_THRESHOLD_BLOCK = "ERR_RISK_THRESHOLD_BLOCK"
    ERR_NO_CLAIM_AMOUNT = "ERR_NO_CLAIM_AMOUNT"
    ERR_ENTRY_NOT_POSTED = "ERR_ENTRY_NOT_POSTED"
    ERR_SESSION_TIME_CONFLICT = "ERR_SESSION_TIME_CONFLICT"
    ERR_BOND_COVERAGE_OVERLAP = "ERR_BOND_COVERAGE_OVERLAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_VIOLATION: 403,
    ApiErrorId.ERR_ENOTARY_NOT_AUTHORIZED: 409,
    ApiErrorId.ERR_NO_SIGNER: 409,
    ApiErrorId.ERR_NO_DOCUMENT: 409,
    ApiErrorId.ERR_NO_NOTARIZED_DOCUMENT: 409,
    ApiErrorId.ERR_CREDENTIAL_NOT_VERIFIED: 409,
    ApiErrorId.ERR_CREDENTIAL_ALREADY_VERIFIED: 409,
    ApiErrorId.ERR_SIGNER_NOT_VERIFIED: 409,
    ApiErrorId.ERR_BOND_BELOW_MINIMUM: 409,
    ApiErrorId.ERR_BOND_NOT_ACTIVE: 409,
    ApiErrorId.ERR_FEE_EXCEEDS_CAP: 409,
    ApiErrorId.ERR_RENEWAL_OUT_OF_GRACE: 409,
    ApiErrorId.ERR_RISK_THRESHOLD_BLOCK: 409,
    ApiErrorId.ERR_NO_CLAIM_AMOUNT: 409,
    ApiErrorId.ERR_ENTRY_NOT_POSTED: 409,
    ApiErrorId.ERR_SESSION_TIME_CONFLICT: 409,
    ApiErrorId.ERR_BOND_COVERAGE_OVERLAP: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
