"""Error IDs and HTTP status mapping (PRD §5). After defining the mapping it
is registered with the framework so validate_error() can cross-check the HTTP
status of each error automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_TARIFF_SHAPE = "ERR_INVALID_TARIFF_SHAPE"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_TARIFF_NOT_ACTIVE = "ERR_TARIFF_NOT_ACTIVE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ORDER_ACCOUNT_MISMATCH = "ERR_ORDER_ACCOUNT_MISMATCH"
    ERR_ASSISTANCE_SHIELD = "ERR_ASSISTANCE_SHIELD"
    ERR_NOT_IN_ARREARS = "ERR_NOT_IN_ARREARS"
    ERR_ARREARS_NOT_CLEARED = "ERR_ARREARS_NOT_CLEARED"
    ERR_BUDGET_PLAN_EXISTS = "ERR_BUDGET_PLAN_EXISTS"
    ERR_BILL_PERIOD_OVERLAP = "ERR_BILL_PERIOD_OVERLAP"
    ERR_READ_OVERLAP = "ERR_READ_OVERLAP"
    ERR_STALE_ACCOUNT_VERSION = "ERR_STALE_ACCOUNT_VERSION"
    ERR_INVALID_PAYMENT = "ERR_INVALID_PAYMENT"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_TARIFF_SHAPE: 422,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_TARIFF_NOT_ACTIVE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ORDER_ACCOUNT_MISMATCH: 409,
    ApiErrorId.ERR_ASSISTANCE_SHIELD: 409,
    ApiErrorId.ERR_NOT_IN_ARREARS: 409,
    ApiErrorId.ERR_ARREARS_NOT_CLEARED: 409,
    ApiErrorId.ERR_BUDGET_PLAN_EXISTS: 409,
    ApiErrorId.ERR_BILL_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_READ_OVERLAP: 409,
    ApiErrorId.ERR_STALE_ACCOUNT_VERSION: 412,
    ApiErrorId.ERR_INVALID_PAYMENT: 409,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
