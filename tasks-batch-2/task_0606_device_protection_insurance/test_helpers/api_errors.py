"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ENROLLMENT_NOT_ACTIVE = "ERR_ENROLLMENT_NOT_ACTIVE"
    ERR_INVALID_IMEI = "ERR_INVALID_IMEI"
    ERR_DUPLICATE_IMEI = "ERR_DUPLICATE_IMEI"
    ERR_INCIDENT_OUT_OF_WINDOW = "ERR_INCIDENT_OUT_OF_WINDOW"
    ERR_POLICE_REPORT_REQUIRED = "ERR_POLICE_REPORT_REQUIRED"
    ERR_OPEN_CLAIM_EXISTS = "ERR_OPEN_CLAIM_EXISTS"
    ERR_FRAUD_BLOCKED = "ERR_FRAUD_BLOCKED"
    ERR_CLAIM_LIMIT_EXCEEDED = "ERR_CLAIM_LIMIT_EXCEEDED"
    ERR_NO_STOCK = "ERR_NO_STOCK"
    ERR_STALE_ENROLLMENT_VERSION = "ERR_STALE_ENROLLMENT_VERSION"
    ERR_STALE_CLAIM_VERSION = "ERR_STALE_CLAIM_VERSION"
    ERR_ROUTE_INPUT_MISSING = "ERR_ROUTE_INPUT_MISSING"
    ERR_GRADE_PATH_MISMATCH = "ERR_GRADE_PATH_MISMATCH"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ENROLLMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_INVALID_IMEI: 422,
    ApiErrorId.ERR_DUPLICATE_IMEI: 409,
    ApiErrorId.ERR_INCIDENT_OUT_OF_WINDOW: 422,
    ApiErrorId.ERR_POLICE_REPORT_REQUIRED: 422,
    ApiErrorId.ERR_OPEN_CLAIM_EXISTS: 409,
    ApiErrorId.ERR_FRAUD_BLOCKED: 409,
    ApiErrorId.ERR_CLAIM_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_NO_STOCK: 409,
    ApiErrorId.ERR_STALE_ENROLLMENT_VERSION: 412,
    ApiErrorId.ERR_STALE_CLAIM_VERSION: 412,
    ApiErrorId.ERR_ROUTE_INPUT_MISSING: 422,
    ApiErrorId.ERR_GRADE_PATH_MISMATCH: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
