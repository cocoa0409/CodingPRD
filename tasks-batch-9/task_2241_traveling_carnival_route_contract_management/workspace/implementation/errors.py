def fail(error_id, message=None):
    """Raise the catalogued error with its catalogued HTTP status."""
    raise ApiError(error_id, HTTP_STATUS[error_id], message)


def invalid(message="Request body is invalid."):
    fail(ERR_INVALID_REQUEST, message)
