"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can auto-check
the HTTP status code for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ACCOUNT_VERSION = "ERR_STALE_ACCOUNT_VERSION"
    ERR_CROSS_ACCOUNT_REFERENCE = "ERR_CROSS_ACCOUNT_REFERENCE"
    ERR_RATING_BLOCKED = "ERR_RATING_BLOCKED"
    ERR_CURFEW_BLOCKED = "ERR_CURFEW_BLOCKED"
    ERR_DAILY_LIMIT_EXCEEDED = "ERR_DAILY_LIMIT_EXCEEDED"
    ERR_DEVICE_BUSY = "ERR_DEVICE_BUSY"
    ERR_HD_NOT_ALLOWED = "ERR_HD_NOT_ALLOWED"
    ERR_TITLE_NOT_DOWNLOADABLE = "ERR_TITLE_NOT_DOWNLOADABLE"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_CONCURRENT_CAP_REACHED = "ERR_CONCURRENT_CAP_REACHED"
    ERR_DOWNLOAD_QUOTA_REACHED = "ERR_DOWNLOAD_QUOTA_REACHED"
    ERR_PROFILE_CAP_REACHED = "ERR_PROFILE_CAP_REACHED"
    ERR_DEVICE_CAP_REACHED = "ERR_DEVICE_CAP_REACHED"
    ERR_INSUFFICIENT_CREDIT = "ERR_INSUFFICIENT_CREDIT"
    ERR_INVITE_EXPIRED = "ERR_INVITE_EXPIRED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ACCOUNT_VERSION: 412,
    ApiErrorId.ERR_CROSS_ACCOUNT_REFERENCE: 409,
    ApiErrorId.ERR_RATING_BLOCKED: 403,
    ApiErrorId.ERR_CURFEW_BLOCKED: 409,
    ApiErrorId.ERR_DAILY_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_DEVICE_BUSY: 409,
    ApiErrorId.ERR_HD_NOT_ALLOWED: 409,
    ApiErrorId.ERR_TITLE_NOT_DOWNLOADABLE: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_CONCURRENT_CAP_REACHED: 409,
    ApiErrorId.ERR_DOWNLOAD_QUOTA_REACHED: 409,
    ApiErrorId.ERR_PROFILE_CAP_REACHED: 409,
    ApiErrorId.ERR_DEVICE_CAP_REACHED: 409,
    ApiErrorId.ERR_INSUFFICIENT_CREDIT: 402,
    ApiErrorId.ERR_INVITE_EXPIRED: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
