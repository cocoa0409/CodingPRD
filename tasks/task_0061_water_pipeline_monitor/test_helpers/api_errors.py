"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    ERR_BAD_REQUEST = "ERR_BAD_REQUEST"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_DMA_FROZEN = "ERR_DMA_FROZEN"
    ERR_REVIEW_IN_PROGRESS = "ERR_REVIEW_IN_PROGRESS"
    ERR_TOPOLOGY_ROLLBACK_BLOCKED = "ERR_TOPOLOGY_ROLLBACK_BLOCKED"
    ERR_DEVICE_UNMOUNTED = "ERR_DEVICE_UNMOUNTED"
    ERR_INVESTIGATION_NO_SIGNAL = "ERR_INVESTIGATION_NO_SIGNAL"
    ERR_DUPLICATE_READING = "ERR_DUPLICATE_READING"
    ERR_TOPOLOGY_DANGLING_REFERENCE = "ERR_TOPOLOGY_DANGLING_REFERENCE"
    ERR_READING_TIMESTAMP_OUT_OF_RANGE = "ERR_READING_TIMESTAMP_OUT_OF_RANGE"
    ERR_READING_OUT_OF_RANGE = "ERR_READING_OUT_OF_RANGE"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_INSUFFICIENT_DATA = "ERR_INSUFFICIENT_DATA"
    ERR_DEVICE_CONFIG_INVALID = "ERR_DEVICE_CONFIG_INVALID"
    ERR_WORK_ORDER_SEGMENT_MISSING = "ERR_WORK_ORDER_SEGMENT_MISSING"


# HTTP status codes per PRD §5 (Error Code Catalogue).
# ERR_DUPLICATE_READING is intentionally HTTP 200 — PRD §3.4: "the response
# carries HTTP 200 (not 201, because no new resource was created), and the
# response surfaces ERR_DUPLICATE_READING as the idempotency-replay signal."
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_BAD_REQUEST: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DMA_FROZEN: 409,
    ApiErrorId.ERR_REVIEW_IN_PROGRESS: 409,
    ApiErrorId.ERR_TOPOLOGY_ROLLBACK_BLOCKED: 409,
    ApiErrorId.ERR_DEVICE_UNMOUNTED: 409,
    ApiErrorId.ERR_INVESTIGATION_NO_SIGNAL: 409,
    ApiErrorId.ERR_DUPLICATE_READING: 200,
    ApiErrorId.ERR_TOPOLOGY_DANGLING_REFERENCE: 422,
    ApiErrorId.ERR_READING_TIMESTAMP_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_READING_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_INSUFFICIENT_DATA: 422,
    ApiErrorId.ERR_DEVICE_CONFIG_INVALID: 422,
    ApiErrorId.ERR_WORK_ORDER_SEGMENT_MISSING: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
