"""Error catalogue (PRD §5). Each ApiError carries error_id, message, http_status."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Auth / existence / request
ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = ("ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER", 400)
ERR_FORBIDDEN_FOR_ROLE = ("ERR_FORBIDDEN_FOR_ROLE", 403)
ERR_NOT_RESOURCE_OWNER = ("ERR_NOT_RESOURCE_OWNER", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)

# Concurrency
ERR_STALE_BATCH_VERSION = ("ERR_STALE_BATCH_VERSION", 412)

# State
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)

# Program
ERR_PROGRAM_NOT_ACTIVE = ("ERR_PROGRAM_NOT_ACTIVE", 409)
ERR_OPEN_BATCH_EXISTS = ("ERR_OPEN_BATCH_EXISTS", 409)

# Charity
ERR_CHARITY_NOT_ELIGIBLE = ("ERR_CHARITY_NOT_ELIGIBLE", 409)
ERR_MAX_REVIEW_ROUNDS = ("ERR_MAX_REVIEW_ROUNDS", 409)
ERR_CHARITY_NOT_APPROVED = ("ERR_CHARITY_NOT_APPROVED", 409)
ERR_DUPLICATE_EIN = ("ERR_DUPLICATE_EIN", 409)

# Campaign / window
