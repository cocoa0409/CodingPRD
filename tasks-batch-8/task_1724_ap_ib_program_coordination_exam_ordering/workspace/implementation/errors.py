"""Error taxonomy with exact IDs and HTTP statuses from the scaffold error catalog."""


class ApiError(Exception):
    def __init__(self, error_id: str, http_status: int, message: str = ""):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# auth / routing
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_REFERENCE_NOT_FOUND = ("ERR_REFERENCE_NOT_FOUND", 422)
# state / concurrency
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_IRREGULARITY_OPEN = ("ERR_IRREGULARITY_OPEN", 409)
# safety gates
ERR_PROCTOR_SUBJECT_CONFLICT = ("ERR_PROCTOR_SUBJECT_CONFLICT", 422)
ERR_ROOM_NOT_ACCOMMODATION_CAPABLE = ("ERR_ROOM_NOT_ACCOMMODATION_CAPABLE", 422)
ERR_TEACHER_NOT_AUTHORIZED = ("ERR_TEACHER_NOT_AUTHORIZED", 422)
# temporal gates
ERR_OUTSIDE_EXAM_WINDOW = ("ERR_OUTSIDE_EXAM_WINDOW", 422)
ERR_ROOM_CONFLICT = ("ERR_ROOM_CONFLICT", 409)
ERR_PROCTOR_OVERLAP = ("ERR_PROCTOR_OVERLAP", 409)
ERR_SESSION_NOT_ENDED = ("ERR_SESSION_NOT_ENDED", 422)
ERR_SCORES_NOT_YET_AVAILABLE = ("ERR_SCORES_NOT_YET_AVAILABLE", 422)
# uniqueness / quota
ERR_DUPLICATE_REGISTRATION = ("ERR_DUPLICATE_REGISTRATION", 409)
ERR_DUPLICATE_AUTHORIZATION = ("ERR_DUPLICATE_AUTHORIZATION", 409)
ERR_DUPLICATE_APPLICATION = ("ERR_DUPLICATE_APPLICATION", 409)
ERR_DUPLICATE_PROCTOR = ("ERR_DUPLICATE_PROCTOR", 409)
ERR_DUPLICATE_SESSION = ("ERR_DUPLICATE_SESSION", 409)
ERR_ORDER_ALREADY_EXISTS = ("ERR_ORDER_ALREADY_EXISTS", 409)
ERR_NEGATIVE_QUANTITY = ("ERR_NEGATIVE_QUANTITY", 422)
ERR_SESSION_FULL = ("ERR_SESSION_FULL", 422)
ERR_ROOM_CAPACITY_INSUFFICIENT = ("ERR_ROOM_CAPACITY_INSUFFICIENT", 422)
ERR_SCORE_BELOW_THRESHOLD = ("ERR_SCORE_BELOW_THRESHOLD", 422)
# fiscal
ERR_BUDGET_EXCEEDED = ("ERR_BUDGET_EXCEEDED", 422)


def raise_error(spec, message: str = ""):
    error_id, status = spec
    raise ApiError(error_id, status, message or error_id)
