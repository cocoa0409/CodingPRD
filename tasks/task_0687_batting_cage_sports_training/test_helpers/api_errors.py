"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, it is registered with the framework so that
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WAIVER_REQUIRED = "ERR_WAIVER_REQUIRED"
    ERR_FACILITY_POSTURE_BLOCK = "ERR_FACILITY_POSTURE_BLOCK"
    ERR_TOO_MANY_STRIKES = "ERR_TOO_MANY_STRIKES"
    ERR_RESOURCE_UNAVAILABLE = "ERR_RESOURCE_UNAVAILABLE"
    ERR_LANE_TIME_CONFLICT = "ERR_LANE_TIME_CONFLICT"
    ERR_OUTSIDE_HOURS = "ERR_OUTSIDE_HOURS"
    ERR_BOOKING_SHAPE_INVALID = "ERR_BOOKING_SHAPE_INVALID"
    ERR_INSUFFICIENT_FUNDS = "ERR_INSUFFICIENT_FUNDS"
    ERR_PROGRAM_FULL = "ERR_PROGRAM_FULL"
    ERR_STALE_LANE_VERSION = "ERR_STALE_LANE_VERSION"
    ERR_STALE_PROGRAM_VERSION = "ERR_STALE_PROGRAM_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WAIVER_REQUIRED: 422,
    ApiErrorId.ERR_FACILITY_POSTURE_BLOCK: 422,
    ApiErrorId.ERR_TOO_MANY_STRIKES: 422,
    ApiErrorId.ERR_RESOURCE_UNAVAILABLE: 422,
    ApiErrorId.ERR_LANE_TIME_CONFLICT: 409,
    ApiErrorId.ERR_OUTSIDE_HOURS: 422,
    ApiErrorId.ERR_BOOKING_SHAPE_INVALID: 422,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS: 422,
    ApiErrorId.ERR_PROGRAM_FULL: 409,
    ApiErrorId.ERR_STALE_LANE_VERSION: 412,
    ApiErrorId.ERR_STALE_PROGRAM_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
