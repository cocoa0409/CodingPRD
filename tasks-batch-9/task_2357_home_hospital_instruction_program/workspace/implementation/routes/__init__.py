def listing(table, filters):
    """Filter a table by equality on the supplied query fields, then paginate."""
    query = middleware.query()
    rows = db.rows(table)
    for field in filters:
        if field in query:
            wanted = query[field]
            rows = [r for r in rows if r.get(field) == wanted]
    window, page = response.paginate(rows, query["limit"], query["offset"])
    return middleware.arr(window, page)
