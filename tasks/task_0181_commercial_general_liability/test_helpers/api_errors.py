from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth
    ERR_MISSING_USER_CONTEXT = "ERR_MISSING_USER_CONTEXT"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    # Existence / reference
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    # Request validation
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_DUPLICATE_FEIN = "ERR_DUPLICATE_FEIN"
    ERR_DUPLICATE_POLICY_NUMBER = "ERR_DUPLICATE_POLICY_NUMBER"
    ERR_CLOCK_NOT_MONOTONIC = "ERR_CLOCK_NOT_MONOTONIC"
    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Policy structural constraints
    ERR_RETRO_DATE_REQUIRED = "ERR_RETRO_DATE_REQUIRED"
    ERR_RETRO_DATE_NOT_ALLOWED = "ERR_RETRO_DATE_NOT_ALLOWED"
    ERR_INVALID_POLICY_PERIOD = "ERR_INVALID_POLICY_PERIOD"
    ERR_AGGREGATE_LIMIT_INVALID = "ERR_AGGREGATE_LIMIT_INVALID"
    ERR_POLICY_NOT_YET_EFFECTIVE = "ERR_POLICY_NOT_YET_EFFECTIVE"
    ERR_POLICY_NOT_IN_FORCE = "ERR_POLICY_NOT_IN_FORCE"
    ERR_OPEN_CLAIMS_BLOCK_CANCEL = "ERR_OPEN_CLAIMS_BLOCK_CANCEL"
    # Coverage / claims
    ERR_OCCURRENCE_OUTSIDE_PERIOD = "ERR_OCCURRENCE_OUTSIDE_PERIOD"
    ERR_CLAIM_BEFORE_RETRO_DATE = "ERR_CLAIM_BEFORE_RETRO_DATE"
    ERR_RELEASE_EXCEEDS_RESERVE = "ERR_RELEASE_EXCEEDS_RESERVE"
    ERR_OPEN_RESERVE_REMAINS = "ERR_OPEN_RESERVE_REMAINS"
    ERR_PAID_CLAIM_CANNOT_DENY = "ERR_PAID_CLAIM_CANNOT_DENY"
    # Certificates / endorsements
    ERR_AI_ENDORSEMENT_MISSING = "ERR_AI_ENDORSEMENT_MISSING"
    ERR_AI_DATE_OUTSIDE_PERIOD = "ERR_AI_DATE_OUTSIDE_PERIOD"
    ERR_POLICY_EXHAUSTED = "ERR_POLICY_EXHAUSTED"
    # Audit
    ERR_POLICY_NOT_AUDITABLE = "ERR_POLICY_NOT_AUDITABLE"
    ERR_AUDIT_BASIS_MISMATCH = "ERR_AUDIT_BASIS_MISMATCH"
    ERR_NO_EXPOSURE_RECORDS = "ERR_NO_EXPOSURE_RECORDS"
    # Concurrency
    ERR_STALE_POLICY_VERSION = "ERR_STALE_POLICY_VERSION"


