"""Error catalogue and the ApiError exception.

Every error identifier and HTTP status here is taken verbatim from PRD section 5
(Error Catalogue) / SCAFFOLD.yaml section 1.6.
"""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status if http_status is not None else ERROR_STATUS.get(error_id, 400)
        self.message = message if message else DEFAULT_MESSAGES.get(error_id, error_id)


def fail(error_id, message=None):
    raise ApiError(error_id, message)


