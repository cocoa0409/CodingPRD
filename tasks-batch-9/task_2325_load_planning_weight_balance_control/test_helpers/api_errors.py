    OFFLOAD_INSUFFICIENT = "ERR_OFFLOAD_INSUFFICIENT"
    LMC_ALLOWANCE_EXCEEDED = "ERR_LMC_ALLOWANCE_EXCEEDED"
    FINDING_NOTE_REQUIRED = "ERR_FINDING_NOTE_REQUIRED"

    def __str__(self) -> str:  # pragma: no cover - convenience only
        return self.value


