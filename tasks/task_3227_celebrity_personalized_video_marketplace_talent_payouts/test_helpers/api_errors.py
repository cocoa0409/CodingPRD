"""Error identifiers and their HTTP status codes.

The mapping is registered with the shared framework at import time so that
``validate_error`` cross-checks the HTTP status automatically.  Every
identifier below is one the PRD's error catalogue lists.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


