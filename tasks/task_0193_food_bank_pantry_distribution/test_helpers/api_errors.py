"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_AGENCY_SCOPE_VIOLATION = "ERR_AGENCY_SCOPE_VIOLATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_COLD_CHAIN_MISMATCH = "ERR_COLD_CHAIN_MISMATCH"
    ERR_COLD_STORAGE_CAPACITY_EXCEEDED = "ERR_COLD_STORAGE_CAPACITY_EXCEEDED"
    ERR_HOUSEHOLD_NOT_CERTIFIED = "ERR_HOUSEHOLD_NOT_CERTIFIED"
    ERR_AGENCY_SUSPENDED = "ERR_AGENCY_SUSPENDED"
    ERR_CYCLE_NOT_OPEN = "ERR_CYCLE_NOT_OPEN"
    ERR_OVER_DISTRIBUTION = "ERR_OVER_DISTRIBUTION"
    ERR_FAIR_SHARE_EXCEEDED = "ERR_FAIR_SHARE_EXCEEDED"
    ERR_STALE_LOT_VERSION = "ERR_STALE_LOT_VERSION"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_AGENCY_SCOPE_VIOLATION: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_COLD_CHAIN_MISMATCH: 422,
    ApiErrorId.ERR_COLD_STORAGE_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_HOUSEHOLD_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_AGENCY_SUSPENDED: 409,
    ApiErrorId.ERR_CYCLE_NOT_OPEN: 409,
    ApiErrorId.ERR_OVER_DISTRIBUTION: 422,
    ApiErrorId.ERR_FAIR_SHARE_EXCEEDED: 409,
    ApiErrorId.ERR_STALE_LOT_VERSION: 412,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
