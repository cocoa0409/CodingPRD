def invalid_request(msg="Malformed request"):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def unauthenticated(msg="Missing or invalid X-User-Role / X-User-ID headers"):
    return ApiError(ERR_UNAUTHENTICATED, 401, msg)


def forbidden(msg="Forbidden"):
    return ApiError(ERR_FORBIDDEN, 403, msg)


def not_found(msg="Resource does not exist"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def invalid_state(msg="Entity not in a valid from-state"):
    return ApiError(ERR_INVALID_STATE, 409, msg)


def conflict(error_id, msg):
    return ApiError(error_id, 409, msg)
