"""Cascades that begin with one write and end at the season gate.

Two entry points are exercised. The agency's response to a transmitted
submission walks transmittal → agency error row → statement filing dimension →
statement furnishing dimension → controlled group → filing season. A
termination recorded against an employee whose statement has already been
delivered walks employee → monthly coverage lines → statement roll-ups →
controlled group → filing season.
"""

from test_helpers import (
    TEST_USERS,
    assert_employment_event,
    assert_fields,
    assert_monthly_coverage_line,
    assert_transmittal_error,
    factories,
    fixtures,
    lines_by_month,
    validate_success,
)

FURNISH_CLOCK_UTC = "2027-01-10T00:00:00Z"
TERMINATION_EFFECTIVE_DATE = "2026-06-15"


# ---------------------------------------------------------------------------
# Shared world builders — composed from test_helpers.fixtures only
# ---------------------------------------------------------------------------
def _transmitted_submission_holding_a_delivered_statement(api):
    """Season → determined-ALE group → member → employee → the employee's
    original statement generated by one preparer and delivered on paper by
    another → a transmittal built by the generating preparer and transmitted by
    the filing agent, so the statement's filing dimension is PENDING_FILING and
    its furnishing dimension is FURNISHED_PAPER.
    """
    ctx = fixtures.determined_ale_group_with_employee(
        api,
        employee_overrides={
            "full_name": "Uma Patel",
            "ssn_last4": "7007",
            "is_hourly": False,
            "monthly_salary_cents": 400000,
            "hourly_rate_cents": factories._UNSET,
        },
        member_overrides={"ein": "999999992", "legal_name": "Cascade Error Co"},
    )
    form = fixtures.generate_form(api, ctx["employee"]["id"])
    fixtures.set_clock(api, FURNISH_CLOCK_UTC)
    fixtures.furnish_form(api, form["id"], "PAPER")
    transmittal = fixtures.built_transmittal_with_forms(
        api, ctx["member"]["id"], [form["id"]]
    )
    fixtures.transmit_transmittal(api, transmittal["id"], "PAPER")
    ctx["form"] = form
    ctx["transmittal"] = transmittal
    return ctx


def _record_acceptance_with_one_error(api, transmittal_id, form_id):
    """The agency accepts the submission with one ERROR-severity row naming the
    only attached statement."""
    response = api.record_agency_response(
        transmittal_id,
        factories.agency_response_payload(
            "ACCEPTED_WITH_ERRORS",
            "AIR-2026-0004",
            [
                factories.agency_error_row(
                    form_id,
                    error_code="AIRTN500",
                    error_field="ssn_last4",
                    severity="ERROR",
                )
            ],
        ),
        TEST_USERS["filing_agent"],
    )
    return validate_success(response, 200)


def _delivered_statement_full_time_in_every_month(api):
    """Season → determined-ALE group → member measured monthly → an employee
    with 160 counted hours in all twelve reporting-year months and one
    minimum-value family offer covering the whole year → the original statement
    generated by one preparer and delivered on paper by another.
    """
    ctx = fixtures.determined_ale_group_with_employee(
        api,
        employee_overrides={
            "full_name": "Vera Lin",
            "ssn_last4": "8008",
            "is_hourly": True,
            "hourly_rate_cents": 1500,
            "w2_box1_wages_cents": 2400000,
        },
        member_overrides={"ein": "999999993", "legal_name": "Termination Cascade Co"},
    )
    employee_id = ctx["employee"]["id"]
    fixtures.record_hours(api, employee_id, 2026, hours_of_service=160)
    fixtures.create_coverage_offer(
        api,
        employee_id,
        offer_kind="MEC_MV_FAMILY",
        minimum_value=True,
        lowest_cost_self_only_cents=17800,
        effective_start_date="2026-01-01",
        effective_end_date="2027-01-01",
    )
    form = fixtures.generate_form(api, employee_id, safe_harbor_preference="W2")
    fixtures.set_clock(api, FURNISH_CLOCK_UTC)
    fixtures.furnish_form(api, form["id"], "PAPER")
    ctx["form"] = form
    return ctx


def _terminate(api, employee_id):
    response = api.create_employment_event(
        factories.employment_event_payload(
            employee_id, "TERMINATION", TERMINATION_EFFECTIVE_DATE,
            note="voluntary resignation",
        ),
        TEST_USERS["benefits_admin"],
    )
    return validate_success(response, 201)


