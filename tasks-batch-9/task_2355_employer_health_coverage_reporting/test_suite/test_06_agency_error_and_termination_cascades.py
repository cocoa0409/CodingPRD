# Entry point 2: a termination recorded against a delivered statement
# ---------------------------------------------------------------------------
class TestTerminationCascade:
    def test_termination_event_terminates_the_employee(self, api):
        """PRD §3.4: "**First**, the employee's `termination_date` is set to the
        effective date, `open_leave_type` is cleared, `employment_status` becomes
        `TERMINATED` and the event's `resulting_status` records it."

        Design: Difficulty/transitive_cascade/termination_cascade_coverage_lines_to_form_to_group_to_season
        """
        ctx = _delivered_statement_full_time_in_every_month(api)

        event = _terminate(api, ctx["employee"]["id"])

        assert_employment_event(
            event,
            employee_id=ctx["employee"]["id"],
            event_type="TERMINATION",
            effective_date=TERMINATION_EFFECTIVE_DATE,
            resulting_status="TERMINATED",
        )
        employee = fixtures.read_employee(api, ctx["employee"]["id"])
        assert_fields(
            employee,
            employment_status="TERMINATED",
            termination_date=TERMINATION_EFFECTIVE_DATE,
            open_leave_type=None,
        )

    def test_termination_rewrites_every_month_after_the_termination_month(self, api):
        """PRD §3.4: "**Second**, because the person is now terminated, every
        coverage line of the employee's non-voided statement for a month strictly
        after the termination month is rewritten to a `line14_code` of `1H`, a null
        `line15_amount_cents`, a `line16_code` of `2A`, `full_time_flag` false,
        `ft_source` of `NOT_EMPLOYED` and `assessable` false; the termination month
        itself receives `special_situation` of `TERMINATION` and, when its governing
        offer is not a `NO_OFFER`, a `line16_code` of `2B`."

        Design: Difficulty/transitive_cascade/termination_cascade_coverage_lines_to_form_to_group_to_season
        """
        ctx = _delivered_statement_full_time_in_every_month(api)

        _terminate(api, ctx["employee"]["id"])

        lines = lines_by_month(fixtures.coverage_lines_for(api, ctx["form"]["id"]))
        for month in range(7, 13):
            assert_monthly_coverage_line(
                lines[month],
                month=month,
                line14_code="1H",
                line15_amount_cents=None,
                line16_code="2A",
                full_time_flag=False,
                ft_source="NOT_EMPLOYED",
                assessable=False,
            )

    def test_termination_month_line_carries_termination_situation_and_2b(self, api):
        """PRD §3.4: "**Second**, because the person is now terminated, every
        coverage line of the employee's non-voided statement for a month strictly
        after the termination month is rewritten to a `line14_code` of `1H`, a null
        `line15_amount_cents`, a `line16_code` of `2A`, `full_time_flag` false,
        `ft_source` of `NOT_EMPLOYED` and `assessable` false; the termination month
        itself receives `special_situation` of `TERMINATION` and, when its governing
        offer is not a `NO_OFFER`, a `line16_code` of `2B`."

        Design: Difficulty/transitive_cascade/termination_cascade_coverage_lines_to_form_to_group_to_season
        """
        ctx = _delivered_statement_full_time_in_every_month(api)

        _terminate(api, ctx["employee"]["id"])

        lines = lines_by_month(fixtures.coverage_lines_for(api, ctx["form"]["id"]))
        assert_monthly_coverage_line(
            lines[6],
            month=6,
            line16_code="2B",
            special_situation="TERMINATION",
            full_time_flag=True,
        )

    def test_termination_recomputes_the_statement_roll_ups(self, api):
        """PRD §3.4: "**Third**, because those lines changed, the parent statement
        recomputes `ft_month_count`, `offered_month_count`, `assessable_month_count`
        and `line15_total_cents`, and its two status dimensions move: a form already
        `FURNISHED_PAPER` or `FURNISHED_ELECTRONIC` goes to `REDELIVERY_REQUIRED`,
        and a form already `FILED_ACCEPTED` or `FILED_WITH_ERRORS` goes to
        `CORRECTION_DRAFTED`."
        PRD §3.6: "The statement then rolls up: `all_12_months_code` is the shared
        line 14 code when all twelve months agree and null otherwise;
        `ft_month_count` counts months with `full_time_flag` true;
        `offered_month_count` counts months whose `line14_code` is not `1H`;
        `assessable_month_count` counts months with `assessable` true; and
        `line15_total_cents` sums `line15_amount_cents` over the months where it is
        not null."

        Design: Difficulty/transitive_cascade/termination_cascade_coverage_lines_to_form_to_group_to_season
        """
        ctx = _delivered_statement_full_time_in_every_month(api)

        _terminate(api, ctx["employee"]["id"])

        form = fixtures.read_form(api, ctx["form"]["id"])
        assert_fields(
            form,
            ft_month_count=6,
            offered_month_count=6,
            assessable_month_count=0,
            line15_total_cents=106800,
        )

    def test_termination_pushes_delivered_statement_and_opens_correction(self, api):
        """PRD §3.4: "**Third**, because those lines changed, the parent statement
        recomputes `ft_month_count`, `offered_month_count`, `assessable_month_count`
        and `line15_total_cents`, and its two status dimensions move: a form already
        `FURNISHED_PAPER` or `FURNISHED_ELECTRONIC` goes to `REDELIVERY_REQUIRED`,
        and a form already `FILED_ACCEPTED` or `FILED_WITH_ERRORS` goes to
        `CORRECTION_DRAFTED`."
        PRD §3.4: "**Fourth**, because the form entered `REDELIVERY_REQUIRED` or
        `CORRECTION_DRAFTED`, the controlled group's `open_correction_count`
        increments and a group in `DETERMINED_ALE` moves to `CORRECTION_OPEN`."
        PRD §3.4: "**Fifth**, because the group entered `CORRECTION_OPEN`, the
        season's `open_correction_count` increments and the season can no longer be
        closed."

        Design: Difficulty/transitive_cascade/termination_cascade_coverage_lines_to_form_to_group_to_season
        """
        ctx = _delivered_statement_full_time_in_every_month(api)

        _terminate(api, ctx["employee"]["id"])

        form = fixtures.read_form(api, ctx["form"]["id"])
        assert form["furnishing_status"] == "REDELIVERY_REQUIRED", (
            "a statement already delivered on paper must move to REDELIVERY_REQUIRED "
            f"when the termination rewrites its lines, got {form['furnishing_status']}"
        )

        group = fixtures.read_group(api, ctx["group"]["id"])
        assert_fields(
            group, determination_state="CORRECTION_OPEN", open_correction_count=1
        )

        season = fixtures.read_season(api, ctx["season"]["id"])
        assert season["open_correction_count"] == 1, (
            "the termination cascade must reach the season gate, but its "
            f"open_correction_count is {season['open_correction_count']}"
        )
