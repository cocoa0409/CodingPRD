class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status) per PRD §5
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_REVIEWER_PAYER_MISMATCH = ("ERR_REVIEWER_PAYER_MISMATCH", 422)
ERR_OPEN_P2P_BLOCKS_DECISION = ("ERR_OPEN_P2P_BLOCKS_DECISION", 409)
ERR_NO_EVIDENCE = ("ERR_NO_EVIDENCE", 422)
ERR_P2P_SLOT_CONFLICT = ("ERR_P2P_SLOT_CONFLICT", 409)
ERR_PAST_DEADLINE = ("ERR_PAST_DEADLINE", 409)
ERR_DUPLICATE_ACTIVE_AUTH = ("ERR_DUPLICATE_ACTIVE_AUTH", 409)
ERR_INVALID_DECISION_FIELDS = ("ERR_INVALID_DECISION_FIELDS", 422)
ERR_APPEAL_NOT_ELIGIBLE = ("ERR_APPEAL_NOT_ELIGIBLE", 422)
ERR_INVALID_SUPERSEDE_TARGET = ("ERR_INVALID_SUPERSEDE_TARGET", 422)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_VALIDATION = ("ERR_VALIDATION", 422)
ERR_PAGINATION_INVALID = ("ERR_PAGINATION_INVALID", 400)


def err(code_tuple, message=None):
    eid, status = code_tuple
    return ApiError(eid, status, message)
