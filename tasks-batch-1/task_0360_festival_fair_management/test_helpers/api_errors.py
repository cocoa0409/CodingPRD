"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DAYCOUNT_RANGE = "ERR_DAYCOUNT_RANGE"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FESTIVAL_POSTURE = "ERR_FESTIVAL_POSTURE"
    ERR_FESTIVAL_SUSPENDED = "ERR_FESTIVAL_SUSPENDED"
    ERR_ALREADY_INSIDE = "ERR_ALREADY_INSIDE"
    ERR_REENTRY_LIMIT = "ERR_REENTRY_LIMIT"
    ERR_STAGE_CONFLICT = "ERR_STAGE_CONFLICT"
    ERR_ARTIST_DOUBLE_BOOKED = "ERR_ARTIST_DOUBLE_BOOKED"
    ERR_DUPLICATE_RFID = "ERR_DUPLICATE_RFID"
    ERR_ZONE_FULL = "ERR_ZONE_FULL"
    ERR_CAPACITY_FULL = "ERR_CAPACITY_FULL"
    ERR_FEE_UNPAID = "ERR_FEE_UNPAID"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_STALE_ZONE_VERSION = "ERR_STALE_ZONE_VERSION"
    ERR_STALE_LOT_VERSION = "ERR_STALE_LOT_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DAYCOUNT_RANGE: 422,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FESTIVAL_POSTURE: 409,
    ApiErrorId.ERR_FESTIVAL_SUSPENDED: 409,
    ApiErrorId.ERR_ALREADY_INSIDE: 409,
    ApiErrorId.ERR_REENTRY_LIMIT: 409,
    ApiErrorId.ERR_STAGE_CONFLICT: 409,
    ApiErrorId.ERR_ARTIST_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_DUPLICATE_RFID: 409,
    ApiErrorId.ERR_ZONE_FULL: 409,
    ApiErrorId.ERR_CAPACITY_FULL: 409,
    ApiErrorId.ERR_FEE_UNPAID: 409,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 422,
    ApiErrorId.ERR_STALE_ZONE_VERSION: 412,
    ApiErrorId.ERR_STALE_LOT_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
