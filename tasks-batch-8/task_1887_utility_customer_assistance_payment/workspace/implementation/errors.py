def unauthenticated(msg="Missing or invalid authentication headers"):
    return ApiError(ERR_UNAUTHENTICATED, 401, msg)


def unauthorized(msg="Role not permitted for this endpoint"):
    return ApiError(ERR_UNAUTHORIZED, 403, msg)


def ownership(msg="Customer may only act on their own account"):
    return ApiError(ERR_ACCOUNT_OWNERSHIP_MISMATCH, 403, msg)


def invalid_request(msg):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, msg)
