"""Error IDs and HTTP status mapping — PRD §5.

Mapping is registered with the framework at import time so
`validate_error()` cross-checks HTTP status codes against the catalog
without each test passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_DISPUTE_NOT_OWNED = "ERR_DISPUTE_NOT_OWNED"
    # Existence — PRD §2.6
    ERR_CANDIDATE_NOT_FOUND = "ERR_CANDIDATE_NOT_FOUND"
    ERR_ORDER_NOT_FOUND = "ERR_ORDER_NOT_FOUND"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    # State — PRD §2.7
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Business — PRD §2.9, §3.x
    ERR_BAN_THE_BOX_VIOLATION = "ERR_BAN_THE_BOX_VIOLATION"
    ERR_SALARY_HISTORY_BAN = "ERR_SALARY_HISTORY_BAN"
    ERR_CONSENT_INVALID = "ERR_CONSENT_INVALID"
    ERR_CONSENT_TIMESTAMP_INVALID = "ERR_CONSENT_TIMESTAMP_INVALID"
    ERR_CONSENT_CANDIDATE_MISMATCH = "ERR_CONSENT_CANDIDATE_MISMATCH"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_COOLING_OFF_NOT_ELAPSED = "ERR_COOLING_OFF_NOT_ELAPSED"
    ERR_OPEN_DISPUTE_BLOCKS_FINAL = "ERR_OPEN_DISPUTE_BLOCKS_FINAL"
    ERR_PACKAGE_SET_INVALID = "ERR_PACKAGE_SET_INVALID"
    ERR_CANDIDATE_NOT_ELIGIBLE = "ERR_CANDIDATE_NOT_ELIGIBLE"
    ERR_REWORK_CAP_EXCEEDED = "ERR_REWORK_CAP_EXCEEDED"
    ERR_AUDIT_CHAIN_BROKEN = "ERR_AUDIT_CHAIN_BROKEN"
    # Uniqueness / concurrency — PRD §2.5, §3.x
    ERR_CANDIDATE_EMAIL_TAKEN = "ERR_CANDIDATE_EMAIL_TAKEN"
    ERR_ADVERSE_FLOW_ALREADY_EXISTS = "ERR_ADVERSE_FLOW_ALREADY_EXISTS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # Schema — PRD §2.7
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"


# PRD §5 Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_DISPUTE_NOT_OWNED: 403,
    ApiErrorId.ERR_CANDIDATE_NOT_FOUND: 404,
    ApiErrorId.ERR_ORDER_NOT_FOUND: 404,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_BAN_THE_BOX_VIOLATION: 422,
    ApiErrorId.ERR_SALARY_HISTORY_BAN: 422,
    ApiErrorId.ERR_CONSENT_INVALID: 422,
    ApiErrorId.ERR_CONSENT_TIMESTAMP_INVALID: 422,
    ApiErrorId.ERR_CONSENT_CANDIDATE_MISMATCH: 422,
    ApiErrorId.ERR_SOD_VIOLATION: 422,
    ApiErrorId.ERR_COOLING_OFF_NOT_ELAPSED: 422,
    ApiErrorId.ERR_OPEN_DISPUTE_BLOCKS_FINAL: 422,
    ApiErrorId.ERR_PACKAGE_SET_INVALID: 422,
    ApiErrorId.ERR_CANDIDATE_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_REWORK_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_AUDIT_CHAIN_BROKEN: 422,
    ApiErrorId.ERR_CANDIDATE_EMAIL_TAKEN: 409,
    ApiErrorId.ERR_ADVERSE_FLOW_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_STALE_VERSION: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 400,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
