def test_line_item_append_only_has_id_and_created_at(api):
    """PRD §2.4: "The sole exception is `TicketLineItem`, which is append-only: once
    created it is never mutated. A `TicketLineItem` therefore carries only `id` and
    `created_at` — it has no `updated_at` and no `version` field."

    Design: Corner/entities/line_item_immutable_no_version_field
    """
    publish_price("CU_BARE_BRIGHT", "NON_FERROUS", spot=375, mill=410)
    seller = register_seller(legal_name="Imm Co", id_type="STATE_ID", id_number="SID-IMM")
    ticket = open_ticket(seller["id"], gross_weight_lb=1500)
    data = validate_success(
        api.add_line_item(ticket["id"], {"grade_code": "CU_BARE_BRIGHT", "weight_lb": 5}, WM), 201
    )
    assert is_valid_uuid(data["id"]), "line item must carry a UUID id"
    assert "version" not in data, "append-only line item must not carry a version field"
    assert "updated_at" not in data, "append-only line item must not carry an updated_at field"


