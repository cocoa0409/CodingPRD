"""Error types and HTTP status map for the slate API."""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


# Error catalog with exact HTTP statuses from PRD §5
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_SEASON_NOT_LOCKED = ("ERR_SEASON_NOT_LOCKED", 409)
ERR_SEASON_HAS_OPEN_TITLES = ("ERR_SEASON_HAS_OPEN_TITLES", 409)
ERR_SLATE_FULL = ("ERR_SLATE_FULL", 409)
ERR_BRAND_VIOLATION = ("ERR_BRAND_VIOLATION", 422)
ERR_DELIVERY_LATE = ("ERR_DELIVERY_LATE", 422)
ERR_NO_WRAPPED_SHOOT = ("ERR_NO_WRAPPED_SHOOT", 409)
ERR_PRODUCTION_QUOTA_EXCEEDED = ("ERR_PRODUCTION_QUOTA_EXCEEDED", 409)
ERR_LOCATION_OVERLAP = ("ERR_LOCATION_OVERLAP", 422)
ERR_LOCATION_BLACKOUT = ("ERR_LOCATION_BLACKOUT", 422)
ERR_TALENT_UNAVAILABLE = ("ERR_TALENT_UNAVAILABLE", 422)
ERR_PREMIERE_CADENCE_VIOLATION = ("ERR_PREMIERE_CADENCE_VIOLATION", 422)
ERR_AIRSLOT_OVERLAP = ("ERR_AIRSLOT_OVERLAP", 422)
ERR_ENCORE_CAP_EXCEEDED = ("ERR_ENCORE_CAP_EXCEEDED", 409)
ERR_AIRSLOT_TOO_EARLY = ("ERR_AIRSLOT_TOO_EARLY", 422)
ERR_STREAMING_BEFORE_PREMIERE = ("ERR_STREAMING_BEFORE_PREMIERE", 422)
ERR_INVALID_WINDOW = ("ERR_INVALID_WINDOW", 422)
ERR_AD_BUDGET_EXCEEDED = ("ERR_AD_BUDGET_EXCEEDED", 402)


def err(err_tuple, message=""):
    error_id, http_status = err_tuple
    return ApiError(error_id, message or error_id, http_status)
