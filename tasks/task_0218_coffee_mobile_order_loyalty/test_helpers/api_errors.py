"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STORE_PAUSED = "ERR_STORE_PAUSED"
    ERR_SLOT_UNAVAILABLE = "ERR_SLOT_UNAVAILABLE"
    ERR_SLOT_FULL = "ERR_SLOT_FULL"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_REWARD_NOT_APPLICABLE = "ERR_REWARD_NOT_APPLICABLE"
    ERR_INSUFFICIENT_STARS = "ERR_INSUFFICIENT_STARS"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_BIRTHDAY_ALREADY_CLAIMED = "ERR_BIRTHDAY_ALREADY_CLAIMED"
    ERR_REFUND_NOT_ALLOWED = "ERR_REFUND_NOT_ALLOWED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_DUPLICATE_CARD = "ERR_DUPLICATE_CARD"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STORE_PAUSED: 409,
    ApiErrorId.ERR_SLOT_UNAVAILABLE: 409,
    ApiErrorId.ERR_SLOT_FULL: 409,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_REWARD_NOT_APPLICABLE: 409,
    ApiErrorId.ERR_INSUFFICIENT_STARS: 409,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 402,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_BIRTHDAY_ALREADY_CLAIMED: 409,
    ApiErrorId.ERR_REFUND_NOT_ALLOWED: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_DUPLICATE_CARD: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
