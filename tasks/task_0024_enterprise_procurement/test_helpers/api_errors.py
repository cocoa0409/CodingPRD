"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # --- Auth / RBAC / existence (PRD §2.1, §2.7) ---
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # --- State / concurrency (PRD §2.4, §2.9) ---
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # --- Schema / pagination (PRD §2.3, §2.8 priority 19/20) ---
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"

    # --- Sourcing / award (PRD §3.2, §3.3) ---
    ERR_SUPPLIER_NOT_QUALIFIED = "ERR_SUPPLIER_NOT_QUALIFIED"
    ERR_INSUFFICIENT_QUOTES = "ERR_INSUFFICIENT_QUOTES"
    ERR_REQUIREMENT_ALREADY_AWARDED = "ERR_REQUIREMENT_ALREADY_AWARDED"
    ERR_BUDGET_WOULD_EXCEED = "ERR_BUDGET_WOULD_EXCEED"

    # --- Approval (PRD §3.3, §3.4) ---
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_PREDECESSOR_NOT_DECIDED = "ERR_PREDECESSOR_NOT_DECIDED"
    ERR_APPROVAL_DEADLINE_PASSED = "ERR_APPROVAL_DEADLINE_PASSED"
