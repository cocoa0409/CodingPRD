"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PAYMENT_NOT_ALLOWED = "ERR_PAYMENT_NOT_ALLOWED"
    ERR_NO_LOCATIONS = "ERR_NO_LOCATIONS"
    ERR_REVIEWS_INCOMPLETE = "ERR_REVIEWS_INCOMPLETE"
    ERR_DEPOSIT_UNPAID = "ERR_DEPOSIT_UNPAID"
    ERR_STALE_APPLICATION_VERSION = "ERR_STALE_APPLICATION_VERSION"
    ERR_COI_NOT_VERIFIED = "ERR_COI_NOT_VERIFIED"
    ERR_OFFICER_INACTIVE = "ERR_OFFICER_INACTIVE"
    ERR_AVIATION_COVERAGE_MISSING = "ERR_AVIATION_COVERAGE_MISSING"
    ERR_SEGMENT_DOUBLE_BOOKED = "ERR_SEGMENT_DOUBLE_BOOKED"
    ERR_OFFICER_DOUBLE_BOOKED = "ERR_OFFICER_DOUBLE_BOOKED"
    ERR_FLIGHT_WINDOW_OUTSIDE_SHOOT = "ERR_FLIGHT_WINDOW_OUTSIDE_SHOOT"
    ERR_NOTICE_TOO_LATE = "ERR_NOTICE_TOO_LATE"
    ERR_FEE_UNPAID = "ERR_FEE_UNPAID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PAYMENT_NOT_ALLOWED: 409,
    ApiErrorId.ERR_NO_LOCATIONS: 422,
    ApiErrorId.ERR_REVIEWS_INCOMPLETE: 409,
    ApiErrorId.ERR_DEPOSIT_UNPAID: 402,
    ApiErrorId.ERR_STALE_APPLICATION_VERSION: 412,
    ApiErrorId.ERR_COI_NOT_VERIFIED: 422,
    ApiErrorId.ERR_OFFICER_INACTIVE: 409,
    ApiErrorId.ERR_AVIATION_COVERAGE_MISSING: 422,
    ApiErrorId.ERR_SEGMENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_OFFICER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_FLIGHT_WINDOW_OUTSIDE_SHOOT: 422,
    ApiErrorId.ERR_NOTICE_TOO_LATE: 422,
    ApiErrorId.ERR_FEE_UNPAID: 402,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
