"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CHANGE_GATING_RESOLUTION = "ERR_CHANGE_GATING_RESOLUTION"
    ERR_PROBLEM_HAS_OPEN_TICKETS = "ERR_PROBLEM_HAS_OPEN_TICKETS"
    ERR_ASSET_HAS_OPEN_INCIDENTS = "ERR_ASSET_HAS_OPEN_INCIDENTS"
    ERR_REOPEN_WINDOW_CLOSED = "ERR_REOPEN_WINDOW_CLOSED"
    ERR_CSAT_WINDOW_CLOSED = "ERR_CSAT_WINDOW_CLOSED"
    ERR_DUPLICATE_SURVEY = "ERR_DUPLICATE_SURVEY"
    ERR_DUPLICATE_VOTE = "ERR_DUPLICATE_VOTE"
    ERR_DUPLICATE_ASSET_TAG = "ERR_DUPLICATE_ASSET_TAG"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_FIELD_VALUE = "ERR_INVALID_FIELD_VALUE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SOD_VIOLATION: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CHANGE_GATING_RESOLUTION: 409,
    ApiErrorId.ERR_PROBLEM_HAS_OPEN_TICKETS: 409,
    ApiErrorId.ERR_ASSET_HAS_OPEN_INCIDENTS: 409,
    ApiErrorId.ERR_REOPEN_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_CSAT_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_DUPLICATE_SURVEY: 409,
    ApiErrorId.ERR_DUPLICATE_VOTE: 409,
    ApiErrorId.ERR_DUPLICATE_ASSET_TAG: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_FIELD_VALUE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
