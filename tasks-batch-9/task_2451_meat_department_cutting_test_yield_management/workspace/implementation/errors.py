def bad_request(message):
    return ApiError(ERR_INVALID_REQUEST, 400, message)


def not_found(error_id, message=None):
    return ApiError(error_id, 404, message or "Resource not found")


def conflict(error_id, message=None):
    return ApiError(error_id, 409, message or error_id)


def unprocessable(error_id, message=None):
    return ApiError(error_id, 422, message or error_id)


def forbidden(error_id, message=None):
    return ApiError(error_id, 403, message or error_id)
