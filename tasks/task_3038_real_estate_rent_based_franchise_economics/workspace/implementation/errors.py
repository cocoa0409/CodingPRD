"""Error catalog for the Real Estate Rent Franchise API.

Every error_id and http_status is taken verbatim from SCAFFOLD.yaml 1.6
and PRD 5. No error identifier is invented or aliased.
"""


class ApiError(Exception):
    """Custom exception carrying the error_id, HTTP status, and message."""

    def __init__(self, error_id: str, http_status: int, message: str = ""):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


