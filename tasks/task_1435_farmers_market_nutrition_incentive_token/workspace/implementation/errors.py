"""Error catalog for the Farmers Market Nutrition Incentive API.

Every error_id and HTTP status is taken verbatim from SCAFFOLD.yaml §1.6 /
PRD.md §5. Error response envelope field names come from
SCAFFOLD.yaml §1.0 (response_envelope.error): data.error_id / data.message.
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message):
        super().__init__(message)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message


