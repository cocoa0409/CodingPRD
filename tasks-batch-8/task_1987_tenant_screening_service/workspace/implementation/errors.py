ERR_INVALID_CRITERIA_STATE = "ERR_INVALID_CRITERIA_STATE"
ERR_INVALID_REPORT_STATE = "ERR_INVALID_REPORT_STATE"
ERR_INVALID_DISPUTE_STATE = "ERR_INVALID_DISPUTE_STATE"
