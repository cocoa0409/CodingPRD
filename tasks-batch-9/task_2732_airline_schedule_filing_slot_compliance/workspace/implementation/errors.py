DEFAULT_MESSAGE = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing or blank.",
    "ERR_ROLE_NOT_PERMITTED": "The acting role may not perform this operation.",
    "ERR_OWNERSHIP_MISMATCH": "The acting carrier does not own the target resource.",
    "ERR_INVALID_REQUEST": "The request payload is malformed or violates a field constraint.",
}


class ApiError(Exception):
    """Carries an error_id, a human message and the HTTP status from the catalogue."""

    def __init__(self, error_id, message=None, http_status=None):
        self.error_id = error_id
        self.message = message or DEFAULT_MESSAGE.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize() + "."
        )
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)
        super().__init__(self.message)


def fail(error_id, message=None):
    raise ApiError(error_id, message)
