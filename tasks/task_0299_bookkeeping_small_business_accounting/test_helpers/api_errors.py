"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can auto-check the
HTTP status that accompanies each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    # Not found
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_ACCOUNT_NOT_FOUND = "ERR_ACCOUNT_NOT_FOUND"
    # Request validation
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_LINE = "ERR_INVALID_LINE"
    ERR_ENTRY_NOT_BALANCED = "ERR_ENTRY_NOT_BALANCED"
    ERR_INVOICE_EMPTY = "ERR_INVOICE_EMPTY"
    ERR_BILL_EMPTY = "ERR_BILL_EMPTY"
    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Segregation
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    # Referential / categorization
    ERR_INVALID_CATEGORIZATION_ACCOUNT = "ERR_INVALID_CATEGORIZATION_ACCOUNT"
    ERR_ACCOUNT_ARCHIVED = "ERR_ACCOUNT_ARCHIVED"
    ERR_ACCOUNT_TYPE_MISMATCH = "ERR_ACCOUNT_TYPE_MISMATCH"
    ERR_DUPLICATE_ACCOUNT_CODE = "ERR_DUPLICATE_ACCOUNT_CODE"
    # Fiscal / period
    ERR_PERIOD_NOT_OPEN = "ERR_PERIOD_NOT_OPEN"
    ERR_PERIOD_CLOSED = "ERR_PERIOD_CLOSED"
    ERR_PERIOD_NOT_CONTIGUOUS = "ERR_PERIOD_NOT_CONTIGUOUS"
    ERR_CHECKLIST_INCOMPLETE = "ERR_CHECKLIST_INCOMPLETE"
    ERR_OPEN_DRAFT_ENTRIES = "ERR_OPEN_DRAFT_ENTRIES"
    ERR_RECONCILIATION_IN_PROGRESS = "ERR_RECONCILIATION_IN_PROGRESS"
    ERR_TRIAL_BALANCE_OUT_OF_BALANCE = "ERR_TRIAL_BALANCE_OUT_OF_BALANCE"
    ERR_NOT_LATEST_CLOSED_PERIOD = "ERR_NOT_LATEST_CLOSED_PERIOD"
    ERR_CLOSING_ENTRY_PROTECTED = "ERR_CLOSING_ENTRY_PROTECTED"
    # Payments
    ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"
    ERR_BILL_OVERPAY = "ERR_BILL_OVERPAY"
    ERR_INVOICE_HAS_PAYMENTS = "ERR_INVOICE_HAS_PAYMENTS"
    # Reconciliation
    ERR_RECONCILIATION_UNBALANCED = "ERR_RECONCILIATION_UNBALANCED"
    ERR_TRANSACTION_NOT_CATEGORIZED = "ERR_TRANSACTION_NOT_CATEGORIZED"
    ERR_TRANSACTION_CLEARED = "ERR_TRANSACTION_CLEARED"
    # Tax rates
    ERR_TAX_RATE_OVERLAP = "ERR_TAX_RATE_OVERLAP"
    # Concurrency
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


