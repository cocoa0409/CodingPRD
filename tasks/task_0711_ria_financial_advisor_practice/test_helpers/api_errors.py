"""Error IDs and HTTP status mapping (RIA Practice PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_IPS_MANDATE_VIOLATION = "ERR_IPS_MANDATE_VIOLATION"
    ERR_CROSS_ENTITY_PRECONDITION = "ERR_CROSS_ENTITY_PRECONDITION"
    ERR_BILLING_PERIOD_OVERLAP = "ERR_BILLING_PERIOD_OVERLAP"
    ERR_REVIEW_DATE_COLLISION = "ERR_REVIEW_DATE_COLLISION"
    ERR_ALLOCATION_INVALID = "ERR_ALLOCATION_INVALID"
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_STALE_HOUSEHOLD_VERSION = "ERR_STALE_HOUSEHOLD_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_FEE_RUN_OPEN = "ERR_FEE_RUN_OPEN"
    ERR_PORTFOLIO_NOT_PUBLISHED = "ERR_PORTFOLIO_NOT_PUBLISHED"
    ERR_NO_APPROVED_IPS = "ERR_NO_APPROVED_IPS"
    ERR_COMPLIANCE_NOT_DUE = "ERR_COMPLIANCE_NOT_DUE"
    ERR_DUPLICATE_APPROVED_IPS = "ERR_DUPLICATE_APPROVED_IPS"
    ERR_GOAL_AMOUNT_INVALID = "ERR_GOAL_AMOUNT_INVALID"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_IPS_MANDATE_VIOLATION: 422,
    ApiErrorId.ERR_CROSS_ENTITY_PRECONDITION: 409,
    ApiErrorId.ERR_BILLING_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_REVIEW_DATE_COLLISION: 409,
    ApiErrorId.ERR_ALLOCATION_INVALID: 422,
    ApiErrorId.ERR_INVALID_PERIOD: 422,
    ApiErrorId.ERR_STALE_HOUSEHOLD_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_FEE_RUN_OPEN: 409,
    ApiErrorId.ERR_PORTFOLIO_NOT_PUBLISHED: 422,
    ApiErrorId.ERR_NO_APPROVED_IPS: 409,
    ApiErrorId.ERR_COMPLIANCE_NOT_DUE: 409,
    ApiErrorId.ERR_DUPLICATE_APPROVED_IPS: 409,
    ApiErrorId.ERR_GOAL_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
