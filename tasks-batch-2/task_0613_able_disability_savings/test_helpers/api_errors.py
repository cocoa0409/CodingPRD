"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_ACCOUNT_OWNER = "ERR_NOT_ACCOUNT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ACCOUNT_VERSION = "ERR_STALE_ACCOUNT_VERSION"
    ERR_ACCOUNT_NOT_OPEN = "ERR_ACCOUNT_NOT_OPEN"
    ERR_NOT_CERTIFIED = "ERR_NOT_CERTIFIED"
    ERR_ONSET_AGE_INELIGIBLE = "ERR_ONSET_AGE_INELIGIBLE"
    ERR_DIAGNOSIS_REQUIRED = "ERR_DIAGNOSIS_REQUIRED"
    ERR_ATW_INELIGIBLE = "ERR_ATW_INELIGIBLE"
    ERR_ANNUAL_CAP_EXCEEDED = "ERR_ANNUAL_CAP_EXCEEDED"
    ERR_ROLLOVER_LIMIT_EXCEEDED = "ERR_ROLLOVER_LIMIT_EXCEEDED"
    ERR_ATW_CAP_EXCEEDED = "ERR_ATW_CAP_EXCEEDED"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_QDE_MISMATCH = "ERR_QDE_MISMATCH"
    ERR_INVESTMENT_CHANGE_LIMIT = "ERR_INVESTMENT_CHANGE_LIMIT"
    ERR_CERT_WINDOW_OVERLAP = "ERR_CERT_WINDOW_OVERLAP"
    ERR_REP_AUTHORITY_OVERLAP = "ERR_REP_AUTHORITY_OVERLAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_ACCOUNT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ACCOUNT_VERSION: 412,
    ApiErrorId.ERR_ACCOUNT_NOT_OPEN: 409,
    ApiErrorId.ERR_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_ONSET_AGE_INELIGIBLE: 409,
    ApiErrorId.ERR_DIAGNOSIS_REQUIRED: 422,
    ApiErrorId.ERR_ATW_INELIGIBLE: 409,
    ApiErrorId.ERR_ANNUAL_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_ROLLOVER_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_ATW_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 409,
    ApiErrorId.ERR_QDE_MISMATCH: 409,
    ApiErrorId.ERR_INVESTMENT_CHANGE_LIMIT: 409,
    ApiErrorId.ERR_CERT_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_REP_AUTHORITY_OVERLAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
