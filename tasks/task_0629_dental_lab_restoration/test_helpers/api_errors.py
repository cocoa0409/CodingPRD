"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_CASE_OWNER = "ERR_NOT_CASE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_CASE_VERSION = "ERR_STALE_CASE_VERSION"
    ERR_STALE_MACHINE_VERSION = "ERR_STALE_MACHINE_VERSION"
    ERR_MATERIAL_INACTIVE = "ERR_MATERIAL_INACTIVE"
    ERR_MACHINE_CAPABILITY_MISMATCH = "ERR_MACHINE_CAPABILITY_MISMATCH"
    ERR_EMPTY_FABRICATION = "ERR_EMPTY_FABRICATION"
    ERR_MAX_REVISIONS_EXCEEDED = "ERR_MAX_REVISIONS_EXCEEDED"
    ERR_MACHINE_DOUBLE_BOOKED = "ERR_MACHINE_DOUBLE_BOOKED"
    ERR_ROUTE_WINDOW_CONFLICT = "ERR_ROUTE_WINDOW_CONFLICT"
    ERR_ROUTE_AT_CAPACITY = "ERR_ROUTE_AT_CAPACITY"
    ERR_UNIT_NOT_WARRANTABLE = "ERR_UNIT_NOT_WARRANTABLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_CASE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_CASE_VERSION: 412,
    ApiErrorId.ERR_STALE_MACHINE_VERSION: 412,
    ApiErrorId.ERR_MATERIAL_INACTIVE: 422,
    ApiErrorId.ERR_MACHINE_CAPABILITY_MISMATCH: 422,
    ApiErrorId.ERR_EMPTY_FABRICATION: 422,
    ApiErrorId.ERR_MAX_REVISIONS_EXCEEDED: 422,
    ApiErrorId.ERR_MACHINE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_ROUTE_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_ROUTE_AT_CAPACITY: 422,
    ApiErrorId.ERR_UNIT_NOT_WARRANTABLE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
