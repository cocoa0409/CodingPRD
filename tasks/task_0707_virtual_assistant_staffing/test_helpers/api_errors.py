"""Error IDs and their HTTP status codes (PRD §5 Error Code Catalogue).

After building the mapping it is registered with the framework so
validate_error() can auto-check the HTTP status from the error_id alone.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


