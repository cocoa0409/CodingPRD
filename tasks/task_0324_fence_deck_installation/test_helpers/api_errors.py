"""Error IDs and HTTP status mapping (PRD §5).

Registers the error_id -> HTTP status map with the framework so
validate_error() can cross-check status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_PROJECT_VERSION = "ERR_STALE_PROJECT_VERSION"
    ERR_ESTIMATE_NOT_PRICED = "ERR_ESTIMATE_NOT_PRICED"
    ERR_EMPTY_ESTIMATE = "ERR_EMPTY_ESTIMATE"
    ERR_SETBACK_VIOLATION = "ERR_SETBACK_VIOLATION"
    ERR_PERMIT_TOO_EARLY = "ERR_PERMIT_TOO_EARLY"
    ERR_MEASURE_REQUIRED = "ERR_MEASURE_REQUIRED"
    ERR_MATERIAL_NOT_READY = "ERR_MATERIAL_NOT_READY"
    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_DOCK_WINDOW_CONFLICT = "ERR_DOCK_WINDOW_CONFLICT"
    ERR_CHANGE_ORDER_TOO_LATE = "ERR_CHANGE_ORDER_TOO_LATE"
    ERR_DRAW_GATE_NOT_MET = "ERR_DRAW_GATE_NOT_MET"
    ERR_DRAW_SEQUENCE_VIOLATION = "ERR_DRAW_SEQUENCE_VIOLATION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_PROJECT_VERSION: 412,
    ApiErrorId.ERR_ESTIMATE_NOT_PRICED: 409,
    ApiErrorId.ERR_EMPTY_ESTIMATE: 409,
    ApiErrorId.ERR_SETBACK_VIOLATION: 409,
    ApiErrorId.ERR_PERMIT_TOO_EARLY: 409,
    ApiErrorId.ERR_MEASURE_REQUIRED: 409,
    ApiErrorId.ERR_MATERIAL_NOT_READY: 409,
    ApiErrorId.ERR_CREW_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_DOCK_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_CHANGE_ORDER_TOO_LATE: 409,
    ApiErrorId.ERR_DRAW_GATE_NOT_MET: 409,
    ApiErrorId.ERR_DRAW_SEQUENCE_VIOLATION: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
