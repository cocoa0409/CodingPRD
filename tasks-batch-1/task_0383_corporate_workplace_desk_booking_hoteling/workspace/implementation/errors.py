"""Domain error classes and the error_id catalog (PRD §5, scaffold §1.6)."""
from __future__ import annotations


class APIError(Exception):
    def __init__(self, error_id: str, http_status: int, message: str = ""):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# ---- error_id constants (exact strings from PRD §5 / scaffold §1.6) ----
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
ERR_RESOURCE_TARGET_MISMATCH = "ERR_RESOURCE_TARGET_MISMATCH"
ERR_OUTSIDE_WORKDAY = "ERR_OUTSIDE_WORKDAY"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_RESOURCE_NOT_BOOKABLE = "ERR_RESOURCE_NOT_BOOKABLE"
ERR_BOOKING_SUSPENDED = "ERR_BOOKING_SUSPENDED"
ERR_TEAM_ZONING_VIOLATION = "ERR_TEAM_ZONING_VIOLATION"
ERR_RESERVATION_LIMIT_REACHED = "ERR_RESERVATION_LIMIT_REACHED"
ERR_SEAT_DOUBLE_BOOKED = "ERR_SEAT_DOUBLE_BOOKED"
ERR_ROOM_DOUBLE_BOOKED = "ERR_ROOM_DOUBLE_BOOKED"
ERR_NEIGHBORHOOD_CAPACITY_FULL = "ERR_NEIGHBORHOOD_CAPACITY_FULL"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_DUPLICATE = "ERR_DUPLICATE"
ERR_AMENITY_LOCKED = "ERR_AMENITY_LOCKED"


# ---- HTTP status by error_id ----
HTTP_STATUS = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN: 403,
    ERR_NOT_FOUND: 404,
    ERR_INVALID_REQUEST: 422,
    ERR_INVALID_PAGINATION: 422,
    ERR_RESOURCE_TARGET_MISMATCH: 422,
    ERR_OUTSIDE_WORKDAY: 422,
    ERR_INVALID_STATE: 409,
    ERR_RESOURCE_NOT_BOOKABLE: 409,
    ERR_BOOKING_SUSPENDED: 409,
    ERR_TEAM_ZONING_VIOLATION: 409,
    ERR_RESERVATION_LIMIT_REACHED: 409,
    ERR_SEAT_DOUBLE_BOOKED: 409,
    ERR_ROOM_DOUBLE_BOOKED: 409,
    ERR_NEIGHBORHOOD_CAPACITY_FULL: 409,
    ERR_STALE_VERSION: 412,
    ERR_DUPLICATE: 409,
    ERR_AMENITY_LOCKED: 409,
}


def err(error_id: str, message: str = ""):
    raise APIError(error_id, HTTP_STATUS[error_id], message or error_id)
