HTTP_STATUS_CODES = {}
for _e in _401:
    HTTP_STATUS_CODES[_e] = 401
for _e in _403:
    HTTP_STATUS_CODES[_e] = 403
for _e in _404:
    HTTP_STATUS_CODES[_e] = 404
for _e in _412:
    HTTP_STATUS_CODES[_e] = 412
for _e in _422:
    HTTP_STATUS_CODES[_e] = 422
# Everything not otherwise banded is a 409 conflict.
for _e in ApiErrorId:
    HTTP_STATUS_CODES.setdefault(_e, 409)

# Also expose the mapping keyed by the plain string form.
HTTP_STATUS_CODES = {str(k.value): v for k, v in HTTP_STATUS_CODES.items()}

set_error_http_status_map(HTTP_STATUS_CODES)
