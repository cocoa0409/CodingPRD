# Register with the framework so validate_error() cross-checks HTTP statuses.
set_error_http_status_map({key.value: status for key, status in ERROR_HTTP_STATUS.items()})


def http_status_for(error_id) -> int:
    """Return the HTTP status the catalogue pairs with an error identifier."""
    key = error_id if isinstance(error_id, ApiErrorId) else ApiErrorId(str(error_id))
    return ERROR_HTTP_STATUS[key]
