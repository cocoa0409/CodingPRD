"""Error IDs and HTTP status mapping (PRD section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SOD_CONFLICT = "ERR_SOD_CONFLICT"
    ERR_TRAINING_NOT_CURRENT = "ERR_TRAINING_NOT_CURRENT"
    ERR_RECUSAL_OVERLAP = "ERR_RECUSAL_OVERLAP"
    ERR_PERIOD_OVERLAP = "ERR_PERIOD_OVERLAP"
    ERR_DUPLICATE_STATEMENT = "ERR_DUPLICATE_STATEMENT"
    ERR_GIFT_LIMIT_EXCEEDED = "ERR_GIFT_LIMIT_EXCEEDED"
    ERR_FILER_DELINQUENT = "ERR_FILER_DELINQUENT"
    ERR_GIFT_ANNUAL_LIMIT_EXCEEDED = "ERR_GIFT_ANNUAL_LIMIT_EXCEEDED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PERIOD_CLOSED = "ERR_PERIOD_CLOSED"
    ERR_INVALID_GIFT_KIND_PAYLOAD = "ERR_INVALID_GIFT_KIND_PAYLOAD"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SOD_CONFLICT: 409,
    ApiErrorId.ERR_TRAINING_NOT_CURRENT: 422,
    ApiErrorId.ERR_RECUSAL_OVERLAP: 409,
    ApiErrorId.ERR_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_DUPLICATE_STATEMENT: 409,
    ApiErrorId.ERR_GIFT_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_FILER_DELINQUENT: 402,
    ApiErrorId.ERR_GIFT_ANNUAL_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PERIOD_CLOSED: 409,
    ApiErrorId.ERR_INVALID_GIFT_KIND_PAYLOAD: 400,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
