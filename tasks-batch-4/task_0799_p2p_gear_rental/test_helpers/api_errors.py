"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LISTING_NOT_ACTIVE = "ERR_LISTING_NOT_ACTIVE"
    ERR_RENTER_NOT_VERIFIED = "ERR_RENTER_NOT_VERIFIED"
    ERR_LISTING_UNAVAILABLE = "ERR_LISTING_UNAVAILABLE"
    ERR_HANDOFF_SLOT_CONFLICT = "ERR_HANDOFF_SLOT_CONFLICT"
    ERR_HANDOFF_MISSING = "ERR_HANDOFF_MISSING"
    ERR_CONDITION_PHOTOS_REQUIRED = "ERR_CONDITION_PHOTOS_REQUIRED"
    ERR_EXTENSION_WINDOW_INVALID = "ERR_EXTENSION_WINDOW_INVALID"
    ERR_TRUST_TOO_LOW = "ERR_TRUST_TOO_LOW"
    ERR_STALE_LISTING_VERSION = "ERR_STALE_LISTING_VERSION"
    ERR_STALE_DEPOSIT_VERSION = "ERR_STALE_DEPOSIT_VERSION"
    ERR_INVALID_AWARD = "ERR_INVALID_AWARD"
    ERR_CLAIM_UNRESOLVED = "ERR_CLAIM_UNRESOLVED"
    ERR_RATING_NOT_ALLOWED = "ERR_RATING_NOT_ALLOWED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LISTING_NOT_ACTIVE: 409,
    ApiErrorId.ERR_RENTER_NOT_VERIFIED: 409,
    ApiErrorId.ERR_LISTING_UNAVAILABLE: 409,
    ApiErrorId.ERR_HANDOFF_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_HANDOFF_MISSING: 409,
    ApiErrorId.ERR_CONDITION_PHOTOS_REQUIRED: 422,
    ApiErrorId.ERR_EXTENSION_WINDOW_INVALID: 422,
    ApiErrorId.ERR_TRUST_TOO_LOW: 422,
    ApiErrorId.ERR_STALE_LISTING_VERSION: 412,
    ApiErrorId.ERR_STALE_DEPOSIT_VERSION: 412,
    ApiErrorId.ERR_INVALID_AWARD: 422,
    ApiErrorId.ERR_CLAIM_UNRESOLVED: 409,
    ApiErrorId.ERR_RATING_NOT_ALLOWED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
