"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NO_UNIT_AVAILABLE = "ERR_NO_UNIT_AVAILABLE"
    ERR_CUSTOMER_WINDOW_CONFLICT = "ERR_CUSTOMER_WINDOW_CONFLICT"
    ERR_PARTY_NOT_OPEN = "ERR_PARTY_NOT_OPEN"
    ERR_PARTY_LOCKED = "ERR_PARTY_LOCKED"
    ERR_NOT_COORDINATOR = "ERR_NOT_COORDINATOR"
    ERR_FIT_NOT_CLEARED = "ERR_FIT_NOT_CLEARED"
    ERR_ALTERATION_PENDING = "ERR_ALTERATION_PENDING"
    ERR_BALANCE_OUTSTANDING = "ERR_BALANCE_OUTSTANDING"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NO_UNIT_AVAILABLE: 409,
    ApiErrorId.ERR_CUSTOMER_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_PARTY_NOT_OPEN: 409,
    ApiErrorId.ERR_PARTY_LOCKED: 409,
    ApiErrorId.ERR_NOT_COORDINATOR: 403,
    ApiErrorId.ERR_FIT_NOT_CLEARED: 409,
    ApiErrorId.ERR_ALTERATION_PENDING: 409,
    ApiErrorId.ERR_BALANCE_OUTSTANDING: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
