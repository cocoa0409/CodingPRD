"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CHAPTER_SUSPENDED = "ERR_CHAPTER_SUSPENDED"
    ERR_PARTY_TIME_CONFLICT = "ERR_PARTY_TIME_CONFLICT"
    ERR_CHAPTER_DOUBLE_BOOK = "ERR_CHAPTER_DOUBLE_BOOK"
    ERR_PREFERENCE_NOT_ELIGIBLE = "ERR_PREFERENCE_NOT_ELIGIBLE"
    ERR_PREFERENCE_RANK_TAKEN = "ERR_PREFERENCE_RANK_TAKEN"
    ERR_ROUND_PHASE_MISMATCH = "ERR_ROUND_PHASE_MISMATCH"
    ERR_CHAPTER_QUOTA_FULL = "ERR_CHAPTER_QUOTA_FULL"
    ERR_DUPLICATE_INVITATION = "ERR_DUPLICATE_INVITATION"
    ERR_GPA_BELOW_MINIMUM = "ERR_GPA_BELOW_MINIMUM"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CHAPTER_SUSPENDED: 409,
    ApiErrorId.ERR_PARTY_TIME_CONFLICT: 409,
    ApiErrorId.ERR_CHAPTER_DOUBLE_BOOK: 409,
    ApiErrorId.ERR_PREFERENCE_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_PREFERENCE_RANK_TAKEN: 409,
    ApiErrorId.ERR_ROUND_PHASE_MISMATCH: 409,
    ApiErrorId.ERR_CHAPTER_QUOTA_FULL: 409,
    ApiErrorId.ERR_DUPLICATE_INVITATION: 409,
    ApiErrorId.ERR_GPA_BELOW_MINIMUM: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
