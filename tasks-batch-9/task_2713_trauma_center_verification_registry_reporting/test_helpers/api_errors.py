"""Error identifiers and their HTTP statuses, taken from the error code catalogue.

Registering the mapping with the framework lets ``validate_error`` cross-check the
HTTP status of every rejection without each test restating it.
"""

from prd_bench_local_runner.testing.validators import set_error_http_status_map


