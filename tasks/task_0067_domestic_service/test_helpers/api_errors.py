"""Error IDs and HTTP status mapping for the Domestic Service Dispatch API (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks HTTP status.
All values transcribed verbatim from PRD §5 Error Code Catalogue.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Authentication & authorization
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State & concurrency
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Ownership / business safety
    ERR_NOT_ASSIGNED = "ERR_NOT_ASSIGNED"
    ERR_CHECKIN_LOCATION_MISMATCH = "ERR_CHECKIN_LOCATION_MISMATCH"

    # Business referential
    ERR_AREA_NOT_SERVICED = "ERR_AREA_NOT_SERVICED"
    ERR_ITEM_INACTIVE = "ERR_ITEM_INACTIVE"

    # Business temporal
    ERR_LEAD_TIME_TOO_SHORT = "ERR_LEAD_TIME_TOO_SHORT"
    ERR_CANCEL_WINDOW_CLOSED = "ERR_CANCEL_WINDOW_CLOSED"
    ERR_MODIFY_WINDOW_CLOSED = "ERR_MODIFY_WINDOW_CLOSED"
    ERR_COMPLAINT_PERIOD_EXPIRED = "ERR_COMPLAINT_PERIOD_EXPIRED"
    ERR_DISPATCH_DEADLINE_PASSED = "ERR_DISPATCH_DEADLINE_PASSED"

    # Business constraint
    ERR_NO_ELIGIBLE_PERSONNEL = "ERR_NO_ELIGIBLE_PERSONNEL"
    ERR_HAS_ACTIVE_ASSIGNMENTS = "ERR_HAS_ACTIVE_ASSIGNMENTS"
    ERR_CHECKLIST_INCOMPLETE = "ERR_CHECKLIST_INCOMPLETE"
    ERR_RATING_NOT_ALLOWED = "ERR_RATING_NOT_ALLOWED"
    ERR_RATING_OUT_OF_RANGE = "ERR_RATING_OUT_OF_RANGE"
    ERR_RATING_ALREADY_EXISTS = "ERR_RATING_ALREADY_EXISTS"
    ERR_EXECUTION_ALREADY_EXISTS = "ERR_EXECUTION_ALREADY_EXISTS"
    ERR_CERT_REQUIREMENTS_NOT_MET = "ERR_CERT_REQUIREMENTS_NOT_MET"
    ERR_INSUFFICIENT_EVIDENCE = "ERR_INSUFFICIENT_EVIDENCE"
    ERR_PERSONNEL_NOT_ELIGIBLE = "ERR_PERSONNEL_NOT_ELIGIBLE"

    # Generic validation
    ERR_VALIDATION_ERROR = "ERR_VALIDATION_ERROR"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_NOT_ASSIGNED: 403,
    ApiErrorId.ERR_CHECKIN_LOCATION_MISMATCH: 422,
    ApiErrorId.ERR_AREA_NOT_SERVICED: 422,
    ApiErrorId.ERR_ITEM_INACTIVE: 422,
    ApiErrorId.ERR_LEAD_TIME_TOO_SHORT: 422,
    ApiErrorId.ERR_CANCEL_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_MODIFY_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_COMPLAINT_PERIOD_EXPIRED: 422,
    ApiErrorId.ERR_DISPATCH_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_PERSONNEL: 422,
    ApiErrorId.ERR_HAS_ACTIVE_ASSIGNMENTS: 422,
    ApiErrorId.ERR_CHECKLIST_INCOMPLETE: 422,
    ApiErrorId.ERR_RATING_NOT_ALLOWED: 422,
    ApiErrorId.ERR_RATING_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_RATING_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_EXECUTION_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_CERT_REQUIREMENTS_NOT_MET: 422,
    ApiErrorId.ERR_INSUFFICIENT_EVIDENCE: 422,
    ApiErrorId.ERR_PERSONNEL_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_VALIDATION_ERROR: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
