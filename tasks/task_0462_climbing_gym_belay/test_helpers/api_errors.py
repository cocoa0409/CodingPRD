"""Error IDs and HTTP status mapping (PRD section 5).

Registers the mapping with the framework so validate_error() can auto-check
HTTP status codes from the error_id alone.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WAIVER_INVALID = "ERR_WAIVER_INVALID"
    ERR_BELAY_CERT_REQUIRED = "ERR_BELAY_CERT_REQUIRED"
    ERR_BELAY_PREREQUISITE_MISSING = "ERR_BELAY_PREREQUISITE_MISSING"
    ERR_MEMBERSHIP_NOT_ACTIVE = "ERR_MEMBERSHIP_NOT_ACTIVE"
    ERR_MEMBERSHIP_FROZEN = "ERR_MEMBERSHIP_FROZEN"
    ERR_ENROLLMENT_WINDOW_CLOSED = "ERR_ENROLLMENT_WINDOW_CLOSED"
    ERR_CAPACITY_FULL = "ERR_CAPACITY_FULL"
    ERR_STALE_FACILITY_VERSION = "ERR_STALE_FACILITY_VERSION"
    ERR_STALE_CLINIC_VERSION = "ERR_STALE_CLINIC_VERSION"
    ERR_STALE_MEMBERSHIP_VERSION = "ERR_STALE_MEMBERSHIP_VERSION"
    ERR_STALE_RENTAL_VERSION = "ERR_STALE_RENTAL_VERSION"
    ERR_STALE_ROUTE_VERSION = "ERR_STALE_ROUTE_VERSION"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_DUPLICATE_WAIVER = "ERR_DUPLICATE_WAIVER"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WAIVER_INVALID: 422,
    ApiErrorId.ERR_BELAY_CERT_REQUIRED: 422,
    ApiErrorId.ERR_BELAY_PREREQUISITE_MISSING: 422,
    ApiErrorId.ERR_MEMBERSHIP_NOT_ACTIVE: 422,
    ApiErrorId.ERR_MEMBERSHIP_FROZEN: 409,
    ApiErrorId.ERR_ENROLLMENT_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_CAPACITY_FULL: 422,
    ApiErrorId.ERR_STALE_FACILITY_VERSION: 412,
    ApiErrorId.ERR_STALE_CLINIC_VERSION: 412,
    ApiErrorId.ERR_STALE_MEMBERSHIP_VERSION: 412,
    ApiErrorId.ERR_STALE_RENTAL_VERSION: 412,
    ApiErrorId.ERR_STALE_ROUTE_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_DUPLICATE_WAIVER: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
