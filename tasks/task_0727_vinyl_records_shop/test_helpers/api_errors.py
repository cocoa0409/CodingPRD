"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEPENDENCY_NOT_READY = "ERR_DEPENDENCY_NOT_READY"
    ERR_INVALID_GRADE_FOR_NEW = "ERR_INVALID_GRADE_FOR_NEW"
    ERR_INSPECTION_INCOMPLETE = "ERR_INSPECTION_INCOMPLETE"
    ERR_PREORDER_WINDOW_CLOSED = "ERR_PREORDER_WINDOW_CLOSED"
    ERR_PICKUP_CAPACITY_EXCEEDED = "ERR_PICKUP_CAPACITY_EXCEEDED"
    ERR_ALLOCATION_EXHAUSTED = "ERR_ALLOCATION_EXHAUSTED"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_INSUFFICIENT_CREDIT = "ERR_INSUFFICIENT_CREDIT"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SLOT_INACTIVE = "ERR_SLOT_INACTIVE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEPENDENCY_NOT_READY: 409,
    ApiErrorId.ERR_INVALID_GRADE_FOR_NEW: 422,
    ApiErrorId.ERR_INSPECTION_INCOMPLETE: 422,
    ApiErrorId.ERR_PREORDER_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_PICKUP_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_ALLOCATION_EXHAUSTED: 409,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_INSUFFICIENT_CREDIT: 402,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SLOT_INACTIVE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
