"""API error class and error-id constants — verbatim from SCAFFOLD §1.6 / PRD §5."""
from __future__ import annotations


# --- Error IDs (verbatim from SCAFFOLD §1.6 / PRD §5) ---
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_SITTER_NOT_CLEARED = "ERR_SITTER_NOT_CLEARED"
ERR_MEET_AND_GREET_REQUIRED = "ERR_MEET_AND_GREET_REQUIRED"
ERR_PET_OWNER_MISMATCH = "ERR_PET_OWNER_MISMATCH"
ERR_SITTER_TIME_CONFLICT = "ERR_SITTER_TIME_CONFLICT"
ERR_PET_TIME_CONFLICT = "ERR_PET_TIME_CONFLICT"
ERR_PRIMARY_CONTACT_EXISTS = "ERR_PRIMARY_CONTACT_EXISTS"
ERR_BG_CHECK_EXISTS = "ERR_BG_CHECK_EXISTS"
ERR_KEY_HANDOFF_EXISTS = "ERR_KEY_HANDOFF_EXISTS"
ERR_WALLET_INSUFFICIENT = "ERR_WALLET_INSUFFICIENT"
ERR_INVALID_APPROVED_AMOUNT = "ERR_INVALID_APPROVED_AMOUNT"
ERR_GPS_BOOKING_NOT_IN_PROGRESS = "ERR_GPS_BOOKING_NOT_IN_PROGRESS"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


_HTTP_FOR: dict[str, int] = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN: 403,
    ERR_NOT_FOUND: 404,
    ERR_FK_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 412,
    ERR_SITTER_NOT_CLEARED: 422,
    ERR_MEET_AND_GREET_REQUIRED: 422,
    ERR_PET_OWNER_MISMATCH: 422,
    ERR_SITTER_TIME_CONFLICT: 409,
    ERR_PET_TIME_CONFLICT: 409,
    ERR_PRIMARY_CONTACT_EXISTS: 409,
    ERR_BG_CHECK_EXISTS: 409,
    ERR_KEY_HANDOFF_EXISTS: 409,
    ERR_WALLET_INSUFFICIENT: 422,
    ERR_INVALID_APPROVED_AMOUNT: 422,
    ERR_GPS_BOOKING_NOT_IN_PROGRESS: 409,
    ERR_INVALID_REQUEST: 400,
}


class ApiError(Exception):
    def __init__(self, error_id: str, message: str, http_status: int | None = None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else _HTTP_FOR.get(error_id, 500)
