"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_STALE_VEHICLE_VERSION = "ERR_STALE_VEHICLE_VERSION"
    ERR_STALE_DEPARTMENT_VERSION = "ERR_STALE_DEPARTMENT_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VEHICLE_DISPOSED = "ERR_VEHICLE_DISPOSED"
    ERR_BAY_CLOSED = "ERR_BAY_CLOSED"
    ERR_OPEN_ACCIDENT_BLOCKS_WO = "ERR_OPEN_ACCIDENT_BLOCKS_WO"
    ERR_DISPOSAL_BLOCKED = "ERR_DISPOSAL_BLOCKED"
    ERR_BAY_TIME_CONFLICT = "ERR_BAY_TIME_CONFLICT"
    ERR_NO_VEHICLE_AVAILABLE = "ERR_NO_VEHICLE_AVAILABLE"
    ERR_ODOMETER_ROLLBACK = "ERR_ODOMETER_ROLLBACK"
    ERR_BELOW_RESERVE = "ERR_BELOW_RESERVE"
    ERR_SUBROGATION_INVALID = "ERR_SUBROGATION_INVALID"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_ASSIGNMENT_INVALID = "ERR_ASSIGNMENT_INVALID"
    ERR_BUDGET_EXCEEDED = "ERR_BUDGET_EXCEEDED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_STALE_VEHICLE_VERSION: 412,
    ApiErrorId.ERR_STALE_DEPARTMENT_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VEHICLE_DISPOSED: 409,
    ApiErrorId.ERR_BAY_CLOSED: 409,
    ApiErrorId.ERR_OPEN_ACCIDENT_BLOCKS_WO: 409,
    ApiErrorId.ERR_DISPOSAL_BLOCKED: 409,
    ApiErrorId.ERR_BAY_TIME_CONFLICT: 409,
    ApiErrorId.ERR_NO_VEHICLE_AVAILABLE: 409,
    ApiErrorId.ERR_ODOMETER_ROLLBACK: 409,
    ApiErrorId.ERR_BELOW_RESERVE: 409,
    ApiErrorId.ERR_SUBROGATION_INVALID: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_ASSIGNMENT_INVALID: 409,
    ApiErrorId.ERR_BUDGET_EXCEEDED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
