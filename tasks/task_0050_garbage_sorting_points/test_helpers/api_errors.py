"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks the HTTP
status code matching each error_id.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # --- Auth / generic ---
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_UNKNOWN_ROLE = "ERR_UNKNOWN_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # --- Business / domain ---
    ERR_RESIDENT_INACTIVE = "ERR_RESIDENT_INACTIVE"
    ERR_NO_ACTIVE_RULE = "ERR_NO_ACTIVE_RULE"
    ERR_WEIGHT_VOLUME_EXCLUSIVITY = "ERR_WEIGHT_VOLUME_EXCLUSIVITY"
    ERR_DISPOSAL_TIME_INVALID = "ERR_DISPOSAL_TIME_INVALID"
    ERR_APPEAL_WINDOW_EXPIRED = "ERR_APPEAL_WINDOW_EXPIRED"
    ERR_ITEM_UNAVAILABLE = "ERR_ITEM_UNAVAILABLE"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_RULE_ALREADY_ACTIVE = "ERR_RULE_ALREADY_ACTIVE"
    ERR_RULE_BACKDATING = "ERR_RULE_BACKDATING"
    ERR_RANKING_PERIOD_NOT_ENDED = "ERR_RANKING_PERIOD_NOT_ENDED"
    ERR_RANKING_PERIOD_OVERLAP = "ERR_RANKING_PERIOD_OVERLAP"
    ERR_RANKING_PERIOD_CLOSED = "ERR_RANKING_PERIOD_CLOSED"
    ERR_RANKING_EMPTY = "ERR_RANKING_EMPTY"
    ERR_DELIVERY_TERMINAL = "ERR_DELIVERY_TERMINAL"
    ERR_VIOLATION_REAPPEAL_LIMIT = "ERR_VIOLATION_REAPPEAL_LIMIT"


HTTP_STATUS_CODES: dict = {
    # Auth / generic
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_UNKNOWN_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,

    # Business / domain
    ApiErrorId.ERR_RESIDENT_INACTIVE: 422,
    ApiErrorId.ERR_NO_ACTIVE_RULE: 422,
    ApiErrorId.ERR_WEIGHT_VOLUME_EXCLUSIVITY: 422,
    ApiErrorId.ERR_DISPOSAL_TIME_INVALID: 422,
    ApiErrorId.ERR_APPEAL_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_ITEM_UNAVAILABLE: 422,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 409,
    ApiErrorId.ERR_RULE_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_RULE_BACKDATING: 422,
    ApiErrorId.ERR_RANKING_PERIOD_NOT_ENDED: 422,
    ApiErrorId.ERR_RANKING_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_RANKING_PERIOD_CLOSED: 409,
    ApiErrorId.ERR_RANKING_EMPTY: 422,
    ApiErrorId.ERR_DELIVERY_TERMINAL: 409,
    ApiErrorId.ERR_VIOLATION_REAPPEAL_LIMIT: 409,
}


# Register so validate_error() can auto-check HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
