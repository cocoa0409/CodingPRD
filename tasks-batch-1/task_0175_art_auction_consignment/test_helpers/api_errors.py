"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can auto-check
HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEPENDENCY_NOT_READY = "ERR_DEPENDENCY_NOT_READY"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PADDLE_INELIGIBLE = "ERR_PADDLE_INELIGIBLE"
    ERR_INVALID_LOT_TERMS = "ERR_INVALID_LOT_TERMS"
    ERR_BID_TOO_LOW = "ERR_BID_TOO_LOW"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_SALE_NOT_EMPTY_OF_OPEN_LOTS = "ERR_SALE_NOT_EMPTY_OF_OPEN_LOTS"
    ERR_LOTS_REQUIRED = "ERR_LOTS_REQUIRED"
    ERR_STATEMENT_ALREADY_PAID = "ERR_STATEMENT_ALREADY_PAID"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEPENDENCY_NOT_READY: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PADDLE_INELIGIBLE: 409,
    ApiErrorId.ERR_INVALID_LOT_TERMS: 422,
    ApiErrorId.ERR_BID_TOO_LOW: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_SALE_NOT_EMPTY_OF_OPEN_LOTS: 409,
    ApiErrorId.ERR_LOTS_REQUIRED: 409,
    ApiErrorId.ERR_STATEMENT_ALREADY_PAID: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
