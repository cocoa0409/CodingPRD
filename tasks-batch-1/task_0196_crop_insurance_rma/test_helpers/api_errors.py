"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework at import time so validate_error()
auto-checks the HTTP status for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_ADJUSTER_NOT_ASSIGNED = "ERR_ADJUSTER_NOT_ASSIGNED"
    ERR_HARVEST_PRICE_UNAVAILABLE = "ERR_HARVEST_PRICE_UNAVAILABLE"
    ERR_PROGRAM_NOT_OPEN = "ERR_PROGRAM_NOT_OPEN"
    ERR_PROGRAM_HAS_OPEN_ELECTIONS = "ERR_PROGRAM_HAS_OPEN_ELECTIONS"
    ERR_ACREAGE_DEADLINE_PASSED = "ERR_ACREAGE_DEADLINE_PASSED"
    ERR_ACREAGE_OVER_REPORTED = "ERR_ACREAGE_OVER_REPORTED"
    ERR_PP_ACRES_EXCEED_REPORTED = "ERR_PP_ACRES_EXCEED_REPORTED"
    ERR_ELECTION_ALREADY_REPORTED = "ERR_ELECTION_ALREADY_REPORTED"
    ERR_POLICY_HAS_NO_ELECTIONS = "ERR_POLICY_HAS_NO_ELECTIONS"
    ERR_POLICY_HAS_OPEN_CLAIMS = "ERR_POLICY_HAS_OPEN_CLAIMS"
    ERR_UNIT_NOT_REPORTED = "ERR_UNIT_NOT_REPORTED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_ADJUSTER_NOT_ASSIGNED: 409,
    ApiErrorId.ERR_HARVEST_PRICE_UNAVAILABLE: 409,
    ApiErrorId.ERR_PROGRAM_NOT_OPEN: 409,
    ApiErrorId.ERR_PROGRAM_HAS_OPEN_ELECTIONS: 409,
    ApiErrorId.ERR_ACREAGE_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_ACREAGE_OVER_REPORTED: 422,
    ApiErrorId.ERR_PP_ACRES_EXCEED_REPORTED: 422,
    ApiErrorId.ERR_ELECTION_ALREADY_REPORTED: 409,
    ApiErrorId.ERR_POLICY_HAS_NO_ELECTIONS: 409,
    ApiErrorId.ERR_POLICY_HAS_OPEN_CLAIMS: 409,
    ApiErrorId.ERR_UNIT_NOT_REPORTED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
