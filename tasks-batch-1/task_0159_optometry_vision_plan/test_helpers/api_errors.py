"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can cross-check the HTTP status automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WRONG_PROVIDER_ROLE = "ERR_WRONG_PROVIDER_ROLE"
    ERR_PRESCRIPTION_NOT_DISPENSABLE = "ERR_PRESCRIPTION_NOT_DISPENSABLE"
    ERR_REMAKE_WINDOW_CLOSED = "ERR_REMAKE_WINDOW_CLOSED"
    ERR_CARRIER_MISMATCH = "ERR_CARRIER_MISMATCH"
    ERR_BENEFIT_PERIOD_CLOSED = "ERR_BENEFIT_PERIOD_CLOSED"
    ERR_MEDICAL_BILLING_INELIGIBLE = "ERR_MEDICAL_BILLING_INELIGIBLE"
    ERR_STALE_ELIGIBILITY_VERSION = "ERR_STALE_ELIGIBILITY_VERSION"
    ERR_BENEFIT_EXHAUSTED = "ERR_BENEFIT_EXHAUSTED"
    ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WRONG_PROVIDER_ROLE: 422,
    ApiErrorId.ERR_PRESCRIPTION_NOT_DISPENSABLE: 409,
    ApiErrorId.ERR_REMAKE_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_CARRIER_MISMATCH: 422,
    ApiErrorId.ERR_BENEFIT_PERIOD_CLOSED: 409,
    ApiErrorId.ERR_MEDICAL_BILLING_INELIGIBLE: 422,
    ApiErrorId.ERR_STALE_ELIGIBILITY_VERSION: 412,
    ApiErrorId.ERR_BENEFIT_EXHAUSTED: 409,
    ApiErrorId.ERR_PAYMENT_EXCEEDS_BALANCE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
