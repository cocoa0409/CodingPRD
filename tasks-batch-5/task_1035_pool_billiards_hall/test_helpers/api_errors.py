"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_TABLE_NOT_ACTIVE = "ERR_TABLE_NOT_ACTIVE"
    ERR_DEPENDENT_STATE = "ERR_DEPENDENT_STATE"
    ERR_TABLE_TIME_CONFLICT = "ERR_TABLE_TIME_CONFLICT"
    ERR_EVENT_CAPACITY_UNAVAILABLE = "ERR_EVENT_CAPACITY_UNAVAILABLE"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_PRECONDITION_NOT_MET = "ERR_PRECONDITION_NOT_MET"
    ERR_INSUFFICIENT_FUNDS = "ERR_INSUFFICIENT_FUNDS"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_MEMBER_SUSPENDED = "ERR_MEMBER_SUSPENDED"
    ERR_STOCK_NEGATIVE = "ERR_STOCK_NEGATIVE"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_PAGINATION = "ERR_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TABLE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_DEPENDENT_STATE: 409,
    ApiErrorId.ERR_TABLE_TIME_CONFLICT: 409,
    ApiErrorId.ERR_EVENT_CAPACITY_UNAVAILABLE: 409,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_PRECONDITION_NOT_MET: 409,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS: 402,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_MEMBER_SUSPENDED: 409,
    ApiErrorId.ERR_STOCK_NEGATIVE: 422,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
