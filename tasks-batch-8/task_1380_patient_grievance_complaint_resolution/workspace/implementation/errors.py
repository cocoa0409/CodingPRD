def api_error(error_id, http_status, message):
    return ApiError(error_id, http_status, message)


def missing_context(message="X-User-ID or X-User-Role header missing or invalid"):
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, 400, message)


def unauthorized_role(message="Role not permitted for this endpoint, or entity-backed capability missing"):
    return ApiError(ERR_UNAUTHORIZED_ROLE, 403, message)


def identity_mismatch(message="Caller identity does not match the resource-bound identity"):
    return ApiError(ERR_IDENTITY_MISMATCH, 403, message)


def invalid_request(message="Request body failed schema validation"):
    return ApiError(ERR_INVALID_REQUEST, 400, message)


def invalid_enum(message="Enum field value outside its declared set"):
    return ApiError(ERR_INVALID_ENUM, 400, message)


def not_found(error_id, message):
    return ApiError(error_id, 404, message)


def stale_version(message="expected_case_version does not match current PatientCase.version"):
    return ApiError(ERR_STALE_VERSION, 412, message)
