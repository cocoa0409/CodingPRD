"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_ACCOUNT_NOT_ELIGIBLE = "ERR_ACCOUNT_NOT_ELIGIBLE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
    ERR_DISCLOSURE_NOT_ACKNOWLEDGED = "ERR_DISCLOSURE_NOT_ACKNOWLEDGED"
    ERR_APR_CAP_EXCEEDED = "ERR_APR_CAP_EXCEEDED"
    ERR_SOD_CONFLICT = "ERR_SOD_CONFLICT"
    ERR_GRADUATION_NOT_ELIGIBLE = "ERR_GRADUATION_NOT_ELIGIBLE"
    ERR_DEPOSIT_NOT_RELEASABLE = "ERR_DEPOSIT_NOT_RELEASABLE"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_DEPOSIT_CAP_EXCEEDED = "ERR_DEPOSIT_CAP_EXCEEDED"
    ERR_INSUFFICIENT_WALLET = "ERR_INSUFFICIENT_WALLET"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_ACCOUNT_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_QUOTE_EXPIRED: 409,
    ApiErrorId.ERR_DISCLOSURE_NOT_ACKNOWLEDGED: 409,
    ApiErrorId.ERR_APR_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_SOD_CONFLICT: 409,
    ApiErrorId.ERR_GRADUATION_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_DEPOSIT_NOT_RELEASABLE: 409,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_DEPOSIT_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_INSUFFICIENT_WALLET: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
