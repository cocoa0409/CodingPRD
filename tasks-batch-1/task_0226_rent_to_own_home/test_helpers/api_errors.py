"""Error IDs and HTTP status mapping (Rent-To-Own Home PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_REFERENCE_MISMATCH = "ERR_REFERENCE_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PROPERTY_NOT_AVAILABLE = "ERR_PROPERTY_NOT_AVAILABLE"
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_AGREEMENT_NOT_EXERCISED = "ERR_AGREEMENT_NOT_EXERCISED"
    ERR_OPTION_EXPIRED = "ERR_OPTION_EXPIRED"
    ERR_OPTION_NOT_YET_EXPIRED = "ERR_OPTION_NOT_YET_EXPIRED"
    ERR_OPTION_BLOCKED_BY_DEFAULT = "ERR_OPTION_BLOCKED_BY_DEFAULT"
    ERR_DEFAULT_THRESHOLD_NOT_MET = "ERR_DEFAULT_THRESHOLD_NOT_MET"
    ERR_CREDIT_SCORE_TOO_LOW = "ERR_CREDIT_SCORE_TOO_LOW"
    ERR_DUPLICATE_PERIOD = "ERR_DUPLICATE_PERIOD"
    ERR_PAYMENT_NOT_PENDING = "ERR_PAYMENT_NOT_PENDING"
    ERR_PAYMENT_NOT_LATE = "ERR_PAYMENT_NOT_LATE"
    ERR_TICKET_NOT_OPEN = "ERR_TICKET_NOT_OPEN"
    ERR_TICKET_NOT_APPROVED = "ERR_TICKET_NOT_APPROVED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_REFERENCE_MISMATCH: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PROPERTY_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_EXERCISED: 409,
    ApiErrorId.ERR_OPTION_EXPIRED: 409,
    ApiErrorId.ERR_OPTION_NOT_YET_EXPIRED: 409,
    ApiErrorId.ERR_OPTION_BLOCKED_BY_DEFAULT: 409,
    ApiErrorId.ERR_DEFAULT_THRESHOLD_NOT_MET: 409,
    ApiErrorId.ERR_CREDIT_SCORE_TOO_LOW: 409,
    ApiErrorId.ERR_DUPLICATE_PERIOD: 409,
    ApiErrorId.ERR_PAYMENT_NOT_PENDING: 409,
    ApiErrorId.ERR_PAYMENT_NOT_LATE: 409,
    ApiErrorId.ERR_TICKET_NOT_OPEN: 409,
    ApiErrorId.ERR_TICKET_NOT_APPROVED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
