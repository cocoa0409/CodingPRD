    INVALID_ENUM_VALUE = "ERR_INVALID_ENUM_VALUE"

    # Optimistic concurrency
    STALE_CASE_VERSION = "ERR_STALE_CASE_VERSION"
    STALE_CYCLE_VERSION = "ERR_STALE_CYCLE_VERSION"

    # State legality
    CASE_NOT_ABSTRACTABLE = "ERR_CASE_NOT_ABSTRACTABLE"
    CASE_ALREADY_LOCKED = "ERR_CASE_ALREADY_LOCKED"
    TRIAGE_ALREADY_REVIEWED = "ERR_TRIAGE_ALREADY_REVIEWED"
