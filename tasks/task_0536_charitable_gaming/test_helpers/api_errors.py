"""Error IDs and HTTP status mapping (Charitable Gaming PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_OCCASION_TIME_INVALID = "ERR_OCCASION_TIME_INVALID"
    ERR_REPORT_PERIOD_INVALID = "ERR_REPORT_PERIOD_INVALID"
    ERR_ALLOCATION_DATE_INVALID = "ERR_ALLOCATION_DATE_INVALID"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ORG_NOT_ELIGIBLE = "ERR_ORG_NOT_ELIGIBLE"
    ERR_LICENSE_NOT_ACTIVE = "ERR_LICENSE_NOT_ACTIVE"
    ERR_SUPPLIER_NOT_REGISTERED = "ERR_SUPPLIER_NOT_REGISTERED"
    ERR_EQUIPMENT_NOT_REGISTERED = "ERR_EQUIPMENT_NOT_REGISTERED"
    ERR_OCCASION_OVERLAP = "ERR_OCCASION_OVERLAP"
    ERR_EQUIPMENT_ALLOCATION_CONFLICT = "ERR_EQUIPMENT_ALLOCATION_CONFLICT"
    ERR_PRIZE_LIMIT_EXCEEDED = "ERR_PRIZE_LIMIT_EXCEEDED"
    ERR_CHARITABLE_MINIMUM_NOT_MET = "ERR_CHARITABLE_MINIMUM_NOT_MET"
    ERR_OUTSTANDING_VIOLATIONS = "ERR_OUTSTANDING_VIOLATIONS"
    ERR_DUPLICATE_SERIAL = "ERR_DUPLICATE_SERIAL"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_OCCASION_TIME_INVALID: 422,
    ApiErrorId.ERR_REPORT_PERIOD_INVALID: 422,
    ApiErrorId.ERR_ALLOCATION_DATE_INVALID: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ORG_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_LICENSE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SUPPLIER_NOT_REGISTERED: 409,
    ApiErrorId.ERR_EQUIPMENT_NOT_REGISTERED: 409,
    ApiErrorId.ERR_OCCASION_OVERLAP: 409,
    ApiErrorId.ERR_EQUIPMENT_ALLOCATION_CONFLICT: 409,
    ApiErrorId.ERR_PRIZE_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_CHARITABLE_MINIMUM_NOT_MET: 409,
    ApiErrorId.ERR_OUTSTANDING_VIOLATIONS: 409,
    ApiErrorId.ERR_DUPLICATE_SERIAL: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
