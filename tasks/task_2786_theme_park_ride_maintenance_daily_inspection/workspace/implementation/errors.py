def fail(error_id, message=None):
    """Raise the catalogued error with its canonical HTTP status."""
    raise ApiError(error_id, STATUS[error_id], message)


def invalid(message="The request payload is not valid."):
    raise ApiError(ERR_INVALID_REQUEST, 400, message)
