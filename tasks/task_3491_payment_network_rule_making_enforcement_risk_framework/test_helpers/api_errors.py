"""Error catalog: all 31 error_ids with the HTTP status PRD §5 assigns each.

Registers the mapping with the framework so validate_error() cross-checks the
HTTP status automatically at every call site.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth / authorization
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    # existence / uniqueness / shape
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    # state gates
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PARTICIPANT_NOT_ACTIVE = "ERR_PARTICIPANT_NOT_ACTIVE"
    ERR_ORIGINATOR_NOT_APPROVED = "ERR_ORIGINATOR_NOT_APPROVED"
    ERR_ENTRY_NOT_SETTLED = "ERR_ENTRY_NOT_SETTLED"
    # business safety / constraints
    ERR_ACCOUNT_VALIDATION_REQUIRED = "ERR_ACCOUNT_VALIDATION_REQUIRED"
    ERR_AUTHORIZATION_REQUIREMENT_VIOLATION = "ERR_AUTHORIZATION_REQUIREMENT_VIOLATION"
    ERR_RETURN_PARTICIPANT_CONFLICT = "ERR_RETURN_PARTICIPANT_CONFLICT"
    ERR_GUIDANCE_WINDOW_OVERLAP = "ERR_GUIDANCE_WINDOW_OVERLAP"
    ERR_PROPOSAL_NOT_EFFECTIVE = "ERR_PROPOSAL_NOT_EFFECTIVE"
    ERR_AUDIT_WINDOW_OVERLAP = "ERR_AUDIT_WINDOW_OVERLAP"
    ERR_VOTE_UNCHANGED = "ERR_VOTE_UNCHANGED"
    # temporal
    ERR_RETURN_WINDOW_EXPIRED = "ERR_RETURN_WINDOW_EXPIRED"
    ERR_COMMENT_PERIOD_TOO_SHORT = "ERR_COMMENT_PERIOD_TOO_SHORT"
    ERR_BALLOT_PERIOD_NOT_CLOSED = "ERR_BALLOT_PERIOD_NOT_CLOSED"
    ERR_EFFECTIVE_DATE_NOT_REACHED = "ERR_EFFECTIVE_DATE_NOT_REACHED"
    ERR_WINDOW_NOT_CLOSED = "ERR_WINDOW_NOT_CLOSED"
    ERR_WINDOW_CUTOFF_PASSED = "ERR_WINDOW_CUTOFF_PASSED"
    ERR_RESPONSE_DEADLINE_NOT_PASSED = "ERR_RESPONSE_DEADLINE_NOT_PASSED"
    ERR_AUDIT_NOT_STARTED = "ERR_AUDIT_NOT_STARTED"
    # fiscal
    ERR_SAME_DAY_ENTRY_LIMIT_EXCEEDED = "ERR_SAME_DAY_ENTRY_LIMIT_EXCEEDED"
    ERR_WINDOW_CAPACITY_EXCEEDED = "ERR_WINDOW_CAPACITY_EXCEEDED"
    ERR_EXPOSURE_LIMIT_EXCEEDED = "ERR_EXPOSURE_LIMIT_EXCEEDED"
    # attestation gates
    ERR_UNRESOLVED_ENFORCEMENT = "ERR_UNRESOLVED_ENFORCEMENT"
    ERR_AUDIT_REQUIRED = "ERR_AUDIT_REQUIRED"
    # optimistic concurrency (evaluated last)
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


