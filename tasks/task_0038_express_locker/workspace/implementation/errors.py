"""Error classes and error ID constants per PRD §5 / scaffold §1.6."""


class APIError(Exception):
    def __init__(self, error_id: str, message: str, http_status: int):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


# Auth & request
ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
ERR_INSUFFICIENT_PERMISSIONS = "ERR_INSUFFICIENT_PERMISSIONS"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

# Existence
ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"

# Machine & compartment
ERR_MACHINE_OFFLINE_DEGRADED = "ERR_MACHINE_OFFLINE_DEGRADED"
ERR_COMPARTMENT_ALREADY_RESERVED = "ERR_COMPARTMENT_ALREADY_RESERVED"
ERR_OCCUPIED_COMPARTMENT_NEEDS_CLEAR = "ERR_OCCUPIED_COMPARTMENT_NEEDS_CLEAR"
ERR_NO_COMPARTMENT_FITS = "ERR_NO_COMPARTMENT_FITS"
ERR_CAPACITY_BLOCKED = "ERR_CAPACITY_BLOCKED"

# Parcel state
ERR_PARCEL_STATE_CHANGED = "ERR_PARCEL_STATE_CHANGED"
ERR_RETRY_EXHAUSTED = "ERR_RETRY_EXHAUSTED"
ERR_WRONG_DEPOSIT_GRACE_EXPIRED = "ERR_WRONG_DEPOSIT_GRACE_EXPIRED"
ERR_NOT_COURIER_OWNER = "ERR_NOT_COURIER_OWNER"
ERR_INVALID_PICKUP_CODE = "ERR_INVALID_PICKUP_CODE"
ERR_FEE_PAYMENT_REQUIRED = "ERR_FEE_PAYMENT_REQUIRED"
ERR_FEE_ZERO_NOT_PAYABLE = "ERR_FEE_ZERO_NOT_PAYABLE"

# Courier
ERR_COURIER_BLACKLISTED = "ERR_COURIER_BLACKLISTED"
ERR_COURIER_RESTRICTED = "ERR_COURIER_RESTRICTED"

# Dispute & settlement
ERR_DISPUTE_ALREADY_RESOLVED = "ERR_DISPUTE_ALREADY_RESOLVED"
ERR_PERIOD_NOT_CLOSED = "ERR_PERIOD_NOT_CLOSED"
ERR_PENDING_FEES_IN_WINDOW = "ERR_PENDING_FEES_IN_WINDOW"
ERR_SETTLEMENT_LOCKED = "ERR_SETTLEMENT_LOCKED"

# Concurrency
ERR_DUPLICATE_PAYMENT_EVENT = "ERR_DUPLICATE_PAYMENT_EVENT"
ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


def bad_header(msg: str = "Missing or invalid X-User-ID / X-User-Role headers"):
    return APIError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, msg, 400)


def forbidden(msg: str = "Role not authorized for this endpoint"):
    return APIError(ERR_INSUFFICIENT_PERMISSIONS, msg, 403)


def invalid_request(msg: str = "Invalid request body"):
    return APIError(ERR_INVALID_REQUEST, msg, 400)


def not_found(msg: str = "Resource not found"):
    return APIError(ERR_RESOURCE_NOT_FOUND, msg, 404)


def version_conflict(msg: str = "OCC version mismatch"):
    return APIError(ERR_VERSION_CONFLICT, msg, 409)


def state_changed(msg: str = "Parcel not in expected state"):
    return APIError(ERR_PARCEL_STATE_CHANGED, msg, 409)
