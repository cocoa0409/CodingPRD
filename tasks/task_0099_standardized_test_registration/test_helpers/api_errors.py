"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_SESSION_VERSION = "ERR_STALE_SESSION_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NOT_504_IEP_ELIGIBLE = "ERR_NOT_504_IEP_ELIGIBLE"
    ERR_ID_VERIFICATION_FAILED = "ERR_ID_VERIFICATION_FAILED"
    ERR_ACCOMMODATION_NOT_BINDABLE = "ERR_ACCOMMODATION_NOT_BINDABLE"
    ERR_SESSION_WINDOW_OVERLAP = "ERR_SESSION_WINDOW_OVERLAP"
    ERR_CANDIDATE_SCHEDULE_CONFLICT = "ERR_CANDIDATE_SCHEDULE_CONFLICT"
    ERR_SESSION_CLOSED = "ERR_SESSION_CLOSED"
    ERR_SESSION_FULL = "ERR_SESSION_FULL"
    ERR_ACCOMMODATED_FULL = "ERR_ACCOMMODATED_FULL"
    ERR_REFUND_WINDOW_CLOSED = "ERR_REFUND_WINDOW_CLOSED"
    ERR_OFFER_NO_LONGER_VALID = "ERR_OFFER_NO_LONGER_VALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_STALE_SESSION_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NOT_504_IEP_ELIGIBLE: 422,
    ApiErrorId.ERR_ID_VERIFICATION_FAILED: 422,
    ApiErrorId.ERR_ACCOMMODATION_NOT_BINDABLE: 409,
    ApiErrorId.ERR_SESSION_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_CANDIDATE_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_SESSION_CLOSED: 409,
    ApiErrorId.ERR_SESSION_FULL: 409,
    ApiErrorId.ERR_ACCOMMODATED_FULL: 409,
    ApiErrorId.ERR_REFUND_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_OFFER_NO_LONGER_VALID: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
