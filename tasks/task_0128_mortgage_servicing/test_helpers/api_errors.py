"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Existence — PRD §2.7
    ERR_LOAN_NOT_FOUND = "ERR_LOAN_NOT_FOUND"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"

    # State / concurrency — PRD §2.5, §2.6
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CONCURRENT_UPDATE = "ERR_CONCURRENT_UPDATE"
    ERR_ESCROW_ANALYSIS_CONFLICT = "ERR_ESCROW_ANALYSIS_CONFLICT"
    ERR_FORBEARANCE_PLAN_EXISTS = "ERR_FORBEARANCE_PLAN_EXISTS"
    ERR_FORECLOSURE_CASE_EXISTS = "ERR_FORECLOSURE_CASE_EXISTS"
    ERR_MEDIATION_ALREADY_OPEN = "ERR_MEDIATION_ALREADY_OPEN"

    # Compliance / safety — PRD §3.6
    ERR_NOI_WINDOW_NOT_ELAPSED = "ERR_NOI_WINDOW_NOT_ELAPSED"
    ERR_AUCTION_NOTICE_VIOLATION = "ERR_AUCTION_NOTICE_VIOLATION"
    ERR_MEDIATION_WINDOW_CLOSED = "ERR_MEDIATION_WINDOW_CLOSED"
    ERR_HARDSHIP_AFFIDAVIT_MISSING = "ERR_HARDSHIP_AFFIDAVIT_MISSING"
    ERR_REINSTATEMENT_CUTOFF = "ERR_REINSTATEMENT_CUTOFF"

    # Eligibility / formula — PRD §3.5, §3.7
    ERR_PMI_LTV_TOO_HIGH = "ERR_PMI_LTV_TOO_HIGH"
    ERR_PMI_HISTORY_INSUFFICIENT = "ERR_PMI_HISTORY_INSUFFICIENT"
    ERR_HAMP_NOT_A_REDUCTION = "ERR_HAMP_NOT_A_REDUCTION"
    ERR_HAMP_AFFORDABILITY_FLOOR = "ERR_HAMP_AFFORDABILITY_FLOOR"
    ERR_HAMP_STALE_OFFER = "ERR_HAMP_STALE_OFFER"

    # Inputs / fiscal — PRD §3.2, §3.3, §3.4, §3.6
    ERR_ESCROW_BASELINE_MISMATCH = "ERR_ESCROW_BASELINE_MISMATCH"
    ERR_PAYMENT_AMOUNT_INVALID = "ERR_PAYMENT_AMOUNT_INVALID"
    ERR_REINSTATEMENT_INSUFFICIENT = "ERR_REINSTATEMENT_INSUFFICIENT"
    ERR_INSUFFICIENT_ESCROW = "ERR_INSUFFICIENT_ESCROW"
    ERR_FORBEARANCE_DATE_INVALID = "ERR_FORBEARANCE_DATE_INVALID"


# PRD §5 Error Code Catalogue — http status per error_id.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_LOAN_NOT_FOUND: 404,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CONCURRENT_UPDATE: 409,
    ApiErrorId.ERR_ESCROW_ANALYSIS_CONFLICT: 409,
    ApiErrorId.ERR_FORBEARANCE_PLAN_EXISTS: 409,
    ApiErrorId.ERR_FORECLOSURE_CASE_EXISTS: 409,
    ApiErrorId.ERR_MEDIATION_ALREADY_OPEN: 409,
    ApiErrorId.ERR_NOI_WINDOW_NOT_ELAPSED: 422,
    ApiErrorId.ERR_AUCTION_NOTICE_VIOLATION: 422,
    ApiErrorId.ERR_MEDIATION_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_HARDSHIP_AFFIDAVIT_MISSING: 422,
    ApiErrorId.ERR_REINSTATEMENT_CUTOFF: 422,
    ApiErrorId.ERR_PMI_LTV_TOO_HIGH: 422,
    ApiErrorId.ERR_PMI_HISTORY_INSUFFICIENT: 422,
    ApiErrorId.ERR_HAMP_NOT_A_REDUCTION: 422,
    ApiErrorId.ERR_HAMP_AFFORDABILITY_FLOOR: 422,
    ApiErrorId.ERR_HAMP_STALE_OFFER: 422,
    ApiErrorId.ERR_ESCROW_BASELINE_MISMATCH: 422,
    ApiErrorId.ERR_PAYMENT_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_REINSTATEMENT_INSUFFICIENT: 422,
    ApiErrorId.ERR_INSUFFICIENT_ESCROW: 422,
    ApiErrorId.ERR_FORBEARANCE_DATE_INVALID: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
