"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_AUTOMATIC_STAY = "ERR_AUTOMATIC_STAY"
    ERR_ACTIVE_DISPUTE = "ERR_ACTIVE_DISPUTE"
    ERR_VALIDATION_PERIOD_ACTIVE = "ERR_VALIDATION_PERIOD_ACTIVE"
    ERR_NOTICE_COOLDOWN = "ERR_NOTICE_COOLDOWN"
    ERR_DEMAND_NOTICE_REQUIRED = "ERR_DEMAND_NOTICE_REQUIRED"
    ERR_LIEN_REQUIRED = "ERR_LIEN_REQUIRED"
    ERR_LIEN_MINIMUM_NOT_MET = "ERR_LIEN_MINIMUM_NOT_MET"
    ERR_PLAN_OVERLAP = "ERR_PLAN_OVERLAP"
    ERR_PLAN_NOT_BREACHABLE = "ERR_PLAN_NOT_BREACHABLE"
    ERR_NOT_DELINQUENT = "ERR_NOT_DELINQUENT"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_PERIOD_INVALID = "ERR_PERIOD_INVALID"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_AUTOMATIC_STAY: 403,
    ApiErrorId.ERR_ACTIVE_DISPUTE: 409,
    ApiErrorId.ERR_VALIDATION_PERIOD_ACTIVE: 409,
    ApiErrorId.ERR_NOTICE_COOLDOWN: 409,
    ApiErrorId.ERR_DEMAND_NOTICE_REQUIRED: 409,
    ApiErrorId.ERR_LIEN_REQUIRED: 409,
    ApiErrorId.ERR_LIEN_MINIMUM_NOT_MET: 422,
    ApiErrorId.ERR_PLAN_OVERLAP: 409,
    ApiErrorId.ERR_PLAN_NOT_BREACHABLE: 409,
    ApiErrorId.ERR_NOT_DELINQUENT: 409,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_PERIOD_INVALID: 422,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
