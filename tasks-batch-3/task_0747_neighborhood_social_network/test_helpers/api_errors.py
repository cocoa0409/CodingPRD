"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_TARGET_VERSION = "ERR_STALE_TARGET_VERSION"
    ERR_RESIDENT_SUSPENDED = "ERR_RESIDENT_SUSPENDED"
    ERR_NOT_VERIFIED_IN_NEIGHBORHOOD = "ERR_NOT_VERIFIED_IN_NEIGHBORHOOD"
    ERR_NEIGHBORHOOD_EMERGENCY_LOCKDOWN = "ERR_NEIGHBORHOOD_EMERGENCY_LOCKDOWN"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"
    ERR_EFFECTIVE_FROM_IN_PAST = "ERR_EFFECTIVE_FROM_IN_PAST"
    ERR_NOTICE_WINDOW_OVERLAP = "ERR_NOTICE_WINDOW_OVERLAP"
    ERR_GROUP_EVENT_CAPACITY = "ERR_GROUP_EVENT_CAPACITY"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_LOCATION_OUTSIDE_GEOFENCE = "ERR_LOCATION_OUTSIDE_GEOFENCE"
    ERR_INVALID_BUDGET = "ERR_INVALID_BUDGET"
    ERR_INVALID_PRICE = "ERR_INVALID_PRICE"
    ERR_DUPLICATE_FLAG = "ERR_DUPLICATE_FLAG"
    ERR_CANNOT_RESERVE_OWN = "ERR_CANNOT_RESERVE_OWN"
    ERR_EVENT_FULL = "ERR_EVENT_FULL"
    ERR_AD_EXHAUSTED = "ERR_AD_EXHAUSTED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_TARGET_VERSION: 412,
    ApiErrorId.ERR_RESIDENT_SUSPENDED: 403,
    ApiErrorId.ERR_NOT_VERIFIED_IN_NEIGHBORHOOD: 403,
    ApiErrorId.ERR_NEIGHBORHOOD_EMERGENCY_LOCKDOWN: 409,
    ApiErrorId.ERR_INVALID_TIME_WINDOW: 422,
    ApiErrorId.ERR_EFFECTIVE_FROM_IN_PAST: 422,
    ApiErrorId.ERR_NOTICE_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_GROUP_EVENT_CAPACITY: 409,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_LOCATION_OUTSIDE_GEOFENCE: 422,
    ApiErrorId.ERR_INVALID_BUDGET: 422,
    ApiErrorId.ERR_INVALID_PRICE: 422,
    ApiErrorId.ERR_DUPLICATE_FLAG: 409,
    ApiErrorId.ERR_CANNOT_RESERVE_OWN: 409,
    ApiErrorId.ERR_EVENT_FULL: 409,
    ApiErrorId.ERR_AD_EXHAUSTED: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
