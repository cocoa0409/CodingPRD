"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_FORBIDDEN_OWNERSHIP = "ERR_FORBIDDEN_OWNERSHIP"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_MISSING_FIELD = "ERR_MISSING_FIELD"
    ERR_OUT_OF_RANGE = "ERR_OUT_OF_RANGE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_BILL_NOT_PAYABLE = "ERR_BILL_NOT_PAYABLE"
    ERR_APPEAL_NOT_REVIEWABLE = "ERR_APPEAL_NOT_REVIEWABLE"
    ERR_INSPECTION_ALREADY_COMPLETED = "ERR_INSPECTION_ALREADY_COMPLETED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ACCOUNT_PARCEL_MISMATCH = "ERR_ACCOUNT_PARCEL_MISMATCH"
    ERR_APPEAL_BILL_MISMATCH = "ERR_APPEAL_BILL_MISMATCH"
    ERR_DUPLICATE_PARCEL = "ERR_DUPLICATE_PARCEL"
    ERR_PARCEL_EXEMPT = "ERR_PARCEL_EXEMPT"
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_CREDIT_WINDOW_OVERLAP = "ERR_CREDIT_WINDOW_OVERLAP"
    ERR_BILL_PERIOD_OVERLAP = "ERR_BILL_PERIOD_OVERLAP"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_FORBIDDEN_OWNERSHIP: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_MISSING_FIELD: 400,
    ApiErrorId.ERR_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_BILL_NOT_PAYABLE: 409,
    ApiErrorId.ERR_APPEAL_NOT_REVIEWABLE: 409,
    ApiErrorId.ERR_INSPECTION_ALREADY_COMPLETED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ACCOUNT_PARCEL_MISMATCH: 422,
    ApiErrorId.ERR_APPEAL_BILL_MISMATCH: 422,
    ApiErrorId.ERR_DUPLICATE_PARCEL: 409,
    ApiErrorId.ERR_PARCEL_EXEMPT: 409,
    ApiErrorId.ERR_INVALID_PERIOD: 422,
    ApiErrorId.ERR_CREDIT_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_BILL_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_OVERPAYMENT: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
