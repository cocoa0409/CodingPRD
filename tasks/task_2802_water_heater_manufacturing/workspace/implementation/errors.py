DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing, empty or name an undeclared role.",
    "ERR_FORBIDDEN_ROLE": "The caller's role is not permitted on this endpoint.",
    "ERR_SUPPLIER_SCOPE_VIOLATION": "A supplier representative may only read its own supplier scope.",
    "ERR_INVALID_REQUEST": "The request payload failed schema validation.",
    "ERR_STALE_PARENT_VERSION": "The pinned parent version does not match the current version.",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        self.error_id = error_id
        self.http_status = ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize() + "."
        )
        super().__init__(self.message)


def bad_request(message=None):
    return ApiError("ERR_INVALID_REQUEST", message)
