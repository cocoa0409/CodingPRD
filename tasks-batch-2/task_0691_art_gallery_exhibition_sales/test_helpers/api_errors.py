"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() automatically cross-checks the HTTP status code.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ARTIST_SUSPENDED = "ERR_ARTIST_SUSPENDED"
    ERR_INSUFFICIENT_COVERAGE = "ERR_INSUFFICIENT_COVERAGE"
    ERR_SCHEDULE_CONFLICT = "ERR_SCHEDULE_CONFLICT"
    ERR_WALL_CAPACITY_EXCEEDED = "ERR_WALL_CAPACITY_EXCEEDED"
    ERR_RSVP_CLOSED = "ERR_RSVP_CLOSED"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"
    ERR_NO_PAYABLE_BALANCE = "ERR_NO_PAYABLE_BALANCE"
    ERR_PLAN_SALE_NOT_INVOICED = "ERR_PLAN_SALE_NOT_INVOICED"
    ERR_LEASE_ARTWORK_NOT_OUT = "ERR_LEASE_ARTWORK_NOT_OUT"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"
    ERR_DUPLICATE_PROVENANCE_EVENT = "ERR_DUPLICATE_PROVENANCE_EVENT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ARTIST_SUSPENDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_COVERAGE: 409,
    ApiErrorId.ERR_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_WALL_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_RSVP_CLOSED: 409,
    ApiErrorId.ERR_OVERPAYMENT: 409,
    ApiErrorId.ERR_NO_PAYABLE_BALANCE: 409,
    ApiErrorId.ERR_PLAN_SALE_NOT_INVOICED: 409,
    ApiErrorId.ERR_LEASE_ARTWORK_NOT_OUT: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
    ApiErrorId.ERR_DUPLICATE_PROVENANCE_EVENT: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
