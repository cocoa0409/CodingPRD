"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() auto-checks the
HTTP status code from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ACTION_ALREADY_CLOSED = "ERR_ACTION_ALREADY_CLOSED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ATTORNEY_NOT_ACTIVE = "ERR_ATTORNEY_NOT_ACTIVE"
    ERR_FOREIGN_REQUIRES_ATTORNEY = "ERR_FOREIGN_REQUIRES_ATTORNEY"
    ERR_TEAS_PLUS_REQUIRES_PREAPPROVED = "ERR_TEAS_PLUS_REQUIRES_PREAPPROVED"
    ERR_NO_GOODS_SERVICES = "ERR_NO_GOODS_SERVICES"
    ERR_PROCEEDING_TARGET_INVALID = "ERR_PROCEEDING_TARGET_INVALID"
    ERR_OPPOSITION_WINDOW_CLOSED = "ERR_OPPOSITION_WINDOW_CLOSED"
    ERR_RESPONSE_DEADLINE_PASSED = "ERR_RESPONSE_DEADLINE_PASSED"
    ERR_SOU_NOT_PERMITTED = "ERR_SOU_NOT_PERMITTED"
    ERR_MAINTENANCE_WINDOW_NOT_OPEN = "ERR_MAINTENANCE_WINDOW_NOT_OPEN"
    ERR_MADRID_COUNTRIES_INVALID = "ERR_MADRID_COUNTRIES_INVALID"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_DUPLICATE_BAR_NUMBER = "ERR_DUPLICATE_BAR_NUMBER"
    ERR_DUPLICATE_NICE_CLASS = "ERR_DUPLICATE_NICE_CLASS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ACTION_ALREADY_CLOSED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ATTORNEY_NOT_ACTIVE: 422,
    ApiErrorId.ERR_FOREIGN_REQUIRES_ATTORNEY: 422,
    ApiErrorId.ERR_TEAS_PLUS_REQUIRES_PREAPPROVED: 422,
    ApiErrorId.ERR_NO_GOODS_SERVICES: 422,
    ApiErrorId.ERR_PROCEEDING_TARGET_INVALID: 422,
    ApiErrorId.ERR_OPPOSITION_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_RESPONSE_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_SOU_NOT_PERMITTED: 422,
    ApiErrorId.ERR_MAINTENANCE_WINDOW_NOT_OPEN: 422,
    ApiErrorId.ERR_MADRID_COUNTRIES_INVALID: 422,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_DUPLICATE_BAR_NUMBER: 409,
    ApiErrorId.ERR_DUPLICATE_NICE_CLASS: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
