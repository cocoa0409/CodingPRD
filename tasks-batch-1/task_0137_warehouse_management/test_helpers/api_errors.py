"""Error IDs and HTTP status mapping (Warehouse Management PRD Section 5).

Registers the mapping with the framework so validate_error() auto-checks HTTP
status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_WAVE_VERSION = "ERR_STALE_WAVE_VERSION"
    ERR_STALE_LPN_VERSION = "ERR_STALE_LPN_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CROSS_ENTITY_STATE = "ERR_CROSS_ENTITY_STATE"
    ERR_DUPLICATE_CODE = "ERR_DUPLICATE_CODE"
    ERR_LOCATION_CAPACITY = "ERR_LOCATION_CAPACITY"
    ERR_PICKFACE_TAKEN = "ERR_PICKFACE_TAKEN"
    ERR_REPLEN_NOT_NEEDED = "ERR_REPLEN_NOT_NEEDED"
    ERR_INSUFFICIENT_AVAILABLE = "ERR_INSUFFICIENT_AVAILABLE"
    ERR_ASN_LINES_OPEN = "ERR_ASN_LINES_OPEN"
    ERR_NO_PUTAWAY_LOCATION = "ERR_NO_PUTAWAY_LOCATION"
    ERR_NO_REPLEN_SOURCE = "ERR_NO_REPLEN_SOURCE"
    ERR_VALIDATION_LIGHT_REQUIRED = "ERR_VALIDATION_LIGHT_REQUIRED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_WAVE_VERSION: 412,
    ApiErrorId.ERR_STALE_LPN_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_CROSS_ENTITY_STATE: 409,
    ApiErrorId.ERR_DUPLICATE_CODE: 409,
    ApiErrorId.ERR_LOCATION_CAPACITY: 409,
    ApiErrorId.ERR_PICKFACE_TAKEN: 409,
    ApiErrorId.ERR_REPLEN_NOT_NEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_AVAILABLE: 409,
    ApiErrorId.ERR_ASN_LINES_OPEN: 409,
    ApiErrorId.ERR_NO_PUTAWAY_LOCATION: 409,
    ApiErrorId.ERR_NO_REPLEN_SOURCE: 409,
    ApiErrorId.ERR_VALIDATION_LIGHT_REQUIRED: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
