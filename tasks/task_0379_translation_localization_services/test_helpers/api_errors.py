"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CLIENT_SUSPENDED = "ERR_CLIENT_SUSPENDED"
    ERR_NO_JOBS = "ERR_NO_JOBS"
    ERR_EMPTY_ANALYSIS = "ERR_EMPTY_ANALYSIS"
    ERR_PROJECT_NOT_APPROVED = "ERR_PROJECT_NOT_APPROVED"
    ERR_PROJECT_NOT_DELIVERED = "ERR_PROJECT_NOT_DELIVERED"
    ERR_PROJECT_HAS_INVOICE = "ERR_PROJECT_HAS_INVOICE"
    ERR_LINGUIST_INACTIVE = "ERR_LINGUIST_INACTIVE"
    ERR_LINGUIST_NOT_QUALIFIED = "ERR_LINGUIST_NOT_QUALIFIED"
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
    ERR_NO_REVIEWER_ASSIGNED = "ERR_NO_REVIEWER_ASSIGNED"
    ERR_NOT_ASSIGNED_TRANSLATOR = "ERR_NOT_ASSIGNED_TRANSLATOR"
    ERR_THROUGHPUT_EXCEEDED = "ERR_THROUGHPUT_EXCEEDED"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CLIENT_SUSPENDED: 409,
    ApiErrorId.ERR_NO_JOBS: 409,
    ApiErrorId.ERR_EMPTY_ANALYSIS: 409,
    ApiErrorId.ERR_PROJECT_NOT_APPROVED: 409,
    ApiErrorId.ERR_PROJECT_NOT_DELIVERED: 409,
    ApiErrorId.ERR_PROJECT_HAS_INVOICE: 409,
    ApiErrorId.ERR_LINGUIST_INACTIVE: 409,
    ApiErrorId.ERR_LINGUIST_NOT_QUALIFIED: 409,
    ApiErrorId.ERR_SEGREGATION_VIOLATION: 409,
    ApiErrorId.ERR_NO_REVIEWER_ASSIGNED: 409,
    ApiErrorId.ERR_NOT_ASSIGNED_TRANSLATOR: 409,
    ApiErrorId.ERR_THROUGHPUT_EXCEEDED: 409,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Build a plain-string map for the framework (validate_error compares against
# the actual error_id string returned by the API).
_STR_STATUS_MAP = {k.value: v for k, v in HTTP_STATUS_CODES.items()}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(_STR_STATUS_MAP)
