    SAMPLE_NOT_FOUND = "ERR_SAMPLE_NOT_FOUND"
    PUBLICATION_NOT_FOUND = "ERR_PUBLICATION_NOT_FOUND"
    NOTIFICATION_NOT_FOUND = "ERR_NOTIFICATION_NOT_FOUND"
    REPLACEMENT_ORDER_NOT_FOUND = "ERR_REPLACEMENT_ORDER_NOT_FOUND"
    STREET_PROJECT_NOT_FOUND = "ERR_STREET_PROJECT_NOT_FOUND"
    FUNDING_SOURCE_NOT_FOUND = "ERR_FUNDING_SOURCE_NOT_FOUND"
    PROGRESS_REPORT_NOT_FOUND = "ERR_PROGRESS_REPORT_NOT_FOUND"

