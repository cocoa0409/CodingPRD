"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_FORBIDDEN_OWNERSHIP = "ERR_FORBIDDEN_OWNERSHIP"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CLEANER_NOT_CLEARED = "ERR_CLEANER_NOT_CLEARED"
    ERR_RECLEAN_NOT_ELIGIBLE = "ERR_RECLEAN_NOT_ELIGIBLE"
    ERR_RECLEAN_WINDOW_CLOSED = "ERR_RECLEAN_WINDOW_CLOSED"
    ERR_ADDON_NOT_ALLOWED = "ERR_ADDON_NOT_ALLOWED"
    ERR_ADDRESS_ARCHIVED = "ERR_ADDRESS_ARCHIVED"
    ERR_NO_CLEANER_AVAILABLE = "ERR_NO_CLEANER_AVAILABLE"
    ERR_CLEANER_DOUBLE_BOOKED = "ERR_CLEANER_DOUBLE_BOOKED"
    ERR_ADDRESS_DOUBLE_BOOKED = "ERR_ADDRESS_DOUBLE_BOOKED"
    ERR_TIP_NOT_ALLOWED = "ERR_TIP_NOT_ALLOWED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_FORBIDDEN_OWNERSHIP: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CLEANER_NOT_CLEARED: 409,
    ApiErrorId.ERR_RECLEAN_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_RECLEAN_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_ADDON_NOT_ALLOWED: 422,
    ApiErrorId.ERR_ADDRESS_ARCHIVED: 409,
    ApiErrorId.ERR_NO_CLEANER_AVAILABLE: 409,
    ApiErrorId.ERR_CLEANER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_ADDRESS_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_TIP_NOT_ALLOWED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
