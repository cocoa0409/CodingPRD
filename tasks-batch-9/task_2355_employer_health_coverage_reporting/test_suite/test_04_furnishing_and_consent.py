def test_electronic_furnish_refused_while_consent_is_pending(api):
    """PRD §3.7: "Electronic delivery additionally requires the employee to hold a consent at
    `GRANTED`, and the absence of one is refused with `ERR_CONSENT_NOT_GRANTED`."
    PRD §2.6: "Electronic furnishing requires a `GRANTED` consent for the employee —
    `ERR_CONSENT_NOT_GRANTED` (409), on furnish."
    PRD §3.7: "A new consent starts with `consent_status` of `PENDING`, `grant_count` of 0,
    and null `granted_at` and `withdrawn_at`."

    Design: Difficulty/cross_entity_state_dependency/electronic_furnish_requires_granted_consent
    """
    ctx = _pending_consent_statement(api)
    assert_furnishing_consent(ctx["consent"], consent_status="PENDING", grant_count=0)

    response = api.furnish_form_1095c(
        ctx["form"]["id"], factories.furnish_payload("ELECTRONIC"), PREPARER_2
    )
    validate_error(response, ApiErrorId.ERR_CONSENT_NOT_GRANTED, 409)

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert form["furnishing_status"] == "NOT_FURNISHED", (
        "the refused delivery must leave the furnishing dimension untouched, got "
        f"{form['furnishing_status']!r}"
    )


def test_electronic_furnish_succeeds_after_the_employee_grants_consent(api):
    """PRD §3.7: "Electronic delivery additionally requires the employee to hold a consent at
    `GRANTED`, and the absence of one is refused with `ERR_CONSENT_NOT_GRANTED`."
    PRD §3.7: "Granting takes the consent from `PENDING` to `GRANTED`, or from `WITHDRAWN`
    back to `GRANTED`; either way it stamps `granted_at` from the logical clock and increments
    `grant_count`, so the counter records how many rounds the consent has been through."
    PRD §3.7: "A successful delivery stamps `furnished_at` and `furnished_by_user_id`."

    Design: Difficulty/cross_entity_state_dependency/electronic_furnish_requires_granted_consent
    """
    ctx = _pending_consent_statement(api)
    employee_headers = make_employee_self_service_headers(ctx["employee"]["id"])

    granted = get_success_data(
        api.grant_furnishing_consent(ctx["consent"]["id"], employee_headers)
    )
    assert_furnishing_consent(granted, consent_status="GRANTED", grant_count=1)
    assert granted["granted_at"].startswith("2027-01-15"), (
        "granted_at is stamped from the logical clock, which stands at 2027-01-15, got "
        f"{granted['granted_at']!r}"
    )

    fixtures.furnish_form(api, ctx["form"]["id"], "ELECTRONIC")

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(
        form,
        furnishing_status="FURNISHED_ELECTRONIC",
        filing_status="NOT_FILED",
        furnished_by_user_id="preparer-2",
        late_furnishing_penalty_cents=0,
    )
    assert is_iso8601_timestamp(form["furnished_at"]), (
        f"a successful delivery stamps furnished_at, got {form['furnished_at']!r}"
    )


