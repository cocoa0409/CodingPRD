"""Error catalog for the Innocence Case Review API.

Every error id and its HTTP status is pinned by PRD section 5 and the
SCAFFOLD errors table. Raise via raise_err(error_id, message).
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message):
        super().__init__(message)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message


