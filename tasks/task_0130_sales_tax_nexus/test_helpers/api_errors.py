"""Error IDs and their HTTP status mapping (PRD §5).

Registering the map with the framework lets validate_error() auto-check the
HTTP status code that accompanies each error_id.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_CERTIFICATE_OVERLAP = "ERR_CERTIFICATE_OVERLAP"
    ERR_RETURN_PERIOD_OVERLAP = "ERR_RETURN_PERIOD_OVERLAP"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NEXUS_NOT_REGISTERED = "ERR_NEXUS_NOT_REGISTERED"
    ERR_TRANSACTION_LOCKED = "ERR_TRANSACTION_LOCKED"
    ERR_AMOUNT_MISMATCH = "ERR_AMOUNT_MISMATCH"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SELLER_SUSPENDED = "ERR_SELLER_SUSPENDED"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_CERTIFICATE_OVERLAP: 409,
    ApiErrorId.ERR_RETURN_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NEXUS_NOT_REGISTERED: 409,
    ApiErrorId.ERR_TRANSACTION_LOCKED: 409,
    ApiErrorId.ERR_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SELLER_SUSPENDED: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 422,
}

# Register with the framework so validate_error() cross-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
