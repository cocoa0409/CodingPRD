"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_TRAVEL_BUFFER_CONFLICT = "ERR_TRAVEL_BUFFER_CONFLICT"
    ERR_CUSTOMER_DOUBLE_BOOKED = "ERR_CUSTOMER_DOUBLE_BOOKED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PRO_NOT_CLEARED = "ERR_PRO_NOT_CLEARED"
    ERR_LICENSE_REQUIRED = "ERR_LICENSE_REQUIRED"
    ERR_SKILL_TAG_MISMATCH = "ERR_SKILL_TAG_MISMATCH"
    ERR_INSTANT_QUOTE_INELIGIBLE = "ERR_INSTANT_QUOTE_INELIGIBLE"
    ERR_ZIP_MISMATCH = "ERR_ZIP_MISMATCH"
    ERR_VISIT_OUTSIDE_WINDOW = "ERR_VISIT_OUTSIDE_WINDOW"
    ERR_WARRANTY_EXPIRED = "ERR_WARRANTY_EXPIRED"
    ERR_PARTIAL_PAYMENT = "ERR_PARTIAL_PAYMENT"
    ERR_REFUND_EXCEEDS_PAID = "ERR_REFUND_EXCEEDS_PAID"
    ERR_PRICING_MODEL_MISMATCH = "ERR_PRICING_MODEL_MISMATCH"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_TRAVEL_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_CUSTOMER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PRO_NOT_CLEARED: 422,
    ApiErrorId.ERR_LICENSE_REQUIRED: 422,
    ApiErrorId.ERR_SKILL_TAG_MISMATCH: 422,
    ApiErrorId.ERR_INSTANT_QUOTE_INELIGIBLE: 422,
    ApiErrorId.ERR_ZIP_MISMATCH: 422,
    ApiErrorId.ERR_VISIT_OUTSIDE_WINDOW: 422,
    ApiErrorId.ERR_WARRANTY_EXPIRED: 422,
    ApiErrorId.ERR_PARTIAL_PAYMENT: 422,
    ApiErrorId.ERR_REFUND_EXCEEDS_PAID: 422,
    ApiErrorId.ERR_PRICING_MODEL_MISMATCH: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
