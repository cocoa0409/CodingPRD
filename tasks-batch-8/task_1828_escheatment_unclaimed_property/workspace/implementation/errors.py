"""Error types and error-id constants for the Escheatment API.

Every error_id and HTTP status below is taken verbatim from SCAFFOLD.yaml
section 1.6 and PRD section 5.
"""


class ApiError(Exception):
    """Application-level error carrying the error_id and HTTP status."""

    def __init__(self, error_id, http_status, message):
        super().__init__(message)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message


