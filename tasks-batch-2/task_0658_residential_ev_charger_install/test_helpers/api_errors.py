"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, register it with the framework so validate_error()
can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_JOB_VERSION = "ERR_STALE_JOB_VERSION"
    ERR_COMPLIANCE_NOT_CLEARED = "ERR_COMPLIANCE_NOT_CLEARED"
    ERR_PANEL_UPGRADE_REQUIRED = "ERR_PANEL_UPGRADE_REQUIRED"
    ERR_ELECTRICIAN_OUT_OF_TERRITORY = "ERR_ELECTRICIAN_OUT_OF_TERRITORY"
    ERR_TERRITORY_MISMATCH = "ERR_TERRITORY_MISMATCH"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_DAILY_CAPACITY_EXCEEDED = "ERR_DAILY_CAPACITY_EXCEEDED"
    ERR_CIRCUIT_EXCEEDS_PANEL = "ERR_CIRCUIT_EXCEEDS_PANEL"
    ERR_INCENTIVE_FULLY_ABSORBED = "ERR_INCENTIVE_FULLY_ABSORBED"
    ERR_ELECTRICIAN_SUSPENDED = "ERR_ELECTRICIAN_SUSPENDED"
    ERR_PERMIT_REJECTED_FINAL = "ERR_PERMIT_REJECTED_FINAL"
    ERR_REOPEN_LIMIT_REACHED = "ERR_REOPEN_LIMIT_REACHED"
    ERR_JOB_NOT_ACTIVATED = "ERR_JOB_NOT_ACTIVATED"
    ERR_OPEN_WARRANTY_BLOCKS_CLOSE = "ERR_OPEN_WARRANTY_BLOCKS_CLOSE"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_JOB_VERSION: 412,
    ApiErrorId.ERR_COMPLIANCE_NOT_CLEARED: 409,
    ApiErrorId.ERR_PANEL_UPGRADE_REQUIRED: 409,
    ApiErrorId.ERR_ELECTRICIAN_OUT_OF_TERRITORY: 422,
    ApiErrorId.ERR_TERRITORY_MISMATCH: 422,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_DAILY_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_CIRCUIT_EXCEEDS_PANEL: 422,
    ApiErrorId.ERR_INCENTIVE_FULLY_ABSORBED: 422,
    ApiErrorId.ERR_ELECTRICIAN_SUSPENDED: 409,
    ApiErrorId.ERR_PERMIT_REJECTED_FINAL: 409,
    ApiErrorId.ERR_REOPEN_LIMIT_REACHED: 409,
    ApiErrorId.ERR_JOB_NOT_ACTIVATED: 409,
    ApiErrorId.ERR_OPEN_WARRANTY_BLOCKS_CLOSE: 409,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
