def bad_request(error_id: str, message: str) -> ApiError:
    return ApiError(error_id, message, 400)


def forbidden(message: str) -> ApiError:
    return ApiError(ERR_INSUFFICIENT_PERMISSIONS, message, 403)


def not_found(error_id: str, message: str) -> ApiError:
    return ApiError(error_id, message, 404)


def conflict(error_id: str, message: str) -> ApiError:
    return ApiError(error_id, message, 409)
