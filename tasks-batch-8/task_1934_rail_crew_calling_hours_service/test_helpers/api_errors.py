"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED_ROLE = "ERR_UNAUTHORIZED_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_HOS_LIMIT_EXCEEDED = "ERR_HOS_LIMIT_EXCEEDED"
    ERR_REST_NOT_SATISFIED = "ERR_REST_NOT_SATISFIED"
    ERR_TEMPORAL_WINDOW = "ERR_TEMPORAL_WINDOW"
    ERR_LEAVE_CONFLICT = "ERR_LEAVE_CONFLICT"
    ERR_JOB_ALREADY_FILLED = "ERR_JOB_ALREADY_FILLED"
    ERR_REFERENTIAL_MISMATCH = "ERR_REFERENTIAL_MISMATCH"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PAY_INCOMPLETE = "ERR_PAY_INCOMPLETE"
    ERR_CALL_POOL_EXHAUSTED = "ERR_CALL_POOL_EXHAUSTED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_HOS_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_REST_NOT_SATISFIED: 422,
    ApiErrorId.ERR_TEMPORAL_WINDOW: 422,
    ApiErrorId.ERR_LEAVE_CONFLICT: 422,
    ApiErrorId.ERR_JOB_ALREADY_FILLED: 422,
    ApiErrorId.ERR_REFERENTIAL_MISMATCH: 422,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PAY_INCOMPLETE: 422,
    ApiErrorId.ERR_CALL_POOL_EXHAUSTED: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
