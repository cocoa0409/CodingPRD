ERR_INVALID_GUARANTOR_STATE = "ERR_INVALID_GUARANTOR_STATE"
ERR_INVALID_NOTICE_STATE = "ERR_INVALID_NOTICE_STATE"
ERR_LANDLORD_SUSPENDED = "ERR_LANDLORD_SUSPENDED"
ERR_INCOME_VERIFICATION_UNRESOLVED = "ERR_INCOME_VERIFICATION_UNRESOLVED"

# Business safety (compliance)
