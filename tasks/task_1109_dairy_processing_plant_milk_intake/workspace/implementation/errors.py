def err(error_id, status, message):
    return ApiError(error_id, status, message)


def bad_input(message):
    return ApiError(ERR_INVALID_INPUT, 400, message)


def not_found(message="Referenced resource id does not exist"):
    return ApiError(ERR_NOT_FOUND, 404, message)


def invalid_state(message="Target resource not in the required state for this transition"):
    return ApiError(ERR_INVALID_STATE, 409, message)
