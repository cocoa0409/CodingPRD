"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_OWNERSHIP_FORBIDDEN = "ERR_OWNERSHIP_FORBIDDEN"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_EMPTY_ORDER = "ERR_EMPTY_ORDER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ORDER_NOT_MODIFIABLE = "ERR_ORDER_NOT_MODIFIABLE"
    ERR_PAYMENT_NOT_CAPTURED = "ERR_PAYMENT_NOT_CAPTURED"
    ERR_ORDER_NOT_FULFILLED = "ERR_ORDER_NOT_FULFILLED"
    ERR_RETURN_NOT_INSPECTABLE = "ERR_RETURN_NOT_INSPECTABLE"
    ERR_SHOE_ALREADY_RETIRED = "ERR_SHOE_ALREADY_RETIRED"
    ERR_SCHEDULE_CONFLICT = "ERR_SCHEDULE_CONFLICT"
    ERR_FITTER_UNAVAILABLE = "ERR_FITTER_UNAVAILABLE"
    ERR_APPOINTMENT_IN_PAST = "ERR_APPOINTMENT_IN_PAST"
    ERR_SUBSCRIPTION_REQUIRED = "ERR_SUBSCRIPTION_REQUIRED"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_REDEMPTION_EXCEEDS_CAP = "ERR_REDEMPTION_EXCEEDS_CAP"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_OWNERSHIP_FORBIDDEN: 403,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_EMPTY_ORDER: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ORDER_NOT_MODIFIABLE: 409,
    ApiErrorId.ERR_PAYMENT_NOT_CAPTURED: 409,
    ApiErrorId.ERR_ORDER_NOT_FULFILLED: 409,
    ApiErrorId.ERR_RETURN_NOT_INSPECTABLE: 409,
    ApiErrorId.ERR_SHOE_ALREADY_RETIRED: 409,
    ApiErrorId.ERR_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_FITTER_UNAVAILABLE: 409,
    ApiErrorId.ERR_APPOINTMENT_IN_PAST: 422,
    ApiErrorId.ERR_SUBSCRIPTION_REQUIRED: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 402,
    ApiErrorId.ERR_REDEMPTION_EXCEEDS_CAP: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
