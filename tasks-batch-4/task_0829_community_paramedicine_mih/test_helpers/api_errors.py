"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_REFERRAL_NOT_SCREENED = "ERR_REFERRAL_NOT_SCREENED"
    ERR_MED_REC_NOT_PENDING = "ERR_MED_REC_NOT_PENDING"
    ERR_CARE_PLAN_NOT_ACTIVE = "ERR_CARE_PLAN_NOT_ACTIVE"
    ERR_ENROLLMENT_NOT_ACTIVE = "ERR_ENROLLMENT_NOT_ACTIVE"
    ERR_PROGRAM_NOT_ACTIVE = "ERR_PROGRAM_NOT_ACTIVE"
    ERR_SCHEDULE_CONFLICT = "ERR_SCHEDULE_CONFLICT"
    ERR_TELEHEALTH_BUFFER_CONFLICT = "ERR_TELEHEALTH_BUFFER_CONFLICT"
    ERR_PROVIDER_TYPE_MISMATCH = "ERR_PROVIDER_TYPE_MISMATCH"
    ERR_CLAIM_EVENTS_CROSS_ENROLLMENT = "ERR_CLAIM_EVENTS_CROSS_ENROLLMENT"
    ERR_COSIGN_REQUIRED = "ERR_COSIGN_REQUIRED"
    ERR_COSIGN_SAME_CLINICIAN = "ERR_COSIGN_SAME_CLINICIAN"
    ERR_CLAIM_NO_BILLABLE_EVENTS = "ERR_CLAIM_NO_BILLABLE_EVENTS"
    ERR_ENROLLMENT_CAP_REACHED = "ERR_ENROLLMENT_CAP_REACHED"
    ERR_BUDGET_EXCEEDED = "ERR_BUDGET_EXCEEDED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_REFERRAL_NOT_SCREENED: 409,
    ApiErrorId.ERR_MED_REC_NOT_PENDING: 409,
    ApiErrorId.ERR_CARE_PLAN_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ENROLLMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PROGRAM_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_TELEHEALTH_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_PROVIDER_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_CLAIM_EVENTS_CROSS_ENROLLMENT: 422,
    ApiErrorId.ERR_COSIGN_REQUIRED: 422,
    ApiErrorId.ERR_COSIGN_SAME_CLINICIAN: 422,
    ApiErrorId.ERR_CLAIM_NO_BILLABLE_EVENTS: 422,
    ApiErrorId.ERR_ENROLLMENT_CAP_REACHED: 409,
    ApiErrorId.ERR_BUDGET_EXCEEDED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
