"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can auto-check
HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_IDENTITY_NOT_ACTIVE = "ERR_IDENTITY_NOT_ACTIVE"
    ERR_ROLE_RETIRED = "ERR_ROLE_RETIRED"
    ERR_ENTITLEMENT_ARCHIVED = "ERR_ENTITLEMENT_ARCHIVED"
    ERR_SOD_SELF_ACTION = "ERR_SOD_SELF_ACTION"
    ERR_DUAL_APPROVAL_REQUIRED = "ERR_DUAL_APPROVAL_REQUIRED"
    ERR_SOD_CONFLICT = "ERR_SOD_CONFLICT"
    ERR_SOD_OVERRIDE_REQUIRED = "ERR_SOD_OVERRIDE_REQUIRED"
    ERR_JIT_WINDOW_OVERLAP = "ERR_JIT_WINDOW_OVERLAP"
    ERR_CAMPAIGN_NOT_ACTIVE = "ERR_CAMPAIGN_NOT_ACTIVE"
    ERR_CAMPAIGN_WINDOW_OVERLAP = "ERR_CAMPAIGN_WINDOW_OVERLAP"
    ERR_IDENTITY_HAS_ACTIVE_GRANTS = "ERR_IDENTITY_HAS_ACTIVE_GRANTS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SOD_PAIR_INVALID = "ERR_SOD_PAIR_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_IDENTITY_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ROLE_RETIRED: 409,
    ApiErrorId.ERR_ENTITLEMENT_ARCHIVED: 409,
    ApiErrorId.ERR_SOD_SELF_ACTION: 403,
    ApiErrorId.ERR_DUAL_APPROVAL_REQUIRED: 422,
    ApiErrorId.ERR_SOD_CONFLICT: 409,
    ApiErrorId.ERR_SOD_OVERRIDE_REQUIRED: 422,
    ApiErrorId.ERR_JIT_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_CAMPAIGN_NOT_ACTIVE: 409,
    ApiErrorId.ERR_CAMPAIGN_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_IDENTITY_HAS_ACTIVE_GRANTS: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SOD_PAIR_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
