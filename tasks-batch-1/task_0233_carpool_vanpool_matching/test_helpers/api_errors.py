"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_TRIP_VERSION = "ERR_STALE_TRIP_VERSION"
    ERR_STALE_POOL_VERSION = "ERR_STALE_POOL_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEPENDENCY_NOT_READY = "ERR_DEPENDENCY_NOT_READY"
    ERR_RELIABILITY_TOO_LOW = "ERR_RELIABILITY_TOO_LOW"
    ERR_TRIP_WINDOW_OVERLAP = "ERR_TRIP_WINDOW_OVERLAP"
    ERR_RIDER_DOUBLE_BOOKED = "ERR_RIDER_DOUBLE_BOOKED"
    ERR_SEATS_EXHAUSTED = "ERR_SEATS_EXHAUSTED"
    ERR_POOL_CAPACITY_EXCEEDED = "ERR_POOL_CAPACITY_EXCEEDED"
    ERR_GRH_EVENT_CAP = "ERR_GRH_EVENT_CAP"
    ERR_GRH_ANNUAL_CAP = "ERR_GRH_ANNUAL_CAP"
    ERR_INSUFFICIENT_WALLET = "ERR_INSUFFICIENT_WALLET"
    ERR_NO_MATCH_FOUND = "ERR_NO_MATCH_FOUND"
    ERR_VALIDATION_DRIVER_REQUIRED = "ERR_VALIDATION_DRIVER_REQUIRED"
    ERR_PROGRAM_BUDGET_EXHAUSTED = "ERR_PROGRAM_BUDGET_EXHAUSTED"
    ERR_MEMBERSHIP_DUPLICATE = "ERR_MEMBERSHIP_DUPLICATE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_TRIP_VERSION: 412,
    ApiErrorId.ERR_STALE_POOL_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEPENDENCY_NOT_READY: 409,
    ApiErrorId.ERR_RELIABILITY_TOO_LOW: 409,
    ApiErrorId.ERR_TRIP_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_RIDER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_SEATS_EXHAUSTED: 409,
    ApiErrorId.ERR_POOL_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_GRH_EVENT_CAP: 409,
    ApiErrorId.ERR_GRH_ANNUAL_CAP: 409,
    ApiErrorId.ERR_INSUFFICIENT_WALLET: 402,
    ApiErrorId.ERR_NO_MATCH_FOUND: 422,
    ApiErrorId.ERR_VALIDATION_DRIVER_REQUIRED: 422,
    ApiErrorId.ERR_PROGRAM_BUDGET_EXHAUSTED: 409,
    ApiErrorId.ERR_MEMBERSHIP_DUPLICATE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
