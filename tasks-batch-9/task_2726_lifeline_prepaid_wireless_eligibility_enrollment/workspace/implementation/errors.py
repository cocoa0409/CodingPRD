DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Missing or empty identity headers",
    "ERR_UNAUTHORIZED": "Role is not permitted to perform this operation",
    "ERR_INVALID_REQUEST": "Request payload failed schema validation",
    "ERR_SEGREGATION_OF_DUTIES": "Segregation of duties prevents this action",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        super(ApiError, self).__init__(message or error_id)
        self.error_id = error_id
        self.http_status = ERROR_STATUS.get(error_id, 400)
        if message is None:
            message = DEFAULT_MESSAGES.get(
                error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize()
            )
        self.message = message


def fail(error_id, message=None):
    raise ApiError(error_id, message)
