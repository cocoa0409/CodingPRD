class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_RESOURCE_OWNER = ("ERR_NOT_RESOURCE_OWNER", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_DUPLICATE_RESOURCE = ("ERR_DUPLICATE_RESOURCE", 409)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_PROPERTY_MISMATCH = ("ERR_PROPERTY_MISMATCH", 409)
ERR_CONTRACT_NOT_ACTIVE = ("ERR_CONTRACT_NOT_ACTIVE", 409)
ERR_NO_EQUIPMENT_AVAILABLE = ("ERR_NO_EQUIPMENT_AVAILABLE", 409)
ERR_EQUIPMENT_NOT_READY = ("ERR_EQUIPMENT_NOT_READY", 409)
ERR_READING_ALREADY_PROCESSED = ("ERR_READING_ALREADY_PROCESSED", 409)
ERR_SNOW_THRESHOLD_NOT_MET = ("ERR_SNOW_THRESHOLD_NOT_MET", 409)
ERR_OPEN_DISPATCH_EXISTS = ("ERR_OPEN_DISPATCH_EXISTS", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_VALIDATION_RANGE = ("ERR_VALIDATION_RANGE", 422)
ERR_NO_SKIPPABLE_VISIT = ("ERR_NO_SKIPPABLE_VISIT", 409)


def err(spec, message=None):
    return ApiError(spec[0], spec[1], message)
