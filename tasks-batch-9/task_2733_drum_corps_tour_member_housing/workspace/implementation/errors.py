DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing or carry an unknown role.",
    "ERR_UNAUTHORIZED": "The acting role is not authorized for this endpoint.",
    "ERR_INVALID_REQUEST": "The request body is malformed.",
    "ERR_INVALID_DATE_RANGE": "An ordered date or instant pair is not strictly increasing.",
    "ERR_CONDITIONAL_FIELD_MISMATCH": "A conditionally required field does not obey its condition.",
    "ERR_AMOUNT_NOT_POSITIVE": "A monetary, count or placement input violates its positivity floor.",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        super(ApiError, self).__init__(message or error_id)
        self.error_id = error_id
        self.http_status = HTTP_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize() + "."
        )
