"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INSURANCE_INVALID = "ERR_INSURANCE_INVALID"
    ERR_LIVEABOARD_NOT_ALLOWED = "ERR_LIVEABOARD_NOT_ALLOWED"
    ERR_SLIP_SIZE_MISMATCH = "ERR_SLIP_SIZE_MISMATCH"
    ERR_SLIP_DATE_CONFLICT = "ERR_SLIP_DATE_CONFLICT"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_LIVEABOARD_QUOTA_EXCEEDED = "ERR_LIVEABOARD_QUOTA_EXCEEDED"
    ERR_VESSEL_TENANT_MISMATCH = "ERR_VESSEL_TENANT_MISMATCH"
    ERR_WAITLIST_INELIGIBLE = "ERR_WAITLIST_INELIGIBLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INSURANCE_INVALID: 422,
    ApiErrorId.ERR_LIVEABOARD_NOT_ALLOWED: 422,
    ApiErrorId.ERR_SLIP_SIZE_MISMATCH: 422,
    ApiErrorId.ERR_SLIP_DATE_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_LIVEABOARD_QUOTA_EXCEEDED: 409,
    ApiErrorId.ERR_VESSEL_TENANT_MISMATCH: 422,
    ApiErrorId.ERR_WAITLIST_INELIGIBLE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
