def not_found(error_id, message):
    return ApiError(error_id, 404, message)


def invalid_request(message):
    return ApiError(ERR_INVALID_REQUEST, 400, message)


def invalid_enum(message):
    return ApiError(ERR_INVALID_ENUM_VALUE, 400, message)


def invalid_state(message):
    return ApiError(ERR_INVALID_STATE, 409, message)


def terminal_locked(message):
    return ApiError(ERR_TERMINAL_STATE_LOCKED, 409, message)


def unprocessable(error_id, message, http_status=422):
    return ApiError(error_id, http_status, message)


def stale_version(message="expected version does not match the parent entity's "
                          "current version"):
    return ApiError(ERR_STALE_VERSION, 412, message)
