"""Error IDs and HTTP status mapping — PRD §5.

The mapping is registered with the framework at import time so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_MISSING_AUTH_HEADERS = "ERR_MISSING_AUTH_HEADERS"
    ERR_UNKNOWN_ROLE = "ERR_UNKNOWN_ROLE"
    ERR_UNKNOWN_IDENTITY = "ERR_UNKNOWN_IDENTITY"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    # Existence — PRD §2.5
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # State / OCC — PRD §2.4, §3
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_EMPLOYEE_TERMINATED = "ERR_EMPLOYEE_TERMINATED"
    # Business — PRD §3.2, §3.3, §3.4, §3.5, §3.6, §3.7, §3.8
    ERR_NOT_ELIGIBLE_TENURE = "ERR_NOT_ELIGIBLE_TENURE"
    ERR_NOT_ELIGIBLE_HOURS = "ERR_NOT_ELIGIBLE_HOURS"
    ERR_NOT_ELIGIBLE_WORKSITE = "ERR_NOT_ELIGIBLE_WORKSITE"
    ERR_CERT_DEADLINE_MISSED = "ERR_CERT_DEADLINE_MISSED"
    ERR_CERT_INCOMPLETE = "ERR_CERT_INCOMPLETE"
    ERR_QUOTA_EXCEEDED = "ERR_QUOTA_EXCEEDED"
    ERR_INSTANCE_NOT_ALLOWED = "ERR_INSTANCE_NOT_ALLOWED"
    ERR_INSTANCE_OVERLAP = "ERR_INSTANCE_OVERLAP"
    ERR_PFL_NOT_AVAILABLE = "ERR_PFL_NOT_AVAILABLE"
    ERR_PFL_MISMATCH = "ERR_PFL_MISMATCH"
    ERR_JOB_RESTORATION_FORFEITED = "ERR_JOB_RESTORATION_FORFEITED"
    ERR_INVOICE_NOT_PAYABLE = "ERR_INVOICE_NOT_PAYABLE"
    ERR_DUPLICATE_INSTANCE_DAY = "ERR_DUPLICATE_INSTANCE_DAY"
    # Generic validation — PRD §5
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 — Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH_HEADERS: 401,
    ApiErrorId.ERR_UNKNOWN_ROLE: 401,
    ApiErrorId.ERR_UNKNOWN_IDENTITY: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_EMPLOYEE_TERMINATED: 409,
    ApiErrorId.ERR_NOT_ELIGIBLE_TENURE: 422,
    ApiErrorId.ERR_NOT_ELIGIBLE_HOURS: 422,
    ApiErrorId.ERR_NOT_ELIGIBLE_WORKSITE: 422,
    ApiErrorId.ERR_CERT_DEADLINE_MISSED: 422,
    ApiErrorId.ERR_CERT_INCOMPLETE: 422,
    ApiErrorId.ERR_QUOTA_EXCEEDED: 422,
    ApiErrorId.ERR_INSTANCE_NOT_ALLOWED: 422,
    ApiErrorId.ERR_INSTANCE_OVERLAP: 422,
    ApiErrorId.ERR_PFL_NOT_AVAILABLE: 422,
    ApiErrorId.ERR_PFL_MISMATCH: 422,
    ApiErrorId.ERR_JOB_RESTORATION_FORFEITED: 409,
    ApiErrorId.ERR_INVOICE_NOT_PAYABLE: 409,
    ApiErrorId.ERR_DUPLICATE_INSTANCE_DAY: 409,
    ApiErrorId.ERR_VALIDATION: 400,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
