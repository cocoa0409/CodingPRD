"""Error catalogue (PRD §5 / SCAFFOLD §1.6).

Every error_id here is verbatim from the scaffold; HTTP statuses match §5.
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Catalogue: error_id -> http status
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_ACCOUNT_NOT_ELIGIBLE = "ERR_ACCOUNT_NOT_ELIGIBLE"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
ERR_DISCLOSURE_NOT_ACKNOWLEDGED = "ERR_DISCLOSURE_NOT_ACKNOWLEDGED"
ERR_APR_CAP_EXCEEDED = "ERR_APR_CAP_EXCEEDED"
ERR_SOD_CONFLICT = "ERR_SOD_CONFLICT"
ERR_GRADUATION_NOT_ELIGIBLE = "ERR_GRADUATION_NOT_ELIGIBLE"
ERR_DEPOSIT_NOT_RELEASABLE = "ERR_DEPOSIT_NOT_RELEASABLE"
ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
ERR_DEPOSIT_CAP_EXCEEDED = "ERR_DEPOSIT_CAP_EXCEEDED"
ERR_INSUFFICIENT_WALLET = "ERR_INSUFFICIENT_WALLET"
ERR_STALE_VERSION = "ERR_STALE_VERSION"

_HTTP = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN: 403,
    ERR_NOT_FOUND: 404,
    ERR_INVALID_REQUEST: 422,
    ERR_ACCOUNT_NOT_ELIGIBLE: 409,
    ERR_INVALID_STATE: 409,
    ERR_QUOTE_EXPIRED: 409,
    ERR_DISCLOSURE_NOT_ACKNOWLEDGED: 409,
    ERR_APR_CAP_EXCEEDED: 422,
    ERR_SOD_CONFLICT: 409,
    ERR_GRADUATION_NOT_ELIGIBLE: 409,
    ERR_DEPOSIT_NOT_RELEASABLE: 409,
    ERR_CREDIT_LIMIT_EXCEEDED: 409,
    ERR_DEPOSIT_CAP_EXCEEDED: 422,
    ERR_INSUFFICIENT_WALLET: 409,
    ERR_STALE_VERSION: 412,
}


def err(error_id, message=None):
    return ApiError(error_id, _HTTP[error_id], message)
