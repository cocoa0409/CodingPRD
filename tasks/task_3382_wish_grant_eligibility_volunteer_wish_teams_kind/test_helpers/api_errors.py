    ERR_INVALID_CLEARANCE_STATE = "ERR_INVALID_CLEARANCE_STATE"
    ERR_INVALID_EVENT_STATE = "ERR_INVALID_EVENT_STATE"
    # Optimistic concurrency
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # Business safety
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_MEDICAL_CLEARANCE_INVALID = "ERR_MEDICAL_CLEARANCE_INVALID"
    # Temporal rules
    ERR_TEAM_SCHEDULE_OVERLAP = "ERR_TEAM_SCHEDULE_OVERLAP"
    ERR_TREATMENT_BLACKOUT_CONFLICT = "ERR_TREATMENT_BLACKOUT_CONFLICT"
    ERR_URGENT_SLA_VIOLATION = "ERR_URGENT_SLA_VIOLATION"
    ERR_DONATION_EXPIRED = "ERR_DONATION_EXPIRED"
    # Intake business constraints
    ERR_CHILD_AGE_OUT_OF_RANGE = "ERR_CHILD_AGE_OUT_OF_RANGE"
    ERR_SELF_REFERRAL_TOO_YOUNG = "ERR_SELF_REFERRAL_TOO_YOUNG"
    ERR_DUPLICATE_REFERRAL = "ERR_DUPLICATE_REFERRAL"
    ERR_NO_TERRITORY_CHAPTER = "ERR_NO_TERRITORY_CHAPTER"
    # Team / visit business constraints
    ERR_TEAM_DUPLICATE_MEMBER = "ERR_TEAM_DUPLICATE_MEMBER"
    ERR_VOLUNTEER_NOT_ACTIVE = "ERR_VOLUNTEER_NOT_ACTIVE"
    ERR_TEAM_CHAPTER_MISMATCH = "ERR_TEAM_CHAPTER_MISMATCH"
    ERR_NOT_TEAM_MEMBER = "ERR_NOT_TEAM_MEMBER"
