    ERR_CONSTRAINT_VIOLATION = "ERR_CONSTRAINT_VIOLATION"
    ERR_BLOCKING_COMMENTS_OPEN = "ERR_BLOCKING_COMMENTS_OPEN"
    ERR_HEARING_REQUIRED = "ERR_HEARING_REQUIRED"
    ERR_HEARING_PENDING = "ERR_HEARING_PENDING"
    ERR_SEQUENCE_VIOLATION = "ERR_SEQUENCE_VIOLATION"
    ERR_CONDITIONS_PENDING = "ERR_CONDITIONS_PENDING"
    ERR_APPEAL_WINDOW_OPEN = "ERR_APPEAL_WINDOW_OPEN"
    ERR_PERMIT_ALREADY_ISSUED = "ERR_PERMIT_ALREADY_ISSUED"
    ERR_INSUFFICIENT_SIGNATURES = "ERR_INSUFFICIENT_SIGNATURES"
    # fiscal
    ERR_FEES_UNPAID = "ERR_FEES_UNPAID"
    ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"
    ERR_NO_ADOPTED_FEE_SCHEDULE = "ERR_NO_ADOPTED_FEE_SCHEDULE"
    # optimistic concurrency
    ERR_STALE_PROJECT_VERSION = "ERR_STALE_PROJECT_VERSION"
    ERR_STALE_APPLICATION_VERSION = "ERR_STALE_APPLICATION_VERSION"


