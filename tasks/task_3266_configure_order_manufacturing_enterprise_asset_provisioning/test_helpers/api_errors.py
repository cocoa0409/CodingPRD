"""Error IDs and HTTP status mapping (PRD section 5 error catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_CONFIGURATION_VERSION = "ERR_STALE_CONFIGURATION_VERSION"
    ERR_STALE_COMPONENT_VERSION = "ERR_STALE_COMPONENT_VERSION"
    ERR_COMPATIBILITY_VIOLATION = "ERR_COMPATIBILITY_VIOLATION"
    ERR_COMPONENT_EOL = "ERR_COMPONENT_EOL"
    ERR_PROGRAM_LOCK_VIOLATION = "ERR_PROGRAM_LOCK_VIOLATION"
    ERR_CONFIGURATION_IN_USE = "ERR_CONFIGURATION_IN_USE"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_INSUFFICIENT_COMPONENT_STOCK = "ERR_INSUFFICIENT_COMPONENT_STOCK"
    ERR_BUILD_OUT_OF_SEQUENCE = "ERR_BUILD_OUT_OF_SEQUENCE"
    ERR_WAVE_WINDOW_OVERLAP = "ERR_WAVE_WINDOW_OVERLAP"
    ERR_OUTSIDE_SHIP_WINDOW = "ERR_OUTSIDE_SHIP_WINDOW"
    ERR_SUBSTITUTION_INCOMPATIBLE = "ERR_SUBSTITUTION_INCOMPATIBLE"
    ERR_PARTS_STOCKING_REQUIRED = "ERR_PARTS_STOCKING_REQUIRED"
    ERR_ENTITLEMENT_OVERLAP = "ERR_ENTITLEMENT_OVERLAP"
    ERR_ASSET_NOT_RECOVERABLE = "ERR_ASSET_NOT_RECOVERABLE"
    ERR_INVALID_ORDER_QUANTITY = "ERR_INVALID_ORDER_QUANTITY"
    ERR_SHORTAGE_PENDING = "ERR_SHORTAGE_PENDING"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_CONFIGURATION_VERSION: 412,
    ApiErrorId.ERR_STALE_COMPONENT_VERSION: 412,
    ApiErrorId.ERR_COMPATIBILITY_VIOLATION: 422,
    ApiErrorId.ERR_COMPONENT_EOL: 422,
    ApiErrorId.ERR_PROGRAM_LOCK_VIOLATION: 422,
    ApiErrorId.ERR_CONFIGURATION_IN_USE: 409,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 402,
    ApiErrorId.ERR_INSUFFICIENT_COMPONENT_STOCK: 422,
    ApiErrorId.ERR_BUILD_OUT_OF_SEQUENCE: 422,
    ApiErrorId.ERR_WAVE_WINDOW_OVERLAP: 422,
    ApiErrorId.ERR_OUTSIDE_SHIP_WINDOW: 422,
    ApiErrorId.ERR_SUBSTITUTION_INCOMPATIBLE: 422,
    ApiErrorId.ERR_PARTS_STOCKING_REQUIRED: 422,
    ApiErrorId.ERR_ENTITLEMENT_OVERLAP: 422,
    ApiErrorId.ERR_ASSET_NOT_RECOVERABLE: 422,
    ApiErrorId.ERR_INVALID_ORDER_QUANTITY: 422,
    ApiErrorId.ERR_SHORTAGE_PENDING: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
# The framework normalizes enum keys via str(); keep keys as plain strings too.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
