"""Error IDs and HTTP status mapping (PRD §5 error catalogue).

After defining the map, it is registered with the framework so that
validate_error() can auto-check the HTTP status for each error id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EMBROIDERY_NOT_ALLOWED = "ERR_EMBROIDERY_NOT_ALLOWED"
    ERR_FITMENT_REQUIRED = "ERR_FITMENT_REQUIRED"
    ERR_LICENSE_REQUIRED = "ERR_LICENSE_REQUIRED"
    ERR_INVALID_JURISDICTION = "ERR_INVALID_JURISDICTION"
    ERR_INVALID_MARKDOWN_WINDOW = "ERR_INVALID_MARKDOWN_WINDOW"
    ERR_MARKDOWN_OVERLAP = "ERR_MARKDOWN_OVERLAP"
    ERR_PRICE_MATCH_NOT_LOWER = "ERR_PRICE_MATCH_NOT_LOWER"
    ERR_ORDER_NOT_MATCHABLE = "ERR_ORDER_NOT_MATCHABLE"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_STALE_INVENTORY_VERSION = "ERR_STALE_INVENTORY_VERSION"
    ERR_DUPLICATE_INVENTORY_ROW = "ERR_DUPLICATE_INVENTORY_ROW"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EMBROIDERY_NOT_ALLOWED: 422,
    ApiErrorId.ERR_FITMENT_REQUIRED: 422,
    ApiErrorId.ERR_LICENSE_REQUIRED: 422,
    ApiErrorId.ERR_INVALID_JURISDICTION: 422,
    ApiErrorId.ERR_INVALID_MARKDOWN_WINDOW: 422,
    ApiErrorId.ERR_MARKDOWN_OVERLAP: 409,
    ApiErrorId.ERR_PRICE_MATCH_NOT_LOWER: 422,
    ApiErrorId.ERR_ORDER_NOT_MATCHABLE: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_STALE_INVENTORY_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE_INVENTORY_ROW: 409,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
