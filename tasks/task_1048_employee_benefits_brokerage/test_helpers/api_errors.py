"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_POLICY_VERSION = "ERR_STALE_POLICY_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NO_ACTIVE_COVERAGE = "ERR_NO_ACTIVE_COVERAGE"
    ERR_QUOTE_NOT_SELECTED = "ERR_QUOTE_NOT_SELECTED"
    ERR_CLIENT_MISMATCH = "ERR_CLIENT_MISMATCH"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_COVERAGE_OVERLAP = "ERR_COVERAGE_OVERLAP"
    ERR_WINDOW_NOT_YET_OPEN = "ERR_WINDOW_NOT_YET_OPEN"
    ERR_WINDOW_NOT_CLOSED = "ERR_WINDOW_NOT_CLOSED"
    ERR_PREMIUM_BELOW_FLOOR = "ERR_PREMIUM_BELOW_FLOOR"
    ERR_INVALID_FIELD = "ERR_INVALID_FIELD"
    ERR_DUPLICATE_EIN = "ERR_DUPLICATE_EIN"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_POLICY_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_NO_ACTIVE_COVERAGE: 409,
    ApiErrorId.ERR_QUOTE_NOT_SELECTED: 409,
    ApiErrorId.ERR_CLIENT_MISMATCH: 409,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_COVERAGE_OVERLAP: 409,
    ApiErrorId.ERR_WINDOW_NOT_YET_OPEN: 409,
    ApiErrorId.ERR_WINDOW_NOT_CLOSED: 409,
    ApiErrorId.ERR_PREMIUM_BELOW_FLOOR: 409,
    ApiErrorId.ERR_INVALID_FIELD: 422,
    ApiErrorId.ERR_DUPLICATE_EIN: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
