    # Auth — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    # Existence — PRD §2.5
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # State — PRD §3
    ERR_PLAN_NOT_ACTIVE = "ERR_PLAN_NOT_ACTIVE"
    ERR_PERIOD_NOT_OPEN = "ERR_PERIOD_NOT_OPEN"
    ERR_INVALID_PERIOD_STATE = "ERR_INVALID_PERIOD_STATE"
    ERR_INVALID_ENROLLMENT_STATE = "ERR_INVALID_ENROLLMENT_STATE"
    ERR_INVALID_DISPOSITION_STATE = "ERR_INVALID_DISPOSITION_STATE"
    ERR_DUPLICATE_ENROLLMENT = "ERR_DUPLICATE_ENROLLMENT"
    ERR_DUPLICATE_PLAN_NAME = "ERR_DUPLICATE_PLAN_NAME"
    # Business — PRD §3
    ERR_PERIOD_LENGTH_OUT_OF_RANGE = "ERR_PERIOD_LENGTH_OUT_OF_RANGE"
    ERR_CONTRIBUTION_RATE_OUT_OF_RANGE = "ERR_CONTRIBUTION_RATE_OUT_OF_RANGE"
