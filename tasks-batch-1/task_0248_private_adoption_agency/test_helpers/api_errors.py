"""Error IDs and HTTP status mapping (Private Adoption Agency API, PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_USER_CONTEXT = "ERR_MISSING_USER_CONTEXT"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_RESOURCE_NOT_FOUND = "ERR_REFERENCED_RESOURCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_PREREQUISITE_NOT_MET = "ERR_PREREQUISITE_NOT_MET"
    ERR_CONSENT_TOO_EARLY = "ERR_CONSENT_TOO_EARLY"
    ERR_REVOCATION_WINDOW_CLOSED = "ERR_REVOCATION_WINDOW_CLOSED"
    ERR_VISIT_WINDOW_INVALID = "ERR_VISIT_WINDOW_INVALID"
    ERR_VISIT_OVERLAP = "ERR_VISIT_OVERLAP"
    ERR_SESSION_BUFFER_CONFLICT = "ERR_SESSION_BUFFER_CONFLICT"
    ERR_VISITS_INCOMPLETE = "ERR_VISITS_INCOMPLETE"
    ERR_ICPC_NOT_APPLICABLE = "ERR_ICPC_NOT_APPLICABLE"
    ERR_INSUFFICIENT_ESCROW = "ERR_INSUFFICIENT_ESCROW"
    ERR_STALE_CASE_VERSION = "ERR_STALE_CASE_VERSION"
    ERR_HOME_STUDY_EXPIRED = "ERR_HOME_STUDY_EXPIRED"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_MISSING_USER_CONTEXT: 400,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_PREREQUISITE_NOT_MET: 409,
    ApiErrorId.ERR_CONSENT_TOO_EARLY: 409,
    ApiErrorId.ERR_REVOCATION_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_VISIT_WINDOW_INVALID: 409,
    ApiErrorId.ERR_VISIT_OVERLAP: 409,
    ApiErrorId.ERR_SESSION_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_VISITS_INCOMPLETE: 409,
    ApiErrorId.ERR_ICPC_NOT_APPLICABLE: 409,
    ApiErrorId.ERR_INSUFFICIENT_ESCROW: 409,
    ApiErrorId.ERR_STALE_CASE_VERSION: 412,
    ApiErrorId.ERR_HOME_STUDY_EXPIRED: 409,
    ApiErrorId.ERR_INVALID_PAGINATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
