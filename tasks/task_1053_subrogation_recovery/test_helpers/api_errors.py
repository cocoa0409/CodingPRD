"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_CLAIM_OWNER = "ERR_NOT_CLAIM_OWNER"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ADVERSE_NOT_ARBITRABLE = "ERR_ADVERSE_NOT_ARBITRABLE"
    ERR_DEMAND_NOT_DISPUTED = "ERR_DEMAND_NOT_DISPUTED"
    ERR_STATUTE_EXPIRED = "ERR_STATUTE_EXPIRED"
    ERR_ARBITRATION_WINDOW_CLOSED = "ERR_ARBITRATION_WINDOW_CLOSED"
    ERR_DEMAND_WINDOW_OPEN = "ERR_DEMAND_WINDOW_OPEN"
    ERR_HEARING_WINDOW_CONFLICT = "ERR_HEARING_WINDOW_CONFLICT"
    ERR_EXCEEDS_SETTLEMENT_AUTHORITY = "ERR_EXCEEDS_SETTLEMENT_AUTHORITY"
    ERR_CARRIER_SUSPENDED = "ERR_CARRIER_SUSPENDED"
    ERR_STATEMENT_NOT_OPEN = "ERR_STATEMENT_NOT_OPEN"
    ERR_PAYMENT_EXCEEDS_SETTLEMENT = "ERR_PAYMENT_EXCEEDS_SETTLEMENT"
    ERR_STALE_CLAIM_VERSION = "ERR_STALE_CLAIM_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_CLAIM_OWNER: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ADVERSE_NOT_ARBITRABLE: 409,
    ApiErrorId.ERR_DEMAND_NOT_DISPUTED: 409,
    ApiErrorId.ERR_STATUTE_EXPIRED: 409,
    ApiErrorId.ERR_ARBITRATION_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_DEMAND_WINDOW_OPEN: 409,
    ApiErrorId.ERR_HEARING_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_EXCEEDS_SETTLEMENT_AUTHORITY: 409,
    ApiErrorId.ERR_CARRIER_SUSPENDED: 409,
    ApiErrorId.ERR_STATEMENT_NOT_OPEN: 409,
    ApiErrorId.ERR_PAYMENT_EXCEEDS_SETTLEMENT: 422,
    ApiErrorId.ERR_STALE_CLAIM_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
