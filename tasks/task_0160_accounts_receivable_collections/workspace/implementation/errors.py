"""Error catalogue and the ApiError exception.

Error IDs and HTTP statuses are taken verbatim from PRD §5 / SCAFFOLD §1.6.
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error ID constants (PRD §5 Error Code Catalogue)
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_DISPUTE_BLOCKS_WRITEOFF = "ERR_DISPUTE_BLOCKS_WRITEOFF"
ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
ERR_CUSTOMER_MISMATCH = "ERR_CUSTOMER_MISMATCH"
ERR_DISPUTE_EXCEEDS_BALANCE = "ERR_DISPUTE_EXCEEDS_BALANCE"
ERR_PROMISE_WINDOW_OVERLAP = "ERR_PROMISE_WINDOW_OVERLAP"
ERR_PAUSE_WINDOW_CONFLICT = "ERR_PAUSE_WINDOW_CONFLICT"
ERR_OVER_APPLICATION = "ERR_OVER_APPLICATION"
ERR_APPLY_EXCEEDS_INVOICE = "ERR_APPLY_EXCEEDS_INVOICE"
ERR_WRITEOFF_AMOUNT_MISMATCH = "ERR_WRITEOFF_AMOUNT_MISMATCH"
ERR_CREDIT_HOLD = "ERR_CREDIT_HOLD"
ERR_VALIDATION = "ERR_VALIDATION"
ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
ERR_PROMISE_ALREADY_RESOLVED = "ERR_PROMISE_ALREADY_RESOLVED"


# HTTP status by error id (PRD §5)
HTTP_STATUS = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNAUTHORIZED: 403,
    ERR_NOT_FOUND: 404,
    ERR_INVALID_REQUEST: 400,
    ERR_INVALID_ENUM: 422,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 412,
    ERR_DISPUTE_BLOCKS_WRITEOFF: 409,
    ERR_SOD_VIOLATION: 403,
    ERR_CUSTOMER_MISMATCH: 409,
    ERR_DISPUTE_EXCEEDS_BALANCE: 422,
    ERR_PROMISE_WINDOW_OVERLAP: 409,
    ERR_PAUSE_WINDOW_CONFLICT: 409,
    ERR_OVER_APPLICATION: 422,
    ERR_APPLY_EXCEEDS_INVOICE: 422,
    ERR_WRITEOFF_AMOUNT_MISMATCH: 422,
    ERR_CREDIT_HOLD: 402,
    ERR_VALIDATION: 422,
    ERR_PAGINATION_INVALID: 400,
    ERR_PROMISE_ALREADY_RESOLVED: 409,
}


def err(error_id, message=None):
    return ApiError(error_id, HTTP_STATUS[error_id], message)
