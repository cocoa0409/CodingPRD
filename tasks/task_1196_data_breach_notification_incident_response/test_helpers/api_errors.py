"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_DEADLINE_PASSED = "ERR_DEADLINE_PASSED"
    ERR_CUSTODY_OVERLAP = "ERR_CUSTODY_OVERLAP"
    ERR_DATA_ELEMENT_OUT_OF_SCOPE = "ERR_DATA_ELEMENT_OUT_OF_SCOPE"
    ERR_SUPERSESSION_CYCLE = "ERR_SUPERSESSION_CYCLE"
    ERR_STAFFING_PLAN_OVERLAP = "ERR_STAFFING_PLAN_OVERLAP"
    ERR_DUPLICATE_SUBJECT = "ERR_DUPLICATE_SUBJECT"
    ERR_OFFER_ALREADY_ACTIVE = "ERR_OFFER_ALREADY_ACTIVE"
    ERR_INCIDENT_NOT_CONFIRMED = "ERR_INCIDENT_NOT_CONFIRMED"
    ERR_NOTICE_NOT_APPROVABLE = "ERR_NOTICE_NOT_APPROVABLE"
    ERR_NO_ACTIVE_STAFFING_PLAN = "ERR_NO_ACTIVE_STAFFING_PLAN"
    ERR_BATCH_NOT_SHIPPABLE = "ERR_BATCH_NOT_SHIPPABLE"
    ERR_EVIDENCE_NOT_SEALED = "ERR_EVIDENCE_NOT_SEALED"
    ERR_REMEDIATION_INCOMPLETE = "ERR_REMEDIATION_INCOMPLETE"
    ERR_NO_AFFECTED_SUBJECTS = "ERR_NO_AFFECTED_SUBJECTS"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_CUSTODY_OVERLAP: 409,
    ApiErrorId.ERR_DATA_ELEMENT_OUT_OF_SCOPE: 422,
    ApiErrorId.ERR_SUPERSESSION_CYCLE: 422,
    ApiErrorId.ERR_STAFFING_PLAN_OVERLAP: 409,
    ApiErrorId.ERR_DUPLICATE_SUBJECT: 409,
    ApiErrorId.ERR_OFFER_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_INCIDENT_NOT_CONFIRMED: 409,
    ApiErrorId.ERR_NOTICE_NOT_APPROVABLE: 409,
    ApiErrorId.ERR_NO_ACTIVE_STAFFING_PLAN: 409,
    ApiErrorId.ERR_BATCH_NOT_SHIPPABLE: 409,
    ApiErrorId.ERR_EVIDENCE_NOT_SEALED: 409,
    ApiErrorId.ERR_REMEDIATION_INCOMPLETE: 409,
    ApiErrorId.ERR_NO_AFFECTED_SUBJECTS: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
