"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks
the HTTP status for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_WAVE_VERSION = "ERR_STALE_WAVE_VERSION"
    ERR_STALE_SUBSCRIPTION_VERSION = "ERR_STALE_SUBSCRIPTION_VERSION"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_DUPLICATE_SKU = "ERR_DUPLICATE_SKU"
    ERR_PREPAID_TERM_NOT_OFFERED = "ERR_PREPAID_TERM_NOT_OFFERED"
    ERR_PLAN_RETIRED = "ERR_PLAN_RETIRED"
    ERR_GIFT_NOT_REACTIVATABLE = "ERR_GIFT_NOT_REACTIVATABLE"
    ERR_PAUSE_LIMIT_REACHED = "ERR_PAUSE_LIMIT_REACHED"
    ERR_BOX_ITEM_COUNT_MISMATCH = "ERR_BOX_ITEM_COUNT_MISMATCH"
    ERR_GIFT_NOT_REDEEMABLE = "ERR_GIFT_NOT_REDEEMABLE"
    ERR_WINBACK_WINDOW_CLOSED = "ERR_WINBACK_WINDOW_CLOSED"
    ERR_CUTOFF_PASSED = "ERR_CUTOFF_PASSED"
    ERR_CUTOFF_NOT_REACHED = "ERR_CUTOFF_NOT_REACHED"
    ERR_INVALID_RESUME_DATE = "ERR_INVALID_RESUME_DATE"
    ERR_BOX_ALREADY_FINALIZED = "ERR_BOX_ALREADY_FINALIZED"
    ERR_EMPTY_WAVE = "ERR_EMPTY_WAVE"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_WAVE_CAPACITY_FULL = "ERR_WAVE_CAPACITY_FULL"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_WAVE_VERSION: 412,
    ApiErrorId.ERR_STALE_SUBSCRIPTION_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_DUPLICATE_SKU: 409,
    ApiErrorId.ERR_PREPAID_TERM_NOT_OFFERED: 422,
    ApiErrorId.ERR_PLAN_RETIRED: 422,
    ApiErrorId.ERR_GIFT_NOT_REACTIVATABLE: 422,
    ApiErrorId.ERR_PAUSE_LIMIT_REACHED: 422,
    ApiErrorId.ERR_BOX_ITEM_COUNT_MISMATCH: 422,
    ApiErrorId.ERR_GIFT_NOT_REDEEMABLE: 422,
    ApiErrorId.ERR_WINBACK_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_CUTOFF_PASSED: 422,
    ApiErrorId.ERR_CUTOFF_NOT_REACHED: 422,
    ApiErrorId.ERR_INVALID_RESUME_DATE: 422,
    ApiErrorId.ERR_BOX_ALREADY_FINALIZED: 422,
    ApiErrorId.ERR_EMPTY_WAVE: 422,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 422,
    ApiErrorId.ERR_WAVE_CAPACITY_FULL: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
# Use plain string keys so lookups by raw error_id string resolve.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
