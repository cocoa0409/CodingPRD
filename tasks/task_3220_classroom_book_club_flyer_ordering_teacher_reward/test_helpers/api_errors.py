"""Error catalog for the Classroom Book Club API.

Every error identifier the API contract declares, together with the HTTP
status each one must be returned with. Registering the mapping with the shared
validators lets ``validate_error`` cross-check the status automatically.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    """Declared error identifiers."""

    # Credentials and role authorization.
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"

    # Existence.
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # State.
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"

    # Business safety.
    ERR_SCHOOL_RESTRICTED = "ERR_SCHOOL_RESTRICTED"
    ERR_LICENSE_SUSPENDED = "ERR_LICENSE_SUSPENDED"
    ERR_ROYALTY_CAP_INVALID = "ERR_ROYALTY_CAP_INVALID"

    # Business constraint.
    ERR_GRADE_BAND_MISMATCH = "ERR_GRADE_BAND_MISMATCH"
    ERR_FORMAT_NOT_ALLOWED = "ERR_FORMAT_NOT_ALLOWED"
    ERR_CYCLE_ALREADY_PUBLISHED = "ERR_CYCLE_ALREADY_PUBLISHED"
    ERR_EMPTY_CYCLE = "ERR_EMPTY_CYCLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # Business temporal.
    ERR_FAIR_OVERLAP = "ERR_FAIR_OVERLAP"
    ERR_TITLE_OVERLAP_CAP = "ERR_TITLE_OVERLAP_CAP"
    ERR_PROMO_WINDOW_INVALID = "ERR_PROMO_WINDOW_INVALID"

    # Promotion shape.
    ERR_PROMO_SHAPE_INVALID = "ERR_PROMO_SHAPE_INVALID"

    # Fiscal.
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_POINTS_BALANCE_NEGATIVE = "ERR_POINTS_BALANCE_NEGATIVE"
    ERR_NOT_LOW_INCOME = "ERR_NOT_LOW_INCOME"

    # Referential / ownership.
    ERR_FORBIDDEN_OWNERSHIP = "ERR_FORBIDDEN_OWNERSHIP"
    ERR_ORDER_NOT_OPEN = "ERR_ORDER_NOT_OPEN"

    # OCC.
    ERR_STALE_VERSION = "ERR_STALE_VERSION"

    # Action-specific.
    ERR_ORDER_HAS_SHIPPED = "ERR_ORDER_HAS_SHIPPED"
    ERR_ORDER_EMPTY = "ERR_ORDER_EMPTY"
    ERR_CYCLE_NOT_PUBLISHED = "ERR_CYCLE_NOT_PUBLISHED"
    ERR_DONATION_NOT_MATCHED = "ERR_DONATION_NOT_MATCHED"
    ERR_FAIR_NOT_CANCELLABLE = "ERR_FAIR_NOT_CANCELLABLE"
    ERR_REDEMPTION_SHAPE_INVALID = "ERR_REDEMPTION_SHAPE_INVALID"
    ERR_ENROLLMENT_EXISTS = "ERR_ENROLLMENT_EXISTS"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ALREADY_TERMINAL: 409,
    ApiErrorId.ERR_SCHOOL_RESTRICTED: 409,
    ApiErrorId.ERR_LICENSE_SUSPENDED: 409,
    ApiErrorId.ERR_ROYALTY_CAP_INVALID: 422,
    ApiErrorId.ERR_GRADE_BAND_MISMATCH: 422,
    ApiErrorId.ERR_FORMAT_NOT_ALLOWED: 422,
    ApiErrorId.ERR_CYCLE_ALREADY_PUBLISHED: 409,
    ApiErrorId.ERR_EMPTY_CYCLE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_FAIR_OVERLAP: 409,
    ApiErrorId.ERR_TITLE_OVERLAP_CAP: 409,
    ApiErrorId.ERR_PROMO_WINDOW_INVALID: 422,
    ApiErrorId.ERR_PROMO_SHAPE_INVALID: 422,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 422,
    ApiErrorId.ERR_POINTS_BALANCE_NEGATIVE: 422,
    ApiErrorId.ERR_NOT_LOW_INCOME: 422,
    ApiErrorId.ERR_FORBIDDEN_OWNERSHIP: 403,
    ApiErrorId.ERR_ORDER_NOT_OPEN: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ORDER_HAS_SHIPPED: 409,
    ApiErrorId.ERR_ORDER_EMPTY: 422,
    ApiErrorId.ERR_CYCLE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_DONATION_NOT_MATCHED: 409,
    ApiErrorId.ERR_FAIR_NOT_CANCELLABLE: 409,
    ApiErrorId.ERR_REDEMPTION_SHAPE_INVALID: 422,
    ApiErrorId.ERR_ENROLLMENT_EXISTS: 409,
}


# Register with the framework so validate_error() auto-checks the HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
