"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks
HTTP status codes from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_START_IN_NO_RIDE_ZONE = "ERR_START_IN_NO_RIDE_ZONE"
    ERR_END_IN_NO_RIDE_ZONE = "ERR_END_IN_NO_RIDE_ZONE"
    ERR_BATTERY_TOO_LOW = "ERR_BATTERY_TOO_LOW"
    ERR_VEHICLE_NOT_AVAILABLE = "ERR_VEHICLE_NOT_AVAILABLE"
    ERR_TECH_WINDOW_OVERLAP = "ERR_TECH_WINDOW_OVERLAP"
    ERR_NO_APPROVED_APPLICATION = "ERR_NO_APPROVED_APPLICATION"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_INSUFFICIENT_WALLET = "ERR_INSUFFICIENT_WALLET"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VEHICLE_VERSION = "ERR_STALE_VEHICLE_VERSION"
    ERR_STALE_RIDER_VERSION = "ERR_STALE_RIDER_VERSION"
    ERR_OUTSTANDING_FINES = "ERR_OUTSTANDING_FINES"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_START_IN_NO_RIDE_ZONE: 422,
    ApiErrorId.ERR_END_IN_NO_RIDE_ZONE: 422,
    ApiErrorId.ERR_BATTERY_TOO_LOW: 422,
    ApiErrorId.ERR_VEHICLE_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_TECH_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_NO_APPROVED_APPLICATION: 422,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_INSUFFICIENT_WALLET: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_STALE_VEHICLE_VERSION: 412,
    ApiErrorId.ERR_STALE_RIDER_VERSION: 412,
    ApiErrorId.ERR_OUTSTANDING_FINES: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
