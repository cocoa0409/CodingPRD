"""Helpers shared by the route modules."""

import envelope
import store
import validate


def list_response(rows):
    limit, offset = validate.pagination()
    page, total = validate.paginate(rows, limit, offset)
    return envelope.array_response(store.public_list(page), limit, offset, total)


def one(row):
    return envelope.object_response(store.public(row))


def one_created(row):
    return envelope.created(store.public(row))


