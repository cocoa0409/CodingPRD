"""Error catalog for the Seasonal Confection Planning API.

Every error_id and HTTP status below is taken verbatim from SCAFFOLD.yaml
section 1.6 / PRD.md section 5. No name is invented.
"""


class ApiError(Exception):
    """Carries (http_status, error_id, message) to the envelope renderer."""

    def __init__(self, http_status, error_id, message):
        super().__init__(message)
        self.http_status = http_status
        self.error_id = error_id
        self.message = message


