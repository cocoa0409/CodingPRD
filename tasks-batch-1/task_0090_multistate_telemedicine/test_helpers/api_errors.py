"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so validate_error()
can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_COMPACT_INELIGIBLE = "ERR_COMPACT_INELIGIBLE"
    ERR_LICENSE_PERIOD_OVERLAP = "ERR_LICENSE_PERIOD_OVERLAP"
    ERR_VISIT_SLOT_CONFLICT = "ERR_VISIT_SLOT_CONFLICT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEA_EXAM_REQUIRED = "ERR_DEA_EXAM_REQUIRED"
    ERR_NO_CONTROLLED_AUTHORITY = "ERR_NO_CONTROLLED_AUTHORITY"
    ERR_MODALITY_NOT_PERMITTED = "ERR_MODALITY_NOT_PERMITTED"
    ERR_NO_LICENSE_IN_STATE = "ERR_NO_LICENSE_IN_STATE"
    ERR_STALE_PRESCRIPTION_VERSION = "ERR_STALE_PRESCRIPTION_VERSION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_NOT_DUE = "ERR_NOT_DUE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_COMPACT_INELIGIBLE: 422,
    ApiErrorId.ERR_LICENSE_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_VISIT_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEA_EXAM_REQUIRED: 422,
    ApiErrorId.ERR_NO_CONTROLLED_AUTHORITY: 422,
    ApiErrorId.ERR_MODALITY_NOT_PERMITTED: 422,
    ApiErrorId.ERR_NO_LICENSE_IN_STATE: 422,
    ApiErrorId.ERR_STALE_PRESCRIPTION_VERSION: 412,
    ApiErrorId.ERR_PAGINATION_INVALID: 422,
    ApiErrorId.ERR_NOT_DUE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
