def err(error_id, message):
    status_map = {
        ERR_AUTH: 400, ERR_VALIDATION: 400, ERR_FORBIDDEN: 403,
        ERR_STALE_VERSION: 412,
    }
    if error_id in status_map:
        status = status_map[error_id]
    elif error_id.endswith("_NOT_FOUND"):
        status = 404
    elif error_id in (
        ERR_NEGOTIATION_ROUND_LIMIT, ERR_OFFER_EXPIRED,
        ERR_START_DATE_BEFORE_CREDENTIAL_ETA, ERR_ITEM_DEPENDENCY_NOT_APPROVED,
        ERR_SEGREGATION_OF_DUTIES, ERR_TEMPLATES_INSUFFICIENT,
        ERR_TEMPLATE_OVERLAP, ERR_START_DATE_NOT_REACHED,
        ERR_PANEL_CAPACITY_EXCEEDED, ERR_NEGATIVE_CENSUS,
        ERR_CAMPAIGN_BUDGET_EXCEEDED, ERR_EVENT_WINDOW_OVERLAP,
        ERR_REPAYMENT_EXCEEDS_OUTSTANDING, ERR_REPORTING_WINDOW_CLOSED,
        ERR_MENTOR_NOT_ACTIVE_PHYSICIAN, ERR_MENTOR_SPECIALTY_MISMATCH,
        ERR_MENTOR_IS_MENTEE, ERR_CHECKINS_INCOMPLETE,
        ERR_CHECKIN_OUT_OF_ORDER,
    ):
        status = 422
    else:
        status = 409
    return ApiError(error_id, status, message)
