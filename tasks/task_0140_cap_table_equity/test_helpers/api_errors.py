"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TABLE_NOT_OPEN = "ERR_TABLE_NOT_OPEN"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_409A_NONCOMPLIANT = "ERR_409A_NONCOMPLIANT"
    ERR_VALUATION_EXPIRED = "ERR_VALUATION_EXPIRED"
    ERR_WRONG_CLASS_TYPE = "ERR_WRONG_CLASS_TYPE"
    ERR_SENIORITY_CYCLE = "ERR_SENIORITY_CYCLE"
    ERR_83B_WINDOW_MISSED = "ERR_83B_WINDOW_MISSED"
    ERR_EXCEEDS_EXERCISABLE = "ERR_EXCEEDS_EXERCISABLE"
    ERR_POOL_INSUFFICIENT = "ERR_POOL_INSUFFICIENT"
    ERR_AUTHORIZED_EXCEEDED = "ERR_AUTHORIZED_EXCEEDED"
    ERR_GRANT_HAS_EXERCISES = "ERR_GRANT_HAS_EXERCISES"
    ERR_ELECTION_BLOCKS_REVERSE = "ERR_ELECTION_BLOCKS_REVERSE"
    ERR_VALUATION_WINDOW_OVERLAP = "ERR_VALUATION_WINDOW_OVERLAP"
    ERR_BLACKOUT_OVERLAP = "ERR_BLACKOUT_OVERLAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_TABLE_NOT_OPEN: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_409A_NONCOMPLIANT: 422,
    ApiErrorId.ERR_VALUATION_EXPIRED: 422,
    ApiErrorId.ERR_WRONG_CLASS_TYPE: 422,
    ApiErrorId.ERR_SENIORITY_CYCLE: 422,
    ApiErrorId.ERR_83B_WINDOW_MISSED: 422,
    ApiErrorId.ERR_EXCEEDS_EXERCISABLE: 422,
    ApiErrorId.ERR_POOL_INSUFFICIENT: 422,
    ApiErrorId.ERR_AUTHORIZED_EXCEEDED: 422,
    ApiErrorId.ERR_GRANT_HAS_EXERCISES: 409,
    ApiErrorId.ERR_ELECTION_BLOCKS_REVERSE: 409,
    ApiErrorId.ERR_VALUATION_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_BLACKOUT_OVERLAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
