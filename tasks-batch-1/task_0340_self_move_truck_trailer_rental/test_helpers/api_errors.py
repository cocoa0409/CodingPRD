"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can auto-check
the HTTP status code without each test passing expected_status explicitly.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_COVERAGE_MISMATCH = "ERR_COVERAGE_MISMATCH"
    ERR_ONE_WAY_DROPOFF_NOT_ALLOWED = "ERR_ONE_WAY_DROPOFF_NOT_ALLOWED"
    ERR_INVALID_TRANSFER = "ERR_INVALID_TRANSFER"
    ERR_ODOMETER_REGRESSION = "ERR_ODOMETER_REGRESSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LICENSE_NOT_VERIFIED = "ERR_LICENSE_NOT_VERIFIED"
    ERR_COVERAGE_REQUIRED = "ERR_COVERAGE_REQUIRED"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_RESERVATION_LOCKED = "ERR_RESERVATION_LOCKED"
    ERR_NO_EQUIPMENT_AVAILABLE = "ERR_NO_EQUIPMENT_AVAILABLE"
    ERR_RETURN_LOT_FULL = "ERR_RETURN_LOT_FULL"
    ERR_EQUIPMENT_DOUBLE_BOOKED = "ERR_EQUIPMENT_DOUBLE_BOOKED"
    ERR_TRANSFER_IN_PROGRESS = "ERR_TRANSFER_IN_PROGRESS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_COVERAGE_MISMATCH: 422,
    ApiErrorId.ERR_ONE_WAY_DROPOFF_NOT_ALLOWED: 422,
    ApiErrorId.ERR_INVALID_TRANSFER: 422,
    ApiErrorId.ERR_ODOMETER_REGRESSION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LICENSE_NOT_VERIFIED: 409,
    ApiErrorId.ERR_COVERAGE_REQUIRED: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_RESERVATION_LOCKED: 409,
    ApiErrorId.ERR_NO_EQUIPMENT_AVAILABLE: 409,
    ApiErrorId.ERR_RETURN_LOT_FULL: 409,
    ApiErrorId.ERR_EQUIPMENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_TRANSFER_IN_PROGRESS: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
