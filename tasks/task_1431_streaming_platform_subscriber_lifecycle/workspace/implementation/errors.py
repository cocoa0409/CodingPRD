ERR_DUPLICATE_ACTIVE_SUBSCRIPTION = ("ERR_DUPLICATE_ACTIVE_SUBSCRIPTION", 409)


def raise_error(err_tuple, message=None):
    error_id, http_status = err_tuple
    raise ApiError(error_id, http_status, message or error_id)
