"""Error IDs and HTTP status mapping (PRD §5).

Registers the error_id -> HTTP status map with the framework at import time so
validate_error() auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_RESOURCE_NOT_FOUND = "ERR_REFERENCED_RESOURCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SECTION_MISMATCH = "ERR_SECTION_MISMATCH"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_SEAT_WINDOW_CONFLICT = "ERR_SEAT_WINDOW_CONFLICT"
    ERR_PARKING_ZONE_FULL = "ERR_PARKING_ZONE_FULL"
    ERR_TRANSFER_NOT_ELIGIBLE = "ERR_TRANSFER_NOT_ELIGIBLE"
    ERR_PAYMENT_PLAN_EXISTS = "ERR_PAYMENT_PLAN_EXISTS"
    ERR_STALE_SUBSCRIPTION_VERSION = "ERR_STALE_SUBSCRIPTION_VERSION"
    ERR_VALIDATION_FROM_TERMINAL = "ERR_VALIDATION_FROM_TERMINAL"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SECTION_MISMATCH: 422,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_SEAT_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_PARKING_ZONE_FULL: 409,
    ApiErrorId.ERR_TRANSFER_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_PAYMENT_PLAN_EXISTS: 409,
    ApiErrorId.ERR_STALE_SUBSCRIPTION_VERSION: 412,
    ApiErrorId.ERR_VALIDATION_FROM_TERMINAL: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
