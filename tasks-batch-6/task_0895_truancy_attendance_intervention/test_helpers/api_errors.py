"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TIER_REGRESSION = "ERR_TIER_REGRESSION"
    ERR_CASE_ALREADY_OPEN = "ERR_CASE_ALREADY_OPEN"
    ERR_CASE_NOT_COURT_ELIGIBLE = "ERR_CASE_NOT_COURT_ELIGIBLE"
    ERR_NO_CONFERENCE_HELD = "ERR_NO_CONFERENCE_HELD"
    ERR_INVALID_STAFF_ROLE = "ERR_INVALID_STAFF_ROLE"
    ERR_CASELOAD_EXCEEDED = "ERR_CASELOAD_EXCEEDED"
    ERR_CONFERENCE_OVERLAP = "ERR_CONFERENCE_OVERLAP"
    ERR_HEARING_OVERLAP = "ERR_HEARING_OVERLAP"
    ERR_GOAL_NOT_FOUND = "ERR_GOAL_NOT_FOUND"
    ERR_STUDENT_NOT_ENROLLED = "ERR_STUDENT_NOT_ENROLLED"
    ERR_DUPLICATE_ATTENDANCE = "ERR_DUPLICATE_ATTENDANCE"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_TIER_REGRESSION: 409,
    ApiErrorId.ERR_CASE_ALREADY_OPEN: 409,
    ApiErrorId.ERR_CASE_NOT_COURT_ELIGIBLE: 409,
    ApiErrorId.ERR_NO_CONFERENCE_HELD: 409,
    ApiErrorId.ERR_INVALID_STAFF_ROLE: 409,
    ApiErrorId.ERR_CASELOAD_EXCEEDED: 409,
    ApiErrorId.ERR_CONFERENCE_OVERLAP: 409,
    ApiErrorId.ERR_HEARING_OVERLAP: 409,
    ApiErrorId.ERR_GOAL_NOT_FOUND: 404,
    ApiErrorId.ERR_STUDENT_NOT_ENROLLED: 409,
    ApiErrorId.ERR_DUPLICATE_ATTENDANCE: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
