"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_LOAN_NOT_FOUND = "ERR_LOAN_NOT_FOUND"
    ERR_BORROWER_NOT_FOUND = "ERR_BORROWER_NOT_FOUND"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PLAN_ALREADY_ACTIVE = "ERR_PLAN_ALREADY_ACTIVE"
    ERR_NOT_VETERAN = "ERR_NOT_VETERAN"
    ERR_PSLF_INSUFFICIENT_PAYMENTS = "ERR_PSLF_INSUFFICIENT_PAYMENTS"
    ERR_DEFAULT_THRESHOLD_NOT_MET = "ERR_DEFAULT_THRESHOLD_NOT_MET"
    ERR_REHABILITATION_NOT_QUALIFIED = "ERR_REHABILITATION_NOT_QUALIFIED"
    ERR_STALE_LOAN_VERSION = "ERR_STALE_LOAN_VERSION"
    ERR_STALE_APPLICATION_VERSION = "ERR_STALE_APPLICATION_VERSION"
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_FUTURE_PAYMENT = "ERR_FUTURE_PAYMENT"
    ERR_PAYMENT_AMOUNT_OUT_OF_RANGE = "ERR_PAYMENT_AMOUNT_OUT_OF_RANGE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED.value: 401,
    ApiErrorId.ERR_UNAUTHORIZED.value: 403,
    ApiErrorId.ERR_LOAN_NOT_FOUND.value: 404,
    ApiErrorId.ERR_BORROWER_NOT_FOUND.value: 404,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND.value: 404,
    ApiErrorId.ERR_INVALID_STATE.value: 409,
    ApiErrorId.ERR_PLAN_ALREADY_ACTIVE.value: 409,
    ApiErrorId.ERR_NOT_VETERAN.value: 422,
    ApiErrorId.ERR_PSLF_INSUFFICIENT_PAYMENTS.value: 422,
    ApiErrorId.ERR_DEFAULT_THRESHOLD_NOT_MET.value: 422,
    ApiErrorId.ERR_REHABILITATION_NOT_QUALIFIED.value: 422,
    ApiErrorId.ERR_STALE_LOAN_VERSION.value: 412,
    ApiErrorId.ERR_STALE_APPLICATION_VERSION.value: 412,
    ApiErrorId.ERR_INVALID_PERIOD.value: 422,
    ApiErrorId.ERR_FUTURE_PAYMENT.value: 422,
    ApiErrorId.ERR_PAYMENT_AMOUNT_OUT_OF_RANGE.value: 422,
    ApiErrorId.ERR_INVALID_REQUEST.value: 400,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
