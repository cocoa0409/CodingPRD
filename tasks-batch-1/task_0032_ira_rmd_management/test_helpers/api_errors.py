"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_INVALID_ROLE = "ERR_INVALID_ROLE"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_CONVERSION_PAIR = "ERR_INVALID_CONVERSION_PAIR"
    ERR_KIND_ACCOUNT_MISMATCH = "ERR_KIND_ACCOUNT_MISMATCH"
    ERR_TAX_YEAR_CLOSED = "ERR_TAX_YEAR_CLOSED"
    ERR_BENEFICIARY_SHARES_INVALID = "ERR_BENEFICIARY_SHARES_INVALID"
    ERR_CONTRIBUTION_CAP_EXCEEDED = "ERR_CONTRIBUTION_CAP_EXCEEDED"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_SECURE_DEADLINE_PASSED = "ERR_SECURE_DEADLINE_PASSED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_INVALID_ROLE: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_CONVERSION_PAIR: 422,
    ApiErrorId.ERR_KIND_ACCOUNT_MISMATCH: 422,
    ApiErrorId.ERR_TAX_YEAR_CLOSED: 422,
    ApiErrorId.ERR_BENEFICIARY_SHARES_INVALID: 422,
    ApiErrorId.ERR_CONTRIBUTION_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 422,
    ApiErrorId.ERR_SECURE_DEADLINE_PASSED: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
