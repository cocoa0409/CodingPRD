"""Error classes and error-id constants for the EV-charger install API."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status), from SCAFFOLD §1.6 / PRD §5.
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_RESOURCE_OWNER = ("ERR_NOT_RESOURCE_OWNER", 403)
ERR_RESOURCE_NOT_FOUND = ("ERR_RESOURCE_NOT_FOUND", 404)
ERR_FK_NOT_FOUND = ("ERR_FK_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_JOB_VERSION = ("ERR_STALE_JOB_VERSION", 412)
ERR_COMPLIANCE_NOT_CLEARED = ("ERR_COMPLIANCE_NOT_CLEARED", 409)
ERR_PANEL_UPGRADE_REQUIRED = ("ERR_PANEL_UPGRADE_REQUIRED", 409)
ERR_ELECTRICIAN_OUT_OF_TERRITORY = ("ERR_ELECTRICIAN_OUT_OF_TERRITORY", 422)
ERR_TERRITORY_MISMATCH = ("ERR_TERRITORY_MISMATCH", 422)
ERR_WINDOW_OVERLAP = ("ERR_WINDOW_OVERLAP", 409)
ERR_DAILY_CAPACITY_EXCEEDED = ("ERR_DAILY_CAPACITY_EXCEEDED", 409)
ERR_CIRCUIT_EXCEEDS_PANEL = ("ERR_CIRCUIT_EXCEEDS_PANEL", 422)
ERR_INCENTIVE_FULLY_ABSORBED = ("ERR_INCENTIVE_FULLY_ABSORBED", 422)
ERR_ELECTRICIAN_SUSPENDED = ("ERR_ELECTRICIAN_SUSPENDED", 409)
ERR_PERMIT_REJECTED_FINAL = ("ERR_PERMIT_REJECTED_FINAL", 409)
ERR_REOPEN_LIMIT_REACHED = ("ERR_REOPEN_LIMIT_REACHED", 409)
ERR_JOB_NOT_ACTIVATED = ("ERR_JOB_NOT_ACTIVATED", 409)
ERR_OPEN_WARRANTY_BLOCKS_CLOSE = ("ERR_OPEN_WARRANTY_BLOCKS_CLOSE", 409)
ERR_VALIDATION_LIMIT = ("ERR_VALIDATION_LIMIT", 422)


def err(catalog_tuple, message=None):
    """Build an ApiError from a (error_id, http_status) catalog tuple."""
    error_id, http_status = catalog_tuple
    return ApiError(error_id, http_status, message)
