"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() auto-checks the HTTP status alongside the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ACCOUNT_VERSION = "ERR_STALE_ACCOUNT_VERSION"
    ERR_DUPLICATE_BILL = "ERR_DUPLICATE_BILL"
    ERR_READ_REGRESSION = "ERR_READ_REGRESSION"
    ERR_MORATORIUM_ACTIVE = "ERR_MORATORIUM_ACTIVE"
    ERR_SHUTOFF_PROTECTED = "ERR_SHUTOFF_PROTECTED"
    ERR_SHUTOFF_NOT_DUE = "ERR_SHUTOFF_NOT_DUE"
    ERR_BILL_NOT_POSTED = "ERR_BILL_NOT_POSTED"
    ERR_ARREARS_BELOW_THRESHOLD = "ERR_ARREARS_BELOW_THRESHOLD"
    ERR_NO_LEAK_VOLUME = "ERR_NO_LEAK_VOLUME"
    ERR_NOT_EXECUTED = "ERR_NOT_EXECUTED"
    ERR_BILL_HAS_PAYMENT = "ERR_BILL_HAS_PAYMENT"
    ERR_CYCLE_CLOSED = "ERR_CYCLE_CLOSED"
    ERR_NO_CONSUMPTION_DATA = "ERR_NO_CONSUMPTION_DATA"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ACCOUNT_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE_BILL: 409,
    ApiErrorId.ERR_READ_REGRESSION: 422,
    ApiErrorId.ERR_MORATORIUM_ACTIVE: 409,
    ApiErrorId.ERR_SHUTOFF_PROTECTED: 409,
    ApiErrorId.ERR_SHUTOFF_NOT_DUE: 409,
    ApiErrorId.ERR_BILL_NOT_POSTED: 409,
    ApiErrorId.ERR_ARREARS_BELOW_THRESHOLD: 409,
    ApiErrorId.ERR_NO_LEAK_VOLUME: 422,
    ApiErrorId.ERR_NOT_EXECUTED: 409,
    ApiErrorId.ERR_BILL_HAS_PAYMENT: 409,
    ApiErrorId.ERR_CYCLE_CLOSED: 409,
    ApiErrorId.ERR_NO_CONSUMPTION_DATA: 422,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
