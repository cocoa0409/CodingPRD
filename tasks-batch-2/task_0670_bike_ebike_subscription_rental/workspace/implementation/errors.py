ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
ERR_NOT_FLEET_ACCOUNT = "ERR_NOT_FLEET_ACCOUNT"

_HTTP = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN_ROLE: 403,
    ERR_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_STALE_MODEL_VERSION: 412,
    ERR_BIKE_RETIRED: 409,
    ERR_DELIVERY_TYPE_MISMATCH: 409,
    ERR_DELIVERY_WINDOW_CONFLICT: 409,
    ERR_BIKE_ALREADY_SERVICING: 409,
    ERR_OFFER_EXPIRED: 409,
    ERR_PAYOUT_EXCEEDS_CAP: 422,
    ERR_RENTAL_CAP_EXCEEDED: 409,
    ERR_NO_BIKES_AVAILABLE: 409,
    ERR_ACCOUNT_SUSPENDED: 409,
    ERR_INVALID_REQUEST: 400,
    ERR_DUPLICATE_RESOURCE: 409,
    ERR_NOT_FLEET_ACCOUNT: 409,
}


def err(error_id, message=None):
    return ApiError(error_id, _HTTP[error_id], message)
