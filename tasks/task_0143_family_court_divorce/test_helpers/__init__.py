"""Barrel export: framework generics + PRD-specific test infrastructure.

Tests import everything from `test_helpers` and never reach into
sub-modules directly.

PRD §2.1 identity rules:
- Judge, Mediator, PlatformAdmin are OPAQUE — shared *_headers
  constants are canonical for those roles.
- Petitioner / Respondent are ENTITY-BACKED — every ownership-gated
  call MUST mint headers via make_petitioner_headers(case[
  'petitioner_party_id']) or make_respondent_headers(case[
  'respondent_party_id']).
- AttorneyOfRecord is OPAQUE BUT its X-User-ID must match the
  Party.counsel_user_id pinned at case creation; tests that want an
  attorney caller create the case with the matching
  *_counsel_user_id set in the payload.
"""
