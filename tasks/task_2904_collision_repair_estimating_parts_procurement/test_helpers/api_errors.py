"""The error catalogue, grouped by the rung of the validation ladder it sits on.

The HTTP status of every identifier is registered with the framework so that a
`validate_error` call cross-checks the status without the caller restating it.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


