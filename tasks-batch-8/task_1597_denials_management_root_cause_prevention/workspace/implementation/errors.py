"""Error types and error-id constants for the Denials Management API."""


class ApiError(Exception):
    """Exception carrying the envelope error_id, HTTP status, and message."""

    def __init__(self, error_id, status, message):
        super().__init__(message)
        self.error_id = error_id
        self.status = status
        self.message = message


