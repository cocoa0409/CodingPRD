"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_SLOT_VERSION = "ERR_STALE_SLOT_VERSION"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_AGE_REQUIREMENT_NOT_MET = "ERR_AGE_REQUIREMENT_NOT_MET"
    ERR_WAIVER_NOT_SIGNED = "ERR_WAIVER_NOT_SIGNED"
    ERR_GROUP_SIZE_INVALID = "ERR_GROUP_SIZE_INVALID"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_NO_GAMEMASTER_AVAILABLE = "ERR_NO_GAMEMASTER_AVAILABLE"
    ERR_NO_SHOW_LIMIT_REACHED = "ERR_NO_SHOW_LIMIT_REACHED"
    ERR_GIFT_CARD_UNUSABLE = "ERR_GIFT_CARD_UNUSABLE"
    ERR_OUTSIDE_OPERATING_HOURS = "ERR_OUTSIDE_OPERATING_HOURS"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_ROOM_RETIRED = "ERR_ROOM_RETIRED"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_SLOT_VERSION: 412,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_AGE_REQUIREMENT_NOT_MET: 409,
    ApiErrorId.ERR_WAIVER_NOT_SIGNED: 409,
    ApiErrorId.ERR_GROUP_SIZE_INVALID: 409,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_NO_GAMEMASTER_AVAILABLE: 409,
    ApiErrorId.ERR_NO_SHOW_LIMIT_REACHED: 409,
    ApiErrorId.ERR_GIFT_CARD_UNUSABLE: 409,
    ApiErrorId.ERR_OUTSIDE_OPERATING_HOURS: 409,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_ROOM_RETIRED: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
