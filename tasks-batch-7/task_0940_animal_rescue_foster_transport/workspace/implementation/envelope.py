"""The standard response envelope (PRD 2.2) and pagination meta (PRD 2.3)."""

from flask import jsonify

import clock
import ids


def _meta():
    return {
        "api_request_id": ids.new_request_id(),
        # (a) server-minted instant: canonical three-fractional-digit rendering.
        "api_request_timestamp": clock.canonical(clock.now()),
    }


def ok(data, status=200):
    body = {"meta": _meta(), "response_type": "object", "data": data if data is not None else {}}
    return jsonify(body), status


def created(data):
    return ok(data, 201)


def listing(rows, limit, offset, total_count):
    meta = _meta()
    meta["limit"] = limit
    meta["offset"] = offset
    meta["total_count"] = total_count
    meta["has_more"] = (offset + len(rows)) < total_count
    body = {"meta": meta, "response_type": "array", "data": rows}
    return jsonify(body), 200


def error(error_id, message, status):
    body = {
        "meta": _meta(),
        "response_type": "error",
        "data": {"error_id": error_id, "message": message},
    }
    return jsonify(body), status
