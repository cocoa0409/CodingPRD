"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REFERENCE = "ERR_INVALID_REFERENCE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_MEMBER_NOT_REGISTERED = "ERR_MEMBER_NOT_REGISTERED"
    ERR_REQUIREMENTS_INCOMPLETE = "ERR_REQUIREMENTS_INCOMPLETE"
    ERR_FORMS_INCOMPLETE = "ERR_FORMS_INCOMPLETE"
    ERR_BOOTH_CONFLICT = "ERR_BOOTH_CONFLICT"
    ERR_MEMBER_DOUBLE_BOOKED = "ERR_MEMBER_DOUBLE_BOOKED"
    ERR_EVENT_FULL = "ERR_EVENT_FULL"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_INSUFFICIENT_TROOP_FUNDS = "ERR_INSUFFICIENT_TROOP_FUNDS"
    ERR_RECHARTER_NOT_READY = "ERR_RECHARTER_NOT_READY"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"
    ERR_DUPLICATE_UNIT_NUMBER = "ERR_DUPLICATE_UNIT_NUMBER"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REFERENCE: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_MEMBER_NOT_REGISTERED: 409,
    ApiErrorId.ERR_REQUIREMENTS_INCOMPLETE: 409,
    ApiErrorId.ERR_FORMS_INCOMPLETE: 409,
    ApiErrorId.ERR_BOOTH_CONFLICT: 409,
    ApiErrorId.ERR_MEMBER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_EVENT_FULL: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_INSUFFICIENT_TROOP_FUNDS: 409,
    ApiErrorId.ERR_RECHARTER_NOT_READY: 409,
    ApiErrorId.ERR_OVERPAYMENT: 409,
    ApiErrorId.ERR_DUPLICATE_UNIT_NUMBER: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
