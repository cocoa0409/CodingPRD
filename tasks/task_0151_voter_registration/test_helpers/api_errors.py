"""Error IDs and HTTP status mapping — PRD §5 Error Code Catalogue.

After definition, the mapping is registered with the framework so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # 400
    ERR_BAD_REQUEST = "ERR_BAD_REQUEST"
    # 401
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    # 403
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_FORBIDDEN_SOD = "ERR_FORBIDDEN_SOD"
    # 404
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # 409
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"
    ERR_DEADLINE_PASSED = "ERR_DEADLINE_PASSED"
    ERR_DOUBLE_VOTE = "ERR_DOUBLE_VOTE"
    ERR_PARTY_LOCKED = "ERR_PARTY_LOCKED"
    ERR_ABSENTEE_ALREADY_ISSUED = "ERR_ABSENTEE_ALREADY_ISSUED"
    ERR_VOTER_NOT_ACTIVE = "ERR_VOTER_NOT_ACTIVE"
    ERR_RETURN_LATE = "ERR_RETURN_LATE"
    ERR_MAX_ROUNDS_REACHED = "ERR_MAX_ROUNDS_REACHED"
    ERR_CURING_IN_PROGRESS = "ERR_CURING_IN_PROGRESS"
    ERR_MACHINE_FAILURE = "ERR_MACHINE_FAILURE"
    ERR_VOTER_HAS_BALLOT = "ERR_VOTER_HAS_BALLOT"
    ERR_TALLY_TOO_EARLY = "ERR_TALLY_TOO_EARLY"
    ERR_RECOUNT_REQUIRED = "ERR_RECOUNT_REQUIRED"
    ERR_RECOUNT_NO_OVERTURN = "ERR_RECOUNT_NO_OVERTURN"
    ERR_NO_PRECINCTS = "ERR_NO_PRECINCTS"
    # 422
    ERR_NOT_CITIZEN = "ERR_NOT_CITIZEN"
    ERR_UNDER_AGE = "ERR_UNDER_AGE"
    ERR_RESIDENCY_INSUFFICIENT = "ERR_RESIDENCY_INSUFFICIENT"
    ERR_NO_PRECINCT_MATCH = "ERR_NO_PRECINCT_MATCH"
    ERR_RECOUNT_PETITION_INSUFFICIENT = "ERR_RECOUNT_PETITION_INSUFFICIENT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_BAD_REQUEST: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_FORBIDDEN_SOD: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_DOUBLE_VOTE: 409,
    ApiErrorId.ERR_PARTY_LOCKED: 409,
    ApiErrorId.ERR_ABSENTEE_ALREADY_ISSUED: 409,
    ApiErrorId.ERR_VOTER_NOT_ACTIVE: 409,
    ApiErrorId.ERR_RETURN_LATE: 409,
    ApiErrorId.ERR_MAX_ROUNDS_REACHED: 409,
    ApiErrorId.ERR_CURING_IN_PROGRESS: 409,
    ApiErrorId.ERR_MACHINE_FAILURE: 409,
    ApiErrorId.ERR_VOTER_HAS_BALLOT: 409,
    ApiErrorId.ERR_TALLY_TOO_EARLY: 409,
    ApiErrorId.ERR_RECOUNT_REQUIRED: 409,
    ApiErrorId.ERR_RECOUNT_NO_OVERTURN: 409,
    ApiErrorId.ERR_NO_PRECINCTS: 409,
    ApiErrorId.ERR_NOT_CITIZEN: 422,
    ApiErrorId.ERR_UNDER_AGE: 422,
    ApiErrorId.ERR_RESIDENCY_INSUFFICIENT: 422,
    ApiErrorId.ERR_NO_PRECINCT_MATCH: 422,
    ApiErrorId.ERR_RECOUNT_PETITION_INSUFFICIENT: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
