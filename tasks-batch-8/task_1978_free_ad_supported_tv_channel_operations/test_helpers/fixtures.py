def create_active_campaign(*, cpm_cents=500, iab_category="IAB-9",
                           total_budget_cents=100000, daily_budget_cents=100000,
                           creative_duration_seconds=30, brand="Acme Soda",
                           advertiser_name="Acme", priority=None,
                           creator_id="ops-1", reviewer_id="rev-1"):
    """Campaign DRAFT -> creative APPROVED -> campaign ACTIVE. Returns (campaign, creative)."""
    campaign_payload = factories.create_ad_campaign_payload(
        advertiser_name=advertiser_name,
        iab_category=iab_category,
        total_budget_cents=total_budget_cents,
        daily_budget_cents=daily_budget_cents,
        cpm_cents=cpm_cents,
    )
    if priority is not None:
        campaign_payload["priority"] = priority
    campaign = get_success_data(
        api_client.create_ad_campaign(campaign_payload, make_adops_headers(creator_id))
    )
    creative = get_success_data(
        api_client.create_ad_creative(
            factories.create_ad_creative_payload(
                campaign["id"], brand=brand, iab_category=iab_category,
                duration_seconds=creative_duration_seconds,
            ),
            make_adops_headers(creator_id),
        )
    )
    get_success_data(api_client.creative_approve(creative["id"], make_reviewer_headers(reviewer_id)))
    campaign = get_success_data(
        api_client.campaign_activate(campaign["id"], make_adops_headers(creator_id))
    )
    return campaign, get_creative(creative["id"])


def create_active_house_ad(*, name="House Promo", priority_weight=5,
                           daily_impression_cap=5, channel_id=None, creator_id="ops-1"):
    payload = factories.create_house_ad_payload(
        name=name, priority_weight=priority_weight,
        daily_impression_cap=daily_impression_cap,
    )
    if channel_id is not None:
        payload["channel_id"] = channel_id
    return get_success_data(
        api_client.create_house_ad(payload, make_adops_headers(creator_id))
    )


def run_decision_run(break_id, operator_id="ops-1"):
    """Decision run with a fresh OCC read of AdBreak.version (PRD §2.8).
    Returns the created FillDecision rows (list)."""
    brk = get_break(break_id)
    return get_success_data(
        api_client.break_decision_run(
            break_id, {"expected_break_version": brk["version"]},
            make_adops_headers(operator_id),
        )
    )


def setup_locked_loop(*, campaign_specs=None, house_ad_specs=None, operator_id="ops-1",
                      **loop_kwargs):
    """Validated loop + (optional campaigns / house ads) + decision run per break
    + LOCKED. campaign_specs: list of kwargs dicts for create_active_campaign."""
    ctx = setup_validated_loop(**loop_kwargs)
    campaigns = []
    for spec in campaign_specs or []:
        campaigns.append(create_active_campaign(**spec))
    house_ads = []
    for spec in house_ad_specs or []:
        house_ads.append(create_active_house_ad(**spec))
    decisions_by_break = {}
    for brk in ctx["breaks"]:
        decisions_by_break[brk["id"]] = run_decision_run(brk["id"], operator_id)
    loop = get_success_data(api_client.loop_lock(ctx["loop"]["id"], PROGRAMMER))
    ctx.update({
        "loop": loop,
        "campaigns": campaigns,
        "house_ads": house_ads,
        "decisions_by_break": decisions_by_break,
    })
    return ctx


def setup_published_loop(operator_id="ops-1", **kwargs):
    """Full chain through PUBLISHED: locked loop -> channel LIVE -> publish."""
    ctx = setup_locked_loop(operator_id=operator_id, **kwargs)
    go_live(ctx["channel"]["id"])
    loop = publish_loop(ctx["loop"]["id"], ctx["channel"]["id"])
    ctx["loop"] = loop
    ctx["channel"] = get_channel(ctx["channel"]["id"])
    return ctx


