def err(error_id: ApiErrorId) -> str:
    """Return the plain string form of an error identifier."""
    return error_id.value if isinstance(error_id, ApiErrorId) else str(error_id)


# Register with the framework so validate_error() cross-checks HTTP status.
set_error_http_status_map({err(k): v for k, v in HTTP_STATUS_CODES.items()})
