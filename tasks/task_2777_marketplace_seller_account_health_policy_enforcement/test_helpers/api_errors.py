    LISTING_SELLER_MISMATCH = "ERR_LISTING_SELLER_MISMATCH"
    LISTING_REQUIRED_FOR_SCOPE = "ERR_LISTING_REQUIRED_FOR_SCOPE"
    REPORTER_NOT_ELIGIBLE = "ERR_REPORTER_NOT_ELIGIBLE"
    POA_ACTION_MISMATCH = "ERR_POA_ACTION_MISMATCH"
    HOLD_ACTION_SELLER_MISMATCH = "ERR_HOLD_ACTION_SELLER_MISMATCH"

    # Money capacity
    HOLD_EXCEEDS_AVAILABLE = "ERR_HOLD_EXCEEDS_AVAILABLE"
    FORFEIT_EXCEEDS_HOLD = "ERR_FORFEIT_EXCEEDS_HOLD"


