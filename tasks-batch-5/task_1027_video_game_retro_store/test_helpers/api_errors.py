"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ITEM_NOT_AVAILABLE = "ERR_ITEM_NOT_AVAILABLE"
    ERR_ALLOCATION_NOT_READY = "ERR_ALLOCATION_NOT_READY"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_RENTAL_OVERLAP = "ERR_RENTAL_OVERLAP"
    ERR_STATION_DOUBLE_BOOKED = "ERR_STATION_DOUBLE_BOOKED"
    ERR_REGISTRATION_CLOSED = "ERR_REGISTRATION_CLOSED"
    ERR_TOURNAMENT_FULL = "ERR_TOURNAMENT_FULL"
    ERR_ALREADY_REGISTERED = "ERR_ALREADY_REGISTERED"
    ERR_ONE_ACTIVE_PREORDER = "ERR_ONE_ACTIVE_PREORDER"
    ERR_INSUFFICIENT_STORE_CREDIT = "ERR_INSUFFICIENT_STORE_CREDIT"
    ERR_INSUFFICIENT_PAYMENT = "ERR_INSUFFICIENT_PAYMENT"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ITEM_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_ALLOCATION_NOT_READY: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_RENTAL_OVERLAP: 409,
    ApiErrorId.ERR_STATION_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_REGISTRATION_CLOSED: 409,
    ApiErrorId.ERR_TOURNAMENT_FULL: 409,
    ApiErrorId.ERR_ALREADY_REGISTERED: 409,
    ApiErrorId.ERR_ONE_ACTIVE_PREORDER: 409,
    ApiErrorId.ERR_INSUFFICIENT_STORE_CREDIT: 402,
    ApiErrorId.ERR_INSUFFICIENT_PAYMENT: 402,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
