    ERR_HARVEST_BLOCKED_WITHDRAWAL = "ERR_HARVEST_BLOCKED_WITHDRAWAL"
    ERR_APIARY_NOT_REGISTERED = "ERR_APIARY_NOT_REGISTERED"
    ERR_HIVE_NOT_PLACEABLE = "ERR_HIVE_NOT_PLACEABLE"
    ERR_HIVE_DOUBLE_BOOKED = "ERR_HIVE_DOUBLE_BOOKED"
    ERR_SITE_CAPACITY_EXCEEDED = "ERR_SITE_CAPACITY_EXCEEDED"
    ERR_INSUFFICIENT_BROOD_FRAMES = "ERR_INSUFFICIENT_BROOD_FRAMES"
    ERR_YARD_CAPACITY_EXCEEDED = "ERR_YARD_CAPACITY_EXCEEDED"
