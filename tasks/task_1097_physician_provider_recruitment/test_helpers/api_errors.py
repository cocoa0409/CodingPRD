"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INTERVIEWER_INVALID = "ERR_INTERVIEWER_INVALID"
    ERR_SPECIALTY_MISMATCH = "ERR_SPECIALTY_MISMATCH"
    ERR_INTERVIEWER_DOUBLE_BOOKED = "ERR_INTERVIEWER_DOUBLE_BOOKED"
    ERR_CANDIDATE_TRAVEL_CONFLICT = "ERR_CANDIDATE_TRAVEL_CONFLICT"
    ERR_OPENING_NOT_OPEN = "ERR_OPENING_NOT_OPEN"
    ERR_COMP_OUT_OF_RANGE = "ERR_COMP_OUT_OF_RANGE"
    ERR_NO_COMPLETED_SITE_VISIT = "ERR_NO_COMPLETED_SITE_VISIT"
    ERR_CREDENTIALING_NOT_CLEARED = "ERR_CREDENTIALING_NOT_CLEARED"
    ERR_GUARANTEE_WINDOW_EXPIRED = "ERR_GUARANTEE_WINDOW_EXPIRED"
    ERR_NO_ELIGIBLE_RECRUITER = "ERR_NO_ELIGIBLE_RECRUITER"
    ERR_OPENING_FILLED = "ERR_OPENING_FILLED"
    ERR_FINAL_COMP_REQUIRED = "ERR_FINAL_COMP_REQUIRED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INTERVIEWER_INVALID: 422,
    ApiErrorId.ERR_SPECIALTY_MISMATCH: 422,
    ApiErrorId.ERR_INTERVIEWER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CANDIDATE_TRAVEL_CONFLICT: 409,
    ApiErrorId.ERR_OPENING_NOT_OPEN: 409,
    ApiErrorId.ERR_COMP_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_NO_COMPLETED_SITE_VISIT: 409,
    ApiErrorId.ERR_CREDENTIALING_NOT_CLEARED: 409,
    ApiErrorId.ERR_GUARANTEE_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_RECRUITER: 409,
    ApiErrorId.ERR_OPENING_FILLED: 409,
    ApiErrorId.ERR_FINAL_COMP_REQUIRED: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
