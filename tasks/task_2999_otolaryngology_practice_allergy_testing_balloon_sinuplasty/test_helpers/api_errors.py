"""The seventy-three error identifiers of the PRD error catalogue.

The mapping from identifier to HTTP status is registered with the framework's
validator module so that ``validate_error`` can cross-check the status code of
every rejection without each call site repeating it.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


