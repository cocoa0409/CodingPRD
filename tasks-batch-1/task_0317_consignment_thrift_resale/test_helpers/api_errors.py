"""Error IDs and HTTP status mapping (PRD Section 5).

After defining the mapping it is registered with the framework so
validate_error() auto-checks the HTTP status from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ITEM_VERSION = "ERR_STALE_ITEM_VERSION"
    ERR_STALE_SETTLEMENT_VERSION = "ERR_STALE_SETTLEMENT_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_AUTHENTICATION_REQUIRED = "ERR_AUTHENTICATION_REQUIRED"
    ERR_ITEM_NOT_ON_FLOOR = "ERR_ITEM_NOT_ON_FLOOR"
    ERR_DUPLICATE_SALE_LINE = "ERR_DUPLICATE_SALE_LINE"
    ERR_RETURN_WINDOW_NOT_ELAPSED = "ERR_RETURN_WINDOW_NOT_ELAPSED"
    ERR_RETURN_WINDOW_ELAPSED = "ERR_RETURN_WINDOW_ELAPSED"
    ERR_PRICE_BELOW_FLOOR = "ERR_PRICE_BELOW_FLOOR"
    ERR_SETTLEMENT_DATE_TAKEN = "ERR_SETTLEMENT_DATE_TAKEN"
    ERR_INSUFFICIENT_STORE_CREDIT = "ERR_INSUFFICIENT_STORE_CREDIT"
    ERR_INVALID_SCHEDULE = "ERR_INVALID_SCHEDULE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_AGREEMENT_PRECONDITION = "ERR_AGREEMENT_PRECONDITION"
    ERR_BATCH_CLOSED = "ERR_BATCH_CLOSED"
    ERR_AGREEMENT_TERMINATED = "ERR_AGREEMENT_TERMINATED"
    ERR_LIST_PRICE_REQUIRED = "ERR_LIST_PRICE_REQUIRED"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ITEM_VERSION: 412,
    ApiErrorId.ERR_STALE_SETTLEMENT_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_AUTHENTICATION_REQUIRED: 409,
    ApiErrorId.ERR_ITEM_NOT_ON_FLOOR: 409,
    ApiErrorId.ERR_DUPLICATE_SALE_LINE: 409,
    ApiErrorId.ERR_RETURN_WINDOW_NOT_ELAPSED: 409,
    ApiErrorId.ERR_RETURN_WINDOW_ELAPSED: 409,
    ApiErrorId.ERR_PRICE_BELOW_FLOOR: 422,
    ApiErrorId.ERR_SETTLEMENT_DATE_TAKEN: 409,
    ApiErrorId.ERR_INSUFFICIENT_STORE_CREDIT: 422,
    ApiErrorId.ERR_INVALID_SCHEDULE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_AGREEMENT_PRECONDITION: 409,
    ApiErrorId.ERR_BATCH_CLOSED: 409,
    ApiErrorId.ERR_AGREEMENT_TERMINATED: 409,
    ApiErrorId.ERR_LIST_PRICE_REQUIRED: 422,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
