    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_KEY = "ERR_DUPLICATE_KEY"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
    ERR_DELIVERY_REQUIRED = "ERR_DELIVERY_REQUIRED"
    ERR_UNIT_DOUBLE_BOOKED = "ERR_UNIT_DOUBLE_BOOKED"
    ERR_TRUCK_DOUBLE_BOOKED = "ERR_TRUCK_DOUBLE_BOOKED"
    ERR_START_IN_PAST = "ERR_START_IN_PAST"
    ERR_ACCOUNT_SUSPENDED = "ERR_ACCOUNT_SUSPENDED"
