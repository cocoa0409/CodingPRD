"""Error definitions for the ATS API."""


class ApiError(Exception):
    """Domain error carrying an error_id, HTTP status and human message."""

    def __init__(self, error_id: str, http_status: int, message: str = ""):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalogue from PRD §5.
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_PRECONDITION_FAILED = "ERR_PRECONDITION_FAILED"
ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
ERR_PANELIST_CONFLICT = "ERR_PANELIST_CONFLICT"
ERR_BGC_INDEPENDENCE = "ERR_BGC_INDEPENDENCE"
ERR_DUPLICATE_APPLICATION = "ERR_DUPLICATE_APPLICATION"
ERR_DUPLICATE_OFFER = "ERR_DUPLICATE_OFFER"
ERR_INVALID_PANEL = "ERR_INVALID_PANEL"
ERR_PANELIST_NOT_ASSIGNED = "ERR_PANELIST_NOT_ASSIGNED"
ERR_FEEDBACK_INCOMPLETE = "ERR_FEEDBACK_INCOMPLETE"
ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
ERR_INTERVIEW_OVERLAP_APPLICATION = "ERR_INTERVIEW_OVERLAP_APPLICATION"
ERR_INTERVIEW_OVERLAP_PANELIST = "ERR_INTERVIEW_OVERLAP_PANELIST"
ERR_SALARY_OUT_OF_BAND = "ERR_SALARY_OUT_OF_BAND"
ERR_BUDGET_EXCEEDED = "ERR_BUDGET_EXCEEDED"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_NOT_REFERRAL_ELIGIBLE = "ERR_NOT_REFERRAL_ELIGIBLE"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


def err(error_id: str, http: int, message: str = "") -> ApiError:
    return ApiError(error_id, http, message or error_id)
