"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping it is registered with the framework so that
validate_error() cross-checks the HTTP status code automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_KEY = "ERR_DUPLICATE_KEY"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INSTRUCTOR_LICENSE_INVALID = "ERR_INSTRUCTOR_LICENSE_INVALID"
    ERR_CLINIC_PHASE_NOT_REACHED = "ERR_CLINIC_PHASE_NOT_REACHED"
    ERR_STATION_DOUBLE_BOOKED = "ERR_STATION_DOUBLE_BOOKED"
    ERR_CLINIC_SLOT_CONFLICT = "ERR_CLINIC_SLOT_CONFLICT"
    ERR_STATION_UNAVAILABLE = "ERR_STATION_UNAVAILABLE"
    ERR_PERIOD_HOURS_NOT_EARNED = "ERR_PERIOD_HOURS_NOT_EARNED"
    ERR_PERIOD_WEEKS_NOT_ELAPSED = "ERR_PERIOD_WEEKS_NOT_ELAPSED"
    ERR_EXAM_NOT_READY = "ERR_EXAM_NOT_READY"
    ERR_OUTSTANDING_BALANCE = "ERR_OUTSTANDING_BALANCE"
    ERR_STALE_ENROLLMENT_VERSION = "ERR_STALE_ENROLLMENT_VERSION"
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_HOURS_EXCEED_SCHEDULED = "ERR_HOURS_EXCEED_SCHEDULED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_KEY: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INSTRUCTOR_LICENSE_INVALID: 409,
    ApiErrorId.ERR_CLINIC_PHASE_NOT_REACHED: 409,
    ApiErrorId.ERR_STATION_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CLINIC_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_STATION_UNAVAILABLE: 409,
    ApiErrorId.ERR_PERIOD_HOURS_NOT_EARNED: 409,
    ApiErrorId.ERR_PERIOD_WEEKS_NOT_ELAPSED: 409,
    ApiErrorId.ERR_EXAM_NOT_READY: 409,
    ApiErrorId.ERR_OUTSTANDING_BALANCE: 409,
    ApiErrorId.ERR_STALE_ENROLLMENT_VERSION: 412,
    ApiErrorId.ERR_INVALID_PERIOD: 409,
    ApiErrorId.ERR_HOURS_EXCEED_SCHEDULED: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
