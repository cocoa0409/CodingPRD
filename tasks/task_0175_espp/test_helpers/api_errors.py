    ERR_SHARES_EXCEED_BALANCE = "ERR_SHARES_EXCEED_BALANCE"
    ERR_FORM_3922_IMMUTABLE = "ERR_FORM_3922_IMMUTABLE"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    # OCC — PRD §2.10
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    # Pagination — PRD §2.3
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    # Clock — PRD §2.9
    ERR_CLOCK_NOT_ADVANCING = "ERR_CLOCK_NOT_ADVANCING"


