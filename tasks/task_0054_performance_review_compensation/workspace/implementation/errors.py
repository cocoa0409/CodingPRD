"""Error classes and error-id constants for the Performance Review API."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id, http_status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_RATING_BAND_UNKNOWN = ("ERR_RATING_BAND_UNKNOWN", 422)
ERR_SEGREGATION_OF_DUTIES = ("ERR_SEGREGATION_OF_DUTIES", 403)
ERR_BAND_COVERAGE_INVALID = ("ERR_BAND_COVERAGE_INVALID", 422)
ERR_DISTRIBUTION_NOT_NORMALIZED = ("ERR_DISTRIBUTION_NOT_NORMALIZED", 422)
ERR_GOAL_WEIGHTS_INVALID = ("ERR_GOAL_WEIGHTS_INVALID", 422)
ERR_DISTRIBUTION_OUT_OF_TOLERANCE = ("ERR_DISTRIBUTION_OUT_OF_TOLERANCE", 422)
ERR_TENURE_INELIGIBLE = ("ERR_TENURE_INELIGIBLE", 422)
ERR_MERIT_BUDGET_EXCEEDED = ("ERR_MERIT_BUDGET_EXCEEDED", 422)
ERR_EQUITY_POOL_EXCEEDED = ("ERR_EQUITY_POOL_EXCEEDED", 422)
ERR_PROMO_JUMP_INVALID = ("ERR_PROMO_JUMP_INVALID", 422)
ERR_STALE_CYCLE_VERSION = ("ERR_STALE_CYCLE_VERSION", 412)
ERR_STALE_REVIEW_VERSION = ("ERR_STALE_REVIEW_VERSION", 412)
ERR_VALIDATION = ("ERR_VALIDATION", 400)


def err(spec, message=None):
    return ApiError(spec[0], spec[1], message)
