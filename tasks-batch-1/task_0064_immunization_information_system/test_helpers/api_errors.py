"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PRODUCT_NOT_AUTHORIZED = "ERR_PRODUCT_NOT_AUTHORIZED"
    ERR_LOT_RECALLED = "ERR_LOT_RECALLED"
    ERR_LOT_EXPIRED = "ERR_LOT_EXPIRED"
    ERR_CONTRAINDICATED = "ERR_CONTRAINDICATED"
    ERR_INTERVAL_TOO_SHORT = "ERR_INTERVAL_TOO_SHORT"
    ERR_LOT_DEPLETED = "ERR_LOT_DEPLETED"
    ERR_NOT_COMPLIANT = "ERR_NOT_COMPLIANT"
    ERR_STALE_PATIENT_VERSION = "ERR_STALE_PATIENT_VERSION"
    ERR_LINE_COUNT_MISMATCH = "ERR_LINE_COUNT_MISMATCH"
    ERR_PROVIDER_SUSPENDED = "ERR_PROVIDER_SUSPENDED"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_ADVERSE_EVENT_BLOCKS_DELETE = "ERR_ADVERSE_EVENT_BLOCKS_DELETE"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PRODUCT_NOT_AUTHORIZED: 422,
    ApiErrorId.ERR_LOT_RECALLED: 409,
    ApiErrorId.ERR_LOT_EXPIRED: 422,
    ApiErrorId.ERR_CONTRAINDICATED: 422,
    ApiErrorId.ERR_INTERVAL_TOO_SHORT: 422,
    ApiErrorId.ERR_LOT_DEPLETED: 422,
    ApiErrorId.ERR_NOT_COMPLIANT: 422,
    ApiErrorId.ERR_STALE_PATIENT_VERSION: 412,
    ApiErrorId.ERR_LINE_COUNT_MISMATCH: 422,
    ApiErrorId.ERR_PROVIDER_SUSPENDED: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_ADVERSE_EVENT_BLOCKS_DELETE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
