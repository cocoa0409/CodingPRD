    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_PROJECT_VERSION = "ERR_STALE_PROJECT_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PROJECT_WRONG_STAGE = "ERR_PROJECT_WRONG_STAGE"
    ERR_PROJECT_NOT_ACTIVATED = "ERR_PROJECT_NOT_ACTIVATED"
    ERR_NO_MILESTONES = "ERR_NO_MILESTONES"
    ERR_CLIENT_NOT_ACTIVE = "ERR_CLIENT_NOT_ACTIVE"
