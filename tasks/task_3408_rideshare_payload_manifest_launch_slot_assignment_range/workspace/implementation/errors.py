def bad_request(msg):
    return ApiError(ERR_INVALID_REQUEST, msg, 400)


def forbidden(msg="role not authorized for this endpoint"):
    return ApiError(ERR_FORBIDDEN, msg, 403)


def not_found(error_id, msg):
    return ApiError(error_id, msg, 404)


def conflict(error_id, msg):
    return ApiError(error_id, msg, 409)


def stale(error_id, msg):
    return ApiError(error_id, msg, 412)


def unprocessable(error_id, msg):
    return ApiError(error_id, msg, 422)
