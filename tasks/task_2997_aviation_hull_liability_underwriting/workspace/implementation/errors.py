"""The complete error catalogue of PRD section 5 and the exception used to raise it."""


class ApiError(Exception):
    """Raised anywhere in the request path; translated into the error envelope."""

    def __init__(self, error_id, message=None, status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.status = status if status is not None else ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(error_id, error_id)


