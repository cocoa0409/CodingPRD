"""Error IDs and HTTP status mapping (PRD §5 error catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_TERM_VERSION = "ERR_STALE_TERM_VERSION"
    ERR_STALE_GOAL_VERSION = "ERR_STALE_GOAL_VERSION"
    ERR_STALE_INVOICE_VERSION = "ERR_STALE_INVOICE_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_TEMPORAL_WINDOW_VIOLATION = "ERR_TEMPORAL_WINDOW_VIOLATION"
    ERR_REFERENTIAL_INTEGRITY = "ERR_REFERENTIAL_INTEGRITY"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_THRESHOLD_NOT_MET = "ERR_THRESHOLD_NOT_MET"
    ERR_FISCAL_VIOLATION = "ERR_FISCAL_VIOLATION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_TERM_VERSION: 412,
    ApiErrorId.ERR_STALE_GOAL_VERSION: 412,
    ApiErrorId.ERR_STALE_INVOICE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 422,
    ApiErrorId.ERR_TEMPORAL_WINDOW_VIOLATION: 422,
    ApiErrorId.ERR_REFERENTIAL_INTEGRITY: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_THRESHOLD_NOT_MET: 422,
    ApiErrorId.ERR_FISCAL_VIOLATION: 422,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
