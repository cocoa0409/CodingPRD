"""Error identifiers and their HTTP statuses, transcribed from PRD section 5.

The map is registered with the shared validator layer so that
``validate_error(response, ERR_X)`` cross-checks the HTTP status without
every call site restating it.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Cross-cutting envelope / routing
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = (
        "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    )
    ERR_INSUFFICIENT_PERMISSIONS = "ERR_INSUFFICIENT_PERMISSIONS"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Business safety
    ERR_PRESCRIBER_NOT_ELIGIBLE = "ERR_PRESCRIBER_NOT_ELIGIBLE"
    ERR_LOT_NOT_RELEASABLE = "ERR_LOT_NOT_RELEASABLE"

    # Temporal
    ERR_VISIT_SCHEDULE_OVERLAP = "ERR_VISIT_SCHEDULE_OVERLAP"
    ERR_COUNT_WINDOW_CONFLICT = "ERR_COUNT_WINDOW_CONFLICT"

    # Referential / fiscal
    ERR_SEGREGATION_OF_DUTIES_VIOLATION = "ERR_SEGREGATION_OF_DUTIES_VIOLATION"
    ERR_QUANTITY_LIMIT_EXCEEDED = "ERR_QUANTITY_LIMIT_EXCEEDED"
    ERR_TERRITORY_BUDGET_EXCEEDED = "ERR_TERRITORY_BUDGET_EXCEEDED"

    # Plan workflow
    ERR_TERRITORY_NOT_ACTIVE = "ERR_TERRITORY_NOT_ACTIVE"
    ERR_EMPTY_TARGET_LIST = "ERR_EMPTY_TARGET_LIST"
    ERR_PLAN_CYCLE_OVERLAP = "ERR_PLAN_CYCLE_OVERLAP"
    ERR_PLAN_LOCKED = "ERR_PLAN_LOCKED"

    # Visit workflow
    ERR_NOT_VISIT_OWNER = "ERR_NOT_VISIT_OWNER"
    ERR_TARGET_ENTRY_INACTIVE = "ERR_TARGET_ENTRY_INACTIVE"
    ERR_REP_SUSPENDED = "ERR_REP_SUSPENDED"
    ERR_VISIT_WINDOW_EXPIRED = "ERR_VISIT_WINDOW_EXPIRED"
    ERR_VISIT_NOT_COMPLETED = "ERR_VISIT_NOT_COMPLETED"
    ERR_SIGNATURE_REQUIRED = "ERR_SIGNATURE_REQUIRED"
    ERR_VISIT_NOT_DUE = "ERR_VISIT_NOT_DUE"

    # Transfer workflow
    ERR_NOT_TRANSFER_RECEIVER = "ERR_NOT_TRANSFER_RECEIVER"
    ERR_NOT_TRANSFER_SENDER = "ERR_NOT_TRANSFER_SENDER"
    ERR_REP_INACTIVE = "ERR_REP_INACTIVE"
    ERR_INSUFFICIENT_RESERVED = "ERR_INSUFFICIENT_RESERVED"

    # Count workflow
    ERR_NOT_COUNT_COUNTER = "ERR_NOT_COUNT_COUNTER"
    ERR_INCOMPLETE_COUNT = "ERR_INCOMPLETE_COUNT"
    ERR_NOT_CUSTODIAN_MANAGER = "ERR_NOT_CUSTODIAN_MANAGER"
    ERR_REOPEN_LIMIT_EXCEEDED = "ERR_REOPEN_LIMIT_EXCEEDED"

    # Excursion / return workflow
    ERR_QUARANTINE_OPEN = "ERR_QUARANTINE_OPEN"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_RETURN_REASON_MISMATCH = "ERR_RETURN_REASON_MISMATCH"
    ERR_SELF_CONFIRM_FORBIDDEN = "ERR_SELF_CONFIRM_FORBIDDEN"


