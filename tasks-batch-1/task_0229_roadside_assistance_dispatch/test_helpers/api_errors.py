"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth / existence / ownership
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # state
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # business rules
    ERR_MEMBERSHIP_NOT_ACTIVE = "ERR_MEMBERSHIP_NOT_ACTIVE"
    ERR_CAPABILITY_MISMATCH = "ERR_CAPABILITY_MISMATCH"
    ERR_PROVIDER_UNAVAILABLE = "ERR_PROVIDER_UNAVAILABLE"
    ERR_OFFER_ALREADY_OUTSTANDING = "ERR_OFFER_ALREADY_OUTSTANDING"
    ERR_DISPATCH_LIMIT_REACHED = "ERR_DISPATCH_LIMIT_REACHED"
    ERR_SHIFT_OVERLAP = "ERR_SHIFT_OVERLAP"
    ERR_NO_BAY_AVAILABLE = "ERR_NO_BAY_AVAILABLE"
    ERR_ANNUAL_LIMIT_EXCEEDED = "ERR_ANNUAL_LIMIT_EXCEEDED"
    ERR_CALL_NOT_COMPLETED = "ERR_CALL_NOT_COMPLETED"
    # request / pagination / claim-target validation
    ERR_INVALID_CLAIM_TARGET = "ERR_INVALID_CLAIM_TARGET"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    # optimistic concurrency
    ERR_STALE_CALL_VERSION = "ERR_STALE_CALL_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_MEMBERSHIP_NOT_ACTIVE: 409,
    ApiErrorId.ERR_CAPABILITY_MISMATCH: 409,
    ApiErrorId.ERR_PROVIDER_UNAVAILABLE: 409,
    ApiErrorId.ERR_OFFER_ALREADY_OUTSTANDING: 409,
    ApiErrorId.ERR_DISPATCH_LIMIT_REACHED: 409,
    ApiErrorId.ERR_SHIFT_OVERLAP: 409,
    ApiErrorId.ERR_NO_BAY_AVAILABLE: 409,
    ApiErrorId.ERR_ANNUAL_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_CALL_NOT_COMPLETED: 409,
    ApiErrorId.ERR_INVALID_CLAIM_TARGET: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
    ApiErrorId.ERR_STALE_CALL_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
