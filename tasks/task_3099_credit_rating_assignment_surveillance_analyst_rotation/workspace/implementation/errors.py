def fail(error_id, message=None):
    """Raise an ApiError using the catalogue's HTTP status for the id."""
    raise ApiError(
        error_id,
        ERROR_STATUS.get(error_id, 409),
        message or MESSAGES.get(error_id, error_id),
    )