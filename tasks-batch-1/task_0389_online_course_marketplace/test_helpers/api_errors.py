"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_COURSE_NOT_PUBLISHABLE = "ERR_COURSE_NOT_PUBLISHABLE"
    ERR_DUPLICATE_LESSON_COMPLETION = "ERR_DUPLICATE_LESSON_COMPLETION"
    ERR_LESSON_LOCKED = "ERR_LESSON_LOCKED"
    ERR_COUPON_NOT_REDEEMABLE = "ERR_COUPON_NOT_REDEEMABLE"
    ERR_COUPON_COURSE_MISMATCH = "ERR_COUPON_COURSE_MISMATCH"
    ERR_COUPON_EXHAUSTED = "ERR_COUPON_EXHAUSTED"
    ERR_ALREADY_ENROLLED = "ERR_ALREADY_ENROLLED"
    ERR_REVIEW_NOT_ELIGIBLE = "ERR_REVIEW_NOT_ELIGIBLE"
    ERR_INVALID_BUNDLE = "ERR_INVALID_BUNDLE"
    ERR_COUPON_WINDOW_OVERLAP = "ERR_COUPON_WINDOW_OVERLAP"
    ERR_BUNDLE_PROMO_OVERLAP = "ERR_BUNDLE_PROMO_OVERLAP"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_REFUND_WINDOW_CLOSED = "ERR_REFUND_WINDOW_CLOSED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_COURSE_NOT_PUBLISHABLE: 422,
    ApiErrorId.ERR_DUPLICATE_LESSON_COMPLETION: 409,
    ApiErrorId.ERR_LESSON_LOCKED: 409,
    ApiErrorId.ERR_COUPON_NOT_REDEEMABLE: 422,
    ApiErrorId.ERR_COUPON_COURSE_MISMATCH: 422,
    ApiErrorId.ERR_COUPON_EXHAUSTED: 409,
    ApiErrorId.ERR_ALREADY_ENROLLED: 409,
    ApiErrorId.ERR_REVIEW_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_INVALID_BUNDLE: 422,
    ApiErrorId.ERR_COUPON_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_BUNDLE_PROMO_OVERLAP: 409,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 422,
    ApiErrorId.ERR_REFUND_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
