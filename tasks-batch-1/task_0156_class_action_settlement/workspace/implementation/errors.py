ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_SETTLEMENT_POSTURE_INVALID = ("ERR_SETTLEMENT_POSTURE_INVALID", 409)
ERR_CLAIM_WINDOW_CLOSED = ("ERR_CLAIM_WINDOW_CLOSED", 422)
ERR_OBJECTION_WINDOW_CLOSED = ("ERR_OBJECTION_WINDOW_CLOSED", 422)
ERR_CURE_WINDOW_CLOSED = ("ERR_CURE_WINDOW_CLOSED", 422)
