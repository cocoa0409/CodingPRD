"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
    ERR_INSURANCE_REQUIRED = "ERR_INSURANCE_REQUIRED"
    ERR_WINDOW_NOT_ELAPSED = "ERR_WINDOW_NOT_ELAPSED"
    ERR_UNIT_OCCUPANCY_OVERLAP = "ERR_UNIT_OCCUPANCY_OVERLAP"
    ERR_COVERAGE_OVERLAP = "ERR_COVERAGE_OVERLAP"
    ERR_BALANCE_NOT_CLEARED = "ERR_BALANCE_NOT_CLEARED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DUPLICATE_UNIT_NUMBER = "ERR_DUPLICATE_UNIT_NUMBER"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_PROCEEDING_EXISTS = "ERR_PROCEEDING_EXISTS"
    ERR_LEASE_HAS_ACTIVITY = "ERR_LEASE_HAS_ACTIVITY"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_UNIT_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_INSURANCE_REQUIRED: 409,
    ApiErrorId.ERR_WINDOW_NOT_ELAPSED: 409,
    ApiErrorId.ERR_UNIT_OCCUPANCY_OVERLAP: 409,
    ApiErrorId.ERR_COVERAGE_OVERLAP: 409,
    ApiErrorId.ERR_BALANCE_NOT_CLEARED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE_UNIT_NUMBER: 409,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_PROCEEDING_EXISTS: 409,
    ApiErrorId.ERR_LEASE_HAS_ACTIVITY: 409,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
