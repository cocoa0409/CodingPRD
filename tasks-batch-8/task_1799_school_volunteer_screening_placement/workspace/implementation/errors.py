def unauthenticated(message="Missing or malformed X-User-Role / X-User-ID headers, or undeclared role"):
    return APIError(ERR_UNAUTHENTICATED, message, 401)


def forbidden(message="Role not permitted on this endpoint, or Volunteer-role ownership check failed"):
    return APIError(ERR_FORBIDDEN, message, 403)


def not_found(message="Path id or body FK id does not resolve to an existing entity"):
    return APIError(ERR_NOT_FOUND, message, 404)


def invalid_request(message="Required field missing, enum outside declared set, or numeric/date shape violated"):
    return APIError(ERR_INVALID_REQUEST, message, 400)
