    ERR_REFEREE_OVERLAP = "ERR_REFEREE_OVERLAP"
    ERR_REFEREE_WEEKLY_CAP_EXCEEDED = "ERR_REFEREE_WEEKLY_CAP_EXCEEDED"
    ERR_GAME_REFEREE_ALREADY_ASSIGNED = "ERR_GAME_REFEREE_ALREADY_ASSIGNED"
    ERR_GAME_REFEREE_REQUIRED = "ERR_GAME_REFEREE_REQUIRED"
    ERR_INVALID_SCORE = "ERR_INVALID_SCORE"
    ERR_INVALID_GAME_OPPONENTS = "ERR_INVALID_GAME_OPPONENTS"
    ERR_GAME_OUT_OF_SEASON_WINDOW = "ERR_GAME_OUT_OF_SEASON_WINDOW"
