    # Capacity and quantity
    MILK_CLASS_MISMATCH = "ERR_MILK_CLASS_MISMATCH"
    COMPONENT_ALREADY_ALLOCATED = "ERR_COMPONENT_ALREADY_ALLOCATED"
    ALLOCATION_EXCEEDS_DONATION_REMAINING = "ERR_ALLOCATION_EXCEEDS_DONATION_REMAINING"
    POOL_DONOR_CAP_EXCEEDED = "ERR_POOL_DONOR_CAP_EXCEEDED"
    POOL_EMPTY = "ERR_POOL_EMPTY"
    POOL_DONOR_COUNT_INSUFFICIENT = "ERR_POOL_DONOR_COUNT_INSUFFICIENT"
    POOL_NUTRITION_OUT_OF_RANGE = "ERR_POOL_NUTRITION_OUT_OF_RANGE"
    POOL_VOLUME_OUT_OF_RANGE = "ERR_POOL_VOLUME_OUT_OF_RANGE"
    BOTTLING_EXCEEDS_POOL_VOLUME = "ERR_BOTTLING_EXCEEDS_POOL_VOLUME"
    DISPENSE_EXCEEDS_PRESCRIPTION_REMAINING = "ERR_DISPENSE_EXCEEDS_PRESCRIPTION_REMAINING"
    DISPENSE_EXCEEDS_LOT_AVAILABLE = "ERR_DISPENSE_EXCEEDS_LOT_AVAILABLE"
    NICU_RESERVE_PROTECTED = "ERR_NICU_RESERVE_PROTECTED"

    # Fiscal
    SUBSIDY_PROGRAM_EXHAUSTED = "ERR_SUBSIDY_PROGRAM_EXHAUSTED"
    SUBSIDY_CAP_EXCEEDED = "ERR_SUBSIDY_CAP_EXCEEDED"


