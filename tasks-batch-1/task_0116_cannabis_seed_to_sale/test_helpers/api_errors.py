"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registering the mapping with the framework lets validate_error() auto-check
the HTTP status code from the error_id alone.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LICENSE_NOT_ACTIVE = "ERR_LICENSE_NOT_ACTIVE"
    ERR_LICENSE_TYPE_MISMATCH = "ERR_LICENSE_TYPE_MISMATCH"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_LAB_HOLD_ACTIVE = "ERR_LAB_HOLD_ACTIVE"
    ERR_SOURCE_DISCRIMINATOR_MISMATCH = "ERR_SOURCE_DISCRIMINATOR_MISMATCH"
    ERR_DUPLICATE_TAG = "ERR_DUPLICATE_TAG"
    ERR_INSUFFICIENT_QUANTITY = "ERR_INSUFFICIENT_QUANTITY"
    ERR_MANIFEST_OVERLAP = "ERR_MANIFEST_OVERLAP"
    ERR_SALE_WINDOW_OVERLAP = "ERR_SALE_WINDOW_OVERLAP"
    ERR_DAILY_LIMIT_EXCEEDED = "ERR_DAILY_LIMIT_EXCEEDED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PARENT_STATE = "ERR_INVALID_PARENT_STATE"
    ERR_WEIGHT_RANGE = "ERR_WEIGHT_RANGE"
    ERR_AGE_VERIFICATION_FAILED = "ERR_AGE_VERIFICATION_FAILED"
    ERR_PARTIAL_DESTROY_NOT_TERMINAL = "ERR_PARTIAL_DESTROY_NOT_TERMINAL"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LICENSE_NOT_ACTIVE: 403,
    ApiErrorId.ERR_LICENSE_TYPE_MISMATCH: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_LAB_HOLD_ACTIVE: 409,
    ApiErrorId.ERR_SOURCE_DISCRIMINATOR_MISMATCH: 422,
    ApiErrorId.ERR_DUPLICATE_TAG: 409,
    ApiErrorId.ERR_INSUFFICIENT_QUANTITY: 409,
    ApiErrorId.ERR_MANIFEST_OVERLAP: 409,
    ApiErrorId.ERR_SALE_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_DAILY_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_PARENT_STATE: 409,
    ApiErrorId.ERR_WEIGHT_RANGE: 422,
    ApiErrorId.ERR_AGE_VERIFICATION_FAILED: 422,
    ApiErrorId.ERR_PARTIAL_DESTROY_NOT_TERMINAL: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
