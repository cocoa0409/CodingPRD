"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth / existence — PRD §2.1, §2.6, §5
    ERR_MISSING_USER_CONTEXT = "ERR_MISSING_USER_CONTEXT"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # State — PRD §2.9, §5
    ERR_INVALID_STATE_TRANSITION = "ERR_INVALID_STATE_TRANSITION"

    # Segregation of duties — PRD §3.9, §5
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"

    # Borrower — PRD §3.2, §5
    ERR_DUPLICATE_EIN = "ERR_DUPLICATE_EIN"
    ERR_NO_PLAID_SNAPSHOT = "ERR_NO_PLAID_SNAPSHOT"
    ERR_BORROWER_UNGRADED = "ERR_BORROWER_UNGRADED"
    ERR_BORROWER_NOT_APPROVED = "ERR_BORROWER_NOT_APPROVED"
    ERR_BORROWER_NOT_LISTABLE = "ERR_BORROWER_NOT_LISTABLE"
    ERR_BORROWER_HAS_LOSSES = "ERR_BORROWER_HAS_LOSSES"

    # Listing / Investment — PRD §3.3, §3.4, §5
    ERR_LISTING_OVERSUBSCRIBED = "ERR_LISTING_OVERSUBSCRIBED"
    ERR_LISTING_INTEGRITY = "ERR_LISTING_INTEGRITY"
    ERR_DIVERSIFICATION_CAP_EXCEEDED = "ERR_DIVERSIFICATION_CAP_EXCEEDED"
    ERR_CROSS_PLATFORM_INVESTMENT = "ERR_CROSS_PLATFORM_INVESTMENT"
    ERR_INSUFFICIENT_CASH = "ERR_INSUFFICIENT_CASH"
    ERR_INVESTMENT_DENOMINATION = "ERR_INVESTMENT_DENOMINATION"

    # Loan / Payment — PRD §3.5, §5
    ERR_LOAN_NOT_PAYABLE = "ERR_LOAN_NOT_PAYABLE"

    # Disclosure — PRD §3.7, §5
    ERR_DISCLOSURE_LOCKED = "ERR_DISCLOSURE_LOCKED"
    ERR_DISCLOSURE_STALE = "ERR_DISCLOSURE_STALE"


# PRD §5 Error Code Catalogue — http status per error_id.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_USER_CONTEXT: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE_TRANSITION: 409,
    ApiErrorId.ERR_SEGREGATION_VIOLATION: 403,
    ApiErrorId.ERR_DUPLICATE_EIN: 409,
    ApiErrorId.ERR_NO_PLAID_SNAPSHOT: 409,
    ApiErrorId.ERR_BORROWER_UNGRADED: 409,
    ApiErrorId.ERR_BORROWER_NOT_APPROVED: 409,
    ApiErrorId.ERR_BORROWER_NOT_LISTABLE: 409,
    ApiErrorId.ERR_BORROWER_HAS_LOSSES: 409,
    ApiErrorId.ERR_LISTING_OVERSUBSCRIBED: 409,
    ApiErrorId.ERR_LISTING_INTEGRITY: 409,
    ApiErrorId.ERR_DIVERSIFICATION_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_CROSS_PLATFORM_INVESTMENT: 409,
    ApiErrorId.ERR_INSUFFICIENT_CASH: 409,
    ApiErrorId.ERR_INVESTMENT_DENOMINATION: 422,
    ApiErrorId.ERR_LOAN_NOT_PAYABLE: 409,
    ApiErrorId.ERR_DISCLOSURE_LOCKED: 409,
    ApiErrorId.ERR_DISCLOSURE_STALE: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
