"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_SHOW_VERSION = "ERR_STALE_SHOW_VERSION"
    ERR_STALE_SESSION_VERSION = "ERR_STALE_SESSION_VERSION"
    ERR_STALE_SPONSOR_VERSION = "ERR_STALE_SPONSOR_VERSION"
    ERR_ACCESSIBLE_SEATS_UNAVAILABLE = "ERR_ACCESSIBLE_SEATS_UNAVAILABLE"
    ERR_AGE_INELIGIBLE = "ERR_AGE_INELIGIBLE"
    ERR_SHOW_TIME_CONFLICT = "ERR_SHOW_TIME_CONFLICT"
    ERR_RENTAL_TIME_CONFLICT = "ERR_RENTAL_TIME_CONFLICT"
    ERR_VENUE_TYPE_MISMATCH = "ERR_VENUE_TYPE_MISMATCH"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"
    ERR_HOLD_EXPIRED = "ERR_HOLD_EXPIRED"
    ERR_PARTY_SIZE_INVALID = "ERR_PARTY_SIZE_INVALID"
    ERR_SHOW_CAPACITY_EXCEEDED = "ERR_SHOW_CAPACITY_EXCEEDED"
    ERR_SESSION_FULL = "ERR_SESSION_FULL"
    ERR_OVERFULFILLMENT = "ERR_OVERFULFILLMENT"
    ERR_ACCOMMODATION_SUBJECT_MISMATCH = "ERR_ACCOMMODATION_SUBJECT_MISMATCH"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_SHOW_VERSION: 412,
    ApiErrorId.ERR_STALE_SESSION_VERSION: 412,
    ApiErrorId.ERR_STALE_SPONSOR_VERSION: 412,
    ApiErrorId.ERR_ACCESSIBLE_SEATS_UNAVAILABLE: 409,
    ApiErrorId.ERR_AGE_INELIGIBLE: 422,
    ApiErrorId.ERR_SHOW_TIME_CONFLICT: 409,
    ApiErrorId.ERR_RENTAL_TIME_CONFLICT: 409,
    ApiErrorId.ERR_VENUE_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_TIME_WINDOW: 422,
    ApiErrorId.ERR_HOLD_EXPIRED: 409,
    ApiErrorId.ERR_PARTY_SIZE_INVALID: 422,
    ApiErrorId.ERR_SHOW_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_SESSION_FULL: 409,
    ApiErrorId.ERR_OVERFULFILLMENT: 422,
    ApiErrorId.ERR_ACCOMMODATION_SUBJECT_MISMATCH: 422,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
