def fail(error_id, message):
    """Raise ApiError with the catalogued HTTP status for error_id."""
    http = ERROR_HTTP.get(error_id)
    if http is None:  # defensive: a typo'd id must not become a 500 silently
        raise AssertionError("unknown error id: %s" % error_id)
    raise ApiError(error_id, message, http)
