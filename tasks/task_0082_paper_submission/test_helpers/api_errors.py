"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # --- auth / authz (PRD §2.1) ---
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # --- existence (PRD §2.5, §2.7) ---
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # --- state / concurrency (PRD §2.5, §2.6, §2.8) ---
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_REVIEW_ROUND_MISMATCH = "ERR_REVIEW_ROUND_MISMATCH"
    ERR_INVITATION_ALREADY_EXISTS = "ERR_INVITATION_ALREADY_EXISTS"
    ERR_PUBLICATION_ALREADY_EXISTS = "ERR_PUBLICATION_ALREADY_EXISTS"

    # --- request shape (PRD §2.3, §5) ---
    ERR_VALIDATION = "ERR_VALIDATION"

    # --- business rules (PRD §3.x) ---
    ERR_ORCID_NOT_VERIFIED = "ERR_ORCID_NOT_VERIFIED"
    ERR_DECLARATION_INCOMPLETE = "ERR_DECLARATION_INCOMPLETE"
    ERR_REVIEWER_CONFLICT = "ERR_REVIEWER_CONFLICT"
    ERR_REVIEWER_EXCLUDED_BY_AUTHOR = "ERR_REVIEWER_EXCLUDED_BY_AUTHOR"
    ERR_EDITOR_TOPIC_MISMATCH = "ERR_EDITOR_TOPIC_MISMATCH"
    ERR_INVITATION_DEADLINE_PASSED = "ERR_INVITATION_DEADLINE_PASSED"
    ERR_REVISION_DEADLINE_PASSED = "ERR_REVISION_DEADLINE_PASSED"
    ERR_INSUFFICIENT_REVIEWS = "ERR_INSUFFICIENT_REVIEWS"
    ERR_DESK_REJECT_REASON_REQUIRED = "ERR_DESK_REJECT_REASON_REQUIRED"
    ERR_REVIEW_INCOMPLETE = "ERR_REVIEW_INCOMPLETE"
    ERR_PUBLICATION_NOT_READY = "ERR_PUBLICATION_NOT_READY"
    ERR_COAUTHOR_LIST_INVALID = "ERR_COAUTHOR_LIST_INVALID"
    ERR_REVIEWER_LISTS_OVERLAP = "ERR_REVIEWER_LISTS_OVERLAP"
    ERR_REVIEWER_OVERLOADED = "ERR_REVIEWER_OVERLOADED"
    ERR_EDITOR_WINDOW_OVERLAP = "ERR_EDITOR_WINDOW_OVERLAP"


# PRD §5 — Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_REVIEW_ROUND_MISMATCH: 409,
    ApiErrorId.ERR_INVITATION_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_PUBLICATION_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_ORCID_NOT_VERIFIED: 422,
    ApiErrorId.ERR_DECLARATION_INCOMPLETE: 422,
    ApiErrorId.ERR_REVIEWER_CONFLICT: 422,
    ApiErrorId.ERR_REVIEWER_EXCLUDED_BY_AUTHOR: 422,
    ApiErrorId.ERR_EDITOR_TOPIC_MISMATCH: 422,
    ApiErrorId.ERR_INVITATION_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_REVISION_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_INSUFFICIENT_REVIEWS: 422,
    ApiErrorId.ERR_DESK_REJECT_REASON_REQUIRED: 422,
    ApiErrorId.ERR_REVIEW_INCOMPLETE: 422,
    ApiErrorId.ERR_PUBLICATION_NOT_READY: 422,
    ApiErrorId.ERR_COAUTHOR_LIST_INVALID: 422,
    ApiErrorId.ERR_REVIEWER_LISTS_OVERLAP: 422,
    ApiErrorId.ERR_REVIEWER_OVERLOADED: 422,
    ApiErrorId.ERR_EDITOR_WINDOW_OVERLAP: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
