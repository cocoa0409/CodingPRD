"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ADVERSE_FINDING_BLOCKS_CLEAR = "ERR_ADVERSE_FINDING_BLOCKS_CLEAR"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CONSENT_NOT_ON_FILE = "ERR_CONSENT_NOT_ON_FILE"
    ERR_VOLUNTEER_NOT_ELIGIBLE = "ERR_VOLUNTEER_NOT_ELIGIBLE"
    ERR_VOLUNTEER_AT_CAPACITY = "ERR_VOLUNTEER_AT_CAPACITY"
    ERR_NO_ELIGIBLE_VOLUNTEER = "ERR_NO_ELIGIBLE_VOLUNTEER"
    ERR_MATCH_NOT_READY_FOR_MEETING = "ERR_MATCH_NOT_READY_FOR_MEETING"
    ERR_MATCH_NOT_ACTIVE = "ERR_MATCH_NOT_ACTIVE"
    ERR_SURVEY_NOT_REQUIRED = "ERR_SURVEY_NOT_REQUIRED"
    ERR_SURVEY_ALREADY_EXISTS = "ERR_SURVEY_ALREADY_EXISTS"
    ERR_MEETING_WINDOW_INVALID = "ERR_MEETING_WINDOW_INVALID"
    ERR_MEETING_OVERLAP = "ERR_MEETING_OVERLAP"
    ERR_GUARDIAN_DOUBLE_BOOKED = "ERR_GUARDIAN_DOUBLE_BOOKED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ADVERSE_FINDING_BLOCKS_CLEAR: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_CONSENT_NOT_ON_FILE: 409,
    ApiErrorId.ERR_VOLUNTEER_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_VOLUNTEER_AT_CAPACITY: 409,
    ApiErrorId.ERR_NO_ELIGIBLE_VOLUNTEER: 409,
    ApiErrorId.ERR_MATCH_NOT_READY_FOR_MEETING: 409,
    ApiErrorId.ERR_MATCH_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SURVEY_NOT_REQUIRED: 409,
    ApiErrorId.ERR_SURVEY_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_MEETING_WINDOW_INVALID: 422,
    ApiErrorId.ERR_MEETING_OVERLAP: 409,
    ApiErrorId.ERR_GUARDIAN_DOUBLE_BOOKED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
# Use plain string keys so str-comparison against response error_id matches.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
