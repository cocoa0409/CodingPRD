from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WINDOW_CLOSED = "ERR_WINDOW_CLOSED"
    ERR_CURE_DEADLINE_PASSED = "ERR_CURE_DEADLINE_PASSED"
    ERR_NOT_CITIZEN = "ERR_NOT_CITIZEN"
    ERR_UNDERAGE = "ERR_UNDERAGE"
    ERR_NO_PRECINCT_MATCH = "ERR_NO_PRECINCT_MATCH"
    ERR_DUPLICATE_REGISTRATION = "ERR_DUPLICATE_REGISTRATION"
    ERR_PRECINCT_FULL = "ERR_PRECINCT_FULL"
    ERR_ALREADY_VOTED = "ERR_ALREADY_VOTED"
    ERR_REGISTRATION_NOT_ACTIVE = "ERR_REGISTRATION_NOT_ACTIVE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_BALLOT_NOT_CURED = "ERR_BALLOT_NOT_CURED"
    ERR_BALLOT_BLOCKS_WITHDRAW = "ERR_BALLOT_BLOCKS_WITHDRAW"
    ERR_PRECINCT_NOT_TALLIED = "ERR_PRECINCT_NOT_TALLIED"
    ERR_PRECINCTS_NOT_TALLIED = "ERR_PRECINCTS_NOT_TALLIED"
    ERR_RECOUNT_IN_PROGRESS = "ERR_RECOUNT_IN_PROGRESS"
    ERR_VOTING_NOT_OPEN = "ERR_VOTING_NOT_OPEN"
    ERR_BACKUP_IN_USE = "ERR_BACKUP_IN_USE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_CURE_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_NOT_CITIZEN: 422,
    ApiErrorId.ERR_UNDERAGE: 422,
    ApiErrorId.ERR_NO_PRECINCT_MATCH: 422,
    ApiErrorId.ERR_DUPLICATE_REGISTRATION: 409,
    ApiErrorId.ERR_PRECINCT_FULL: 409,
    ApiErrorId.ERR_ALREADY_VOTED: 409,
    ApiErrorId.ERR_REGISTRATION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_BALLOT_NOT_CURED: 409,
    ApiErrorId.ERR_BALLOT_BLOCKS_WITHDRAW: 409,
    ApiErrorId.ERR_PRECINCT_NOT_TALLIED: 409,
    ApiErrorId.ERR_PRECINCTS_NOT_TALLIED: 409,
    ApiErrorId.ERR_RECOUNT_IN_PROGRESS: 409,
    ApiErrorId.ERR_VOTING_NOT_OPEN: 422,
    ApiErrorId.ERR_BACKUP_IN_USE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
