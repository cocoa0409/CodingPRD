    PICK_TASK_NOT_FOUND = "ERR_PICK_TASK_NOT_FOUND"
    PROPOSAL_NOT_FOUND = "ERR_PROPOSAL_NOT_FOUND"

    # Shape / pagination / concurrency
    INVALID_REQUEST = "ERR_INVALID_REQUEST"
    INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    STALE_VERSION = "ERR_STALE_VERSION"

    # State
    INVALID_STATE = "ERR_INVALID_STATE"
    WAVE_FROZEN = "ERR_WAVE_FROZEN"
    ZONE_NOT_OPERATIONAL = "ERR_ZONE_NOT_OPERATIONAL"

    # Safety / compatibility
    TEMPERATURE_ZONE_MISMATCH = "ERR_TEMPERATURE_ZONE_MISMATCH"
    STATION_ZONE_UNSUPPORTED = "ERR_STATION_ZONE_UNSUPPORTED"
    WEIGHT_OUT_OF_TOLERANCE = "ERR_WEIGHT_OUT_OF_TOLERANCE"
    ROUTE_MISMATCH = "ERR_ROUTE_MISMATCH"
    WAVE_SLOT_MISMATCH = "ERR_WAVE_SLOT_MISMATCH"
    SUBSTITUTE_NOT_COMPARABLE = "ERR_SUBSTITUTE_NOT_COMPARABLE"
    SUPERSEDE_TARGET_INVALID = "ERR_SUPERSEDE_TARGET_INVALID"

    # Temporal / capacity
    MAINTENANCE_WINDOW_OVERLAP = "ERR_MAINTENANCE_WINDOW_OVERLAP"
    DOCK_BAY_CAPACITY_EXCEEDED = "ERR_DOCK_BAY_CAPACITY_EXCEEDED"
    SLOT_WINDOW_CLOSED = "ERR_SLOT_WINDOW_CLOSED"
    PROPOSAL_EXPIRED = "ERR_PROPOSAL_EXPIRED"
    PROPOSAL_NOT_EXPIRED = "ERR_PROPOSAL_NOT_EXPIRED"

    # Workflow preconditions
    NO_TOTES_TO_CONSOLIDATE = "ERR_NO_TOTES_TO_CONSOLIDATE"
    DOCK_NOT_ASSIGNED = "ERR_DOCK_NOT_ASSIGNED"
    WAVE_HAS_NO_ORDERS = "ERR_WAVE_HAS_NO_ORDERS"
    NO_ELIGIBLE_PICK_STATION = "ERR_NO_ELIGIBLE_PICK_STATION"
    STATION_TOTE_CAPACITY_EXCEEDED = "ERR_STATION_TOTE_CAPACITY_EXCEEDED"
    ORDER_DISPATCH_BLOCKED = "ERR_ORDER_DISPATCH_BLOCKED"
    DUPLICATE_SLOT_BOOKING = "ERR_DUPLICATE_SLOT_BOOKING"
    TOTE_NOT_ASSIGNED = "ERR_TOTE_NOT_ASSIGNED"
    LINE_NOT_SHORT = "ERR_LINE_NOT_SHORT"
    PROPOSAL_ALREADY_OPEN = "ERR_PROPOSAL_ALREADY_OPEN"
    INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"

    # Fiscal / quantity
    WITHHELD_UNITS_EXCEEDED = "ERR_WITHHELD_UNITS_EXCEEDED"
    SLOT_UNITS_EXCEED_CAPACITY = "ERR_SLOT_UNITS_EXCEED_CAPACITY"
    MINIMUM_ORDER_NOT_MET = "ERR_MINIMUM_ORDER_NOT_MET"


