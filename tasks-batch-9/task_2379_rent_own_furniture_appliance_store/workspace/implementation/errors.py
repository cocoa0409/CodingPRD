"""Error identifiers and the API exception type (PRD section 5)."""


class ApiError(Exception):
    """Raised anywhere in a request to abort with the standard error envelope."""

    def __init__(self, error_id, message=None):
        self.error_id = error_id
        self.http_status = HTTP_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGE.get(error_id, error_id)
        super().__init__(self.message)


