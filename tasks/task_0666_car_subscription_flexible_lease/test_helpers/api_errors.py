"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PLAN_MISMATCH = "ERR_PLAN_MISMATCH"
    ERR_NOT_ELIGIBLE = "ERR_NOT_ELIGIBLE"
    ERR_BILLING_PAST_DUE = "ERR_BILLING_PAST_DUE"
    ERR_MIN_TERM_ELAPSED = "ERR_MIN_TERM_ELAPSED"
    ERR_VEHICLE_SLOT_OVERLAP = "ERR_VEHICLE_SLOT_OVERLAP"
    ERR_COURIER_BUFFER_CONFLICT = "ERR_COURIER_BUFFER_CONFLICT"
    ERR_DUPLICATE_VALUE = "ERR_DUPLICATE_VALUE"
    ERR_ODOMETER_REGRESSION = "ERR_ODOMETER_REGRESSION"
    ERR_STALE_VEHICLE_VERSION = "ERR_STALE_VEHICLE_VERSION"
    ERR_STALE_SUBSCRIPTION_VERSION = "ERR_STALE_SUBSCRIPTION_VERSION"
    ERR_NO_VEHICLE_AVAILABLE = "ERR_NO_VEHICLE_AVAILABLE"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PLAN_MISMATCH: 409,
    ApiErrorId.ERR_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_BILLING_PAST_DUE: 409,
    ApiErrorId.ERR_MIN_TERM_ELAPSED: 409,
    ApiErrorId.ERR_VEHICLE_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_COURIER_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_VALUE: 409,
    ApiErrorId.ERR_ODOMETER_REGRESSION: 422,
    ApiErrorId.ERR_STALE_VEHICLE_VERSION: 412,
    ApiErrorId.ERR_STALE_SUBSCRIPTION_VERSION: 412,
    ApiErrorId.ERR_NO_VEHICLE_AVAILABLE: 409,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
