"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SCREENING_BLOCKED = "ERR_SCREENING_BLOCKED"
    ERR_CONSENT_MISSING = "ERR_CONSENT_MISSING"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NO_STANDING_ORDER = "ERR_NO_STANDING_ORDER"
    ERR_SLOT_CONFLICT = "ERR_SLOT_CONFLICT"
    ERR_SUPPLY_UNAVAILABLE = "ERR_SUPPLY_UNAVAILABLE"
    ERR_CREDIT_INSUFFICIENT = "ERR_CREDIT_INSUFFICIENT"
    ERR_LOT_HAS_RESERVATIONS = "ERR_LOT_HAS_RESERVATIONS"
    ERR_CONSENT_NOT_AFFIRMED = "ERR_CONSENT_NOT_AFFIRMED"
    ERR_ROUTE_LOCKED = "ERR_ROUTE_LOCKED"
    ERR_VALIDATION_PARAM = "ERR_VALIDATION_PARAM"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SCREENING_BLOCKED: 409,
    ApiErrorId.ERR_CONSENT_MISSING: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_NO_STANDING_ORDER: 409,
    ApiErrorId.ERR_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_SUPPLY_UNAVAILABLE: 409,
    ApiErrorId.ERR_CREDIT_INSUFFICIENT: 409,
    ApiErrorId.ERR_LOT_HAS_RESERVATIONS: 409,
    ApiErrorId.ERR_CONSENT_NOT_AFFIRMED: 422,
    ApiErrorId.ERR_ROUTE_LOCKED: 409,
    ApiErrorId.ERR_VALIDATION_PARAM: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
