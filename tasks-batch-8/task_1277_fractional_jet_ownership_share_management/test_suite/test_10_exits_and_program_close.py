class TestSettlementInvariant:
    def _approved_exit_at_year_zero(self, program_code):
        """1/8 MID share at 40000000 with 2000000 deposit; the August invoice PAID;
        exit opened, valued, approved while contract_year_index is still 0."""
        sc = setup_program_with_share(
            program_code=program_code, class_code="MID", fraction=(1, 8),
            purchase_price_cents=40000000, initial_deposit_cents=2000000,
        )
        invoice = create_issued_invoice(sc["owner"]["id"], "2026-08", "2026-09-01T00:00:00Z")
        pay_invoice_ok(invoice["id"], sc["owner"]["id"], invoice["total_due_cents"])
        exit_req = open_exit_ok(sc["share"]["id"], sc["owner"]["id"])
        sc.update({"invoice": invoice, "exit": exit_req})
        return sc

    def test_valuation_at_year_zero_applies_full_penalty(self, api):
        """PRD §3.9: "Otherwise the penalty is 20 percent of market value, scaled by the
        unelapsed fraction of the three-year minimum hold — the years remaining divided
        by three — rounded half-up to whole cents."

        Design: Difficulty/compensating_invariant/deposit_balance_exit_settle_invariant
        """
        sc = self._approved_exit_at_year_zero("FJX-CI2")
        valued = value_exit_ok(sc["exit"]["id"], "finops-valuer-1")
        # market 32800000; years_held = 0 -> penalty = round(32800000 * 0.20 * 3/3)
        assert valued["early_exit_penalty_cents"] == 6560000
        assert valued["buyout_amount_cents"] == 26240000, (
            f"32800000 - 6560000, got {valued['buyout_amount_cents']}"
        )

    def test_settle_consumes_deposit_and_closes_share(self, api):
        """PRD §3.9: "With settlement recorded, the exit request moves to `SETTLED`, the
        deposit ledger is drawn to zero, the share moves from `IN_EXIT` to `CLOSED`, and
        if it was the owner's last non-closed share, the owner transitions to `EXITED`
        per §2.10."
        PRD §2.10: "By that point the owner's refundable `deposit_balance_cents` ledger —
        the ledger exit settlement draws against, which may never hold a negative balance
        — must have been drawn down to exactly zero."

        Design: Difficulty/compensating_invariant/deposit_balance_exit_settle_invariant
        """
        sc = self._approved_exit_at_year_zero("FJX-CI2B")
        value_exit_ok(sc["exit"]["id"], "finops-valuer-1")
        approve_exit_ok(sc["exit"]["id"], "finops-approver-1")
        settled = settle_exit_ok(sc["exit"]["id"], "finops-approver-1")
        # buyout 26240000 - outstanding 0 (invoice PAID) + deposit 2000000
        assert settled["settlement_cents"] == 28240000, (
            f"no cents created or destroyed: 26240000 + 2000000 - 0, got "
            f"{settled['settlement_cents']}"
        )
        owner = get_owner(sc["owner"]["id"])
        assert owner["deposit_balance_cents"] == 0, "the deposit is fully consumed"
        assert get_share(sc["share"]["id"])["share_status"] == "CLOSED"
        assert owner["owner_standing"] == "EXITED", "last share closed -> owner EXITED"


class TestExitGates:
    def test_reject_returns_share_to_active_without_restoring_bookings(self, api):
        """PRD §3.9: "`FinanceOps` may reject a request in `SUBMITTED` or `VALUED`,
        landing it in `REJECTED`, and the owner may withdraw from those same states,
        landing it in `WITHDRAWN`; in either case the share returns from `IN_EXIT` to
        `ACTIVE`. Bookings that the entry cascade expired are not restored — re-entry
        into the program's flight schedule starts fresh."
        PRD §3.9: "The request opens an ExitRequest with `exit_status` `SUBMITTED` and
        swings the share into `IN_EXIT`, expiring its `REQUESTED` bookings and cancelling
        its `CONFIRMED` ones with the usual compensating re-credit of their estimated
        hours."

        Design: Corner/state_machines/exit_reject_returns_share_to_active
        """
        sc = setup_program_with_share(program_code="FJX-SM5", class_code="MID")
        booking = create_booking_ok(
            sc["share"]["id"], sc["owner"]["id"], sc["cls"]["id"],
            "2026-09-10T15:00:00Z", 1.00,
            expected_share_version=sc["share"]["version"],
        )
        exit_req = open_exit_ok(sc["share"]["id"], sc["owner"]["id"])
        assert exit_req["exit_status"] == "SUBMITTED"
        assert get_booking(booking["id"])["booking_status"] == "EXPIRED", (
            "the entry cascade expires REQUESTED bookings"
        )
        rejected = validate_success(api.reject_exit(exit_req["id"], FIN), 200)
        assert rejected["exit_status"] == "REJECTED"
        assert get_share(sc["share"]["id"])["share_status"] == "ACTIVE", (
            "rejection compensates the share back to ACTIVE"
        )
        assert get_booking(booking["id"])["booking_status"] == "EXPIRED", (
            "expired bookings are NOT restored"
        )

    def test_approve_by_valuer_identity_rejected(self, api):
        """PRD §3.9: "Approval enforces segregation of duties: the `FinanceOps` identity
        approving the exit must differ from the identity that ran the valuation,
        otherwise the approval is rejected with `ERR_SEGREGATION_OF_DUTIES` (HTTP 403)."

        Design: Corner/validations/exit_approve_segregation_of_duties
        """
        sc = setup_program_with_share(program_code="FJX-VA5", class_code="MID")
        exit_req = open_exit_ok(sc["share"]["id"], sc["owner"]["id"])
        value_exit_ok(exit_req["id"], "finops-valuer-1")
        resp = api.approve_exit(exit_req["id"], make_finance_ops_headers("finops-valuer-1"))
        validate_error(resp, ApiErrorId.ERR_SEGREGATION_OF_DUTIES)
        assert resp.status_code == 403
        unchanged = validate_success(api.get_exit_request(exit_req["id"], FIN), 200)
        assert unchanged["exit_status"] == "VALUED"
        # A different FinanceOps identity may approve
        approved = approve_exit_ok(exit_req["id"], "finops-approver-1")
        assert approved["exit_status"] == "APPROVED"

    def test_approve_before_valuation_rejected(self, api):
        """PRD §3.9: "Approval or settlement attempted before valuation has run is
        rejected with `ERR_EXIT_NOT_VALUED` (HTTP 409)."

        Design: Corner/errors/error_exit_not_valued
        """
        sc = setup_program_with_share(program_code="FJX-ER4", class_code="MID")
        exit_req = open_exit_ok(sc["share"]["id"], sc["owner"]["id"])
        resp = api.approve_exit(exit_req["id"], make_finance_ops_headers("finops-approver-1"))
        validate_error(resp, ApiErrorId.ERR_EXIT_NOT_VALUED)
        assert resp.status_code == 409
        unchanged = validate_success(api.get_exit_request(exit_req["id"], FIN), 200)
        assert unchanged["exit_status"] == "SUBMITTED"


class TestProgramClose:
    def test_close_blocked_by_disputed_invoice(self, api):
        """PRD §2.9: "Moving from `WINDING_DOWN` to `CLOSED` requires that no share
        remain in `ACTIVE` or `LISTED`, that no exit request stand in `SUBMITTED`,
        `VALUED`, or `APPROVED`, and that no invoice stand in `OPEN`, `ISSUED`,
        `PAST_DUE`, or `DISPUTED`; unmet preconditions are rejected with
        `ERR_PROGRAM_NOT_CLOSABLE` (HTTP 409)."

        Design: Difficulty/cross_entity_state_dependency/program_close_gated_by_invoice_states
        """
        sc = setup_program_with_share(program_code="FJX-CE2", class_code="MID")
        # A second owner carries the blocking DISPUTED invoice (a different owner's
        # settlement must not net it away).
        other = create_owner(sc["program"]["id"], legal_name="CE2 Other")
        invoice = create_issued_invoice(other["id"], "2026-08", "2026-09-01T00:00:00Z")
        disputed = validate_success(
            api.dispute_invoice(invoice["id"], make_owner_headers(other["id"])), 200
        )
        assert disputed["invoice_status"] == "DISPUTED"

        # The only share CLOSED via a fully settled exit
        settle_exit_flow(sc["share"]["id"], sc["owner"]["id"])
        assert get_share(sc["share"]["id"])["share_status"] == "CLOSED"

        wound = validate_success(api.wind_down_program(sc["program"]["id"], ADMIN), 200)
        assert wound["program_posture"] == "WINDING_DOWN"
        resp = api.close_program(sc["program"]["id"], ADMIN)
        validate_error(resp, ApiErrorId.ERR_PROGRAM_NOT_CLOSABLE)
        assert resp.status_code == 409
        posture = validate_success(api.get_program(sc["program"]["id"], ADMIN), 200)
        assert posture["program_posture"] == "WINDING_DOWN"

    def test_close_succeeds_when_all_ledgers_clear(self, api):
        """PRD §2.9: "Moving from `WINDING_DOWN` to `CLOSED` requires that no share
        remain in `ACTIVE` or `LISTED`, that no exit request stand in `SUBMITTED`,
        `VALUED`, or `APPROVED`, and that no invoice stand in `OPEN`, `ISSUED`,
        `PAST_DUE`, or `DISPUTED`; unmet preconditions are rejected with
        `ERR_PROGRAM_NOT_CLOSABLE` (HTTP 409). On closure, every owner of the program
        transitions to `EXITED`."

        Design: Difficulty/cross_entity_state_dependency/program_close_gated_by_invoice_states
        """
        sc = setup_program_with_share(program_code="FJX-CE2B", class_code="MID")
        settle_exit_flow(sc["share"]["id"], sc["owner"]["id"])
        validate_success(api.wind_down_program(sc["program"]["id"], ADMIN), 200)
        closed = validate_success(api.close_program(sc["program"]["id"], ADMIN), 200)
        assert closed["program_posture"] == "CLOSED"
        assert get_owner(sc["owner"]["id"])["owner_standing"] == "EXITED", (
            "closure transitions every owner to EXITED"
        )
