"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_EMAIL_TAKEN = "ERR_EMAIL_TAKEN"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_TICKET_ELIGIBILITY = "ERR_TICKET_ELIGIBILITY"
    ERR_MEMBERSHIP_NOT_ACTIVE = "ERR_MEMBERSHIP_NOT_ACTIVE"
    ERR_SLOT_WINDOW = "ERR_SLOT_WINDOW"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_EXHIBIT_BUFFER_CONFLICT = "ERR_EXHIBIT_BUFFER_CONFLICT"
    ERR_NO_GUEST_PASS = "ERR_NO_GUEST_PASS"
    ERR_SLOT_CAPACITY = "ERR_SLOT_CAPACITY"
    ERR_HOUSEHOLD_FULL = "ERR_HOUSEHOLD_FULL"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_EMAIL_TAKEN: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TICKET_ELIGIBILITY: 409,
    ApiErrorId.ERR_MEMBERSHIP_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SLOT_WINDOW: 409,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_EXHIBIT_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_NO_GUEST_PASS: 409,
    ApiErrorId.ERR_SLOT_CAPACITY: 409,
    ApiErrorId.ERR_HOUSEHOLD_FULL: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
