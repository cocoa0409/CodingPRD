def not_found(error_id: str) -> APIError:
    return APIError(error_id, 404)


def invalid_request(message: str = "Invalid request") -> APIError:
    return APIError(ERR_INVALID_REQUEST, 422, message)


def conflict(error_id: str, message: str | None = None) -> APIError:
    return APIError(error_id, 409, message)
