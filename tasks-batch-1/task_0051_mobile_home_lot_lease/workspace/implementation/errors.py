ERR_NO_METER_READINGS = ("ERR_NO_METER_READINGS", 409)
ERR_DUPLICATE_BALLOT = ("ERR_DUPLICATE_BALLOT", 409)


def err(code_tuple, message=None):
    eid, status = code_tuple
    return ApiError(eid, status, message)
