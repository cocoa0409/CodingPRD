class TestVoidingAFinalizedRun:
    def test_void_restores_every_share_counter_to_its_pre_finalize_reading(self, api):
        """PRD 3.5: "On the plan, `allocated_shares_total` decreases by the pool less the
        residue, `unallocated_released_shares` is restored to the run's
        `released_shares_snapshot`, `unallocated_forfeiture_shares` is restored to its
        `forfeiture_shares_snapshot`, and `total_plan_shares` decreases by the run's
        `contributed_shares`."
        PRD 3.5: "The share conservation counters must read identically before the finalize
        and after the void."
        PRD 2.10: "Every share that enters or leaves the trust moves exactly one of these
        counters in each direction; where an operation has a compensating reversal, the
        reversal is specified so that the whole set reads identically before the forward
        operation and after the reversal."

        Design: Difficulty/compensating_invariant/allocation_void_conserves_total_plan_shares
        """
        ctx = setup_ironwood_finalized_run(contributed_shares=2000)
        after_finalize = ctx["plan"]
        assert after_finalize["total_plan_shares"] == 602_000
        assert after_finalize["allocated_shares_total"] == 2000

        run = validate_success(api.void_allocation_run(
            ctx["run"]["id"], {"reason": "Restated appraisal, allocation withdrawn."}, TRUSTEE))
        assert run["status"] == "VOID"
        assert run["void_reason"] == "Restated appraisal, allocation withdrawn."

        plan = get_plan(ctx["plan"]["id"])
        assert plan["total_plan_shares"] == 600_000
        assert plan["suspense_shares"] == 600_000
        assert plan["allocated_shares_total"] == 0
        assert plan["unallocated_released_shares"] == 0
        assert plan["unallocated_forfeiture_shares"] == 0
        assert plan["reacquired_shares"] == 0
        assert plan["plan_status"] == "VALUATION_PENDING"
        assert plan["forfeiture_posture"] == "CLEAR"
        assert_share_conservation(plan)

        for person in ctx["participants"]:
            assert get_participant(person["id"])["allocated_shares"] == 0, (
                "every allocation line of the run is reversed on the participant"
            )

    def test_void_deletes_statements_but_leaves_the_allocation_lines_readable(self, api):
        """PRD 3.5: "Every participant statement generated by this run is deleted outright."
        PRD 3.5: "Every allocation line of the run is reversed: each participant's
        `allocated_shares` decreases by the line's `allocated_shares` and their `vested_shares`
        is recomputed from the reduced balance."
        PRD 2.4: "Two record types are exceptions and are deliberately immutable once written:
        loan payments and share allocation lines carry only `id` and `created_at`."

        Design: Difficulty/compensating_invariant/allocation_void_conserves_total_plan_shares
        """
        ctx = setup_ironwood_finalized_run(contributed_shares=2000)
        pa, pb, pc = ctx["participants"]
        assert len(list_statements(allocation_run_id=ctx["run"]["id"])) == 3

        void_run(ctx["run"]["id"])

        _rows, meta = validate_paginated(
            api.list_participant_statements(
                ADMIN, params={"allocation_run_id": ctx["run"]["id"]})
        )
        assert meta["total_count"] == 0, "every statement generated by the run is deleted"

        assert get_allocation_line(ctx["run"]["id"], pa["id"])["allocated_shares"] == 876
        assert get_allocation_line(ctx["run"]["id"], pb["id"])["allocated_shares"] == 749
        assert get_allocation_line(ctx["run"]["id"], pc["id"])["allocated_shares"] == 375
        for person in (pa, pb, pc):
            refreshed = get_participant(person["id"])
            assert refreshed["vested_shares"] == 0, (
                "vested_shares is recomputed from the reduced balance"
            )


class TestParticipantStatement:
    def test_statement_delivery_marks_communicated_without_touching_snapshot(self, api):
        """PRD 3.6: "A statement is created with `delivery_status` `GENERATED` and
        `delivery_channel` null. The `PlanAdministrator` marks it as communicated, which
        drives `delivery_status` from `GENERATED` to `DELIVERED` and records the
        `delivery_channel` supplied in the request — one of `EMAIL`, `POSTAL` or `PORTAL`.
        Delivery touches nothing else: every numeric snapshot field is left exactly as
        generated, and `DELIVERED` is terminal."
        PRD 3.6: "`total_value_cents` is simply the closing share balance multiplied by the
        frozen share price."

        Design: Corner/state_machines/statement_delivery_marks_communicated_without_touching_snapshot
        """
        ctx = setup_finalized_run(
            contributed_shares=500,
            plan_overrides={"plan_name": "Statement Plan", "sponsor_name": "Corner Corp",
                            "vesting_schedule": "CLIFF_3YR"},
            participants=[{"employee_number": "E-701"}],
        )
        statement = get_statement_for(ctx["run"]["id"], ctx["participants"][0]["id"])
        assert statement["delivery_status"] == "GENERATED"
        assert statement["delivery_channel"] is None

        delivered = validate_success(api.deliver_participant_statement(
            statement["id"], {"delivery_channel": "EMAIL"}, ADMIN))
        assert_participant_statement(delivered)
        assert delivered["delivery_status"] == "DELIVERED"
        assert delivered["delivery_channel"] == "EMAIL"
        assert delivered["opening_shares"] == 0
        assert delivered["shares_allocated"] == 500
        assert delivered["closing_shares"] == 500
        assert delivered["share_price_cents"] == 7125
        assert delivered["vested_percentage"] == 100
        assert delivered["vested_value_cents"] == 3_562_500
        assert delivered["total_value_cents"] == 3_562_500
        assert delivered["forfeited_shares_this_year"] == 0
        assert delivered["plan_year"] == 2026

        validate_error(
            api.deliver_participant_statement(statement["id"], {"delivery_channel": "POSTAL"},
                                              ADMIN),
            ApiErrorId.ERR_INVALID_STATE,
        )

    def test_statement_snapshot_frozen_against_later_valuation(self, api):
        """PRD 3.6: "Approving a later appraisal, which moves the plan's
        `current_share_price_cents`, must leave every existing statement unchanged. Rolling
        the plan year forward must leave every existing statement unchanged. Nothing in this
        system ever rewrites a numeric field on a statement once it has been generated; the
        only way an existing statement's numbers change is for the whole statement to be
        deleted by voiding the run that produced it."
        PRD 3.6: "`share_price_cents` on the statement is a copy of the run's
        `share_price_cents`."

        Design: Corner/calculations/statement_snapshot_frozen_against_later_valuation
        """
        ctx = setup_finalized_run(
            contributed_shares=500,
            plan_overrides={"plan_name": "Snapshot Plan", "sponsor_name": "Corner Corp",
                            "vesting_schedule": "CLIFF_3YR"},
            participants=[{"employee_number": "E-702"}],
        )
        statement = get_statement_for(ctx["run"]["id"])
        assert statement["share_price_cents"] == 7125

        rollover_plan(ctx["plan"]["id"])
        closed = close_year(ctx["plan"]["id"])
        valuation_2027 = submit_valuation(
            ctx["plan"]["id"], closed["version"], plan_year=2027,
            enterprise_value_cents=11_000_000_000,
            effective_from_date="2027-01-01", effective_to_date="2028-01-01",
        )
        approved = approve_valuation(valuation_2027["id"])

        assert approved["share_price_cents"] == 6375
        assert get_plan(ctx["plan"]["id"])["current_share_price_cents"] == 6375
        assert get_plan(ctx["plan"]["id"])["plan_year"] == 2027

        after = validate_success(api.get_participant_statement(statement["id"], ADMIN))
        assert after["share_price_cents"] == 7125, "the frozen price survives a later approval"
        assert after["total_value_cents"] == 3_562_500
        assert after["vested_value_cents"] == 3_562_500
        assert after["plan_year"] == 2026
        assert after["closing_shares"] == 500
