    ERR_REGULAR_SEASON_INCOMPLETE = "ERR_REGULAR_SEASON_INCOMPLETE"
    ERR_SEASON_NOT_READY = "ERR_SEASON_NOT_READY"

    # OCC — PRD §2.4
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Generic
    ERR_VALIDATION = "ERR_VALIDATION"


