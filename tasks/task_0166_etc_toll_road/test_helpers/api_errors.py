"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, registers it with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations

from enum import Enum
from typing import Dict

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_INVALID_ROLE = "ERR_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_VEHICLE_ALREADY_BOUND = "ERR_VEHICLE_ALREADY_BOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ACCOUNT_NOT_ACTIVE = "ERR_ACCOUNT_NOT_ACTIVE"
    ERR_VEHICLE_BLOCKED = "ERR_VEHICLE_BLOCKED"
    ERR_INSUFFICIENT_FUNDS_ON_PLATE_BILL = "ERR_INSUFFICIENT_FUNDS_ON_PLATE_BILL"
    ERR_HOV_FRAUD_RECORDED = "ERR_HOV_FRAUD_RECORDED"
    ERR_DUPLICATE_TOLL_EVENT = "ERR_DUPLICATE_TOLL_EVENT"
    ERR_VOID_WINDOW_EXPIRED = "ERR_VOID_WINDOW_EXPIRED"
    ERR_DISPUTE_LIMIT_REACHED = "ERR_DISPUTE_LIMIT_REACHED"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_RELOAD_ALREADY_RUNNING = "ERR_RELOAD_ALREADY_RUNNING"
    ERR_INTEROP_POLICY_AMBIGUOUS = "ERR_INTEROP_POLICY_AMBIGUOUS"
    ERR_INVALID_RELOAD_AMOUNT = "ERR_INVALID_RELOAD_AMOUNT"
    ERR_ACCOUNT_HAS_OBLIGATIONS = "ERR_ACCOUNT_HAS_OBLIGATIONS"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: Dict[str, int] = {
    ApiErrorId.ERR_MISSING_AUTH.value: 401,
    ApiErrorId.ERR_INVALID_ROLE.value: 401,
    ApiErrorId.ERR_FORBIDDEN.value: 403,
    ApiErrorId.ERR_NOT_FOUND.value: 404,
    ApiErrorId.ERR_DUPLICATE_RESOURCE.value: 409,
    ApiErrorId.ERR_VEHICLE_ALREADY_BOUND.value: 409,
    ApiErrorId.ERR_INVALID_STATE.value: 409,
    ApiErrorId.ERR_ACCOUNT_NOT_ACTIVE.value: 409,
    ApiErrorId.ERR_VEHICLE_BLOCKED.value: 409,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS_ON_PLATE_BILL.value: 409,
    ApiErrorId.ERR_HOV_FRAUD_RECORDED.value: 409,
    ApiErrorId.ERR_DUPLICATE_TOLL_EVENT.value: 409,
    ApiErrorId.ERR_VOID_WINDOW_EXPIRED.value: 409,
    ApiErrorId.ERR_DISPUTE_LIMIT_REACHED.value: 409,
    ApiErrorId.ERR_VERSION_CONFLICT.value: 409,
    ApiErrorId.ERR_RELOAD_ALREADY_RUNNING.value: 409,
    ApiErrorId.ERR_INTEROP_POLICY_AMBIGUOUS.value: 422,
    ApiErrorId.ERR_INVALID_RELOAD_AMOUNT.value: 422,
    ApiErrorId.ERR_ACCOUNT_HAS_OBLIGATIONS.value: 409,
    ApiErrorId.ERR_VALIDATION.value: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
