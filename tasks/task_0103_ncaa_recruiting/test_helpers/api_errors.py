"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1, §5
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Existence — PRD §2.6
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # State — PRD §2.5, §2.7, §2.8
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"

    # Generic body shape — PRD §2.6, §2.8
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"

    # Eligibility — PRD §3.2, §3.3
    ERR_ELIGIBILITY_NOT_CLEARED = "ERR_ELIGIBILITY_NOT_CLEARED"
    ERR_ELIGIBILITY_ALREADY_DECIDED = "ERR_ELIGIBILITY_ALREADY_DECIDED"

    # Slot / athlete preconditions — PRD §3.2, §3.3
    ERR_NO_SIGNED_SLOT = "ERR_NO_SIGNED_SLOT"
    ERR_ATHLETE_NOT_AVAILABLE = "ERR_ATHLETE_NOT_AVAILABLE"
    ERR_ATHLETE_NOT_ENROLLED = "ERR_ATHLETE_NOT_ENROLLED"

    # NILDeal — PRD §3.5, §3.6
    ERR_AMATEUR_STATUS_LOST = "ERR_AMATEUR_STATUS_LOST"
    ERR_PAY_FOR_PLAY_DETECTED = "ERR_PAY_FOR_PLAY_DETECTED"
    ERR_PENDING_NIL_REVIEW = "ERR_PENDING_NIL_REVIEW"

    # Caps — PRD §3.3
    ERR_SCHOLARSHIP_CAP_EXCEEDED = "ERR_SCHOLARSHIP_CAP_EXCEEDED"
    ERR_ROSTER_CAP_EXCEEDED = "ERR_ROSTER_CAP_EXCEEDED"

    # Recruiting calendar / contact — PRD §3.1, §3.8
    ERR_CONTACT_NOT_PERMITTED = "ERR_CONTACT_NOT_PERMITTED"
    ERR_CALENDAR_WINDOW_INVALID = "ERR_CALENDAR_WINDOW_INVALID"

    # Transfer portal — PRD §3.4
    ERR_PORTAL_WINDOW_CLOSED = "ERR_PORTAL_WINDOW_CLOSED"
    ERR_PORTAL_INELIGIBLE = "ERR_PORTAL_INELIGIBLE"
    ERR_DUPLICATE_PORTAL_ENTRY = "ERR_DUPLICATE_PORTAL_ENTRY"

    # Violations — PRD §3.3, §3.7
    ERR_APPEAL_WINDOW_CLOSED = "ERR_APPEAL_WINDOW_CLOSED"
    ERR_NO_SUSTAINED_VIOLATION = "ERR_NO_SUSTAINED_VIOLATION"


# PRD §5 HTTP status mapping.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID_ROLE: 403,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 400,
    ApiErrorId.ERR_ELIGIBILITY_NOT_CLEARED: 409,
    ApiErrorId.ERR_ELIGIBILITY_ALREADY_DECIDED: 409,
    ApiErrorId.ERR_NO_SIGNED_SLOT: 409,
    ApiErrorId.ERR_ATHLETE_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_ATHLETE_NOT_ENROLLED: 409,
    ApiErrorId.ERR_AMATEUR_STATUS_LOST: 409,
    ApiErrorId.ERR_PAY_FOR_PLAY_DETECTED: 409,
    ApiErrorId.ERR_PENDING_NIL_REVIEW: 409,
    ApiErrorId.ERR_SCHOLARSHIP_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_ROSTER_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_CONTACT_NOT_PERMITTED: 409,
    ApiErrorId.ERR_CALENDAR_WINDOW_INVALID: 400,
    ApiErrorId.ERR_PORTAL_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_PORTAL_INELIGIBLE: 409,
    ApiErrorId.ERR_DUPLICATE_PORTAL_ENTRY: 409,
    ApiErrorId.ERR_APPEAL_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_NO_SUSTAINED_VIOLATION: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
