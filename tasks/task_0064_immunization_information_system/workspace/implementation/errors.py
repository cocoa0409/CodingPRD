class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_PRODUCT_NOT_AUTHORIZED = ("ERR_PRODUCT_NOT_AUTHORIZED", 422)
ERR_LOT_RECALLED = ("ERR_LOT_RECALLED", 409)
ERR_LOT_EXPIRED = ("ERR_LOT_EXPIRED", 422)
ERR_CONTRAINDICATED = ("ERR_CONTRAINDICATED", 422)
ERR_INTERVAL_TOO_SHORT = ("ERR_INTERVAL_TOO_SHORT", 422)
ERR_LOT_DEPLETED = ("ERR_LOT_DEPLETED", 422)
ERR_NOT_COMPLIANT = ("ERR_NOT_COMPLIANT", 422)
ERR_STALE_PATIENT_VERSION = ("ERR_STALE_PATIENT_VERSION", 412)
ERR_LINE_COUNT_MISMATCH = ("ERR_LINE_COUNT_MISMATCH", 422)
ERR_PROVIDER_SUSPENDED = ("ERR_PROVIDER_SUSPENDED", 409)
ERR_DUPLICATE = ("ERR_DUPLICATE", 409)
ERR_ADVERSE_EVENT_BLOCKS_DELETE = ("ERR_ADVERSE_EVENT_BLOCKS_DELETE", 409)
ERR_VALIDATION = ("ERR_VALIDATION", 422)


def err(spec, message=None):
    return ApiError(spec[0], spec[1], message)
