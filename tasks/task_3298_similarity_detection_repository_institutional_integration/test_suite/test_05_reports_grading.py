def test_finalize_already_finalized_rejected(api):
    """PRD §3.7: "The report must be `DRAFT` and the interpretation must be
    present; finalizing a report in any other state is
    `ERR_INVALID_SUBMISSION_STATE` (HTTP 409)"

    Design: Corner/state_machines/finalize_already_finalized_rejected
    """
    inst, integ, instr, student, asg, sub = setup_processed_submission("US", "idem body")
    report = get_report(sub["id"], instr["id"])
    finalize_report(report["id"], instr["id"], "NOT_MISCONDUCT")

    resp = api.finalize_report(
        report["id"],
        {"instructor_interpretation": "POSSIBLE_MISCONDUCT"},
        make_instructor_headers(instr["id"]),
    )
    validate_error(resp, ApiErrorId.ERR_INVALID_SUBMISSION_STATE, expected_status=409)
    after = get_report(sub["id"], instr["id"])
    assert after["instructor_interpretation"] == "NOT_MISCONDUCT", (
        "the second payload must not overwrite the recorded interpretation"
    )


def test_finalize_stale_report_rejected(api):
    """PRD §3.7: "finalizing a `STALE` report is specifically `ERR_REPORT_STALE`
    (HTTP 409) — a stale report must first be regenerated by re-running the
    pipeline." PRD §3.7: "The only way out of `STALE` is a pipeline re-run on
    the owning submission (which must be `REPORT_READY`), returning the report
    to `DRAFT` with refreshed snapshot and scores."

    Design: Corner/validations/finalize_stale_report_rejected
    """
    inst, integ, instr, student, asg, sub = setup_processed_submission("US", "stale body")
    report = get_report(sub["id"], instr["id"])
    # Stale the report via an exclusion-settings change.
    asg_v = get_assignment_version(asg["id"], instr["id"])
    resp = api.patch_assignment(
        asg["id"],
        {"expected_assignment_version": asg_v, "exclude_quotes": True},
        make_instructor_headers(instr["id"]),
    )
    validate_success(resp)

    stale_resp = api.finalize_report(
        report["id"],
        {"instructor_interpretation": "NOT_MISCONDUCT"},
        make_instructor_headers(instr["id"]),
    )
    validate_error(stale_resp, ApiErrorId.ERR_REPORT_STALE, expected_status=409)

    process(sub["id"], instr["id"])  # STALE -> DRAFT with refreshed snapshot
    finalized = finalize_report(report["id"], instr["id"], "NOT_MISCONDUCT")
    assert finalized["report_state"] == "FINALIZED"


def test_grade_entry_requires_similarity_report(api):
    """PRD §3.8: "Creation requires the submission to already have a similarity
    report in `DRAFT` or `FINALIZED`; grading against a submission with no
    report — or only a `STALE` one — is rejected with
    `ERR_GRADE_REQUIRES_REPORT` (HTTP 409)." PRD §3.8: "At creation the entry
    captures `pinned_report_version`, the report's current `version` at that
    moment" PRD §3.8: "A grade entry starts with `grade_state` `PROVISIONAL`"

    Design: Difficulty/cross_entity_state_dependency/grade_entry_requires_similarity_report
    """
    inst, integ, instr, student, asg = setup_basic_scenario("US")
    sub = submit(asg["id"], student["id"], "unprocessed body")

    resp = api.create_grade_entry(
        sub["id"], {"score_points": 50}, make_instructor_headers(instr["id"])
    )
    validate_error(resp, ApiErrorId.ERR_GRADE_REQUIRES_REPORT, expected_status=409)

    process(sub["id"], instr["id"])
    report = get_report(sub["id"], instr["id"])
    grade = create_grade(sub["id"], instr["id"], score_points=50)
    assert grade["pinned_report_version"] == report["version"]
    assert grade["grade_state"] == "PROVISIONAL"


def test_grade_entry_release_on_finalize(api):
    """PRD §3.7: "Successful finalization stamps `finalized_at` from the logical
    clock, bumps the report's `version`, and releases grades: every grade entry
    of the submission in `PROVISIONAL` flips to `RELEASED` with its own
    `version` increment."

    Design: Difficulty/cross_entity_state_dependency/grade_entry_requires_similarity_report
    """
    inst, integ, instr, student, asg, sub = setup_processed_submission("US", "grade release body")
    grade = create_grade(sub["id"], instr["id"], score_points=77)
    assert grade["grade_state"] == "PROVISIONAL"
    report = get_report(sub["id"], instr["id"])
    finalize_report(report["id"], instr["id"], "NOT_MISCONDUCT")

    data, meta = validate_paginated(api.list_grade_entries(sub["id"], make_instructor_headers(instr["id"])))
    assert len(data) == 1
    assert data[0]["grade_state"] == "RELEASED", "finalization must release PROVISIONAL grades"
