"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VOTING_NOT_OPEN = "ERR_VOTING_NOT_OPEN"
    ERR_KIT_COMPROMISED = "ERR_KIT_COMPROMISED"
    ERR_EQUIPMENT_NOT_OPERATIONAL = "ERR_EQUIPMENT_NOT_OPERATIONAL"
    ERR_WORKER_NOT_CERTIFIED = "ERR_WORKER_NOT_CERTIFIED"
    ERR_WORKER_SHIFT_OVERLAP = "ERR_WORKER_SHIFT_OVERLAP"
    ERR_PLACE_CAPACITY_EXCEEDED = "ERR_PLACE_CAPACITY_EXCEEDED"
    ERR_INVALID_CUSTODY_TRANSITION = "ERR_INVALID_CUSTODY_TRANSITION"
    ERR_INSUFFICIENT_BALLOT_STOCK = "ERR_INSUFFICIENT_BALLOT_STOCK"
    ERR_UNDERSTAFFED = "ERR_UNDERSTAFFED"
    ERR_NO_OPEN_SLOTS = "ERR_NO_OPEN_SLOTS"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VOTING_NOT_OPEN: 409,
    ApiErrorId.ERR_KIT_COMPROMISED: 409,
    ApiErrorId.ERR_EQUIPMENT_NOT_OPERATIONAL: 409,
    ApiErrorId.ERR_WORKER_NOT_CERTIFIED: 422,
    ApiErrorId.ERR_WORKER_SHIFT_OVERLAP: 409,
    ApiErrorId.ERR_PLACE_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_INVALID_CUSTODY_TRANSITION: 422,
    ApiErrorId.ERR_INSUFFICIENT_BALLOT_STOCK: 422,
    ApiErrorId.ERR_UNDERSTAFFED: 422,
    ApiErrorId.ERR_NO_OPEN_SLOTS: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
