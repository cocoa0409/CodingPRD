def err_unauthenticated(msg="Missing or unrecognized X-User-Role or X-User-ID"):
    return ApiError(ERR_UNAUTHENTICATED, msg, 401)


def err_unauthorized_role(msg="Role not authorized for this endpoint"):
    return ApiError(ERR_UNAUTHORIZED_ROLE, msg, 403)


def err_resident_not_owner(msg="Resident does not own this resource"):
    return ApiError(ERR_RESIDENT_NOT_OWNER, msg, 403)


def err_invalid_request(msg="Invalid request"):
    return ApiError(ERR_INVALID_REQUEST, msg, 400)


def err_not_found(error_id=ERR_NOT_FOUND, msg="Resource not found"):
    return ApiError(error_id, msg, 404)


def err_stale_version(msg="Stale version"):
    return ApiError(ERR_STALE_VERSION, msg, 412)


def err_invalid_state(msg="Invalid state"):
    return ApiError(ERR_INVALID_STATE, msg, 409)
