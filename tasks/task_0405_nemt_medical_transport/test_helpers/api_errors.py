"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_MEMBER_INELIGIBLE = "ERR_MEMBER_INELIGIBLE"
    ERR_LOS_NOT_AUTHORIZED = "ERR_LOS_NOT_AUTHORIZED"
    ERR_MODALITY_MISMATCH = "ERR_MODALITY_MISMATCH"
    ERR_NO_BROKER_AVAILABLE = "ERR_NO_BROKER_AVAILABLE"
    ERR_ASSIGNMENT_EXISTS = "ERR_ASSIGNMENT_EXISTS"
    ERR_LEG_SEQUENCE_VIOLATION = "ERR_LEG_SEQUENCE_VIOLATION"
    ERR_RECON_INCOMPLETE = "ERR_RECON_INCOMPLETE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DEPENDENCY_EXISTS = "ERR_DEPENDENCY_EXISTS"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_MEMBER_INELIGIBLE: 409,
    ApiErrorId.ERR_LOS_NOT_AUTHORIZED: 409,
    ApiErrorId.ERR_MODALITY_MISMATCH: 409,
    ApiErrorId.ERR_NO_BROKER_AVAILABLE: 409,
    ApiErrorId.ERR_ASSIGNMENT_EXISTS: 409,
    ApiErrorId.ERR_LEG_SEQUENCE_VIOLATION: 409,
    ApiErrorId.ERR_RECON_INCOMPLETE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DEPENDENCY_EXISTS: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
