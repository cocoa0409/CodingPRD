"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_ASSIGNED_INSPECTOR = "ERR_NOT_ASSIGNED_INSPECTOR"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INSPECTOR_NOT_CERTIFIED = "ERR_INSPECTOR_NOT_CERTIFIED"
    ERR_TERRITORY_MISMATCH = "ERR_TERRITORY_MISMATCH"
    ERR_INSPECTOR_DOUBLE_BOOKED = "ERR_INSPECTOR_DOUBLE_BOOKED"
    ERR_PROPERTY_SAME_DAY_CONFLICT = "ERR_PROPERTY_SAME_DAY_CONFLICT"
    ERR_DAILY_CAPACITY_EXCEEDED = "ERR_DAILY_CAPACITY_EXCEEDED"
    ERR_DUPLICATE_ADDON = "ERR_DUPLICATE_ADDON"
    ERR_REINSPECTION_NOT_WARRANTED = "ERR_REINSPECTION_NOT_WARRANTED"
    ERR_REINSPECTION_TOO_SOON = "ERR_REINSPECTION_TOO_SOON"
    ERR_ORDER_UNPAID = "ERR_ORDER_UNPAID"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_ASSIGNED_INSPECTOR: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INSPECTOR_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_TERRITORY_MISMATCH: 409,
    ApiErrorId.ERR_INSPECTOR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_PROPERTY_SAME_DAY_CONFLICT: 409,
    ApiErrorId.ERR_DAILY_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_DUPLICATE_ADDON: 409,
    ApiErrorId.ERR_REINSPECTION_NOT_WARRANTED: 409,
    ApiErrorId.ERR_REINSPECTION_TOO_SOON: 409,
    ApiErrorId.ERR_ORDER_UNPAID: 402,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION_RANGE: 400,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
