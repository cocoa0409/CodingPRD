"""Barrel export: framework generics + PRD-specific test infrastructure.

Tests import everything from `test_helpers` and never reach into
sub-modules directly.

PRD §2.1 identity rules:
- All four roles (ProviderClinician, ReviewingClinician,
  SchoolRegistrar, PublicHealthOfficer) are OPAQUE - "X-User-ID is an
  opaque operator identifier and is not the id of any persisted entity
  in the system." Shared TEST_USERS headers are canonical for general
  use.
- The exception is the SoD check on AdverseEvent (PRD §3.9), which
  compares the acting reviewer's X-User-ID to the dose's recorded
  administering_clinician_id. Per-instance builders
  make_provider_clinician_headers / make_reviewing_clinician_headers
  let tests control these ids explicitly to satisfy or provoke the
  SoD check.
"""
