def test_catalog_entity_not_found_on_subscribe(api):
    """PRD §2.6: "When an operation's request body references a catalog entity ... that referenced
    entity must both exist and be active; a missing or inactive catalog reference is rejected with
    `ERR_CATALOG_ENTITY_NOT_FOUND` (HTTP 404)."

    Design: Corner/entities/catalog_entity_not_found_on_subscribe
    """
    prospect = create_prospect_account(customer_name="NoPkg", service_state_code="CA")
    res = api.create_subscription(
        prospect["id"], {"package_id": "11111111-1111-4111-8111-111111111111"}, CSA
    )
    validate_error(res, "ERR_CATALOG_ENTITY_NOT_FOUND", expected_status=404)
