ERR_DRAWER_NOT_OPEN = "ERR_DRAWER_NOT_OPEN"
ERR_EMBARGOED_DESTINATION = "ERR_EMBARGOED_DESTINATION"
ERR_RISK_CEILING_EXCEEDED = "ERR_RISK_CEILING_EXCEEDED"
ERR_VELOCITY_LIMIT_EXCEEDED = "ERR_VELOCITY_LIMIT_EXCEEDED"
ERR_DAILY_LIMIT_EXCEEDED = "ERR_DAILY_LIMIT_EXCEEDED"
