"""Error IDs and HTTP status mapping (PRD Section 5).

Registers the mapping with the framework so validate_error() can auto-check the
HTTP status code for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_TIER_INSUFFICIENT = "ERR_TIER_INSUFFICIENT"
    ERR_CAREGIVER_SUSPENDED = "ERR_CAREGIVER_SUSPENDED"
    ERR_POSTING_MISMATCH = "ERR_POSTING_MISMATCH"
    ERR_RATE_BELOW_FLOOR = "ERR_RATE_BELOW_FLOOR"
    ERR_RECURRENCE_INVALID = "ERR_RECURRENCE_INVALID"
    ERR_CAREGIVER_DOUBLE_BOOKED = "ERR_CAREGIVER_DOUBLE_BOOKED"
    ERR_FAMILY_WINDOW_CONFLICT = "ERR_FAMILY_WINDOW_CONFLICT"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_BOOKING_NOT_COMPLETED = "ERR_BOOKING_NOT_COMPLETED"
    ERR_INSUFFICIENT_ESCROW = "ERR_INSUFFICIENT_ESCROW"
    ERR_PAYOUT_SESSION_INVALID = "ERR_PAYOUT_SESSION_INVALID"
    ERR_NO_ELIGIBLE_CAREGIVER = "ERR_NO_ELIGIBLE_CAREGIVER"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TIER_INSUFFICIENT: 422,
    ApiErrorId.ERR_CAREGIVER_SUSPENDED: 422,
    ApiErrorId.ERR_POSTING_MISMATCH: 422,
    ApiErrorId.ERR_RATE_BELOW_FLOOR: 422,
    ApiErrorId.ERR_RECURRENCE_INVALID: 422,
    ApiErrorId.ERR_CAREGIVER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_FAMILY_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_BOOKING_NOT_COMPLETED: 422,
    ApiErrorId.ERR_INSUFFICIENT_ESCROW: 422,
    ApiErrorId.ERR_PAYOUT_SESSION_INVALID: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_CAREGIVER: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
