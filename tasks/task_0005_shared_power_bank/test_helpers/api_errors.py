    ERR_RETURN_FAILED = "ERR_RETURN_FAILED"
    ERR_DEPOSIT_INSUFFICIENT = "ERR_DEPOSIT_INSUFFICIENT"
    ERR_WALLET_INSUFFICIENT = "ERR_WALLET_INSUFFICIENT"
