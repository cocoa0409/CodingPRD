"""Barrel export: framework generics + PRD-specific test infrastructure.

Tests import everything from `test_helpers` and never reach into
sub-modules directly.

PRD §2.1 identity rules:
    - ParkManager is entity_backed by Park: X-User-ID is the acting
      Park.id; ownership checks on park-scoped resources (Lots, Homes,
      Leases, RentIncreaseNotices, EvictionCases, HomeSaleTransfers,
      ConversionRequests) compare the resource's park_id to X-User-ID.
    - Resident is entity_backed by Resident: X-User-ID is the acting
      Resident.id; Resident-only mutations require X-User-ID to match
      the resource's resident_id or owner_resident_id (PRD §2.1).
    - PlatformAdmin is opaque: X-User-ID is an audit identifier and is
      not compared against any entity id.

For ownership-gated calls, fixtures MUST mint headers with the actual
Park.id / Resident.id via make_<role>_headers(entity_id) — never fall
back to the shared TEST_USERS constant for those calls.
"""
