def err_missing_headers():
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, 400,
                    "X-User-ID or X-User-Role header missing or empty")


def err_forbidden():
    return ApiError(ERR_INSUFFICIENT_PERMISSIONS, 403,
                    "Role not permitted for this endpoint")


def err_not_found(error_id, resource_name):
    return ApiError(error_id, 404, "%s not found" % resource_name)


def err_state(error_id, message):
    return ApiError(error_id, 409, message)


def err_input(error_id, message):
    return ApiError(error_id, 400, message)


def err_not_assigned():
    return ApiError(ERR_NOT_ASSIGNED_CLINICIAN, 403,
                    "Acting clinician is not the assigned clinician for this resource")


def err_stale():
    return ApiError(ERR_STALE_VERSION, 412,
                    "Expected version does not match the resource's current version")
