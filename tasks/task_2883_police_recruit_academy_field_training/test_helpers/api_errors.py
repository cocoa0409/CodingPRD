"""Error identifiers, their HTTP statuses and the validation-ladder rungs.

Every identifier below appears in the API's error catalogue.  ``ERROR_STATUS``
maps identifier to the single HTTP status the catalogue assigns it, and is
registered with the framework validators so that ``validate_error`` can check
the status whenever a test does not name one explicitly.

``LADDER_RUNG`` records the fixed ascending rung order of the rejection
precedence ladder.  A lower rung wins: when one request violates two rules the
caller sees the error whose rung is smaller.  Tests that pit two violations
against each other use ``assert_ladder_precedence`` in ``assertions.py``.
"""
