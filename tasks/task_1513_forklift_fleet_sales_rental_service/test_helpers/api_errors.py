"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PM_OVERDUE = "ERR_PM_OVERDUE"
    ERR_NO_CERTIFIED_OPERATOR = "ERR_NO_CERTIFIED_OPERATOR"
    ERR_OPERATOR_CERT_EXPIRED = "ERR_OPERATOR_CERT_EXPIRED"
    ERR_UNIT_DISPOSITION_MISMATCH = "ERR_UNIT_DISPOSITION_MISMATCH"
    ERR_TECHNICIAN_INACTIVE = "ERR_TECHNICIAN_INACTIVE"
    ERR_QUOTE_EMPTY = "ERR_QUOTE_EMPTY"
    ERR_VAN_STOCK_INSUFFICIENT = "ERR_VAN_STOCK_INSUFFICIENT"
    ERR_FUEL_PROGRAM_MISMATCH = "ERR_FUEL_PROGRAM_MISMATCH"
    ERR_HOUR_METER_REGRESSION = "ERR_HOUR_METER_REGRESSION"
    ERR_RENTAL_WINDOW_OVERLAP = "ERR_RENTAL_WINDOW_OVERLAP"
    ERR_DISPATCH_WINDOW_OVERLAP = "ERR_DISPATCH_WINDOW_OVERLAP"
    ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
    ERR_ACCOUNT_CREDIT_HOLD = "ERR_ACCOUNT_CREDIT_HOLD"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_INSPECTION_NOT_APPROVED = "ERR_INSPECTION_NOT_APPROVED"
    # Named verbatim in PRD §3.2 prose ("otherwise `ERR_UNIT_NOT_LISTED`") but
    # absent from the §5 catalogue, so no HTTP status is registered for it:
    # validate_error checks the error_id only, never a status, for this id.
    ERR_UNIT_NOT_LISTED = "ERR_UNIT_NOT_LISTED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_UNIT_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PM_OVERDUE: 422,
    ApiErrorId.ERR_NO_CERTIFIED_OPERATOR: 422,
    ApiErrorId.ERR_OPERATOR_CERT_EXPIRED: 422,
    ApiErrorId.ERR_UNIT_DISPOSITION_MISMATCH: 422,
    ApiErrorId.ERR_TECHNICIAN_INACTIVE: 422,
    ApiErrorId.ERR_QUOTE_EMPTY: 422,
    ApiErrorId.ERR_VAN_STOCK_INSUFFICIENT: 422,
    ApiErrorId.ERR_FUEL_PROGRAM_MISMATCH: 422,
    ApiErrorId.ERR_HOUR_METER_REGRESSION: 422,
    ApiErrorId.ERR_RENTAL_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_DISPATCH_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_QUOTE_EXPIRED: 422,
    ApiErrorId.ERR_ACCOUNT_CREDIT_HOLD: 422,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_INSPECTION_NOT_APPROVED: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
