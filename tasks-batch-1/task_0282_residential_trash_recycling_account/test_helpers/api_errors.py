"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CARTS_INCOMPLETE = "ERR_CARTS_INCOMPLETE"
    ERR_PLAN_ARCHIVED = "ERR_PLAN_ARCHIVED"
    ERR_ADDRESS_IN_USE = "ERR_ADDRESS_IN_USE"
    ERR_DATE_DOUBLE_BOOKED = "ERR_DATE_DOUBLE_BOOKED"
    ERR_REPORT_TOO_EARLY = "ERR_REPORT_TOO_EARLY"
    ERR_CONTAMINATION_NOT_RECYCLING = "ERR_CONTAMINATION_NOT_RECYCLING"
    ERR_NO_PAYMENT_METHOD = "ERR_NO_PAYMENT_METHOD"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CARTS_INCOMPLETE: 409,
    ApiErrorId.ERR_PLAN_ARCHIVED: 409,
    ApiErrorId.ERR_ADDRESS_IN_USE: 409,
    ApiErrorId.ERR_DATE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_REPORT_TOO_EARLY: 409,
    ApiErrorId.ERR_CONTAMINATION_NOT_RECYCLING: 409,
    ApiErrorId.ERR_NO_PAYMENT_METHOD: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
