def test_list_sellers_paginated_envelope(api):
    """PRD §2.3: "The `meta` block of a list response carries, in addition to the
    standard request fields, the four pagination fields: `limit` and `offset`
    echoing the effective values used, `total_count` giving the number of rows
    matching the filter before pagination, and `has_more` indicating whether rows
    remain beyond the returned page."

    Design: Corner/entities/list_sellers_paginated_envelope
    """
    register_seller(legal_name="L1", id_type="STATE_ID", id_number="SID-L1")
    register_seller(legal_name="L2", id_type="STATE_ID", id_number="SID-L2")
    rows, meta = validate_paginated(api.list_sellers(WM, params={"limit": 1, "offset": 0}))
    assert meta["total_count"] >= 2, f"expected total_count >= 2, got {meta['total_count']}"
    assert meta["has_more"] is True, f"expected has_more True with limit 1, got {meta['has_more']}"
