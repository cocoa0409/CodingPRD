"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_MEMBER_NOT_ELIGIBLE = "ERR_MEMBER_NOT_ELIGIBLE"
    ERR_SLOT_UNAVAILABLE = "ERR_SLOT_UNAVAILABLE"
    ERR_MEMBER_DOUBLE_BOOKED = "ERR_MEMBER_DOUBLE_BOOKED"
    ERR_PHYSICAL_NOT_DUE = "ERR_PHYSICAL_NOT_DUE"
    ERR_NO_PANEL_CAPACITY = "ERR_NO_PANEL_CAPACITY"
    ERR_SEAT_LIMIT_REACHED = "ERR_SEAT_LIMIT_REACHED"
    ERR_CARE_PLAN_EMPTY = "ERR_CARE_PLAN_EMPTY"
    ERR_REFERRAL_EXPIRED = "ERR_REFERRAL_EXPIRED"
    ERR_AMOUNT_MISMATCH = "ERR_AMOUNT_MISMATCH"
    ERR_PCP_REQUIRED = "ERR_PCP_REQUIRED"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_MEMBER_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_SLOT_UNAVAILABLE: 409,
    ApiErrorId.ERR_MEMBER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_PHYSICAL_NOT_DUE: 409,
    ApiErrorId.ERR_NO_PANEL_CAPACITY: 409,
    ApiErrorId.ERR_SEAT_LIMIT_REACHED: 409,
    ApiErrorId.ERR_CARE_PLAN_EMPTY: 409,
    ApiErrorId.ERR_REFERRAL_EXPIRED: 409,
    ApiErrorId.ERR_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_PCP_REQUIRED: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
