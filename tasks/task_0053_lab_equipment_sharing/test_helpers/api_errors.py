"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EQUIPMENT_UNAVAILABLE = "ERR_EQUIPMENT_UNAVAILABLE"
    ERR_AUTHORIZATION_INVALID = "ERR_AUTHORIZATION_INVALID"
    ERR_AUTHORIZATION_ALREADY_DECIDED = "ERR_AUTHORIZATION_ALREADY_DECIDED"
    ERR_CERTIFICATE_EXPIRED = "ERR_CERTIFICATE_EXPIRED"
    ERR_QUALIFICATION_NOT_MET = "ERR_QUALIFICATION_NOT_MET"
    ERR_SHARING_SCOPE_VIOLATION = "ERR_SHARING_SCOPE_VIOLATION"
    ERR_LEAD_TIME_VIOLATED = "ERR_LEAD_TIME_VIOLATED"
    ERR_SLOT_GRID_VIOLATION = "ERR_SLOT_GRID_VIOLATION"
    ERR_DURATION_LIMIT_EXCEEDED = "ERR_DURATION_LIMIT_EXCEEDED"
    ERR_MAINTENANCE_BLOCK = "ERR_MAINTENANCE_BLOCK"
    ERR_RESERVATION_OVERLAP = "ERR_RESERVATION_OVERLAP"
    ERR_PEAK_PRIORITY_VIOLATION = "ERR_PEAK_PRIORITY_VIOLATION"
    ERR_FEE_SPLIT_INVALID = "ERR_FEE_SPLIT_INVALID"
    ERR_BILLING_RULE_RACED = "ERR_BILLING_RULE_RACED"
    ERR_NOTHING_TO_SETTLE = "ERR_NOTHING_TO_SETTLE"
    ERR_IDEMPOTENCY_CONFLICT = "ERR_IDEMPOTENCY_CONFLICT"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_BAD_REQUEST = "ERR_BAD_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EQUIPMENT_UNAVAILABLE: 409,
    ApiErrorId.ERR_AUTHORIZATION_INVALID: 422,
    ApiErrorId.ERR_AUTHORIZATION_ALREADY_DECIDED: 409,
    ApiErrorId.ERR_CERTIFICATE_EXPIRED: 422,
    ApiErrorId.ERR_QUALIFICATION_NOT_MET: 422,
    ApiErrorId.ERR_SHARING_SCOPE_VIOLATION: 422,
    ApiErrorId.ERR_LEAD_TIME_VIOLATED: 422,
    ApiErrorId.ERR_SLOT_GRID_VIOLATION: 422,
    ApiErrorId.ERR_DURATION_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_MAINTENANCE_BLOCK: 409,
    ApiErrorId.ERR_RESERVATION_OVERLAP: 409,
    ApiErrorId.ERR_PEAK_PRIORITY_VIOLATION: 409,
    ApiErrorId.ERR_FEE_SPLIT_INVALID: 422,
    ApiErrorId.ERR_BILLING_RULE_RACED: 409,
    ApiErrorId.ERR_NOTHING_TO_SETTLE: 422,
    ApiErrorId.ERR_IDEMPOTENCY_CONFLICT: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_BAD_REQUEST: 400,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
