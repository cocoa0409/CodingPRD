"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_CLINIC_REQUIRED_FOR_ACCOUNT_BILLING = "ERR_CLINIC_REQUIRED_FOR_ACCOUNT_BILLING"
    ERR_STALE_CASE_VERSION = "ERR_STALE_CASE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SERVICE_TYPE_MISMATCH = "ERR_SERVICE_TYPE_MISMATCH"
    ERR_CUSTODY_CHAIN_BROKEN = "ERR_CUSTODY_CHAIN_BROKEN"
    ERR_RETORT_WINDOW_CONFLICT = "ERR_RETORT_WINDOW_CONFLICT"
    ERR_VIEWING_ROOM_CONFLICT = "ERR_VIEWING_ROOM_CONFLICT"
    ERR_RETORT_OVERLOADED = "ERR_RETORT_OVERLOADED"
    ERR_COOLER_FULL = "ERR_COOLER_FULL"
    ERR_BATCH_EMPTY = "ERR_BATCH_EMPTY"
    ERR_CLINIC_CREDIT_EXCEEDED = "ERR_CLINIC_CREDIT_EXCEEDED"
    ERR_LINE_ITEM_LOCKED = "ERR_LINE_ITEM_LOCKED"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_VIEWING_FIELDS_REQUIRED = "ERR_VIEWING_FIELDS_REQUIRED"
    ERR_SCHEDULE_WINDOW_INVALID = "ERR_SCHEDULE_WINDOW_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_CLINIC_REQUIRED_FOR_ACCOUNT_BILLING: 422,
    ApiErrorId.ERR_STALE_CASE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SERVICE_TYPE_MISMATCH: 409,
    ApiErrorId.ERR_CUSTODY_CHAIN_BROKEN: 409,
    ApiErrorId.ERR_RETORT_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_VIEWING_ROOM_CONFLICT: 409,
    ApiErrorId.ERR_RETORT_OVERLOADED: 409,
    ApiErrorId.ERR_COOLER_FULL: 409,
    ApiErrorId.ERR_BATCH_EMPTY: 409,
    ApiErrorId.ERR_CLINIC_CREDIT_EXCEEDED: 409,
    ApiErrorId.ERR_LINE_ITEM_LOCKED: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 422,
    ApiErrorId.ERR_VIEWING_FIELDS_REQUIRED: 422,
    ApiErrorId.ERR_SCHEDULE_WINDOW_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
