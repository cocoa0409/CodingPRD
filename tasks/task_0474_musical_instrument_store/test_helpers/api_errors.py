"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_SERIAL = "ERR_DUPLICATE_SERIAL"
    ERR_RESERVATION_MISMATCH = "ERR_RESERVATION_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PLAN_NOT_RENT_TO_OWN = "ERR_PLAN_NOT_RENT_TO_OWN"
    ERR_PAYOFF_MISMATCH = "ERR_PAYOFF_MISMATCH"
    ERR_OUTSTANDING_LATE_FEES = "ERR_OUTSTANDING_LATE_FEES"
    ERR_CREDIT_TOO_LOW = "ERR_CREDIT_TOO_LOW"
    ERR_DEPOSIT_INSUFFICIENT = "ERR_DEPOSIT_INSUFFICIENT"
    ERR_LAYAWAY_NOT_PAID = "ERR_LAYAWAY_NOT_PAID"
    ERR_TICKET_NOT_ASSIGNED = "ERR_TICKET_NOT_ASSIGNED"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_SERIAL: 409,
    ApiErrorId.ERR_RESERVATION_MISMATCH: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PLAN_NOT_RENT_TO_OWN: 409,
    ApiErrorId.ERR_PAYOFF_MISMATCH: 422,
    ApiErrorId.ERR_OUTSTANDING_LATE_FEES: 409,
    ApiErrorId.ERR_CREDIT_TOO_LOW: 422,
    ApiErrorId.ERR_DEPOSIT_INSUFFICIENT: 422,
    ApiErrorId.ERR_LAYAWAY_NOT_PAID: 422,
    ApiErrorId.ERR_TICKET_NOT_ASSIGNED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
