"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PATRON_BARRED = "ERR_PATRON_BARRED"
    ERR_PROBATION_PRIME_BLOCKED = "ERR_PROBATION_PRIME_BLOCKED"
    ERR_COI_REQUIRED = "ERR_COI_REQUIRED"
    ERR_COI_INSUFFICIENT = "ERR_COI_INSUFFICIENT"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_DOUBLE_BOOKING = "ERR_DOUBLE_BOOKING"
    ERR_PAYMENT_REQUIRED = "ERR_PAYMENT_REQUIRED"
    ERR_LOTTERY_NOT_CLOSED = "ERR_LOTTERY_NOT_CLOSED"
    ERR_LOTTERY_NO_ENTRIES = "ERR_LOTTERY_NO_ENTRIES"
    ERR_DUPLICATE_ENTRY = "ERR_DUPLICATE_ENTRY"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PATRON_BARRED: 403,
    ApiErrorId.ERR_PROBATION_PRIME_BLOCKED: 403,
    ApiErrorId.ERR_COI_REQUIRED: 422,
    ApiErrorId.ERR_COI_INSUFFICIENT: 422,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_DOUBLE_BOOKING: 409,
    ApiErrorId.ERR_PAYMENT_REQUIRED: 422,
    ApiErrorId.ERR_LOTTERY_NOT_CLOSED: 409,
    ApiErrorId.ERR_LOTTERY_NO_ENTRIES: 409,
    ApiErrorId.ERR_DUPLICATE_ENTRY: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
