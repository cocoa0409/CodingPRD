    METHOD_NOT_APPROVED = "ERR_METHOD_NOT_APPROVED"
    THEME_DEPTH_EXCEEDED = "ERR_THEME_DEPTH_EXCEEDED"
    NO_ELIGIBLE_PARTICIPANTS = "ERR_NO_ELIGIBLE_PARTICIPANTS"
    EVIDENCE_STUDY_MISMATCH = "ERR_EVIDENCE_STUDY_MISMATCH"
    CITATION_STUDY_MISMATCH = "ERR_CITATION_STUDY_MISMATCH"
    NO_ADMISSIBLE_EVIDENCE = "ERR_NO_ADMISSIBLE_EVIDENCE"
