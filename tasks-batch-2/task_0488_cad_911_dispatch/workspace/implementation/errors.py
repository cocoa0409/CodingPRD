"""Error classes and error ID constants (Scaffold Table 6 / PRD §5)."""

# Auth / existence / validation
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

# Concurrency / state / business
ERR_STALE_INCIDENT_VERSION = "ERR_STALE_INCIDENT_VERSION"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_INCIDENT_HELD = "ERR_INCIDENT_HELD"
ERR_DISCIPLINE_MISMATCH = "ERR_DISCIPLINE_MISMATCH"
ERR_AGENCY_UNAVAILABLE = "ERR_AGENCY_UNAVAILABLE"
ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
ERR_DUPLICATE_ASSIGNMENT = "ERR_DUPLICATE_ASSIGNMENT"
ERR_NO_UNIT_AVAILABLE = "ERR_NO_UNIT_AVAILABLE"
ERR_OPEN_ASSIGNMENTS = "ERR_OPEN_ASSIGNMENTS"
ERR_REPORT_STANDARD_MISMATCH = "ERR_REPORT_STANDARD_MISMATCH"
ERR_INCIDENT_NOT_CLOSED = "ERR_INCIDENT_NOT_CLOSED"
ERR_DUPLICATE_CALL_SIGN = "ERR_DUPLICATE_CALL_SIGN"
ERR_STATION_AGENCY_MISMATCH = "ERR_STATION_AGENCY_MISMATCH"

# error_id -> default HTTP status
HTTP_STATUS = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN_ROLE: 403,
    ERR_NOT_FOUND: 404,
    ERR_REFERENCE_NOT_FOUND: 404,
    ERR_INVALID_REQUEST: 422,
    ERR_STALE_INCIDENT_VERSION: 412,
    ERR_INVALID_STATE: 409,
    ERR_INCIDENT_HELD: 409,
    ERR_DISCIPLINE_MISMATCH: 409,
    ERR_AGENCY_UNAVAILABLE: 409,
    ERR_UNIT_NOT_AVAILABLE: 409,
    ERR_DUPLICATE_ASSIGNMENT: 409,
    ERR_NO_UNIT_AVAILABLE: 409,
    ERR_OPEN_ASSIGNMENTS: 409,
    ERR_REPORT_STANDARD_MISMATCH: 409,
    ERR_INCIDENT_NOT_CLOSED: 409,
    ERR_DUPLICATE_CALL_SIGN: 409,
    ERR_STATION_AGENCY_MISMATCH: 409,
}


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = http_status or HTTP_STATUS.get(error_id, 400)


def err(error_id, message=None):
    return ApiError(error_id, message)
