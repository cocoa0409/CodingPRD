"""Error IDs and HTTP status mapping (PRD §5 error catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CROSS_PLAN_REFERENCE = "ERR_CROSS_PLAN_REFERENCE"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_CLAIM_WINDOW_AMBIGUITY = "ERR_CLAIM_WINDOW_AMBIGUITY"
    ERR_NOTICE_OUTSTANDING = "ERR_NOTICE_OUTSTANDING"
    ERR_LASER_CONFLICT = "ERR_LASER_CONFLICT"
    ERR_AMOUNT_OUT_OF_RANGE = "ERR_AMOUNT_OUT_OF_RANGE"
    ERR_FILING_DEADLINE_PASSED = "ERR_FILING_DEADLINE_PASSED"
    ERR_REIMBURSEMENT_MISMATCH = "ERR_REIMBURSEMENT_MISMATCH"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CROSS_PLAN_REFERENCE: 422,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_CLAIM_WINDOW_AMBIGUITY: 422,
    ApiErrorId.ERR_NOTICE_OUTSTANDING: 422,
    ApiErrorId.ERR_LASER_CONFLICT: 422,
    ApiErrorId.ERR_AMOUNT_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_FILING_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_REIMBURSEMENT_MISMATCH: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
