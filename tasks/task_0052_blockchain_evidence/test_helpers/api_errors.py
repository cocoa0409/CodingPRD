"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_PERMISSION_DENIED = "ERR_PERMISSION_DENIED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_CUSTOMER_NOT_FOUND = "ERR_CUSTOMER_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EVIDENCE_NOT_CONFIRMED = "ERR_EVIDENCE_NOT_CONFIRMED"
    ERR_HASH_FORMAT_INVALID = "ERR_HASH_FORMAT_INVALID"
    ERR_BATCH_MEMBER_INVALID = "ERR_BATCH_MEMBER_INVALID"
    ERR_BATCH_SIZE_OUT_OF_RANGE = "ERR_BATCH_SIZE_OUT_OF_RANGE"
    ERR_PERIOD_INVALID = "ERR_PERIOD_INVALID"
    ERR_RESUBMIT_LIMIT_EXCEEDED = "ERR_RESUBMIT_LIMIT_EXCEEDED"
    ERR_TIMESTAMP_REQUIRED = "ERR_TIMESTAMP_REQUIRED"
    ERR_CERTIFICATE_REQUIRED = "ERR_CERTIFICATE_REQUIRED"
    ERR_EVIDENCE_EXPIRED = "ERR_EVIDENCE_EXPIRED"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_DUPLICATE_IDEMPOTENCY_KEY = "ERR_DUPLICATE_IDEMPOTENCY_KEY"
    ERR_DUPLICATE_PAYMENT_REF = "ERR_DUPLICATE_PAYMENT_REF"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_INVOICE_SCOPE_INVALID = "ERR_INVOICE_SCOPE_INVALID"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_PERMISSION_DENIED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_CUSTOMER_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EVIDENCE_NOT_CONFIRMED: 409,
    ApiErrorId.ERR_HASH_FORMAT_INVALID: 422,
    ApiErrorId.ERR_BATCH_MEMBER_INVALID: 422,
    ApiErrorId.ERR_BATCH_SIZE_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_PERIOD_INVALID: 422,
    ApiErrorId.ERR_RESUBMIT_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_TIMESTAMP_REQUIRED: 409,
    ApiErrorId.ERR_CERTIFICATE_REQUIRED: 409,
    ApiErrorId.ERR_EVIDENCE_EXPIRED: 410,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 402,
    ApiErrorId.ERR_DUPLICATE_IDEMPOTENCY_KEY: 409,
    ApiErrorId.ERR_DUPLICATE_PAYMENT_REF: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INVOICE_SCOPE_INVALID: 422,
    ApiErrorId.ERR_VALIDATION_FAILED: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
