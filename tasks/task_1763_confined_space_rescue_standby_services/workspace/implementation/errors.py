"""Error classes and error-ID constants.

Every error_id and HTTP status below is taken verbatim from the PRD section 5
Error Code Catalogue / SCAFFOLD errors table.
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message):
        super().__init__(message)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message


def raise_error(err_tuple, message):
    raise ApiError(err_tuple[0], err_tuple[1], message)


