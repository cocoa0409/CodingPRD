"""Error catalog and the ApiError exception."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error ID -> HTTP status (from PRD §5 / scaffold §1.6)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_ONBOARDING_INCOMPLETE = ("ERR_ONBOARDING_INCOMPLETE", 409)
ERR_OPEN_CLOSES_EXIST = ("ERR_OPEN_CLOSES_EXIST", 409)
ERR_DECEMBER_CLOSE_NOT_FINAL = ("ERR_DECEMBER_CLOSE_NOT_FINAL", 409)
ERR_CLOSE_FINALIZED = ("ERR_CLOSE_FINALIZED", 409)
ERR_NO_LEDGER_ACCOUNTS = ("ERR_NO_LEDGER_ACCOUNTS", 409)
ERR_CROSS_CLIENT_PARENT = ("ERR_CROSS_CLIENT_PARENT", 422)
ERR_DUPLICATE_ACCOUNT_CODE = ("ERR_DUPLICATE_ACCOUNT_CODE", 409)
ERR_DUPLICATE_PERIOD = ("ERR_DUPLICATE_PERIOD", 409)
ERR_PAY_PERIOD_OVERLAP = ("ERR_PAY_PERIOD_OVERLAP", 409)
ERR_COVENANT_BREACH = ("ERR_COVENANT_BREACH", 422)
ERR_UNDERPAYMENT = ("ERR_UNDERPAYMENT", 422)
ERR_MISSING_SCHEDULE_DATE = ("ERR_MISSING_SCHEDULE_DATE", 422)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_PERIOD = ("ERR_INVALID_PERIOD", 422)
ERR_INVALID_TASK_STATUS = ("ERR_INVALID_TASK_STATUS", 422)
ERR_NEGATIVE_AMOUNT = ("ERR_NEGATIVE_AMOUNT", 422)
ERR_VALIDATION_LIMIT = ("ERR_VALIDATION_LIMIT", 400)


def err(spec, message=None):
    """Build an ApiError from an (error_id, http_status) tuple."""
    return ApiError(spec[0], spec[1], message)
