"""Error IDs and HTTP status mapping (PRD §5).

After defining the map it is registered with the framework so validate_error()
auto-checks the HTTP status from the error_id without callers passing it.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_CROSS_COMMUNITY_REFERENCE = "ERR_CROSS_COMMUNITY_REFERENCE"
    ERR_DUPLICATE_LOT_NUMBER = "ERR_DUPLICATE_LOT_NUMBER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LOT_NOT_VACANT = "ERR_LOT_NOT_VACANT"
    ERR_LOT_FROZEN = "ERR_LOT_FROZEN"
    ERR_EVICTION_IN_PROGRESS = "ERR_EVICTION_IN_PROGRESS"
    ERR_STALE_LOT_VERSION = "ERR_STALE_LOT_VERSION"
    ERR_INCREASE_TOO_SOON = "ERR_INCREASE_TOO_SOON"
    ERR_CURE_PERIOD_EXPIRED = "ERR_CURE_PERIOD_EXPIRED"
    ERR_CURE_PERIOD_ACTIVE = "ERR_CURE_PERIOD_ACTIVE"
    ERR_ARREARS_BELOW_THRESHOLD = "ERR_ARREARS_BELOW_THRESHOLD"
    ERR_ARREARS_NOT_CLEARED = "ERR_ARREARS_NOT_CLEARED"
    ERR_NO_OCCUPIED_LOTS = "ERR_NO_OCCUPIED_LOTS"
    ERR_NO_METER_READINGS = "ERR_NO_METER_READINGS"
    ERR_DUPLICATE_BALLOT = "ERR_DUPLICATE_BALLOT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_CROSS_COMMUNITY_REFERENCE: 409,
    ApiErrorId.ERR_DUPLICATE_LOT_NUMBER: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LOT_NOT_VACANT: 409,
    ApiErrorId.ERR_LOT_FROZEN: 409,
    ApiErrorId.ERR_EVICTION_IN_PROGRESS: 409,
    ApiErrorId.ERR_STALE_LOT_VERSION: 412,
    ApiErrorId.ERR_INCREASE_TOO_SOON: 409,
    ApiErrorId.ERR_CURE_PERIOD_EXPIRED: 409,
    ApiErrorId.ERR_CURE_PERIOD_ACTIVE: 409,
    ApiErrorId.ERR_ARREARS_BELOW_THRESHOLD: 409,
    ApiErrorId.ERR_ARREARS_NOT_CLEARED: 409,
    ApiErrorId.ERR_NO_OCCUPIED_LOTS: 409,
    ApiErrorId.ERR_NO_METER_READINGS: 409,
    ApiErrorId.ERR_DUPLICATE_BALLOT: 409,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
