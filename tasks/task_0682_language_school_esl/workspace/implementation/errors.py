"""Error catalog (PRD §5 / SCAFFOLD §1.6)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# (error_id, http_status) pairs taken verbatim from the PRD §5 catalogue.
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_PLACEMENT_MISMATCH = ("ERR_PLACEMENT_MISMATCH", 409)
ERR_VISA_NONCOMPLIANT = ("ERR_VISA_NONCOMPLIANT", 409)
ERR_SCHEDULE_CONFLICT = ("ERR_SCHEDULE_CONFLICT", 409)
ERR_DUPLICATE_SESSION = ("ERR_DUPLICATE_SESSION", 409)
ERR_CONTRACT_SEATS_EXHAUSTED = ("ERR_CONTRACT_SEATS_EXHAUSTED", 409)
ERR_COHORT_FULL = ("ERR_COHORT_FULL", 409)
ERR_STALE_COHORT_VERSION = ("ERR_STALE_COHORT_VERSION", 412)
ERR_STALE_CONTRACT_VERSION = ("ERR_STALE_CONTRACT_VERSION", 412)
ERR_COMPLETION_REQUIREMENTS_UNMET = ("ERR_COMPLETION_REQUIREMENTS_UNMET", 409)
ERR_NOT_FULL_COURSE_OF_STUDY = ("ERR_NOT_FULL_COURSE_OF_STUDY", 409)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_DUPLICATE_EMAIL = ("ERR_DUPLICATE_EMAIL", 409)
ERR_CONTRACT_REQUIRED_FOR_SPONSOR = ("ERR_CONTRACT_REQUIRED_FOR_SPONSOR", 404)
ERR_INVALID_TERMINATION_REASON = ("ERR_INVALID_TERMINATION_REASON", 422)
ERR_ADDON_ENROLLMENT_MISMATCH = ("ERR_ADDON_ENROLLMENT_MISMATCH", 409)
ERR_VALIDATION_PAGINATION = ("ERR_VALIDATION_PAGINATION", 422)


def err(pair, message=None):
    return ApiError(pair[0], pair[1], message)
