"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INSTRUCTOR_NOT_CERTIFIED = "ERR_INSTRUCTOR_NOT_CERTIFIED"
    ERR_INSTRUCTOR_SCHEDULE_CONFLICT = "ERR_INSTRUCTOR_SCHEDULE_CONFLICT"
    ERR_ROOM_SCHEDULE_CONFLICT = "ERR_ROOM_SCHEDULE_CONFLICT"
    ERR_AGE_BAND_MISMATCH = "ERR_AGE_BAND_MISMATCH"
    ERR_LEVEL_MISMATCH = "ERR_LEVEL_MISMATCH"
    ERR_MEMBERSHIP_NOT_ACTIVE = "ERR_MEMBERSHIP_NOT_ACTIVE"
    ERR_SESSION_FULL = "ERR_SESSION_FULL"
    ERR_PARTICIPATION_REQUIRED = "ERR_PARTICIPATION_REQUIRED"
    ERR_NO_CREDIT_AVAILABLE = "ERR_NO_CREDIT_AVAILABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INSTRUCTOR_NOT_CERTIFIED: 422,
    ApiErrorId.ERR_INSTRUCTOR_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_ROOM_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_AGE_BAND_MISMATCH: 422,
    ApiErrorId.ERR_LEVEL_MISMATCH: 422,
    ApiErrorId.ERR_MEMBERSHIP_NOT_ACTIVE: 422,
    ApiErrorId.ERR_SESSION_FULL: 409,
    ApiErrorId.ERR_PARTICIPATION_REQUIRED: 422,
    ApiErrorId.ERR_NO_CREDIT_AVAILABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
