"""Error IDs and HTTP status mapping (PRD Section 5).

Registers the mapping with the framework so validate_error() can
auto-check the HTTP status of every error response.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CAMPAIGN_ALREADY_ALLOCATED = "ERR_CAMPAIGN_ALREADY_ALLOCATED"
    ERR_ALLOCATION_EXHAUSTED = "ERR_ALLOCATION_EXHAUSTED"
    ERR_RESERVATION_NOT_ALLOCATED = "ERR_RESERVATION_NOT_ALLOCATED"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_HAZMAT_ACK_REQUIRED = "ERR_HAZMAT_ACK_REQUIRED"
    ERR_INSUFFICIENT_PAYMENT = "ERR_INSUFFICIENT_PAYMENT"
    ERR_WINDOW_CLOSED = "ERR_WINDOW_CLOSED"
    ERR_CHECKIN_WINDOW_CLOSED = "ERR_CHECKIN_WINDOW_CLOSED"
    ERR_EVENT_FULL = "ERR_EVENT_FULL"
    ERR_DUPLICATE_ENTRY = "ERR_DUPLICATE_ENTRY"
    ERR_LANE_CONFLICT = "ERR_LANE_CONFLICT"
    ERR_BENCH_CONFLICT = "ERR_BENCH_CONFLICT"
    ERR_SAFETY_INSPECTION_REQUIRED = "ERR_SAFETY_INSPECTION_REQUIRED"
    ERR_INVALID_ACTION = "ERR_INVALID_ACTION"
    ERR_LANE_OUT_OF_RANGE = "ERR_LANE_OUT_OF_RANGE"
    ERR_PAYMENT_ALREADY_SETTLED = "ERR_PAYMENT_ALREADY_SETTLED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CAMPAIGN_ALREADY_ALLOCATED: 409,
    ApiErrorId.ERR_ALLOCATION_EXHAUSTED: 409,
    ApiErrorId.ERR_RESERVATION_NOT_ALLOCATED: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_HAZMAT_ACK_REQUIRED: 409,
    ApiErrorId.ERR_INSUFFICIENT_PAYMENT: 402,
    ApiErrorId.ERR_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_CHECKIN_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_EVENT_FULL: 409,
    ApiErrorId.ERR_DUPLICATE_ENTRY: 409,
    ApiErrorId.ERR_LANE_CONFLICT: 409,
    ApiErrorId.ERR_BENCH_CONFLICT: 409,
    ApiErrorId.ERR_SAFETY_INSPECTION_REQUIRED: 409,
    ApiErrorId.ERR_INVALID_ACTION: 400,
    ApiErrorId.ERR_LANE_OUT_OF_RANGE: 400,
    ApiErrorId.ERR_PAYMENT_ALREADY_SETTLED: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
