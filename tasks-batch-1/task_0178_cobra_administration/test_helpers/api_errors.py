"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, it is registered with the framework so
validate_error() can auto-cross-check HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_BENEFICIARY_NOT_ELIGIBLE = "ERR_BENEFICIARY_NOT_ELIGIBLE"
    ERR_ELECTION_WINDOW_CLOSED = "ERR_ELECTION_WINDOW_CLOSED"
    ERR_DISABILITY_WINDOW_INVALID = "ERR_DISABILITY_WINDOW_INVALID"
    ERR_EXTENSION_NOT_APPLICABLE = "ERR_EXTENSION_NOT_APPLICABLE"
    ERR_INVALID_TERMINATION_REASON = "ERR_INVALID_TERMINATION_REASON"
    ERR_INVALID_COVERAGE_MONTH = "ERR_INVALID_COVERAGE_MONTH"
    ERR_DUPLICATE_INVOICE = "ERR_DUPLICATE_INVOICE"
    ERR_NO_OPEN_INVOICE = "ERR_NO_OPEN_INVOICE"
    ERR_INVALID_SUBSIDY_RANGE = "ERR_INVALID_SUBSIDY_RANGE"
    ERR_REFUND_EXCEEDS_CREDIT = "ERR_REFUND_EXCEEDS_CREDIT"
    ERR_NO_CREDIT_BALANCE = "ERR_NO_CREDIT_BALANCE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_BENEFICIARY_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_ELECTION_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_DISABILITY_WINDOW_INVALID: 409,
    ApiErrorId.ERR_EXTENSION_NOT_APPLICABLE: 409,
    ApiErrorId.ERR_INVALID_TERMINATION_REASON: 409,
    ApiErrorId.ERR_INVALID_COVERAGE_MONTH: 409,
    ApiErrorId.ERR_DUPLICATE_INVOICE: 409,
    ApiErrorId.ERR_NO_OPEN_INVOICE: 409,
    ApiErrorId.ERR_INVALID_SUBSIDY_RANGE: 409,
    ApiErrorId.ERR_REFUND_EXCEEDS_CREDIT: 409,
    ApiErrorId.ERR_NO_CREDIT_BALANCE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
