# Teach the shared validators which status each error id must carry, so that
# validate_error() checks the status without every call site repeating it.
set_error_http_status_map(HTTP_STATUS_CODES)


def expected_status_for(error_id) -> int:
    """HTTP status the PRD pins to ``error_id``."""
    key = error_id.value if isinstance(error_id, ApiErrorId) else str(error_id)
    return HTTP_STATUS_CODES[key]
