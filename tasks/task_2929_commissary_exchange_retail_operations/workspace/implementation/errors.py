"""Error catalogue (PRD section 5) and the exception type carrying it."""


class ApiError(Exception):
    """Raised anywhere in the request path; rendered by the Flask error handler."""

    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status if http_status is not None else ERROR_CATALOG.get(error_id, 400)
        self.message = message if message else DEFAULT_MESSAGES.get(error_id, error_id)


