"""Error classes and error ID constants for the Radon Testing & Mitigation API.

Every error_id / http_status pair traces verbatim to PRD §5 (Error Code Catalogue)
and SCAFFOLD §1.6.
"""


class ApiError(Exception):
    """Raised anywhere in request handling; carries the canonical error_id,
    a human-readable message, and the HTTP status to emit."""

    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


