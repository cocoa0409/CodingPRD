    ERR_PLAYER_NOT_FOUND = "ERR_PLAYER_NOT_FOUND"
    ERR_GAME_NOT_FOUND = "ERR_GAME_NOT_FOUND"
    ERR_SHIFT_NOT_FOUND = "ERR_SHIFT_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # State — PRD §2.6
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_PLAYER_STATE = "ERR_INVALID_PLAYER_STATE"
    ERR_SEASON_NOT_DRAFT_OPEN = "ERR_SEASON_NOT_DRAFT_OPEN"

    # Business safety — PRD §3.2, §3.3
    ERR_BIRTH_CERT_REQUIRED = "ERR_BIRTH_CERT_REQUIRED"
    ERR_AGE_INELIGIBLE = "ERR_AGE_INELIGIBLE"
    ERR_COACH_NO_BACKGROUND_CHECK = "ERR_COACH_NO_BACKGROUND_CHECK"
    ERR_TIER_A_CAP_EXCEEDED = "ERR_TIER_A_CAP_EXCEEDED"

