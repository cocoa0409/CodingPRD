    ERR_WITHIN_GRACE = "ERR_WITHIN_GRACE"
    ERR_GRACE_WINDOW_EXPIRED = "ERR_GRACE_WINDOW_EXPIRED"
    ERR_ODOMETER_ROLLBACK = "ERR_ODOMETER_ROLLBACK"
    ERR_TOTAL_LOSS_REQUIRES_WRITEOFF = "ERR_TOTAL_LOSS_REQUIRES_WRITEOFF"
    ERR_NO_TOTAL_INCIDENT = "ERR_NO_TOTAL_INCIDENT"
    ERR_NO_AVAILABILITY = "ERR_NO_AVAILABILITY"
    ERR_AGREEMENT_STILL_OPEN = "ERR_AGREEMENT_STILL_OPEN"
    ERR_OPEN_INCIDENT = "ERR_OPEN_INCIDENT"
    ERR_NOT_AN_UPGRADE = "ERR_NOT_AN_UPGRADE"
