"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / RBAC / existence
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State / OCC
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Project / submit / review
    ERR_KYC_REQUIRED = "ERR_KYC_REQUIRED"
    ERR_SEGREGATION_OF_DUTIES_VIOLATION = "ERR_SEGREGATION_OF_DUTIES_VIOLATION"
    ERR_DEADLINE_TOO_SOON = "ERR_DEADLINE_TOO_SOON"
    ERR_NO_REWARDS_DEFINED = "ERR_NO_REWARDS_DEFINED"

    # Order modification / inventory / shipping / cross-project
    ERR_MODIFICATION_WINDOW_CLOSED = "ERR_MODIFICATION_WINDOW_CLOSED"
    ERR_REWARD_INVENTORY_EXHAUSTED = "ERR_REWARD_INVENTORY_EXHAUSTED"
    ERR_ADDON_INVENTORY_EXHAUSTED = "ERR_ADDON_INVENTORY_EXHAUSTED"
    ERR_SHIPPING_ADDRESS_REQUIRED = "ERR_SHIPPING_ADDRESS_REQUIRED"
    ERR_CROSS_PROJECT_REFERENCE = "ERR_CROSS_PROJECT_REFERENCE"

    # Refunds / settlement
    ERR_REFUND_EXCEEDS_REMAINDER = "ERR_REFUND_EXCEEDS_REMAINDER"
    ERR_UPDATE_FREQUENCY_BREACH = "ERR_UPDATE_FREQUENCY_BREACH"
    ERR_PENDING_REFUNDS_BLOCK_SETTLEMENT = "ERR_PENDING_REFUNDS_BLOCK_SETTLEMENT"

    # Generic constraints
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_DUPLICATE_TIER_LABEL = "ERR_DUPLICATE_TIER_LABEL"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_KYC_REQUIRED: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES_VIOLATION: 403,
    ApiErrorId.ERR_DEADLINE_TOO_SOON: 422,
    ApiErrorId.ERR_NO_REWARDS_DEFINED: 422,
    ApiErrorId.ERR_MODIFICATION_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_REWARD_INVENTORY_EXHAUSTED: 409,
    ApiErrorId.ERR_ADDON_INVENTORY_EXHAUSTED: 409,
    ApiErrorId.ERR_SHIPPING_ADDRESS_REQUIRED: 422,
    ApiErrorId.ERR_CROSS_PROJECT_REFERENCE: 422,
    ApiErrorId.ERR_REFUND_EXCEEDS_REMAINDER: 422,
    ApiErrorId.ERR_UPDATE_FREQUENCY_BREACH: 422,
    ApiErrorId.ERR_PENDING_REFUNDS_BLOCK_SETTLEMENT: 422,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_DUPLICATE_TIER_LABEL: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
