"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the map, register it with the framework so validate_error()
auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CLAIM_CREDITOR_MISMATCH = "ERR_CLAIM_CREDITOR_MISMATCH"
    ERR_RELIEF_TARGET_NOT_SECURED = "ERR_RELIEF_TARGET_NOT_SECURED"
    ERR_MEANS_TEST_ABUSE = "ERR_MEANS_TEST_ABUSE"
    ERR_PRIOR_DISCHARGE_BAR = "ERR_PRIOR_DISCHARGE_BAR"
    ERR_STAY_TERMINATED = "ERR_STAY_TERMINATED"
    ERR_EXEMPTION_EXCEEDS_ASSET = "ERR_EXEMPTION_EXCEEDS_ASSET"
    ERR_NOT_CHAPTER_13 = "ERR_NOT_CHAPTER_13"
    ERR_PLAN_INFEASIBLE = "ERR_PLAN_INFEASIBLE"
    ERR_PLAN_OVERPAYMENT = "ERR_PLAN_OVERPAYMENT"
    ERR_STALE_CASE_VERSION = "ERR_STALE_CASE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CLAIM_CREDITOR_MISMATCH: 409,
    ApiErrorId.ERR_RELIEF_TARGET_NOT_SECURED: 409,
    ApiErrorId.ERR_MEANS_TEST_ABUSE: 409,
    ApiErrorId.ERR_PRIOR_DISCHARGE_BAR: 409,
    ApiErrorId.ERR_STAY_TERMINATED: 409,
    ApiErrorId.ERR_EXEMPTION_EXCEEDS_ASSET: 422,
    ApiErrorId.ERR_NOT_CHAPTER_13: 409,
    ApiErrorId.ERR_PLAN_INFEASIBLE: 409,
    ApiErrorId.ERR_PLAN_OVERPAYMENT: 422,
    ApiErrorId.ERR_STALE_CASE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
