"""Expense accrual endpoints: manual create (non-ADMIN_FEE), get, list."""
from flask import Blueprint

from db import store
from errors import ApiError
from middleware import ALL_ROLES, get_context, require_roles
from response import created, filter_arg, ok, paginate
from services import navmath
from validation import parse_body, require_fk, require_path_entity

bp = Blueprint("accruals", __name__)

ACCRUAL_SCHEMA = {
    "share_class_id": ("string", True, None),
    "accrual_date": ("date", True, None),
    "category": ("enum", True, ["ADMIN_FEE", "CUSTODY_FEE", "AUDIT_FEE", "LEGAL_FEE", "OTHER"]),
    "annual_rate_bps": ("posnumber", True, None),
}


@bp.post("/expense-accruals")
def create_expense_accrual():
    get_context()
    require_roles(["FundAccountant"])
    body = parse_body(ACCRUAL_SCHEMA)
    cls = require_fk(store.share_classes, body["share_class_id"], "share_class_id")

    # Constraints (priority 9, listed order): the date must match an ESTIMATED
    # record of the class; ADMIN_FEE rows are system-generated only.
    nav = navmath.nav_at(cls["id"], body["accrual_date"])
    if nav is None or nav["status"] != "ESTIMATED":
        raise ApiError("ERR_NO_ESTIMABLE_NAV", 422,
                       "accrual_date does not match an ESTIMATED NavRecord of the class")
    if body["category"] == "ADMIN_FEE":
        raise ApiError("ERR_CATEGORY_SYSTEM_MANAGED", 422,
                       "ADMIN_FEE accruals are generated by NavRecord creation only")

    row = navmath.new_accrual(cls["id"], body["accrual_date"], body["category"],
                              body["annual_rate_bps"], nav["gross_asset_value"])
    navmath.recompute_nav(nav, bump=True)
    return created(row)


@bp.get("/expense-accruals/<expense_accrual_id>")
def get_expense_accrual(expense_accrual_id):
    get_context()
    row = require_path_entity(store.expense_accruals, expense_accrual_id)
    require_roles(ALL_ROLES)
    return ok(row)


@bp.get("/expense-accruals")
def list_expense_accruals():
    get_context()
    require_roles(ALL_ROLES)
    rows = list(store.expense_accruals.values())
    rows = filter_arg(rows, "share_class_id")
    rows = filter_arg(rows, "accrual_date")
    rows = filter_arg(rows, "category")
    rows = filter_arg(rows, "status")
    page, meta = paginate(rows)
    return ok(page, rtype="array", pagination=meta)
