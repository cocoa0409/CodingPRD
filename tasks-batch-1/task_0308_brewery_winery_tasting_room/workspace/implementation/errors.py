"""Error catalogue (PRD §5) and the ApiError exception."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# PRD §5 Error Code Catalogue
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_RESOURCE_OWNER = ("ERR_NOT_RESOURCE_OWNER", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_FK_NOT_FOUND = ("ERR_FK_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_PRODUCT_VERSION = ("ERR_STALE_PRODUCT_VERSION", 412)
ERR_STALE_RELEASE_VERSION = ("ERR_STALE_RELEASE_VERSION", 412)
ERR_STALE_WINERY_VERSION = ("ERR_STALE_WINERY_VERSION", 412)
ERR_AGE_RESTRICTION = ("ERR_AGE_RESTRICTION", 422)
ERR_STATE_SHIPPING_LIMIT = ("ERR_STATE_SHIPPING_LIMIT", 422)
ERR_WINERY_SUSPENDED = ("ERR_WINERY_SUSPENDED", 409)
ERR_PER_MEMBER_CAP_EXCEEDED = ("ERR_PER_MEMBER_CAP_EXCEEDED", 422)
ERR_RELEASE_WINDOW_CLOSED = ("ERR_RELEASE_WINDOW_CLOSED", 422)
ERR_TABLE_DOUBLE_BOOKED = ("ERR_TABLE_DOUBLE_BOOKED", 409)
ERR_BILLING_PAST_DUE = ("ERR_BILLING_PAST_DUE", 409)
ERR_INSUFFICIENT_INVENTORY = ("ERR_INSUFFICIENT_INVENTORY", 409)
ERR_INSUFFICIENT_BULK = ("ERR_INSUFFICIENT_BULK", 409)
ERR_INSUFFICIENT_POINTS = ("ERR_INSUFFICIENT_POINTS", 422)
ERR_RELEASE_NOT_OPEN = ("ERR_RELEASE_NOT_OPEN", 409)
ERR_BATCH_HAS_INVENTORY = ("ERR_BATCH_HAS_INVENTORY", 409)


def err(spec, message=None):
    """Build an ApiError from an (error_id, http_status) tuple."""
    return ApiError(spec[0], spec[1], message)
