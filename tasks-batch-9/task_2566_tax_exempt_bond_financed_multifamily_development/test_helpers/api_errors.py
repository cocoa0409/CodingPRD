"""The error catalogue of PRD §5 and the id-to-HTTP-status map it fixes.

Importing this module registers the map with the framework, so a test may write
``validate_error(response, ApiErrorId.ERR_X)`` and have the HTTP status
cross-checked without repeating the number at every call site.
"""

