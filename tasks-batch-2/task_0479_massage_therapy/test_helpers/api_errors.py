"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CONSENT_REQUIRED = "ERR_CONSENT_REQUIRED"
    ERR_CONTRAINDICATION = "ERR_CONTRAINDICATION"
    ERR_INTAKE_INVALID = "ERR_INTAKE_INVALID"
    ERR_LICENSE_EXPIRED = "ERR_LICENSE_EXPIRED"
    ERR_CERTIFICATION_REQUIRED = "ERR_CERTIFICATION_REQUIRED"
    ERR_TABLE_UNSUITABLE = "ERR_TABLE_UNSUITABLE"
    ERR_TABLE_DOUBLE_BOOKED = "ERR_TABLE_DOUBLE_BOOKED"
    ERR_THERAPIST_DOUBLE_BOOKED = "ERR_THERAPIST_DOUBLE_BOOKED"
    ERR_NO_CREDITS = "ERR_NO_CREDITS"
    ERR_INSUFFICIENT_HSA = "ERR_INSUFFICIENT_HSA"
    ERR_NOT_BILLABLE = "ERR_NOT_BILLABLE"
    ERR_RENEWAL_TOO_EARLY = "ERR_RENEWAL_TOO_EARLY"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CONSENT_REQUIRED: 422,
    ApiErrorId.ERR_CONTRAINDICATION: 422,
    ApiErrorId.ERR_INTAKE_INVALID: 422,
    ApiErrorId.ERR_LICENSE_EXPIRED: 422,
    ApiErrorId.ERR_CERTIFICATION_REQUIRED: 422,
    ApiErrorId.ERR_TABLE_UNSUITABLE: 422,
    ApiErrorId.ERR_TABLE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_THERAPIST_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_NO_CREDITS: 422,
    ApiErrorId.ERR_INSUFFICIENT_HSA: 422,
    ApiErrorId.ERR_NOT_BILLABLE: 422,
    ApiErrorId.ERR_RENEWAL_TOO_EARLY: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
