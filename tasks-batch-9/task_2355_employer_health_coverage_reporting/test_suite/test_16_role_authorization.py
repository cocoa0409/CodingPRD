def test_benefits_admin_may_furnish_a_statement_a_preparer_generated(api):
    """PRD §3.7: "Furnishing a statement is available to a `Preparer` or a
    `BenefitsAdmin` and takes a `delivery_channel` of `PAPER` or `ELECTRONIC` plus
    an optional `intentional_disregard` flag."
    PRD §3.7: "It is accepted only from `NOT_FURNISHED` or `REDELIVERY_REQUIRED`,
    so `furnishing_status` walks `NOT_FURNISHED` → `FURNISHED_PAPER` or
    `NOT_FURNISHED` → `FURNISHED_ELECTRONIC` on first delivery and
    `REDELIVERY_REQUIRED` → `FURNISHED_PAPER` or `REDELIVERY_REQUIRED` →
    `FURNISHED_ELECTRONIC` on redelivery."
    PRD §3.7: "A successful delivery stamps `furnished_at` and
    `furnished_by_user_id`."

    Design: Corner/RBAC/benefits_admin_shares_furnish_with_preparer
    """
    ctx = _statement_ready_to_furnish(api)

    furnished = validate_success(
        api.furnish_form_1095c(ctx["form"]["id"], f.furnish_payload("PAPER"), BA), 200
    )
    assert furnished["furnishing_status"] == "FURNISHED_PAPER", (
        f"expected FURNISHED_PAPER after a paper delivery, got "
        f"{furnished['furnishing_status']!r}"
    )
    assert furnished["furnished_by_user_id"] == BA["X-User-ID"], (
        f"expected the acting benefits admin {BA['X-User-ID']!r} in "
        f"furnished_by_user_id, got {furnished['furnished_by_user_id']!r}"
    )
    assert furnished["furnished_at"] is not None, "a successful delivery stamps furnished_at"


def test_benefits_admin_furnishing_before_the_deadline_carries_no_penalty(api):
    """PRD §3.7: "The day count is the whole-day difference between the logical
    clock's UTC date and the season's `furnishing_deadline_date`."
    PRD §3.7: "A statement delivered on or before the deadline date carries no
    penalty at all — the deadline date itself is not late."
    PRD §3.7: "The figure lands in the statement's `late_furnishing_penalty_cents`,
    and the member's `furnishing_penalty_total_cents` absorbs only the **delta** —
    the newly computed penalty minus whatever this statement had previously
    contributed — so a redelivery at a worse tier adds only the increase rather
    than double-counting the original charge."

    Design: Corner/RBAC/benefits_admin_shares_furnish_with_preparer
    """
    ctx = _statement_ready_to_furnish(api)

    furnished = validate_success(
        api.furnish_form_1095c(ctx["form"]["id"], f.furnish_payload("PAPER"), BA), 200
    )
    assert furnished["late_furnishing_penalty_cents"] == 0, (
        "delivery on 2027-02-01 is before the 2027-03-02 furnishing deadline and "
        f"must carry no penalty, got {furnished['late_furnishing_penalty_cents']}"
    )


def test_generating_preparer_may_not_furnish_the_statement_they_generated(api):
    """PRD §2.7: "The user who generated or last regenerated a statement may not
    be the user who furnishes it: on furnishing, `X-User-ID` must differ from that
    form's `generated_by_user_id`."
    PRD §2.7: "All three violations answer `ERR_SEGREGATION_OF_DUTIES` with HTTP
    403, and because they sit at rung 23 they are reported ahead of the furnishing
    window, the notice response window and every constraint below them."

    Design: Corner/RBAC/benefits_admin_shares_furnish_with_preparer
    """
    ctx = _statement_ready_to_furnish(api)
    assert ctx["form"]["generated_by_user_id"] == PREPARER_1["X-User-ID"], (
        "the statement must be generated by the first preparer for this scenario"
    )

    refused = api.furnish_form_1095c(
        ctx["form"]["id"], f.furnish_payload("PAPER"), PREPARER_1
    )
    validate_error(refused, ApiErrorId.ERR_SEGREGATION_OF_DUTIES, 403)

    after = fixtures.read_form(api, ctx["form"]["id"])
    assert after["furnishing_status"] == "NOT_FURNISHED", (
        f"the refused delivery must leave the statement undelivered, got "
        f"{after['furnishing_status']!r}"
    )


