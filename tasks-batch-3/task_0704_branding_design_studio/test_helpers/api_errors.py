    ERR_NO_APPROVED_CONCEPT = "ERR_NO_APPROVED_CONCEPT"
    ERR_DELIVERABLES_INCOMPLETE = "ERR_DELIVERABLES_INCOMPLETE"
    ERR_DEPOSIT_UNPAID = "ERR_DEPOSIT_UNPAID"
    ERR_OPEN_INVOICES = "ERR_OPEN_INVOICES"
    ERR_REVISION_LIMIT_REACHED = "ERR_REVISION_LIMIT_REACHED"
    ERR_INTERVAL_OVERLAP = "ERR_INTERVAL_OVERLAP"
    ERR_ZERO_AMOUNT_MILESTONE = "ERR_ZERO_AMOUNT_MILESTONE"
