"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INSTALLER_NOT_LICENSED = "ERR_INSTALLER_NOT_LICENSED"
    ERR_DESIGN_INFEASIBLE = "ERR_DESIGN_INFEASIBLE"
    ERR_FINANCING_FIELDS_MISSING = "ERR_FINANCING_FIELDS_MISSING"
    ERR_FINANCING_ALREADY_ACTIVE = "ERR_FINANCING_ALREADY_ACTIVE"
    ERR_PERIOD_OVERLAP = "ERR_PERIOD_OVERLAP"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_CLAIM_WINDOW_OVERLAP = "ERR_CLAIM_WINDOW_OVERLAP"
    ERR_OUT_OF_ORDER_SETTLEMENT = "ERR_OUT_OF_ORDER_SETTLEMENT"
    ERR_INSUFFICIENT_FEEDER_HEADROOM = "ERR_INSUFFICIENT_FEEDER_HEADROOM"
    ERR_NO_LISTED_SRECS = "ERR_NO_LISTED_SRECS"
    ERR_BROKER_MARKET_MISMATCH = "ERR_BROKER_MARKET_MISMATCH"
    ERR_NO_SHORTFALL = "ERR_NO_SHORTFALL"
    ERR_STALE_PROJECT_VERSION = "ERR_STALE_PROJECT_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INSTALLER_NOT_LICENSED: 422,
    ApiErrorId.ERR_DESIGN_INFEASIBLE: 422,
    ApiErrorId.ERR_FINANCING_FIELDS_MISSING: 422,
    ApiErrorId.ERR_FINANCING_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_CLAIM_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_OUT_OF_ORDER_SETTLEMENT: 409,
    ApiErrorId.ERR_INSUFFICIENT_FEEDER_HEADROOM: 422,
    ApiErrorId.ERR_NO_LISTED_SRECS: 422,
    ApiErrorId.ERR_BROKER_MARKET_MISMATCH: 422,
    ApiErrorId.ERR_NO_SHORTFALL: 422,
    ApiErrorId.ERR_STALE_PROJECT_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
