    INVALID_TRANSITION = "ERR_INVALID_TRANSITION"
    ASSET_NOT_COLLECTABLE = "ERR_ASSET_NOT_COLLECTABLE"
    PROGRAM_POSTURE_BLOCKED = "ERR_PROGRAM_POSTURE_BLOCKED"

    # --- business: compliance ---
    POLICY_NOT_PUBLISHED = "ERR_POLICY_NOT_PUBLISHED"
    NOTICE_NOT_PUBLISHED = "ERR_NOTICE_NOT_PUBLISHED"
    TRANSLATION_LOCALE_MISSING = "ERR_TRANSLATION_LOCALE_MISSING"
    WRITTEN_RELEASE_REQUIRED = "ERR_WRITTEN_RELEASE_REQUIRED"
    VENDOR_RISK_TOO_HIGH = "ERR_VENDOR_RISK_TOO_HIGH"

    # --- business: temporal ---
    NOTICE_LEAD_NOT_MET = "ERR_NOTICE_LEAD_NOT_MET"
    NOTICE_WINDOW_OVERLAP = "ERR_NOTICE_WINDOW_OVERLAP"
    ACCOMMODATION_WINDOW_CONFLICT = "ERR_ACCOMMODATION_WINDOW_CONFLICT"
    DELETION_DEADLINE_MISSED = "ERR_DELETION_DEADLINE_MISSED"

    # --- business: limits ---
    RETENTION_EXCEEDS_JURISDICTION_MAX = "ERR_RETENTION_EXCEEDS_JURISDICTION_MAX"
    CONTRACT_SCORE_BELOW_FLOOR = "ERR_CONTRACT_SCORE_BELOW_FLOOR"
    ACCOMMODATION_METHOD_NOT_PERMITTED = "ERR_ACCOMMODATION_METHOD_NOT_PERMITTED"
    NOTIFIED_COUNT_SHORTFALL = "ERR_NOTIFIED_COUNT_SHORTFALL"
    VENDOR_CONTRACT_NONCOMPLIANT = "ERR_VENDOR_CONTRACT_NONCOMPLIANT"
    CONSENT_GAP_OPEN = "ERR_CONSENT_GAP_OPEN"

    # --- business: referential coherence ---
    JURISDICTION_MISMATCH = "ERR_JURISDICTION_MISMATCH"
    SUBJECT_CLASS_MISMATCH = "ERR_SUBJECT_CLASS_MISMATCH"

    # --- business: uniqueness ---
    CONSENT_ALREADY_EXISTS = "ERR_CONSENT_ALREADY_EXISTS"
    DUPLICATE_EXECUTED_CONTRACT = "ERR_DUPLICATE_EXECUTED_CONTRACT"
    ASSESSMENT_ALREADY_FINAL = "ERR_ASSESSMENT_ALREADY_FINAL"

    # --- business: dependency ---
    ASSET_STILL_ACTIVE = "ERR_ASSET_STILL_ACTIVE"
    NOTIFICATION_OUTSTANDING = "ERR_NOTIFICATION_OUTSTANDING"
    EXEMPTION_NOT_AVAILABLE = "ERR_EXEMPTION_NOT_AVAILABLE"

    # --- business: fiscal ---
    EXPOSURE_CAP_EXCEEDED = "ERR_EXPOSURE_CAP_EXCEEDED"


