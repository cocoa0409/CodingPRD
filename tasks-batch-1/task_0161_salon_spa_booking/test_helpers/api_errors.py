"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_RESOURCE_TYPE_MISMATCH = "ERR_RESOURCE_TYPE_MISMATCH"
    ERR_CLIENT_NOT_BOOKABLE = "ERR_CLIENT_NOT_BOOKABLE"
    ERR_BOOKING_IN_PAST = "ERR_BOOKING_IN_PAST"
    ERR_RESOURCE_INACTIVE = "ERR_RESOURCE_INACTIVE"
    ERR_STYLIST_DOUBLE_BOOKED = "ERR_STYLIST_DOUBLE_BOOKED"
    ERR_RESOURCE_DOUBLE_BOOKED = "ERR_RESOURCE_DOUBLE_BOOKED"
    ERR_PACKAGE_EXHAUSTED = "ERR_PACKAGE_EXHAUSTED"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_ALREADY_CHECKED_OUT = "ERR_ALREADY_CHECKED_OUT"
    ERR_STALE_STYLIST_VERSION = "ERR_STALE_STYLIST_VERSION"
    ERR_STALE_SALON_VERSION = "ERR_STALE_SALON_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DISPUTE_TARGET_INVALID = "ERR_DISPUTE_TARGET_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_RESOURCE_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_CLIENT_NOT_BOOKABLE: 422,
    ApiErrorId.ERR_BOOKING_IN_PAST: 422,
    ApiErrorId.ERR_RESOURCE_INACTIVE: 422,
    ApiErrorId.ERR_STYLIST_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_RESOURCE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_PACKAGE_EXHAUSTED: 422,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 422,
    ApiErrorId.ERR_ALREADY_CHECKED_OUT: 409,
    ApiErrorId.ERR_STALE_STYLIST_VERSION: 412,
    ApiErrorId.ERR_STALE_SALON_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DISPUTE_TARGET_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
