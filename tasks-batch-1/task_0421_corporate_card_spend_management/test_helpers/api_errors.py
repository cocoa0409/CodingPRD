"""Error IDs and their HTTP status mapping (PRD §5 Error Code Catalogue).

Registering the map with the framework lets validate_error() auto-check the
HTTP status that pairs with each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_USER_CONTEXT = "ERR_MISSING_USER_CONTEXT"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_SELF_APPROVAL = "ERR_SELF_APPROVAL"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_DUPLICATE_GL_CODE = "ERR_DUPLICATE_GL_CODE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_COMPANY_SUSPENDED = "ERR_COMPANY_SUSPENDED"
    ERR_MCC_BLOCKED = "ERR_MCC_BLOCKED"
    ERR_CARD_NOT_ACTIVE = "ERR_CARD_NOT_ACTIVE"
    ERR_PER_TXN_LIMIT_EXCEEDED = "ERR_PER_TXN_LIMIT_EXCEEDED"
    ERR_CARD_LIMIT_EXCEEDED = "ERR_CARD_LIMIT_EXCEEDED"
    ERR_INSUFFICIENT_CREDIT = "ERR_INSUFFICIENT_CREDIT"
    ERR_CARD_HAS_OPEN_AUTH = "ERR_CARD_HAS_OPEN_AUTH"
    ERR_GL_CODE_REQUIRED = "ERR_GL_CODE_REQUIRED"
    ERR_APPROVAL_REQUIRED = "ERR_APPROVAL_REQUIRED"
    ERR_APPROVAL_NOT_NEEDED = "ERR_APPROVAL_NOT_NEEDED"
    ERR_RECEIPT_REQUIRED = "ERR_RECEIPT_REQUIRED"
    ERR_CLOCK_NOT_SET = "ERR_CLOCK_NOT_SET"
    ERR_INSUFFICIENT_REWARD_BALANCE = "ERR_INSUFFICIENT_REWARD_BALANCE"
    ERR_AUTH_WINDOW_OVERLAP = "ERR_AUTH_WINDOW_OVERLAP"
    ERR_AUTH_WINDOW_TOO_CLOSE = "ERR_AUTH_WINDOW_TOO_CLOSE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_MISSING_USER_CONTEXT: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_SELF_APPROVAL: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_DUPLICATE_GL_CODE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_COMPANY_SUSPENDED: 409,
    ApiErrorId.ERR_MCC_BLOCKED: 409,
    ApiErrorId.ERR_CARD_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PER_TXN_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_CARD_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_CREDIT: 402,
    ApiErrorId.ERR_CARD_HAS_OPEN_AUTH: 409,
    ApiErrorId.ERR_GL_CODE_REQUIRED: 409,
    ApiErrorId.ERR_APPROVAL_REQUIRED: 409,
    ApiErrorId.ERR_APPROVAL_NOT_NEEDED: 409,
    ApiErrorId.ERR_RECEIPT_REQUIRED: 409,
    ApiErrorId.ERR_CLOCK_NOT_SET: 409,
    ApiErrorId.ERR_INSUFFICIENT_REWARD_BALANCE: 409,
    ApiErrorId.ERR_AUTH_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_AUTH_WINDOW_TOO_CLOSE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
