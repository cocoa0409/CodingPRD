def setup_exhausted_campaign_loop(*, total_budget_cents=500, cpm_cents=500):
    """Validated 600s loop (570s entry + 30s break) + campaign whose single
    DIRECT decision (committed cost == cpm * 1000 * 1 / 1000 == cpm_cents) is
    run PROVISIONAL. Caller then locks / publishes / voids as needed.
    Budget defaults make the lock flip the campaign to EXHAUSTED at equality."""
    ctx = setup_validated_loop(
        channel_name="Ch Ex", loop_duration=600, break_durations=(30,),
        content_runtime=570,
    )
    campaign, creative = create_active_campaign(
        cpm_cents=cpm_cents, total_budget_cents=total_budget_cents,
        daily_budget_cents=total_budget_cents,
    )
    decisions = run_decision_run(ctx["breaks"][0]["id"])
    ctx.update({"campaign": campaign, "creative": creative, "decisions": decisions})
    return ctx


def setup_two_day_score_scenario():
    """Two PUBLISHED loops (2026-09-01 and 2026-09-02), each tiled 540s entry +
    60s break with one DIRECT 30s decision, both AIRED and RECONCILED with zero
    impressions. Feeds the channel-performance-score threshold tests (PRD §3.7)."""
    base = setup_channel_with_grant(channel_name="Ch Score", loop_duration=600,
                                    content_runtime=540, max_plays=10)
    channel = base["channel"]
    content = base["content"]
    campaign, creative = create_active_campaign(
        cpm_cents=500, total_budget_cents=5000, daily_budget_cents=5000,
    )
    platform = setup_platform(active=False)
    out = {**base, "campaign": campaign, "creative": creative, "platform": platform,
           "loops": {}, "breaks": {}}
    for date in (C.BROADCAST_DATE, C.BROADCAST_DATE_2):
        loop = create_loop(channel["id"], date)
        entries, breaks = tile_loop(loop["id"], content["id"], (60,))
        loop = get_success_data(api_client.loop_validate(loop["id"], PROGRAMMER))
        decisions = run_decision_run(breaks[0]["id"])
        loop = get_success_data(api_client.loop_lock(loop["id"], PROGRAMMER))
        if channel["channel_status"] != "LIVE":
            channel = go_live(channel["id"])
        loop = publish_loop(loop["id"], channel["id"])
        channel = get_channel(channel["id"])
        get_success_data(api_client.break_mark_aired(breaks[0]["id"], PROGRAMMER))
        get_success_data(api_client.break_reconcile(breaks[0]["id"], ADOPS))
        out["loops"][date] = loop
        out["breaks"][date] = (breaks[0], decisions)
    out["channel"] = channel
    return out
