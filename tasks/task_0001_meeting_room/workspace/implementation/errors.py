ERR_CAPACITY_EXCEEDED = ("ERR_CAPACITY_EXCEEDED", 400)
ERR_ROOM_HAS_ACTIVE_BOOKINGS = ("ERR_ROOM_HAS_ACTIVE_BOOKINGS", 409)
ERR_DUPLICATE_WAITLIST = ("ERR_DUPLICATE_WAITLIST", 409)

# Series
ERR_INVALID_SERIES_RANGE = ("ERR_INVALID_SERIES_RANGE", 400)
ERR_EMPTY_SERIES = ("ERR_EMPTY_SERIES", 400)
ERR_ROOM_NAME_TAKEN = ("ERR_ROOM_NAME_TAKEN", 409)


def raise_error(error_tuple, message=None):
    error_id, http_status = error_tuple
    if message is None:
        message = error_id
    raise ApiError(error_id, message, http_status)
