"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth & RBAC (PRD §2.1)
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    # Existence & payload shape (PRD §2.5)
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    # State machine guards (PRD §2.5, §3.8)
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Optimistic concurrency (PRD §2.9)
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # Clock & temporal gates (PRD §2.5, §2.6)
    ERR_OUTSIDE_WINDOW = "ERR_OUTSIDE_WINDOW"
    ERR_ELIGIBILITY_WINDOW = "ERR_ELIGIBILITY_WINDOW"
    ERR_CEREMONY_OVERLAP = "ERR_CEREMONY_OVERLAP"
    ERR_ROUND_WINDOW_TOO_CLOSE = "ERR_ROUND_WINDOW_TOO_CLOSE"
    # Business safety & duty segregation (PRD §3.5, §3.8)
    ERR_CONFLICT_OF_INTEREST = "ERR_CONFLICT_OF_INTEREST"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    # Structural & fiscal constraints (PRD §2.5, §3.1-§3.3)
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_CONSTRAINT_VIOLATION = "ERR_CONSTRAINT_VIOLATION"
    ERR_FISCAL_BLOCK = "ERR_FISCAL_BLOCK"
    # Panel / ballot / aggregate integrity (PRD §3.6, §3.7, §3.8)
    ERR_PANEL_INCOMPLETE = "ERR_PANEL_INCOMPLETE"
    ERR_INCOMPLETE_BALLOT = "ERR_INCOMPLETE_BALLOT"
    ERR_REFERENTIAL_INTEGRITY = "ERR_REFERENTIAL_INTEGRITY"
    ERR_APPEAL_CAP_EXCEEDED = "ERR_APPEAL_CAP_EXCEEDED"
    # Embargo & audit chain (PRD §2.10, §2.11)
    ERR_EMBARGO_ACTIVE = "ERR_EMBARGO_ACTIVE"
    ERR_HASH_CHAIN_BROKEN = "ERR_HASH_CHAIN_BROKEN"


