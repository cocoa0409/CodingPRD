"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_MISSING_HEADERS = "ERR_AUTH_MISSING_HEADERS"
    ERR_AUTH_UNKNOWN_ROLE = "ERR_AUTH_UNKNOWN_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Existence — PRD §2.4
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_RESOURCE_NOT_FOUND = "ERR_REFERENCED_RESOURCE_NOT_FOUND"

    # Body shape / pagination
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"

    # State / OCC
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Business
    ERR_RFE_ALREADY_OUTSTANDING = "ERR_RFE_ALREADY_OUTSTANDING"
    ERR_BIOMETRICS_ALREADY_SCHEDULED = "ERR_BIOMETRICS_ALREADY_SCHEDULED"
    ERR_BIOMETRICS_TOO_SOON = "ERR_BIOMETRICS_TOO_SOON"
    ERR_INTERVIEW_TOO_SOON = "ERR_INTERVIEW_TOO_SOON"
    ERR_INTERVIEW_NOT_APPLICABLE = "ERR_INTERVIEW_NOT_APPLICABLE"
    ERR_BIOMETRICS_RESCHEDULE_LIMIT = "ERR_BIOMETRICS_RESCHEDULE_LIMIT"
    ERR_BIOMETRICS_RESCHEDULE_TOO_LATE = "ERR_BIOMETRICS_RESCHEDULE_TOO_LATE"
    ERR_RFE_DEADLINE_PASSED = "ERR_RFE_DEADLINE_PASSED"
    ERR_I485_MISSING_APPROVED_I130 = "ERR_I485_MISSING_APPROVED_I130"
    ERR_PRIORITY_DATE_NOT_CURRENT = "ERR_PRIORITY_DATE_NOT_CURRENT"
    ERR_RECEIPT_NUMBER_COLLISION = "ERR_RECEIPT_NUMBER_COLLISION"


# PRD §5 — Error Code Catalogue (HTTP status mapping).
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING_HEADERS: 401,
    ApiErrorId.ERR_AUTH_UNKNOWN_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_RESOURCE_NOT_FOUND: 422,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_RFE_ALREADY_OUTSTANDING: 409,
    ApiErrorId.ERR_BIOMETRICS_ALREADY_SCHEDULED: 409,
    ApiErrorId.ERR_BIOMETRICS_TOO_SOON: 422,
    ApiErrorId.ERR_INTERVIEW_TOO_SOON: 422,
    ApiErrorId.ERR_INTERVIEW_NOT_APPLICABLE: 422,
    ApiErrorId.ERR_BIOMETRICS_RESCHEDULE_LIMIT: 409,
    ApiErrorId.ERR_BIOMETRICS_RESCHEDULE_TOO_LATE: 422,
    ApiErrorId.ERR_RFE_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_I485_MISSING_APPROVED_I130: 422,
    ApiErrorId.ERR_PRIORITY_DATE_NOT_CURRENT: 409,
    ApiErrorId.ERR_RECEIPT_NUMBER_COLLISION: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
