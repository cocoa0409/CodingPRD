"""Error types and error-id constants for the perioperative API.

Every error id below is taken verbatim from PRD section 5 (Error Code
Catalogue) / SCAFFOLD.yaml section 1.6.
"""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


