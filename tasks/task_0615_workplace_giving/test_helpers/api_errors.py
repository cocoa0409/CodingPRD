    ERR_SCHEDULE_OVERLAP = "ERR_SCHEDULE_OVERLAP"
    ERR_DEDUCTION_LIMIT_EXCEEDED = "ERR_DEDUCTION_LIMIT_EXCEEDED"
    # Donation / disbursement
    ERR_DONATION_DISBURSED = "ERR_DONATION_DISBURSED"
    ERR_LOG_DISBURSED = "ERR_LOG_DISBURSED"
    ERR_EMPTY_BATCH = "ERR_EMPTY_BATCH"
    ERR_BATCH_PERIOD_OVERLAP = "ERR_BATCH_PERIOD_OVERLAP"
    ERR_SOURCE_NOT_DISBURSABLE = "ERR_SOURCE_NOT_DISBURSABLE"
    ERR_SOURCE_ALREADY_GRANTED = "ERR_SOURCE_ALREADY_GRANTED"
    ERR_GRANT_CHARITY_MISMATCH = "ERR_GRANT_CHARITY_MISMATCH"


