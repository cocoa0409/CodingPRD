def raise_err(spec, message):
    error_id, http_status = spec
    raise ApiError(error_id, message, http_status)


def err_validation(msg):
    raise_err(ERR_VALIDATION, msg)


def err_not_found(msg):
    raise_err(ERR_NOT_FOUND, msg)


def err_invalid_state(msg):
    raise_err(ERR_INVALID_STATE, msg)


def err_unauthorized(msg):
    raise_err(ERR_UNAUTHORIZED_ROLE, msg)


def err_unauthenticated(msg):
    raise_err(ERR_UNAUTHENTICATED, msg)
