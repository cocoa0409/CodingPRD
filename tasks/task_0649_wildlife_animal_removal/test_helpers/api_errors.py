"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PERMIT_REQUIRED = "ERR_PERMIT_REQUIRED"
    ERR_TECH_NOT_CERTIFIED = "ERR_TECH_NOT_CERTIFIED"
    ERR_RELOCATION_DISTANCE = "ERR_RELOCATION_DISTANCE"
    ERR_ENTRY_POINT_MISMATCH = "ERR_ENTRY_POINT_MISMATCH"
    ERR_TECH_WINDOW_CONFLICT = "ERR_TECH_WINDOW_CONFLICT"
    ERR_VISIT_OVERLAP = "ERR_VISIT_OVERLAP"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_EMPTY_SET = "ERR_EMPTY_SET"
    ERR_KIT_EXHAUSTED = "ERR_KIT_EXHAUSTED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PERMIT_REQUIRED: 409,
    ApiErrorId.ERR_TECH_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_RELOCATION_DISTANCE: 422,
    ApiErrorId.ERR_ENTRY_POINT_MISMATCH: 409,
    ApiErrorId.ERR_TECH_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_VISIT_OVERLAP: 409,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_EMPTY_SET: 409,
    ApiErrorId.ERR_KIT_EXHAUSTED: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
