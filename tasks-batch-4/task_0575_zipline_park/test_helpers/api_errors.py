"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SLOT_NOT_OPEN = "ERR_SLOT_NOT_OPEN"
    ERR_SLOT_FULL = "ERR_SLOT_FULL"
    ERR_WEIGHT_OUT_OF_RANGE = "ERR_WEIGHT_OUT_OF_RANGE"
    ERR_AGE_BELOW_MINIMUM = "ERR_AGE_BELOW_MINIMUM"
    ERR_WAIVER_REQUIRED = "ERR_WAIVER_REQUIRED"
    ERR_GUIDE_UNCERTIFIED = "ERR_GUIDE_UNCERTIFIED"
    ERR_GUIDE_DOUBLE_BOOKED = "ERR_GUIDE_DOUBLE_BOOKED"
    ERR_GEAR_UNAVAILABLE = "ERR_GEAR_UNAVAILABLE"
    ERR_NO_GUIDE_ASSIGNED = "ERR_NO_GUIDE_ASSIGNED"
    ERR_UNDERSTAFFED = "ERR_UNDERSTAFFED"
    ERR_GROUP_SLOT_MISMATCH = "ERR_GROUP_SLOT_MISMATCH"
    ERR_SEASON_PASS_INVALID = "ERR_SEASON_PASS_INVALID"
    ERR_SEASON_PASS_EXHAUSTED = "ERR_SEASON_PASS_EXHAUSTED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SLOT_NOT_OPEN: 409,
    ApiErrorId.ERR_SLOT_FULL: 409,
    ApiErrorId.ERR_WEIGHT_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_AGE_BELOW_MINIMUM: 422,
    ApiErrorId.ERR_WAIVER_REQUIRED: 422,
    ApiErrorId.ERR_GUIDE_UNCERTIFIED: 422,
    ApiErrorId.ERR_GUIDE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_GEAR_UNAVAILABLE: 409,
    ApiErrorId.ERR_NO_GUIDE_ASSIGNED: 409,
    ApiErrorId.ERR_UNDERSTAFFED: 409,
    ApiErrorId.ERR_GROUP_SLOT_MISMATCH: 422,
    ApiErrorId.ERR_SEASON_PASS_INVALID: 422,
    ApiErrorId.ERR_SEASON_PASS_EXHAUSTED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
