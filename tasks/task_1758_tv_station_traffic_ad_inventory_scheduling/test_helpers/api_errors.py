"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DATE_WINDOW = "ERR_DATE_WINDOW"
    ERR_REFERENCE_MISMATCH = "ERR_REFERENCE_MISMATCH"
    ERR_POLITICAL_RESERVE = "ERR_POLITICAL_RESERVE"
    ERR_AVAIL_OVERFLOW = "ERR_AVAIL_OVERFLOW"
    ERR_SEPARATION_VIOLATION = "ERR_SEPARATION_VIOLATION"
    ERR_COPY_NOT_RECEIVED = "ERR_COPY_NOT_RECEIVED"
    ERR_RECONCILE_MISMATCH = "ERR_RECONCILE_MISMATCH"
    ERR_CREDIT_LIMIT = "ERR_CREDIT_LIMIT"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_STALE_AVAIL_VERSION = "ERR_STALE_AVAIL_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DATE_WINDOW: 422,
    ApiErrorId.ERR_REFERENCE_MISMATCH: 422,
    ApiErrorId.ERR_POLITICAL_RESERVE: 422,
    ApiErrorId.ERR_AVAIL_OVERFLOW: 422,
    ApiErrorId.ERR_SEPARATION_VIOLATION: 422,
    ApiErrorId.ERR_COPY_NOT_RECEIVED: 422,
    ApiErrorId.ERR_RECONCILE_MISMATCH: 422,
    ApiErrorId.ERR_CREDIT_LIMIT: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_STALE_AVAIL_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status codes.
set_error_http_status_map(HTTP_STATUS_CODES)
