    # --- eligibility / idempotence (rungs 56, 57) ---
    LINE_NOT_ELIGIBLE = "ERR_LINE_NOT_ELIGIBLE"
    EVIDENCE_ALREADY_RETRACTED = "ERR_EVIDENCE_ALREADY_RETRACTED"

    # --- posture (rungs 58, 59) ---
    PROGRAM_POSTURE_FROZEN = "ERR_PROGRAM_POSTURE_FROZEN"
    PROGRAM_POSTURE_RESTRICTED = "ERR_PROGRAM_POSTURE_RESTRICTED"

    # --- referential business gates (rungs 52, 60) ---
    CONSENT_NOT_RESOLVED = "ERR_CONSENT_NOT_RESOLVED"
    INVENTORY_NOT_PUBLISHED = "ERR_INVENTORY_NOT_PUBLISHED"
    UNVALIDATED_SAMPLING_STRATUM = "ERR_UNVALIDATED_SAMPLING_STRATUM"
    CREW_INACTIVE = "ERR_CREW_INACTIVE"
    PINNED_SNAPSHOT_STALE = "ERR_PINNED_SNAPSHOT_STALE"
    NOTIFICATION_OVERDUE_BLOCK = "ERR_NOTIFICATION_OVERDUE_BLOCK"
    COMPLIANCE_DEADLINE_PASSED = "ERR_COMPLIANCE_DEADLINE_PASSED"

    # --- safety gate (rung 65) ---
    CCT_NOT_OPTIMIZED = "ERR_CCT_NOT_OPTIMIZED"

    # --- uniqueness / membership / shape (rung 70) ---
    DUPLICATE_PWSID = "ERR_DUPLICATE_PWSID"
    DUPLICATE_ADDRESS_LABEL = "ERR_DUPLICATE_ADDRESS_LABEL"
    DUPLICATE_STRATUM_CODE = "ERR_DUPLICATE_STRATUM_CODE"
    CREW_METHOD_NOT_CERTIFIED = "ERR_CREW_METHOD_NOT_CERTIFIED"
    CREW_OUTSIDE_SHIFT = "ERR_CREW_OUTSIDE_SHIFT"
    EVIDENCE_SIDE_MISMATCH = "ERR_EVIDENCE_SIDE_MISMATCH"
    REPLACED_SIDES_MISMATCH = "ERR_REPLACED_SIDES_MISMATCH"
    SAMPLE_COUNT_INSUFFICIENT = "ERR_SAMPLE_COUNT_INSUFFICIENT"

    # --- temporal conflicts (rung 75) ---
    CREW_WINDOW_CONFLICT = "ERR_CREW_WINDOW_CONFLICT"
    MORATORIUM_CONFLICT = "ERR_MORATORIUM_CONFLICT"
    PERIOD_OVERLAP = "ERR_PERIOD_OVERLAP"
    CLOCK_NOT_MONOTONIC = "ERR_CLOCK_NOT_MONOTONIC"

    # --- capacity conflicts (rung 78) ---
    CREW_DAILY_CAPACITY_EXCEEDED = "ERR_CREW_DAILY_CAPACITY_EXCEEDED"
    EXCAVATION_CAPACITY_EXCEEDED = "ERR_EXCAVATION_CAPACITY_EXCEEDED"

    # --- equity and fiscal (rungs 85, 90) ---
    EQUITY_REQUIREMENT_BREACH = "ERR_EQUITY_REQUIREMENT_BREACH"
    FUNDING_INSUFFICIENT = "ERR_FUNDING_INSUFFICIENT"

    def __str__(self) -> str:  # pragma: no cover - convenience only
        return self.value


