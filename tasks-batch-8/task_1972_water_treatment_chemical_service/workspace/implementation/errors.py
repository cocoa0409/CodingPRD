def missing_context():
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, 400,
                    "X-User-ID and X-User-Role headers must both be present and non-empty")


def unauthorized_role():
    return ApiError(ERR_UNAUTHORIZED_ROLE, 403,
                    "Role is not permitted to call this endpoint")


def forbidden(msg="Caller does not own the target resource"):
    return ApiError(ERR_FORBIDDEN, 403, msg)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def invalid_request(msg):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def invalid_state(msg="Target resource is not in a state that permits this transition"):
    return ApiError(ERR_INVALID_STATE, 409, msg)


def stale_version(msg="Expected version does not match the resource's current version"):
    return ApiError(ERR_STALE_VERSION, 412, msg)


def field_constraint(msg):
    return ApiError(ERR_FIELD_CONSTRAINT, 422, msg)
