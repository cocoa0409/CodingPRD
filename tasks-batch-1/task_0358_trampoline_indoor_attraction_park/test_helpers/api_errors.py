"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_GUARDIAN_REQUIRED = "ERR_GUARDIAN_REQUIRED"
    ERR_INVALID_SIGNER = "ERR_INVALID_SIGNER"
    ERR_WAIVER_MISSING_OR_EXPIRED = "ERR_WAIVER_MISSING_OR_EXPIRED"
    ERR_OUTSIDE_CHECKIN_WINDOW = "ERR_OUTSIDE_CHECKIN_WINDOW"
    ERR_ROOM_CONFLICT = "ERR_ROOM_CONFLICT"
    ERR_INVALID_SLOT_WINDOW = "ERR_INVALID_SLOT_WINDOW"
    ERR_GUEST_COUNT_OUT_OF_RANGE = "ERR_GUEST_COUNT_OUT_OF_RANGE"
    ERR_INVALID_QUANTITY = "ERR_INVALID_QUANTITY"
    ERR_STALE_SLOT_VERSION = "ERR_STALE_SLOT_VERSION"
    ERR_SLOT_CAPACITY_EXCEEDED = "ERR_SLOT_CAPACITY_EXCEEDED"
    ERR_ALREADY_PAID = "ERR_ALREADY_PAID"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_RENEWAL_NOT_DUE = "ERR_RENEWAL_NOT_DUE"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_GUARDIAN_REQUIRED: 422,
    ApiErrorId.ERR_INVALID_SIGNER: 422,
    ApiErrorId.ERR_WAIVER_MISSING_OR_EXPIRED: 422,
    ApiErrorId.ERR_OUTSIDE_CHECKIN_WINDOW: 422,
    ApiErrorId.ERR_ROOM_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_SLOT_WINDOW: 422,
    ApiErrorId.ERR_GUEST_COUNT_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_INVALID_QUANTITY: 422,
    ApiErrorId.ERR_STALE_SLOT_VERSION: 412,
    ApiErrorId.ERR_SLOT_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_ALREADY_PAID: 409,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_RENEWAL_NOT_DUE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
