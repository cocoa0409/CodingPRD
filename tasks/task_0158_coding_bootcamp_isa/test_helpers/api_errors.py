"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_COHORT_TIMING = "ERR_COHORT_TIMING"
    ERR_COHORT_FULL = "ERR_COHORT_FULL"
    ERR_COOLING_OFF_EXPIRED = "ERR_COOLING_OFF_EXPIRED"
    ERR_DEPOSIT_ALREADY_RESOLVED = "ERR_DEPOSIT_ALREADY_RESOLVED"
    ERR_DISMISSAL_NOT_JUSTIFIED = "ERR_DISMISSAL_NOT_JUSTIFIED"
    ERR_PROGRESS_INCOMPLETE = "ERR_PROGRESS_INCOMPLETE"
    ERR_DEFERMENT_INELIGIBLE = "ERR_DEFERMENT_INELIGIBLE"
    ERR_DEFERMENT_OVERLAP = "ERR_DEFERMENT_OVERLAP"
    ERR_INCOME_PERIOD_OVERLAP = "ERR_INCOME_PERIOD_OVERLAP"
    ERR_SALARY_REQUIRED = "ERR_SALARY_REQUIRED"
    ERR_OUTCOME_NOT_GRADUATE = "ERR_OUTCOME_NOT_GRADUATE"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_COHORT_TIMING: 409,
    ApiErrorId.ERR_COHORT_FULL: 409,
    ApiErrorId.ERR_COOLING_OFF_EXPIRED: 409,
    ApiErrorId.ERR_DEPOSIT_ALREADY_RESOLVED: 409,
    ApiErrorId.ERR_DISMISSAL_NOT_JUSTIFIED: 409,
    ApiErrorId.ERR_PROGRESS_INCOMPLETE: 409,
    ApiErrorId.ERR_DEFERMENT_INELIGIBLE: 409,
    ApiErrorId.ERR_DEFERMENT_OVERLAP: 409,
    ApiErrorId.ERR_INCOME_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_SALARY_REQUIRED: 400,
    ApiErrorId.ERR_OUTCOME_NOT_GRADUATE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
