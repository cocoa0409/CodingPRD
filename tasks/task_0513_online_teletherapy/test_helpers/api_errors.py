"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_NOT_FOUND = "ERR_REFERENCED_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CLIENT_RISK_BLOCKED = "ERR_CLIENT_RISK_BLOCKED"
    ERR_INTAKE_NOT_CLEARED = "ERR_INTAKE_NOT_CLEARED"
    ERR_LICENSE_STATE_MISMATCH = "ERR_LICENSE_STATE_MISMATCH"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SESSION_OVERLAP = "ERR_SESSION_OVERLAP"
    ERR_THERAPIST_DOUBLE_BOOKED = "ERR_THERAPIST_DOUBLE_BOOKED"
    ERR_NO_CREDIT = "ERR_NO_CREDIT"
    ERR_THREAD_NOT_OPEN = "ERR_THREAD_NOT_OPEN"
    ERR_DUPLICATE_SUBSCRIPTION = "ERR_DUPLICATE_SUBSCRIPTION"
    ERR_CYCLE_NOT_DUE = "ERR_CYCLE_NOT_DUE"
    ERR_NO_ELIGIBLE_THERAPIST = "ERR_NO_ELIGIBLE_THERAPIST"
    ERR_CANCEL_NOT_DUE = "ERR_CANCEL_NOT_DUE"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CLIENT_RISK_BLOCKED: 409,
    ApiErrorId.ERR_INTAKE_NOT_CLEARED: 409,
    ApiErrorId.ERR_LICENSE_STATE_MISMATCH: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SESSION_OVERLAP: 409,
    ApiErrorId.ERR_THERAPIST_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_NO_CREDIT: 409,
    ApiErrorId.ERR_THREAD_NOT_OPEN: 409,
    ApiErrorId.ERR_DUPLICATE_SUBSCRIPTION: 409,
    ApiErrorId.ERR_CYCLE_NOT_DUE: 409,
    ApiErrorId.ERR_NO_ELIGIBLE_THERAPIST: 409,
    ApiErrorId.ERR_CANCEL_NOT_DUE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
