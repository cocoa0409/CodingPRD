"""Error catalog + APIError exception.

Every error_id and HTTP status is copied verbatim from PRD section 5 /
SCAFFOLD section 1.6.  The envelope writen by app.py uses `error_id` /
`message` inside `data`, per PRD 2.2.
"""


class APIError(Exception):
    def __init__(self, error_id, message="", http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)


