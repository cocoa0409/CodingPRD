"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_TEMPORAL_VIOLATION = "ERR_TEMPORAL_VIOLATION"
    ERR_RIGHTS_VIOLATION = "ERR_RIGHTS_VIOLATION"
    ERR_FORBIDDEN_CROSS_ACCOUNT = "ERR_FORBIDDEN_CROSS_ACCOUNT"
    ERR_AMBIGUOUS_TIER = "ERR_AMBIGUOUS_TIER"
    ERR_NO_MATCHING_TIER = "ERR_NO_MATCHING_TIER"
    ERR_NO_ENTITLEMENT = "ERR_NO_ENTITLEMENT"
    ERR_MIN_COMMITMENT_NOT_MET = "ERR_MIN_COMMITMENT_NOT_MET"
    ERR_FISCAL_INCONSISTENCY = "ERR_FISCAL_INCONSISTENCY"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TEMPORAL_VIOLATION: 422,
    ApiErrorId.ERR_RIGHTS_VIOLATION: 422,
    ApiErrorId.ERR_FORBIDDEN_CROSS_ACCOUNT: 403,
    ApiErrorId.ERR_AMBIGUOUS_TIER: 422,
    ApiErrorId.ERR_NO_MATCHING_TIER: 422,
    ApiErrorId.ERR_NO_ENTITLEMENT: 422,
    ApiErrorId.ERR_MIN_COMMITMENT_NOT_MET: 422,
    ApiErrorId.ERR_FISCAL_INCONSISTENCY: 422,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status codes.
set_error_http_status_map(HTTP_STATUS_CODES)
