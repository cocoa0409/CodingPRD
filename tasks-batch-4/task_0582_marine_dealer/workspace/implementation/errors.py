"""Error class and error-id constants (SCAFFOLD 1.6 / PRD Section 5)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super(ApiError, self).__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Universal gates
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)

# State / concurrency
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_UNIT_VERSION = ("ERR_STALE_UNIT_VERSION", 412)

# Deal / unit
ERR_UNIT_NOT_AVAILABLE = ("ERR_UNIT_NOT_AVAILABLE", 409)
ERR_UNIT_HAS_ACTIVE_DEAL = ("ERR_UNIT_HAS_ACTIVE_DEAL", 409)
ERR_DOWN_PAYMENT_TOO_LOW = ("ERR_DOWN_PAYMENT_TOO_LOW", 402)
ERR_OPEN_RECALL_BLOCKS_DELIVERY = ("ERR_OPEN_RECALL_BLOCKS_DELIVERY", 409)

# Service lines
ERR_PART_REQUIRED_FOR_LINE = ("ERR_PART_REQUIRED_FOR_LINE", 422)
ERR_HOURS_REQUIRED_FOR_LABOR = ("ERR_HOURS_REQUIRED_FOR_LABOR", 422)
ERR_INVALID_QUANTITY = ("ERR_INVALID_QUANTITY", 422)
ERR_INSUFFICIENT_STOCK = ("ERR_INSUFFICIENT_STOCK", 409)

# Storage / scheduling
ERR_RESERVATION_DATES_INVALID = ("ERR_RESERVATION_DATES_INVALID", 422)
ERR_SCHEDULE_WINDOW_INVALID = ("ERR_SCHEDULE_WINDOW_INVALID", 422)
ERR_BERTH_CLOSED = ("ERR_BERTH_CLOSED", 409)
ERR_UNIT_EXCEEDS_BERTH = ("ERR_UNIT_EXCEEDS_BERTH", 422)
ERR_BERTH_DOUBLE_BOOKED = ("ERR_BERTH_DOUBLE_BOOKED", 409)
ERR_BAY_SCHEDULE_CONFLICT = ("ERR_BAY_SCHEDULE_CONFLICT", 409)

# Floor plan
ERR_CURTAILMENT_NOT_DUE = ("ERR_CURTAILMENT_NOT_DUE", 409)
ERR_CURTAILMENT_EXCEEDS_PRINCIPAL = ("ERR_CURTAILMENT_EXCEEDS_PRINCIPAL", 422)


def err(pair, message=None):
    return ApiError(pair[0], pair[1], message)
