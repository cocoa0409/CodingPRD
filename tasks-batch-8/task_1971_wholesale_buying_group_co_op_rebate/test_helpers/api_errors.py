"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() automatically
cross-checks HTTP status codes.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth
    ERR_MISSING_OR_INVALID_USER_CONTEXT = "ERR_MISSING_OR_INVALID_USER_CONTEXT"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Fiscal / pool
    ERR_INSUFFICIENT_POOL = "ERR_INSUFFICIENT_POOL"
    ERR_QUARTER_MISMATCH = "ERR_QUARTER_MISMATCH"
    ERR_FUTURE_QUARTER = "ERR_FUTURE_QUARTER"
    ERR_SPLIT_MISMATCH = "ERR_SPLIT_MISMATCH"
    # Business constraint (program/supplier)
    ERR_INVALID_TIER_SCHEDULE = "ERR_INVALID_TIER_SCHEDULE"
    ERR_INVALID_EXCLUSIVITY = "ERR_INVALID_EXCLUSIVITY"
    ERR_DUPLICATE_PROGRAM_CODE = "ERR_DUPLICATE_PROGRAM_CODE"
    ERR_SUPPLIER_NOT_ONBOARDED = "ERR_SUPPLIER_NOT_ONBOARDED"
    ERR_SUPPLIER_HAS_ACTIVE_PROGRAMS = "ERR_SUPPLIER_HAS_ACTIVE_PROGRAMS"
    ERR_PROGRAM_NOT_OPEN = "ERR_PROGRAM_NOT_OPEN"
    ERR_PROGRAM_HAS_ENROLLMENTS = "ERR_PROGRAM_HAS_ENROLLMENTS"
    ERR_MEMBER_NOT_ACTIVE = "ERR_MEMBER_NOT_ACTIVE"
    ERR_OPEN_CLAWBACK = "ERR_OPEN_CLAWBACK"
    # Concurrency
    ERR_STALE_PROGRAM_VERSION = "ERR_STALE_PROGRAM_VERSION"
    ERR_STALE_DISTRIBUTION_VERSION = "ERR_STALE_DISTRIBUTION_VERSION"
    # Request shape
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT: 400,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INSUFFICIENT_POOL: 409,
    ApiErrorId.ERR_QUARTER_MISMATCH: 409,
    ApiErrorId.ERR_FUTURE_QUARTER: 409,
    ApiErrorId.ERR_SPLIT_MISMATCH: 500,
    ApiErrorId.ERR_INVALID_TIER_SCHEDULE: 422,
    ApiErrorId.ERR_INVALID_EXCLUSIVITY: 422,
    ApiErrorId.ERR_DUPLICATE_PROGRAM_CODE: 409,
    ApiErrorId.ERR_SUPPLIER_NOT_ONBOARDED: 409,
    ApiErrorId.ERR_SUPPLIER_HAS_ACTIVE_PROGRAMS: 409,
    ApiErrorId.ERR_PROGRAM_NOT_OPEN: 409,
    ApiErrorId.ERR_PROGRAM_HAS_ENROLLMENTS: 409,
    ApiErrorId.ERR_MEMBER_NOT_ACTIVE: 409,
    ApiErrorId.ERR_OPEN_CLAWBACK: 409,
    ApiErrorId.ERR_STALE_PROGRAM_VERSION: 412,
    ApiErrorId.ERR_STALE_DISTRIBUTION_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
