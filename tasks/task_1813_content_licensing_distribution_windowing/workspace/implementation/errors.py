"""API error type and the canonical error-id catalog."""


class ApiError(Exception):
    def __init__(self, error_id: str, message: str, http_status: int):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


def raise_error(error_id: str, message: str, http_status: int):
    raise ApiError(error_id, message, http_status)


