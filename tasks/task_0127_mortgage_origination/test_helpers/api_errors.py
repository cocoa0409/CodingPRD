"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_UDAAP_SOD_VIOLATION = "ERR_UDAAP_SOD_VIOLATION"

    # Existence — PRD §2.5
    ERR_APPLICATION_NOT_FOUND = "ERR_APPLICATION_NOT_FOUND"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"

    # State machine — PRD §3
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Business safety / temporal — PRD §3
    ERR_UDAAP_REVIEW_REQUIRED = "ERR_UDAAP_REVIEW_REQUIRED"
    ERR_TRID_WAITING_PERIOD = "ERR_TRID_WAITING_PERIOD"
    ERR_APPRAISAL_EXPIRED = "ERR_APPRAISAL_EXPIRED"
    ERR_RATE_LOCK_EXPIRED = "ERR_RATE_LOCK_EXPIRED"
    ERR_MISSING_DEPENDENCIES = "ERR_MISSING_DEPENDENCIES"

    # Business constraints — PRD §3.5, §3.6
    ERR_APR_TOLERANCE_EXCEEDED = "ERR_APR_TOLERANCE_EXCEEDED"
    ERR_EXTENSION_CAP_EXCEEDED = "ERR_EXTENSION_CAP_EXCEEDED"
    ERR_EXTENSION_IN_FLIGHT = "ERR_EXTENSION_IN_FLIGHT"
    ERR_RATE_LOCK_OVERLAP = "ERR_RATE_LOCK_OVERLAP"
    ERR_APPRAISAL_OVERLAP = "ERR_APPRAISAL_OVERLAP"
    ERR_DISCLOSURE_VERSION_CONFLICT = "ERR_DISCLOSURE_VERSION_CONFLICT"
    ERR_COMPLIANCE_REVIEWER_CONFLICT = "ERR_COMPLIANCE_REVIEWER_CONFLICT"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Business fiscal — PRD §3.8
    ERR_DTI_EXCEEDED = "ERR_DTI_EXCEEDED"
    ERR_LTV_EXCEEDED = "ERR_LTV_EXCEEDED"
    ERR_INVALID_COUNTER_OFFER = "ERR_INVALID_COUNTER_OFFER"

    # Schema — PRD §5
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 — Error Code Catalogue table.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_UDAAP_SOD_VIOLATION: 403,
    ApiErrorId.ERR_APPLICATION_NOT_FOUND: 404,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_UDAAP_REVIEW_REQUIRED: 409,
    ApiErrorId.ERR_TRID_WAITING_PERIOD: 409,
    ApiErrorId.ERR_APPRAISAL_EXPIRED: 409,
    ApiErrorId.ERR_RATE_LOCK_EXPIRED: 409,
    ApiErrorId.ERR_MISSING_DEPENDENCIES: 409,
    ApiErrorId.ERR_APR_TOLERANCE_EXCEEDED: 409,
    ApiErrorId.ERR_EXTENSION_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_EXTENSION_IN_FLIGHT: 409,
    ApiErrorId.ERR_RATE_LOCK_OVERLAP: 409,
    ApiErrorId.ERR_APPRAISAL_OVERLAP: 409,
    ApiErrorId.ERR_DISCLOSURE_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_COMPLIANCE_REVIEWER_CONFLICT: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DTI_EXCEEDED: 422,
    ApiErrorId.ERR_LTV_EXCEEDED: 422,
    ApiErrorId.ERR_INVALID_COUNTER_OFFER: 422,
    ApiErrorId.ERR_VALIDATION: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
