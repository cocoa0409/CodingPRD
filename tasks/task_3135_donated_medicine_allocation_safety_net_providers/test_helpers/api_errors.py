"""Error identifiers and HTTP status mapping for the Donated Medicine Allocation API.

Every error identifier the PRD declares, paired with the HTTP status it must
be returned with. Registering the mapping lets ``validate_error`` cross-check
the status automatically, so a test only has to name the identifier.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_FORBIDDEN_OWNERSHIP = "ERR_FORBIDDEN_OWNERSHIP"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DONOR_NOT_ACTIVE = "ERR_DONOR_NOT_ACTIVE"
    ERR_CONTROLLED_DONOR_UNREGISTERED = "ERR_CONTROLLED_DONOR_UNREGISTERED"
    ERR_CONTROLLED_SITE_NOT_AUTHORIZED = "ERR_CONTROLLED_SITE_NOT_AUTHORIZED"
    ERR_COLD_CHAIN_INADEQUATE = "ERR_COLD_CHAIN_INADEQUATE"
    ERR_COLD_CHAIN_PACK_REQUIRED = "ERR_COLD_CHAIN_PACK_REQUIRED"
    ERR_LOT_NOT_RELEASABLE = "ERR_LOT_NOT_RELEASABLE"
    ERR_IMPORT_LICENSE_MISSING = "ERR_IMPORT_LICENSE_MISSING"
    ERR_NO_VERIFIED_LICENSE = "ERR_NO_VERIFIED_LICENSE"
    ERR_LICENSE_EXPIRED = "ERR_LICENSE_EXPIRED"
    ERR_SITE_NOT_QUALIFIED = "ERR_SITE_NOT_QUALIFIED"
    ERR_QUANTITY_INVALID = "ERR_QUANTITY_INVALID"
    ERR_INSUFFICIENT_AVAILABLE = "ERR_INSUFFICIENT_AVAILABLE"
    ERR_OVERREPORTED = "ERR_OVERREPORTED"
    ERR_CUSTOMS_NOT_CLEARED = "ERR_CUSTOMS_NOT_CLEARED"
    ERR_CUSTOMS_VALUE_INVALID = "ERR_CUSTOMS_VALUE_INVALID"
    ERR_INCOMPATIBLE_TEMPERATURE_BANDS = "ERR_INCOMPATIBLE_TEMPERATURE_BANDS"
    ERR_MODULE_OUT_OF_REGION = "ERR_MODULE_OUT_OF_REGION"
    ERR_EMERGENCY_NOT_ACTIVE = "ERR_EMERGENCY_NOT_ACTIVE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_FORBIDDEN_OWNERSHIP: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DONOR_NOT_ACTIVE: 409,
    ApiErrorId.ERR_CONTROLLED_DONOR_UNREGISTERED: 422,
    ApiErrorId.ERR_CONTROLLED_SITE_NOT_AUTHORIZED: 422,
    ApiErrorId.ERR_COLD_CHAIN_INADEQUATE: 422,
    ApiErrorId.ERR_COLD_CHAIN_PACK_REQUIRED: 422,
    ApiErrorId.ERR_LOT_NOT_RELEASABLE: 409,
    ApiErrorId.ERR_IMPORT_LICENSE_MISSING: 422,
    ApiErrorId.ERR_NO_VERIFIED_LICENSE: 422,
    ApiErrorId.ERR_LICENSE_EXPIRED: 422,
    ApiErrorId.ERR_SITE_NOT_QUALIFIED: 409,
    ApiErrorId.ERR_QUANTITY_INVALID: 422,
    ApiErrorId.ERR_INSUFFICIENT_AVAILABLE: 409,
    ApiErrorId.ERR_OVERREPORTED: 422,
    ApiErrorId.ERR_CUSTOMS_NOT_CLEARED: 409,
    ApiErrorId.ERR_CUSTOMS_VALUE_INVALID: 422,
    ApiErrorId.ERR_INCOMPATIBLE_TEMPERATURE_BANDS: 422,
    ApiErrorId.ERR_MODULE_OUT_OF_REGION: 422,
    ApiErrorId.ERR_EMERGENCY_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
}

# Register with the framework so validate_error() cross-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
