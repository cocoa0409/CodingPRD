"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / authorization
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Existence / referential
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_MISMATCH = "ERR_REFERENCE_MISMATCH"

    # Concurrency / state
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_POSTURE_BLOCKED = "ERR_POSTURE_BLOCKED"

    # Scheduling / location
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_PERMIT_REQUIRED = "ERR_PERMIT_REQUIRED"
    ERR_LOCATION_OVER_CAPACITY = "ERR_LOCATION_OVER_CAPACITY"
    ERR_WEATHER_BLOCKED = "ERR_WEATHER_BLOCKED"

    # Casting / actor scheduling
    ERR_AUDITION_NOT_PASSED = "ERR_AUDITION_NOT_PASSED"
    ERR_ACTOR_CALLSHEET_CONFLICT = "ERR_ACTOR_CALLSHEET_CONFLICT"
    ERR_CROSS_PROJECT_CONFLICT = "ERR_CROSS_PROJECT_CONFLICT"

    # Equipment
    ERR_EQUIPMENT_UNAVAILABLE = "ERR_EQUIPMENT_UNAVAILABLE"
    ERR_INVALID_EVENT_PAYLOAD = "ERR_INVALID_EVENT_PAYLOAD"

    # Fiscal
    ERR_BUDGET_OVERALLOCATED = "ERR_BUDGET_OVERALLOCATED"
    ERR_RESERVE_INSUFFICIENT = "ERR_RESERVE_INSUFFICIENT"
    ERR_OPEN_OBLIGATIONS = "ERR_OPEN_OBLIGATIONS"

    # Generic
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_MISMATCH: 422,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_POSTURE_BLOCKED: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_PERMIT_REQUIRED: 409,
    ApiErrorId.ERR_LOCATION_OVER_CAPACITY: 409,
    ApiErrorId.ERR_WEATHER_BLOCKED: 409,
    ApiErrorId.ERR_AUDITION_NOT_PASSED: 422,
    ApiErrorId.ERR_ACTOR_CALLSHEET_CONFLICT: 409,
    ApiErrorId.ERR_CROSS_PROJECT_CONFLICT: 409,
    ApiErrorId.ERR_EQUIPMENT_UNAVAILABLE: 409,
    ApiErrorId.ERR_INVALID_EVENT_PAYLOAD: 422,
    ApiErrorId.ERR_BUDGET_OVERALLOCATED: 422,
    ApiErrorId.ERR_RESERVE_INSUFFICIENT: 409,
    ApiErrorId.ERR_OPEN_OBLIGATIONS: 409,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
