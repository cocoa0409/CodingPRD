"""Error classes and error-id catalogue (PRD Section 5)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Authentication / authorization
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
# Existence / request well-formedness
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_CROSS_CASE_REFERENCE = ("ERR_CROSS_CASE_REFERENCE", 422)
# Concurrency / state
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
# Posture gates
ERR_CASE_FROZEN = ("ERR_CASE_FROZEN", 409)
ERR_CASE_RESTRICTED = ("ERR_CASE_RESTRICTED", 409)
# Temporal / fiscal / domain
ERR_HEARING_CONFLICT = ("ERR_HEARING_CONFLICT", 409)
ERR_STATUTE_EXPIRED = ("ERR_STATUTE_EXPIRED", 409)
ERR_FILING_FEE_UNPAID = ("ERR_FILING_FEE_UNPAID", 409)
ERR_APPEAL_WINDOW_CLOSED = ("ERR_APPEAL_WINDOW_CLOSED", 409)
