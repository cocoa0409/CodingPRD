"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, registers it with the framework so
`validate_error()` can cross-check HTTP status codes automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_IDENTIFIER = "ERR_DUPLICATE_IDENTIFIER"
    ERR_STAT_REQUIRES_PHONE_CHANNEL = "ERR_STAT_REQUIRES_PHONE_CHANNEL"
    ERR_RELEASED_RESULT_BLOCKS_REJECT = "ERR_RELEASED_RESULT_BLOCKS_REJECT"
    ERR_INSTRUMENT_SLOT_CONFLICT = "ERR_INSTRUMENT_SLOT_CONFLICT"
    ERR_COLLECTOR_BUSY = "ERR_COLLECTOR_BUSY"
    ERR_SPECIMEN_ORDER_MISMATCH = "ERR_SPECIMEN_ORDER_MISMATCH"
    ERR_RUN_SPECIMEN_MISMATCH = "ERR_RUN_SPECIMEN_MISMATCH"
    ERR_INVALID_RANGE = "ERR_INVALID_RANGE"
    ERR_ACK_WINDOW_CLOSED = "ERR_ACK_WINDOW_CLOSED"
    ERR_ACK_WRONG_RECIPIENT = "ERR_ACK_WRONG_RECIPIENT"
    ERR_STALE_LAB_ORDER_VERSION = "ERR_STALE_LAB_ORDER_VERSION"
    ERR_STALE_RESULT_VERSION = "ERR_STALE_RESULT_VERSION"
    ERR_CLINICIAN_ROLE_MISMATCH = "ERR_CLINICIAN_ROLE_MISMATCH"
    ERR_BACKUP_REQUIRED = "ERR_BACKUP_REQUIRED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_IDENTIFIER: 409,
    ApiErrorId.ERR_STAT_REQUIRES_PHONE_CHANNEL: 422,
    ApiErrorId.ERR_RELEASED_RESULT_BLOCKS_REJECT: 409,
    ApiErrorId.ERR_INSTRUMENT_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_COLLECTOR_BUSY: 409,
    ApiErrorId.ERR_SPECIMEN_ORDER_MISMATCH: 422,
    ApiErrorId.ERR_RUN_SPECIMEN_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_RANGE: 422,
    ApiErrorId.ERR_ACK_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_ACK_WRONG_RECIPIENT: 403,
    ApiErrorId.ERR_STALE_LAB_ORDER_VERSION: 412,
    ApiErrorId.ERR_STALE_RESULT_VERSION: 412,
    ApiErrorId.ERR_CLINICIAN_ROLE_MISMATCH: 422,
    ApiErrorId.ERR_BACKUP_REQUIRED: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
