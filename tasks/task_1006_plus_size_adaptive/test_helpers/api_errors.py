"""Error IDs and their HTTP status mapping (PRD §5 error catalogue).

Registering the map with the framework lets validate_error() cross-check the
HTTP status automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EMPTY_ORDER = "ERR_EMPTY_ORDER"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_SIZE_OUT_OF_RANGE = "ERR_SIZE_OUT_OF_RANGE"
    ERR_INVALID_LINE_SELECTION = "ERR_INVALID_LINE_SELECTION"
    ERR_INVALID_KEEP_SELECTION = "ERR_INVALID_KEEP_SELECTION"
    ERR_EXCHANGE_VARIANT_REQUIRED = "ERR_EXCHANGE_VARIANT_REQUIRED"
    ERR_SPECIALTY_MISMATCH = "ERR_SPECIALTY_MISMATCH"
    ERR_CUSTOMER_SUSPENDED = "ERR_CUSTOMER_SUSPENDED"
    ERR_BOOKING_SUSPENDED = "ERR_BOOKING_SUSPENDED"
    ERR_SUBSCRIPTION_NOT_ACTIVE = "ERR_SUBSCRIPTION_NOT_ACTIVE"
    ERR_SPECIALIST_ON_LEAVE = "ERR_SPECIALIST_ON_LEAVE"
    ERR_RETURN_WINDOW_CLOSED = "ERR_RETURN_WINDOW_CLOSED"
    ERR_TRYON_WINDOW_OPEN = "ERR_TRYON_WINDOW_OPEN"
    ERR_SPECIALIST_UNAVAILABLE = "ERR_SPECIALIST_UNAVAILABLE"
    ERR_CUSTOMER_DOUBLE_BOOKED = "ERR_CUSTOMER_DOUBLE_BOOKED"
    ERR_APPOINTMENT_NOT_ENDED = "ERR_APPOINTMENT_NOT_ENDED"
    ERR_APPOINTMENT_NOT_STARTED = "ERR_APPOINTMENT_NOT_STARTED"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EMPTY_ORDER: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_SIZE_OUT_OF_RANGE: 409,
    ApiErrorId.ERR_INVALID_LINE_SELECTION: 409,
    ApiErrorId.ERR_INVALID_KEEP_SELECTION: 409,
    ApiErrorId.ERR_EXCHANGE_VARIANT_REQUIRED: 409,
    ApiErrorId.ERR_SPECIALTY_MISMATCH: 409,
    ApiErrorId.ERR_CUSTOMER_SUSPENDED: 409,
    ApiErrorId.ERR_BOOKING_SUSPENDED: 409,
    ApiErrorId.ERR_SUBSCRIPTION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SPECIALIST_ON_LEAVE: 409,
    ApiErrorId.ERR_RETURN_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_TRYON_WINDOW_OPEN: 409,
    ApiErrorId.ERR_SPECIALIST_UNAVAILABLE: 409,
    ApiErrorId.ERR_CUSTOMER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_APPOINTMENT_NOT_ENDED: 409,
    ApiErrorId.ERR_APPOINTMENT_NOT_STARTED: 409,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
