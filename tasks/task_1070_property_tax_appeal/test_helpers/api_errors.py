"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_FORBIDDEN_NOT_OWNER = "ERR_FORBIDDEN_NOT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ASSESSMENT_NOT_APPEALABLE = "ERR_ASSESSMENT_NOT_APPEALABLE"
    ERR_NO_HELD_HEARING = "ERR_NO_HELD_HEARING"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_FEE_AGREEMENT_NOT_ACTIVE = "ERR_FEE_AGREEMENT_NOT_ACTIVE"
    ERR_FILING_DEADLINE_PASSED = "ERR_FILING_DEADLINE_PASSED"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_NO_EVIDENCE = "ERR_NO_EVIDENCE"
    ERR_REPRESENTATIVE_UNAVAILABLE = "ERR_REPRESENTATIVE_UNAVAILABLE"
    ERR_DOCKET_ROOM_FULL = "ERR_DOCKET_ROOM_FULL"
    ERR_INVALID_VALUE = "ERR_INVALID_VALUE"
    ERR_NO_BILLABLE_SAVINGS = "ERR_NO_BILLABLE_SAVINGS"
    ERR_STALE_APPEAL_VERSION = "ERR_STALE_APPEAL_VERSION"
    ERR_DUPLICATE = "ERR_DUPLICATE"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_FORBIDDEN_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ASSESSMENT_NOT_APPEALABLE: 409,
    ApiErrorId.ERR_NO_HELD_HEARING: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_FEE_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_FILING_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_OFFER_EXPIRED: 409,
    ApiErrorId.ERR_NO_EVIDENCE: 422,
    ApiErrorId.ERR_REPRESENTATIVE_UNAVAILABLE: 409,
    ApiErrorId.ERR_DOCKET_ROOM_FULL: 409,
    ApiErrorId.ERR_INVALID_VALUE: 422,
    ApiErrorId.ERR_NO_BILLABLE_SAVINGS: 409,
    ApiErrorId.ERR_STALE_APPEAL_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
