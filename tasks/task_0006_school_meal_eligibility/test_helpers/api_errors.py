"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_HOUSEHOLD_INCOMPLETE = "ERR_HOUSEHOLD_INCOMPLETE"
    ERR_ALLERGEN_CONFLICT = "ERR_ALLERGEN_CONFLICT"
    ERR_NO_ACTIVE_ELIGIBILITY = "ERR_NO_ACTIVE_ELIGIBILITY"
    ERR_INSUFFICIENT_FUNDS = "ERR_INSUFFICIENT_FUNDS"
    ERR_TOPUP_CAP_EXCEEDED = "ERR_TOPUP_CAP_EXCEEDED"
    ERR_DUPLICATE_IDEMPOTENCY_KEY = "ERR_DUPLICATE_IDEMPOTENCY_KEY"
    ERR_CLAIM_PERIOD_OVERLAP = "ERR_CLAIM_PERIOD_OVERLAP"
    ERR_ELIGIBILITY_OVERLAP = "ERR_ELIGIBILITY_OVERLAP"
    ERR_PERIOD_NOT_SETTLED = "ERR_PERIOD_NOT_SETTLED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED.value: 401,
    ApiErrorId.ERR_FORBIDDEN.value: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER.value: 403,
    ApiErrorId.ERR_NOT_FOUND.value: 404,
    ApiErrorId.ERR_INVALID_REQUEST.value: 400,
    ApiErrorId.ERR_INVALID_PAGINATION.value: 400,
    ApiErrorId.ERR_INVALID_STATE.value: 409,
    ApiErrorId.ERR_HOUSEHOLD_INCOMPLETE.value: 422,
    ApiErrorId.ERR_ALLERGEN_CONFLICT.value: 422,
    ApiErrorId.ERR_NO_ACTIVE_ELIGIBILITY.value: 422,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS.value: 422,
    ApiErrorId.ERR_TOPUP_CAP_EXCEEDED.value: 422,
    ApiErrorId.ERR_DUPLICATE_IDEMPOTENCY_KEY.value: 409,
    ApiErrorId.ERR_CLAIM_PERIOD_OVERLAP.value: 409,
    ApiErrorId.ERR_ELIGIBILITY_OVERLAP.value: 409,
    ApiErrorId.ERR_PERIOD_NOT_SETTLED.value: 409,
    ApiErrorId.ERR_STALE_VERSION.value: 412,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
