"""Error catalogue (PRD 5) and the ApiError exception carried by every rejection."""


class ApiError(Exception):
    """Raised anywhere in the request pipeline; translated into the PRD 2.2 error envelope."""

    def __init__(self, error_id, message=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = ERROR_HTTP.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(error_id, error_id)


