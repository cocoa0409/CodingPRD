"""Error catalog: every error identifier the PRD declares (§5) with its HTTP
status. Registering the mapping with the shared validators lets
``validate_error`` cross-check the status automatically, so a test only has to
name the identifier it expects.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Credentials, role admission, ownership, segregation of duties.
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED_ROLE = "ERR_UNAUTHORIZED_ROLE"
    ERR_NOT_ENTITY_OWNER = "ERR_NOT_ENTITY_OWNER"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Request shape and path resolution.
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State-level checks.
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Applicant eligibility.
    ERR_AGE_INELIGIBLE = "ERR_AGE_INELIGIBLE"
    ERR_EDUCATION_INELIGIBLE = "ERR_EDUCATION_INELIGIBLE"
    ERR_SERVICE_INELIGIBLE = "ERR_SERVICE_INELIGIBLE"

    # Temporal windows.
    ERR_SERVICE_DATE_INVALID = "ERR_SERVICE_DATE_INVALID"
    ERR_VERIFICATION_WINDOW_EXPIRED = "ERR_VERIFICATION_WINDOW_EXPIRED"
    ERR_BACKFILL_WINDOW_CLOSED = "ERR_BACKFILL_WINDOW_CLOSED"
    ERR_REPORT_WINDOW_CLOSED = "ERR_REPORT_WINDOW_CLOSED"

    # Referential gates.
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_DATA_SHARING_NOT_SIGNED = "ERR_DATA_SHARING_NOT_SIGNED"
    ERR_MEMBER_NOT_ACTIVE = "ERR_MEMBER_NOT_ACTIVE"
    ERR_MEMBER_NOT_PLACED = "ERR_MEMBER_NOT_PLACED"
    ERR_AWARD_NOT_EARNED = "ERR_AWARD_NOT_EARNED"

    # Constraint checks.
    ERR_DAILY_HOUR_CAP_EXCEEDED = "ERR_DAILY_HOUR_CAP_EXCEEDED"
    ERR_FUNDRAISING_CAP_EXCEEDED = "ERR_FUNDRAISING_CAP_EXCEEDED"
    ERR_CASELOAD_FULL = "ERR_CASELOAD_FULL"
    ERR_STUDENT_CASELOAD_CONFLICT = "ERR_STUDENT_CASELOAD_CONFLICT"
    ERR_ASSIGNMENT_OVERLAP = "ERR_ASSIGNMENT_OVERLAP"
    ERR_TEAM_CAPACITY_EXCEEDED = "ERR_TEAM_CAPACITY_EXCEEDED"
    ERR_BACKFILL_LIMIT_REACHED = "ERR_BACKFILL_LIMIT_REACHED"
    ERR_TEAM_STAFFING_BELOW_MINIMUM = "ERR_TEAM_STAFFING_BELOW_MINIMUM"
    ERR_DUPLICATE_PAYMENT_PERIOD = "ERR_DUPLICATE_PAYMENT_PERIOD"
    ERR_COMPLETION_HOURS_NOT_MET = "ERR_COMPLETION_HOURS_NOT_MET"

    # Fiscal gate.
    ERR_SITE_FUNDING_DEFICIT = "ERR_SITE_FUNDING_DEFICIT"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED_ROLE: 403,
    ApiErrorId.ERR_NOT_ENTITY_OWNER: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_AGE_INELIGIBLE: 422,
    ApiErrorId.ERR_EDUCATION_INELIGIBLE: 422,
    ApiErrorId.ERR_SERVICE_INELIGIBLE: 422,
    ApiErrorId.ERR_SERVICE_DATE_INVALID: 422,
    ApiErrorId.ERR_VERIFICATION_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_BACKFILL_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_REPORT_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_DAILY_HOUR_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_FUNDRAISING_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_CASELOAD_FULL: 422,
    ApiErrorId.ERR_STUDENT_CASELOAD_CONFLICT: 409,
    ApiErrorId.ERR_ASSIGNMENT_OVERLAP: 409,
    ApiErrorId.ERR_TEAM_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_BACKFILL_LIMIT_REACHED: 422,
    ApiErrorId.ERR_TEAM_STAFFING_BELOW_MINIMUM: 422,
    ApiErrorId.ERR_DUPLICATE_PAYMENT_PERIOD: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_DATA_SHARING_NOT_SIGNED: 409,
    ApiErrorId.ERR_MEMBER_NOT_ACTIVE: 409,
    ApiErrorId.ERR_MEMBER_NOT_PLACED: 422,
    ApiErrorId.ERR_AWARD_NOT_EARNED: 409,
    ApiErrorId.ERR_COMPLETION_HOURS_NOT_MET: 422,
    ApiErrorId.ERR_SITE_FUNDING_DEFICIT: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
