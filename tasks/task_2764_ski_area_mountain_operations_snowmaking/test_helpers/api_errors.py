# Register the mapping so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(ERROR_HTTP_STATUS)


def http_status_for(error_id: str) -> int:
    """Return the HTTP status the catalogue pairs with an error identifier."""
    return ERROR_HTTP_STATUS[error_id]


def priority_of(error_id: str) -> int:
    """Return the validation ladder position of an error identifier."""
    return VALIDATION_PRIORITY[error_id]


def wins(lower_error_id: str, higher_error_id: str) -> bool:
    """True when lower_error_id is checked before higher_error_id."""
    return VALIDATION_PRIORITY[lower_error_id] < VALIDATION_PRIORITY[higher_error_id]
