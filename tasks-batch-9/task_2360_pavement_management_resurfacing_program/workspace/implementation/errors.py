DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Both X-User-ID and X-User-Role headers must be present and non-empty.",
    "ERR_UNAUTHORIZED": "The declared role is not permitted for this operation.",
    "ERR_INVALID_REQUEST": "The request is malformed.",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(
            error_id, _humanize(error_id)
        )


def _humanize(error_id):
    text = error_id
    if text.startswith("ERR_"):
        text = text[4:]
    return text.replace("_", " ").capitalize() + "."


def fail(error_id, message=None):
    raise ApiError(error_id, message)
