"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_NICU_CRITERIA_MET = "ERR_NICU_CRITERIA_MET"
    ERR_PHARMACY_SIGNOFF_REQUIRED = "ERR_PHARMACY_SIGNOFF_REQUIRED"
    ERR_BIRTH_CERT_PREREQUISITE = "ERR_BIRTH_CERT_PREREQUISITE"
    ERR_DISCHARGE_PREREQUISITE = "ERR_DISCHARGE_PREREQUISITE"
    ERR_LEGAL_NAME_REQUIRED = "ERR_LEGAL_NAME_REQUIRED"
    ERR_SEP_WINDOW_CLOSED = "ERR_SEP_WINDOW_CLOSED"
    ERR_READINESS_BELOW_THRESHOLD = "ERR_READINESS_BELOW_THRESHOLD"
    ERR_DUPLICATE_BIRTH_SEQUENCE = "ERR_DUPLICATE_BIRTH_SEQUENCE"
    ERR_NO_ACTIVE_NICU_STAY = "ERR_NO_ACTIVE_NICU_STAY"
    ERR_DEPENDENT_SLOTS_EXHAUSTED = "ERR_DEPENDENT_SLOTS_EXHAUSTED"
    ERR_NICU_CRITERIA_NOT_MET = "ERR_NICU_CRITERIA_NOT_MET"
    ERR_ADMIT_WINDOW_CLOSED = "ERR_ADMIT_WINDOW_CLOSED"
    ERR_BAG_ALREADY_ISSUED = "ERR_BAG_ALREADY_ISSUED"
    ERR_BED_INTERVAL_OVERLAP = "ERR_BED_INTERVAL_OVERLAP"
    ERR_CONSULT_BUFFER_CONFLICT = "ERR_CONSULT_BUFFER_CONFLICT"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_NICU_CRITERIA_MET: 422,
    ApiErrorId.ERR_PHARMACY_SIGNOFF_REQUIRED: 422,
    ApiErrorId.ERR_BIRTH_CERT_PREREQUISITE: 422,
    ApiErrorId.ERR_DISCHARGE_PREREQUISITE: 422,
    ApiErrorId.ERR_LEGAL_NAME_REQUIRED: 422,
    ApiErrorId.ERR_SEP_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_READINESS_BELOW_THRESHOLD: 422,
    ApiErrorId.ERR_DUPLICATE_BIRTH_SEQUENCE: 409,
    ApiErrorId.ERR_NO_ACTIVE_NICU_STAY: 422,
    ApiErrorId.ERR_DEPENDENT_SLOTS_EXHAUSTED: 422,
    ApiErrorId.ERR_NICU_CRITERIA_NOT_MET: 422,
    ApiErrorId.ERR_ADMIT_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_BAG_ALREADY_ISSUED: 409,
    ApiErrorId.ERR_BED_INTERVAL_OVERLAP: 409,
    ApiErrorId.ERR_CONSULT_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
