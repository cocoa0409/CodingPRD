"""The error catalogue of the biometric privacy consent API.

The enum members mirror the ``error_id`` strings the API returns, and
``HTTP_STATUS_CODES`` mirrors the HTTP status each one is committed to.  The
mapping is registered with the framework validators at import time so that
``validate_error`` cross-checks the status automatically.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # --- auth ---
    UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    SUBJECT_MISMATCH = "ERR_SUBJECT_MISMATCH"
    SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # --- validation ---
    INVALID_REQUEST = "ERR_INVALID_REQUEST"

