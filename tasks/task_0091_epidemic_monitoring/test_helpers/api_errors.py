"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_DUPLICATE_CASE = "ERR_DUPLICATE_CASE"
    ERR_DUPLICATE_BULLETIN = "ERR_DUPLICATE_BULLETIN"
    ERR_INSTITUTION_INACTIVE = "ERR_INSTITUTION_INACTIVE"
    ERR_TEST_RESULT_EXPIRED = "ERR_TEST_RESULT_EXPIRED"
    ERR_ISOLATION_DATE_INVALID = "ERR_ISOLATION_DATE_INVALID"
    ERR_FACILITY_AT_CAPACITY = "ERR_FACILITY_AT_CAPACITY"
    ERR_RELEASE_NOT_ELIGIBLE = "ERR_RELEASE_NOT_ELIGIBLE"
    ERR_SELF_CONTACT = "ERR_SELF_CONTACT"
    ERR_EVENT_TIME_INVALID = "ERR_EVENT_TIME_INVALID"
    ERR_SUPPLY_INSUFFICIENT = "ERR_SUPPLY_INSUFFICIENT"
    ERR_DISPATCH_QUANTITY_MISMATCH = "ERR_DISPATCH_QUANTITY_MISMATCH"
    ERR_CONSUMPTION_EXCEEDS_DISPATCH = "ERR_CONSUMPTION_EXCEEDS_DISPATCH"
    ERR_TIER_STALE = "ERR_TIER_STALE"
    ERR_INVALID_CHANNELS = "ERR_INVALID_CHANNELS"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"


# Per PRD §5 Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_CASE: 409,
    ApiErrorId.ERR_DUPLICATE_BULLETIN: 409,
    ApiErrorId.ERR_INSTITUTION_INACTIVE: 403,
    ApiErrorId.ERR_TEST_RESULT_EXPIRED: 422,
    ApiErrorId.ERR_ISOLATION_DATE_INVALID: 422,
    ApiErrorId.ERR_FACILITY_AT_CAPACITY: 409,
    ApiErrorId.ERR_RELEASE_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_SELF_CONTACT: 422,
    ApiErrorId.ERR_EVENT_TIME_INVALID: 422,
    ApiErrorId.ERR_SUPPLY_INSUFFICIENT: 409,
    ApiErrorId.ERR_DISPATCH_QUANTITY_MISMATCH: 422,
    ApiErrorId.ERR_CONSUMPTION_EXCEEDS_DISPATCH: 422,
    ApiErrorId.ERR_TIER_STALE: 422,
    ApiErrorId.ERR_INVALID_CHANNELS: 422,
    ApiErrorId.ERR_INVALID_PAGINATION: 400,
}


# Register with framework so validate_error() can cross-check HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
