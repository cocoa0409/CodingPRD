"""Temporal overlap rules: caregiver double-booking (half-open interval plus a
30-minute travel buffer) at clock-in, and family window conflict (closed-adjacency
overlap, no buffer) at confirm.

Translates difficulty instances under resource_temporal_overlap.
"""
import pytest
from test_helpers import (
    validate_success, validate_error, get_success_data,
    set_clock, create_family, create_cleared_available_caregiver,
    create_open_posting, offer_booking, confirm_booking, first_session,
    make_family_headers, make_caregiver_headers, TEST_USERS,
)

ADMIN = TEST_USERS["admin_headers"]


class TestCaregiverDoubleBookedTravelBuffer:
    """resource_temporal_overlap / caregiver_double_book_halfopen_with_travel_buffer."""

    def test_clock_in_rejected_within_travel_buffer(self, api):
        """PRD §3.7: "treating each window as the half-open interval from
        `window_start` up to but not including `window_end`, two of the
        caregiver's sessions conflict if they come within the travel buffer of 30
        minutes of one another, so a gap of at least 30 minutes must separate
        them. A collision is rejected with `ERR_CAREGIVER_DOUBLE_BOOKED`."

        Session A 08:00-12:00 IN_PROGRESS; session B 12:15-14:00 (15-min gap <
        30-min buffer) → clock-in B rejected.

        Design: Difficulty/resource_temporal_overlap/caregiver_double_book_halfopen_with_travel_buffer
        """
        set_clock("2026-03-01T00:00:00Z")
        fam = create_family(wallet_balance_cents=200000, num_children=1,
                            required_tier="BASIC", email="ov@x.com")
        cg = create_cleared_available_caregiver(tier="BASIC", email="ovcg@x.com")

        # Booking A is confirmed and its session clocked IN (IN_PROGRESS) before
        # booking B's session exists. Per PRD §3.7 the clock-in overlap check runs
        # against the caregiver's *non-terminal* sessions (SCHEDULED included), so
        # session A must be clocked in while it is the caregiver's only session;
        # session B is then generated by confirming booking B (confirmation runs
        # no caregiver-overlap check) and its later clock-in is what the buffer
        # rule must reject because session A is IN_PROGRESS within 15 min < 30 min.
        pa = create_open_posting(fam["id"], care_type="ONE_TIME",
                                 family_pay_rate_cents=2000, required_tier="BASIC", title="OvA")
        ba = offer_booking(fam["id"], cg["id"], pa["id"], agreed_rate_cents=2000,
                           scheduled_start="2026-03-30T08:00:00Z",
                           scheduled_end="2026-03-30T12:00:00Z")
        ba = confirm_booking(ba["id"], cg["id"])

        set_clock("2026-03-30T08:00:00Z")
        sa = first_session(ba["id"])
        get_success_data(api.clock_in(sa["id"], make_caregiver_headers(cg["id"])))

        pb = create_open_posting(fam["id"], care_type="ONE_TIME",
                                 family_pay_rate_cents=2000, required_tier="BASIC", title="OvB")
        bb = offer_booking(fam["id"], cg["id"], pb["id"], agreed_rate_cents=2000,
                           scheduled_start="2026-03-30T12:15:00Z",
                           scheduled_end="2026-03-30T14:00:00Z")
        bb = confirm_booking(bb["id"], cg["id"])

        set_clock("2026-03-30T12:10:00Z")
        sb = first_session(bb["id"])
        res = api.clock_in(sb["id"], make_caregiver_headers(cg["id"]))
        validate_error(res, "ERR_CAREGIVER_DOUBLE_BOOKED")

    def test_first_session_clock_in_succeeds(self, api):
        """PRD §3.7: "On a successful clock-in the session moves to `IN_PROGRESS`,
        its `clock_in_at` is stamped with the current clock".

        Confirms the first (non-conflicting) session clocks in cleanly, so the
        rejection of the second is attributable to the buffer rule and not a
        broken setup.

        Design: Difficulty/resource_temporal_overlap/caregiver_double_book_halfopen_with_travel_buffer
        """
        set_clock("2026-03-01T00:00:00Z")
        fam = create_family(wallet_balance_cents=200000, num_children=1,
                            required_tier="BASIC", email="ov2@x.com")
        cg = create_cleared_available_caregiver(tier="BASIC", email="ov2cg@x.com")
        pa = create_open_posting(fam["id"], care_type="ONE_TIME",
                                 family_pay_rate_cents=2000, required_tier="BASIC", title="OvA")
        ba = offer_booking(fam["id"], cg["id"], pa["id"], agreed_rate_cents=2000,
                           scheduled_start="2026-03-30T08:00:00Z",
                           scheduled_end="2026-03-30T12:00:00Z")
        ba = confirm_booking(ba["id"], cg["id"])
        set_clock("2026-03-30T08:00:00Z")
        sa = first_session(ba["id"])
        clocked = validate_success(api.clock_in(sa["id"], make_caregiver_headers(cg["id"])), 200)
        assert clocked["status"] == "IN_PROGRESS"


class TestFamilyWindowConflict:
    """resource_temporal_overlap / family_window_conflict_closed_no_buffer_on_confirm."""

    def test_second_confirm_rejected_on_overlapping_window(self, api):
        """PRD §3.5: "The family must not already hold another `CONFIRMED` or
        `IN_PROGRESS` booking whose first-session window overlaps this booking's
        first-session window — overlap here is closed-adjacency with no buffer,
        meaning two windows conflict whenever they share any instant — else
        `ERR_FAMILY_WINDOW_CONFLICT`."

        Booking-1 CONFIRMED (caregiver1, 09:00-13:00); booking-2 (caregiver2,
        12:00-15:00) overlaps → second confirm rejected.

        Design: Difficulty/resource_temporal_overlap/family_window_conflict_closed_no_buffer_on_confirm
        """
        set_clock("2026-03-01T00:00:00Z")
        fam = create_family(wallet_balance_cents=200000, num_children=1,
                            required_tier="BASIC", email="fw@x.com")
        cg1 = create_cleared_available_caregiver(tier="BASIC", email="fwcg1@x.com")
        cg2 = create_cleared_available_caregiver(tier="BASIC", email="fwcg2@x.com")

        p1 = create_open_posting(fam["id"], care_type="ONE_TIME",
                                 family_pay_rate_cents=2000, required_tier="BASIC", title="Fw1")
        b1 = offer_booking(fam["id"], cg1["id"], p1["id"], agreed_rate_cents=2000,
                           scheduled_start="2026-03-28T09:00:00Z",
                           scheduled_end="2026-03-28T13:00:00Z")
        confirm_booking(b1["id"], cg1["id"])

        p2 = create_open_posting(fam["id"], care_type="ONE_TIME",
                                 family_pay_rate_cents=2000, required_tier="BASIC", title="Fw2")
        b2 = offer_booking(fam["id"], cg2["id"], p2["id"], agreed_rate_cents=2000,
                           scheduled_start="2026-03-28T12:00:00Z",
                           scheduled_end="2026-03-28T15:00:00Z")
        res = api.confirm_booking(b2["id"], make_caregiver_headers(cg2["id"]))
        validate_error(res, "ERR_FAMILY_WINDOW_CONFLICT")

    def test_first_booking_confirms_before_conflict(self, api):
        """PRD §3.5: "The booking itself moves to `CONFIRMED`."

        Confirms booking-1 reaches CONFIRMED so the conflict on booking-2 is
        attributable to the family-window rule.

        Design: Difficulty/resource_temporal_overlap/family_window_conflict_closed_no_buffer_on_confirm
        """
        set_clock("2026-03-01T00:00:00Z")
        fam = create_family(wallet_balance_cents=200000, num_children=1,
                            required_tier="BASIC", email="fw3@x.com")
        cg1 = create_cleared_available_caregiver(tier="BASIC", email="fw3cg1@x.com")
        p1 = create_open_posting(fam["id"], care_type="ONE_TIME",
                                 family_pay_rate_cents=2000, required_tier="BASIC", title="Fw1")
        b1 = offer_booking(fam["id"], cg1["id"], p1["id"], agreed_rate_cents=2000,
                           scheduled_start="2026-03-28T09:00:00Z",
                           scheduled_end="2026-03-28T13:00:00Z")
        confirmed = confirm_booking(b1["id"], cg1["id"])
        assert confirmed["status"] == "CONFIRMED"
