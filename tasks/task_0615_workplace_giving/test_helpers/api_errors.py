"""Error IDs and HTTP status mapping (PRD 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / existence / request
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    # Concurrency
    ERR_STALE_BATCH_VERSION = "ERR_STALE_BATCH_VERSION"
    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Program
    ERR_PROGRAM_NOT_ACTIVE = "ERR_PROGRAM_NOT_ACTIVE"
    ERR_OPEN_BATCH_EXISTS = "ERR_OPEN_BATCH_EXISTS"
    # Charity
    ERR_CHARITY_NOT_ELIGIBLE = "ERR_CHARITY_NOT_ELIGIBLE"
    ERR_MAX_REVIEW_ROUNDS = "ERR_MAX_REVIEW_ROUNDS"
    ERR_CHARITY_NOT_APPROVED = "ERR_CHARITY_NOT_APPROVED"
    ERR_DUPLICATE_EIN = "ERR_DUPLICATE_EIN"
    # Campaign / window
    ERR_CAMPAIGN_NOT_LIVE = "ERR_CAMPAIGN_NOT_LIVE"
    ERR_CAMPAIGN_WINDOW_CLOSED = "ERR_CAMPAIGN_WINDOW_CLOSED"
    # Employee
    ERR_EMPLOYEE_NOT_ACTIVE = "ERR_EMPLOYEE_NOT_ACTIVE"
    ERR_DUPLICATE_EMPLOYEE_EMAIL = "ERR_DUPLICATE_EMPLOYEE_EMAIL"
