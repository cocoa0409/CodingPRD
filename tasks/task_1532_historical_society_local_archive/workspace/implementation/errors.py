class ApiError(Exception):
    """Exception carrying the error envelope triple."""

    def __init__(self, error_id: str, message: str, http_status: int | None = None):
        self.error_id = error_id
        self.message = message
        self.http_status = (
            http_status if http_status is not None else HTTP_STATUS.get(error_id, 400)
        )
        super().__init__(f"{error_id}: {message}")


def raise_err(error_id: str, message: str):
    raise ApiError(error_id, message, HTTP_STATUS[error_id])
