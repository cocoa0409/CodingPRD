def install_error_http_status_map() -> None:
    """Teach the shared validators the declared error -> HTTP status mapping."""
    set_error_http_status_map(ERROR_HTTP_STATUS)


def expected_status_for(error_id: str) -> int:
    """Return the HTTP status the PRD declares for `error_id`."""
    return ERROR_HTTP_STATUS[error_id]
