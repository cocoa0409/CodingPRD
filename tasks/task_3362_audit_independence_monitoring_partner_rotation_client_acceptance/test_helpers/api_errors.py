"""Error identifiers and their HTTP status codes.

The identifiers are the ones the contract's error catalogue declares; the
status map is registered with the shared validators so that every error
assertion cross-checks the status code as well as the identifier.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Request shape, authentication and authorization.
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_MISSING_AUTH_HEADERS = "ERR_MISSING_AUTH_HEADERS"
    ERR_UNAUTHORIZED_ROLE = "ERR_UNAUTHORIZED_ROLE"

    # Path-segment existence, one code per resource family.
    ERR_CLIENT_NOT_FOUND = "ERR_CLIENT_NOT_FOUND"
    ERR_ENGAGEMENT_NOT_FOUND = "ERR_ENGAGEMENT_NOT_FOUND"
    ERR_ACCEPTANCE_NOT_FOUND = "ERR_ACCEPTANCE_NOT_FOUND"
    ERR_ASSESSMENT_NOT_FOUND = "ERR_ASSESSMENT_NOT_FOUND"
    ERR_PROFESSIONAL_NOT_FOUND = "ERR_PROFESSIONAL_NOT_FOUND"
    ERR_ASSIGNMENT_NOT_FOUND = "ERR_ASSIGNMENT_NOT_FOUND"
    ERR_FINDING_NOT_FOUND = "ERR_FINDING_NOT_FOUND"
    ERR_THREAT_NOT_FOUND = "ERR_THREAT_NOT_FOUND"
    ERR_SERVICE_NOT_FOUND = "ERR_SERVICE_NOT_FOUND"
    ERR_AFFILIATE_NOT_FOUND = "ERR_AFFILIATE_NOT_FOUND"
    ERR_ATTESTATION_NOT_FOUND = "ERR_ATTESTATION_NOT_FOUND"
    ERR_REVIEW_NOT_FOUND = "ERR_REVIEW_NOT_FOUND"

    # Body foreign-key resolution.
    ERR_REFERENCED_ENTITY_NOT_FOUND = "ERR_REFERENCED_ENTITY_NOT_FOUND"

    # State, concurrency and business rules.
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PROHIBITED_SERVICE = "ERR_PROHIBITED_SERVICE"
    ERR_MATERIAL_INTEREST_CONFLICT = "ERR_MATERIAL_INTEREST_CONFLICT"
    ERR_COOLING_OFF_ACTIVE = "ERR_COOLING_OFF_ACTIVE"
    ERR_DUPLICATE_ROLE_HOLDER = "ERR_DUPLICATE_ROLE_HOLDER"
    ERR_ROLE_ASSIGNMENT_OVERLAP = "ERR_ROLE_ASSIGNMENT_OVERLAP"
    ERR_REVIEW_WINDOW_CONFLICT = "ERR_REVIEW_WINDOW_CONFLICT"
    ERR_ROTATION_LIMIT_REACHED = "ERR_ROTATION_LIMIT_REACHED"
    ERR_WORKLOAD_LIMIT_EXCEEDED = "ERR_WORKLOAD_LIMIT_EXCEEDED"
    ERR_REMEDIATION_ATTEMPTS_EXHAUSTED = "ERR_REMEDIATION_ATTEMPTS_EXHAUSTED"
    ERR_ACCEPTANCE_CONDITIONS_UNMET = "ERR_ACCEPTANCE_CONDITIONS_UNMET"
    ERR_NAF_CAP_EXCEEDED = "ERR_NAF_CAP_EXCEEDED"
    ERR_ASSESSMENT_DATE_IN_FUTURE = "ERR_ASSESSMENT_DATE_IN_FUTURE"
    ERR_BACKDATED_ASSIGNMENT = "ERR_BACKDATED_ASSIGNMENT"
    ERR_ENGAGEMENT_FROZEN = "ERR_ENGAGEMENT_FROZEN"
    ERR_FINDINGS_OPEN = "ERR_FINDINGS_OPEN"
    ERR_ATTESTATION_INCOMPLETE = "ERR_ATTESTATION_INCOMPLETE"


