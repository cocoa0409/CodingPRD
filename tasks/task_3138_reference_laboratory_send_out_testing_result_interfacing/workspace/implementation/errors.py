"""Error identifiers, HTTP status codes and the ApiError exception.

The error catalogue mirrors PRD section 5 / SCAFFOLD section 1.6 verbatim; the
status code carried in HTTP_STATUS is the authoritative one the service returns.
"""


class ApiError(Exception):
    """An error carrying the envelope error_id, a message and an HTTP status."""

    def __init__(self, error_id, message="", http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or error_id
        if http_status is None:
            http_status = HTTP_STATUS.get(error_id, 400)
        self.http_status = http_status


