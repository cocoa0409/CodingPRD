"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEADLINE_PASSED = "ERR_DEADLINE_PASSED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_VERIFICATION_ATTEMPTS_EXHAUSTED = "ERR_VERIFICATION_ATTEMPTS_EXHAUSTED"
    ERR_EXEMPTION_BASIS_UNSUPPORTED = "ERR_EXEMPTION_BASIS_UNSUPPORTED"
    ERR_LEGAL_HOLD_ACTIVE = "ERR_LEGAL_HOLD_ACTIVE"
    ERR_UNDECIDED_EXEMPTION = "ERR_UNDECIDED_EXEMPTION"
    ERR_UNRESOLVED_FINDINGS = "ERR_UNRESOLVED_FINDINGS"
    ERR_NO_FINDINGS = "ERR_NO_FINDINGS"
    ERR_PROCESSOR_SUSPENDED = "ERR_PROCESSOR_SUSPENDED"
    ERR_NOTIFICATION_NOT_ACKED = "ERR_NOTIFICATION_NOT_ACKED"
    ERR_EXTENSION_LIMIT_REACHED = "ERR_EXTENSION_LIMIT_REACHED"
    ERR_FULFILLMENT_INCOMPLETE = "ERR_FULFILLMENT_INCOMPLETE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_VERIFICATION_ATTEMPTS_EXHAUSTED: 409,
    ApiErrorId.ERR_EXEMPTION_BASIS_UNSUPPORTED: 409,
    ApiErrorId.ERR_LEGAL_HOLD_ACTIVE: 409,
    ApiErrorId.ERR_UNDECIDED_EXEMPTION: 409,
    ApiErrorId.ERR_UNRESOLVED_FINDINGS: 409,
    ApiErrorId.ERR_NO_FINDINGS: 409,
    ApiErrorId.ERR_PROCESSOR_SUSPENDED: 409,
    ApiErrorId.ERR_NOTIFICATION_NOT_ACKED: 409,
    ApiErrorId.ERR_EXTENSION_LIMIT_REACHED: 409,
    ApiErrorId.ERR_FULFILLMENT_INCOMPLETE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
