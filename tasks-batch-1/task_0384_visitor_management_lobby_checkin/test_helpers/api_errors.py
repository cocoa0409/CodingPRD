"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_FLOOR_VERSION = "ERR_STALE_FLOOR_VERSION"
    ERR_STALE_VISIT_VERSION = "ERR_STALE_VISIT_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_ID_NOT_SCANNED = "ERR_ID_NOT_SCANNED"
    ERR_AGREEMENT_NOT_SIGNED = "ERR_AGREEMENT_NOT_SIGNED"
    ERR_VISIT_NOT_SIGNABLE = "ERR_VISIT_NOT_SIGNABLE"
    ERR_PASS_NOT_ACTIVE = "ERR_PASS_NOT_ACTIVE"
    ERR_PASS_WINDOW = "ERR_PASS_WINDOW"
    ERR_ROOM_CONFLICT = "ERR_ROOM_CONFLICT"
    ERR_PARKING_CONFLICT = "ERR_PARKING_CONFLICT"
    ERR_FLOOR_AT_CAPACITY = "ERR_FLOOR_AT_CAPACITY"
    ERR_NO_BADGE_AVAILABLE = "ERR_NO_BADGE_AVAILABLE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_FLOOR_VERSION: 412,
    ApiErrorId.ERR_STALE_VISIT_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_ID_NOT_SCANNED: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_SIGNED: 409,
    ApiErrorId.ERR_VISIT_NOT_SIGNABLE: 409,
    ApiErrorId.ERR_PASS_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PASS_WINDOW: 409,
    ApiErrorId.ERR_ROOM_CONFLICT: 409,
    ApiErrorId.ERR_PARKING_CONFLICT: 409,
    ApiErrorId.ERR_FLOOR_AT_CAPACITY: 409,
    ApiErrorId.ERR_NO_BADGE_AVAILABLE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
