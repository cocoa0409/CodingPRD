"""API error type carrying the PRD-defined error_id and HTTP status (PRD §5)."""


class ApiError(Exception):
    def __init__(self, error_id, status, message):
        super().__init__(message)
        self.error_id = error_id
        self.status = status
        self.message = message


# ---- auth / request shape ----
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_UNAUTHORIZED = ("ERR_UNAUTHORIZED", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)

# ---- state / OCC ----
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)

# ---- business: safety gates ----
ERR_WATER_CRITICAL = ("ERR_WATER_CRITICAL", 422)
ERR_WATER_OUT_OF_SPEC = ("ERR_WATER_OUT_OF_SPEC", 422)
ERR_NO_VALID_CHEMISTRY = ("ERR_NO_VALID_CHEMISTRY", 422)
ERR_CERT_NOT_VALID = ("ERR_CERT_NOT_VALID", 422)
ERR_PLANT_EMERGENCY = ("ERR_PLANT_EMERGENCY", 422)
ERR_OPERATOR_LICENSE_INVALID = ("ERR_OPERATOR_LICENSE_INVALID", 422)
ERR_LICENSE_WRONG_STATE = ("ERR_LICENSE_WRONG_STATE", 422)
ERR_SOD_VERIFICATION = ("ERR_SOD_VERIFICATION", 422)

# ---- business: referential / temporal ----
ERR_REFERENCED_NOT_FOUND = ("ERR_REFERENCED_NOT_FOUND", 422)
ERR_DISPATCH_WINDOW_CONFLICT = ("ERR_DISPATCH_WINDOW_CONFLICT", 409)
