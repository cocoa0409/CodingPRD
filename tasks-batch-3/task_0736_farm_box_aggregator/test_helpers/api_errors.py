    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CYCLE_NOT_OPEN = "ERR_CYCLE_NOT_OPEN"
    ERR_EMPTY_ORDER = "ERR_EMPTY_ORDER"
    ERR_ORDER_NOT_ALLOCATED = "ERR_ORDER_NOT_ALLOCATED"
    ERR_LINES_NOT_PACKED = "ERR_LINES_NOT_PACKED"
    ERR_ORDER_IN_PACKOUT = "ERR_ORDER_IN_PACKOUT"
