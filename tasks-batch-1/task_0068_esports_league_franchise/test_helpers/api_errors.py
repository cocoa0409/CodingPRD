"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_TEAM_OWNER = "ERR_NOT_TEAM_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_TRADE_WINDOW_CLOSED = "ERR_TRADE_WINDOW_CLOSED"
    ERR_TEAM_RESTRICTED = "ERR_TEAM_RESTRICTED"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_TRADE_ASSETS = "ERR_INVALID_TRADE_ASSETS"
    ERR_ROSTER_LIMIT_EXCEEDED = "ERR_ROSTER_LIMIT_EXCEEDED"
    ERR_PLAYOFF_PRECONDITION = "ERR_PLAYOFF_PRECONDITION"
    ERR_INVALID_FIELD_VALUE = "ERR_INVALID_FIELD_VALUE"
    ERR_CONTRACT_TERM_OVERLAP = "ERR_CONTRACT_TERM_OVERLAP"
    ERR_STINT_OVERLAP = "ERR_STINT_OVERLAP"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_TEAM_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TRADE_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_TEAM_RESTRICTED: 409,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_TRADE_ASSETS: 422,
    ApiErrorId.ERR_ROSTER_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_PLAYOFF_PRECONDITION: 409,
    ApiErrorId.ERR_INVALID_FIELD_VALUE: 422,
    ApiErrorId.ERR_CONTRACT_TERM_OVERLAP: 409,
    ApiErrorId.ERR_STINT_OVERLAP: 409,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
