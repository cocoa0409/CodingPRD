# Entry point 1: the agency's acceptance with errors
# ---------------------------------------------------------------------------
class TestAgencyErrorCascade:
    def test_acceptance_with_errors_sets_transmittal_error_counters(self, api):
        """PRD §3.8: "An acceptance with errors requires a non-empty `errors` array
        and runs the same five-link chain the termination cascade does."
        PRD §3.8: "**First**, the receipt identifier is recorded and one
        **TransmittalError** row is created per entry, with `resolution_status` of
        `OPEN`, a null `resolution_note`, a null `corrected_form_id` and a null
        `resolved_by_user_id`; `error_count` and `open_error_count` are set from
        those rows."

        Design: Difficulty/transitive_cascade/agency_error_cascade_transmittal_to_form_to_group_to_season
        """
        ctx = _transmitted_submission_holding_a_delivered_statement(api)

        _record_acceptance_with_one_error(
            api, ctx["transmittal"]["id"], ctx["form"]["id"]
        )

        transmittal = fixtures.read_transmittal(api, ctx["transmittal"]["id"])
        assert transmittal["status"] == "ACCEPTED_WITH_ERRORS", (
            "an acceptance with errors must leave the transmittal in "
            f"ACCEPTED_WITH_ERRORS, got {transmittal['status']}"
        )
        assert_fields(
            transmittal,
            error_count=1,
            open_error_count=1,
            receipt_id="AIR-2026-0004",
        )

    def test_acceptance_with_errors_creates_one_open_row_naming_the_statement(self, api):
        """PRD §3.8: "**First**, the receipt identifier is recorded and one
        **TransmittalError** row is created per entry, with `resolution_status` of
        `OPEN`, a null `resolution_note`, a null `corrected_form_id` and a null
        `resolved_by_user_id`; `error_count` and `open_error_count` are set from
        those rows."
        PRD §2.5: "agency error rows created by an agency response are only
        discoverable by filtering on `transmittal_id`, `form_1095c_id`,
        `corrected_form_id` or `resolution_status`"

        Design: Difficulty/transitive_cascade/agency_error_cascade_transmittal_to_form_to_group_to_season
        """
        ctx = _transmitted_submission_holding_a_delivered_statement(api)
        transmittal_id = ctx["transmittal"]["id"]

        _record_acceptance_with_one_error(api, transmittal_id, ctx["form"]["id"])

        rows = validate_success(
            api.list_transmittal_errors(
                TEST_USERS["preparer"],
                params={"transmittal_id": transmittal_id, "limit": 100},
            )
        )
        assert len(rows) == 1, (
            f"expected exactly one agency error row for the transmittal, got {len(rows)}"
        )
        assert_transmittal_error(
            rows[0],
            transmittal_id=transmittal_id,
            form_1095c_id=ctx["form"]["id"],
            error_code="AIRTN500",
            error_field="ssn_last4",
            severity="ERROR",
            resolution_status="OPEN",
            resolution_note=None,
            corrected_form_id=None,
            resolved_by_user_id=None,
        )

    def test_named_statement_moves_to_filed_with_errors_and_redelivery_required(self, api):
        """PRD §3.8: "**Second**, because the transmittal entered
        `ACCEPTED_WITH_ERRORS`, each attached statement named by an error of `FATAL`
        or `ERROR` severity moves `PENDING_FILING` → `FILED_WITH_ERRORS` while every
        unnamed statement moves `PENDING_FILING` → `FILED_ACCEPTED`."
        PRD §3.8: "**Third**, because a statement entered `FILED_WITH_ERRORS`, any
        such statement already sitting at `FURNISHED_PAPER` or
        `FURNISHED_ELECTRONIC` also moves to `REDELIVERY_REQUIRED`."

        Design: Difficulty/transitive_cascade/agency_error_cascade_transmittal_to_form_to_group_to_season
        """
        ctx = _transmitted_submission_holding_a_delivered_statement(api)

        _record_acceptance_with_one_error(
            api, ctx["transmittal"]["id"], ctx["form"]["id"]
        )

        form = fixtures.read_form(api, ctx["form"]["id"])
        assert form["filing_status"] == "FILED_WITH_ERRORS", (
            "a statement named by an ERROR-severity agency error must reach "
            f"FILED_WITH_ERRORS, got {form['filing_status']}"
        )
        assert form["furnishing_status"] == "REDELIVERY_REQUIRED", (
            "a delivered statement that entered FILED_WITH_ERRORS must be pushed to "
            f"REDELIVERY_REQUIRED, got {form['furnishing_status']}"
        )

    def test_errored_delivered_statement_opens_a_correction_on_group_and_season(self, api):
        """PRD §3.8: "**Fourth**, that redelivery flag increments the controlled
        group's `open_correction_count` and moves a `DETERMINED_ALE` group to
        `CORRECTION_OPEN`."
        PRD §3.8: "**Fifth**, the group's move increments the season's
        `open_correction_count` and the season can no longer be closed."

        Design: Difficulty/transitive_cascade/agency_error_cascade_transmittal_to_form_to_group_to_season
        """
        ctx = _transmitted_submission_holding_a_delivered_statement(api)

        _record_acceptance_with_one_error(
            api, ctx["transmittal"]["id"], ctx["form"]["id"]
        )

        group = fixtures.read_group(api, ctx["group"]["id"])
        assert group["determination_state"] == "CORRECTION_OPEN", (
            "a DETERMINED_ALE group must move to CORRECTION_OPEN when a statement "
            f"needs redelivery, got {group['determination_state']}"
        )
        assert group["open_correction_count"] == 1, (
            f"expected group open_correction_count 1, got {group['open_correction_count']}"
        )

        season = fixtures.read_season(api, ctx["season"]["id"])
        assert season["open_correction_count"] == 1, (
            "the group's move into CORRECTION_OPEN must increment the season's "
            f"open_correction_count, got {season['open_correction_count']}"
        )


