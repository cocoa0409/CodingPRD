"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can
auto-check HTTP status codes against the PRD-declared status.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth / Authz
    ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = (
        "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    )
    ERR_INSUFFICIENT_PERMISSIONS = "ERR_INSUFFICIENT_PERMISSIONS"

    # Existence
    ERR_EXAM_NOT_FOUND = "ERR_EXAM_NOT_FOUND"
    ERR_QUESTION_NOT_FOUND = "ERR_QUESTION_NOT_FOUND"
    ERR_REGISTRATION_NOT_FOUND = "ERR_REGISTRATION_NOT_FOUND"
    ERR_ATTEMPT_NOT_FOUND = "ERR_ATTEMPT_NOT_FOUND"
    ERR_GRADING_ASSIGNMENT_NOT_FOUND = "ERR_GRADING_ASSIGNMENT_NOT_FOUND"
    ERR_APPEAL_NOT_FOUND = "ERR_APPEAL_NOT_FOUND"

    # State
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EXAM_NOT_IN_SESSION = "ERR_EXAM_NOT_IN_SESSION"
    ERR_EXAM_NOT_GRADING = "ERR_EXAM_NOT_GRADING"
    ERR_EXAM_NOT_IN_APPEAL_WINDOW = "ERR_EXAM_NOT_IN_APPEAL_WINDOW"
    ERR_GRADING_INCOMPLETE = "ERR_GRADING_INCOMPLETE"
    ERR_EXAM_WINDOW_CLOSED = "ERR_EXAM_WINDOW_CLOSED"
    ERR_NO_PENDING_RECHECK = "ERR_NO_PENDING_RECHECK"
    ERR_GRADING_ALREADY_CLAIMED = "ERR_GRADING_ALREADY_CLAIMED"
    ERR_DOUBLE_BLIND_VIOLATION = "ERR_DOUBLE_BLIND_VIOLATION"
    ERR_APPEAL_OFFICER_WAS_MARKER = "ERR_APPEAL_OFFICER_WAS_MARKER"

    # Business safety / data
    ERR_IDENTITY_MISMATCH = "ERR_IDENTITY_MISMATCH"
    ERR_EVIDENCE_REQUIRED = "ERR_EVIDENCE_REQUIRED"
    ERR_AWARDED_OUT_OF_RANGE = "ERR_AWARDED_OUT_OF_RANGE"
    ERR_RUBRIC_SUM_MISMATCH = "ERR_RUBRIC_SUM_MISMATCH"
    ERR_RUBRIC_INVALID = "ERR_RUBRIC_INVALID"
    ERR_QUESTION_NOT_ON_PAPER = "ERR_QUESTION_NOT_ON_PAPER"
    ERR_QUESTION_BANK_EMPTY = "ERR_QUESTION_BANK_EMPTY"
    ERR_SAMPLING_INFEASIBLE = "ERR_SAMPLING_INFEASIBLE"

    # Pagination
    ERR_INVALID_PAGINATION_PARAMETERS = "ERR_INVALID_PAGINATION_PARAMETERS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER: 400,
    ApiErrorId.ERR_INSUFFICIENT_PERMISSIONS: 403,
    ApiErrorId.ERR_EXAM_NOT_FOUND: 404,
    ApiErrorId.ERR_QUESTION_NOT_FOUND: 404,
    ApiErrorId.ERR_REGISTRATION_NOT_FOUND: 404,
    ApiErrorId.ERR_ATTEMPT_NOT_FOUND: 404,
    ApiErrorId.ERR_GRADING_ASSIGNMENT_NOT_FOUND: 404,
    ApiErrorId.ERR_APPEAL_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EXAM_NOT_IN_SESSION: 409,
    ApiErrorId.ERR_EXAM_NOT_GRADING: 409,
    ApiErrorId.ERR_EXAM_NOT_IN_APPEAL_WINDOW: 409,
    ApiErrorId.ERR_GRADING_INCOMPLETE: 409,
    ApiErrorId.ERR_EXAM_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_NO_PENDING_RECHECK: 409,
    ApiErrorId.ERR_GRADING_ALREADY_CLAIMED: 409,
    ApiErrorId.ERR_DOUBLE_BLIND_VIOLATION: 409,
    ApiErrorId.ERR_APPEAL_OFFICER_WAS_MARKER: 409,
    ApiErrorId.ERR_IDENTITY_MISMATCH: 422,
    ApiErrorId.ERR_EVIDENCE_REQUIRED: 422,
    ApiErrorId.ERR_AWARDED_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_RUBRIC_SUM_MISMATCH: 422,
    ApiErrorId.ERR_RUBRIC_INVALID: 422,
    ApiErrorId.ERR_QUESTION_NOT_ON_PAPER: 422,
    ApiErrorId.ERR_QUESTION_BANK_EMPTY: 422,
    ApiErrorId.ERR_SAMPLING_INFEASIBLE: 422,
    ApiErrorId.ERR_INVALID_PAGINATION_PARAMETERS: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
