"""The 46-code error catalogue of PRD §5, with its HTTP status mapping.

Importing this module registers the mapping with the framework's response
validators, so ``validate_error(response, ApiErrorId.ERR_X)`` cross-checks the HTTP
status without every call site restating it.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


