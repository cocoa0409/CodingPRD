"""Error catalog (SCAFFOLD §1.6 / PRD §5). Each ApiError carries the exact
error_id, http status, and a human-readable message."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error id -> (http_status, default message)
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_MODEL_VERSION = "ERR_STALE_MODEL_VERSION"
ERR_BIKE_RETIRED = "ERR_BIKE_RETIRED"
ERR_DELIVERY_TYPE_MISMATCH = "ERR_DELIVERY_TYPE_MISMATCH"
ERR_DELIVERY_WINDOW_CONFLICT = "ERR_DELIVERY_WINDOW_CONFLICT"
ERR_BIKE_ALREADY_SERVICING = "ERR_BIKE_ALREADY_SERVICING"
ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
ERR_PAYOUT_EXCEEDS_CAP = "ERR_PAYOUT_EXCEEDS_CAP"
ERR_RENTAL_CAP_EXCEEDED = "ERR_RENTAL_CAP_EXCEEDED"
ERR_NO_BIKES_AVAILABLE = "ERR_NO_BIKES_AVAILABLE"
ERR_ACCOUNT_SUSPENDED = "ERR_ACCOUNT_SUSPENDED"
