"""Error classes and error ID constants per SCAFFOLD §1.6 / PRD §5."""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


# Error catalog (id -> http status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_FK_NOT_FOUND = ("ERR_FK_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_SELF_APPROVAL_FORBIDDEN = ("ERR_SELF_APPROVAL_FORBIDDEN", 403)
ERR_NOT_ADMITTED = ("ERR_NOT_ADMITTED", 403)
ERR_DEADLINE_PASSED = ("ERR_DEADLINE_PASSED", 409)
ERR_BRIEF_OVER_LIMIT = ("ERR_BRIEF_OVER_LIMIT", 422)
ERR_TOA_UNVERIFIED = ("ERR_TOA_UNVERIFIED", 422)
ERR_RECORD_NOT_COMPLETE = ("ERR_RECORD_NOT_COMPLETE", 409)
ERR_ARGUMENT_OVERLAP = ("ERR_ARGUMENT_OVERLAP", 409)
ERR_ARGUMENT_NOTICE_TOO_SHORT = ("ERR_ARGUMENT_NOTICE_TOO_SHORT", 422)
ERR_GRANT_DAYS_INVALID = ("ERR_GRANT_DAYS_INVALID", 422)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_SERVICE_INCOMPLETE = ("ERR_SERVICE_INCOMPLETE", 422)
ERR_DECISION_NOT_ISSUED = ("ERR_DECISION_NOT_ISSUED", 409)
ERR_DUPLICATE = ("ERR_DUPLICATE", 409)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_ALREADY_TERMINAL = ("ERR_ALREADY_TERMINAL", 409)
ERR_PAGINATION = ("ERR_PAGINATION", 400)


def raise_error(err, message=""):
    error_id, http_status = err
    raise ApiError(error_id, message or error_id, http_status)
