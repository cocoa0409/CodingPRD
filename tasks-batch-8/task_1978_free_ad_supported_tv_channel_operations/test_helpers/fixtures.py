def setup_revenue_report_scenario(*, decision_specs, agreement_below=2000,
                                  agreement_above=4000, agreement_threshold=100000,
                                  agreement_min=0, broadcast_date=C.BROADCAST_DATE,
                                  period=C.PERIOD_MONTH, finalize=False,
                                  analyst_id="fin-1", controller_id="ctl-1"):
    """Full aired-and-measured scenario feeding a revenue report.

    decision_specs: 1 or 2 dicts, each {cpm_cents, iab_category, impressions,
    reconcile} — one 30s break per spec on a 600s loop (content runtime tiles
    the remainder). Each break's decision run places that spec's creative
    (distinct IAB categories required when two breaks are adjacent, PRD §3.6).

    Chain: validated loop -> campaigns ACTIVE -> decision runs -> LOCKED ->
    channel LIVE -> PUBLISHED -> breaks AIRED -> platform ACTIVE -> agreement
    ACTIVE -> AD_IMPRESSION events on the platform -> reconcile flagged breaks
    -> clock to the month after the period -> report created (DRAFT) ->
    generate-provisional (PROVISIONAL) -> optional finalize.
    """
    n = len(decision_specs)
    assert n in (1, 2), "scenario tiles one or two 30s breaks"
    ctx = setup_validated_loop(
        channel_name="Ch Rev", loop_duration=600, break_durations=tuple(30 for _ in decision_specs),
        broadcast_date=broadcast_date,
    )
    campaigns = []
    decisions = []
    for i, spec in enumerate(decision_specs):
        campaign, creative = create_active_campaign(
            cpm_cents=spec["cpm_cents"], iab_category=spec["iab_category"],
            advertiser_name=f"Adv-{i}", brand=f"Brand-{i}",
        )
        campaigns.append((campaign, creative))
    for i, brk in enumerate(ctx["breaks"]):
        rows = run_decision_run(brk["id"])
        decisions.append(rows[0])
    ctx["loop"] = get_success_data(api_client.loop_lock(ctx["loop"]["id"], PROGRAMMER))
    go_live(ctx["channel"]["id"])
    ctx["loop"] = publish_loop(ctx["loop"]["id"], ctx["channel"]["id"])
    for brk in ctx["breaks"]:
        get_success_data(api_client.break_mark_aired(brk["id"], PROGRAMMER))
    platform = setup_platform()
    agreement = setup_active_agreement(
        ctx["channel"]["id"], platform["id"],
        below=agreement_below, above=agreement_above,
        threshold=agreement_threshold, minimum_guarantee=agreement_min,
    )
    for i, spec in enumerate(decision_specs):
        post_impressions(
            ctx["channel"]["id"], platform["id"],
            ctx["breaks"][i]["id"], decisions[i]["id"], spec["impressions"],
            occurred_at=f"{broadcast_date}T00:0{7 + i}:30Z", session=f"s{i}",
        )
    for i, spec in enumerate(decision_specs):
        if spec.get("reconcile", True):
            get_success_data(api_client.break_reconcile(ctx["breaks"][i]["id"], ADOPS))
    advance_clock(C.CLOCK_AFTER_PERIOD)
    report = get_success_data(
        api_client.create_revenue_report(
            factories.create_revenue_report_payload(
                ctx["channel"]["id"], platform["id"], period_month=period,
            ),
            make_analyst_headers(analyst_id),
        )
    )
    report = get_success_data(
        api_client.report_generate_provisional(report["id"], make_analyst_headers(analyst_id))
    )
    finalized = None
    if finalize:
        finalized = get_success_data(
            api_client.report_finalize(report["id"], make_controller_headers(controller_id))
        )
    ctx.update({
        "campaigns": campaigns,
        "decisions": decisions,
        "platform": platform,
        "agreement": agreement,
        "report": report,
        "finalized_report": finalized,
    })
    return ctx


def setup_elapsed_report(*, channel_name="Ch RP", analyst_id="fin-1",
                         period=C.PERIOD_MONTH, below=3000, above=4000,
                         threshold=100000, minimum_guarantee=0):
    """Minimal report with no loops/decisions (empty period): channel + ACTIVE
    platform + ACTIVE agreement + clock past period end + report DRAFT."""
    channel = create_channel(name=channel_name)
    platform = setup_platform()
    agreement = setup_active_agreement(
        channel["id"], platform["id"], below=below, above=above,
        threshold=threshold, minimum_guarantee=minimum_guarantee,
    )
    advance_clock(C.CLOCK_AFTER_PERIOD)
    report = get_success_data(
        api_client.create_revenue_report(
            factories.create_revenue_report_payload(
                channel["id"], platform["id"], period_month=period,
            ),
            make_analyst_headers(analyst_id),
        )
    )
    return {"channel": channel, "platform": platform, "agreement": agreement,
            "report": report}


def setup_provisional_report(**kwargs):
    ctx = setup_elapsed_report(**kwargs)
    analyst_id = kwargs.get("analyst_id", "fin-1")
    ctx["report"] = get_success_data(
        api_client.report_generate_provisional(
            ctx["report"]["id"], make_analyst_headers(analyst_id)
        )
    )
    return ctx


def setup_finalized_report(**kwargs):
    ctx = setup_provisional_report(**kwargs)
    controller_id = kwargs.get("controller_id", "ctl-1")
    ctx["report"] = get_success_data(
        api_client.report_finalize(ctx["report"]["id"], make_controller_headers(controller_id))
    )
    return ctx


