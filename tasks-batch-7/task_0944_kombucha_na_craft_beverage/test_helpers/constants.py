# --- Label element sets (PRD section 3.1) ---
ALWAYS_REQUIRED_ELEMENTS = [
    "PRODUCT_NAME",
    "NET_CONTENTS",
    "INGREDIENTS",
    "PRODUCER_ADDRESS",
    "LOT_CODE",
    "BEST_BY",
]
NON_ALCOHOLIC_ELEMENTS = [
    "NON_ALCOHOLIC_STATEMENT",
    "CONTAINS_LESS_THAN_HALF_PERCENT_ALCOHOL",
]
ALCOHOLIC_ELEMENTS = [
    "ALCOHOL_CONTENT_STATEMENT",
    "GOVERNMENT_WARNING",
    "AGE_RESTRICTED",
]
PASTEURIZED_ELEMENTS = ["PASTEURIZED_STATEMENT"]
RAW_ELEMENTS = ["KEEP_REFRIGERATED", "LIVE_CULTURES"]


def required_label_elements(abv_class: str, pasteurized: bool):
    """The element codes a revision with this abv_class / pasteurized pair must carry."""
    required = list(ALWAYS_REQUIRED_ELEMENTS)
    if abv_class == "NON_ALCOHOLIC":
        required += list(NON_ALCOHOLIC_ELEMENTS)
    else:
        required += list(ALCOHOLIC_ELEMENTS)
    if pasteurized:
        required += list(PASTEURIZED_ELEMENTS)
    else:
        required += list(RAW_ELEMENTS)
    return required
