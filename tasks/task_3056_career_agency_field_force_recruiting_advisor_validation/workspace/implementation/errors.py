"""Error catalog for the Career Agency Field Force API.

Every error id below traces verbatim to a sentence in PRD.md (§2, §3) or to the
scaffold error catalogue (§1.6). No id is invented.
"""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


