"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / RBAC / existence
    ERR_MISSING_AUTH_HEADERS = "ERR_MISSING_AUTH_HEADERS"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State / OCC / shape
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"

    # Sensor
    ERR_POLL_INTERVAL_OUT_OF_RANGE = "ERR_POLL_INTERVAL_OUT_OF_RANGE"

    # Valve groups / pump
    ERR_VALVE_GROUP_INVALID = "ERR_VALVE_GROUP_INVALID"
    ERR_VALVE_GROUP_PUMP_MISMATCH = "ERR_VALVE_GROUP_PUMP_MISMATCH"
    ERR_PUMP_INTERLOCK_BUSY = "ERR_PUMP_INTERLOCK_BUSY"

    # Plans / windows
    ERR_PLAN_WINDOW_OVERLAP = "ERR_PLAN_WINDOW_OVERLAP"
    ERR_PRECONDITION_NOT_MET = "ERR_PRECONDITION_NOT_MET"

    # Quotas / overrides
    ERR_QUOTA_EXCEEDED = "ERR_QUOTA_EXCEEDED"
    ERR_OVERRIDE_AMOUNT_INVALID = "ERR_OVERRIDE_AMOUNT_INVALID"
    ERR_OVERRIDE_ALREADY_DECIDED = "ERR_OVERRIDE_ALREADY_DECIDED"

    # Feedback / bills
    ERR_FEEDBACK_ALREADY_RECORDED = "ERR_FEEDBACK_ALREADY_RECORDED"
    ERR_BILL_PERIOD_INVALID = "ERR_BILL_PERIOD_INVALID"
    ERR_BILL_STATE_CONFLICT = "ERR_BILL_STATE_CONFLICT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH_HEADERS: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_STALE_VERSION: 409,
    ApiErrorId.ERR_POLL_INTERVAL_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_VALVE_GROUP_INVALID: 422,
    ApiErrorId.ERR_VALVE_GROUP_PUMP_MISMATCH: 422,
    ApiErrorId.ERR_PUMP_INTERLOCK_BUSY: 409,
    ApiErrorId.ERR_PLAN_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_PRECONDITION_NOT_MET: 422,
    ApiErrorId.ERR_QUOTA_EXCEEDED: 422,
    ApiErrorId.ERR_OVERRIDE_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_OVERRIDE_ALREADY_DECIDED: 409,
    ApiErrorId.ERR_FEEDBACK_ALREADY_RECORDED: 409,
    ApiErrorId.ERR_BILL_PERIOD_INVALID: 422,
    ApiErrorId.ERR_BILL_STATE_CONFLICT: 409,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
