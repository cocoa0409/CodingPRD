def test_create_seller_returns_201_with_defaults(api):
    """PRD §3.1: "A freshly registered seller starts in `status` `ACTIVE`, with its
    cumulative-cash ledger `ytd_cash_paid_cents` at 0, its `requires_1099` flag
    false, and its `open_theft_reports` count at 0."

    Design: Corner/entities/create_seller_returns_201_with_defaults
    """
    data = validate_success(
        api.create_seller(
            {"legal_name": "New Seller", "id_type": "DRIVERS_LICENSE", "id_number": "DL-100"}, WM), 201
    )
    assert data["status"] == "ACTIVE", f"expected ACTIVE, got {data['status']}"
    assert data["ytd_cash_paid_cents"] == 0
    assert data["requires_1099"] is False
    assert data["open_theft_reports"] == 0


