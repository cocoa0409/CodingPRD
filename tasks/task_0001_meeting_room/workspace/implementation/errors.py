class ApiError(Exception):
    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


# Auth
ERR_AUTH_REQUIRED = ("ERR_AUTH_REQUIRED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)

# Request
ERR_BAD_REQUEST = ("ERR_BAD_REQUEST", 400)

# Not Found
ERR_ROOM_NOT_FOUND = ("ERR_ROOM_NOT_FOUND", 404)
ERR_BOOKING_NOT_FOUND = ("ERR_BOOKING_NOT_FOUND", 404)
ERR_WAITLIST_NOT_FOUND = ("ERR_WAITLIST_NOT_FOUND", 404)
ERR_SERIES_NOT_FOUND = ("ERR_SERIES_NOT_FOUND", 404)

# Concurrency
ERR_VERSION_CONFLICT = ("ERR_VERSION_CONFLICT", 409)

# State
ERR_ROOM_NOT_ACTIVE = ("ERR_ROOM_NOT_ACTIVE", 409)
ERR_INVALID_BOOKING_STATE = ("ERR_INVALID_BOOKING_STATE", 409)
ERR_INVALID_WAITLIST_STATE = ("ERR_INVALID_WAITLIST_STATE", 409)
ERR_INVALID_SERIES_STATE = ("ERR_INVALID_SERIES_STATE", 409)

# Temporal
ERR_INVALID_TIME_RANGE = ("ERR_INVALID_TIME_RANGE", 400)
ERR_BOOKING_TOO_SHORT = ("ERR_BOOKING_TOO_SHORT", 400)
ERR_BOOKING_TOO_LONG = ("ERR_BOOKING_TOO_LONG", 400)
ERR_BOOKING_IN_PAST = ("ERR_BOOKING_IN_PAST", 400)
