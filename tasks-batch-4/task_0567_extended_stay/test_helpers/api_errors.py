"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping we register it with the framework so validate_error()
auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
    ERR_MASTER_LEASE_NOT_ACTIVE = "ERR_MASTER_LEASE_NOT_ACTIVE"
    ERR_STAY_NOT_ACTIVE = "ERR_STAY_NOT_ACTIVE"
    ERR_UNIT_TIME_CONFLICT = "ERR_UNIT_TIME_CONFLICT"
    ERR_EMPLOYEE_DOUBLE_BOOKED = "ERR_EMPLOYEE_DOUBLE_BOOKED"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_MIN_TERM_NOT_MET = "ERR_MIN_TERM_NOT_MET"
    ERR_MASTER_LEASE_CAP_EXCEEDED = "ERR_MASTER_LEASE_CAP_EXCEEDED"
    ERR_DAMAGE_EXCEEDS_DEPOSIT = "ERR_DAMAGE_EXCEEDS_DEPOSIT"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_UNIT_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_MASTER_LEASE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_STAY_NOT_ACTIVE: 409,
    ApiErrorId.ERR_UNIT_TIME_CONFLICT: 409,
    ApiErrorId.ERR_EMPLOYEE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_MIN_TERM_NOT_MET: 422,
    ApiErrorId.ERR_MASTER_LEASE_CAP_EXCEEDED: 402,
    ApiErrorId.ERR_DAMAGE_EXCEEDS_DEPOSIT: 402,
    ApiErrorId.ERR_STALE_VERSION: 412,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
