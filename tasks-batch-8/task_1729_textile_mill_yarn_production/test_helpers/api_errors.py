"""Error IDs and HTTP status mapping (PRD §5 catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_QUALITY_GATE_FAILED = "ERR_QUALITY_GATE_FAILED"
    ERR_DUPLICATE_KEY = "ERR_DUPLICATE_KEY"
    ERR_WINDOW_CONFLICT = "ERR_WINDOW_CONFLICT"
    ERR_REFERENTIAL_VIOLATION = "ERR_REFERENTIAL_VIOLATION"
    ERR_INSUFFICIENT_CAPACITY = "ERR_INSUFFICIENT_CAPACITY"
    ERR_COUNT_OUT_OF_RANGE = "ERR_COUNT_OUT_OF_RANGE"
    ERR_SHADE_OUT_OF_BAND = "ERR_SHADE_OUT_OF_BAND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_SECOND_QUALITY_NOT_ALLOCATABLE = "ERR_SECOND_QUALITY_NOT_ALLOCATABLE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_QUALITY_GATE_FAILED: 422,
    ApiErrorId.ERR_DUPLICATE_KEY: 409,
    ApiErrorId.ERR_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_REFERENTIAL_VIOLATION: 422,
    ApiErrorId.ERR_INSUFFICIENT_CAPACITY: 422,
    ApiErrorId.ERR_COUNT_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_SHADE_OUT_OF_BAND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_SECOND_QUALITY_NOT_ALLOCATABLE: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
