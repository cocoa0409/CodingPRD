"""Error classes and error ID constants per the scaffold error catalog."""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


# Auth
ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
ERR_UNAUTHORIZED_ROLE = "ERR_UNAUTHORIZED_ROLE"
ERR_OWNERSHIP_MISMATCH = "ERR_OWNERSHIP_MISMATCH"

# Existence / input
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

# Concurrency
ERR_STALE_VERSION = "ERR_STALE_VERSION"

# State
ERR_APPLICATION_TERMINAL = "ERR_APPLICATION_TERMINAL"
