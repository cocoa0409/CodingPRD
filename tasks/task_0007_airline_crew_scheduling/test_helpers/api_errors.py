"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CROSS_ENTITY_STATE = "ERR_CROSS_ENTITY_STATE"
    ERR_FAA_DUTY_CAP_EXCEEDED = "ERR_FAA_DUTY_CAP_EXCEEDED"
    ERR_FAA_FLIGHT_CAP_EXCEEDED = "ERR_FAA_FLIGHT_CAP_EXCEEDED"
    ERR_CREW_REST_VIOLATION = "ERR_CREW_REST_VIOLATION"
    ERR_RANK_SEAT_MISMATCH = "ERR_RANK_SEAT_MISMATCH"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"
    ERR_PAIRING_OVERLAP = "ERR_PAIRING_OVERLAP"
    ERR_LEG_OVERLAP = "ERR_LEG_OVERLAP"
    ERR_DUPLICATE_BID = "ERR_DUPLICATE_BID"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_NO_RESERVE_AVAILABLE = "ERR_NO_RESERVE_AVAILABLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED.value: 401,
    ApiErrorId.ERR_FORBIDDEN.value: 403,
    ApiErrorId.ERR_NOT_FOUND.value: 404,
    ApiErrorId.ERR_INVALID_STATE.value: 409,
    ApiErrorId.ERR_CROSS_ENTITY_STATE.value: 409,
    ApiErrorId.ERR_FAA_DUTY_CAP_EXCEEDED.value: 422,
    ApiErrorId.ERR_FAA_FLIGHT_CAP_EXCEEDED.value: 422,
    ApiErrorId.ERR_CREW_REST_VIOLATION.value: 422,
    ApiErrorId.ERR_RANK_SEAT_MISMATCH.value: 422,
    ApiErrorId.ERR_INVALID_TIME_WINDOW.value: 422,
    ApiErrorId.ERR_PAIRING_OVERLAP.value: 422,
    ApiErrorId.ERR_LEG_OVERLAP.value: 422,
    ApiErrorId.ERR_DUPLICATE_BID.value: 409,
    ApiErrorId.ERR_STALE_VERSION.value: 412,
    ApiErrorId.ERR_NO_RESERVE_AVAILABLE.value: 422,
    ApiErrorId.ERR_INVALID_REQUEST.value: 400,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
