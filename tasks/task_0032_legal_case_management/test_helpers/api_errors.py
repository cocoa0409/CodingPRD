"""Error IDs and HTTP status mapping for the Legal Case Management API.

PRD §5 enumerates every error_id and the HTTP status it must surface. The
mapping is registered with the framework so ``validate_error()`` checks
both the error_id and the HTTP status code automatically.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / RBAC / existence
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_NOT_FOUND = "ERR_REFERENCED_NOT_FOUND"

    # State / archive
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CASE_ARCHIVED = "ERR_CASE_ARCHIVED"
    ERR_CASE_POSTURE_FROZEN = "ERR_CASE_POSTURE_FROZEN"

    # Conflict-of-interest / segregation / rank / lock
    ERR_CONFLICT_OF_INTEREST = "ERR_CONFLICT_OF_INTEREST"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_REVIEWER_RANK_INSUFFICIENT = "ERR_REVIEWER_RANK_INSUFFICIENT"
    ERR_DRAFT_LOCKED = "ERR_DRAFT_LOCKED"

    # Template / hearing / party
    ERR_TEMPLATE_CASE_TYPE_MISMATCH = "ERR_TEMPLATE_CASE_TYPE_MISMATCH"
    ERR_HEARING_INVALID_INTERVAL = "ERR_HEARING_INVALID_INTERVAL"
    ERR_HEARING_PAST_TIME = "ERR_HEARING_PAST_TIME"
    ERR_HEARING_ROOM_CONFLICT = "ERR_HEARING_ROOM_CONFLICT"
    ERR_LAWYER_SCHEDULE_CONFLICT = "ERR_LAWYER_SCHEDULE_CONFLICT"
    ERR_PARTY_NOT_VERIFIED = "ERR_PARTY_NOT_VERIFIED"

    # Custody / billing / time / claim
    ERR_CUSTODY_CHAIN_BROKEN = "ERR_CUSTODY_CHAIN_BROKEN"
    ERR_BILLING_MODE_INVALID = "ERR_BILLING_MODE_INVALID"
    ERR_TIME_ENTRY_ADJUSTMENT_INVALID = "ERR_TIME_ENTRY_ADJUSTMENT_INVALID"
    ERR_CLAIM_AMOUNT_INVALID = "ERR_CLAIM_AMOUNT_INVALID"

    # External events / OCC
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_PAYMENT_DUPLICATE = "ERR_PAYMENT_DUPLICATE"
    ERR_EVENT_PAYLOAD_INVALID = "ERR_EVENT_PAYLOAD_INVALID"
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"

    # Generic input validation
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CASE_ARCHIVED: 409,
    ApiErrorId.ERR_CASE_POSTURE_FROZEN: 409,
    ApiErrorId.ERR_CONFLICT_OF_INTEREST: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_REVIEWER_RANK_INSUFFICIENT: 403,
    ApiErrorId.ERR_DRAFT_LOCKED: 409,
    ApiErrorId.ERR_TEMPLATE_CASE_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_HEARING_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_HEARING_PAST_TIME: 422,
    ApiErrorId.ERR_HEARING_ROOM_CONFLICT: 409,
    ApiErrorId.ERR_LAWYER_SCHEDULE_CONFLICT: 409,
    ApiErrorId.ERR_PARTY_NOT_VERIFIED: 409,
    ApiErrorId.ERR_CUSTODY_CHAIN_BROKEN: 409,
    ApiErrorId.ERR_BILLING_MODE_INVALID: 422,
    ApiErrorId.ERR_TIME_ENTRY_ADJUSTMENT_INVALID: 422,
    ApiErrorId.ERR_CLAIM_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_PAYMENT_DUPLICATE: 409,
    ApiErrorId.ERR_EVENT_PAYLOAD_INVALID: 422,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 422,
}


# Register so validate_error() can cross-check HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
