"""Error catalog for the Federal Water Allocation API (PRD §5).

Every error identifier the contract declares, with the HTTP status each one
must carry. Registering the mapping with the shared validators lets
``validate_error`` cross-check the status automatically, so a test only has
to name the identifier it expects.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    """Declared error identifiers, grouped by the validation tier that emits them (PRD §2.9)."""

    # Tier 1-2: credentials and role authorization.
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Tier 3: request shape.
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # Tier 4: existence.
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # Tier 5: ownership and segregation of duties.
    ERR_OWNERSHIP_MISMATCH = "ERR_OWNERSHIP_MISMATCH"
    ERR_REVIEWER_CONFLICT = "ERR_REVIEWER_CONFLICT"

    # Tier 6: state gates.
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CONTRACT_SUSPENDED = "ERR_CONTRACT_SUSPENDED"
    ERR_YEAR_NOT_ANNOUNCED = "ERR_YEAR_NOT_ANNOUNCED"
    ERR_YEAR_CLOSED = "ERR_YEAR_CLOSED"
    ERR_NO_PUBLISHED_ANNOUNCEMENT = "ERR_NO_PUBLISHED_ANNOUNCEMENT"
    ERR_REVISION_LIMIT_EXCEEDED = "ERR_REVISION_LIMIT_EXCEEDED"
    ERR_COMPLIANCE_HOLD = "ERR_COMPLIANCE_HOLD"

    # Tier 7: environmental and regulatory safety.
    ERR_ENV_MIN_FLOW_VIOLATION = "ERR_ENV_MIN_FLOW_VIOLATION"
    ERR_MAX_RELEASE_EXCEEDED = "ERR_MAX_RELEASE_EXCEEDED"
    ERR_FLOOD_CONTROL_REQUIRED = "ERR_FLOOD_CONTROL_REQUIRED"
    ERR_PULSE_WINDOW_OVERLAP = "ERR_PULSE_WINDOW_OVERLAP"

    # Tier 8: business constraints.
    ERR_OUTLET_CAPACITY_EXCEEDED = "ERR_OUTLET_CAPACITY_EXCEEDED"
    ERR_INSUFFICIENT_STORAGE = "ERR_INSUFFICIENT_STORAGE"
    ERR_RESERVOIR_ALREADY_EXISTS = "ERR_RESERVOIR_ALREADY_EXISTS"
    ERR_DUPLICATE_CONTRACT_NUMBER = "ERR_DUPLICATE_CONTRACT_NUMBER"
    ERR_DUPLICATE_WATER_YEAR = "ERR_DUPLICATE_WATER_YEAR"
    ERR_DUPLICATE_REVENUE_PERIOD = "ERR_DUPLICATE_REVENUE_PERIOD"
    ERR_DUPLICATE_REVIEW = "ERR_DUPLICATE_REVIEW"
    ERR_ALREADY_RATIFIED = "ERR_ALREADY_RATIFIED"
    ERR_ACTIVATION_CONFLICT = "ERR_ACTIVATION_CONFLICT"
    ERR_INVALID_QUANTITY = "ERR_INVALID_QUANTITY"

    # Tier 9: temporal windows.
    ERR_SCHEDULE_IN_PAST = "ERR_SCHEDULE_IN_PAST"
    ERR_RELEASE_WINDOW_INVALID = "ERR_RELEASE_WINDOW_INVALID"
    ERR_OBJECTION_WINDOW_OPEN = "ERR_OBJECTION_WINDOW_OPEN"
    ERR_OBJECTION_WINDOW_CLOSED = "ERR_OBJECTION_WINDOW_CLOSED"

    # Tier 10: cross-entity referential state.
    ERR_REVIEW_PENDING = "ERR_REVIEW_PENDING"

    # Tier 11: fiscal sufficiency.
    ERR_ALLOCATION_EXCEEDED = "ERR_ALLOCATION_EXCEEDED"

    # Optimistic concurrency (PRD §2.7).
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_OWNERSHIP_MISMATCH: 403,
    ApiErrorId.ERR_REVIEWER_CONFLICT: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CONTRACT_SUSPENDED: 409,
    ApiErrorId.ERR_YEAR_NOT_ANNOUNCED: 409,
    ApiErrorId.ERR_YEAR_CLOSED: 409,
    ApiErrorId.ERR_NO_PUBLISHED_ANNOUNCEMENT: 409,
    ApiErrorId.ERR_REVISION_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_COMPLIANCE_HOLD: 409,
    ApiErrorId.ERR_ENV_MIN_FLOW_VIOLATION: 422,
    ApiErrorId.ERR_MAX_RELEASE_EXCEEDED: 422,
    ApiErrorId.ERR_FLOOD_CONTROL_REQUIRED: 422,
    ApiErrorId.ERR_PULSE_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_OUTLET_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_INSUFFICIENT_STORAGE: 422,
    ApiErrorId.ERR_RESERVOIR_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_DUPLICATE_CONTRACT_NUMBER: 409,
    ApiErrorId.ERR_DUPLICATE_WATER_YEAR: 409,
    ApiErrorId.ERR_DUPLICATE_REVENUE_PERIOD: 409,
    ApiErrorId.ERR_DUPLICATE_REVIEW: 409,
    ApiErrorId.ERR_ALREADY_RATIFIED: 409,
    ApiErrorId.ERR_ACTIVATION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_QUANTITY: 400,
    ApiErrorId.ERR_SCHEDULE_IN_PAST: 422,
    ApiErrorId.ERR_RELEASE_WINDOW_INVALID: 422,
    ApiErrorId.ERR_OBJECTION_WINDOW_OPEN: 409,
    ApiErrorId.ERR_OBJECTION_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_REVIEW_PENDING: 409,
    ApiErrorId.ERR_ALLOCATION_EXCEEDED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
