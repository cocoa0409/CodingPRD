"""Error IDs and HTTP status mapping (PRD Section 5).

After defining the mapping, it is registered with the framework so that
validate_error() can auto-check HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_ASSIGNED_AGENT = "ERR_NOT_ASSIGNED_AGENT"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LIVE_MONITORING_BLOCKS_CANCEL = "ERR_LIVE_MONITORING_BLOCKS_CANCEL"
    ERR_911_NOT_AUTHORIZED = "ERR_911_NOT_AUTHORIZED"
    ERR_CONTRACT_NOT_MONITORING = "ERR_CONTRACT_NOT_MONITORING"
    ERR_ESCALATION_ORDER = "ERR_ESCALATION_ORDER"
    ERR_NO_SHIFT_COVERAGE = "ERR_NO_SHIFT_COVERAGE"
    ERR_SHIFT_OVERLAP = "ERR_SHIFT_OVERLAP"
    ERR_HOLD_OVERLAP = "ERR_HOLD_OVERLAP"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_TEMPORAL_NOT_DUE = "ERR_TEMPORAL_NOT_DUE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ENROLL_PRECONDITION = "ERR_ENROLL_PRECONDITION"
    ERR_CONTACT_TREE_INVALID = "ERR_CONTACT_TREE_INVALID"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_ASSIGNED_AGENT: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LIVE_MONITORING_BLOCKS_CANCEL: 409,
    ApiErrorId.ERR_911_NOT_AUTHORIZED: 409,
    ApiErrorId.ERR_CONTRACT_NOT_MONITORING: 409,
    ApiErrorId.ERR_ESCALATION_ORDER: 409,
    ApiErrorId.ERR_NO_SHIFT_COVERAGE: 409,
    ApiErrorId.ERR_SHIFT_OVERLAP: 409,
    ApiErrorId.ERR_HOLD_OVERLAP: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_TEMPORAL_NOT_DUE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ENROLL_PRECONDITION: 422,
    ApiErrorId.ERR_CONTACT_TREE_INVALID: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
