# "a missing `Flight` reports `ERR_FLIGHT_NOT_FOUND`, a missing
# `ProductionBatch` reports `ERR_BATCH_NOT_FOUND`, a missing `Cart` reports
# `ERR_CART_NOT_FOUND`" and every other entity reports `ERR_RESOURCE_NOT_FOUND`
# (PRD §2.6).
PATH_NOT_FOUND_ERRORS: List[ApiErrorId] = [
    ApiErrorId.ERR_FLIGHT_NOT_FOUND,
    ApiErrorId.ERR_BATCH_NOT_FOUND,
    ApiErrorId.ERR_CART_NOT_FOUND,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND,
]

# Register with the framework so `validate_error()` cross-checks the HTTP status
# of every identifier it is handed.
set_error_http_status_map({str(k.value): v for k, v in HTTP_STATUS_CODES.items()})
