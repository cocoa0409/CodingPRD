"""Every error identifier in the PRD's error catalogue, with its HTTP status.

The status map is registered with the shared validator layer at import time so
`validate_error(response, ApiErrorId.X)` can check the status without each test
restating it.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Authentication / authorization
    UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ROLE_NOT_PERMITTED = "ERR_ROLE_NOT_PERMITTED"
    UNIT_SCOPE_VIOLATION = "ERR_UNIT_SCOPE_VIOLATION"

    # Payload shape
    INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # Path resolution
    UNIT_NOT_FOUND = "ERR_UNIT_NOT_FOUND"
    STANDARD_NOT_FOUND = "ERR_STANDARD_NOT_FOUND"
    CREDENTIAL_NOT_FOUND = "ERR_CREDENTIAL_NOT_FOUND"
    ASSET_NOT_FOUND = "ERR_ASSET_NOT_FOUND"
    REVIEW_NOT_FOUND = "ERR_REVIEW_NOT_FOUND"
    REFERRAL_NOT_FOUND = "ERR_REFERRAL_NOT_FOUND"
    RESERVATION_NOT_FOUND = "ERR_RESERVATION_NOT_FOUND"
    RUN_NOT_FOUND = "ERR_RUN_NOT_FOUND"
    ADMISSION_NOT_FOUND = "ERR_ADMISSION_NOT_FOUND"
    MILK_BATCH_NOT_FOUND = "ERR_MILK_BATCH_NOT_FOUND"
    ESCALATION_NOT_FOUND = "ERR_ESCALATION_NOT_FOUND"
    REPORT_NOT_FOUND = "ERR_REPORT_NOT_FOUND"
    ENROLLMENT_NOT_FOUND = "ERR_ENROLLMENT_NOT_FOUND"

    # Optimistic concurrency
    UNIT_VERSION_CONFLICT = "ERR_UNIT_VERSION_CONFLICT"
    ADMISSION_VERSION_CONFLICT = "ERR_ADMISSION_VERSION_CONFLICT"

    # State machines
    INVALID_STATE = "ERR_INVALID_STATE"
    DEPENDENT_STATE_INVALID = "ERR_DEPENDENT_STATE_INVALID"

    # Capability, capacity and clinical gates
    LEVEL_CAPABILITY_INSUFFICIENT = "ERR_LEVEL_CAPABILITY_INSUFFICIENT"
    UNIT_SUSPENDED = "ERR_UNIT_SUSPENDED"
    CREW_COMPOSITION_INVALID = "ERR_CREW_COMPOSITION_INVALID"
    ISOLETTE_NOT_SERVICEABLE = "ERR_ISOLETTE_NOT_SERVICEABLE"
    WEATHER_MINIMUMS_NOT_MET = "ERR_WEATHER_MINIMUMS_NOT_MET"
    STABILIZATION_INCOMPLETE = "ERR_STABILIZATION_INCOMPLETE"
    DEVELOPMENTAL_BUNDLE_INCOMPLETE = "ERR_DEVELOPMENTAL_BUNDLE_INCOMPLETE"
    MILK_NOT_ADMINISTRABLE = "ERR_MILK_NOT_ADMINISTRABLE"
    MILK_EXPIRED = "ERR_MILK_EXPIRED"
    NOT_ELIGIBLE_FOR_FOLLOWUP = "ERR_NOT_ELIGIBLE_FOR_FOLLOWUP"
    SURGE_NO_STAFFED_CAPACITY = "ERR_SURGE_NO_STAFFED_CAPACITY"
    MILK_VOLUME_EXCEEDED = "ERR_MILK_VOLUME_EXCEEDED"

    # Conflicts
    ISOLETTE_UNIT_MISMATCH = "ERR_ISOLETTE_UNIT_MISMATCH"
    MILK_LABEL_MISMATCH = "ERR_MILK_LABEL_MISMATCH"
    MATERNAL_TRANSFER_PREFERENCE = "ERR_MATERNAL_TRANSFER_PREFERENCE"
    DUPLICATE_ENROLLMENT = "ERR_DUPLICATE_ENROLLMENT"
    ISOLETTE_UNAVAILABLE = "ERR_ISOLETTE_UNAVAILABLE"
    ESCALATION_WINDOW_OVERLAP = "ERR_ESCALATION_WINDOW_OVERLAP"
    APPOINTMENT_OUTSIDE_WINDOW = "ERR_APPOINTMENT_OUTSIDE_WINDOW"
    PERIOD_INVALID = "ERR_PERIOD_INVALID"
    DUPLICATE_STANDARD = "ERR_DUPLICATE_STANDARD"
    REVIEW_ALREADY_OPEN = "ERR_REVIEW_ALREADY_OPEN"
    SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    NO_BED_AVAILABLE = "ERR_NO_BED_AVAILABLE"
    SURGE_THRESHOLD_NOT_MET = "ERR_SURGE_THRESHOLD_NOT_MET"
    CLINIC_DAY_FULL = "ERR_CLINIC_DAY_FULL"


