"""Error classes and error-id constants (from PRD §5 / scaffold §1.6)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog: id -> http status
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_CARRIER_INELIGIBLE = ("ERR_CARRIER_INELIGIBLE", 422)
ERR_PSYCH_CLEARANCE_MISSING = ("ERR_PSYCH_CLEARANCE_MISSING", 422)
ERR_INSURANCE_REVIEW_REQUIRED = ("ERR_INSURANCE_REVIEW_REQUIRED", 422)
ERR_COOLING_OFF_ACTIVE = ("ERR_COOLING_OFF_ACTIVE", 422)
ERR_MILESTONE_ORDER_VIOLATION = ("ERR_MILESTONE_ORDER_VIOLATION", 422)
ERR_DUPLICATE_MILESTONE = ("ERR_DUPLICATE_MILESTONE", 409)
ERR_BUDGET_EXCEEDED = ("ERR_BUDGET_EXCEEDED", 422)
ERR_INSUFFICIENT_ESCROW = ("ERR_INSUFFICIENT_ESCROW", 422)
ERR_SEGREGATION_OF_DUTIES = ("ERR_SEGREGATION_OF_DUTIES", 422)
ERR_PARENTAGE_JURISDICTION_BLOCKED = ("ERR_PARENTAGE_JURISDICTION_BLOCKED", 422)
ERR_MILESTONE_GATE_NOT_MET = ("ERR_MILESTONE_GATE_NOT_MET", 422)
ERR_JOURNEY_PRECONDITION = ("ERR_JOURNEY_PRECONDITION", 422)
ERR_VALIDATION_LIMIT = ("ERR_VALIDATION_LIMIT", 422)


def err(catalog_tuple, message=None):
    error_id, http_status = catalog_tuple
    return ApiError(error_id, http_status, message)
