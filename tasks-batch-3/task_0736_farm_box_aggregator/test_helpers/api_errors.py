    ERR_OFFERING_CYCLE_MISMATCH = "ERR_OFFERING_CYCLE_MISMATCH"
    ERR_NOT_LINE_OWNER = "ERR_NOT_LINE_OWNER"
    ERR_FARM_NOT_SNAP_AUTHORIZED = "ERR_FARM_NOT_SNAP_AUTHORIZED"
    ERR_CYCLE_WINDOW_CONFLICT = "ERR_CYCLE_WINDOW_CONFLICT"
    ERR_SLOT_CAPACITY_EXCEEDED = "ERR_SLOT_CAPACITY_EXCEEDED"
