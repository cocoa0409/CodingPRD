def missing_headers():
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, 400,
                    "X-User-ID and X-User-Role headers must be present and non-empty")


def invalid_request(msg="Invalid request body"):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def insufficient(msg="Role not permitted for this endpoint"):
    return ApiError(ERR_INSUFFICIENT_PERMISSIONS, 403, msg)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def provider_not_found(msg="attributed_provider_ref does not resolve to an existing provider"):
    return ApiError(ERR_PROVIDER_NOT_FOUND, 404, msg)


def stale_version(msg="Expected version does not match current version"):
    return ApiError(ERR_STALE_VERSION, 412, msg)


def invalid_state(msg="State machine forbids the transition"):
    return ApiError(ERR_INVALID_STATE, 409, msg)
