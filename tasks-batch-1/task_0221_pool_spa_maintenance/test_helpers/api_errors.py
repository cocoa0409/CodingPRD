"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_POOL_OWNER = "ERR_NOT_POOL_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FREQUENCY_PLAN_MISMATCH = "ERR_FREQUENCY_PLAN_MISMATCH"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_CRITICAL_REPAIR_BLOCKS_OPEN = "ERR_CRITICAL_REPAIR_BLOCKS_OPEN"
    ERR_OPEN_VISITS_BLOCK_CLOSE = "ERR_OPEN_VISITS_BLOCK_CLOSE"
    ERR_EMPTY_ROUTE = "ERR_EMPTY_ROUTE"
    ERR_ROUTE_AT_CAPACITY = "ERR_ROUTE_AT_CAPACITY"
    ERR_SKIP_REASON_REQUIRED = "ERR_SKIP_REASON_REQUIRED"
    ERR_NOTHING_TO_BILL = "ERR_NOTHING_TO_BILL"
    ERR_INVOICE_REFERENCE_MISMATCH = "ERR_INVOICE_REFERENCE_MISMATCH"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_POOL_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FREQUENCY_PLAN_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_CRITICAL_REPAIR_BLOCKS_OPEN: 409,
    ApiErrorId.ERR_OPEN_VISITS_BLOCK_CLOSE: 409,
    ApiErrorId.ERR_EMPTY_ROUTE: 409,
    ApiErrorId.ERR_ROUTE_AT_CAPACITY: 409,
    ApiErrorId.ERR_SKIP_REASON_REQUIRED: 422,
    ApiErrorId.ERR_NOTHING_TO_BILL: 422,
    ApiErrorId.ERR_INVOICE_REFERENCE_MISMATCH: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status codes.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
