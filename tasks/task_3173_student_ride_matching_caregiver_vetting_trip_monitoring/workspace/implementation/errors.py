"""Error identifiers, HTTP statuses and the ApiError exception.

Every error_id / http status pairing is transcribed from SCAFFOLD.yaml section
1.6 (Error Code Catalog) and PRD section 5.
"""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status=None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else STATUS_OF.get(error_id, 400)


