def _humanize(error_id):
    words = error_id[4:].replace("_", " ").lower() if error_id.startswith("ERR_") else error_id
    return words.capitalize() + "."


class ApiError(Exception):
    """Raised anywhere in the request path; app.py turns it into the envelope."""

    def __init__(self, error_id, message=None, http_status=None):
        self.error_id = error_id
        self.http_status = http_status or ERROR_HTTP.get(error_id, 400)
        self.message = message or _humanize(error_id)
        super().__init__("%s: %s" % (self.error_id, self.message))


def bad_request(message):
    return ApiError(ERR_INVALID_REQUEST, message)


def conflict(error_id, message=None):
    return ApiError(error_id, message)
