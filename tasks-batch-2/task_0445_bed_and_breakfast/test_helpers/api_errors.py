    ERR_BREAKFAST_OVER_PARTY = "ERR_BREAKFAST_OVER_PARTY"
    ERR_ROOM_DOUBLE_BOOKED = "ERR_ROOM_DOUBLE_BOOKED"
    ERR_TURNOVER_NOT_READY = "ERR_TURNOVER_NOT_READY"
    ERR_MIN_NIGHTS_NOT_MET = "ERR_MIN_NIGHTS_NOT_MET"
    ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"
    ERR_GIFT_INSUFFICIENT = "ERR_GIFT_INSUFFICIENT"
    ERR_DEPOSIT_NOT_MET = "ERR_DEPOSIT_NOT_MET"
