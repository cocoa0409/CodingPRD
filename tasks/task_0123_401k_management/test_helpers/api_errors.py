    ERR_STALE_DATA = "ERR_STALE_DATA"

    # Request format — PRD §5
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PLAN_CONFIG = "ERR_INVALID_PLAN_CONFIG"
    ERR_CLOCK_NOT_MONOTONIC = "ERR_CLOCK_NOT_MONOTONIC"


