class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or error_id.replace("ERR_", "").replace("_", " ").capitalize() + "."
        self.http_status = http_status or ERROR_HTTP.get(error_id, 400)


def bad_request(message="The request payload is malformed or violates a declared bound."):
    return ApiError("ERR_INVALID_REQUEST", message)
