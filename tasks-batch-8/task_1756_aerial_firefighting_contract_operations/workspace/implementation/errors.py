def err(error_id, message, http_status):
    return ApiError(error_id, message, http_status)


def bad_request(msg):
    return err(ERR_INVALID_REQUEST, msg, 400)


def invalid_state(msg):
    return err(ERR_INVALID_STATE, msg, 409)


def already_terminal(msg):
    return err(ERR_ALREADY_TERMINAL, msg, 409)
