    # --- Invoice / tax (PRD §3.9) ---
    ERR_THREE_WAY_MATCH_FAILED = "ERR_THREE_WAY_MATCH_FAILED"
    ERR_TAX_NONCOMPLIANT = "ERR_TAX_NONCOMPLIANT"

    # --- Requirement temporal (PRD §3.2) ---
    ERR_DELIVERY_DATE_TOO_EARLY = "ERR_DELIVERY_DATE_TOO_EARLY"

    # --- Contract (PRD §3.6, §2.9) ---
    ERR_CONTRACT_ALREADY_EXISTS = "ERR_CONTRACT_ALREADY_EXISTS"
    ERR_PAYMENT_ALREADY_APPLIED = "ERR_PAYMENT_ALREADY_APPLIED"
    ERR_SIGNATURE_ALREADY_COLLECTED = "ERR_SIGNATURE_ALREADY_COLLECTED"
    ERR_CLAUSE_TEMPLATE_INACTIVE = "ERR_CLAUSE_TEMPLATE_INACTIVE"


