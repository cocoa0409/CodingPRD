"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_SELLER_FROZEN = "ERR_SELLER_FROZEN"
    ERR_CATEGORY_MISMATCH = "ERR_CATEGORY_MISMATCH"
    ERR_GRADE_NOT_ACTIVE = "ERR_GRADE_NOT_ACTIVE"
    ERR_INVALID_WEIGHT = "ERR_INVALID_WEIGHT"
    ERR_CONTAINER_CAPACITY_EXCEEDED = "ERR_CONTAINER_CAPACITY_EXCEEDED"
    ERR_HEDGE_OVER_REALIZED = "ERR_HEDGE_OVER_REALIZED"
    ERR_TIN_REQUIRED_FOR_1099 = "ERR_TIN_REQUIRED_FOR_1099"
    ERR_STALE_CONTAINER_VERSION = "ERR_STALE_CONTAINER_VERSION"
    ERR_STALE_HEDGE_VERSION = "ERR_STALE_HEDGE_VERSION"
    ERR_NO_LINE_ITEMS = "ERR_NO_LINE_ITEMS"
    ERR_DUPLICATE_PAYOUT = "ERR_DUPLICATE_PAYOUT"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_SELLER_FROZEN: 409,
    ApiErrorId.ERR_CATEGORY_MISMATCH: 409,
    ApiErrorId.ERR_GRADE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_INVALID_WEIGHT: 422,
    ApiErrorId.ERR_CONTAINER_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_HEDGE_OVER_REALIZED: 409,
    ApiErrorId.ERR_TIN_REQUIRED_FOR_1099: 422,
    ApiErrorId.ERR_STALE_CONTAINER_VERSION: 412,
    ApiErrorId.ERR_STALE_HEDGE_VERSION: 412,
    ApiErrorId.ERR_NO_LINE_ITEMS: 409,
    ApiErrorId.ERR_DUPLICATE_PAYOUT: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
