"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CONSULTATION_NOT_ELIGIBLE = "ERR_CONSULTATION_NOT_ELIGIBLE"
    ERR_CONSENT_NOT_ACTIVE = "ERR_CONSENT_NOT_ACTIVE"
    ERR_DISPOSITION_NOT_ACTIVE = "ERR_DISPOSITION_NOT_ACTIVE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_SPECIMEN_NOT_OWNED = "ERR_SPECIMEN_NOT_OWNED"
    ERR_SPECIMEN_NOT_AVAILABLE = "ERR_SPECIMEN_NOT_AVAILABLE"
    ERR_PROVIDER_UNAVAILABLE = "ERR_PROVIDER_UNAVAILABLE"
    ERR_ROOM_UNAVAILABLE = "ERR_ROOM_UNAVAILABLE"
    ERR_INSUFFICIENT_MONITORING_VISITS = "ERR_INSUFFICIENT_MONITORING_VISITS"
    ERR_TANK_AT_CAPACITY = "ERR_TANK_AT_CAPACITY"
    ERR_DUPLICATE_ACTIVE_RESOURCE = "ERR_DUPLICATE_ACTIVE_RESOURCE"
    ERR_PERIOD_NOT_ELAPSED = "ERR_PERIOD_NOT_ELAPSED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CONSULTATION_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_CONSENT_NOT_ACTIVE: 422,
    ApiErrorId.ERR_DISPOSITION_NOT_ACTIVE: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_SPECIMEN_NOT_OWNED: 422,
    ApiErrorId.ERR_SPECIMEN_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_PROVIDER_UNAVAILABLE: 409,
    ApiErrorId.ERR_ROOM_UNAVAILABLE: 409,
    ApiErrorId.ERR_INSUFFICIENT_MONITORING_VISITS: 422,
    ApiErrorId.ERR_TANK_AT_CAPACITY: 409,
    ApiErrorId.ERR_DUPLICATE_ACTIVE_RESOURCE: 409,
    ApiErrorId.ERR_PERIOD_NOT_ELAPSED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
