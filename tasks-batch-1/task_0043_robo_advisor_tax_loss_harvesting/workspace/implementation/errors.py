class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status) per PRD §5 / SCAFFOLD §1.6
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_DUPLICATE_RESOURCE = ("ERR_DUPLICATE_RESOURCE", 409)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_ACCOUNT_NOT_OPERABLE = ("ERR_ACCOUNT_NOT_OPERABLE", 409)
ERR_NOT_REBALANCE_DUE = ("ERR_NOT_REBALANCE_DUE", 409)
ERR_STALE_ACCOUNT_VERSION = ("ERR_STALE_ACCOUNT_VERSION", 412)
ERR_NOT_A_LOSS_LOT = ("ERR_NOT_A_LOSS_LOT", 409)
ERR_SUBSTANTIALLY_IDENTICAL = ("ERR_SUBSTANTIALLY_IDENTICAL", 409)
ERR_REPLACEMENT_TOO_CORRELATED = ("ERR_REPLACEMENT_TOO_CORRELATED", 409)
ERR_SECURITY_DELISTED = ("ERR_SECURITY_DELISTED", 409)
ERR_NO_MODEL_FOR_SCORE = ("ERR_NO_MODEL_FOR_SCORE", 409)
ERR_MODEL_RETIRED = ("ERR_MODEL_RETIRED", 409)
ERR_QUARTER_ALREADY_REBALANCED = ("ERR_QUARTER_ALREADY_REBALANCED", 409)
ERR_OPEN_LOTS_REMAIN = ("ERR_OPEN_LOTS_REMAIN", 409)
ERR_TAX_YEAR_NOT_CLOSED = ("ERR_TAX_YEAR_NOT_CLOSED", 409)


def err(code_tuple, message=None):
    eid, status = code_tuple
    return ApiError(eid, status, message)
