def unauthenticated(msg="Missing or invalid X-User-ID / X-User-Role headers"):
    return ApiError(ERR_UNAUTHENTICATED, msg, 401)


def unauthorized(msg="Role not permitted for this endpoint"):
    return ApiError(ERR_UNAUTHORIZED, msg, 403)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, msg, 404)


def validation(msg="Field validation failed"):
    return ApiError(ERR_VALIDATION, msg, 400)


def invalid_state(msg="Entity not in a valid state for this transition"):
    return ApiError(ERR_INVALID_STATE, msg, 409)
