from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ONBOARDING_INCOMPLETE = "ERR_ONBOARDING_INCOMPLETE"
    ERR_OPEN_CLOSES_EXIST = "ERR_OPEN_CLOSES_EXIST"
    ERR_DECEMBER_CLOSE_NOT_FINAL = "ERR_DECEMBER_CLOSE_NOT_FINAL"
    ERR_CLOSE_FINALIZED = "ERR_CLOSE_FINALIZED"
    ERR_NO_LEDGER_ACCOUNTS = "ERR_NO_LEDGER_ACCOUNTS"
    ERR_CROSS_CLIENT_PARENT = "ERR_CROSS_CLIENT_PARENT"
    ERR_DUPLICATE_ACCOUNT_CODE = "ERR_DUPLICATE_ACCOUNT_CODE"
    ERR_DUPLICATE_PERIOD = "ERR_DUPLICATE_PERIOD"
    ERR_PAY_PERIOD_OVERLAP = "ERR_PAY_PERIOD_OVERLAP"
    ERR_COVENANT_BREACH = "ERR_COVENANT_BREACH"
    ERR_UNDERPAYMENT = "ERR_UNDERPAYMENT"
    ERR_MISSING_SCHEDULE_DATE = "ERR_MISSING_SCHEDULE_DATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_INVALID_TASK_STATUS = "ERR_INVALID_TASK_STATUS"
    ERR_NEGATIVE_AMOUNT = "ERR_NEGATIVE_AMOUNT"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ONBOARDING_INCOMPLETE: 409,
    ApiErrorId.ERR_OPEN_CLOSES_EXIST: 409,
    ApiErrorId.ERR_DECEMBER_CLOSE_NOT_FINAL: 409,
    ApiErrorId.ERR_CLOSE_FINALIZED: 409,
    ApiErrorId.ERR_NO_LEDGER_ACCOUNTS: 409,
    ApiErrorId.ERR_CROSS_CLIENT_PARENT: 422,
    ApiErrorId.ERR_DUPLICATE_ACCOUNT_CODE: 409,
    ApiErrorId.ERR_DUPLICATE_PERIOD: 409,
    ApiErrorId.ERR_PAY_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_COVENANT_BREACH: 422,
    ApiErrorId.ERR_UNDERPAYMENT: 422,
    ApiErrorId.ERR_MISSING_SCHEDULE_DATE: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_PERIOD: 422,
    ApiErrorId.ERR_INVALID_TASK_STATUS: 422,
    ApiErrorId.ERR_NEGATIVE_AMOUNT: 422,
    ApiErrorId.ERR_VALIDATION_LIMIT: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
