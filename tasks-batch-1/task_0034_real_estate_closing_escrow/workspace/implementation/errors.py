ERR_WIRE_SOD_VIOLATION = "ERR_WIRE_SOD_VIOLATION"
ERR_WIRE_NOT_LOCKED = "ERR_WIRE_NOT_LOCKED"
ERR_BUYER_WIRE_NOT_LOCKED = "ERR_BUYER_WIRE_NOT_LOCKED"
