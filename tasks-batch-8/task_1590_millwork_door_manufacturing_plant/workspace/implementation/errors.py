"""Error types and the full error-id -> HTTP status catalog for the Millwork Door Plant API."""


class ApiError(Exception):
    """Domain error carrying a machine-readable error_id and HTTP status."""

    def __init__(self, error_id, status, message):
        super().__init__(message)
        self.error_id = error_id
        self.status = status
        self.message = message


