    VENDOR_SUSPENDED = "ERR_VENDOR_SUSPENDED"
    PART_TYPE_NOT_OFFERED = "ERR_PART_TYPE_NOT_OFFERED"
    PART_TYPE_NOT_ALLOWED_BY_INSURER = "ERR_PART_TYPE_NOT_ALLOWED_BY_INSURER"
