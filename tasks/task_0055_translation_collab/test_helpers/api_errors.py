"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_SEGMENT_STATE = "ERR_INVALID_SEGMENT_STATE"
    ERR_INVALID_ASSIGNMENT_STATE = "ERR_INVALID_ASSIGNMENT_STATE"
    ERR_ASSIGNMENT_ALREADY_TAKEN = "ERR_ASSIGNMENT_ALREADY_TAKEN"
    ERR_PROJECT_NOT_READY = "ERR_PROJECT_NOT_READY"
    ERR_TEST_TRANSLATION_REQUIRED = "ERR_TEST_TRANSLATION_REQUIRED"
    ERR_TRANSLATOR_PROFILE_MISMATCH = "ERR_TRANSLATOR_PROFILE_MISMATCH"
    ERR_ACCEPT_WINDOW_EXPIRED = "ERR_ACCEPT_WINDOW_EXPIRED"
    ERR_SEGMENT_ALREADY_ASSIGNED = "ERR_SEGMENT_ALREADY_ASSIGNED"
    ERR_PACKAGE_SIZE_EXCEEDED = "ERR_PACKAGE_SIZE_EXCEEDED"
    ERR_TRANSLATOR_OVERLOADED = "ERR_TRANSLATOR_OVERLOADED"
    ERR_TERMINOLOGY_CONFLICT = "ERR_TERMINOLOGY_CONFLICT"
    ERR_REPETITION_PRICE_TOO_LOW = "ERR_REPETITION_PRICE_TOO_LOW"
    ERR_INVALID_PRICE = "ERR_INVALID_PRICE"
    ERR_DEADLINE_NOT_IN_FUTURE = "ERR_DEADLINE_NOT_IN_FUTURE"
    ERR_SAME_SOURCE_TARGET = "ERR_SAME_SOURCE_TARGET"
    ERR_EMPTY_PROJECT = "ERR_EMPTY_PROJECT"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"
    ERR_NO_ELIGIBLE_TRANSLATOR = "ERR_NO_ELIGIBLE_TRANSLATOR"
    ERR_QUALITY_SCORE_ALREADY_FINALIZED = "ERR_QUALITY_SCORE_ALREADY_FINALIZED"
    ERR_TERMINOLOGY_RESOLVE_REQUIRES_LOSER = "ERR_TERMINOLOGY_RESOLVE_REQUIRES_LOSER"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INVALID_SEGMENT_STATE: 409,
    ApiErrorId.ERR_INVALID_ASSIGNMENT_STATE: 409,
    ApiErrorId.ERR_ASSIGNMENT_ALREADY_TAKEN: 409,
    ApiErrorId.ERR_PROJECT_NOT_READY: 409,
    ApiErrorId.ERR_TEST_TRANSLATION_REQUIRED: 422,
    ApiErrorId.ERR_TRANSLATOR_PROFILE_MISMATCH: 422,
    ApiErrorId.ERR_ACCEPT_WINDOW_EXPIRED: 409,
    ApiErrorId.ERR_SEGMENT_ALREADY_ASSIGNED: 409,
    ApiErrorId.ERR_PACKAGE_SIZE_EXCEEDED: 422,
    ApiErrorId.ERR_TRANSLATOR_OVERLOADED: 422,
    ApiErrorId.ERR_TERMINOLOGY_CONFLICT: 409,
    ApiErrorId.ERR_REPETITION_PRICE_TOO_LOW: 422,
    ApiErrorId.ERR_INVALID_PRICE: 422,
    ApiErrorId.ERR_DEADLINE_NOT_IN_FUTURE: 422,
    ApiErrorId.ERR_SAME_SOURCE_TARGET: 422,
    ApiErrorId.ERR_EMPTY_PROJECT: 422,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_TRANSLATOR: 409,
    ApiErrorId.ERR_QUALITY_SCORE_ALREADY_FINALIZED: 409,
    ApiErrorId.ERR_TERMINOLOGY_RESOLVE_REQUIRES_LOSER: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
