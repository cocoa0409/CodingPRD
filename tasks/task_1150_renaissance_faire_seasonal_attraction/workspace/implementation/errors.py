def not_found(err_id, what):
    return ApiError(err_id, 404, "%s not found" % what)


def invalid(msg):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def conflict(err_id, msg):
    return ApiError(err_id, 409, msg)
