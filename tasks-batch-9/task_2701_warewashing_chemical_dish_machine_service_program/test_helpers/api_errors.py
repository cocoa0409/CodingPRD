def ladder_rung(error_id: str) -> int:
    """Return the 1-based §2.8 ladder rung an error identifier sits on."""
    for index, rung in enumerate(RULE_LADDER, start=1):
        if error_id in rung:
            return index
    raise KeyError(f"{error_id} is not on the §2.8 rule ladder")
