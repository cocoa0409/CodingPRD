"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_COST_CENTER_FROZEN = "ERR_COST_CENTER_FROZEN"
    ERR_SPAN_LIMIT_EXCEEDED = "ERR_SPAN_LIMIT_EXCEEDED"
    ERR_HAS_DIRECT_REPORTS = "ERR_HAS_DIRECT_REPORTS"
    ERR_POSITION_NOT_FUNDED = "ERR_POSITION_NOT_FUNDED"
    ERR_POSITION_ALREADY_FILLED = "ERR_POSITION_ALREADY_FILLED"
    ERR_POSITION_NOT_FILLED = "ERR_POSITION_NOT_FILLED"
    ERR_EMPLOYEE_UNAVAILABLE = "ERR_EMPLOYEE_UNAVAILABLE"
    ERR_SALARY_OUT_OF_BAND = "ERR_SALARY_OUT_OF_BAND"
    ERR_INCUMBENCY_OVERLAP = "ERR_INCUMBENCY_OVERLAP"
    ERR_FREEZE_WINDOW_OVERLAP = "ERR_FREEZE_WINDOW_OVERLAP"
    ERR_FTE_CAP_EXCEEDED = "ERR_FTE_CAP_EXCEEDED"
    ERR_BUDGET_EXCEEDED = "ERR_BUDGET_EXCEEDED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_COST_CENTER_FROZEN: 409,
    ApiErrorId.ERR_SPAN_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_HAS_DIRECT_REPORTS: 409,
    ApiErrorId.ERR_POSITION_NOT_FUNDED: 409,
    ApiErrorId.ERR_POSITION_ALREADY_FILLED: 409,
    ApiErrorId.ERR_POSITION_NOT_FILLED: 409,
    ApiErrorId.ERR_EMPLOYEE_UNAVAILABLE: 409,
    ApiErrorId.ERR_SALARY_OUT_OF_BAND: 409,
    ApiErrorId.ERR_INCUMBENCY_OVERLAP: 409,
    ApiErrorId.ERR_FREEZE_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_FTE_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_BUDGET_EXCEEDED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
