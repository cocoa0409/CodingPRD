"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ISOLATION_REQUIRED = "ERR_ISOLATION_REQUIRED"
    ERR_TELEMETRY_REQUIRED = "ERR_TELEMETRY_REQUIRED"
    ERR_COHORT_CONFLICT = "ERR_COHORT_CONFLICT"
    ERR_BED_NOT_AVAILABLE = "ERR_BED_NOT_AVAILABLE"
    ERR_SAME_BED = "ERR_SAME_BED"
    ERR_OPEN_BARRIERS = "ERR_OPEN_BARRIERS"
    ERR_NO_ELIGIBLE_BED = "ERR_NO_ELIGIBLE_BED"
    ERR_BED_NOT_DIRTY = "ERR_BED_NOT_DIRTY"
    ERR_EVS_TASK_EXISTS = "ERR_EVS_TASK_EXISTS"
    ERR_BED_OCCUPIED = "ERR_BED_OCCUPIED"
    ERR_STALE_BED_VERSION = "ERR_STALE_BED_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ISOLATION_REQUIRED: 409,
    ApiErrorId.ERR_TELEMETRY_REQUIRED: 409,
    ApiErrorId.ERR_COHORT_CONFLICT: 409,
    ApiErrorId.ERR_BED_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_SAME_BED: 409,
    ApiErrorId.ERR_OPEN_BARRIERS: 409,
    ApiErrorId.ERR_NO_ELIGIBLE_BED: 409,
    ApiErrorId.ERR_BED_NOT_DIRTY: 409,
    ApiErrorId.ERR_EVS_TASK_EXISTS: 409,
    ApiErrorId.ERR_BED_OCCUPIED: 409,
    ApiErrorId.ERR_STALE_BED_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
