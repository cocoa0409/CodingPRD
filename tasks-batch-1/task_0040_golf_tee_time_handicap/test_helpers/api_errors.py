"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_BOOKING_OWNER = "ERR_NOT_BOOKING_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TEE_TIME_CLOSED = "ERR_TEE_TIME_CLOSED"
    ERR_DUPLICATE_BOOKING = "ERR_DUPLICATE_BOOKING"
    ERR_GOLFER_TIME_CONFLICT = "ERR_GOLFER_TIME_CONFLICT"
    ERR_SLOT_START_PASSED = "ERR_SLOT_START_PASSED"
    ERR_SLOT_FULL_NO_STANDBY = "ERR_SLOT_FULL_NO_STANDBY"
    ERR_STALE_TEE_TIME_VERSION = "ERR_STALE_TEE_TIME_VERSION"
    ERR_REVISION_NOT_MONOTONIC = "ERR_REVISION_NOT_MONOTONIC"
    ERR_TEE_INTERVAL_CONFLICT = "ERR_TEE_INTERVAL_CONFLICT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_BOOKING_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_TEE_TIME_CLOSED: 409,
    ApiErrorId.ERR_DUPLICATE_BOOKING: 409,
    ApiErrorId.ERR_GOLFER_TIME_CONFLICT: 409,
    ApiErrorId.ERR_SLOT_START_PASSED: 409,
    ApiErrorId.ERR_SLOT_FULL_NO_STANDBY: 409,
    ApiErrorId.ERR_STALE_TEE_TIME_VERSION: 412,
    ApiErrorId.ERR_REVISION_NOT_MONOTONIC: 409,
    ApiErrorId.ERR_TEE_INTERVAL_CONFLICT: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
