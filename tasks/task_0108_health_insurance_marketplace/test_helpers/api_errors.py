"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_APPLICATION_OWNER = "ERR_NOT_APPLICATION_OWNER"

    # Existence — PRD §3.9 / §2.5
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State / concurrency — PRD §3.9
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"

    # Business — PRD §3.1, §3.2, §3.3, §3.4, §3.5, §3.6, §3.7, §3.9
    ERR_MISSING_PRIMARY_FILER = "ERR_MISSING_PRIMARY_FILER"
    ERR_COVERAGE_YEAR_INVALID = "ERR_COVERAGE_YEAR_INVALID"
    ERR_OUTSIDE_ENROLLMENT_WINDOW = "ERR_OUTSIDE_ENROLLMENT_WINDOW"
    ERR_PLAN_STATE_MISMATCH = "ERR_PLAN_STATE_MISMATCH"
    ERR_CSR_VARIANT_MISMATCH = "ERR_CSR_VARIANT_MISMATCH"
    ERR_OUTSIDE_SEP_WINDOW = "ERR_OUTSIDE_SEP_WINDOW"
    ERR_MAGI_NEGATIVE = "ERR_MAGI_NEGATIVE"
    ERR_NO_BENCHMARK_PLAN = "ERR_NO_BENCHMARK_PLAN"
    ERR_ENROLLMENT_ALREADY_EXISTS = "ERR_ENROLLMENT_ALREADY_EXISTS"
    ERR_PAYMENT_INSUFFICIENT = "ERR_PAYMENT_INSUFFICIENT"
    ERR_BENCHMARK_CONFLICT = "ERR_BENCHMARK_CONFLICT"
    ERR_SEP_WINDOW_EXPIRED = "ERR_SEP_WINDOW_EXPIRED"
    ERR_SEP_CONFLICT = "ERR_SEP_CONFLICT"
    ERR_INVOICE_ALREADY_PAID = "ERR_INVOICE_ALREADY_PAID"
    ERR_DEPENDENT_AGE_INVALID = "ERR_DEPENDENT_AGE_INVALID"


# PRD §5 Error Code Catalogue table.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_APPLICATION_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 409,
    ApiErrorId.ERR_MISSING_PRIMARY_FILER: 422,
    ApiErrorId.ERR_COVERAGE_YEAR_INVALID: 422,
    ApiErrorId.ERR_OUTSIDE_ENROLLMENT_WINDOW: 409,
    ApiErrorId.ERR_PLAN_STATE_MISMATCH: 422,
    ApiErrorId.ERR_CSR_VARIANT_MISMATCH: 422,
    ApiErrorId.ERR_OUTSIDE_SEP_WINDOW: 422,
    ApiErrorId.ERR_MAGI_NEGATIVE: 422,
    ApiErrorId.ERR_NO_BENCHMARK_PLAN: 422,
    ApiErrorId.ERR_ENROLLMENT_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_PAYMENT_INSUFFICIENT: 422,
    ApiErrorId.ERR_BENCHMARK_CONFLICT: 409,
    ApiErrorId.ERR_SEP_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_SEP_CONFLICT: 409,
    ApiErrorId.ERR_INVOICE_ALREADY_PAID: 409,
    ApiErrorId.ERR_DEPENDENT_AGE_INVALID: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
