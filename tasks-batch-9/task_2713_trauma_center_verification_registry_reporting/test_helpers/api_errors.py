    INVALID_CYCLE_STATE = "ERR_INVALID_CYCLE_STATE"
    INVALID_PI_STATE = "ERR_INVALID_PI_STATE"
    INVALID_DEFICIENCY_STATE = "ERR_INVALID_DEFICIENCY_STATE"
    INVALID_ACTION_STATE = "ERR_INVALID_ACTION_STATE"
    INVALID_AGREEMENT_STATE = "ERR_INVALID_AGREEMENT_STATE"
    INVALID_OUTREACH_STATE = "ERR_INVALID_OUTREACH_STATE"

    # Business safety
    POSTURE_SUSPENDED = "ERR_POSTURE_SUSPENDED"
    DICTIONARY_CRITICAL_VIOLATION = "ERR_DICTIONARY_CRITICAL_VIOLATION"
    ABSTRACTION_NOT_VALIDATED = "ERR_ABSTRACTION_NOT_VALIDATED"
