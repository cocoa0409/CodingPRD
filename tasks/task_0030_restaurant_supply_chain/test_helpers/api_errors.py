"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / RBAC / existence
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_INVALID_ROLE = "ERR_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # State / OCC
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"

    # Store / order rules
    ERR_CATALOG_PERMISSION_DENIED = "ERR_CATALOG_PERMISSION_DENIED"
    ERR_ORDER_WINDOW_CLOSED = "ERR_ORDER_WINDOW_CLOSED"
    ERR_ORDER_CUTOFF_PASSED = "ERR_ORDER_CUTOFF_PASSED"
    ERR_QUANTITY_OUT_OF_RANGE = "ERR_QUANTITY_OUT_OF_RANGE"

    # Production / shelf life / equipment
    ERR_EQUIPMENT_CAPACITY_EXCEEDED = "ERR_EQUIPMENT_CAPACITY_EXCEEDED"
    ERR_SHELF_LIFE_INSUFFICIENT = "ERR_SHELF_LIFE_INSUFFICIENT"

    # Delivery / vehicle
    ERR_VEHICLE_NOT_AVAILABLE = "ERR_VEHICLE_NOT_AVAILABLE"
    ERR_VEHICLE_CAPACITY_EXCEEDED = "ERR_VEHICLE_CAPACITY_EXCEEDED"
    ERR_TEMPERATURE_ZONE_INCOMPATIBLE = "ERR_TEMPERATURE_ZONE_INCOMPATIBLE"
    ERR_DELIVERY_WINDOW_OVERLAP = "ERR_DELIVERY_WINDOW_OVERLAP"
    ERR_BATCH_NOT_READY = "ERR_BATCH_NOT_READY"
    ERR_DRIVER_MISMATCH = "ERR_DRIVER_MISMATCH"

    # Inventory / disposal
    ERR_TIER3_DISPOSAL_REQUIRED = "ERR_TIER3_DISPOSAL_REQUIRED"

    # Loss / fiscal
    ERR_RESPONSIBILITY_REQUIRED = "ERR_RESPONSIBILITY_REQUIRED"
    ERR_LOSS_EXCEEDS_ON_HAND = "ERR_LOSS_EXCEEDS_ON_HAND"
    ERR_INVESTIGATION_PENDING = "ERR_INVESTIGATION_PENDING"

    # Replenishment
    ERR_REPLENISHMENT_CYCLE_NOT_ELAPSED = "ERR_REPLENISHMENT_CYCLE_NOT_ELAPSED"
    ERR_REPLENISHMENT_DUPLICATE = "ERR_REPLENISHMENT_DUPLICATE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 409,
    ApiErrorId.ERR_CATALOG_PERMISSION_DENIED: 422,
    ApiErrorId.ERR_ORDER_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_ORDER_CUTOFF_PASSED: 422,
    ApiErrorId.ERR_QUANTITY_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_EQUIPMENT_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_SHELF_LIFE_INSUFFICIENT: 422,
    ApiErrorId.ERR_VEHICLE_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_VEHICLE_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_TEMPERATURE_ZONE_INCOMPATIBLE: 422,
    ApiErrorId.ERR_DELIVERY_WINDOW_OVERLAP: 422,
    ApiErrorId.ERR_BATCH_NOT_READY: 422,
    ApiErrorId.ERR_DRIVER_MISMATCH: 403,
    ApiErrorId.ERR_TIER3_DISPOSAL_REQUIRED: 422,
    ApiErrorId.ERR_RESPONSIBILITY_REQUIRED: 422,
    ApiErrorId.ERR_LOSS_EXCEEDS_ON_HAND: 422,
    ApiErrorId.ERR_INVESTIGATION_PENDING: 422,
    ApiErrorId.ERR_REPLENISHMENT_CYCLE_NOT_ELAPSED: 422,
    ApiErrorId.ERR_REPLENISHMENT_DUPLICATE: 409,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
