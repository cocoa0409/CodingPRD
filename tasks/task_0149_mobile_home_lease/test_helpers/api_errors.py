"""Error IDs and HTTP status mapping — PRD §5 Error Code Catalogue.

After definition, the mapping is registered with the framework so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_FORBIDDEN_NOT_OWNER = "ERR_FORBIDDEN_NOT_OWNER"
    # Existence — PRD §2.5
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_REFERENCED_RESOURCE_NOT_FOUND = "ERR_REFERENCED_RESOURCE_NOT_FOUND"
    # State / OCC — PRD §2.8, §2.10
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"
    # Validation — PRD §2.10
    ERR_VALIDATION = "ERR_VALIDATION"
    # Eviction — PRD §3.6
    ERR_NO_CURE_PERMITTED = "ERR_NO_CURE_PERMITTED"
    ERR_CURE_WINDOW_EXPIRED = "ERR_CURE_WINDOW_EXPIRED"
    ERR_BALANCE_NOT_ZERO = "ERR_BALANCE_NOT_ZERO"
    # Home sale — PRD §3.7
    ERR_BUYER_INELIGIBLE = "ERR_BUYER_INELIGIBLE"
    ERR_HOME_NOT_RESIDENT_OWNED = "ERR_HOME_NOT_RESIDENT_OWNED"
    # Lease sign — PRD §3.2
    ERR_LOT_OCCUPIED = "ERR_LOT_OCCUPIED"
    # Conversion — PRD §3.8
    ERR_LOT_ALREADY_RESIDENT_OWNED = "ERR_LOT_ALREADY_RESIDENT_OWNED"
    ERR_BUYOUT_UNDERVALUED = "ERR_BUYOUT_UNDERVALUED"
    # Rent increase — PRD §3.5
    ERR_NOTICE_WINDOW_TOO_SHORT = "ERR_NOTICE_WINDOW_TOO_SHORT"
    ERR_RENT_INCREASE_BLOCKED_DURING_EVICTION = (
        "ERR_RENT_INCREASE_BLOCKED_DURING_EVICTION"
    )
    ERR_RENT_INCREASE_NONPOSITIVE = "ERR_RENT_INCREASE_NONPOSITIVE"
    # Concurrency — PRD §2.8
    ERR_LOT_OCCUPIED_BY_PENDING_OP = "ERR_LOT_OCCUPIED_BY_PENDING_OP"
    # Uniqueness — PRD §3.1
    ERR_DUPLICATE_VIN = "ERR_DUPLICATE_VIN"
    ERR_DUPLICATE_LOT_NUMBER = "ERR_DUPLICATE_LOT_NUMBER"


# PRD §5 — Error Code Catalogue (HTTP status mapping).
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_FORBIDDEN_NOT_OWNER: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_NO_CURE_PERMITTED: 409,
    ApiErrorId.ERR_CURE_WINDOW_EXPIRED: 409,
    ApiErrorId.ERR_BALANCE_NOT_ZERO: 409,
    ApiErrorId.ERR_BUYER_INELIGIBLE: 422,
    ApiErrorId.ERR_HOME_NOT_RESIDENT_OWNED: 409,
    ApiErrorId.ERR_LOT_OCCUPIED: 409,
    ApiErrorId.ERR_LOT_ALREADY_RESIDENT_OWNED: 409,
    ApiErrorId.ERR_BUYOUT_UNDERVALUED: 422,
    ApiErrorId.ERR_NOTICE_WINDOW_TOO_SHORT: 422,
    ApiErrorId.ERR_RENT_INCREASE_BLOCKED_DURING_EVICTION: 409,
    ApiErrorId.ERR_RENT_INCREASE_NONPOSITIVE: 422,
    ApiErrorId.ERR_LOT_OCCUPIED_BY_PENDING_OP: 409,
    ApiErrorId.ERR_DUPLICATE_VIN: 409,
    ApiErrorId.ERR_DUPLICATE_LOT_NUMBER: 409,
}


set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
