"""Error catalog and the APIError exception (PRD §5)."""

# Error IDs and their HTTP status codes, verbatim from the PRD error catalogue.
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
ERR_CERTIFICATE_OVERLAP = "ERR_CERTIFICATE_OVERLAP"
ERR_RETURN_PERIOD_OVERLAP = "ERR_RETURN_PERIOD_OVERLAP"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
ERR_NEXUS_NOT_REGISTERED = "ERR_NEXUS_NOT_REGISTERED"
ERR_TRANSACTION_LOCKED = "ERR_TRANSACTION_LOCKED"
ERR_AMOUNT_MISMATCH = "ERR_AMOUNT_MISMATCH"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_SELLER_SUSPENDED = "ERR_SELLER_SUSPENDED"
ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"

_HTTP = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNAUTHORIZED: 403,
    ERR_NOT_FOUND: 404,
    ERR_REFERENCE_NOT_FOUND: 404,
    ERR_INVALID_REQUEST: 400,
    ERR_DUPLICATE_RESOURCE: 409,
    ERR_INVALID_INTERVAL: 422,
    ERR_CERTIFICATE_OVERLAP: 409,
    ERR_RETURN_PERIOD_OVERLAP: 409,
    ERR_INVALID_STATE: 409,
    ERR_SEGREGATION_OF_DUTIES: 403,
    ERR_NEXUS_NOT_REGISTERED: 409,
    ERR_TRANSACTION_LOCKED: 409,
    ERR_AMOUNT_MISMATCH: 422,
    ERR_STALE_VERSION: 412,
    ERR_SELLER_SUSPENDED: 409,
    ERR_VALIDATION_FAILED: 422,
}


class APIError(Exception):
    def __init__(self, error_id, message="", http_status=None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = http_status if http_status is not None else _HTTP.get(error_id, 400)
