def err_missing_context():
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, 400,
                    "X-User-ID or X-User-Role header missing or malformed")


def err_invalid_request(msg="Malformed body, missing required field, unknown field, or invalid enum value"):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def err_forbidden(msg="Role not permitted for endpoint, or entity-backed role acting outside its scope"):
    return ApiError(ERR_FORBIDDEN_FOR_ROLE, 403, msg)


def err_not_found(msg="Referenced resource does not exist"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def err_invalid_state(msg="Target resource in a state that forbids the transition"):
    return ApiError(ERR_INVALID_STATE, 409, msg)
