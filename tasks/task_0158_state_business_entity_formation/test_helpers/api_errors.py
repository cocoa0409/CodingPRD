"""Error IDs and HTTP status mapping — PRD §5 Error Code Catalogue.

After definition, the mapping is registered with the framework so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_INVALID_ROLE = "ERR_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    # Existence — PRD §2.7
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # State — PRD §2.11
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ENTITY_NOT_ACTIVE = "ERR_ENTITY_NOT_ACTIVE"
    ERR_HAS_DEPENDENCIES = "ERR_HAS_DEPENDENCIES"
    # Uniqueness — PRD §3.1, §3.5, §3.6, §3.7
    ERR_DUPLICATE_LEGAL_NAME = "ERR_DUPLICATE_LEGAL_NAME"
    ERR_DUPLICATE_ANNUAL_REPORT = "ERR_DUPLICATE_ANNUAL_REPORT"
    ERR_DUPLICATE_FOREIGN_QUALIFICATION = "ERR_DUPLICATE_FOREIGN_QUALIFICATION"
    ERR_DUPLICATE_TAX_YEAR = "ERR_DUPLICATE_TAX_YEAR"
    # OCC — PRD §2.5
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    # Business safety / 422 — PRD §3.2, §3.3, §3.6, §3.7, §3.8
    ERR_INVALID_AGENT_ADDRESS = "ERR_INVALID_AGENT_ADDRESS"
    ERR_OWNER_UNDERAGE = "ERR_OWNER_UNDERAGE"
    ERR_STALE_COGS = "ERR_STALE_COGS"
    ERR_AGENT_STATE_MISMATCH = "ERR_AGENT_STATE_MISMATCH"
    ERR_TEMPLATE_TYPE_MISMATCH = "ERR_TEMPLATE_TYPE_MISMATCH"
    ERR_OWNERSHIP_NOT_100 = "ERR_OWNERSHIP_NOT_100"
    ERR_FOREIGN_STATE_IS_HOME = "ERR_FOREIGN_STATE_IS_HOME"
    ERR_INVALID_TAX_METHOD = "ERR_INVALID_TAX_METHOD"
    ERR_TAX_METHOD_MISMATCH = "ERR_TAX_METHOD_MISMATCH"
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"


# PRD §5 — Error Code Catalogue (HTTP status mapping)
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_INVALID_ROLE: 403,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ENTITY_NOT_ACTIVE: 409,
    ApiErrorId.ERR_HAS_DEPENDENCIES: 409,
    ApiErrorId.ERR_DUPLICATE_LEGAL_NAME: 409,
    ApiErrorId.ERR_DUPLICATE_ANNUAL_REPORT: 409,
    ApiErrorId.ERR_DUPLICATE_FOREIGN_QUALIFICATION: 409,
    ApiErrorId.ERR_DUPLICATE_TAX_YEAR: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_AGENT_ADDRESS: 422,
    ApiErrorId.ERR_OWNER_UNDERAGE: 422,
    ApiErrorId.ERR_STALE_COGS: 422,
    ApiErrorId.ERR_AGENT_STATE_MISMATCH: 422,
    ApiErrorId.ERR_TEMPLATE_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_OWNERSHIP_NOT_100: 422,
    ApiErrorId.ERR_FOREIGN_STATE_IS_HOME: 422,
    ApiErrorId.ERR_INVALID_TAX_METHOD: 422,
    ApiErrorId.ERR_TAX_METHOD_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_INPUT: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
