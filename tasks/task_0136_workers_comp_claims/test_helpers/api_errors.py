"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FROI_NOT_ACKNOWLEDGED = "ERR_FROI_NOT_ACKNOWLEDGED"
    ERR_INVALID_MTC = "ERR_INVALID_MTC"
    ERR_RATING_NOT_FINALIZED = "ERR_RATING_NOT_FINALIZED"
    ERR_STATUTE_EXPIRED = "ERR_STATUTE_EXPIRED"
    ERR_IME_WINDOW_CONFLICT = "ERR_IME_WINDOW_CONFLICT"
    ERR_RTW_WINDOW_CONFLICT = "ERR_RTW_WINDOW_CONFLICT"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_RESERVE_INSUFFICIENT = "ERR_RESERVE_INSUFFICIENT"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_CLAIM_VERSION = "ERR_STALE_CLAIM_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FROI_NOT_ACKNOWLEDGED: 409,
    ApiErrorId.ERR_INVALID_MTC: 422,
    ApiErrorId.ERR_RATING_NOT_FINALIZED: 409,
    ApiErrorId.ERR_STATUTE_EXPIRED: 422,
    ApiErrorId.ERR_IME_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_RTW_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_RESERVE_INSUFFICIENT: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_STALE_CLAIM_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
