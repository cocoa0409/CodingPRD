"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks HTTP status.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ALLERGEN_CONFLICT = "ERR_ALLERGEN_CONFLICT"
    ERR_EMPLOYEE_INACTIVE = "ERR_EMPLOYEE_INACTIVE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_VENUE_TIME_CONFLICT = "ERR_VENUE_TIME_CONFLICT"
    ERR_SESSION_BUFFER_CONFLICT = "ERR_SESSION_BUFFER_CONFLICT"
    ERR_DUPLICATE_SESSION_SLOT = "ERR_DUPLICATE_SESSION_SLOT"
    ERR_DUPLICATE_BADGE = "ERR_DUPLICATE_BADGE"
    ERR_VENUE_CAPACITY_EXCEEDED = "ERR_VENUE_CAPACITY_EXCEEDED"
    ERR_MENU_CYCLE_NOT_PUBLISHED = "ERR_MENU_CYCLE_NOT_PUBLISHED"
    ERR_EMPTY_MENU_CYCLE = "ERR_EMPTY_MENU_CYCLE"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_WALLET_INSUFFICIENT = "ERR_WALLET_INSUFFICIENT"
    ERR_VARIANCE_TOO_LARGE = "ERR_VARIANCE_TOO_LARGE"
    ERR_PO_NOT_RECEIVED = "ERR_PO_NOT_RECEIVED"
    ERR_SITE_SUSPENDED = "ERR_SITE_SUSPENDED"
    ERR_SESSION_HAS_SALES = "ERR_SESSION_HAS_SALES"
    ERR_SESSION_NOT_OPEN = "ERR_SESSION_NOT_OPEN"
    ERR_STALE_SITE_VERSION = "ERR_STALE_SITE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ALLERGEN_CONFLICT: 422,
    ApiErrorId.ERR_EMPLOYEE_INACTIVE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_VENUE_TIME_CONFLICT: 409,
    ApiErrorId.ERR_SESSION_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_SESSION_SLOT: 409,
    ApiErrorId.ERR_DUPLICATE_BADGE: 409,
    ApiErrorId.ERR_VENUE_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_MENU_CYCLE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_EMPTY_MENU_CYCLE: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_WALLET_INSUFFICIENT: 409,
    ApiErrorId.ERR_VARIANCE_TOO_LARGE: 409,
    ApiErrorId.ERR_PO_NOT_RECEIVED: 409,
    ApiErrorId.ERR_SITE_SUSPENDED: 409,
    ApiErrorId.ERR_SESSION_HAS_SALES: 409,
    ApiErrorId.ERR_SESSION_NOT_OPEN: 409,
    ApiErrorId.ERR_STALE_SITE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
