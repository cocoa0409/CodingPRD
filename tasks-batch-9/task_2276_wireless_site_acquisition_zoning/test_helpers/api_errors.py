    INVALID_PERMIT_STATE = "ERR_INVALID_PERMIT_STATE"
    INVALID_ORDER_STATE = "ERR_INVALID_ORDER_STATE"
    INVALID_PLAN_STATE = "ERR_INVALID_PLAN_STATE"
    MARKET_MISMATCH = "ERR_MARKET_MISMATCH"
    LANDLORD_MISMATCH = "ERR_LANDLORD_MISMATCH"
