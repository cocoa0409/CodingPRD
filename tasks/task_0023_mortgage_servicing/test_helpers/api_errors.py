"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_MEDIATION_REQUIRED = "ERR_MEDIATION_REQUIRED"
    ERR_NOTICE_PERIOD_VIOLATED = "ERR_NOTICE_PERIOD_VIOLATED"
    ERR_FORBEARANCE_WINDOW_EXCEEDED = "ERR_FORBEARANCE_WINDOW_EXCEEDED"
    ERR_DISBURSEMENT_IN_PAST = "ERR_DISBURSEMENT_IN_PAST"
    ERR_CUSHION_OVERLIMIT = "ERR_CUSHION_OVERLIMIT"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_PMI_NOT_ELIGIBLE_LTV = "ERR_PMI_NOT_ELIGIBLE_LTV"
    ERR_PMI_NOT_ELIGIBLE_HISTORY = "ERR_PMI_NOT_ELIGIBLE_HISTORY"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_MEDIATION_REQUIRED: 422,
    ApiErrorId.ERR_NOTICE_PERIOD_VIOLATED: 422,
    ApiErrorId.ERR_FORBEARANCE_WINDOW_EXCEEDED: 422,
    ApiErrorId.ERR_DISBURSEMENT_IN_PAST: 422,
    ApiErrorId.ERR_CUSHION_OVERLIMIT: 422,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_PMI_NOT_ELIGIBLE_LTV: 422,
    ApiErrorId.ERR_PMI_NOT_ELIGIBLE_HISTORY: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
