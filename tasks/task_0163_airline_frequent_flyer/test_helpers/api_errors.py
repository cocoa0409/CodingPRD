    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_GIFT_DAILY_CAP_EXCEEDED = "ERR_GIFT_DAILY_CAP_EXCEEDED"
    ERR_GIFT_BELOW_MINIMUM = "ERR_GIFT_BELOW_MINIMUM"

