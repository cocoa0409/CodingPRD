"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_GRADE_NOT_FUNDABLE = "ERR_GRADE_NOT_FUNDABLE"
    ERR_DISCLOSURE_MISSING = "ERR_DISCLOSURE_MISSING"
    ERR_LOAN_NOT_FUNDING = "ERR_LOAN_NOT_FUNDING"
    ERR_FUNDING_EXCEEDED = "ERR_FUNDING_EXCEEDED"
    ERR_DIVERSIFICATION_BREACH = "ERR_DIVERSIFICATION_BREACH"
    ERR_PAYMENT_EXCEEDS_PAYOFF = "ERR_PAYMENT_EXCEEDS_PAYOFF"
    ERR_RECOVERY_EXCEEDS_BASIS = "ERR_RECOVERY_EXCEEDS_BASIS"
    ERR_LATE_FEE_NOT_DUE = "ERR_LATE_FEE_NOT_DUE"
    ERR_STALE_LOAN_VERSION = "ERR_STALE_LOAN_VERSION"
    ERR_INSUFFICIENT_CAPITAL = "ERR_INSUFFICIENT_CAPITAL"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_GRADE_NOT_FUNDABLE: 422,
    ApiErrorId.ERR_DISCLOSURE_MISSING: 422,
    ApiErrorId.ERR_LOAN_NOT_FUNDING: 409,
    ApiErrorId.ERR_FUNDING_EXCEEDED: 422,
    ApiErrorId.ERR_DIVERSIFICATION_BREACH: 422,
    ApiErrorId.ERR_PAYMENT_EXCEEDS_PAYOFF: 422,
    ApiErrorId.ERR_RECOVERY_EXCEEDS_BASIS: 422,
    ApiErrorId.ERR_LATE_FEE_NOT_DUE: 409,
    ApiErrorId.ERR_STALE_LOAN_VERSION: 412,
    ApiErrorId.ERR_INSUFFICIENT_CAPITAL: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
