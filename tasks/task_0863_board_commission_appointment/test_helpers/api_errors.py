"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DISTRICT_REQUIRED = "ERR_DISTRICT_REQUIRED"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_STALE_SEAT_VERSION = "ERR_STALE_SEAT_VERSION"
    ERR_RESIDENCY_REQUIREMENT_NOT_MET = "ERR_RESIDENCY_REQUIREMENT_NOT_MET"
    ERR_SEAT_LIMIT_REACHED = "ERR_SEAT_LIMIT_REACHED"
    ERR_APPLICATION_WINDOW_CLOSED = "ERR_APPLICATION_WINDOW_CLOSED"
    ERR_TERM_OVERLAP = "ERR_TERM_OVERLAP"
    ERR_MEETING_TOO_CLOSE = "ERR_MEETING_TOO_CLOSE"
    ERR_MEETING_NOT_YET_DUE = "ERR_MEETING_NOT_YET_DUE"
    ERR_MEETING_NOT_HELD = "ERR_MEETING_NOT_HELD"
    ERR_QUORUM_NOT_MET = "ERR_QUORUM_NOT_MET"
    ERR_TERM_LIMIT_EXCEEDED = "ERR_TERM_LIMIT_EXCEEDED"
    ERR_ATTENDANCE_ABOVE_THRESHOLD = "ERR_ATTENDANCE_ABOVE_THRESHOLD"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DISTRICT_REQUIRED: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_STALE_SEAT_VERSION: 412,
    ApiErrorId.ERR_RESIDENCY_REQUIREMENT_NOT_MET: 422,
    ApiErrorId.ERR_SEAT_LIMIT_REACHED: 409,
    ApiErrorId.ERR_APPLICATION_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_TERM_OVERLAP: 409,
    ApiErrorId.ERR_MEETING_TOO_CLOSE: 409,
    ApiErrorId.ERR_MEETING_NOT_YET_DUE: 409,
    ApiErrorId.ERR_MEETING_NOT_HELD: 409,
    ApiErrorId.ERR_QUORUM_NOT_MET: 422,
    ApiErrorId.ERR_TERM_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_ATTENDANCE_ABOVE_THRESHOLD: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
