"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks the
HTTP status for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PROVIDER_NOT_ACCREDITED = "ERR_PROVIDER_NOT_ACCREDITED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_COMPLETION_OUT_OF_WINDOW = "ERR_COMPLETION_OUT_OF_WINDOW"
    ERR_CYCLE_OVERLAP = "ERR_CYCLE_OVERLAP"
    ERR_AUDIT_COOLDOWN_ACTIVE = "ERR_AUDIT_COOLDOWN_ACTIVE"
    ERR_AUDIT_ALREADY_OPEN = "ERR_AUDIT_ALREADY_OPEN"
    ERR_SAME_JURISDICTION = "ERR_SAME_JURISDICTION"
    ERR_REQUIREMENTS_NOT_MET = "ERR_REQUIREMENTS_NOT_MET"
    ERR_CARRYOVER_EXCEEDS_CAP = "ERR_CARRYOVER_EXCEEDS_CAP"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PROVIDER_NOT_ACCREDITED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_COMPLETION_OUT_OF_WINDOW: 422,
    ApiErrorId.ERR_CYCLE_OVERLAP: 409,
    ApiErrorId.ERR_AUDIT_COOLDOWN_ACTIVE: 409,
    ApiErrorId.ERR_AUDIT_ALREADY_OPEN: 409,
    ApiErrorId.ERR_SAME_JURISDICTION: 422,
    ApiErrorId.ERR_REQUIREMENTS_NOT_MET: 409,
    ApiErrorId.ERR_CARRYOVER_EXCEEDS_CAP: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
