_DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing or blank.",
    "ERR_FORBIDDEN_ROLE": "The caller's role may not perform this operation.",
    "ERR_IDENTITY_NOT_FOUND": "The caller identity does not resolve to a live record.",
    "ERR_INVALID_REQUEST": "The request body is malformed or fails a field constraint.",
    "ERR_PAGINATION_INVALID": "Pagination parameters are out of range.",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)
        self.message = message or _DEFAULT_MESSAGES.get(error_id, error_id)


def raise_error(error_id, message=None):
    raise ApiError(error_id, message)
