"""Error IDs and their HTTP status mapping (PRD §5), registered with the framework."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_STALE_CONTRIBUTOR_VERSION = "ERR_STALE_CONTRIBUTOR_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CONTRIBUTOR_SUSPENDED = "ERR_CONTRIBUTOR_SUSPENDED"
    ERR_CONTRIBUTOR_NOT_ACTIVE = "ERR_CONTRIBUTOR_NOT_ACTIVE"
    ERR_RELEASE_NOT_VERIFIED = "ERR_RELEASE_NOT_VERIFIED"
    ERR_EXCLUSIVITY_OVERLAP = "ERR_EXCLUSIVITY_OVERLAP"
    ERR_TAKEDOWN_HOLD_CONFLICT = "ERR_TAKEDOWN_HOLD_CONFLICT"
    ERR_NOT_SIMILAR_ENOUGH = "ERR_NOT_SIMILAR_ENOUGH"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_BELOW_PAYOUT_THRESHOLD = "ERR_BELOW_PAYOUT_THRESHOLD"
    ERR_NOT_YET_CLEARED = "ERR_NOT_YET_CLEARED"
    ERR_MISSING_REJECT_REASON = "ERR_MISSING_REJECT_REASON"
    ERR_MISSING_SIMILAR_TARGET = "ERR_MISSING_SIMILAR_TARGET"
    ERR_RELEASE_REQUIRED = "ERR_RELEASE_REQUIRED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_STALE_CONTRIBUTOR_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CONTRIBUTOR_SUSPENDED: 403,
    ApiErrorId.ERR_CONTRIBUTOR_NOT_ACTIVE: 409,
    ApiErrorId.ERR_RELEASE_NOT_VERIFIED: 422,
    ApiErrorId.ERR_EXCLUSIVITY_OVERLAP: 409,
    ApiErrorId.ERR_TAKEDOWN_HOLD_CONFLICT: 409,
    ApiErrorId.ERR_NOT_SIMILAR_ENOUGH: 422,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_BELOW_PAYOUT_THRESHOLD: 422,
    ApiErrorId.ERR_NOT_YET_CLEARED: 409,
    ApiErrorId.ERR_MISSING_REJECT_REASON: 422,
    ApiErrorId.ERR_MISSING_SIMILAR_TARGET: 422,
    ApiErrorId.ERR_RELEASE_REQUIRED: 422,
}

# Register with the framework so validate_error() auto-checks the HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
