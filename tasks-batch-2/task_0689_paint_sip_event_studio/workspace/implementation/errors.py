"""Error catalog and the ApiError exception."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error IDs -> HTTP status (from SCAFFOLD §1.6 / PRD §5)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_REFERENCE_NOT_FOUND = ("ERR_REFERENCE_NOT_FOUND", 422)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_BOOKING_MODE_MISMATCH = ("ERR_BOOKING_MODE_MISMATCH", 422)
ERR_ARTIST_DOUBLE_BOOKED = ("ERR_ARTIST_DOUBLE_BOOKED", 409)
ERR_STUDIO_TIME_CONFLICT = ("ERR_STUDIO_TIME_CONFLICT", 409)
ERR_WAIVER_OR_AGE_FAIL = ("ERR_WAIVER_OR_AGE_FAIL", 422)
ERR_ATTENDEE_ROSTER_INCOMPLETE = ("ERR_ATTENDEE_ROSTER_INCOMPLETE", 422)
ERR_INSUFFICIENT_SEATS = ("ERR_INSUFFICIENT_SEATS", 409)
ERR_STALE_EVENT_VERSION = ("ERR_STALE_EVENT_VERSION", 412)
ERR_INVALID_EVENT_CONFIG = ("ERR_INVALID_EVENT_CONFIG", 422)
ERR_GIFT_CARD_DEPLETED = ("ERR_GIFT_CARD_DEPLETED", 422)
ERR_ARTIST_INACTIVE = ("ERR_ARTIST_INACTIVE", 422)
ERR_EVENT_NOT_STARTED = ("ERR_EVENT_NOT_STARTED", 409)
ERR_VALIDATION = ("ERR_VALIDATION", 400)
ERR_DUPLICATE_RESOURCE = ("ERR_DUPLICATE_RESOURCE", 409)
ERR_CREDIT_INSUFFICIENT = ("ERR_CREDIT_INSUFFICIENT", 422)


def err(catalog_entry, message=None):
    error_id, http_status = catalog_entry
    return ApiError(error_id, http_status, message)
