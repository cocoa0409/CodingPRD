"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_DEAL_VERSION = "ERR_STALE_DEAL_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WRONG_SIDE = "ERR_WRONG_SIDE"
    ERR_LISTING_NOT_NEGOTIABLE = "ERR_LISTING_NOT_NEGOTIABLE"
    ERR_REQUIREMENT_NOT_ACTIVE = "ERR_REQUIREMENT_NOT_ACTIVE"
    ERR_SPACE_NOT_AVAILABLE = "ERR_SPACE_NOT_AVAILABLE"
    ERR_TOUR_WINDOW_CONFLICT = "ERR_TOUR_WINDOW_CONFLICT"
    ERR_BROKER_DOUBLE_BOOKED = "ERR_BROKER_DOUBLE_BOOKED"
    ERR_TOUR_NOT_STARTED = "ERR_TOUR_NOT_STARTED"
    ERR_TOUR_NOT_ENDED = "ERR_TOUR_NOT_ENDED"
    ERR_LISTING_HAS_LIVE_DEAL = "ERR_LISTING_HAS_LIVE_DEAL"
    ERR_REQUIREMENT_HAS_LIVE_DEAL = "ERR_REQUIREMENT_HAS_LIVE_DEAL"
    ERR_BROKER_SUSPENDED = "ERR_BROKER_SUSPENDED"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_DEAL_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WRONG_SIDE: 409,
    ApiErrorId.ERR_LISTING_NOT_NEGOTIABLE: 409,
    ApiErrorId.ERR_REQUIREMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SPACE_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_TOUR_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_BROKER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_TOUR_NOT_STARTED: 409,
    ApiErrorId.ERR_TOUR_NOT_ENDED: 409,
    ApiErrorId.ERR_LISTING_HAS_LIVE_DEAL: 409,
    ApiErrorId.ERR_REQUIREMENT_HAS_LIVE_DEAL: 409,
    ApiErrorId.ERR_BROKER_SUSPENDED: 409,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
