"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_ORDER_OWNER = "ERR_NOT_ORDER_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_STAND_VERSION = "ERR_STALE_STAND_VERSION"
    ERR_EVENT_NOT_OPENABLE = "ERR_EVENT_NOT_OPENABLE"
    ERR_UNDERSTAFFED_OPEN = "ERR_UNDERSTAFFED_OPEN"
    ERR_STAND_NOT_OPEN = "ERR_STAND_NOT_OPEN"
    ERR_ORDER_UNPAID = "ERR_ORDER_UNPAID"
    ERR_LOT_NOT_EXPIRED = "ERR_LOT_NOT_EXPIRED"
    ERR_CROSS_EVENT_TRANSFER = "ERR_CROSS_EVENT_TRANSFER"
    ERR_EVENT_WINDOW_OVERLAP = "ERR_EVENT_WINDOW_OVERLAP"
    ERR_SHIFT_OVERLAP = "ERR_SHIFT_OVERLAP"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_TRANSFER_QTY_EXCEEDS_ONHAND = "ERR_TRANSFER_QTY_EXCEEDS_ONHAND"
    ERR_EVENT_NOT_SETTLEABLE = "ERR_EVENT_NOT_SETTLEABLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_ORDER_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_STAND_VERSION: 412,
    ApiErrorId.ERR_EVENT_NOT_OPENABLE: 409,
    ApiErrorId.ERR_UNDERSTAFFED_OPEN: 409,
    ApiErrorId.ERR_STAND_NOT_OPEN: 409,
    ApiErrorId.ERR_ORDER_UNPAID: 409,
    ApiErrorId.ERR_LOT_NOT_EXPIRED: 409,
    ApiErrorId.ERR_CROSS_EVENT_TRANSFER: 422,
    ApiErrorId.ERR_EVENT_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_SHIFT_OVERLAP: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_TRANSFER_QTY_EXCEEDS_ONHAND: 409,
    ApiErrorId.ERR_EVENT_NOT_SETTLEABLE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
