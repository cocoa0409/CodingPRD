"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping we register it with the framework so
`validate_error()` cross-checks the HTTP status automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_ACCOUNT_OWNER = "ERR_NOT_ACCOUNT_OWNER"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_PARTNER_FIELD_MISMATCH = "ERR_PARTNER_FIELD_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CROSS_PRODUCT_MISMATCH = "ERR_CROSS_PRODUCT_MISMATCH"
    ERR_DUPLICATE_ACTIVATION = "ERR_DUPLICATE_ACTIVATION"
    ERR_TEMPORAL_OUT_OF_RANGE = "ERR_TEMPORAL_OUT_OF_RANGE"
    ERR_BELOW_MIN_TRANSFER = "ERR_BELOW_MIN_TRANSFER"
    ERR_STALE_ACCOUNT_VERSION = "ERR_STALE_ACCOUNT_VERSION"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_ACCOUNT_OWNER: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_PARTNER_FIELD_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CROSS_PRODUCT_MISMATCH: 422,
    ApiErrorId.ERR_DUPLICATE_ACTIVATION: 409,
    ApiErrorId.ERR_TEMPORAL_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_BELOW_MIN_TRANSFER: 422,
    ApiErrorId.ERR_STALE_ACCOUNT_VERSION: 412,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
