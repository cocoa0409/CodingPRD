"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can cross-check
HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_POOL_VERSION = "ERR_STALE_POOL_VERSION"
    ERR_STALE_MEMBER_VERSION = "ERR_STALE_MEMBER_VERSION"
    ERR_STATUS_MATCH_EXHAUSTED = "ERR_STATUS_MATCH_EXHAUSTED"
    ERR_CERTIFICATE_NOT_VALID = "ERR_CERTIFICATE_NOT_VALID"
    ERR_GIFT_TO_SELF = "ERR_GIFT_TO_SELF"
    ERR_DEPARTURE_NOT_REACHED = "ERR_DEPARTURE_NOT_REACHED"
    ERR_LOAD_FACTOR_REQUIRED = "ERR_LOAD_FACTOR_REQUIRED"
    ERR_POOL_ALREADY_CLEARED = "ERR_POOL_ALREADY_CLEARED"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_GIFT_AMOUNT_INVALID = "ERR_GIFT_AMOUNT_INVALID"
    ERR_POOL_CAPACITY_INVALID = "ERR_POOL_CAPACITY_INVALID"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_POOL_VERSION: 412,
    ApiErrorId.ERR_STALE_MEMBER_VERSION: 412,
    ApiErrorId.ERR_STATUS_MATCH_EXHAUSTED: 409,
    ApiErrorId.ERR_CERTIFICATE_NOT_VALID: 422,
    ApiErrorId.ERR_GIFT_TO_SELF: 422,
    ApiErrorId.ERR_DEPARTURE_NOT_REACHED: 422,
    ApiErrorId.ERR_LOAD_FACTOR_REQUIRED: 422,
    ApiErrorId.ERR_POOL_ALREADY_CLEARED: 409,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 422,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_GIFT_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_POOL_CAPACITY_INVALID: 400,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
