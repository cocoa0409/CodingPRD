"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_OWNERSHIP_MISMATCH = "ERR_OWNERSHIP_MISMATCH"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VESSEL_VERSION = "ERR_STALE_VESSEL_VERSION"
    ERR_VESSEL_NOT_INSPECTABLE = "ERR_VESSEL_NOT_INSPECTABLE"
    ERR_CRITICAL_DEFICIENCY_OPEN = "ERR_CRITICAL_DEFICIENCY_OPEN"
    ERR_INSURANCE_COORDINATION_INVALID = "ERR_INSURANCE_COORDINATION_INVALID"
    ERR_INSPECTOR_NOT_COMMISSIONED = "ERR_INSPECTOR_NOT_COMMISSIONED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_DUPLICATE_UNIQUE_FIELD = "ERR_DUPLICATE_UNIQUE_FIELD"
    ERR_DEFICIENCY_NOT_REPAIRABLE = "ERR_DEFICIENCY_NOT_REPAIRABLE"
    ERR_INSPECTOR_DOUBLE_BOOKED = "ERR_INSPECTOR_DOUBLE_BOOKED"
    ERR_POLICY_COVERAGE_OVERLAP = "ERR_POLICY_COVERAGE_OVERLAP"
    ERR_FEE_NOT_PAID = "ERR_FEE_NOT_PAID"
    ERR_CERTIFICATE_NOT_DUE = "ERR_CERTIFICATE_NOT_DUE"
    ERR_POLICY_NOT_EXPIRABLE = "ERR_POLICY_NOT_EXPIRABLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_OWNERSHIP_MISMATCH: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VESSEL_VERSION: 412,
    ApiErrorId.ERR_VESSEL_NOT_INSPECTABLE: 409,
    ApiErrorId.ERR_CRITICAL_DEFICIENCY_OPEN: 409,
    ApiErrorId.ERR_INSURANCE_COORDINATION_INVALID: 409,
    ApiErrorId.ERR_INSPECTOR_NOT_COMMISSIONED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_DUPLICATE_UNIQUE_FIELD: 409,
    ApiErrorId.ERR_DEFICIENCY_NOT_REPAIRABLE: 409,
    ApiErrorId.ERR_INSPECTOR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_POLICY_COVERAGE_OVERLAP: 409,
    ApiErrorId.ERR_FEE_NOT_PAID: 402,
    ApiErrorId.ERR_CERTIFICATE_NOT_DUE: 409,
    ApiErrorId.ERR_POLICY_NOT_EXPIRABLE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
