from __future__ import annotations

"""Error codes and the APIError exception."""


# Authentication / authorization
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"

# Existence
ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

# State + OCC
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"

# Domain
ERR_CHAPTER_SUSPENDED = "ERR_CHAPTER_SUSPENDED"
ERR_PARTY_TIME_CONFLICT = "ERR_PARTY_TIME_CONFLICT"
ERR_CHAPTER_DOUBLE_BOOK = "ERR_CHAPTER_DOUBLE_BOOK"
ERR_PREFERENCE_NOT_ELIGIBLE = "ERR_PREFERENCE_NOT_ELIGIBLE"
ERR_PREFERENCE_RANK_TAKEN = "ERR_PREFERENCE_RANK_TAKEN"
ERR_ROUND_PHASE_MISMATCH = "ERR_ROUND_PHASE_MISMATCH"
ERR_CHAPTER_QUOTA_FULL = "ERR_CHAPTER_QUOTA_FULL"
ERR_DUPLICATE_INVITATION = "ERR_DUPLICATE_INVITATION"
ERR_GPA_BELOW_MINIMUM = "ERR_GPA_BELOW_MINIMUM"

# Generic
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_FOR_ERR = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNAUTHORIZED: 403,
    ERR_RESOURCE_NOT_FOUND: 404,
    ERR_REFERENCE_NOT_FOUND: 422,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 412,
    ERR_CHAPTER_SUSPENDED: 409,
    ERR_PARTY_TIME_CONFLICT: 409,
    ERR_CHAPTER_DOUBLE_BOOK: 409,
    ERR_PREFERENCE_NOT_ELIGIBLE: 409,
    ERR_PREFERENCE_RANK_TAKEN: 409,
    ERR_ROUND_PHASE_MISMATCH: 409,
    ERR_CHAPTER_QUOTA_FULL: 409,
    ERR_DUPLICATE_INVITATION: 409,
    ERR_GPA_BELOW_MINIMUM: 422,
    ERR_INVALID_REQUEST: 400,
}


class APIError(Exception):
    """Raised by handlers / services. Carries error_id + message + http status."""

    def __init__(self, error_id: str, message: str, http_status: int | None = None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else HTTP_FOR_ERR.get(error_id, 400)
