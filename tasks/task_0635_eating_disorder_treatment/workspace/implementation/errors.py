"""Error classes and the complete error catalogue.

Every error_id and its HTTP status is taken verbatim from PRD §5 (Error Code
Catalogue) and SCAFFOLD Table 6.
"""


class ApiError(Exception):
    """An application error that maps to a standard error envelope."""

    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


