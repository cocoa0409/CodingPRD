def error_status(error_id: str) -> int:
    """Return the HTTP status the PRD pins to ``error_id``."""
    return ERROR_STATUS_MAP[error_id]


def priority_of(error_id: str) -> int:
    """Return the screening rank of ``error_id``; lower is screened first."""
    return VALIDATION_PRIORITY.index(error_id)


def assert_wins_over(winner: str, loser: str) -> None:
    """Assert that ``winner`` is screened strictly earlier than ``loser``."""
    assert priority_of(winner) < priority_of(loser), (
        "%s must be screened before %s" % (winner, loser)
    )


def register_error_status_map() -> None:
    """Teach the shared validators which status belongs to each error."""
    set_error_http_status_map(ERROR_STATUS_MAP)
