"""Domain-specific exceptions and error id catalog (PRD §5 / SCAFFOLD §1.6)."""


class APIError(Exception):
    def __init__(self, error_id, http_status, message=None):
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id
        super().__init__(self.message)


# Error ID constants — names match PRD §5 / SCAFFOLD §1.6 verbatim.
ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_OWNERSHIP_VIOLATION = "ERR_OWNERSHIP_VIOLATION"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_OBJECTION_ALREADY_PENDING = "ERR_OBJECTION_ALREADY_PENDING"
ERR_DECLARATION_ALREADY_SUBMITTED = "ERR_DECLARATION_ALREADY_SUBMITTED"
ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
ERR_PENALTY_OVERDUE = "ERR_PENALTY_OVERDUE"
ERR_WINDOW_CLOSED = "ERR_WINDOW_CLOSED"
ERR_VERIFIER_CONFLICT_OF_INTEREST = "ERR_VERIFIER_CONFLICT_OF_INTEREST"
ERR_SUPPORTING_DOCUMENT_REQUIRED = "ERR_SUPPORTING_DOCUMENT_REQUIRED"
ERR_CCER_CAP_EXCEEDED = "ERR_CCER_CAP_EXCEEDED"
ERR_BORROW_CAP_EXCEEDED = "ERR_BORROW_CAP_EXCEEDED"
ERR_INVALID_ORDER = "ERR_INVALID_ORDER"
ERR_INVALID_RATIO = "ERR_INVALID_RATIO"
ERR_INVALID_INPUT = "ERR_INVALID_INPUT"


HTTP_STATUS = {
    ERR_AUTH_REQUIRED: 401,
    ERR_FORBIDDEN: 403,
    ERR_OWNERSHIP_VIOLATION: 403,
    ERR_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 409,
    ERR_OBJECTION_ALREADY_PENDING: 409,
    ERR_DECLARATION_ALREADY_SUBMITTED: 409,
    ERR_INSUFFICIENT_BALANCE: 409,
    ERR_PENALTY_OVERDUE: 409,
    ERR_WINDOW_CLOSED: 422,
    ERR_VERIFIER_CONFLICT_OF_INTEREST: 422,
    ERR_SUPPORTING_DOCUMENT_REQUIRED: 422,
    ERR_CCER_CAP_EXCEEDED: 422,
    ERR_BORROW_CAP_EXCEEDED: 422,
    ERR_INVALID_ORDER: 422,
    ERR_INVALID_RATIO: 422,
    ERR_INVALID_INPUT: 422,
}


def raise_error(error_id, message=None):
    raise APIError(error_id, HTTP_STATUS[error_id], message)
