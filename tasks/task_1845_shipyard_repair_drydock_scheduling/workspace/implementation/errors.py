"""Error types and the error catalog for the Shipyard Repair & Drydock API.

Error IDs and HTTP statuses are read verbatim from SCAFFOLD.yaml section 1.6
and PRD section 5.
"""

from __future__ import annotations


class ApiError(Exception):
    def __init__(self, error_id: str, http_status: int, message: str):
        super().__init__(message)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message


# --- Auth ---
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"

# --- Generic shape ---
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_NOT_FOUND = "ERR_NOT_FOUND"

# --- State ---
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_PROJECT_NOT_CONTRACTED = "ERR_PROJECT_NOT_CONTRACTED"
ERR_PROJECT_NOT_IN_DOCK = "ERR_PROJECT_NOT_IN_DOCK"
