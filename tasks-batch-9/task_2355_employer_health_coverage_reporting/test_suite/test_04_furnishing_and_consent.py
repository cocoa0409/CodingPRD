# The consent cycle PENDING -> GRANTED -> WITHDRAWN -> GRANTED
# ---------------------------------------------------------------------------
def test_regranting_a_withdrawn_consent_increments_grant_count(api):
    """PRD §3.7: "Granting takes the consent from `PENDING` to `GRANTED`, or from
    `WITHDRAWN` back to `GRANTED`; either way it stamps `granted_at` from the logical clock
    and increments `grant_count`, so the counter records how many rounds the consent has been
    through."
    PRD §3.7: "Withdrawing takes `GRANTED` to `WITHDRAWN`, stamps `withdrawn_at`, and is
    refused with `ERR_CONSENT_NOT_GRANTED` from any other state."

    Design: Difficulty/non_linear_state_machine/consent_withdraw_then_regrant_increments_grant_count
    """
    ctx = _electronically_furnished_statement(api)
    employee_headers = make_employee_self_service_headers(ctx["employee"]["id"])
    consent_id = ctx["consent"]["id"]

    withdrawn = fixtures.withdraw_consent(api, consent_id, ctx["employee"]["id"])
    assert_furnishing_consent(withdrawn, consent_status="WITHDRAWN")
    assert is_iso8601_timestamp(withdrawn["withdrawn_at"]), (
        f"withdrawal must stamp withdrawn_at, got {withdrawn['withdrawn_at']!r}"
    )

    regranted = get_success_data(
        api.grant_furnishing_consent(consent_id, employee_headers)
    )
    assert_furnishing_consent(regranted, consent_status="GRANTED", grant_count=2)
    assert regranted["grant_count"] == 2, (
        "the PENDING -> GRANTED -> WITHDRAWN -> GRANTED cycle is two grant rounds, so "
        f"grant_count should be 2, got {regranted['grant_count']}"
    )


def test_consent_withdrawal_forces_redelivery_of_the_electronic_statement(api):
    """PRD §3.7: "Withdrawal is not a quiet bookkeeping change: every statement of that
    employee sitting at `FURNISHED_ELECTRONIC` is pushed back to `REDELIVERY_REQUIRED`, which
    increments the controlled group's `open_correction_count`, moves a `DETERMINED_ALE` group
    to `CORRECTION_OPEN` and increments the season's `open_correction_count`."

    Design: Difficulty/non_linear_state_machine/consent_withdraw_then_regrant_increments_grant_count
    """
    ctx = _electronically_furnished_statement(api)

    furnished = fixtures.read_form(api, ctx["form"]["id"])
    assert furnished["furnishing_status"] == "FURNISHED_ELECTRONIC", (
        f"setup should leave the statement delivered electronically, got "
        f"{furnished['furnishing_status']!r}"
    )

    fixtures.withdraw_consent(api, ctx["consent"]["id"], ctx["employee"]["id"])

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(form, furnishing_status="REDELIVERY_REQUIRED")

    group = fixtures.read_group(api, ctx["group"]["id"])
    assert group["determination_state"] == "CORRECTION_OPEN", (
        f"the withdrawal opens a correction on the group, got "
        f"{group['determination_state']!r}"
    )
    assert group["open_correction_count"] == 1, (
        f"expected one open correction on the group, got {group['open_correction_count']}"
    )

    season = fixtures.read_season(api, ctx["season"]["id"])
    assert season["open_correction_count"] == 1, (
        f"the group's move increments the season's counter, got "
        f"{season['open_correction_count']}"
    )


def test_redelivery_after_regrant_closes_the_open_correction(api):
    """PRD §3.7: "A redelivery additionally decrements the controlled group's
    `open_correction_count`, and once that count reaches zero the group returns from
    `CORRECTION_OPEN` to `DETERMINED_ALE`, which decrements the season's counter in turn."
    PRD §3.7: "A statement delivered on or before the deadline date carries no penalty at all
    — the deadline date itself is not late."
    PRD §3.7: "The figure lands in the statement's `late_furnishing_penalty_cents`, and the
    member's `furnishing_penalty_total_cents` absorbs only the **delta** — the newly computed
    penalty minus whatever this statement had previously contributed — so a redelivery at a
    worse tier adds only the increase rather than double-counting the original charge."

    Design: Difficulty/non_linear_state_machine/consent_withdraw_then_regrant_increments_grant_count
    """
    ctx = _electronically_furnished_statement(api)
    employee_headers = make_employee_self_service_headers(ctx["employee"]["id"])

    fixtures.withdraw_consent(api, ctx["consent"]["id"], ctx["employee"]["id"])
    get_success_data(
        api.grant_furnishing_consent(ctx["consent"]["id"], employee_headers)
    )
    fixtures.furnish_form(api, ctx["form"]["id"], "ELECTRONIC")

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(
        form, furnishing_status="FURNISHED_ELECTRONIC", late_furnishing_penalty_cents=0
    )

    member = fixtures.read_member(api, ctx["member"]["id"])
    assert member["furnishing_penalty_total_cents"] == 0, (
        "both deliveries landed before the furnishing deadline, so the member absorbs no "
        f"penalty, got {member['furnishing_penalty_total_cents']}"
    )

    group = fixtures.read_group(api, ctx["group"]["id"])
    assert group["determination_state"] == "DETERMINED_ALE", (
        f"the redelivery returns the group to DETERMINED_ALE, got "
        f"{group['determination_state']!r}"
    )
    assert group["open_correction_count"] == 0, (
        f"expected the group's correction to close, got {group['open_correction_count']}"
    )

    season = fixtures.read_season(api, ctx["season"]["id"])
    assert season["open_correction_count"] == 0, (
        f"the season's counter decrements in turn, got {season['open_correction_count']}"
    )


