"""Error identifiers and their HTTP status mapping (PRD §5).

Registering the map with the framework lets ``validate_error()`` cross-check the
HTTP status automatically whenever an error id is asserted.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    # not found
    ERR_ORGANIZATION_NOT_FOUND = "ERR_ORGANIZATION_NOT_FOUND"
    ERR_FILING_NOT_FOUND = "ERR_FILING_NOT_FOUND"
    ERR_EXTRACTED_FIELD_NOT_FOUND = "ERR_EXTRACTED_FIELD_NOT_FOUND"
    ERR_LICENSE_NOT_FOUND = "ERR_LICENSE_NOT_FOUND"
    ERR_USAGE_EVENT_NOT_FOUND = "ERR_USAGE_EVENT_NOT_FOUND"
    ERR_SEAL_NOT_FOUND = "ERR_SEAL_NOT_FOUND"
    ERR_GRANT_NOT_FOUND = "ERR_GRANT_NOT_FOUND"
    ERR_CORRECTION_REQUEST_NOT_FOUND = "ERR_CORRECTION_REQUEST_NOT_FOUND"
    ERR_IDENTITY_CASE_NOT_FOUND = "ERR_IDENTITY_CASE_NOT_FOUND"
    # request shape
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    # state
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERIFICATION_STEP_INVALID = "ERR_VERIFICATION_STEP_INVALID"
    ERR_PROFILE_INCOMPLETE = "ERR_PROFILE_INCOMPLETE"
    ERR_NO_EXTRACTED_FIELDS = "ERR_NO_EXTRACTED_FIELDS"
    # business safety
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_ORG_NOT_IN_GOOD_STANDING = "ERR_ORG_NOT_IN_GOOD_STANDING"
    # business constraints
    ERR_EIN_ALREADY_REGISTERED = "ERR_EIN_ALREADY_REGISTERED"
    ERR_FILING_COVERAGE_OVERLAP = "ERR_FILING_COVERAGE_OVERLAP"
    ERR_LICENSE_TERM_OVERLAP = "ERR_LICENSE_TERM_OVERLAP"
    ERR_LEADERSHIP_TERM_OVERLAP = "ERR_LEADERSHIP_TERM_OVERLAP"
    ERR_MERGE_CYCLE_DETECTED = "ERR_MERGE_CYCLE_DETECTED"
    ERR_IDENTITY_CASE_INVALID = "ERR_IDENTITY_CASE_INVALID"
    # business fiscal
    ERR_QUOTA_EXCEEDED = "ERR_QUOTA_EXCEEDED"
    # business referential
    ERR_UNSUPPORTED_FORM_VERSION = "ERR_UNSUPPORTED_FORM_VERSION"
    ERR_FIELD_NOT_CORRECTABLE = "ERR_FIELD_NOT_CORRECTABLE"
    ERR_PERMITTED_USE_NOT_IN_TIER = "ERR_PERMITTED_USE_NOT_IN_TIER"
    ERR_SEAL_DISCLOSURE_INSUFFICIENT = "ERR_SEAL_DISCLOSURE_INSUFFICIENT"
    # business temporal
    ERR_LICENSE_TERM_CLOSED = "ERR_LICENSE_TERM_CLOSED"
    ERR_SEAL_LAPSED = "ERR_SEAL_LAPSED"
    # optimistic concurrency
    ERR_STALE_ORGANIZATION_VERSION = "ERR_STALE_ORGANIZATION_VERSION"
    ERR_STALE_EXTRACTED_FIELD_VERSION = "ERR_STALE_EXTRACTED_FIELD_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_ORGANIZATION_NOT_FOUND: 404,
    ApiErrorId.ERR_FILING_NOT_FOUND: 404,
    ApiErrorId.ERR_EXTRACTED_FIELD_NOT_FOUND: 404,
    ApiErrorId.ERR_LICENSE_NOT_FOUND: 404,
    ApiErrorId.ERR_USAGE_EVENT_NOT_FOUND: 404,
    ApiErrorId.ERR_SEAL_NOT_FOUND: 404,
    ApiErrorId.ERR_GRANT_NOT_FOUND: 404,
    ApiErrorId.ERR_CORRECTION_REQUEST_NOT_FOUND: 404,
    ApiErrorId.ERR_IDENTITY_CASE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERIFICATION_STEP_INVALID: 409,
    ApiErrorId.ERR_PROFILE_INCOMPLETE: 409,
    ApiErrorId.ERR_NO_EXTRACTED_FIELDS: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_ORG_NOT_IN_GOOD_STANDING: 403,
    ApiErrorId.ERR_EIN_ALREADY_REGISTERED: 409,
    ApiErrorId.ERR_FILING_COVERAGE_OVERLAP: 409,
    ApiErrorId.ERR_LICENSE_TERM_OVERLAP: 409,
    ApiErrorId.ERR_LEADERSHIP_TERM_OVERLAP: 409,
    ApiErrorId.ERR_MERGE_CYCLE_DETECTED: 409,
    ApiErrorId.ERR_IDENTITY_CASE_INVALID: 409,
    ApiErrorId.ERR_QUOTA_EXCEEDED: 402,
    ApiErrorId.ERR_UNSUPPORTED_FORM_VERSION: 422,
    ApiErrorId.ERR_FIELD_NOT_CORRECTABLE: 422,
    ApiErrorId.ERR_PERMITTED_USE_NOT_IN_TIER: 403,
    ApiErrorId.ERR_SEAL_DISCLOSURE_INSUFFICIENT: 422,
    ApiErrorId.ERR_LICENSE_TERM_CLOSED: 409,
    ApiErrorId.ERR_SEAL_LAPSED: 409,
    ApiErrorId.ERR_STALE_ORGANIZATION_VERSION: 412,
    ApiErrorId.ERR_STALE_EXTRACTED_FIELD_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
