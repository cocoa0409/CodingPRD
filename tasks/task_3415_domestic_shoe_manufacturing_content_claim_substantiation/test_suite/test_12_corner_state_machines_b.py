def test_claim_publish_with_expired_evidence_returns_evidence_stale():
    """PRD §3.8: "The model must still be `ACTIVE` (`ERR_MODEL_NOT_ACTIVE`),
    and freshness is re-checked at the current logical clock: every
    `SUPPLIER_ORIGIN_CERT` and `ASSEMBLY_LABOR_RECORD` counted at
    substantiation must still be `VERIFIED` and unexpired, otherwise
    `ERR_EVIDENCE_STALE` (HTTP 422)."
    PRD §2.4: "Expiry never cascades. A claim is not automatically challenged
    because one of its evidence documents expired, but freshness is re-checked
    when the claim is published, and government audits count only `VERIFIED`
    unexpired documents."

    Design: Corner/state_machines/claim_publish_with_expired_evidence_returns_evidence_stale
    """
    kit = m95_completed_run()
    docs = claim_with_verified_docs(kit["model"]["id"], "MADE_IN_USA",
                                    valid_from="2026-08-15",
                                    valid_until="2026-09-10")
    claim = substantiate(docs["claim"]["id"], kit["report"]["id"])
    assert claim["status"] == "SUBSTANTIATED"

    set_clock("2026-09-11T00:00:00Z")  # both documents lapse
    assert get_document(docs["d_oc"]["id"])["status"] == "EXPIRED"
    assert get_document(docs["d_lr"]["id"])["status"] == "EXPIRED"

    resp = api.publish_claim(claim["id"], COMPLIANCE)
    validate_error(resp, ApiErrorId.ERR_EVIDENCE_STALE)
    after = get_claim(claim["id"])
    assert after["status"] == "SUBSTANTIATED" and after["version"] == 2


def test_evidence_expiry_sweep_on_clock_set():
    """PRD §2.4: "Advancing the clock fires an evidence-expiry sweep: every
    evidence document in `VERIFIED` status whose `valid_until` is now strictly
    earlier than the new clock date transitions from `VERIFIED` to `EXPIRED`,
    with its `version` incremented by 1."
    PRD §2.4: "A document counts as unexpired exactly when its `valid_until` is
    on or after the current logical-clock date."

    Design: Corner/state_machines/evidence_expiry_sweep_on_clock_set
    """
    set_clock()
    make_factory()
    component = make_component()
    lot = make_lot(component["id"])
    d_exp = make_verified_document("SUPPLIER_ORIGIN_CERT", "material_lot_id",
                                   lot["id"], valid_until="2026-09-10")
    d_ok = make_verified_document("SUPPLIER_ORIGIN_CERT", "material_lot_id",
                                  lot["id"], valid_until="2027-08-31")

    # Inclusive boundary: at clock 2026-09-10 the first document is unexpired.
    set_clock("2026-09-10T00:00:00Z")
    assert get_document(d_exp["id"])["status"] == "VERIFIED"

    set_clock("2026-09-11T00:00:00Z")
    expired = get_document(d_exp["id"])
    assert expired["status"] == "EXPIRED" and expired["version"] == 3
    assert get_document(d_ok["id"])["status"] == "VERIFIED"


