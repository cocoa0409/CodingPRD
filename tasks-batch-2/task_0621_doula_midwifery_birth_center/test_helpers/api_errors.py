"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping, register it with the framework so validate_error()
can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_RISK_TRANSFER_REQUIRED = "ERR_RISK_TRANSFER_REQUIRED"
    ERR_BACKUP_SAME_PROVIDER = "ERR_BACKUP_SAME_PROVIDER"
    ERR_PROVIDER_AT_CAPACITY = "ERR_PROVIDER_AT_CAPACITY"
    ERR_PROVIDER_WINDOW_OVERLAP = "ERR_PROVIDER_WINDOW_OVERLAP"
    ERR_ROOM_DOUBLE_BOOKED = "ERR_ROOM_DOUBLE_BOOKED"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_CLAIM_AMOUNTS_INVALID = "ERR_CLAIM_AMOUNTS_INVALID"
    ERR_KIT_OUT_OF_STOCK = "ERR_KIT_OUT_OF_STOCK"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"
    ERR_NO_BALANCE = "ERR_NO_BALANCE"
    ERR_POSTPARTUM_INCOMPLETE = "ERR_POSTPARTUM_INCOMPLETE"
    ERR_NO_ACTIVE_BOOKING = "ERR_NO_ACTIVE_BOOKING"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_CLAIM_HAS_PLAN = "ERR_CLAIM_HAS_PLAN"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_RISK_TRANSFER_REQUIRED: 409,
    ApiErrorId.ERR_BACKUP_SAME_PROVIDER: 409,
    ApiErrorId.ERR_PROVIDER_AT_CAPACITY: 409,
    ApiErrorId.ERR_PROVIDER_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_ROOM_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_CLAIM_AMOUNTS_INVALID: 422,
    ApiErrorId.ERR_KIT_OUT_OF_STOCK: 409,
    ApiErrorId.ERR_OVERPAYMENT: 409,
    ApiErrorId.ERR_NO_BALANCE: 409,
    ApiErrorId.ERR_POSTPARTUM_INCOMPLETE: 409,
    ApiErrorId.ERR_NO_ACTIVE_BOOKING: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_CLAIM_HAS_PLAN: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
