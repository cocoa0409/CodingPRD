"""Error catalog for the private mortgage insurance API.

Every error_id / http status pair is read verbatim from SCAFFOLD.yaml
section 1.6 (Error Code Catalog).
"""


class ApiError(Exception):
    def __init__(self, error_id, message, http_status=None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else HTTP_BY_ERROR.get(error_id, 409)


