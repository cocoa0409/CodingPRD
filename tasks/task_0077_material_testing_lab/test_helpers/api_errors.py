"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # ---- auth / authz ----
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID = "ERR_AUTH_INVALID"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # ---- existence ----
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # ---- state ----
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # ---- concurrency / OCC ----
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_INSTRUMENT_SLOT_CONFLICT = "ERR_INSTRUMENT_SLOT_CONFLICT"
    ERR_TESTER_WORKLOAD_EXCEEDED = "ERR_TESTER_WORKLOAD_EXCEEDED"

    # ---- business rules ----
    ERR_BOOKING_OUTSIDE_CALIBRATION = "ERR_BOOKING_OUTSIDE_CALIBRATION"
    ERR_NO_QUALIFIED_TESTER = "ERR_NO_QUALIFIED_TESTER"
    ERR_TEST_METHOD_NOT_SUPPORTED = "ERR_TEST_METHOD_NOT_SUPPORTED"
    ERR_WITNESS_RECORD_INCONSISTENT = "ERR_WITNESS_RECORD_INCONSISTENT"
    ERR_RETEST_LIMIT_EXCEEDED = "ERR_RETEST_LIMIT_EXCEEDED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_REVIEWER_SCOPE_MISMATCH = "ERR_REVIEWER_SCOPE_MISMATCH"
    ERR_SIGNATORY_SCOPE_MISMATCH = "ERR_SIGNATORY_SCOPE_MISMATCH"
    ERR_REPORT_BLOCKED_INSTRUMENT_LAPSED = (
        "ERR_REPORT_BLOCKED_INSTRUMENT_LAPSED"
    )
    ERR_INVOICE_INELIGIBLE_TASKS = "ERR_INVOICE_INELIGIBLE_TASKS"
    ERR_DEPOSIT_OVERDRAW = "ERR_DEPOSIT_OVERDRAW"
    ERR_DATA_MODIFICATION_REASON_REQUIRED = (
        "ERR_DATA_MODIFICATION_REASON_REQUIRED"
    )

    # ---- generic shape / pagination ----
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 — Error Code Catalogue table
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INSTRUMENT_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_TESTER_WORKLOAD_EXCEEDED: 409,
    ApiErrorId.ERR_BOOKING_OUTSIDE_CALIBRATION: 422,
    ApiErrorId.ERR_NO_QUALIFIED_TESTER: 422,
    ApiErrorId.ERR_TEST_METHOD_NOT_SUPPORTED: 422,
    ApiErrorId.ERR_WITNESS_RECORD_INCONSISTENT: 422,
    ApiErrorId.ERR_RETEST_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 422,
    ApiErrorId.ERR_REVIEWER_SCOPE_MISMATCH: 422,
    ApiErrorId.ERR_SIGNATORY_SCOPE_MISMATCH: 422,
    ApiErrorId.ERR_REPORT_BLOCKED_INSTRUMENT_LAPSED: 422,
    ApiErrorId.ERR_INVOICE_INELIGIBLE_TASKS: 422,
    ApiErrorId.ERR_DEPOSIT_OVERDRAW: 422,
    ApiErrorId.ERR_DATA_MODIFICATION_REASON_REQUIRED: 422,
    ApiErrorId.ERR_INVALID_PAGINATION: 400,
    ApiErrorId.ERR_VALIDATION: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
