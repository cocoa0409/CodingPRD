"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, register it with the framework so validate_error()
auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVENTORY_ROW_MISSING = "ERR_INVENTORY_ROW_MISSING"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INSUFFICIENT_CLEARANCE = "ERR_INSUFFICIENT_CLEARANCE"
    ERR_DECLARED_VALUE_OVER_CAP = "ERR_DECLARED_VALUE_OVER_CAP"
    ERR_CREW_WINDOW_CONFLICT = "ERR_CREW_WINDOW_CONFLICT"
    ERR_TRUCK_CAPACITY_EXCEEDED = "ERR_TRUCK_CAPACITY_EXCEEDED"
    ERR_OPEN_LOGISTICS = "ERR_OPEN_LOGISTICS"
    ERR_BILLING_NOT_CURRENT = "ERR_BILLING_NOT_CURRENT"
    ERR_OUTSTANDING_BALANCE = "ERR_OUTSTANDING_BALANCE"
    ERR_NO_INVENTORY = "ERR_NO_INVENTORY"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVENTORY_ROW_MISSING: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INSUFFICIENT_CLEARANCE: 422,
    ApiErrorId.ERR_DECLARED_VALUE_OVER_CAP: 422,
    ApiErrorId.ERR_CREW_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_TRUCK_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_OPEN_LOGISTICS: 409,
    ApiErrorId.ERR_BILLING_NOT_CURRENT: 409,
    ApiErrorId.ERR_OUTSTANDING_BALANCE: 409,
    ApiErrorId.ERR_NO_INVENTORY: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
