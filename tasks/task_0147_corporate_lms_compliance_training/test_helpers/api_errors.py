"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework at import time so validate_error()
auto-checks the HTTP status code from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_RECURRENCE_CONFIG_INVALID = "ERR_RECURRENCE_CONFIG_INVALID"
    ERR_PREREQUISITE_NOT_PUBLISHED = "ERR_PREREQUISITE_NOT_PUBLISHED"
    ERR_COURSE_HAS_OPEN_ENROLLMENTS = "ERR_COURSE_HAS_OPEN_ENROLLMENTS"
    ERR_PATH_EMPTY = "ERR_PATH_EMPTY"
    ERR_PATH_STEP_COURSE_NOT_PUBLISHED = "ERR_PATH_STEP_COURSE_NOT_PUBLISHED"
    ERR_PATH_SEQUENCE_INVALID = "ERR_PATH_SEQUENCE_INVALID"
    ERR_PATH_HAS_OPEN_ENROLLMENTS = "ERR_PATH_HAS_OPEN_ENROLLMENTS"
    ERR_COURSE_NOT_PUBLISHED = "ERR_COURSE_NOT_PUBLISHED"
    ERR_PREREQUISITE_NOT_MET = "ERR_PREREQUISITE_NOT_MET"
    ERR_PATH_STEP_LOCKED = "ERR_PATH_STEP_LOCKED"
    ERR_ATTEMPTS_EXHAUSTED = "ERR_ATTEMPTS_EXHAUSTED"
    ERR_SESSION_ALREADY_OPEN = "ERR_SESSION_ALREADY_OPEN"
    ERR_ASSIGNMENT_RULE_OVERLAP = "ERR_ASSIGNMENT_RULE_OVERLAP"
    ERR_PREREQUISITE_CYCLE = "ERR_PREREQUISITE_CYCLE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_RECURRENCE_CONFIG_INVALID: 409,
    ApiErrorId.ERR_PREREQUISITE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_COURSE_HAS_OPEN_ENROLLMENTS: 409,
    ApiErrorId.ERR_PATH_EMPTY: 409,
    ApiErrorId.ERR_PATH_STEP_COURSE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_PATH_SEQUENCE_INVALID: 409,
    ApiErrorId.ERR_PATH_HAS_OPEN_ENROLLMENTS: 409,
    ApiErrorId.ERR_COURSE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_PREREQUISITE_NOT_MET: 409,
    ApiErrorId.ERR_PATH_STEP_LOCKED: 409,
    ApiErrorId.ERR_ATTEMPTS_EXHAUSTED: 409,
    ApiErrorId.ERR_SESSION_ALREADY_OPEN: 409,
    ApiErrorId.ERR_ASSIGNMENT_RULE_OVERLAP: 409,
    ApiErrorId.ERR_PREREQUISITE_CYCLE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
