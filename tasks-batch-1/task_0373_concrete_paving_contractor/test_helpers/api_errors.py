"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PRECONDITION_NOT_MET = "ERR_PRECONDITION_NOT_MET"
    ERR_STALE_PROJECT_VERSION = "ERR_STALE_PROJECT_VERSION"
    ERR_WEATHER_OUT_OF_RANGE = "ERR_WEATHER_OUT_OF_RANGE"
    ERR_CURE_WINDOW_NOT_ELAPSED = "ERR_CURE_WINDOW_NOT_ELAPSED"
    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_EQUIPMENT_DOUBLE_BOOKED = "ERR_EQUIPMENT_DOUBLE_BOOKED"
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
    ERR_DRAW_EXCEEDS_CONTRACT = "ERR_DRAW_EXCEEDS_CONTRACT"
    ERR_DRAW_SEQUENCE_INVALID = "ERR_DRAW_SEQUENCE_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PRECONDITION_NOT_MET: 409,
    ApiErrorId.ERR_STALE_PROJECT_VERSION: 412,
    ApiErrorId.ERR_WEATHER_OUT_OF_RANGE: 409,
    ApiErrorId.ERR_CURE_WINDOW_NOT_ELAPSED: 409,
    ApiErrorId.ERR_CREW_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_EQUIPMENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_SEGREGATION_VIOLATION: 403,
    ApiErrorId.ERR_DRAW_EXCEEDS_CONTRACT: 409,
    ApiErrorId.ERR_DRAW_SEQUENCE_INVALID: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
