"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_VALUE = "ERR_DUPLICATE_VALUE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ACQUISITION_TYPE_MISMATCH = "ERR_ACQUISITION_TYPE_MISMATCH"
    ERR_CMN_REQUIRED = "ERR_CMN_REQUIRED"
    ERR_PRIOR_AUTH_REQUIRED = "ERR_PRIOR_AUTH_REQUIRED"
    ERR_SUPPLIER_NOT_ACCREDITED = "ERR_SUPPLIER_NOT_ACCREDITED"
    ERR_NO_PROOF_OF_DELIVERY = "ERR_NO_PROOF_OF_DELIVERY"
    ERR_POD_SIGNATURE_REQUIRED = "ERR_POD_SIGNATURE_REQUIRED"
    ERR_CMN_SIGNED_AFTER_ORDER = "ERR_CMN_SIGNED_AFTER_ORDER"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_RENTAL_CAP_REACHED = "ERR_RENTAL_CAP_REACHED"
    ERR_CYCLE_OVERLAP = "ERR_CYCLE_OVERLAP"
    ERR_RESUPPLY_TOO_SOON = "ERR_RESUPPLY_TOO_SOON"
    ERR_NOT_A_CPAP_ORDER = "ERR_NOT_A_CPAP_ORDER"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_VALUE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ACQUISITION_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_CMN_REQUIRED: 422,
    ApiErrorId.ERR_PRIOR_AUTH_REQUIRED: 422,
    ApiErrorId.ERR_SUPPLIER_NOT_ACCREDITED: 422,
    ApiErrorId.ERR_NO_PROOF_OF_DELIVERY: 422,
    ApiErrorId.ERR_POD_SIGNATURE_REQUIRED: 422,
    ApiErrorId.ERR_CMN_SIGNED_AFTER_ORDER: 422,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_RENTAL_CAP_REACHED: 422,
    ApiErrorId.ERR_CYCLE_OVERLAP: 422,
    ApiErrorId.ERR_RESUPPLY_TOO_SOON: 422,
    ApiErrorId.ERR_NOT_A_CPAP_ORDER: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
