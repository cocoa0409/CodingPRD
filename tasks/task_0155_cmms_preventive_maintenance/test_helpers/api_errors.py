"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SKILL_INSUFFICIENT = "ERR_SKILL_INSUFFICIENT"
    ERR_SCHEDULE_CONFIG_INVALID = "ERR_SCHEDULE_CONFIG_INVALID"
    ERR_METER_NOT_MONOTONIC = "ERR_METER_NOT_MONOTONIC"
    ERR_DOWNTIME_OVERLAP = "ERR_DOWNTIME_OVERLAP"
    ERR_DOWNTIME_INTERVAL_INVALID = "ERR_DOWNTIME_INTERVAL_INVALID"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_BACKLOG_EXCEEDED = "ERR_BACKLOG_EXCEEDED"
    ERR_WARRANTY_EXPIRED = "ERR_WARRANTY_EXPIRED"
    ERR_PARTS_NOT_COMMITTED = "ERR_PARTS_NOT_COMMITTED"
    ERR_DOWNTIME_OPEN = "ERR_DOWNTIME_OPEN"
    ERR_DUPLICATE_SKU = "ERR_DUPLICATE_SKU"
    ERR_ASSET_BUSY = "ERR_ASSET_BUSY"
    ERR_PM_NOT_DUE = "ERR_PM_NOT_DUE"
    ERR_TECH_DOUBLE_BOOKED = "ERR_TECH_DOUBLE_BOOKED"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SKILL_INSUFFICIENT: 422,
    ApiErrorId.ERR_SCHEDULE_CONFIG_INVALID: 422,
    ApiErrorId.ERR_METER_NOT_MONOTONIC: 422,
    ApiErrorId.ERR_DOWNTIME_OVERLAP: 409,
    ApiErrorId.ERR_DOWNTIME_INTERVAL_INVALID: 422,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 422,
    ApiErrorId.ERR_BACKLOG_EXCEEDED: 422,
    ApiErrorId.ERR_WARRANTY_EXPIRED: 422,
    ApiErrorId.ERR_PARTS_NOT_COMMITTED: 409,
    ApiErrorId.ERR_DOWNTIME_OPEN: 409,
    ApiErrorId.ERR_DUPLICATE_SKU: 409,
    ApiErrorId.ERR_ASSET_BUSY: 409,
    ApiErrorId.ERR_PM_NOT_DUE: 409,
    ApiErrorId.ERR_TECH_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
