"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_NO_QUALIFYING_WEATHER = "ERR_NO_QUALIFYING_WEATHER"
    ERR_RESCHEDULE_LIMIT = "ERR_RESCHEDULE_LIMIT"
    ERR_DATE_OUT_OF_SEASON = "ERR_DATE_OUT_OF_SEASON"
    ERR_GUARANTEE_EXPIRED = "ERR_GUARANTEE_EXPIRED"
    ERR_ZONE_NOT_TREATABLE = "ERR_ZONE_NOT_TREATABLE"
    ERR_REGION_MISMATCH = "ERR_REGION_MISMATCH"
    ERR_ROUTE_AT_CAPACITY = "ERR_ROUTE_AT_CAPACITY"
    ERR_RETREAT_ALREADY_EXISTS = "ERR_RETREAT_ALREADY_EXISTS"
    ERR_UNDERPAYMENT = "ERR_UNDERPAYMENT"
    ERR_NO_APPLICATION_LOGGED = "ERR_NO_APPLICATION_LOGGED"
    ERR_SUBSCRIPTION_NOT_ACTIVE = "ERR_SUBSCRIPTION_NOT_ACTIVE"
    ERR_ROUTE_NOT_EMPTY = "ERR_ROUTE_NOT_EMPTY"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_NO_QUALIFYING_WEATHER: 409,
    ApiErrorId.ERR_RESCHEDULE_LIMIT: 409,
    ApiErrorId.ERR_DATE_OUT_OF_SEASON: 409,
    ApiErrorId.ERR_GUARANTEE_EXPIRED: 409,
    ApiErrorId.ERR_ZONE_NOT_TREATABLE: 409,
    ApiErrorId.ERR_REGION_MISMATCH: 409,
    ApiErrorId.ERR_ROUTE_AT_CAPACITY: 409,
    ApiErrorId.ERR_RETREAT_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_UNDERPAYMENT: 402,
    ApiErrorId.ERR_NO_APPLICATION_LOGGED: 409,
    ApiErrorId.ERR_SUBSCRIPTION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ROUTE_NOT_EMPTY: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
