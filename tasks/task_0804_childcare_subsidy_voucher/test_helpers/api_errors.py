    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DETERMINATION_FAMILY_MISMATCH = "ERR_DETERMINATION_FAMILY_MISMATCH"
    ERR_PROVIDER_NOT_LICENSED = "ERR_PROVIDER_NOT_LICENSED"
