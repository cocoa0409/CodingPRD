"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can cross-check
HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # 401 / 403 auth
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_SHOP_OWNER = "ERR_NOT_SHOP_OWNER"
    # 400 validation
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_RATING = "ERR_INVALID_RATING"
    ERR_PERSONALIZATION_TOO_LONG = "ERR_PERSONALIZATION_TOO_LONG"
    ERR_INVALID_RESOLUTION = "ERR_INVALID_RESOLUTION"
    ERR_RESTOCK_INVALID_QTY = "ERR_RESTOCK_INVALID_QTY"
    # 404 not found
    ERR_SHOP_NOT_FOUND = "ERR_SHOP_NOT_FOUND"
    ERR_SHIPPING_PROFILE_NOT_FOUND = "ERR_SHIPPING_PROFILE_NOT_FOUND"
    ERR_MATERIAL_NOT_FOUND = "ERR_MATERIAL_NOT_FOUND"
    ERR_LISTING_NOT_FOUND = "ERR_LISTING_NOT_FOUND"
    ERR_VACATION_PERIOD_NOT_FOUND = "ERR_VACATION_PERIOD_NOT_FOUND"
    ERR_ORDER_NOT_FOUND = "ERR_ORDER_NOT_FOUND"
    ERR_REVIEW_NOT_FOUND = "ERR_REVIEW_NOT_FOUND"
    ERR_CASE_NOT_FOUND = "ERR_CASE_NOT_FOUND"
    ERR_PAYOUT_NOT_FOUND = "ERR_PAYOUT_NOT_FOUND"
    # 409 state / conflict
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LISTING_NOT_PURCHASABLE = "ERR_LISTING_NOT_PURCHASABLE"
    ERR_VACATION_OVERLAP = "ERR_VACATION_OVERLAP"
    ERR_PRODUCTION_CAPACITY_EXCEEDED = "ERR_PRODUCTION_CAPACITY_EXCEEDED"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_DUPLICATE_REVIEW = "ERR_DUPLICATE_REVIEW"
    ERR_PAYOUT_HAS_OPEN_CASE = "ERR_PAYOUT_HAS_OPEN_CASE"
    # 422 business
    ERR_SHOP_ON_VACATION = "ERR_SHOP_ON_VACATION"
    ERR_PERSONALIZATION_REQUIRED = "ERR_PERSONALIZATION_REQUIRED"
    ERR_REVIEW_NOT_ALLOWED = "ERR_REVIEW_NOT_ALLOWED"
    ERR_CASE_NOT_ALLOWED = "ERR_CASE_NOT_ALLOWED"
    ERR_PAYOUT_NOT_ELIGIBLE = "ERR_PAYOUT_NOT_ELIGIBLE"
    # 412 optimistic concurrency
    ERR_STALE_SHOP_VERSION = "ERR_STALE_SHOP_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_SHOP_OWNER: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_RATING: 400,
    ApiErrorId.ERR_PERSONALIZATION_TOO_LONG: 400,
    ApiErrorId.ERR_INVALID_RESOLUTION: 400,
    ApiErrorId.ERR_RESTOCK_INVALID_QTY: 400,
    ApiErrorId.ERR_SHOP_NOT_FOUND: 404,
    ApiErrorId.ERR_SHIPPING_PROFILE_NOT_FOUND: 404,
    ApiErrorId.ERR_MATERIAL_NOT_FOUND: 404,
    ApiErrorId.ERR_LISTING_NOT_FOUND: 404,
    ApiErrorId.ERR_VACATION_PERIOD_NOT_FOUND: 404,
    ApiErrorId.ERR_ORDER_NOT_FOUND: 404,
    ApiErrorId.ERR_REVIEW_NOT_FOUND: 404,
    ApiErrorId.ERR_CASE_NOT_FOUND: 404,
    ApiErrorId.ERR_PAYOUT_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LISTING_NOT_PURCHASABLE: 409,
    ApiErrorId.ERR_VACATION_OVERLAP: 409,
    ApiErrorId.ERR_PRODUCTION_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_DUPLICATE_REVIEW: 409,
    ApiErrorId.ERR_PAYOUT_HAS_OPEN_CASE: 409,
    ApiErrorId.ERR_SHOP_ON_VACATION: 422,
    ApiErrorId.ERR_PERSONALIZATION_REQUIRED: 422,
    ApiErrorId.ERR_REVIEW_NOT_ALLOWED: 422,
    ApiErrorId.ERR_CASE_NOT_ALLOWED: 422,
    ApiErrorId.ERR_PAYOUT_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_STALE_SHOP_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
