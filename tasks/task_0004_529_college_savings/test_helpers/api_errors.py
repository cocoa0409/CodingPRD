"""Error IDs and HTTP status mapping for the 529 College Savings API."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_NOT_FOUND = "ERR_REFERENCED_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ACCOUNT_VERSION = "ERR_STALE_ACCOUNT_VERSION"
    ERR_BENEFICIARY_NOT_FAMILY_MEMBER = "ERR_BENEFICIARY_NOT_FAMILY_MEMBER"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_REVISION_LIMIT_EXCEEDED = "ERR_REVISION_LIMIT_EXCEEDED"
    ERR_REVERSE_WINDOW_CLOSED = "ERR_REVERSE_WINDOW_CLOSED"
    ERR_UNSUPPORTED_STATE_CODE = "ERR_UNSUPPORTED_STATE_CODE"
    ERR_EMAIL_TAKEN = "ERR_EMAIL_TAKEN"
    ERR_FORM_ALREADY_EXISTS = "ERR_FORM_ALREADY_EXISTS"
    ERR_INCENTIVE_ALREADY_EXISTS = "ERR_INCENTIVE_ALREADY_EXISTS"
    ERR_FORM_PREMATURE_ISSUANCE = "ERR_FORM_PREMATURE_ISSUANCE"
    ERR_FORM_CORRECTION_WINDOW_CLOSED = "ERR_FORM_CORRECTION_WINDOW_CLOSED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ACCOUNT_VERSION: 412,
    ApiErrorId.ERR_BENEFICIARY_NOT_FAMILY_MEMBER: 422,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 422,
    ApiErrorId.ERR_REVISION_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_REVERSE_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_UNSUPPORTED_STATE_CODE: 422,
    ApiErrorId.ERR_EMAIL_TAKEN: 409,
    ApiErrorId.ERR_FORM_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_INCENTIVE_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_FORM_PREMATURE_ISSUANCE: 422,
    ApiErrorId.ERR_FORM_CORRECTION_WINDOW_CLOSED: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
