"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_BOOKING_OWNER = "ERR_NOT_BOOKING_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_KEY = "ERR_DUPLICATE_KEY"
    ERR_QTY_OUT_OF_RANGE = "ERR_QTY_OUT_OF_RANGE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_BOOKING_LOCKED = "ERR_BOOKING_LOCKED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_BOOTH_INTERVAL_CONFLICT = "ERR_BOOTH_INTERVAL_CONFLICT"
    ERR_NO_BOOTH_AVAILABLE = "ERR_NO_BOOTH_AVAILABLE"
    ERR_ATTENDANT_INTERVAL_CONFLICT = "ERR_ATTENDANT_INTERVAL_CONFLICT"
    ERR_NO_ATTENDANT_AVAILABLE = "ERR_NO_ATTENDANT_AVAILABLE"
    ERR_DEPOSIT_AMOUNT_MISMATCH = "ERR_DEPOSIT_AMOUNT_MISMATCH"
    ERR_BALANCE_AMOUNT_MISMATCH = "ERR_BALANCE_AMOUNT_MISMATCH"
    ERR_REFUND_AMOUNT_MISMATCH = "ERR_REFUND_AMOUNT_MISMATCH"
    ERR_GALLERY_EMPTY = "ERR_GALLERY_EMPTY"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_BOOKING_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_KEY: 409,
    ApiErrorId.ERR_QTY_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_BOOKING_LOCKED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_BOOTH_INTERVAL_CONFLICT: 409,
    ApiErrorId.ERR_NO_BOOTH_AVAILABLE: 409,
    ApiErrorId.ERR_ATTENDANT_INTERVAL_CONFLICT: 409,
    ApiErrorId.ERR_NO_ATTENDANT_AVAILABLE: 409,
    ApiErrorId.ERR_DEPOSIT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_BALANCE_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_REFUND_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_GALLERY_EMPTY: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
