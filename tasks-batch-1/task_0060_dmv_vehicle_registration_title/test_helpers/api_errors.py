"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_VIN = "ERR_INVALID_VIN"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VIN_NOT_VERIFIED = "ERR_VIN_NOT_VERIFIED"
    ERR_TRANSFER_REQUIRES_TITLE = "ERR_TRANSFER_REQUIRES_TITLE"
    ERR_SALVAGE_INSPECTION_REQUIRED = "ERR_SALVAGE_INSPECTION_REQUIRED"
    ERR_EMISSIONS_REQUIRED = "ERR_EMISSIONS_REQUIRED"
    ERR_TITLE_NOT_ISSUED = "ERR_TITLE_NOT_ISSUED"
    ERR_FEES_UNPAID = "ERR_FEES_UNPAID"
    ERR_LIEN_REQUIRES_TITLE = "ERR_LIEN_REQUIRES_TITLE"
    ERR_PLATE_NUMBER_TAKEN = "ERR_PLATE_NUMBER_TAKEN"
    ERR_REGISTRATION_TERM_OVERLAP = "ERR_REGISTRATION_TERM_OVERLAP"
    ERR_PLATE_ALREADY_ASSIGNED = "ERR_PLATE_ALREADY_ASSIGNED"
    ERR_PLATE_NOT_ELECTRONIC = "ERR_PLATE_NOT_ELECTRONIC"
    ERR_REGISTRATION_NOT_ACTIVE = "ERR_REGISTRATION_NOT_ACTIVE"
    ERR_DOCUMENTS_INCOMPLETE = "ERR_DOCUMENTS_INCOMPLETE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_VIN: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VIN_NOT_VERIFIED: 409,
    ApiErrorId.ERR_TRANSFER_REQUIRES_TITLE: 409,
    ApiErrorId.ERR_SALVAGE_INSPECTION_REQUIRED: 409,
    ApiErrorId.ERR_EMISSIONS_REQUIRED: 409,
    ApiErrorId.ERR_TITLE_NOT_ISSUED: 409,
    ApiErrorId.ERR_FEES_UNPAID: 402,
    ApiErrorId.ERR_LIEN_REQUIRES_TITLE: 409,
    ApiErrorId.ERR_PLATE_NUMBER_TAKEN: 409,
    ApiErrorId.ERR_REGISTRATION_TERM_OVERLAP: 409,
    ApiErrorId.ERR_PLATE_ALREADY_ASSIGNED: 409,
    ApiErrorId.ERR_PLATE_NOT_ELECTRONIC: 409,
    ApiErrorId.ERR_REGISTRATION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_DOCUMENTS_INCOMPLETE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
