ERR_NO_INCOME_DOCUMENTS = ("ERR_NO_INCOME_DOCUMENTS", 409)
ERR_ITEMIZED_REQUIRES_SCHEDULE_A = ("ERR_ITEMIZED_REQUIRES_SCHEDULE_A", 409)
ERR_RETURN_NOT_COMPUTED = ("ERR_RETURN_NOT_COMPUTED", 409)
