    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_CARD_TYPE_RETIRED = "ERR_CARD_TYPE_RETIRED"
    ERR_TRAINER_INACTIVE = "ERR_TRAINER_INACTIVE"
    ERR_SPECIALTY_MISMATCH = "ERR_SPECIALTY_MISMATCH"
    ERR_SLOT_ALREADY_RESERVED = "ERR_SLOT_ALREADY_RESERVED"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_CLASS_OVERLAP = "ERR_CLASS_OVERLAP"
    ERR_CAPACITY_REACHED = "ERR_CAPACITY_REACHED"
    ERR_CANCEL_WINDOW_EXPIRED = "ERR_CANCEL_WINDOW_EXPIRED"
    ERR_REFUND_NOT_ELIGIBLE = "ERR_REFUND_NOT_ELIGIBLE"
    ERR_REFUND_FROZEN_CARD_BLOCKED = "ERR_REFUND_FROZEN_CARD_BLOCKED"
