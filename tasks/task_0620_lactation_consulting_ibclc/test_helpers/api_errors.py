"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can cross-check the HTTP status automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth / existence
    ERR_MISSING_AUTH_CONTEXT = "ERR_MISSING_AUTH_CONTEXT"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_REFERENCED_RESOURCE_NOT_FOUND = "ERR_REFERENCED_RESOURCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    # referential / cross-entity
    ERR_CROSS_PRACTICE_REFERENCE = "ERR_CROSS_PRACTICE_REFERENCE"
    ERR_ACA_PREVENTIVE_DISABLED = "ERR_ACA_PREVENTIVE_DISABLED"
    # state
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CONSULT_NOT_SCHEDULED = "ERR_CONSULT_NOT_SCHEDULED"
    ERR_CONSULT_NOT_IN_PROGRESS = "ERR_CONSULT_NOT_IN_PROGRESS"
    ERR_CONSULT_NOT_STARTABLE = "ERR_CONSULT_NOT_STARTABLE"
    ERR_CONSULT_NOT_CANCELLABLE = "ERR_CONSULT_NOT_CANCELLABLE"
    ERR_CONSULT_NOT_COMPLETED = "ERR_CONSULT_NOT_COMPLETED"
    ERR_NO_FEEDING_ASSESSMENT = "ERR_NO_FEEDING_ASSESSMENT"
    ERR_CLIENT_SUSPENDED = "ERR_CLIENT_SUSPENDED"
    ERR_SUPERBILL_NOT_SUBMITTABLE = "ERR_SUPERBILL_NOT_SUBMITTABLE"
    ERR_SUPERBILL_NOT_SUBMITTED = "ERR_SUPERBILL_NOT_SUBMITTED"
    ERR_SUPERBILL_NOT_VOIDABLE = "ERR_SUPERBILL_NOT_VOIDABLE"
    ERR_DME_NOT_PENDING = "ERR_DME_NOT_PENDING"
    ERR_DME_WINDOW_NOT_MET = "ERR_DME_WINDOW_NOT_MET"
    ERR_PLAN_NOT_OPEN = "ERR_PLAN_NOT_OPEN"
    ERR_PLAN_CLOSED = "ERR_PLAN_CLOSED"
    ERR_REFERRAL_NOT_OPEN = "ERR_REFERRAL_NOT_OPEN"
    # temporal / fiscal
    ERR_CONSULTANT_DOUBLE_BOOKED = "ERR_CONSULTANT_DOUBLE_BOOKED"
    ERR_CLIENT_DOUBLE_BOOKED = "ERR_CLIENT_DOUBLE_BOOKED"
    ERR_NO_PACKAGE_CREDITS = "ERR_NO_PACKAGE_CREDITS"
    # concurrency
    ERR_STALE_CLIENT_VERSION = "ERR_STALE_CLIENT_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH_CONTEXT: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_CROSS_PRACTICE_REFERENCE: 409,
    ApiErrorId.ERR_ACA_PREVENTIVE_DISABLED: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CONSULT_NOT_SCHEDULED: 409,
    ApiErrorId.ERR_CONSULT_NOT_IN_PROGRESS: 409,
    ApiErrorId.ERR_CONSULT_NOT_STARTABLE: 409,
    ApiErrorId.ERR_CONSULT_NOT_CANCELLABLE: 409,
    ApiErrorId.ERR_CONSULT_NOT_COMPLETED: 409,
    ApiErrorId.ERR_NO_FEEDING_ASSESSMENT: 409,
    ApiErrorId.ERR_CLIENT_SUSPENDED: 409,
    ApiErrorId.ERR_SUPERBILL_NOT_SUBMITTABLE: 409,
    ApiErrorId.ERR_SUPERBILL_NOT_SUBMITTED: 409,
    ApiErrorId.ERR_SUPERBILL_NOT_VOIDABLE: 409,
    ApiErrorId.ERR_DME_NOT_PENDING: 409,
    ApiErrorId.ERR_DME_WINDOW_NOT_MET: 409,
    ApiErrorId.ERR_PLAN_NOT_OPEN: 409,
    ApiErrorId.ERR_PLAN_CLOSED: 409,
    ApiErrorId.ERR_REFERRAL_NOT_OPEN: 409,
    ApiErrorId.ERR_CONSULTANT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CLIENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_NO_PACKAGE_CREDITS: 402,
    ApiErrorId.ERR_STALE_CLIENT_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
