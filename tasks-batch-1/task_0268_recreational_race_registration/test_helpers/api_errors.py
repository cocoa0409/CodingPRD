"""Error IDs and HTTP status mapping (PRD §5).

The mapping is registered with the framework so validate_error() can auto-check
the HTTP status that accompanies each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_RELATION_MISMATCH = "ERR_RELATION_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_REGISTRATION_CLOSED = "ERR_REGISTRATION_CLOSED"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_NO_ACTIVE_PRICING_TIER = "ERR_NO_ACTIVE_PRICING_TIER"
    ERR_FUNDRAISING_MINIMUM_NOT_MET = "ERR_FUNDRAISING_MINIMUM_NOT_MET"
    ERR_WAVE_FULL = "ERR_WAVE_FULL"
    ERR_DISTANCE_FULL = "ERR_DISTANCE_FULL"
    ERR_STALE_DISTANCE_VERSION = "ERR_STALE_DISTANCE_VERSION"
    ERR_PACKET_ALREADY_ISSUED = "ERR_PACKET_ALREADY_ISSUED"
    ERR_PACKET_NOT_ELIGIBLE = "ERR_PACKET_NOT_ELIGIBLE"
    ERR_INVALID_TIMING = "ERR_INVALID_TIMING"
    ERR_TARGET_EVENT_INVALID = "ERR_TARGET_EVENT_INVALID"
    ERR_DUPLICATE_PRICING_TIER = "ERR_DUPLICATE_PRICING_TIER"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_RELATION_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_REGISTRATION_CLOSED: 409,
    ApiErrorId.ERR_OFFER_EXPIRED: 409,
    ApiErrorId.ERR_NO_ACTIVE_PRICING_TIER: 409,
    ApiErrorId.ERR_FUNDRAISING_MINIMUM_NOT_MET: 409,
    ApiErrorId.ERR_WAVE_FULL: 409,
    ApiErrorId.ERR_DISTANCE_FULL: 409,
    ApiErrorId.ERR_STALE_DISTANCE_VERSION: 412,
    ApiErrorId.ERR_PACKET_ALREADY_ISSUED: 409,
    ApiErrorId.ERR_PACKET_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_INVALID_TIMING: 422,
    ApiErrorId.ERR_TARGET_EVENT_INVALID: 409,
    ApiErrorId.ERR_DUPLICATE_PRICING_TIER: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
