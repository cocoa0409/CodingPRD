"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_OWNERSHIP_VIOLATION = "ERR_OWNERSHIP_VIOLATION"

    # Existence — PRD §2.8
    ERR_CUSTOMER_NOT_FOUND = "ERR_CUSTOMER_NOT_FOUND"
    ERR_ACCOUNT_NOT_FOUND = "ERR_ACCOUNT_NOT_FOUND"
    ERR_OPTIONS_APPROVAL_NOT_FOUND = "ERR_OPTIONS_APPROVAL_NOT_FOUND"
    ERR_ORDER_NOT_FOUND = "ERR_ORDER_NOT_FOUND"
    ERR_TRANSFER_NOT_FOUND = "ERR_TRANSFER_NOT_FOUND"

    # Validation / state — PRD §2.9, §5
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ACCOUNT_NOT_APPROVED = "ERR_ACCOUNT_NOT_APPROVED"
    ERR_KYC_NOT_VERIFIED = "ERR_KYC_NOT_VERIFIED"
    ERR_TRADING_FROZEN = "ERR_TRADING_FROZEN"

    # KYC — PRD §3.1
    ERR_KYC_INELIGIBLE_COUNTRY = "ERR_KYC_INELIGIBLE_COUNTRY"
    ERR_KYC_AGE_INELIGIBLE = "ERR_KYC_AGE_INELIGIBLE"
    ERR_W9_NAME_MISMATCH = "ERR_W9_NAME_MISMATCH"

    # Options — PRD §3.2, §3.3
    ERR_OPTIONS_LEVEL_INSUFFICIENT = "ERR_OPTIONS_LEVEL_INSUFFICIENT"
    ERR_OPTIONS_LEVEL_EXCEEDS_ELIGIBILITY = (
        "ERR_OPTIONS_LEVEL_EXCEEDS_ELIGIBILITY"
    )
    ERR_REVISION_LIMIT_REACHED = "ERR_REVISION_LIMIT_REACHED"
    ERR_OPTIONS_APPROVAL_IN_PROGRESS = (
        "ERR_OPTIONS_APPROVAL_IN_PROGRESS"
    )

    # Orders — PRD §3.3, §3.4
    ERR_ORDER_PRICE_MISSING = "ERR_ORDER_PRICE_MISSING"
    ERR_ORDER_STRATEGY_REQUIRED = "ERR_ORDER_STRATEGY_REQUIRED"
    ERR_FILL_PRICE_VIOLATES_LIMITS = "ERR_FILL_PRICE_VIOLATES_LIMITS"
    ERR_INSUFFICIENT_MARGIN = "ERR_INSUFFICIENT_MARGIN"
    ERR_PDT_EQUITY_BELOW_MINIMUM = "ERR_PDT_EQUITY_BELOW_MINIMUM"

    # ACAT — PRD §3.5, §3.6
    ERR_TRANSFER_ALREADY_PENDING = "ERR_TRANSFER_ALREADY_PENDING"
    ERR_OPEN_ORDERS_BLOCK_TRANSFER = "ERR_OPEN_ORDERS_BLOCK_TRANSFER"
    ERR_ACCOUNT_HAS_DEPENDENCIES = "ERR_ACCOUNT_HAS_DEPENDENCIES"


