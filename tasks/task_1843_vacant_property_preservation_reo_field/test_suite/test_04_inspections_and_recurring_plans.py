class TestRecurringGenerationBudgetInvariant:
    def _setup_plan_with_one_generated(self):
        ctx = setup_portfolio(item_code="GRASS_CUT",
                              property_overrides={"heating_system": "NONE", "fixture_count": 4},
                              clock="2026-08-01T00:00:00Z", with_crew=False)
        plan = create_recurring_plan(ctx["property_id"], service_type="GRASS_CUT",
                                     season_start_md="08-01", season_end_md="08-31",
                                     interval_days=1, max_per_season=2)
        sweep = run_daily_sweep()
        return ctx, plan, sweep["generated_work_order_ids"][0]

    def test_generation_consumes_and_cancel_restores_budget(self, api):
        """PRD: "Each generation increments `generated_this_season`" and "when the
        cancelled or expired order's `source` is `RECURRING_AUTO` and it carries a
        `recurring_plan_id`, the plan's `generated_this_season` is decremented by
        one, restoring the season allowance the generation consumed."

        Design: Difficulty/compensating_invariant/recurring_generation_cancel_budget_invariant
        """
        ctx, plan, g1 = self._setup_plan_with_one_generated()
        mid = validate_success(api.get_recurring_plan(plan["id"], ADMIN))
        assert mid["generated_this_season"] == 1, f"generation consumed one unit, got {mid['generated_this_season']}"
        validate_success(api.cancel_work_order(g1, {"reason": "servicer stop"},
                                               make_servicer_headers(ctx["servicer_id"])))
        after = validate_success(api.get_recurring_plan(plan["id"], ADMIN))
        assert after["generated_this_season"] == 0, (
            f"cancellation compensated exactly one unit, got {after['generated_this_season']}")

    def test_restored_budget_allows_regeneration(self, api):
        """PRD: "an operation and its reversal leave the counter unchanged" (the
        counter-compensation invariant of "Cross-Resource Cascades and Consistent
        Reconciliation") and "The sweep generates a work order — `source`
        `RECURRING_AUTO`, with `due_date` set to the clock date plus
        `interval_days` — only when all four conditions hold".

        Design: Difficulty/compensating_invariant/recurring_generation_cancel_budget_invariant
        """
        ctx, plan, g1 = self._setup_plan_with_one_generated()
        validate_success(api.cancel_work_order(g1, {"reason": "servicer stop"},
                                               make_servicer_headers(ctx["servicer_id"])))
        set_clock("2026-08-02T00:00:00Z")
        sweep2 = run_daily_sweep()
        assert len(sweep2["generated_work_order_ids"]) == 1, (
            "restored budget allowed regeneration on the next interval day")
        final = validate_success(api.get_recurring_plan(plan["id"], ADMIN))
        assert final["generated_this_season"] == 1, (
            f"budget accounting conserved: 1 - 1 + 1 nets to 1, got {final['generated_this_season']}")


class TestRecurringGenerationInterval:
    def test_recurring_interval_exact_boundary(self, api):
        """PRD: "`last_generated_date` is null or at least `interval_days` have
        elapsed since it (exactly `interval_days` elapsed is enough)".

        Design: Corner/calculations/recurring_interval_exact_boundary
        """
        ctx = setup_portfolio(item_code="GRASS_CUT",
                              property_overrides={"heating_system": "NONE", "fixture_count": 4},
                              clock="2026-08-01T00:00:00Z", with_crew=False)
        plan = create_recurring_plan(ctx["property_id"], service_type="GRASS_CUT",
                                     season_start_md="07-01", season_end_md="09-30",
                                     interval_days=14, max_per_season=5)
        first = run_daily_sweep()
        assert len(first["generated_work_order_ids"]) == 1, "first generation has no interval gate"
        set_clock("2026-08-14T00:00:00Z")
        day13 = run_daily_sweep()
        assert day13["generated_work_order_ids"] == [], "13 elapsed days < interval 14 generates nothing"
        set_clock("2026-08-15T00:00:00Z")
        day14 = run_daily_sweep()
        assert len(day14["generated_work_order_ids"]) == 1, "14 >= 14 fires"
        plan_after = validate_success(api.get_recurring_plan(plan["id"], ADMIN))
        assert plan_after["generated_this_season"] == 2


class TestPlanTerminalAndSeasonGates:
    def test_recurring_plan_resume_after_end_returns_invalid_state(self, api):
        """PRD: "Ending a plan — from `ACTIVE` or `SUSPENDED` to the terminal
        `ENDED` — is a `VendorAdmin` action" and "Resumption — `SUSPENDED →
        ACTIVE`", so an ENDED plan fails "The target resource must be in a state
        that permits the requested transition; failures surface as
        `ERR_INVALID_STATE`".

        Design: Corner/state_machines/recurring_plan_resume_after_end_returns_invalid_state
        """
        ctx = setup_portfolio(with_allowable=False, with_crew=False,
                              property_overrides={"heating_system": "NONE", "fixture_count": 4})
        plan = create_recurring_plan(ctx["property_id"], service_type="GRASS_CUT",
                                     season_start_md="04-01", season_end_md="10-31",
                                     interval_days=14, max_per_season=6)
        validate_success(api.end_recurring_plan(plan["id"], ADMIN))
        resp = api.resume_recurring_plan(plan["id"], ADMIN)
        validate_error(resp, ApiErrorId.ERR_INVALID_STATE)

    def test_plan_resume_out_of_season_rejected(self, api):
        """PRD: "the clock date must lie within the plan's current-year season
        window, or the resume is rejected with `ERR_SEASON_WINDOW_CLOSED`".

        Design: Corner/errors/plan_resume_out_of_season_rejected
        """
        ctx = setup_portfolio(with_allowable=False, with_crew=False,
                              clock="2026-05-01T00:00:00Z",
                              property_overrides={"heating_system": "NONE", "fixture_count": 4})
        plan = create_recurring_plan(ctx["property_id"], service_type="GRASS_CUT",
                                     season_start_md="04-01", season_end_md="06-30",
                                     interval_days=14, max_per_season=6)
        validate_success(api.suspend_recurring_plan(plan["id"], ADMIN))
        set_clock("2026-08-01T00:00:00Z")
        resp = api.resume_recurring_plan(plan["id"], ADMIN)
        validate_error(resp, ApiErrorId.ERR_SEASON_WINDOW_CLOSED)
