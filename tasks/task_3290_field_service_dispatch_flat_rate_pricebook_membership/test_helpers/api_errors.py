"""Error identifiers and the HTTP status each one is carried on (PRD §5).

Registering the mapping with the framework lets `validate_error()` cross-check
the HTTP status automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NO_APPOINTMENT_LINES = "ERR_NO_APPOINTMENT_LINES"
    ERR_OVERRIDE_ALREADY_PENDING = "ERR_OVERRIDE_ALREADY_PENDING"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_WINDOW_INVALID = "ERR_WINDOW_INVALID"
    ERR_VISIT_OVERLAP = "ERR_VISIT_OVERLAP"
    ERR_NO_ELIGIBLE_TECHNICIAN = "ERR_NO_ELIGIBLE_TECHNICIAN"
    ERR_MEMBER_VISIT_SEQUENCE_INVALID = "ERR_MEMBER_VISIT_SEQUENCE_INVALID"
    ERR_PRICEBOOK_REVISION_NOT_PUBLISHED = "ERR_PRICEBOOK_REVISION_NOT_PUBLISHED"
    ERR_TECHNICIAN_CAPACITY_EXCEEDED = "ERR_TECHNICIAN_CAPACITY_EXCEEDED"
    ERR_DUPLICATE_VISIT_SEQUENCE = "ERR_DUPLICATE_VISIT_SEQUENCE"
    ERR_SUBSCRIPTION_TERM_EXCEEDED = "ERR_SUBSCRIPTION_TERM_EXCEEDED"
    ERR_OVERRIDE_EXCEEDS_LIMIT = "ERR_OVERRIDE_EXCEEDS_LIMIT"
    ERR_DISCOUNT_FLOOR_REACHED = "ERR_DISCOUNT_FLOOR_REACHED"
    ERR_OVER_COLLECTION = "ERR_OVER_COLLECTION"
    ERR_MEMBERSHIP_CANCEL_BLOCKED = "ERR_MEMBERSHIP_CANCEL_BLOCKED"
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_DESCRIPTION_TOO_SHORT = "ERR_DESCRIPTION_TOO_SHORT"
    ERR_CALL_NOT_REVIEWABLE = "ERR_CALL_NOT_REVIEWABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHORIZED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NO_APPOINTMENT_LINES: 409,
    ApiErrorId.ERR_OVERRIDE_ALREADY_PENDING: 409,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_WINDOW_INVALID: 400,
    ApiErrorId.ERR_VISIT_OVERLAP: 409,
    ApiErrorId.ERR_NO_ELIGIBLE_TECHNICIAN: 422,
    ApiErrorId.ERR_MEMBER_VISIT_SEQUENCE_INVALID: 422,
    ApiErrorId.ERR_PRICEBOOK_REVISION_NOT_PUBLISHED: 422,
    ApiErrorId.ERR_TECHNICIAN_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_DUPLICATE_VISIT_SEQUENCE: 409,
    ApiErrorId.ERR_SUBSCRIPTION_TERM_EXCEEDED: 422,
    ApiErrorId.ERR_OVERRIDE_EXCEEDS_LIMIT: 422,
    ApiErrorId.ERR_DISCOUNT_FLOOR_REACHED: 422,
    ApiErrorId.ERR_OVER_COLLECTION: 422,
    ApiErrorId.ERR_MEMBERSHIP_CANCEL_BLOCKED: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_DESCRIPTION_TOO_SHORT: 422,
    ApiErrorId.ERR_CALL_NOT_REVIEWABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Both the enum and its string value resolve to the same status.
HTTP_STATUS_CODES.update({k.value: v for k, v in list(HTTP_STATUS_CODES.items())})

set_error_http_status_map(HTTP_STATUS_CODES)