"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_DEAL_CODE = "ERR_DUPLICATE_DEAL_CODE"
    ERR_DUPLICATE_PERIOD = "ERR_DUPLICATE_PERIOD"
    ERR_NONMONOTONIC_PERIOD = "ERR_NONMONOTONIC_PERIOD"
    ERR_FUTURE_PERIOD = "ERR_FUTURE_PERIOD"
    ERR_ASSUMPTION_MISMATCH = "ERR_ASSUMPTION_MISMATCH"
    ERR_SCENARIO_NOT_COMPUTED = "ERR_SCENARIO_NOT_COMPUTED"
    ERR_NOI_NONPOSITIVE = "ERR_NOI_NONPOSITIVE"
    ERR_PROMOTE_REGRESSIVE = "ERR_PROMOTE_REGRESSIVE"
    ERR_DUPLICATE_VOTE = "ERR_DUPLICATE_VOTE"
    ERR_SEG_DUTIES = "ERR_SEG_DUTIES"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_DEAL_CODE: 409,
    ApiErrorId.ERR_DUPLICATE_PERIOD: 409,
    ApiErrorId.ERR_NONMONOTONIC_PERIOD: 422,
    ApiErrorId.ERR_FUTURE_PERIOD: 422,
    ApiErrorId.ERR_ASSUMPTION_MISMATCH: 422,
    ApiErrorId.ERR_SCENARIO_NOT_COMPUTED: 422,
    ApiErrorId.ERR_NOI_NONPOSITIVE: 422,
    ApiErrorId.ERR_PROMOTE_REGRESSIVE: 422,
    ApiErrorId.ERR_DUPLICATE_VOTE: 409,
    ApiErrorId.ERR_SEG_DUTIES: 403,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
