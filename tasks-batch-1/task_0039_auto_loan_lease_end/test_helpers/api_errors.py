"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_NO_ACTIVE_RATE_CARD = "ERR_NO_ACTIVE_RATE_CARD"
    ERR_VEHICLE_UNAVAILABLE = "ERR_VEHICLE_UNAVAILABLE"
    ERR_LOAN_NOT_PAYABLE = "ERR_LOAN_NOT_PAYABLE"
    ERR_LOAN_TERM_COMPLETE = "ERR_LOAN_TERM_COMPLETE"
    ERR_LEASE_NOT_MATURABLE = "ERR_LEASE_NOT_MATURABLE"
    ERR_LEASE_NOT_ELECTABLE = "ERR_LEASE_NOT_ELECTABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DEFAULT_THRESHOLD_NOT_MET = "ERR_DEFAULT_THRESHOLD_NOT_MET"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_PAYOFF_AMOUNT_MISMATCH = "ERR_PAYOFF_AMOUNT_MISMATCH"
    ERR_MILEAGE_SCHEDULE_INVALID = "ERR_MILEAGE_SCHEDULE_INVALID"
    ERR_RENEW_TERM_INVALID = "ERR_RENEW_TERM_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_NO_ACTIVE_RATE_CARD: 409,
    ApiErrorId.ERR_VEHICLE_UNAVAILABLE: 409,
    ApiErrorId.ERR_LOAN_NOT_PAYABLE: 409,
    ApiErrorId.ERR_LOAN_TERM_COMPLETE: 409,
    ApiErrorId.ERR_LEASE_NOT_MATURABLE: 409,
    ApiErrorId.ERR_LEASE_NOT_ELECTABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DEFAULT_THRESHOLD_NOT_MET: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 409,
    ApiErrorId.ERR_PAYOFF_AMOUNT_MISMATCH: 409,
    ApiErrorId.ERR_MILEAGE_SCHEDULE_INVALID: 422,
    ApiErrorId.ERR_RENEW_TERM_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
