"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can cross-check the HTTP status code automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"
    ERR_TRIP_TYPE_FIELDS = "ERR_TRIP_TYPE_FIELDS"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FLIGHT_NOT_APPLICABLE = "ERR_FLIGHT_NOT_APPLICABLE"
    ERR_WAIT_SEQUENCE = "ERR_WAIT_SEQUENCE"
    ERR_RESOURCE_UNAVAILABLE = "ERR_RESOURCE_UNAVAILABLE"
    ERR_CHAUFFEUR_DOUBLE_BOOKED = "ERR_CHAUFFEUR_DOUBLE_BOOKED"
    ERR_VEHICLE_TURNAROUND_VIOLATION = "ERR_VEHICLE_TURNAROUND_VIOLATION"
    ERR_FULFILLMENT_CONFLICT = "ERR_FULFILLMENT_CONFLICT"
    ERR_AFFILIATE_INELIGIBLE = "ERR_AFFILIATE_INELIGIBLE"
    ERR_NOT_BILLABLE = "ERR_NOT_BILLABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ACCOUNT_SUSPENDED = "ERR_ACCOUNT_SUSPENDED"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"
    ERR_DUPLICATE_PLATE = "ERR_DUPLICATE_PLATE"
    ERR_DUPLICATE_CLASS_CODE = "ERR_DUPLICATE_CLASS_CODE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_TIME_WINDOW: 422,
    ApiErrorId.ERR_TRIP_TYPE_FIELDS: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FLIGHT_NOT_APPLICABLE: 409,
    ApiErrorId.ERR_WAIT_SEQUENCE: 409,
    ApiErrorId.ERR_RESOURCE_UNAVAILABLE: 409,
    ApiErrorId.ERR_CHAUFFEUR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_VEHICLE_TURNAROUND_VIOLATION: 409,
    ApiErrorId.ERR_FULFILLMENT_CONFLICT: 409,
    ApiErrorId.ERR_AFFILIATE_INELIGIBLE: 409,
    ApiErrorId.ERR_NOT_BILLABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ACCOUNT_SUSPENDED: 409,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
    ApiErrorId.ERR_DUPLICATE_PLATE: 409,
    ApiErrorId.ERR_DUPLICATE_CLASS_CODE: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
