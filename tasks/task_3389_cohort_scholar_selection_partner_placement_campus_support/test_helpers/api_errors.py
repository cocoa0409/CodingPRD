    ERR_INTERNSHIP_OVERLAP = "ERR_INTERNSHIP_OVERLAP"
    ERR_COHORT_SIZE_INVALID = "ERR_COHORT_SIZE_INVALID"
    # Capacity / quota (tier 11)
    ERR_NOMINATION_QUOTA_EXCEEDED = "ERR_NOMINATION_QUOTA_EXCEEDED"
    ERR_COHORT_FULL = "ERR_COHORT_FULL"
    # Threshold gates (tier 12)
    ERR_INSUFFICIENT_EVALUATIONS = "ERR_INSUFFICIENT_EVALUATIONS"
    ERR_CUTOFF_NOT_MET = "ERR_CUTOFF_NOT_MET"
    ERR_RENEWAL_THRESHOLDS_NOT_MET = "ERR_RENEWAL_THRESHOLDS_NOT_MET"


