"""Complete error catalogue (PRD section 5)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status=None, message=None):
        super(ApiError, self).__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status if http_status is not None else \
            ERROR_CATALOG.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(error_id, error_id)


