"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ORDER_EMPTY = "ERR_ORDER_EMPTY"
    ERR_FILE_NOT_PRINTABLE = "ERR_FILE_NOT_PRINTABLE"
    ERR_MATERIAL_RETIRED = "ERR_MATERIAL_RETIRED"
    ERR_PROCESS_MISMATCH = "ERR_PROCESS_MISMATCH"
    ERR_MACHINE_OFFLINE = "ERR_MACHINE_OFFLINE"
    ERR_MACHINE_BUSY = "ERR_MACHINE_BUSY"
    ERR_MACHINE_SLOT_CONFLICT = "ERR_MACHINE_SLOT_CONFLICT"
    ERR_MACHINE_CAPACITY_EXCEEDED = "ERR_MACHINE_CAPACITY_EXCEEDED"
    ERR_STATION_SLOT_CONFLICT = "ERR_STATION_SLOT_CONFLICT"
    ERR_SPOOL_INSUFFICIENT = "ERR_SPOOL_INSUFFICIENT"
    ERR_ORDER_NOT_ESCROWED = "ERR_ORDER_NOT_ESCROWED"
    ERR_ORDER_NOT_READY = "ERR_ORDER_NOT_READY"
    ERR_NO_SHIPMENT = "ERR_NO_SHIPMENT"
    ERR_PRODUCTION_STARTED = "ERR_PRODUCTION_STARTED"
    ERR_INSUFFICIENT_WALLET = "ERR_INSUFFICIENT_WALLET"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ORDER_EMPTY: 409,
    ApiErrorId.ERR_FILE_NOT_PRINTABLE: 409,
    ApiErrorId.ERR_MATERIAL_RETIRED: 409,
    ApiErrorId.ERR_PROCESS_MISMATCH: 409,
    ApiErrorId.ERR_MACHINE_OFFLINE: 409,
    ApiErrorId.ERR_MACHINE_BUSY: 409,
    ApiErrorId.ERR_MACHINE_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_MACHINE_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_STATION_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_SPOOL_INSUFFICIENT: 409,
    ApiErrorId.ERR_ORDER_NOT_ESCROWED: 409,
    ApiErrorId.ERR_ORDER_NOT_READY: 409,
    ApiErrorId.ERR_NO_SHIPMENT: 409,
    ApiErrorId.ERR_PRODUCTION_STARTED: 409,
    ApiErrorId.ERR_INSUFFICIENT_WALLET: 402,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
