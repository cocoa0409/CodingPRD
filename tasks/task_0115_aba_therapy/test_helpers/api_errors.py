"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth / RBAC — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_THERAPIST_OF_RECORD = "ERR_NOT_THERAPIST_OF_RECORD"

    # Existence — PRD §2.7
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State — PRD §2.8 / §3
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SESSION_NOT_COMPLETED = "ERR_SESSION_NOT_COMPLETED"
    ERR_SESSION_THERAPIST_OVERLAP = "ERR_SESSION_THERAPIST_OVERLAP"
    ERR_PARENT_TRAINING_BUFFER = "ERR_PARENT_TRAINING_BUFFER"
    ERR_TREATMENT_PLAN_CONFLICT = "ERR_TREATMENT_PLAN_CONFLICT"
    ERR_CLAIM_STATE_INVALID = "ERR_CLAIM_STATE_INVALID"
    ERR_RENEWAL_CONFLICT = "ERR_RENEWAL_CONFLICT"
    ERR_SESSION_ALREADY_CLAIMED = "ERR_SESSION_ALREADY_CLAIMED"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Business safety / referential / fiscal — PRD §2.8 / §3
    ERR_SUPERVISION_RATIO_BREACH = "ERR_SUPERVISION_RATIO_BREACH"
    ERR_PLAN_RATIO_INSUFFICIENT = "ERR_PLAN_RATIO_INSUFFICIENT"
    ERR_SESSION_AUTH_MISMATCH = "ERR_SESSION_AUTH_MISMATCH"
    ERR_CPT_CODE_MISMATCH = "ERR_CPT_CODE_MISMATCH"
    ERR_NO_RBT_TO_SUPERVISE = "ERR_NO_RBT_TO_SUPERVISE"
    ERR_SESSION_OUTSIDE_AUTH_WINDOW = "ERR_SESSION_OUTSIDE_AUTH_WINDOW"
    ERR_AUTH_UNITS_EXHAUSTED = "ERR_AUTH_UNITS_EXHAUSTED"
    ERR_EMPTY_CLAIM = "ERR_EMPTY_CLAIM"
    ERR_RENEWAL_CPT_MISMATCH = "ERR_RENEWAL_CPT_MISMATCH"
    ERR_APPEAL_LIMIT_REACHED = "ERR_APPEAL_LIMIT_REACHED"

    # Pagination / validation — PRD §2.3 / §2.8
    ERR_PAGINATION_PARAMS = "ERR_PAGINATION_PARAMS"
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 Error Code Catalogue (verbatim).
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_THERAPIST_OF_RECORD: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SESSION_NOT_COMPLETED: 409,
    ApiErrorId.ERR_SESSION_THERAPIST_OVERLAP: 409,
    ApiErrorId.ERR_PARENT_TRAINING_BUFFER: 409,
    ApiErrorId.ERR_TREATMENT_PLAN_CONFLICT: 409,
    ApiErrorId.ERR_CLAIM_STATE_INVALID: 409,
    ApiErrorId.ERR_RENEWAL_CONFLICT: 409,
    ApiErrorId.ERR_SESSION_ALREADY_CLAIMED: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_SUPERVISION_RATIO_BREACH: 422,
    ApiErrorId.ERR_PLAN_RATIO_INSUFFICIENT: 422,
    ApiErrorId.ERR_SESSION_AUTH_MISMATCH: 422,
    ApiErrorId.ERR_CPT_CODE_MISMATCH: 422,
    ApiErrorId.ERR_NO_RBT_TO_SUPERVISE: 422,
    ApiErrorId.ERR_SESSION_OUTSIDE_AUTH_WINDOW: 422,
    ApiErrorId.ERR_AUTH_UNITS_EXHAUSTED: 422,
    ApiErrorId.ERR_EMPTY_CLAIM: 422,
    ApiErrorId.ERR_RENEWAL_CPT_MISMATCH: 422,
    ApiErrorId.ERR_APPEAL_LIMIT_REACHED: 422,
    ApiErrorId.ERR_PAGINATION_PARAMS: 422,
    ApiErrorId.ERR_VALIDATION: 422,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
