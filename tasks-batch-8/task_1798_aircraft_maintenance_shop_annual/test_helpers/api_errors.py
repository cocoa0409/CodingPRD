"""Error IDs and HTTP status mapping (PRD section 5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_MECHANIC_OVERBOOKED = "ERR_MECHANIC_OVERBOOKED"
    ERR_TRACEABILITY_MISSING = "ERR_TRACEABILITY_MISSING"
    ERR_AIRWORTHINESS_BLOCKED = "ERR_AIRWORTHINESS_BLOCKED"
    ERR_OWNER_DECISION_REQUIRED = "ERR_OWNER_DECISION_REQUIRED"
    ERR_INVOICE_LOCKED = "ERR_INVOICE_LOCKED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_CHECKLIST_INCOMPLETE = "ERR_CHECKLIST_INCOMPLETE"
    ERR_DUPLICATE_INVOICE = "ERR_DUPLICATE_INVOICE"
    ERR_CERTIFICATE_INSUFFICIENT = "ERR_CERTIFICATE_INSUFFICIENT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_MECHANIC_OVERBOOKED: 409,
    ApiErrorId.ERR_TRACEABILITY_MISSING: 422,
    ApiErrorId.ERR_AIRWORTHINESS_BLOCKED: 422,
    ApiErrorId.ERR_OWNER_DECISION_REQUIRED: 422,
    ApiErrorId.ERR_INVOICE_LOCKED: 409,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_CHECKLIST_INCOMPLETE: 422,
    ApiErrorId.ERR_DUPLICATE_INVOICE: 409,
    ApiErrorId.ERR_CERTIFICATE_INSUFFICIENT: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
