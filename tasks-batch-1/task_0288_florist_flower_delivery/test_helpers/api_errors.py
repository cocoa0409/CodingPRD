"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PRECONDITION_NOT_MET = "ERR_PRECONDITION_NOT_MET"
    ERR_PAST_SAME_DAY_CUTOFF = "ERR_PAST_SAME_DAY_CUTOFF"
    ERR_DELIVERY_DATE_IN_PAST = "ERR_DELIVERY_DATE_IN_PAST"
    ERR_SUBSTITUTION_NOT_ALLOWED = "ERR_SUBSTITUTION_NOT_ALLOWED"
    ERR_ZONE_WINDOW_FULL = "ERR_ZONE_WINDOW_FULL"
    ERR_NO_FLORIST_AVAILABLE = "ERR_NO_FLORIST_AVAILABLE"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_SCHEDULE_EXHAUSTED = "ERR_SCHEDULE_EXHAUSTED"
    ERR_ZONE_INACTIVE = "ERR_ZONE_INACTIVE"
    ERR_ARRANGEMENT_INACTIVE = "ERR_ARRANGEMENT_INACTIVE"
    ERR_CLAIM_WINDOW_INVALID = "ERR_CLAIM_WINDOW_INVALID"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PRECONDITION_NOT_MET: 409,
    ApiErrorId.ERR_PAST_SAME_DAY_CUTOFF: 409,
    ApiErrorId.ERR_DELIVERY_DATE_IN_PAST: 409,
    ApiErrorId.ERR_SUBSTITUTION_NOT_ALLOWED: 409,
    ApiErrorId.ERR_ZONE_WINDOW_FULL: 409,
    ApiErrorId.ERR_NO_FLORIST_AVAILABLE: 409,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_SCHEDULE_EXHAUSTED: 409,
    ApiErrorId.ERR_ZONE_INACTIVE: 409,
    ApiErrorId.ERR_ARRANGEMENT_INACTIVE: 409,
    ApiErrorId.ERR_CLAIM_WINDOW_INVALID: 409,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
