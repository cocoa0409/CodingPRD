DEFAULT_MESSAGES = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing or invalid",
    "ERR_UNAUTHORIZED": "Role may not perform this operation",
    "ERR_PRODUCT_OWNERSHIP_MISMATCH": "ProductOwner does not own the target product",
    "ERR_SEGREGATION_OF_DUTIES": "The acting user may not both author and sign off",
    "ERR_INVALID_REQUEST": "Request body is invalid",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super(ApiError, self).__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGES.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").capitalize())


def bad_request(detail):
    return ApiError("ERR_INVALID_REQUEST", "Request body is invalid: %s" % detail)
