"""Error IDs and HTTP status mapping (PRD Section 5).

After defining the mapping, register it with the framework so that
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_CODE = "ERR_DUPLICATE_CODE"
    ERR_DUPLICATE_SKU = "ERR_DUPLICATE_SKU"
    ERR_INVALID_QUANTITY = "ERR_INVALID_QUANTITY"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_RECIPE_NOT_APPROVED = "ERR_RECIPE_NOT_APPROVED"
    ERR_ALLERGEN_CHANGEOVER_REQUIRED = "ERR_ALLERGEN_CHANGEOVER_REQUIRED"
    ERR_LOT_EXPIRED = "ERR_LOT_EXPIRED"
    ERR_INSUFFICIENT_MATERIAL = "ERR_INSUFFICIENT_MATERIAL"
    ERR_OVERRUN_EXCEEDED = "ERR_OVERRUN_EXCEEDED"
    ERR_LINE_OVERLAP = "ERR_LINE_OVERLAP"
    ERR_CREW_OVERLAP = "ERR_CREW_OVERLAP"
    ERR_QA_REJECT_RATE_EXCEEDED = "ERR_QA_REJECT_RATE_EXCEEDED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_CODE: 409,
    ApiErrorId.ERR_DUPLICATE_SKU: 409,
    ApiErrorId.ERR_INVALID_QUANTITY: 422,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_RECIPE_NOT_APPROVED: 409,
    ApiErrorId.ERR_ALLERGEN_CHANGEOVER_REQUIRED: 409,
    ApiErrorId.ERR_LOT_EXPIRED: 409,
    ApiErrorId.ERR_INSUFFICIENT_MATERIAL: 409,
    ApiErrorId.ERR_OVERRUN_EXCEEDED: 422,
    ApiErrorId.ERR_LINE_OVERLAP: 409,
    ApiErrorId.ERR_CREW_OVERLAP: 409,
    ApiErrorId.ERR_QA_REJECT_RATE_EXCEEDED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
