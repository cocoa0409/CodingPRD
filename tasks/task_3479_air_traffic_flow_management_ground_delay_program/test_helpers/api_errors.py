"""Error identifiers and their HTTP status mapping (PRD §5).

The mapping is registered with the shared validator machinery at import time,
so ``validate_error(response, ApiErrorId.X)`` cross-checks the status code
against this catalogue automatically.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth tier (PRD §2.6 items 1-3)
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"

    # Existence tier (PRD §2.6 item 4)
    ERR_FACILITY_NOT_FOUND = "ERR_FACILITY_NOT_FOUND"
    ERR_OPERATOR_NOT_FOUND = "ERR_OPERATOR_NOT_FOUND"
    ERR_FLIGHT_NOT_FOUND = "ERR_FLIGHT_NOT_FOUND"
    ERR_TMI_NOT_FOUND = "ERR_TMI_NOT_FOUND"
    ERR_CONSTRAINT_EVENT_NOT_FOUND = "ERR_CONSTRAINT_EVENT_NOT_FOUND"
    ERR_FORECAST_NOT_FOUND = "ERR_FORECAST_NOT_FOUND"
    ERR_GA_REQUEST_NOT_FOUND = "ERR_GA_REQUEST_NOT_FOUND"
    ERR_REROUTE_ASSIGNMENT_NOT_FOUND = "ERR_REROUTE_ASSIGNMENT_NOT_FOUND"

    # Malformed body
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # State tier (PRD §2.6 item 5)
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TMI_TERMINAL = "ERR_TMI_TERMINAL"
    ERR_TMI_NOT_ACTIVE = "ERR_TMI_NOT_ACTIVE"
    ERR_FACILITY_NOT_OPERATIONAL = "ERR_FACILITY_NOT_OPERATIONAL"
    ERR_FLIGHT_NOT_CANCELLABLE = "ERR_FLIGHT_NOT_CANCELLABLE"

    # Business rules (PRD §2.6 items 6-20)
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_SECTOR_CAPACITY_EXCEEDED = "ERR_SECTOR_CAPACITY_EXCEEDED"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_PROGRAM_WINDOW_IN_PAST = "ERR_PROGRAM_WINDOW_IN_PAST"
    ERR_GA_WINDOW_OUTSIDE_PROGRAM = "ERR_GA_WINDOW_OUTSIDE_PROGRAM"
    ERR_STALE_FLIGHT_DATA = "ERR_STALE_FLIGHT_DATA"
    ERR_FACILITY_IDENT_CONFLICT = "ERR_FACILITY_IDENT_CONFLICT"
    ERR_CONSTRAINT_EVENT_OVERLAP = "ERR_CONSTRAINT_EVENT_OVERLAP"
    ERR_TMI_OVERLAP = "ERR_TMI_OVERLAP"
    ERR_INVALID_RATE = "ERR_INVALID_RATE"
    ERR_FACILITY_TYPE_NOT_AIRPORT = "ERR_FACILITY_TYPE_NOT_AIRPORT"
    ERR_REROUTE_SECTOR_TYPE = "ERR_REROUTE_SECTOR_TYPE"
    ERR_TMI_TYPE_NOT_GDP = "ERR_TMI_TYPE_NOT_GDP"
    ERR_OPERATOR_TYPE_INELIGIBLE = "ERR_OPERATOR_TYPE_INELIGIBLE"
    ERR_SUBSTITUTION_SAME_FLIGHT = "ERR_SUBSTITUTION_SAME_FLIGHT"
    ERR_FLIGHT_NOT_IN_PROGRAM = "ERR_FLIGHT_NOT_IN_PROGRAM"
    ERR_SUBSTITUTION_SHIFT_EXCEEDED = "ERR_SUBSTITUTION_SHIFT_EXCEEDED"
    ERR_EXTENSION_LIMIT_EXCEEDED = "ERR_EXTENSION_LIMIT_EXCEEDED"
    ERR_NO_CURRENT_FORECAST = "ERR_NO_CURRENT_FORECAST"
    ERR_RATE_EXCEEDS_CAPACITY = "ERR_RATE_EXCEEDS_CAPACITY"

    # Optimistic concurrency (PRD §2.7)
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


