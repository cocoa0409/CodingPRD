"""Error IDs and HTTP status mapping from scaffold Table 6."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Request
    ERR_BAD_REQUEST = "ERR_BAD_REQUEST"

    # Not Found
    ERR_ROOM_NOT_FOUND = "ERR_ROOM_NOT_FOUND"
    ERR_BOOKING_NOT_FOUND = "ERR_BOOKING_NOT_FOUND"
    ERR_WAITLIST_NOT_FOUND = "ERR_WAITLIST_NOT_FOUND"
    ERR_SERIES_NOT_FOUND = "ERR_SERIES_NOT_FOUND"

    # Concurrency
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # State
    ERR_ROOM_NOT_ACTIVE = "ERR_ROOM_NOT_ACTIVE"
    ERR_INVALID_BOOKING_STATE = "ERR_INVALID_BOOKING_STATE"
    ERR_INVALID_WAITLIST_STATE = "ERR_INVALID_WAITLIST_STATE"
    ERR_INVALID_SERIES_STATE = "ERR_INVALID_SERIES_STATE"

    # Temporal
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_BOOKING_TOO_SHORT = "ERR_BOOKING_TOO_SHORT"
    ERR_BOOKING_TOO_LONG = "ERR_BOOKING_TOO_LONG"
    ERR_BOOKING_IN_PAST = "ERR_BOOKING_IN_PAST"
    ERR_CHECKIN_WINDOW = "ERR_CHECKIN_WINDOW"

    # Conflict
    ERR_TIME_CONFLICT = "ERR_TIME_CONFLICT"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_ROOM_HAS_ACTIVE_BOOKINGS = "ERR_ROOM_HAS_ACTIVE_BOOKINGS"
    ERR_DUPLICATE_WAITLIST = "ERR_DUPLICATE_WAITLIST"

    # Series
    ERR_INVALID_SERIES_RANGE = "ERR_INVALID_SERIES_RANGE"
    ERR_EMPTY_SERIES = "ERR_EMPTY_SERIES"

    # Room name uniqueness
    ERR_ROOM_NAME_TAKEN = "ERR_ROOM_NAME_TAKEN"


