def bad_request(msg="invalid request"):
    raise ApiError(ERR_INVALID, 400, msg)


def bad_enum(msg="invalid enum value"):
    raise ApiError(ERR_ENUM, 400, msg)


def not_found(msg="resource not found"):
    raise ApiError(ERR_NOT_FOUND, 404, msg)
