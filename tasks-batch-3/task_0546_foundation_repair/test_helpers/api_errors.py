    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_CREW_REGION_MISMATCH = "ERR_CREW_REGION_MISMATCH"
    ERR_PERMIT_NOT_APPROVED = "ERR_PERMIT_NOT_APPROVED"
    ERR_SCHEDULE_WINDOW_INVALID = "ERR_SCHEDULE_WINDOW_INVALID"
    ERR_PIER_COUNT_MISMATCH = "ERR_PIER_COUNT_MISMATCH"
    ERR_NO_PIERS = "ERR_NO_PIERS"
    ERR_FINANCING_LIMIT_EXCEEDED = "ERR_FINANCING_LIMIT_EXCEEDED"
    ERR_WARRANTY_NOT_ACTIVE = "ERR_WARRANTY_NOT_ACTIVE"
    ERR_VISIT_TOO_SOON = "ERR_VISIT_TOO_SOON"
