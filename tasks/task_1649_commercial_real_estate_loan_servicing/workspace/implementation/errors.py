def unauthenticated(msg="Missing or invalid authentication headers"):
    return ApiError(ERR_UNAUTHENTICATED, msg, 401)


def unauthorized(msg="Role not authorized for this endpoint"):
    return ApiError(ERR_UNAUTHORIZED, msg, 403)


def ownership(msg="Ownership mismatch"):
    return ApiError(ERR_OWNERSHIP_MISMATCH, msg, 403)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, msg, 404)


def invalid_request(msg="Invalid request"):
    return ApiError(ERR_INVALID_REQUEST, msg, 400)


def stale_version(msg="Stale parent version"):
    return ApiError(ERR_STALE_VERSION, msg, 412)


def invalid_state(msg="Invalid state for requested transition"):
    return ApiError(ERR_INVALID_STATE, msg, 409)
