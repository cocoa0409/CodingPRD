class ApiError(Exception):
    """Transport-level failure carrying an error_id and its HTTP status."""

    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = http_status or ERROR_HTTP.get(error_id, 400)


def invalid_request(message="The request body does not match the endpoint schema."):
    return ApiError(ERR_INVALID_REQUEST, message)


def not_found(error_id, message=None):
    return ApiError(error_id, message or "The requested resource does not exist.")
