"""Error IDs and HTTP status mapping from PRD §5 (Error Code Catalogue)."""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth & RBAC (PRD §2.1)
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    # Resolution (PRD §2.5)
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    # State preconditions (PRD §2.6)
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Business referential
    ERR_VOTER_NOT_ELIGIBLE = "ERR_VOTER_NOT_ELIGIBLE"
    ERR_DUPLICATE_VOTE = "ERR_DUPLICATE_VOTE"
    # Business temporal
    ERR_VOTING_CLOSED = "ERR_VOTING_CLOSED"
    ERR_VOTING_WINDOW_INVALID = "ERR_VOTING_WINDOW_INVALID"
    ERR_SLOT_MISALIGNED = "ERR_SLOT_MISALIGNED"
    ERR_SLOT_IN_PAST = "ERR_SLOT_IN_PAST"
    ERR_FACILITY_SLOT_FULL = "ERR_FACILITY_SLOT_FULL"
    # Business safety
    ERR_OWNER_DELINQUENT = "ERR_OWNER_DELINQUENT"
    # Business constraint
    ERR_PARKING_QUOTA_EXCEEDED = "ERR_PARKING_QUOTA_EXCEEDED"
    ERR_PARKING_KIND_MISMATCH = "ERR_PARKING_KIND_MISMATCH"
    ERR_PARKING_SPACE_TAKEN = "ERR_PARKING_SPACE_TAKEN"
    ERR_DUPLICATE_PAYMENT = "ERR_DUPLICATE_PAYMENT"
    ERR_DUPLICATE_RULE_CODE = "ERR_DUPLICATE_RULE_CODE"
    ERR_DUPLICATE_PROPERTY = "ERR_DUPLICATE_PROPERTY"
    # Business fiscal
    ERR_PAYMENT_AMOUNT_INVALID = "ERR_PAYMENT_AMOUNT_INVALID"
    ERR_RATING_OUT_OF_RANGE = "ERR_RATING_OUT_OF_RANGE"
    # Concurrency / OCC
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VOTER_NOT_ELIGIBLE: 403,
    ApiErrorId.ERR_DUPLICATE_VOTE: 409,
    ApiErrorId.ERR_VOTING_CLOSED: 409,
    ApiErrorId.ERR_VOTING_WINDOW_INVALID: 422,
    ApiErrorId.ERR_SLOT_MISALIGNED: 422,
    ApiErrorId.ERR_SLOT_IN_PAST: 422,
    ApiErrorId.ERR_FACILITY_SLOT_FULL: 409,
    ApiErrorId.ERR_OWNER_DELINQUENT: 403,
    ApiErrorId.ERR_PARKING_QUOTA_EXCEEDED: 422,
    ApiErrorId.ERR_PARKING_KIND_MISMATCH: 422,
    ApiErrorId.ERR_PARKING_SPACE_TAKEN: 409,
    ApiErrorId.ERR_DUPLICATE_PAYMENT: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_RATING_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_DUPLICATE_RULE_CODE: 409,
    ApiErrorId.ERR_DUPLICATE_PROPERTY: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
}

# Register both enum-keyed and string-keyed forms so callers can use either.
_STRING_KEYED_MAP = {k.value: v for k, v in HTTP_STATUS_CODES.items()}
set_error_http_status_map(_STRING_KEYED_MAP)
