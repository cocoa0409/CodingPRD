"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CLIENT_NOT_ACTIVE = "ERR_CLIENT_NOT_ACTIVE"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_STUDY_TYPE_MISMATCH = "ERR_STUDY_TYPE_MISMATCH"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_PROPERTY_STUDY_OVERLAP = "ERR_PROPERTY_STUDY_OVERLAP"
    ERR_RD_BASE_PERIOD_OVERLAP = "ERR_RD_BASE_PERIOD_OVERLAP"
    ERR_AMEND_WINDOW_EXPIRED = "ERR_AMEND_WINDOW_EXPIRED"
    ERR_FEE_PERCENT_TOO_HIGH = "ERR_FEE_PERCENT_TOO_HIGH"
    ERR_ALLOCATION_EXCEEDS_BASIS = "ERR_ALLOCATION_EXCEEDS_BASIS"
    ERR_NO_ALLOCATED_COMPONENTS = "ERR_NO_ALLOCATED_COMPONENTS"
    ERR_NO_QUALIFIED_QRE = "ERR_NO_QUALIFIED_QRE"
    ERR_MISSING_FEE_TERMS = "ERR_MISSING_FEE_TERMS"
    ERR_STALE_STUDY_VERSION = "ERR_STALE_STUDY_VERSION"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CLIENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SOD_VIOLATION: 403,
    ApiErrorId.ERR_STUDY_TYPE_MISMATCH: 409,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_PROPERTY_STUDY_OVERLAP: 409,
    ApiErrorId.ERR_RD_BASE_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_AMEND_WINDOW_EXPIRED: 409,
    ApiErrorId.ERR_FEE_PERCENT_TOO_HIGH: 422,
    ApiErrorId.ERR_ALLOCATION_EXCEEDS_BASIS: 409,
    ApiErrorId.ERR_NO_ALLOCATED_COMPONENTS: 409,
    ApiErrorId.ERR_NO_QUALIFIED_QRE: 409,
    ApiErrorId.ERR_MISSING_FEE_TERMS: 422,
    ApiErrorId.ERR_STALE_STUDY_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
