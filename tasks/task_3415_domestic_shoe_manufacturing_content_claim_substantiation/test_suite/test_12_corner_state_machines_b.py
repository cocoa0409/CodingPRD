def test_certification_suspend_reinstate_roundtrip_without_runs():
    """PRD §3.2: "The certification-level suspend and reinstate capabilities
    work one entry at a time: addressed by the worker and an `operation` path
    segment naming `STITCHING`, `LASTING`, or `ASSEMBLY`, they flip that
    entry's `cert_status` from `CERTIFIED` to `SUSPENDED` or back again, and a
    certification suspension triggers exactly the same in-production workforce
    re-check cascade as a full worker suspension."

    Design: Corner/state_machines/certification_suspend_reinstate_roundtrip_without_runs
    """
    set_clock()
    factory = make_factory()
    worker = make_worker(factory["id"], "Ada Lovelace")
    enrollment = enroll(worker["id"], "STITCHING", target_level=1)
    assess(enrollment["id"], 88)

    validate_success(api.suspend_certification(worker["id"], "STITCHING", TRAINING))
    mid = _get_worker(worker["id"])
    assert mid["certifications"] == [
        {"operation": "STITCHING", "level": 1, "cert_status": "SUSPENDED"}]

    validate_success(api.reinstate_certification(worker["id"], "STITCHING", TRAINING))
    end = _get_worker(worker["id"])
    assert end["certifications"] == [
        {"operation": "STITCHING", "level": 1, "cert_status": "CERTIFIED"}]
    # No runs exist, so the workforce re-check cascade is a no-op.
    runs, meta = validate_paginated(api.list_runs(PLANNER))
    assert runs == [] and meta["total_count"] == 0


def test_report_supersede_replaces_active_same_variant():
    """PRD §3.6: "Reports are immutable snapshots with a one-live rule: at most
    one report per run and variant may be `ACTIVE` at a time. Creating a new
    report of a variant that already has an `ACTIVE` report on the same run —
    whether created directly or generated by the evidence-rejection recompute
    of §3.8 — supersedes the previous one, moving it from `ACTIVE` to
    `SUPERSEDED` and incrementing the superseded report's `version` by 1."

    Design: Corner/state_machines/report_supersede_replaces_active_same_variant
    """
    kit = standard_kit()  # run PLANNED; PROVISIONAL needs no completion
    run_id = kit["run"]["id"]
    rep1 = create_report(run_id, "PROVISIONAL")
    rep2 = create_report(run_id, "PROVISIONAL")

    reports = validate_success(api.list_content_reports(
        run_id, PLANNER, params={"variant": "PROVISIONAL"}))
    by_id = {r["id"]: r for r in reports}
    assert by_id[rep1["id"]]["status"] == "SUPERSEDED"
    assert by_id[rep2["id"]]["status"] == "ACTIVE"
    active = [r for r in reports if r["status"] == "ACTIVE"]
    assert len(active) == 1 and active[0]["id"] == rep2["id"]
    # Supersede is about authority, not recomputation drift.
    assert by_id[rep1["id"]]["material_cost_cents"] == 100
    assert by_id[rep2["id"]]["material_cost_cents"] == 100


def test_allocation_shift_from_open_returns_not_locked():
    """PRD §3.4: "The allocation must be `LOCKED` (otherwise
    `ERR_INVALID_STATE`, and a reserve or shift against a non-locked allocation
    is rejected with `ERR_ALLOCATION_NOT_LOCKED`, HTTP 409)."

    Design: Corner/state_machines/allocation_shift_from_open_returns_not_locked
    """
    kit = standard_kit(with_run=False)  # allocation stays OPEN
    allocation = get_allocation(kit["allocation"]["id"])
    assert allocation["status"] == "OPEN"
    resp = api.shift_allocation(
        allocation["id"],
        shift_allocation_payload("TO_DOMESTIC", 10, allocation["version"]), ADMIN)
    validate_error(resp, ApiErrorId.ERR_ALLOCATION_NOT_LOCKED)
    after = get_allocation(allocation["id"])
    assert after["status"] == "OPEN"
    assert after["domestic_reserved_units"] == 0
    assert after["import_reserved_units"] == 100


def _locked_30_70_kit(reserve=False):
    """Allocation total 100 locked with a STOCK run of 30 in the week ->
    domestic 30 / import 70; optionally the run is MATERIAL_RESERVED (30 units
    consumed against the domestic pool)."""
    kit = standard_kit(run_units=30)
    kit["allocation"] = lock_allocation(kit["allocation"]["id"])
    if reserve:
        kit["run"] = reserve_run(kit["run"]["id"])
    return kit


def test_allocation_shift_exceeding_source_is_rejected():
    """PRD §3.4: "The `units` must be at least 1 and no more than the source
    bucket — for `TO_DOMESTIC` the source is `import_reserved_units`, for
    `TO_IMPORT` it is `domestic_reserved_units` — with equality allowed;
    overshooting the source is rejected with `ERR_SHIFT_EXCEEDS_SOURCE` (HTTP
    422)."

    Design: Corner/state_machines/allocation_shift_exceeding_source_is_rejected
    """
    kit = _locked_30_70_kit()
    allocation = kit["allocation"]
    assert allocation["domestic_reserved_units"] == 30
    assert allocation["import_reserved_units"] == 70

    full = validate_success(api.shift_allocation(
        allocation["id"],
        shift_allocation_payload("TO_DOMESTIC", 70, allocation["version"]), ADMIN))
    assert full["domestic_reserved_units"] == 100
    assert full["import_reserved_units"] == 0

    over = api.shift_allocation(
        allocation["id"],
        shift_allocation_payload("TO_DOMESTIC", 1, full["version"]), ADMIN)
    validate_error(over, ApiErrorId.ERR_SHIFT_EXCEEDS_SOURCE)
    after = get_allocation(allocation["id"])
    assert after["domestic_reserved_units"] == 100
    assert after["import_reserved_units"] == 0


def test_allocation_shift_below_consumed_is_rejected():
    """PRD §3.4: "A `TO_IMPORT` shift carries one additional floor: the
    resulting `domestic_reserved_units` must remain at least the domestic units
    already consumed, where consumption is the sum of `planned_units` over the
    runs of that factory and week in `MATERIAL_RESERVED`, `IN_PRODUCTION`,
    `QUALITY_HOLD`, or `COMPLETED`; breaching the floor is rejected with
    `ERR_SHIFT_BELOW_CONSUMED` (HTTP 422)."

    Design: Corner/state_machines/allocation_shift_below_consumed_is_rejected
    """
    kit = _locked_30_70_kit(reserve=True)
    allocation = kit["allocation"]
    resp = api.shift_allocation(
        allocation["id"],
        shift_allocation_payload("TO_IMPORT", 20, allocation["version"]), ADMIN)
    validate_error(resp, ApiErrorId.ERR_SHIFT_BELOW_CONSUMED)  # 30-20=10 < 30
    after = get_allocation(allocation["id"])
    assert after["domestic_reserved_units"] == 30
    assert after["import_reserved_units"] == 70


def test_allocation_reconcile_with_open_runs_returns_week_runs_open():
    """PRD §3.4: "Reconciliation requires the allocation to be `LOCKED` and
    requires that no run of that factory and week remain in `PLANNED`,
    `MATERIAL_RESERVED`, `IN_PRODUCTION`, or `QUALITY_HOLD` — if any are still
    open the request is rejected with `ERR_WEEK_RUNS_OPEN` (HTTP 409).
    Reconciliation moves the allocation to `RECONCILED`, which is terminal, and
    increments its `version`."

    Design: Corner/state_machines/allocation_reconcile_with_open_runs_returns_week_runs_open
    """
    kit = standard_kit()
    lock_allocation(kit["allocation"]["id"])
    blocked = api.reconcile_allocation(kit["allocation"]["id"], ADMIN)
    validate_error(blocked, ApiErrorId.ERR_WEEK_RUNS_OPEN)

    validate_success(api.cancel_run(kit["run"]["id"], PLANNER))
    reconciled = validate_success(api.reconcile_allocation(kit["allocation"]["id"], ADMIN))
    assert reconciled["status"] == "RECONCILED"


