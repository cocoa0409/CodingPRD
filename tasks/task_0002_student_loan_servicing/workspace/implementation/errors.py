"""Error catalog from SCAFFOLD §1.6 / PRD §5."""

# Error IDs
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_BORROWER_DISCHARGED = "ERR_BORROWER_DISCHARGED"
ERR_DEFAULT_THRESHOLD_NOT_MET = "ERR_DEFAULT_THRESHOLD_NOT_MET"
ERR_EMAIL_DUPLICATE = "ERR_EMAIL_DUPLICATE"
ERR_NOT_VETERAN = "ERR_NOT_VETERAN"
ERR_VA_DOC_REQUIRED_OR_FORBIDDEN = "ERR_VA_DOC_REQUIRED_OR_FORBIDDEN"
ERR_PLAN_FIELDS_INVALID = "ERR_PLAN_FIELDS_INVALID"
ERR_PAYMENT_DATE_OUT_OF_WINDOW = "ERR_PAYMENT_DATE_OUT_OF_WINDOW"
ERR_PAYMENT_EXCEEDS_BALANCE = "ERR_PAYMENT_EXCEEDS_BALANCE"
ERR_CERTIFICATION_FIELDS_INVALID = "ERR_CERTIFICATION_FIELDS_INVALID"
ERR_INVALID_CLOCK = "ERR_INVALID_CLOCK"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

# HTTP status mapping
HTTP_STATUS = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNAUTHORIZED: 403,
    ERR_FORBIDDEN_ROLE: 403,
    ERR_NOT_RESOURCE_OWNER: 403,
    ERR_SOD_VIOLATION: 403,
    ERR_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_BORROWER_DISCHARGED: 409,
    ERR_DEFAULT_THRESHOLD_NOT_MET: 409,
    ERR_EMAIL_DUPLICATE: 409,
    ERR_NOT_VETERAN: 422,
    ERR_VA_DOC_REQUIRED_OR_FORBIDDEN: 422,
    ERR_PLAN_FIELDS_INVALID: 422,
    ERR_PAYMENT_DATE_OUT_OF_WINDOW: 422,
    ERR_PAYMENT_EXCEEDS_BALANCE: 422,
    ERR_CERTIFICATION_FIELDS_INVALID: 422,
    ERR_INVALID_CLOCK: 422,
    ERR_STALE_VERSION: 412,
    ERR_INVALID_REQUEST: 400,
}


class APIError(Exception):
    """Single exception class carrying an error_id from the catalog."""

    def __init__(self, error_id: str, message: str = ""):
        if error_id not in HTTP_STATUS:
            raise ValueError(f"Unknown error_id: {error_id}")
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = HTTP_STATUS[error_id]
        super().__init__(self.message)
