"""Error IDs and HTTP status mapping (PRD 5. Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_MASH_NOT_AVAILABLE = "ERR_MASH_NOT_AVAILABLE"
    ERR_LABEL_NOT_APPROVED = "ERR_LABEL_NOT_APPROVED"
    ERR_BARREL_NOT_AGING = "ERR_BARREL_NOT_AGING"
    ERR_INSUFFICIENT_PROOF_GALLONS = "ERR_INSUFFICIENT_PROOF_GALLONS"
    ERR_LINE_CONFLICT = "ERR_LINE_CONFLICT"
    ERR_NOT_TAX_DETERMINED = "ERR_NOT_TAX_DETERMINED"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_INSUFFICIENT_BONDED_PG = "ERR_INSUFFICIENT_BONDED_PG"
    ERR_AGE_NOT_VERIFIED = "ERR_AGE_NOT_VERIFIED"
    ERR_CLUB_NOT_ELIGIBLE = "ERR_CLUB_NOT_ELIGIBLE"
    ERR_TOUR_OVERLAP = "ERR_TOUR_OVERLAP"
    ERR_TOUR_CAPACITY = "ERR_TOUR_CAPACITY"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_MASH_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_LABEL_NOT_APPROVED: 409,
    ApiErrorId.ERR_BARREL_NOT_AGING: 409,
    ApiErrorId.ERR_INSUFFICIENT_PROOF_GALLONS: 409,
    ApiErrorId.ERR_LINE_CONFLICT: 409,
    ApiErrorId.ERR_NOT_TAX_DETERMINED: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_INSUFFICIENT_BONDED_PG: 409,
    ApiErrorId.ERR_AGE_NOT_VERIFIED: 403,
    ApiErrorId.ERR_CLUB_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_TOUR_OVERLAP: 409,
    ApiErrorId.ERR_TOUR_CAPACITY: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
