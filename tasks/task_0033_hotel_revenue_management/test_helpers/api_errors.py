"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # --- Auth / RBAC / existence ---
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # --- State / lifecycle ---
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_MODIFICATION_NOT_ALLOWED = "ERR_MODIFICATION_NOT_ALLOWED"
    ERR_MODIFICATION_TOO_LATE = "ERR_MODIFICATION_TOO_LATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # --- Room / reservation safety ---
    ERR_ROOM_UNAVAILABLE = "ERR_ROOM_UNAVAILABLE"
    ERR_ROOM_TYPE_MISMATCH = "ERR_ROOM_TYPE_MISMATCH"
    ERR_RATE_PLAN_NOT_DISTRIBUTED = "ERR_RATE_PLAN_NOT_DISTRIBUTED"

    # --- Maintenance / channels ---
    ERR_MAINTENANCE_OVERLAP = "ERR_MAINTENANCE_OVERLAP"
    ERR_ROOM_CURRENTLY_OCCUPIED = "ERR_ROOM_CURRENTLY_OCCUPIED"
    ERR_DUPLICATE_PRIORITY_RANK = "ERR_DUPLICATE_PRIORITY_RANK"
    ERR_INVENTORY_SHARE_EXCEEDED = "ERR_INVENTORY_SHARE_EXCEEDED"

    # --- Inventory / overbooking ---
    ERR_INVENTORY_EXHAUSTED = "ERR_INVENTORY_EXHAUSTED"
    ERR_OVERBOOKING_LIMIT_EXCEEDED = "ERR_OVERBOOKING_LIMIT_EXCEEDED"

    # --- Override workflow ---
    ERR_OVERRIDE_ALREADY_PENDING = "ERR_OVERRIDE_ALREADY_PENDING"

    # --- Concurrency / generic input ---
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_MODIFICATION_NOT_ALLOWED: 409,
    ApiErrorId.ERR_MODIFICATION_TOO_LATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_ROOM_UNAVAILABLE: 409,
    ApiErrorId.ERR_ROOM_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_RATE_PLAN_NOT_DISTRIBUTED: 422,
    ApiErrorId.ERR_MAINTENANCE_OVERLAP: 409,
    ApiErrorId.ERR_ROOM_CURRENTLY_OCCUPIED: 409,
    ApiErrorId.ERR_DUPLICATE_PRIORITY_RANK: 409,
    ApiErrorId.ERR_INVENTORY_SHARE_EXCEEDED: 422,
    ApiErrorId.ERR_INVENTORY_EXHAUSTED: 409,
    ApiErrorId.ERR_OVERBOOKING_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_OVERRIDE_ALREADY_PENDING: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
    ApiErrorId.ERR_INVALID_INPUT: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
