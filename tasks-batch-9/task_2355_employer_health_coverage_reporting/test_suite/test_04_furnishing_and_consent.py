def test_paper_furnishing_leaves_the_filing_dimension_at_not_filed(api):
    """PRD §3.6: "It creates a **Form1095C** with `form_type` of `ORIGINAL`, a
    `furnishing_status` of `NOT_FURNISHED` and a `filing_status` of `NOT_FILED` — the two
    status dimensions move independently of one another for the rest of the statement's life
    — and twelve **MonthlyCoverageLine** rows created together, one per month, each stamped
    with the parent statement's identity through `form_1095c_id` and its own `month`."
    PRD §3.7: "It is accepted only from `NOT_FURNISHED` or `REDELIVERY_REQUIRED`, so
    `furnishing_status` walks `NOT_FURNISHED` → `FURNISHED_PAPER` or `NOT_FURNISHED` →
    `FURNISHED_ELECTRONIC` on first delivery and `REDELIVERY_REQUIRED` → `FURNISHED_PAPER` or
    `REDELIVERY_REQUIRED` → `FURNISHED_ELECTRONIC` on redelivery."
    PRD §3.7: "A successful delivery stamps `furnished_at` and `furnished_by_user_id`."

    Design: Difficulty/non_linear_state_machine/form_furnishing_and_filing_dimensions_advance_independently
    """
    ctx = _statement_ready_to_furnish(
        api, "999999991", "Tomas Reed", "6006", "2027-02-01T00:00:00Z"
    )

    fixtures.furnish_form(api, ctx["form"]["id"], "PAPER")

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(
        form,
        furnishing_status="FURNISHED_PAPER",
        filing_status="NOT_FILED",
        generated_by_user_id="preparer-1",
        furnished_by_user_id="preparer-2",
        late_furnishing_penalty_cents=0,
    )
    assert form["filing_status"] == "NOT_FILED", (
        "delivering on paper must not move the filing dimension, got "
        f"{form['filing_status']!r}"
    )


def test_attaching_a_furnished_statement_advances_only_the_filing_dimension(api):
    """PRD §3.8: "Each attached form moves `NOT_FILED` → `ATTACHED` and records the
    transmittal in its `transmittal_id`, the transmittal's `form_count` increments, and the
    member's `unattached_form_count` moves into `attached_form_count`; the member's `version`
    advances."
    PRD §3.8: "The conserved quantity across attach and detach is the member's
    `generated_form_count`, which neither operation changes."

    Design: Difficulty/non_linear_state_machine/form_furnishing_and_filing_dimensions_advance_independently
    """
    ctx = _statement_ready_to_furnish(
        api, "999999991", "Tomas Reed", "6006", "2027-02-01T00:00:00Z"
    )
    fixtures.furnish_form(api, ctx["form"]["id"], "PAPER")

    transmittal = fixtures.open_transmittal(api, ctx["member"]["id"])
    fixtures.attach_forms(api, transmittal["id"], [ctx["form"]["id"]])

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(
        form,
        filing_status="ATTACHED",
        furnishing_status="FURNISHED_PAPER",
        transmittal_id=transmittal["id"],
    )

    assert_transmittal(fixtures.read_transmittal(api, transmittal["id"]), form_count=1)

    member = fixtures.read_member(api, ctx["member"]["id"])
    assert member["attached_form_count"] == 1, (
        f"the attached statement should be counted, got {member['attached_form_count']}"
    )
    assert member["unattached_form_count"] == 0, (
        f"the unattached count moves into the attached count, got "
        f"{member['unattached_form_count']}"
    )
    assert member["generated_form_count"] == 1, (
        "generated_form_count is conserved across attach, got "
        f"{member['generated_form_count']}"
    )


def test_transmission_moves_the_statement_to_pending_filing_only(api):
    """PRD §3.8: "Success moves `DRAFT`-descended state `BUILT` → `TRANSMITTED`, stamps
    `channel`, `transmitted_by_user_id` and `transmitted_at`, and moves every attached
    statement `ATTACHED` → `PENDING_FILING`."
    PRD §3.8: "The sum is `aggregate_return_count`, and `required_channel` becomes
    `ELECTRONIC` when it is at or above the season's `electronic_filing_threshold`, otherwise
    `ANY`."
    PRD §3.8: "A `PAPER` channel against a `required_channel` of `ELECTRONIC` is refused with
    `ERR_ELECTRONIC_FILING_REQUIRED`; a `required_channel` of `ANY` accepts either."

    Design: Difficulty/non_linear_state_machine/form_furnishing_and_filing_dimensions_advance_independently
    """
    ctx = _statement_ready_to_furnish(
        api, "999999991", "Tomas Reed", "6006", "2027-02-01T00:00:00Z"
    )
    fixtures.furnish_form(api, ctx["form"]["id"], "PAPER")

    built = fixtures.built_transmittal_with_forms(
        api, ctx["member"]["id"], [ctx["form"]["id"]]
    )
    assert_transmittal(built, status="BUILT", required_channel="ANY")

    fixtures.transmit_transmittal(api, built["id"], "PAPER")

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(
        form, filing_status="PENDING_FILING", furnishing_status="FURNISHED_PAPER"
    )
    assert form["furnishing_status"] == "FURNISHED_PAPER", (
        "transmission must not disturb the furnishing dimension, got "
        f"{form['furnishing_status']!r}"
    )

    transmittal = fixtures.read_transmittal(api, built["id"])
    assert_transmittal(transmittal, status="TRANSMITTED", channel="PAPER")


def test_clean_acceptance_files_the_statement_without_touching_furnishing(api):
    """PRD §3.8: "A clean acceptance requires the `errors` array to be empty; it records the
    receipt identifier, moves every attached statement `PENDING_FILING` → `FILED_ACCEPTED`,
    and clears the member's `open_transmittal_id`."
    PRD §3.6: "It creates a **Form1095C** with `form_type` of `ORIGINAL`, a
    `furnishing_status` of `NOT_FURNISHED` and a `filing_status` of `NOT_FILED` — the two
    status dimensions move independently of one another for the rest of the statement's life
    — and twelve **MonthlyCoverageLine** rows created together, one per month, each stamped
    with the parent statement's identity through `form_1095c_id` and its own `month`."
    PRD §3.8: "Closing the season is the last act, and only a `ComplianceOfficer` may attempt
    it. The season must still be `OPEN`, its `open_correction_count` must be zero — meaning
    no group of the season sits in `CORRECTION_OPEN` — and every transmittal of every
    `ACTIVE` member of every group of the season must have settled into `ACCEPTED` or
    `SUPERSEDED`."

    Design: Difficulty/non_linear_state_machine/form_furnishing_and_filing_dimensions_advance_independently
    """
    ctx = _statement_ready_to_furnish(
        api, "999999991", "Tomas Reed", "6006", "2027-02-01T00:00:00Z"
    )
    fixtures.furnish_form(api, ctx["form"]["id"], "PAPER")

    built = fixtures.built_transmittal_with_forms(
        api, ctx["member"]["id"], [ctx["form"]["id"]]
    )
    fixtures.transmit_transmittal(api, built["id"], "PAPER")
    fixtures.record_agency_response(api, built["id"], "ACCEPTED", "AIR-2026-0003")

    form = fixtures.read_form(api, ctx["form"]["id"])
    assert_form_1095c(
        form, filing_status="FILED_ACCEPTED", furnishing_status="FURNISHED_PAPER"
    )
    assert (form["furnishing_status"], form["filing_status"]) == (
        "FURNISHED_PAPER",
        "FILED_ACCEPTED",
    ), (
        "the two dimensions advance independently, so the combined state should be "
        f"(FURNISHED_PAPER, FILED_ACCEPTED), got "
        f"({form['furnishing_status']!r}, {form['filing_status']!r})"
    )

    transmittal = fixtures.read_transmittal(api, built["id"])
    assert_transmittal(transmittal, status="ACCEPTED", receipt_id="AIR-2026-0003")

    group = fixtures.read_group(api, ctx["group"]["id"])
    assert group["open_correction_count"] == 0, (
        "a clean acceptance opens no correction, got "
        f"{group['open_correction_count']}"
    )
