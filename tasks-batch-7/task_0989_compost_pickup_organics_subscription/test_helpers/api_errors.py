    ERR_TAG_NOT_RESOLVABLE = "ERR_TAG_NOT_RESOLVABLE"
    ERR_REDEMPTION_NOT_FULFILLABLE = "ERR_REDEMPTION_NOT_FULFILLABLE"
    ERR_INVOICE_NOT_PAYABLE = "ERR_INVOICE_NOT_PAYABLE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
