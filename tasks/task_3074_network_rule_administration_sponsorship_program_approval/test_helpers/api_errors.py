"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can cross-check
HTTP status codes automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_IDENTITY_MISMATCH = "ERR_IDENTITY_MISMATCH"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_WINDOW_NOT_OPEN = "ERR_WINDOW_NOT_OPEN"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_WINDOW_EXPIRED = "ERR_WINDOW_EXPIRED"
    ERR_CERTIFICATION_STALE = "ERR_CERTIFICATION_STALE"
    ERR_PROGRAM_NOT_ENABLED = "ERR_PROGRAM_NOT_ENABLED"
    ERR_RATE_NOT_FOUND = "ERR_RATE_NOT_FOUND"
    ERR_SETTLEMENT_INVALID = "ERR_SETTLEMENT_INVALID"
    ERR_RULE_NOT_EFFECTIVE = "ERR_RULE_NOT_EFFECTIVE"
    ERR_SPONSOR_INACTIVE = "ERR_SPONSOR_INACTIVE"
    ERR_DRAFT_LINES_REMAIN = "ERR_DRAFT_LINES_REMAIN"
    ERR_MERCHANT_NOT_ACTIVE = "ERR_MERCHANT_NOT_ACTIVE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_IDENTITY_MISMATCH: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_WINDOW_NOT_OPEN: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 422,
    ApiErrorId.ERR_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_CERTIFICATION_STALE: 422,
    ApiErrorId.ERR_PROGRAM_NOT_ENABLED: 422,
    ApiErrorId.ERR_RATE_NOT_FOUND: 422,
    ApiErrorId.ERR_SETTLEMENT_INVALID: 422,
    ApiErrorId.ERR_RULE_NOT_EFFECTIVE: 422,
    ApiErrorId.ERR_SPONSOR_INACTIVE: 422,
    ApiErrorId.ERR_DRAFT_LINES_REMAIN: 422,
    ApiErrorId.ERR_MERCHANT_NOT_ACTIVE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
