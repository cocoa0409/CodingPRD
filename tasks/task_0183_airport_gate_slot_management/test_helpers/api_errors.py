"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CROSS_STATE_BLOCKED = "ERR_CROSS_STATE_BLOCKED"
    ERR_WINGSPAN_EXCEEDED = "ERR_WINGSPAN_EXCEEDED"
    ERR_GATE_WINDOW_CONFLICT = "ERR_GATE_WINDOW_CONFLICT"
    ERR_CUTE_BUSY = "ERR_CUTE_BUSY"
    ERR_EQUIPMENT_BUSY = "ERR_EQUIPMENT_BUSY"
    ERR_REMOTE_STAND_FULL = "ERR_REMOTE_STAND_FULL"
    ERR_SLOT_DOUBLE_BOOKED = "ERR_SLOT_DOUBLE_BOOKED"
    ERR_TURN_TIME_TOO_SHORT = "ERR_TURN_TIME_TOO_SHORT"
    ERR_SLOT_WINDOW_MISSED = "ERR_SLOT_WINDOW_MISSED"
    ERR_STALE_GATE_VERSION = "ERR_STALE_GATE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CROSS_STATE_BLOCKED: 409,
    ApiErrorId.ERR_WINGSPAN_EXCEEDED: 422,
    ApiErrorId.ERR_GATE_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_CUTE_BUSY: 409,
    ApiErrorId.ERR_EQUIPMENT_BUSY: 409,
    ApiErrorId.ERR_REMOTE_STAND_FULL: 409,
    ApiErrorId.ERR_SLOT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_TURN_TIME_TOO_SHORT: 422,
    ApiErrorId.ERR_SLOT_WINDOW_MISSED: 422,
    ApiErrorId.ERR_STALE_GATE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
