def setup_channel_with_grant(*, channel_name="Ch", loop_duration=600,
                             content_runtime=540, max_plays=10,
                             grant_window=(C.GRANT_WINDOW_START, C.GRANT_WINDOW_END),
                             channel_overrides=None):
    """Channel + AVAILABLE content + ACTIVE rights grant covering it."""
    channel = create_channel(
        name=channel_name, loop_duration=loop_duration, **(channel_overrides or {})
    )
    content = create_available_content(runtime_seconds=content_runtime)
    grant = create_active_grant(
        channel["id"], content["id"], max_plays=max_plays,
        window_start=grant_window[0], window_end=grant_window[1],
    )
    return {"channel": channel, "content": content, "grant": grant}


def tile_loop(loop_id, content_id, break_durations=(60,)):
    """Append one entry then mark the given breaks (each lands after the current
    last entry, per PRD §3.3). Returns (entries, breaks) with create responses."""
    entry = get_success_data(
        api_client.loop_add_entry(loop_id, {"content_id": content_id}, PROGRAMMER)
    )
    breaks = []
    for duration in break_durations:
        brk = get_success_data(
            api_client.loop_add_ad_break(
                loop_id, {"duration_seconds": duration}, PROGRAMMER
            )
        )
        breaks.append(brk)
    return [entry], breaks


def setup_validated_loop(*, channel_name="Ch", loop_duration=600,
                         break_durations=(60,), content_runtime=None,
                         broadcast_date=C.BROADCAST_DATE, max_plays=10,
                         grant_window=(C.GRANT_WINDOW_START, C.GRANT_WINDOW_END),
                         channel_overrides=None):
    """Channel + AVAILABLE content + ACTIVE grant + tiled loop in VALIDATED."""
    base = setup_channel_with_grant(
        channel_name=channel_name, loop_duration=loop_duration,
        content_runtime=content_runtime
        if content_runtime is not None
        else loop_duration - sum(break_durations),
        max_plays=max_plays, grant_window=grant_window,
        channel_overrides=channel_overrides,
    )
    loop = create_loop(base["channel"]["id"], broadcast_date)
    entries, breaks = tile_loop(loop["id"], base["content"]["id"], break_durations)
    loop = get_success_data(api_client.loop_validate(loop["id"], PROGRAMMER))
    return {**base, "loop": loop, "entries": entries, "breaks": breaks}


