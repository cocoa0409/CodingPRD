"""Error IDs and HTTP status mapping (PRD section 5 Error Code Catalogue).

After defining the mapping, register it with the framework so validate_error()
auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_FORBIDDEN_NOT_OWNER = "ERR_FORBIDDEN_NOT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_MEMBER_NOT_ACTIVE = "ERR_MEMBER_NOT_ACTIVE"
    ERR_MEMBER_HAS_OPEN_OBLIGATIONS = "ERR_MEMBER_HAS_OPEN_OBLIGATIONS"
    ERR_STATION_OUT_OF_SERVICE = "ERR_STATION_OUT_OF_SERVICE"
    ERR_PEAK_REQUIRES_PREMIUM = "ERR_PEAK_REQUIRES_PREMIUM"
    ERR_BOOKING_OVERLAP = "ERR_BOOKING_OVERLAP"
    ERR_RECIPE_EMPTY = "ERR_RECIPE_EMPTY"
    ERR_RECIPE_NOT_PUBLISHED = "ERR_RECIPE_NOT_PUBLISHED"
    ERR_RECIPE_IN_USE = "ERR_RECIPE_IN_USE"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_BATCH_NOT_COMPLETED = "ERR_BATCH_NOT_COMPLETED"
    ERR_ALLERGEN_CONFLICT = "ERR_ALLERGEN_CONFLICT"
    ERR_STORAGE_CAPACITY_EXCEEDED = "ERR_STORAGE_CAPACITY_EXCEEDED"
    ERR_UNIT_QUARANTINED = "ERR_UNIT_QUARANTINED"
    ERR_UNIT_NOT_RECOVERED = "ERR_UNIT_NOT_RECOVERED"
    ERR_INSUFFICIENT_WALLET = "ERR_INSUFFICIENT_WALLET"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_FORBIDDEN_NOT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_MEMBER_NOT_ACTIVE: 409,
    ApiErrorId.ERR_MEMBER_HAS_OPEN_OBLIGATIONS: 409,
    ApiErrorId.ERR_STATION_OUT_OF_SERVICE: 409,
    ApiErrorId.ERR_PEAK_REQUIRES_PREMIUM: 409,
    ApiErrorId.ERR_BOOKING_OVERLAP: 409,
    ApiErrorId.ERR_RECIPE_EMPTY: 409,
    ApiErrorId.ERR_RECIPE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_RECIPE_IN_USE: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_BATCH_NOT_COMPLETED: 409,
    ApiErrorId.ERR_ALLERGEN_CONFLICT: 409,
    ApiErrorId.ERR_STORAGE_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_UNIT_QUARANTINED: 409,
    ApiErrorId.ERR_UNIT_NOT_RECOVERED: 409,
    ApiErrorId.ERR_INSUFFICIENT_WALLET: 402,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
