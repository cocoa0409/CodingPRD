ERR_PROGRAM_NOT_OPEN = "ERR_PROGRAM_NOT_OPEN"
ERR_PROGRAM_HAS_OPEN_ELECTIONS = "ERR_PROGRAM_HAS_OPEN_ELECTIONS"
ERR_ACREAGE_DEADLINE_PASSED = "ERR_ACREAGE_DEADLINE_PASSED"
ERR_ACREAGE_OVER_REPORTED = "ERR_ACREAGE_OVER_REPORTED"
ERR_PP_ACRES_EXCEED_REPORTED = "ERR_PP_ACRES_EXCEED_REPORTED"
ERR_ELECTION_ALREADY_REPORTED = "ERR_ELECTION_ALREADY_REPORTED"
