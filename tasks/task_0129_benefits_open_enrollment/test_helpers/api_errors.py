"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_EOI_REQUIRED = "ERR_EOI_REQUIRED"
    ERR_EMPLOYEE_NOT_ELIGIBLE = "ERR_EMPLOYEE_NOT_ELIGIBLE"
    ERR_LIFE_EVENT_WINDOW_EXPIRED = "ERR_LIFE_EVENT_WINDOW_EXPIRED"
    ERR_WAITING_PERIOD_OVERLAP = "ERR_WAITING_PERIOD_OVERLAP"
    ERR_COVERAGE_OVERLAP = "ERR_COVERAGE_OVERLAP"
    ERR_DEPENDENT_NOT_VERIFIED = "ERR_DEPENDENT_NOT_VERIFIED"
    ERR_STALE_EMPLOYEE_VERSION = "ERR_STALE_EMPLOYEE_VERSION"
    ERR_PLAN_ARCHIVED = "ERR_PLAN_ARCHIVED"
    ERR_FORM_ALREADY_FILED = "ERR_FORM_ALREADY_FILED"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_EOI_REQUIRED: 409,
    ApiErrorId.ERR_EMPLOYEE_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_LIFE_EVENT_WINDOW_EXPIRED: 409,
    ApiErrorId.ERR_WAITING_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_COVERAGE_OVERLAP: 409,
    ApiErrorId.ERR_DEPENDENT_NOT_VERIFIED: 409,
    ApiErrorId.ERR_STALE_EMPLOYEE_VERSION: 412,
    ApiErrorId.ERR_PLAN_ARCHIVED: 409,
    ApiErrorId.ERR_FORM_ALREADY_FILED: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
