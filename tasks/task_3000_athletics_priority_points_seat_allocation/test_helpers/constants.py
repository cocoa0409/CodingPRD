# ─── Rounding helpers (PRD section 2.6) ───────────────────────────────────

POINTS_PLACES = Decimal("0.01")
RATIO_PLACES = Decimal("0.0001")


def round_half_up(value, places=POINTS_PLACES):
    """Quantize a Decimal-compatible value half up, as PRD section 2.6 mandates."""
    return Decimal(str(value)).quantize(Decimal(str(places)), rounding=ROUND_HALF_UP)


def cents_half_up(value):
    """Round a monetary quantity to whole integer cents, half up."""
    return int(Decimal(str(value)).quantize(Decimal("1"), rounding=ROUND_HALF_UP))
