"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_IMMUTABLE = "ERR_IMMUTABLE"
    ERR_ROUTE_LOCKED = "ERR_ROUTE_LOCKED"
    ERR_ACCOUNT_ON_HOLD = "ERR_ACCOUNT_ON_HOLD"
    ERR_TECH_SUSPENDED = "ERR_TECH_SUSPENDED"
    ERR_TECH_NOT_CERTIFIED = "ERR_TECH_NOT_CERTIFIED"
    ERR_TECH_WINDOW_CONFLICT = "ERR_TECH_WINDOW_CONFLICT"
    ERR_SITE_BUFFER_CONFLICT = "ERR_SITE_BUFFER_CONFLICT"
    ERR_OUTSIDE_SHIFT = "ERR_OUTSIDE_SHIFT"
    ERR_REPORT_NOT_FINALIZED = "ERR_REPORT_NOT_FINALIZED"
    ERR_SITE_NON_COMPLIANT = "ERR_SITE_NON_COMPLIANT"
    ERR_COOLING_OFF = "ERR_COOLING_OFF"
    ERR_MEASUREMENT_REQUIRED = "ERR_MEASUREMENT_REQUIRED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_IMMUTABLE: 409,
    ApiErrorId.ERR_ROUTE_LOCKED: 409,
    ApiErrorId.ERR_ACCOUNT_ON_HOLD: 409,
    ApiErrorId.ERR_TECH_SUSPENDED: 409,
    ApiErrorId.ERR_TECH_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_TECH_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_SITE_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_OUTSIDE_SHIFT: 409,
    ApiErrorId.ERR_REPORT_NOT_FINALIZED: 409,
    ApiErrorId.ERR_SITE_NON_COMPLIANT: 409,
    ApiErrorId.ERR_COOLING_OFF: 409,
    ApiErrorId.ERR_MEASUREMENT_REQUIRED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
