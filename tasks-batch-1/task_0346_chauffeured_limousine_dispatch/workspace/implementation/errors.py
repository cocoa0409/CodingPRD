"""Error classes and error ID constants (PRD §5 Error Code Catalogue)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error ID -> HTTP status (PRD §5)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_TIME_WINDOW = ("ERR_INVALID_TIME_WINDOW", 422)
ERR_TRIP_TYPE_FIELDS = ("ERR_TRIP_TYPE_FIELDS", 422)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_FLIGHT_NOT_APPLICABLE = ("ERR_FLIGHT_NOT_APPLICABLE", 409)
ERR_WAIT_SEQUENCE = ("ERR_WAIT_SEQUENCE", 409)
ERR_RESOURCE_UNAVAILABLE = ("ERR_RESOURCE_UNAVAILABLE", 409)
ERR_CHAUFFEUR_DOUBLE_BOOKED = ("ERR_CHAUFFEUR_DOUBLE_BOOKED", 409)
ERR_VEHICLE_TURNAROUND_VIOLATION = ("ERR_VEHICLE_TURNAROUND_VIOLATION", 409)
ERR_FULFILLMENT_CONFLICT = ("ERR_FULFILLMENT_CONFLICT", 409)
ERR_AFFILIATE_INELIGIBLE = ("ERR_AFFILIATE_INELIGIBLE", 409)
ERR_NOT_BILLABLE = ("ERR_NOT_BILLABLE", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_ACCOUNT_SUSPENDED = ("ERR_ACCOUNT_SUSPENDED", 409)
ERR_VALIDATION_RANGE = ("ERR_VALIDATION_RANGE", 422)
ERR_DUPLICATE_PLATE = ("ERR_DUPLICATE_PLATE", 409)
ERR_DUPLICATE_CLASS_CODE = ("ERR_DUPLICATE_CLASS_CODE", 409)


def err(spec, message=None):
    """Build an ApiError from one of the (id, status) tuples above."""
    return ApiError(spec[0], spec[1], message)
