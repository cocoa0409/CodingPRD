"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_FACILITY_UNIT_LIMIT = "ERR_FACILITY_UNIT_LIMIT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CROSS_ENTITY_STATE = "ERR_CROSS_ENTITY_STATE"
    ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
    ERR_AGREEMENT_HAS_ACTIVE_SERVICE = "ERR_AGREEMENT_HAS_ACTIVE_SERVICE"
    ERR_UNIT_OVERLAP = "ERR_UNIT_OVERLAP"
    ERR_TRANSPORTER_CONFLICT = "ERR_TRANSPORTER_CONFLICT"
    ERR_INSURANCE_LAPSED = "ERR_INSURANCE_LAPSED"
    ERR_COVERAGE_INSUFFICIENT = "ERR_COVERAGE_INSUFFICIENT"
    ERR_MEMBER_SUSPENDED = "ERR_MEMBER_SUSPENDED"
    ERR_UNITS_AVAILABLE = "ERR_UNITS_AVAILABLE"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_STALE_UNIT_VERSION = "ERR_STALE_UNIT_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_FACILITY_UNIT_LIMIT: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CROSS_ENTITY_STATE: 409,
    ApiErrorId.ERR_UNIT_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_AGREEMENT_HAS_ACTIVE_SERVICE: 409,
    ApiErrorId.ERR_UNIT_OVERLAP: 409,
    ApiErrorId.ERR_TRANSPORTER_CONFLICT: 409,
    ApiErrorId.ERR_INSURANCE_LAPSED: 409,
    ApiErrorId.ERR_COVERAGE_INSUFFICIENT: 409,
    ApiErrorId.ERR_MEMBER_SUSPENDED: 402,
    ApiErrorId.ERR_UNITS_AVAILABLE: 409,
    ApiErrorId.ERR_OFFER_EXPIRED: 409,
    ApiErrorId.ERR_STALE_UNIT_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
