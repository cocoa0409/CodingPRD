"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_DISPOSITION_ROLE_MISMATCH = "ERR_DISPOSITION_ROLE_MISMATCH"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TERM_NOT_OPEN = "ERR_TERM_NOT_OPEN"
    ERR_BEFORE_REPORT_DATE = "ERR_BEFORE_REPORT_DATE"
    ERR_DUPLICATE_SUMMONS = "ERR_DUPLICATE_SUMMONS"
    ERR_DUPLICATE_SERVICE_DATE = "ERR_DUPLICATE_SERVICE_DATE"
    ERR_TRIAL_NOT_READY = "ERR_TRIAL_NOT_READY"
    ERR_SUMMONS_NOT_REPORTING = "ERR_SUMMONS_NOT_REPORTING"
    ERR_PANEL_FULL = "ERR_PANEL_FULL"
    ERR_DEFERRAL_LIMIT = "ERR_DEFERRAL_LIMIT"
    ERR_POOL_EXHAUSTED = "ERR_POOL_EXHAUSTED"
    ERR_STALE_PANEL_VERSION = "ERR_STALE_PANEL_VERSION"
    ERR_STALE_TERM_VERSION = "ERR_STALE_TERM_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_DISPOSITION_ROLE_MISMATCH: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_TERM_NOT_OPEN: 409,
    ApiErrorId.ERR_BEFORE_REPORT_DATE: 409,
    ApiErrorId.ERR_DUPLICATE_SUMMONS: 409,
    ApiErrorId.ERR_DUPLICATE_SERVICE_DATE: 409,
    ApiErrorId.ERR_TRIAL_NOT_READY: 409,
    ApiErrorId.ERR_SUMMONS_NOT_REPORTING: 409,
    ApiErrorId.ERR_PANEL_FULL: 409,
    ApiErrorId.ERR_DEFERRAL_LIMIT: 409,
    ApiErrorId.ERR_POOL_EXHAUSTED: 409,
    ApiErrorId.ERR_STALE_PANEL_VERSION: 412,
    ApiErrorId.ERR_STALE_TERM_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
