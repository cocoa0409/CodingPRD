"""Error IDs and HTTP status mapping (MES PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_OPERATION_SEQUENCE_VIOLATION = "ERR_OPERATION_SEQUENCE_VIOLATION"
    ERR_ROUTING_NOT_RELEASED = "ERR_ROUTING_NOT_RELEASED"
    ERR_MACHINE_DOWN = "ERR_MACHINE_DOWN"
    ERR_TRAVELER_NOT_SIGNED = "ERR_TRAVELER_NOT_SIGNED"
    ERR_RUNLOG_OVERLAP = "ERR_RUNLOG_OVERLAP"
    ERR_SETUP_BUFFER_CONFLICT = "ERR_SETUP_BUFFER_CONFLICT"
    ERR_BOM_CYCLE = "ERR_BOM_CYCLE"
    ERR_DUPLICATE_SEQUENCE = "ERR_DUPLICATE_SEQUENCE"
    ERR_SCRAP_QTY_EXCEEDS = "ERR_SCRAP_QTY_EXCEEDS"
    ERR_INSUFFICIENT_LOT_QTY = "ERR_INSUFFICIENT_LOT_QTY"
    ERR_LOT_PRODUCT_MISMATCH = "ERR_LOT_PRODUCT_MISMATCH"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_OPERATION_SEQUENCE_VIOLATION: 409,
    ApiErrorId.ERR_ROUTING_NOT_RELEASED: 409,
    ApiErrorId.ERR_MACHINE_DOWN: 409,
    ApiErrorId.ERR_TRAVELER_NOT_SIGNED: 409,
    ApiErrorId.ERR_RUNLOG_OVERLAP: 409,
    ApiErrorId.ERR_SETUP_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_BOM_CYCLE: 409,
    ApiErrorId.ERR_DUPLICATE_SEQUENCE: 409,
    ApiErrorId.ERR_SCRAP_QTY_EXCEEDS: 422,
    ApiErrorId.ERR_INSUFFICIENT_LOT_QTY: 422,
    ApiErrorId.ERR_LOT_PRODUCT_MISMATCH: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
