"""API error class and error-id constants (verbatim from SCAFFOLD §1.6 / PRD §5)."""
from __future__ import annotations


ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_MEDIATION_REQUIRED = "ERR_MEDIATION_REQUIRED"
ERR_NOTICE_PERIOD_VIOLATED = "ERR_NOTICE_PERIOD_VIOLATED"
ERR_FORBEARANCE_WINDOW_EXCEEDED = "ERR_FORBEARANCE_WINDOW_EXCEEDED"
ERR_DISBURSEMENT_IN_PAST = "ERR_DISBURSEMENT_IN_PAST"
ERR_CUSHION_OVERLIMIT = "ERR_CUSHION_OVERLIMIT"
ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
ERR_PMI_NOT_ELIGIBLE_LTV = "ERR_PMI_NOT_ELIGIBLE_LTV"
ERR_PMI_NOT_ELIGIBLE_HISTORY = "ERR_PMI_NOT_ELIGIBLE_HISTORY"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


_HTTP_FOR: dict[str, int] = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNAUTHORIZED: 403,
    ERR_RESOURCE_NOT_FOUND: 404,
    ERR_FK_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 412,
    ERR_MEDIATION_REQUIRED: 422,
    ERR_NOTICE_PERIOD_VIOLATED: 422,
    ERR_FORBEARANCE_WINDOW_EXCEEDED: 422,
    ERR_DISBURSEMENT_IN_PAST: 422,
    ERR_CUSHION_OVERLIMIT: 422,
    ERR_INVALID_AMOUNT: 422,
    ERR_PMI_NOT_ELIGIBLE_LTV: 422,
    ERR_PMI_NOT_ELIGIBLE_HISTORY: 422,
    ERR_INVALID_REQUEST: 400,
}


class ApiError(Exception):
    def __init__(self, error_id: str, message: str, http_status: int | None = None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else _HTTP_FOR.get(error_id, 500)
