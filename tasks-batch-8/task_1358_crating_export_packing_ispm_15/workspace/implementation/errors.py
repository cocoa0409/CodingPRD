def bad_request(msg):
    return ApiError(ERR_INVALID_REQUEST, msg, 400)


def not_found(msg):
    return ApiError(ERR_NOT_FOUND, msg, 404)


def conflict(error_id, msg):
    return ApiError(error_id, msg, 409)


def unprocessable(error_id, msg):
    return ApiError(error_id, msg, 422)
