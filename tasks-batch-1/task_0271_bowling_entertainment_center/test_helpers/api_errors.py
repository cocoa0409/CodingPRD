"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, register it with the framework so validate_error()
auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # --- auth ---
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    # --- existence / request ---
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    # --- state ---
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # --- cross-entity referential ---
    ERR_RESOURCE_OUT_OF_SERVICE = "ERR_RESOURCE_OUT_OF_SERVICE"
    ERR_RENTALS_OUTSTANDING = "ERR_RENTALS_OUTSTANDING"
    ERR_LEAGUE_NOT_ACTIVE = "ERR_LEAGUE_NOT_ACTIVE"
    ERR_LEAGUE_HAS_SCHEDULED_NIGHTS = "ERR_LEAGUE_HAS_SCHEDULED_NIGHTS"
    ERR_LEAGUE_NO_NIGHTS = "ERR_LEAGUE_NO_NIGHTS"
    # --- temporal / capacity ---
    ERR_LANE_TIME_CONFLICT = "ERR_LANE_TIME_CONFLICT"
    ERR_BAY_TIME_CONFLICT = "ERR_BAY_TIME_CONFLICT"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_RENTAL_UNAVAILABLE = "ERR_RENTAL_UNAVAILABLE"
    # --- fiscal / lifecycle ---
    ERR_CUSTOMER_SUSPENDED = "ERR_CUSTOMER_SUSPENDED"
    ERR_NOT_WAITLISTED = "ERR_NOT_WAITLISTED"
    ERR_DUPLICATE_LANE_NUMBER = "ERR_DUPLICATE_LANE_NUMBER"
    ERR_DUPLICATE_NIGHT_INDEX = "ERR_DUPLICATE_NIGHT_INDEX"
    ERR_PARTY_GUESTS_EXCEED_MAX = "ERR_PARTY_GUESTS_EXCEED_MAX"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_RESOURCE_OUT_OF_SERVICE: 409,
    ApiErrorId.ERR_RENTALS_OUTSTANDING: 409,
    ApiErrorId.ERR_LEAGUE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_LEAGUE_HAS_SCHEDULED_NIGHTS: 409,
    ApiErrorId.ERR_LEAGUE_NO_NIGHTS: 409,
    ApiErrorId.ERR_LANE_TIME_CONFLICT: 409,
    ApiErrorId.ERR_BAY_TIME_CONFLICT: 409,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_RENTAL_UNAVAILABLE: 409,
    ApiErrorId.ERR_CUSTOMER_SUSPENDED: 409,
    ApiErrorId.ERR_NOT_WAITLISTED: 409,
    ApiErrorId.ERR_DUPLICATE_LANE_NUMBER: 409,
    ApiErrorId.ERR_DUPLICATE_NIGHT_INDEX: 409,
    ApiErrorId.ERR_PARTY_GUESTS_EXCEED_MAX: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
