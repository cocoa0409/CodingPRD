@bp.route("/fafsa/completion-reports", methods=["POST"])
def create_report():
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["CampaignAdmin"])
    body = validate.get_json_body(required=True)
    validate.check_fields(body, required=["campaign_id", "variant"], optional=[])
    campaign_id = validate.req_string(body, "campaign_id")
    variant = validate.req_enum(body, "variant", core.REPORT_VARIANTS)
    campaign = core.get_campaign_or_404(campaign_id)
    if campaign["status"] not in ("OPEN", "STATE_GRACE"):
        errors.raise_error(errors.ERR_CAMPAIGN_NOT_OPEN, "Report generation requires campaign OPEN or STATE_GRACE")

    rows, total_eligible, total_completed, overall_rate = core.generate_report_rows(campaign, variant)
    common = make_common()
    report = {
        **common,
        "campaign_id": campaign_id,
        "variant": variant,
        "status": "GENERATED",
        "rows": rows,
        "eligible_count": total_eligible,
        "completed_count": total_completed,
        "overall_rate": overall_rate,
        "_seq": store.next_seq(),
    }
    store.completion_reports[report["id"]] = report
    return success_object(core.serialize(report), 201)


