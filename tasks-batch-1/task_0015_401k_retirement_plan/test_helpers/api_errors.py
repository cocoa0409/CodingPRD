"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_LOAN_ALREADY_OUTSTANDING = "ERR_LOAN_ALREADY_OUTSTANDING"
    ERR_LOAN_EXCEEDS_LIMIT = "ERR_LOAN_EXCEEDS_LIMIT"
    ERR_DEFERRAL_LIMIT_EXCEEDED = "ERR_DEFERRAL_LIMIT_EXCEEDED"
    ERR_NO_HARDSHIP_HEADROOM = "ERR_NO_HARDSHIP_HEADROOM"
    ERR_RMD_NOT_REQUIRED = "ERR_RMD_NOT_REQUIRED"
    ERR_JOINT_LIFE_INELIGIBLE = "ERR_JOINT_LIFE_INELIGIBLE"
    ERR_DUPLICATE_RMD_YEAR = "ERR_DUPLICATE_RMD_YEAR"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_LOAN_ALREADY_OUTSTANDING: 409,
    ApiErrorId.ERR_LOAN_EXCEEDS_LIMIT: 422,
    ApiErrorId.ERR_DEFERRAL_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_NO_HARDSHIP_HEADROOM: 422,
    ApiErrorId.ERR_RMD_NOT_REQUIRED: 422,
    ApiErrorId.ERR_JOINT_LIFE_INELIGIBLE: 422,
    ApiErrorId.ERR_DUPLICATE_RMD_YEAR: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
