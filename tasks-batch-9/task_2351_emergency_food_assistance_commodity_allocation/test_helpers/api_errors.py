# Tests reference these identifiers either short (``ApiErrorId.DOCK_WINDOW_CONFLICT``)
# or fully qualified (``ApiErrorId.ERR_DOCK_WINDOW_CONFLICT``); expose both spellings
# so a test module never has to remember which convention it used.
for _short_name, _error_id in list(vars(ApiErrorId).items()):
    if not _short_name.startswith("_"):
        setattr(ApiErrorId, _error_id, _error_id)
del _short_name, _error_id


