def tm_factor(pct):
    """TM_FACTOR band for a translation-memory match percentage."""
    if pct is None:
        pct = 0
    if pct >= 95:
        return Decimal("0.10")
    if pct >= 75:
        return Decimal("0.45")
    if pct >= 50:
        return Decimal("0.75")
    return Decimal("1.00")
