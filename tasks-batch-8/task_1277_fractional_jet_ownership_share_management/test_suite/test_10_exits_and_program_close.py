class TestBuyoutFormulaAfterOneYear:
    def _valued_exit_after_one_year(self, program_code):
        """1/8 MID share bought at 40000000 with a 2000000 deposit; one issued-unpaid
        August invoice; clock advanced one full contract year; exit opened + valued."""
        sc = setup_program_with_share(
            program_code=program_code, class_code="MID", fraction=(1, 8),
            purchase_price_cents=40000000, initial_deposit_cents=2000000,
            monthly_fee_base_cents=4000000,
        )
        invoice = create_issued_invoice(sc["owner"]["id"], "2026-08", "2026-09-01T00:00:00Z")
        set_clock("2027-09-01T00:00:00Z")  # crosses the August 2027 anniversary -> year 1
        exit_req = open_exit_ok(sc["share"]["id"], sc["owner"]["id"])
        sc.update({"invoice": invoice, "exit": exit_req})
        return sc

    def test_valuation_computes_penalty_and_buyout(self, api):
        """PRD §3.9: "Market value is the share's `purchase_price_cents` scaled by an 82
        percent residual index — 8200 basis points — rounded half-up to whole cents. When
        at least three full contract years have elapsed since activation — a
        `contract_year_index` of three or more — the `early_exit_penalty_cents` is zero.
        Otherwise the penalty is 20 percent of market value, scaled by the unelapsed
        fraction of the three-year minimum hold — the years remaining divided by three —
        rounded half-up to whole cents."

        Design: Difficulty/combinatorial_formula/exit_buyout_circular_evaluation_order
        """
        sc = self._valued_exit_after_one_year("FJX-CF2")
        valued = value_exit_ok(sc["exit"]["id"], "finops-valuer-1")
        assert valued["exit_status"] == "VALUED"
        # market = round(40000000 * 0.82) = 32800000; years_held = 1
        # penalty = round(32800000 * 0.20 * (3-1)/3) = 4373333
        assert valued["early_exit_penalty_cents"] == 4373333, (
            f"got {valued['early_exit_penalty_cents']}"
        )
        assert valued["buyout_amount_cents"] == 28426667, (
            f"32800000 - 4373333, got {valued['buyout_amount_cents']}"
        )

    def test_settlement_nets_outstanding_invoice_and_deposit(self, api):
        """PRD §3.9: "The `settlement_cents` is the buyout amount minus the owner's
        `outstanding_invoice_balance_cents` plus the owner's `deposit_balance_cents`,
        where the outstanding balance is the sum of `total_due_cents` across the owner's
        invoices standing in `OPEN`, `ISSUED`, `PAST_DUE`, or `DISPUTED` as of the settle
        clock; those invoices are force-closed, netted into the settlement."
        PRD §3.9: "The valuation never feeds itself — no line generated by the exit
        enters its own outstanding balance."

        Design: Difficulty/combinatorial_formula/exit_buyout_circular_evaluation_order
        """
        sc = self._valued_exit_after_one_year("FJX-CF2B")
        # The August invoice (management fee 1/8 x 4000000 = 500000) is still outstanding
        invoice = get_invoice_safe(api, sc["invoice"]["id"])
        assert invoice["total_due_cents"] == 500000
        value_exit_ok(sc["exit"]["id"], "finops-valuer-1")
        approve_exit_ok(sc["exit"]["id"], "finops-approver-1")
        settled = settle_exit_ok(sc["exit"]["id"], "finops-approver-1")
        # settlement = 28426667 - 500000 + 2000000 = 29926667
        assert settled["settlement_cents"] == 29926667, (
            f"buyout nets the outstanding invoice and returns the deposit, got "
            f"{settled['settlement_cents']}"
        )
        assert settled["exit_status"] == "SETTLED"


