"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Existence — PRD §2.5
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"

    # Schema — PRD §5
    ERR_VALIDATION = "ERR_VALIDATION"

    # Beneficiary state — PRD §2.8
    ERR_BENEFICIARY_DECEASED = "ERR_BENEFICIARY_DECEASED"

    # Entity state — PRD §2.8
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Plan / enrollment guards — PRD §3.4 / §3.8 / §3.9
    ERR_PLAN_INACTIVE = "ERR_PLAN_INACTIVE"
    ERR_NON_PART_D_CLAIM = "ERR_NON_PART_D_CLAIM"
    ERR_PERIOD_NOT_OPEN = "ERR_PERIOD_NOT_OPEN"
    ERR_PERIOD_ALREADY_CONSUMED = "ERR_PERIOD_ALREADY_CONSUMED"
    ERR_EFFECTIVE_DATE_OUTSIDE_PERIOD = "ERR_EFFECTIVE_DATE_OUTSIDE_PERIOD"
    ERR_FILL_DATE_OUT_OF_COVERAGE = "ERR_FILL_DATE_OUT_OF_COVERAGE"
    ERR_DUPLICATE_PART_ENROLLMENT = "ERR_DUPLICATE_PART_ENROLLMENT"
    ERR_MEDIGAP_STATE_MISMATCH = "ERR_MEDIGAP_STATE_MISMATCH"
    ERR_TRANSFER_WINDOW_INVALID = "ERR_TRANSFER_WINDOW_INVALID"
    ERR_INVALID_PREMIUM = "ERR_INVALID_PREMIUM"

    # Ledger — PRD §2.10
    ERR_LEDGER_INVARIANT_BREACH = "ERR_LEDGER_INVARIANT_BREACH"
    ERR_REVERSE_BLOCKED_BY_LATER_CLAIM = "ERR_REVERSE_BLOCKED_BY_LATER_CLAIM"
    ERR_LEDGER_VERSION_STALE = "ERR_LEDGER_VERSION_STALE"

    # Segregation of duties — PRD §3.8
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # OCC — PRD §2.7
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


# PRD §5 — Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_BENEFICIARY_DECEASED: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PLAN_INACTIVE: 422,
    ApiErrorId.ERR_NON_PART_D_CLAIM: 422,
    ApiErrorId.ERR_PERIOD_NOT_OPEN: 409,
    ApiErrorId.ERR_PERIOD_ALREADY_CONSUMED: 409,
    ApiErrorId.ERR_EFFECTIVE_DATE_OUTSIDE_PERIOD: 422,
    ApiErrorId.ERR_FILL_DATE_OUT_OF_COVERAGE: 422,
    ApiErrorId.ERR_DUPLICATE_PART_ENROLLMENT: 409,
    ApiErrorId.ERR_MEDIGAP_STATE_MISMATCH: 422,
    ApiErrorId.ERR_LEDGER_INVARIANT_BREACH: 409,
    ApiErrorId.ERR_REVERSE_BLOCKED_BY_LATER_CLAIM: 409,
    ApiErrorId.ERR_LEDGER_VERSION_STALE: 409,
    ApiErrorId.ERR_TRANSFER_WINDOW_INVALID: 422,
    ApiErrorId.ERR_INVALID_PREMIUM: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
