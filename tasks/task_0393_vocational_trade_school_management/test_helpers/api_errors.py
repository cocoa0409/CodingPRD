    # program / cohort lifecycle
    ERR_PROGRAM_NOT_OPEN = "ERR_PROGRAM_NOT_OPEN"
    ERR_COHORT_NOT_STARTED = "ERR_COHORT_NOT_STARTED"
    ERR_COHORT_CLOSED = "ERR_COHORT_CLOSED"
    ERR_COHORT_FULL = "ERR_COHORT_FULL"
    ERR_OPEN_AGREEMENTS_EXIST = "ERR_OPEN_AGREEMENTS_EXIST"
    # enrollment / SAP
    ERR_ADMISSION_PREREQ_UNMET = "ERR_ADMISSION_PREREQ_UNMET"
    ERR_SCOPE_MISMATCH = "ERR_SCOPE_MISMATCH"
    ERR_SAP_DISMISSED = "ERR_SAP_DISMISSED"
    ERR_SAP_NOT_SATISFACTORY = "ERR_SAP_NOT_SATISFACTORY"
    ERR_SAP_NOT_APPEALABLE = "ERR_SAP_NOT_APPEALABLE"
