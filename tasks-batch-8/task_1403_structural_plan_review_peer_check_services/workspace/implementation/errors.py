def bad_request(error_id=ERR_INVALID_REQUEST, message="Invalid request"):
    return ApiError(error_id, 400, message)


def forbidden(error_id, message):
    return ApiError(error_id, 403, message)


def not_found(error_id, message):
    return ApiError(error_id, 404, message)


def conflict(error_id, message):
    return ApiError(error_id, 409, message)


def unprocessable(error_id, message):
    return ApiError(error_id, 422, message)


def stale(error_id, message):
    return ApiError(error_id, 412, message)
