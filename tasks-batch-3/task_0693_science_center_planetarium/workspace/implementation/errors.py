"""Error catalogue and the ApiError exception (PRD §5)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error id -> http status (PRD §5 Error Code Catalogue)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_SHOW_VERSION = ("ERR_STALE_SHOW_VERSION", 412)
ERR_STALE_SESSION_VERSION = ("ERR_STALE_SESSION_VERSION", 412)
ERR_STALE_SPONSOR_VERSION = ("ERR_STALE_SPONSOR_VERSION", 412)
ERR_ACCESSIBLE_SEATS_UNAVAILABLE = ("ERR_ACCESSIBLE_SEATS_UNAVAILABLE", 409)
ERR_AGE_INELIGIBLE = ("ERR_AGE_INELIGIBLE", 422)
ERR_SHOW_TIME_CONFLICT = ("ERR_SHOW_TIME_CONFLICT", 409)
ERR_RENTAL_TIME_CONFLICT = ("ERR_RENTAL_TIME_CONFLICT", 409)
ERR_VENUE_TYPE_MISMATCH = ("ERR_VENUE_TYPE_MISMATCH", 422)
ERR_INVALID_TIME_WINDOW = ("ERR_INVALID_TIME_WINDOW", 422)
ERR_HOLD_EXPIRED = ("ERR_HOLD_EXPIRED", 409)
ERR_PARTY_SIZE_INVALID = ("ERR_PARTY_SIZE_INVALID", 422)
ERR_SHOW_CAPACITY_EXCEEDED = ("ERR_SHOW_CAPACITY_EXCEEDED", 409)
ERR_SESSION_FULL = ("ERR_SESSION_FULL", 409)
ERR_OVERFULFILLMENT = ("ERR_OVERFULFILLMENT", 422)
ERR_ACCOMMODATION_SUBJECT_MISMATCH = ("ERR_ACCOMMODATION_SUBJECT_MISMATCH", 422)
ERR_VALIDATION = ("ERR_VALIDATION", 422)
ERR_PAGINATION_INVALID = ("ERR_PAGINATION_INVALID", 400)


def err(spec, message=None):
    """Build an ApiError from one of the (id, http) tuples above."""
    error_id, http_status = spec
    return ApiError(error_id, http_status, message)
