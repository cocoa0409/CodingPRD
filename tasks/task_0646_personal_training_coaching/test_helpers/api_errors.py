"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can cross-check the HTTP status automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    # existence
    ERR_TRAINER_NOT_FOUND = "ERR_TRAINER_NOT_FOUND"
    ERR_CLIENT_NOT_FOUND = "ERR_CLIENT_NOT_FOUND"
    ERR_ENGAGEMENT_NOT_FOUND = "ERR_ENGAGEMENT_NOT_FOUND"
    ERR_PACK_NOT_FOUND = "ERR_PACK_NOT_FOUND"
    ERR_BOOKING_NOT_FOUND = "ERR_BOOKING_NOT_FOUND"
    ERR_PROGRAM_NOT_FOUND = "ERR_PROGRAM_NOT_FOUND"
    ERR_MACROPLAN_NOT_FOUND = "ERR_MACROPLAN_NOT_FOUND"
    ERR_CHECKIN_NOT_FOUND = "ERR_CHECKIN_NOT_FOUND"
    # request validation
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    # state
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INTAKE_NOT_SUBMITTED = "ERR_INTAKE_NOT_SUBMITTED"
    ERR_INTAKE_NOT_ASSESSED = "ERR_INTAKE_NOT_ASSESSED"
    ERR_ENGAGEMENT_NOT_ACTIVE = "ERR_ENGAGEMENT_NOT_ACTIVE"
    ERR_PROGRAM_NOT_PUBLISHED = "ERR_PROGRAM_NOT_PUBLISHED"
    # business referential / constraint
    ERR_PACK_MODEL_MISMATCH = "ERR_PACK_MODEL_MISMATCH"
    ERR_NO_SESSIONS_REMAINING = "ERR_NO_SESSIONS_REMAINING"
    ERR_NO_WEIGHT_FOR_MACROS = "ERR_NO_WEIGHT_FOR_MACROS"
    # safety / threshold
    ERR_BOOKING_PRIVILEGE_SUSPENDED = "ERR_BOOKING_PRIVILEGE_SUSPENDED"
    # temporal
    ERR_BOOKING_OVERLAP = "ERR_BOOKING_OVERLAP"
    ERR_CLIENT_DOUBLE_BOOKED = "ERR_CLIENT_DOUBLE_BOOKED"
    ERR_RESCHEDULE_TOO_LATE = "ERR_RESCHEDULE_TOO_LATE"
    ERR_SESSION_NOT_STARTED = "ERR_SESSION_NOT_STARTED"
    ERR_SESSION_NOT_ENDED = "ERR_SESSION_NOT_ENDED"
    # concurrency
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_TRAINER_NOT_FOUND: 404,
    ApiErrorId.ERR_CLIENT_NOT_FOUND: 404,
    ApiErrorId.ERR_ENGAGEMENT_NOT_FOUND: 404,
    ApiErrorId.ERR_PACK_NOT_FOUND: 404,
    ApiErrorId.ERR_BOOKING_NOT_FOUND: 404,
    ApiErrorId.ERR_PROGRAM_NOT_FOUND: 404,
    ApiErrorId.ERR_MACROPLAN_NOT_FOUND: 404,
    ApiErrorId.ERR_CHECKIN_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INTAKE_NOT_SUBMITTED: 409,
    ApiErrorId.ERR_INTAKE_NOT_ASSESSED: 409,
    ApiErrorId.ERR_ENGAGEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PROGRAM_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_PACK_MODEL_MISMATCH: 409,
    ApiErrorId.ERR_NO_SESSIONS_REMAINING: 409,
    ApiErrorId.ERR_NO_WEIGHT_FOR_MACROS: 409,
    ApiErrorId.ERR_BOOKING_PRIVILEGE_SUSPENDED: 403,
    ApiErrorId.ERR_BOOKING_OVERLAP: 409,
    ApiErrorId.ERR_CLIENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_RESCHEDULE_TOO_LATE: 409,
    ApiErrorId.ERR_SESSION_NOT_STARTED: 409,
    ApiErrorId.ERR_SESSION_NOT_ENDED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
