class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog (id -> http status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_RESOURCE_NOT_FOUND = ("ERR_RESOURCE_NOT_FOUND", 404)
ERR_FK_MISMATCH = ("ERR_FK_MISMATCH", 409)
ERR_DUPLICATE_TIN = ("ERR_DUPLICATE_TIN", 409)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_SEGREGATION_OF_DUTIES = ("ERR_SEGREGATION_OF_DUTIES", 409)
ERR_CONFLICTING_RESOLUTION = ("ERR_CONFLICTING_RESOLUTION", 409)
ERR_PAYOFF_SHAPE_INVALID = ("ERR_PAYOFF_SHAPE_INVALID", 422)
ERR_SHORT_TERM_TOO_LONG = ("ERR_SHORT_TERM_TOO_LONG", 422)
ERR_AGREEMENT_WINDOW_OVERLAP = ("ERR_AGREEMENT_WINDOW_OVERLAP", 409)
ERR_OVERLAPPING_SUSPENSION = ("ERR_OVERLAPPING_SUSPENSION", 409)
ERR_OFFER_BELOW_RCP = ("ERR_OFFER_BELOW_RCP", 422)
ERR_LIEN_RELEASE_BLOCKED = ("ERR_LIEN_RELEASE_BLOCKED", 409)
ERR_NOTHING_TO_SWEEP = ("ERR_NOTHING_TO_SWEEP", 422)
ERR_STALE_ACCOUNT_VERSION = ("ERR_STALE_ACCOUNT_VERSION", 412)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)


def err(spec, message=None):
    return ApiError(spec[0], spec[1], message)
