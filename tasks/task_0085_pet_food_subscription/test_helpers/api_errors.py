    # ---- business / referential ----
    ERR_ADDRESS_VERIFICATION_FAILED = "ERR_ADDRESS_VERIFICATION_FAILED"
    ERR_ADDRESS_NOT_VERIFIED = "ERR_ADDRESS_NOT_VERIFIED"
    ERR_ALLERGEN_PROHIBITED = "ERR_ALLERGEN_PROHIBITED"
    ERR_VET_PRESCRIBED_REQUIRED = "ERR_VET_PRESCRIBED_REQUIRED"
    ERR_RECIPE_NOT_ELIGIBLE = "ERR_RECIPE_NOT_ELIGIBLE"
    ERR_ROTATION_VIOLATION = "ERR_ROTATION_VIOLATION"
    ERR_NO_RECIPE_AVAILABLE = "ERR_NO_RECIPE_AVAILABLE"

    # ---- capacity / inventory ----
    ERR_NO_WAREHOUSE_AVAILABLE = "ERR_NO_WAREHOUSE_AVAILABLE"
    ERR_WAREHOUSE_CAPACITY_EXCEEDED = "ERR_WAREHOUSE_CAPACITY_EXCEEDED"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"

    # ---- optimistic concurrency ----
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


