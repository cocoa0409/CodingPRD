    UNSETTLED_STATEMENTS = "ERR_UNSETTLED_STATEMENTS"
    REVISION_LIMIT_EXCEEDED = "ERR_REVISION_LIMIT_EXCEEDED"
    REOPEN_LIMIT_EXCEEDED = "ERR_REOPEN_LIMIT_EXCEEDED"
    DISPUTE_LIMIT_EXCEEDED = "ERR_DISPUTE_LIMIT_EXCEEDED"

