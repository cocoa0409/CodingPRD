"""Error identifiers and their HTTP status codes.

The mapping is registered with the shared validator module so that
``validate_error(resp, ApiError.X)`` checks the status code automatically when
the caller does not pass one explicitly.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


