"""Error catalogue (PRD section 5). Every identifier and its HTTP status."""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super(ApiError, self).__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status or ERROR_STATUS.get(error_id, 422)
        self.message = message or DEFAULT_MESSAGE.get(error_id, error_id)


