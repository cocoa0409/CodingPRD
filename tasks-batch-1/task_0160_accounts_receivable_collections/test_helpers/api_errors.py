"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() auto-checks the
HTTP status from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DISPUTE_BLOCKS_WRITEOFF = "ERR_DISPUTE_BLOCKS_WRITEOFF"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_CUSTOMER_MISMATCH = "ERR_CUSTOMER_MISMATCH"
    ERR_DISPUTE_EXCEEDS_BALANCE = "ERR_DISPUTE_EXCEEDS_BALANCE"
    ERR_PROMISE_WINDOW_OVERLAP = "ERR_PROMISE_WINDOW_OVERLAP"
    ERR_PAUSE_WINDOW_CONFLICT = "ERR_PAUSE_WINDOW_CONFLICT"
    ERR_OVER_APPLICATION = "ERR_OVER_APPLICATION"
    ERR_APPLY_EXCEEDS_INVOICE = "ERR_APPLY_EXCEEDS_INVOICE"
    ERR_WRITEOFF_AMOUNT_MISMATCH = "ERR_WRITEOFF_AMOUNT_MISMATCH"
    ERR_CREDIT_HOLD = "ERR_CREDIT_HOLD"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_PROMISE_ALREADY_RESOLVED = "ERR_PROMISE_ALREADY_RESOLVED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DISPUTE_BLOCKS_WRITEOFF: 409,
    ApiErrorId.ERR_SOD_VIOLATION: 403,
    ApiErrorId.ERR_CUSTOMER_MISMATCH: 409,
    ApiErrorId.ERR_DISPUTE_EXCEEDS_BALANCE: 422,
    ApiErrorId.ERR_PROMISE_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_PAUSE_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_OVER_APPLICATION: 422,
    ApiErrorId.ERR_APPLY_EXCEEDS_INVOICE: 422,
    ApiErrorId.ERR_WRITEOFF_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_CREDIT_HOLD: 402,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
    ApiErrorId.ERR_PROMISE_ALREADY_RESOLVED: 409,
}

# Register with the framework so validate_error() cross-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
