"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_CERTIFICATE_HOLDER = "ERR_NOT_CERTIFICATE_HOLDER"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_BID = "ERR_INVALID_BID"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_CROSS_COUNTY_REFERENCE = "ERR_CROSS_COUNTY_REFERENCE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SALE_NOT_DUE = "ERR_SALE_NOT_DUE"
    ERR_SALE_EMPTY = "ERR_SALE_EMPTY"
    ERR_REDEMPTION_PERIOD_OPEN = "ERR_REDEMPTION_PERIOD_OPEN"
    ERR_DEED_ALREADY_AWARDED = "ERR_DEED_ALREADY_AWARDED"
    ERR_BID_BELOW_MINIMUM = "ERR_BID_BELOW_MINIMUM"
    ERR_DUPLICATE_SUB_TAX = "ERR_DUPLICATE_SUB_TAX"
    ERR_INSUFFICIENT_ESCROW = "ERR_INSUFFICIENT_ESCROW"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_CERTIFICATE_HOLDER: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_BID: 422,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_CROSS_COUNTY_REFERENCE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SALE_NOT_DUE: 409,
    ApiErrorId.ERR_SALE_EMPTY: 409,
    ApiErrorId.ERR_REDEMPTION_PERIOD_OPEN: 409,
    ApiErrorId.ERR_DEED_ALREADY_AWARDED: 409,
    ApiErrorId.ERR_BID_BELOW_MINIMUM: 409,
    ApiErrorId.ERR_DUPLICATE_SUB_TAX: 409,
    ApiErrorId.ERR_INSUFFICIENT_ESCROW: 402,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
