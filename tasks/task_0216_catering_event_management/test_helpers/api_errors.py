"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PACKAGE_RETIRED = "ERR_PACKAGE_RETIRED"
    ERR_LEAD_TIME_VIOLATED = "ERR_LEAD_TIME_VIOLATED"
    ERR_LEG_WINDOW_CONFLICT = "ERR_LEG_WINDOW_CONFLICT"
    ERR_VENUE_OVERBOOKED = "ERR_VENUE_OVERBOOKED"
    ERR_LEG_OUT_OF_ORDER = "ERR_LEG_OUT_OF_ORDER"
    ERR_BELOW_MIN_HEADCOUNT = "ERR_BELOW_MIN_HEADCOUNT"
    ERR_DIETARY_EXCEEDS_HEADCOUNT = "ERR_DIETARY_EXCEEDS_HEADCOUNT"
    ERR_OPEN_CHANGE_REQUEST = "ERR_OPEN_CHANGE_REQUEST"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_BALANCE_UNPAID = "ERR_BALANCE_UNPAID"
    ERR_STAFF_POOL_EXHAUSTED = "ERR_STAFF_POOL_EXHAUSTED"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_INVALID_PAYMENT = "ERR_INVALID_PAYMENT"
    ERR_VALIDATION_WINDOW = "ERR_VALIDATION_WINDOW"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PACKAGE_RETIRED: 409,
    ApiErrorId.ERR_LEAD_TIME_VIOLATED: 409,
    ApiErrorId.ERR_LEG_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_VENUE_OVERBOOKED: 409,
    ApiErrorId.ERR_LEG_OUT_OF_ORDER: 409,
    ApiErrorId.ERR_BELOW_MIN_HEADCOUNT: 422,
    ApiErrorId.ERR_DIETARY_EXCEEDS_HEADCOUNT: 422,
    ApiErrorId.ERR_OPEN_CHANGE_REQUEST: 409,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_BALANCE_UNPAID: 409,
    ApiErrorId.ERR_STAFF_POOL_EXHAUSTED: 409,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_INVALID_PAYMENT: 422,
    ApiErrorId.ERR_VALIDATION_WINDOW: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
