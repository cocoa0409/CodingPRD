"""Error identifiers and their HTTP statuses for the lead service line API.

Registering the map with ``set_error_http_status_map`` lets ``validate_error``
check the HTTP status implicitly whenever a caller passes only an error id.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


