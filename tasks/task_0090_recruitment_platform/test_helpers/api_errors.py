"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_INVALID_ROLE = "ERR_AUTH_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_HR_NOT_BOUND = "ERR_HR_NOT_BOUND"
    ERR_RESUME_NOT_VISIBLE = "ERR_RESUME_NOT_VISIBLE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PROHIBITED_CONTENT = "ERR_PROHIBITED_CONTENT"
    ERR_DUPLICATE_POSTING = "ERR_DUPLICATE_POSTING"
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_SLOT_IN_PAST = "ERR_SLOT_IN_PAST"
    ERR_INTERVIEWER_BUSY = "ERR_INTERVIEWER_BUSY"
    ERR_CANDIDATE_RATE_LIMIT = "ERR_CANDIDATE_RATE_LIMIT"
    ERR_POSTING_QUOTA_EXCEEDED = "ERR_POSTING_QUOTA_EXCEEDED"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_INVALID_SALARY_RANGE = "ERR_INVALID_SALARY_RANGE"
    ERR_ONBOARDING_ALREADY_EXISTS = "ERR_ONBOARDING_ALREADY_EXISTS"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_FEEDBACK_INVALID = "ERR_FEEDBACK_INVALID"
    ERR_CHECK_INVALID = "ERR_CHECK_INVALID"


# Per PRD §5 Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_HR_NOT_BOUND: 403,
    ApiErrorId.ERR_RESUME_NOT_VISIBLE: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PROHIBITED_CONTENT: 422,
    ApiErrorId.ERR_DUPLICATE_POSTING: 409,
    ApiErrorId.ERR_SEGREGATION_VIOLATION: 422,
    ApiErrorId.ERR_OFFER_EXPIRED: 409,
    ApiErrorId.ERR_SLOT_IN_PAST: 422,
    ApiErrorId.ERR_INTERVIEWER_BUSY: 409,
    ApiErrorId.ERR_CANDIDATE_RATE_LIMIT: 429,
    ApiErrorId.ERR_POSTING_QUOTA_EXCEEDED: 409,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_INVALID_SALARY_RANGE: 422,
    ApiErrorId.ERR_ONBOARDING_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_FEEDBACK_INVALID: 422,
    ApiErrorId.ERR_CHECK_INVALID: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
