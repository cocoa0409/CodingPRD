"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # auth / existence / request
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_SCORE_OUT_OF_RANGE = "ERR_SCORE_OUT_OF_RANGE"
    # concurrency / state
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # center / agreement
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_CENTER_OPERATING = "ERR_CENTER_OPERATING"
    ERR_CENTER_NOT_OPERATING = "ERR_CENTER_NOT_OPERATING"
    ERR_ROYALTY_RATE_INVALID = "ERR_ROYALTY_RATE_INVALID"
    ERR_TERRITORY_CONFLICT = "ERR_TERRITORY_CONFLICT"
    # enrollment / curriculum
    ERR_DIAGNOSTIC_MISSING = "ERR_DIAGNOSTIC_MISSING"
    ERR_LEVEL_SUBJECT_MISMATCH = "ERR_LEVEL_SUBJECT_MISMATCH"
    ERR_PREREQ_CYCLE = "ERR_PREREQ_CYCLE"
    ERR_ENROLLMENT_NOT_ACTIVE = "ERR_ENROLLMENT_NOT_ACTIVE"
    # session / attendance
    ERR_RATIO_EXCEEDED = "ERR_RATIO_EXCEEDED"
    ERR_SESSION_OVERLAP = "ERR_SESSION_OVERLAP"
    ERR_INSTRUCTOR_DOUBLE_BOOKED = "ERR_INSTRUCTOR_DOUBLE_BOOKED"
    ERR_SESSION_NOT_OPEN = "ERR_SESSION_NOT_OPEN"
    ERR_SESSION_NOT_STARTED = "ERR_SESSION_NOT_STARTED"
    # invoice
    ERR_EMPTY_INVOICE = "ERR_EMPTY_INVOICE"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_SCORE_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_CENTER_OPERATING: 409,
    ApiErrorId.ERR_CENTER_NOT_OPERATING: 409,
    ApiErrorId.ERR_ROYALTY_RATE_INVALID: 409,
    ApiErrorId.ERR_TERRITORY_CONFLICT: 409,
    ApiErrorId.ERR_DIAGNOSTIC_MISSING: 409,
    ApiErrorId.ERR_LEVEL_SUBJECT_MISMATCH: 409,
    ApiErrorId.ERR_PREREQ_CYCLE: 409,
    ApiErrorId.ERR_ENROLLMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_RATIO_EXCEEDED: 409,
    ApiErrorId.ERR_SESSION_OVERLAP: 409,
    ApiErrorId.ERR_INSTRUCTOR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_SESSION_NOT_OPEN: 409,
    ApiErrorId.ERR_SESSION_NOT_STARTED: 409,
    ApiErrorId.ERR_EMPTY_INVOICE: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
