@bp.route("/fafsa/support-cases/<cid>/resolve", methods=["POST"])
def resolve_case(cid):
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["Specialist"])
    case = core.get_case_or_404(cid)
    body = validate.get_json_body(required=False) or {}
    validate.check_fields(body, required=[], optional=["resolution_outcome"])
    if case["status"] not in ("IN_REVIEW", "ESCALATED"):
        errors.raise_error(errors.ERR_CASE_NOT_ACTIONABLE, "resolve requires IN_REVIEW or ESCALATED")
    if case.get("assigned_specialist_id") is None:
        errors.raise_error(errors.ERR_CASE_UNASSIGNED, "Case has no assigned specialist")
    middleware.require_ownership(auth, case["assigned_specialist_id"])

    senior = core.get_senior_or_404(case["senior_record_id"])
    if case["case_type"] == "VERIFICATION_FOLLOWUP":
        # Checklist must be COMPLETE
        checklist = None
        for cl in store.checklists.values():
            if cl["senior_record_id"] == senior["id"] and cl["status"] != "ARCHIVED":
                checklist = cl
                break
        if checklist is None or checklist["status"] != "COMPLETE":
            errors.raise_error(errors.ERR_CHECKLIST_NOT_COMPLETE, "VERIFICATION_FOLLOWUP resolve requires checklist COMPLETE")
        outcome = "VERIFICATION_COMPLETED"
    else:
        # SPECIAL_CIRCUMSTANCE
        outcome = body.get("resolution_outcome")
        if outcome not in ("INDEPENDENT_CONFIRMED", "NOT_QUALIFIED"):
            errors.raise_error(
                errors.ERR_DETERMINATION_REQUIRED,
                "resolution_outcome must be INDEPENDENT_CONFIRMED or NOT_QUALIFIED",
            )
    specialist_id = case["assigned_specialist_id"]
    case["status"] = "RESOLVED"
    case["resolution_outcome"] = outcome
    touch(case)
    if specialist_id:
        core.bump_case_count(specialist_id, -1)

    # Special-circumstance determination side effects
    if case["case_type"] == "SPECIAL_CIRCUMSTANCE":
        if outcome == "INDEPENDENT_CONFIRMED":
            if senior["dependency_status"] in ("DEPENDENT", "PENDING_REVIEW"):
                senior["dependency_status"] = "INDEPENDENT"
                touch(senior)
            core.regenerate_checklist_for_independent(senior)
        elif outcome == "NOT_QUALIFIED":
            if senior["dependency_status"] == "PENDING_REVIEW":
                senior["dependency_status"] = "DEPENDENT"
                touch(senior)
    return success_object(core.serialize(case))


