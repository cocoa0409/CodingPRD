"""Statement certification: ledger lock, regeneration rules, segregation of
duties, staleness, and gate ordering (PRD §3.8, §2.8)."""
from test_helpers import (
    validate_success, validate_error, validate_paginated,
    setup_active_agreement, post_expense, generate_statement,
    certify_statement, make_operator_headers, TEST_USERS,
)

AE = TEST_USERS["account_executive_headers"]
FO = TEST_USERS["flight_ops_headers"]
FC = TEST_USERS["finance_controller_headers"]


def _setup_draft_statement(api, tail_number, preparer_user_id="ae-1"):
    """ACTIVE agreement + FUEL expense 250000 in 2026-08 + DRAFT statement
    generated by the given AccountExecutive user id."""
    scenario = setup_active_agreement(tail_number=tail_number)
    aircraft_id = scenario["aircraft"]["id"]
    expense = post_expense(aircraft_id, category="FUEL", amount_cents=250000,
                           service_date="2026-08-05", paid_date="2026-08-07")
    statement = generate_statement(aircraft_id, period="2026-08",
                                   preparer_user_id=preparer_user_id)
    assert statement["status"] == "DRAFT"
    return scenario, expense, statement


def test_expense_billed_and_statement_locked_on_certify(api):
    """PRD §3.8: "Successful certification moves the statement from `DRAFT` to
    `CERTIFIED`, stamps `certified_by_user_id` with the acting `X-User-ID`, and
    locks the ledger: every in-period `POSTED` expense of the aircraft
    transitions to `BILLED` with its `statement_id` set to the certifying
    statement."
    PRD §2.9: "Standalone list endpoints that accept query filters
    (`aircraft_id`, `statement_id`, `trip_id`, `status`, `category`,
    `previous_event_id`, `crew_member_id`, `owner_id`) treat each supplied
    filter as an equality match"

    Design: Corner/entities/expense_billed_and_statement_locked_on_certify
    """
    _scenario, expense, statement = _setup_draft_statement(api, "N230JX")

    certified = certify_statement(statement["id"], certifier_user_id="fc-1")
    assert certified["status"] == "CERTIFIED"
    assert certified["certified_by_user_id"] == "fc-1"

    billed = validate_success(api.get_expense(expense["id"], FC), 200)
    assert billed["status"] == "BILLED"
    assert billed["statement_id"] == statement["id"]

    data, meta = validate_paginated(
        api.list_expenses(FC, params={"statement_id": statement["id"]})
    )
    assert meta["total_count"] == 1
    assert data[0]["id"] == expense["id"]


def test_statement_deliver_full_lifecycle(api):
    """PRD §3.8: "Delivery by an `AccountExecutive` moves a `CERTIFIED`
    statement to `DELIVERED`. Certify from a non-`DRAFT` state or deliver from
    a non-`CERTIFIED` state is `ERR_STATEMENT_INVALID_STATE`."

    Design: Corner/endpoints/statement_deliver_full_lifecycle
    """
    _scenario, _expense, statement = _setup_draft_statement(api, "N480JX")

    early = api.deliver_statement(statement["id"], AE)
    validate_error(early, "ERR_STATEMENT_INVALID_STATE", expected_status=409)

    certify_statement(statement["id"], certifier_user_id="fc-1")
    delivered = validate_success(api.deliver_statement(statement["id"], AE), 200)
    assert delivered["status"] == "DELIVERED"


def test_statement_regenerate_over_certified_rejected(api):
    """PRD §3.8: "Generation is idempotent over drafts: at most one statement
    per aircraft and period may exist in `CERTIFIED` or `DELIVERED` — a
    duplicate there is rejected with `ERR_STATEMENT_EXISTS` — while generating
    over an existing `DRAFT` recomputes and returns that draft rather than
    creating a duplicate."

    Design: Corner/validations/statement_regenerate_over_certified_rejected
    """
    scenario, _expense, statement = _setup_draft_statement(api, "N380JX")
    certify_statement(statement["id"], certifier_user_id="fc-1")

    res = api.create_statement(
        {"aircraft_id": scenario["aircraft"]["id"], "period": "2026-08"}, AE
    )
    validate_error(res, "ERR_STATEMENT_EXISTS", expected_status=409)

    current = validate_success(api.get_statement(statement["id"], AE), 200)
    assert current["status"] == "CERTIFIED"


def test_segregation_of_duties_same_user_certify_rejected(api):
    """PRD §3.8: "Certification is a `FinanceController` action against a
    `DRAFT` statement, and it carries a segregation-of-duties rule: the acting
    `X-User-ID` must differ from the statement's `prepared_by_user_id`, else
    `ERR_SEGREGATION_OF_DUTIES`."

    Design: Corner/validations/segregation_of_duties_same_user_certify_rejected
    """
    _scenario, _expense, statement = _setup_draft_statement(
        api, "N390JX", preparer_user_id="shared-1"
    )
    assert statement["prepared_by_user_id"] == "shared-1"

    same_user = make_operator_headers("shared-1", "FinanceController")
    res = api.certify_statement(statement["id"], same_user)
    validate_error(res, "ERR_SEGREGATION_OF_DUTIES", expected_status=403)

    current = validate_success(api.get_statement(statement["id"], AE), 200)
    assert current["status"] == "DRAFT"
    assert current.get("certified_by_user_id") is None


def test_stale_statement_certify_rejected(api):
    """PRD §3.8: "Certification also enforces staleness: if any `POSTED`
    expense of the aircraft exists whose `service_date` falls in the period and
    which is not reflected in the statement's last computation, certification
    is rejected with `ERR_STATEMENT_STALE` — the preparer must regenerate the
    draft to pick up the new expense."

    Design: Corner/validations/stale_statement_certify_rejected
    """
    scenario, _expense, statement = _setup_draft_statement(api, "N400JB")
    # Late expense posted after the statement's computation; remains POSTED and
    # unreflected in the DRAFT's totals.
    post_expense(scenario["aircraft"]["id"], category="OTHER",
                 amount_cents=90000, service_date="2026-08-20",
                 paid_date=None, vendor_name="Late Catering")

    res = api.certify_statement(
        statement["id"], make_operator_headers("fc-1", "FinanceController")
    )
    validate_error(res, "ERR_STATEMENT_STALE", expected_status=409)

    current = validate_success(api.get_statement(statement["id"], AE), 200)
    assert current["status"] == "DRAFT"


def _setup_certified_then_late_expense(api):
    """Statement certified (E1 now BILLED); a second expense E2 posted
    afterwards remains POSTED and unreflected."""
    scenario, expense, statement = _setup_draft_statement(api, "N110JX")
    certified = certify_statement(statement["id"], certifier_user_id="fc-1")
    assert certified["status"] == "CERTIFIED"
    late = post_expense(scenario["aircraft"]["id"], category="OTHER",
                        amount_cents=90000, service_date="2026-08-20",
                        paid_date=None, vendor_name="Late Catering")
    return scenario, expense, statement, late


def test_certify_state_check_precedes_staleness_check(api):
    """PRD §3.8: "Certify from a non-`DRAFT` state or deliver from a
    non-`CERTIFIED` state is `ERR_STATEMENT_INVALID_STATE`."
    PRD §2.8: "Only after all four of those gates pass do state-machine
    preconditions, business-safety gates, temporal gates, uniqueness
    constraints, fiscal staleness checks, and finally the OCC stale-version
    check run, in that order."

    The statement is already CERTIFIED (state violation) AND a late POSTED
    expense makes its content stale (fiscal violation); the state error wins.

    Design: Difficulty/priority_pair_validation_conflict/certify_state_check_precedes_staleness_check
    """
    _scenario, _e1, statement, _late = _setup_certified_then_late_expense(api)

    res = api.certify_statement(
        statement["id"], make_operator_headers("fc-2", "FinanceController")
    )
    validate_error(res, "ERR_STATEMENT_INVALID_STATE", expected_status=409)


def test_certify_state_violation_leaves_statement_and_expense_untouched(api):
    """PRD §3.8: "Certify from a non-`DRAFT` state or deliver from a
    non-`CERTIFIED` state is `ERR_STATEMENT_INVALID_STATE`."
    PRD §2.8: "Only after all four of those gates pass do state-machine
    preconditions, business-safety gates, temporal gates, uniqueness
    constraints, fiscal staleness checks, and finally the OCC stale-version
    check run, in that order."

    Design: Difficulty/priority_pair_validation_conflict/certify_state_check_precedes_staleness_check
    """
    _scenario, _e1, statement, late = _setup_certified_then_late_expense(api)

    res = api.certify_statement(
        statement["id"], make_operator_headers("fc-2", "FinanceController")
    )
    validate_error(res, "ERR_STATEMENT_INVALID_STATE", expected_status=409)

    current = validate_success(api.get_statement(statement["id"], AE), 200)
    assert current["status"] == "CERTIFIED"

    late_after = validate_success(api.get_expense(late["id"], FC), 200)
    assert late_after["status"] == "POSTED", (
        "the failed re-certification must not bill the late expense"
    )
    assert late_after.get("statement_id") is None


def test_account_exec_cannot_certify_statement(api):
    """PRD §2.1: "When the acting role is not listed among an endpoint's
    authorized roles, the request is rejected with `ERR_FORBIDDEN_ROLE`
    (HTTP 403)."
    PRD §4: POST /statements/{id}/certify is authorized for FinanceController
    only.

    Design: Corner/rbac/account_exec_cannot_certify_statement
    """
    _scenario, _expense, statement = _setup_draft_statement(api, "N510JX")

    res = api.certify_statement(
        statement["id"], make_operator_headers("ae-9", "AccountExecutive")
    )
    validate_error(res, "ERR_FORBIDDEN_ROLE", expected_status=403)

    current = validate_success(api.get_statement(statement["id"], AE), 200)
    assert current["status"] == "DRAFT"


def test_expense_void_after_billed_rejected(api):
    """PRD §3.8: "Voiding by the `FinanceController` moves a `POSTED` expense
    to `VOID` — anything else is `ERR_EXPENSE_NOT_POSTED` — and likewise
    triggers recomputation of any `DRAFT` statement covering that period, with
    totals dropping the voided line."

    Design: Corner/validations/expense_void_after_billed_rejected
    """
    _scenario, expense, statement = _setup_draft_statement(api, "N420JX")
    certify_statement(statement["id"], certifier_user_id="fc-1")

    res = api.void_expense(expense["id"], FC)
    validate_error(res, "ERR_EXPENSE_NOT_POSTED", expected_status=409)

    current = validate_success(api.get_expense(expense["id"], FC), 200)
    assert current["status"] == "BILLED"
