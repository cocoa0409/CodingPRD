"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PRODUCT_MISMATCH = "ERR_PRODUCT_MISMATCH"
    ERR_WEIGHT_CLASS_REJECTED = "ERR_WEIGHT_CLASS_REJECTED"
    ERR_DEICE_FIELDS_REQUIRED = "ERR_DEICE_FIELDS_REQUIRED"
    ERR_SPOT_TOW_BUFFER_CONFLICT = "ERR_SPOT_TOW_BUFFER_CONFLICT"
    ERR_SPOT_WINDOW_CONFLICT = "ERR_SPOT_WINDOW_CONFLICT"
    ERR_SLOT_OVERLAP = "ERR_SLOT_OVERLAP"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"
    ERR_SPOT_OUT_OF_SERVICE = "ERR_SPOT_OUT_OF_SERVICE"
    ERR_CONTRACT_EXPIRED = "ERR_CONTRACT_EXPIRED"
    ERR_VISIT_NOT_SERVICEABLE = "ERR_VISIT_NOT_SERVICEABLE"
    ERR_MISSING_FIELD = "ERR_MISSING_FIELD"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PRODUCT_MISMATCH: 422,
    ApiErrorId.ERR_WEIGHT_CLASS_REJECTED: 422,
    ApiErrorId.ERR_DEICE_FIELDS_REQUIRED: 422,
    ApiErrorId.ERR_SPOT_TOW_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_SPOT_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_SLOT_OVERLAP: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_OVERPAYMENT: 422,
    ApiErrorId.ERR_SPOT_OUT_OF_SERVICE: 409,
    ApiErrorId.ERR_CONTRACT_EXPIRED: 422,
    ApiErrorId.ERR_VISIT_NOT_SERVICEABLE: 409,
    ApiErrorId.ERR_MISSING_FIELD: 400,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
