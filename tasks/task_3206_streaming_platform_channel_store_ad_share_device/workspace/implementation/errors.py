def raise_err(spec, message):
    raise ApiError(spec[0], spec[1], message)


def unauthenticated(msg="X-User-ID and X-User-Role headers must be present and non-empty"):
    raise_err(ERR_UNAUTHENTICATED, msg)


def forbidden(msg="Role not permitted for this endpoint"):
    raise_err(ERR_FORBIDDEN_ROLE, msg)


def not_found(msg="Resource not found"):
    raise_err(ERR_NOT_FOUND, msg)


def invalid_request(msg="Invalid request"):
    raise_err(ERR_INVALID_REQUEST, msg)


def invalid_state(msg="Invalid state for this operation"):
    raise_err(ERR_INVALID_STATE, msg)
