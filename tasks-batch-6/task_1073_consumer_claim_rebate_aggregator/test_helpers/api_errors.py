"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_MATCH_MISMATCH = "ERR_MATCH_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_PROGRAM_VERSION = "ERR_STALE_PROGRAM_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_PROGRAM_NOT_OPEN = "ERR_PROGRAM_NOT_OPEN"
    ERR_CONSUMER_NOT_VERIFIED = "ERR_CONSUMER_NOT_VERIFIED"
    ERR_CLAIM_WINDOW_CLOSED = "ERR_CLAIM_WINDOW_CLOSED"
    ERR_BENEFIT_PERIOD_OVERLAP = "ERR_BENEFIT_PERIOD_OVERLAP"
    ERR_PROGRAM_WINDOW_CONFLICT = "ERR_PROGRAM_WINDOW_CONFLICT"
    ERR_INSUFFICIENT_DOCUMENTS = "ERR_INSUFFICIENT_DOCUMENTS"
    ERR_NOT_ELIGIBLE = "ERR_NOT_ELIGIBLE"
    ERR_FRAUD_HOLD = "ERR_FRAUD_HOLD"
    ERR_RISK_THRESHOLD_EXCEEDED = "ERR_RISK_THRESHOLD_EXCEEDED"
    ERR_FUND_EXHAUSTED = "ERR_FUND_EXHAUSTED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_MATCH_MISMATCH: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_PROGRAM_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_PROGRAM_NOT_OPEN: 409,
    ApiErrorId.ERR_CONSUMER_NOT_VERIFIED: 409,
    ApiErrorId.ERR_CLAIM_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_BENEFIT_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_PROGRAM_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_INSUFFICIENT_DOCUMENTS: 409,
    ApiErrorId.ERR_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_FRAUD_HOLD: 409,
    ApiErrorId.ERR_RISK_THRESHOLD_EXCEEDED: 409,
    ApiErrorId.ERR_FUND_EXHAUSTED: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status codes.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
