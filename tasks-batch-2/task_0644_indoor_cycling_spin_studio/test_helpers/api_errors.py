    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_SESSION_VERSION = "ERR_STALE_SESSION_VERSION"
    ERR_STALE_PACK_VERSION = "ERR_STALE_PACK_VERSION"
    ERR_MEMBER_SUSPENDED = "ERR_MEMBER_SUSPENDED"
    ERR_SCHEDULE_CONFLICT = "ERR_SCHEDULE_CONFLICT"
    ERR_BIKE_UNAVAILABLE = "ERR_BIKE_UNAVAILABLE"
    ERR_DUPLICATE_RESERVATION = "ERR_DUPLICATE_RESERVATION"
    ERR_NO_CHARGEABLE_PACK = "ERR_NO_CHARGEABLE_PACK"
    ERR_SESSION_FULL = "ERR_SESSION_FULL"
    ERR_WAITLIST_FULL = "ERR_WAITLIST_FULL"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
