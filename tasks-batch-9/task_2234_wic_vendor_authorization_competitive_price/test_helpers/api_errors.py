"""
Error identifiers and their HTTP status codes, transcribed from the PRD error
catalogue (section 5).

Registering the status map with the framework makes ``validate_error`` assert the
HTTP status automatically, so a test that names an error id also pins its status.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


