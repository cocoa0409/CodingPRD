"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks
the HTTP status code for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_REPORTS_NOT_FINALIZED = "ERR_REPORTS_NOT_FINALIZED"
    ERR_RELATIVE_FINDER_NOT_OPTED_IN = "ERR_RELATIVE_FINDER_NOT_OPTED_IN"
    ERR_PURGE_IN_PROGRESS = "ERR_PURGE_IN_PROGRESS"
    ERR_RETEST_NOT_ELIGIBLE = "ERR_RETEST_NOT_ELIGIBLE"
    ERR_SAMPLE_NOT_GENOTYPABLE = "ERR_SAMPLE_NOT_GENOTYPABLE"
    ERR_SUBSCRIPTION_EXISTS = "ERR_SUBSCRIPTION_EXISTS"
    ERR_GRACE_NOT_ELAPSED = "ERR_GRACE_NOT_ELAPSED"
    ERR_INVALID_RANGE = "ERR_INVALID_RANGE"
    ERR_HEALTH_NOT_INCLUDED = "ERR_HEALTH_NOT_INCLUDED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_TOKEN = "ERR_INVALID_TOKEN"
    ERR_UPGRADE_NOT_ALLOWED = "ERR_UPGRADE_NOT_ALLOWED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_REPORTS_NOT_FINALIZED: 409,
    ApiErrorId.ERR_RELATIVE_FINDER_NOT_OPTED_IN: 422,
    ApiErrorId.ERR_PURGE_IN_PROGRESS: 409,
    ApiErrorId.ERR_RETEST_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_SAMPLE_NOT_GENOTYPABLE: 422,
    ApiErrorId.ERR_SUBSCRIPTION_EXISTS: 409,
    ApiErrorId.ERR_GRACE_NOT_ELAPSED: 409,
    ApiErrorId.ERR_INVALID_RANGE: 422,
    ApiErrorId.ERR_HEALTH_NOT_INCLUDED: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_TOKEN: 404,
    ApiErrorId.ERR_UPGRADE_NOT_ALLOWED: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
