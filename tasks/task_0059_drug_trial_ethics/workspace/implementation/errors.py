from __future__ import annotations

"""Custom error class + error-id constants."""


class APIError(Exception):
    def __init__(self, error_id: str, http_status: int, message: str = ""):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error id constants
ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
ERR_AUTH_INVALID = "ERR_AUTH_INVALID"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_MEMBER_RECUSED = "ERR_MEMBER_RECUSED"
ERR_MEMBER_NOT_QUALIFIED = "ERR_MEMBER_NOT_QUALIFIED"
ERR_AGENDA_LEAD_TIME_VIOLATION = "ERR_AGENDA_LEAD_TIME_VIOLATION"
ERR_RECTIFICATION_EXPIRED = "ERR_RECTIFICATION_EXPIRED"
ERR_CHECKLIST_INCOMPLETE = "ERR_CHECKLIST_INCOMPLETE"
ERR_DUPLICATE_VOTE = "ERR_DUPLICATE_VOTE"
ERR_QUORUM_NOT_MET = "ERR_QUORUM_NOT_MET"
ERR_FIELD_VALIDATION = "ERR_FIELD_VALIDATION"
ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


HTTP_BY_ERROR = {
    ERR_AUTH_MISSING: 401,
    ERR_AUTH_INVALID: 401,
    ERR_NOT_FOUND: 404,
    ERR_REFERENCE_NOT_FOUND: 404,
    ERR_FORBIDDEN: 403,
    ERR_INVALID_STATE: 409,
    ERR_MEMBER_RECUSED: 403,
    ERR_MEMBER_NOT_QUALIFIED: 422,
    ERR_AGENDA_LEAD_TIME_VIOLATION: 422,
    ERR_RECTIFICATION_EXPIRED: 409,
    ERR_CHECKLIST_INCOMPLETE: 422,
    ERR_DUPLICATE_VOTE: 409,
    ERR_QUORUM_NOT_MET: 422,
    ERR_FIELD_VALIDATION: 422,
    ERR_VERSION_CONFLICT: 409,
}


def raise_error(error_id: str, message: str | None = None) -> None:
    raise APIError(error_id, HTTP_BY_ERROR.get(error_id, 400), message or error_id)
