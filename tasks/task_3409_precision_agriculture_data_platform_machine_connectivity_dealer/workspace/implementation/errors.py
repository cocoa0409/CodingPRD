class ApiError(Exception):
    """Carries an error_id, an HTTP status, and a human-readable message."""

    def __init__(self, error_id, status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.status = status
        self.message = message or error_id


def invalid_request(message):
    return ApiError(ERR_INVALID_REQUEST, 400, message)


def not_found(message="resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, message)


def access_denied(message="data access denied"):
    return ApiError(ERR_DATA_ACCESS_DENIED, 403, message)


def invalid_state(message="invalid state transition"):
    return ApiError(ERR_INVALID_STATE_TRANSITION, 409, message)
