"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PROPERTY_MISMATCH = "ERR_PROPERTY_MISMATCH"
    ERR_CONTRACT_NOT_ACTIVE = "ERR_CONTRACT_NOT_ACTIVE"
    ERR_NO_EQUIPMENT_AVAILABLE = "ERR_NO_EQUIPMENT_AVAILABLE"
    ERR_EQUIPMENT_NOT_READY = "ERR_EQUIPMENT_NOT_READY"
    ERR_READING_ALREADY_PROCESSED = "ERR_READING_ALREADY_PROCESSED"
    ERR_SNOW_THRESHOLD_NOT_MET = "ERR_SNOW_THRESHOLD_NOT_MET"
    ERR_OPEN_DISPATCH_EXISTS = "ERR_OPEN_DISPATCH_EXISTS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"
    ERR_NO_SKIPPABLE_VISIT = "ERR_NO_SKIPPABLE_VISIT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PROPERTY_MISMATCH: 409,
    ApiErrorId.ERR_CONTRACT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_NO_EQUIPMENT_AVAILABLE: 409,
    ApiErrorId.ERR_EQUIPMENT_NOT_READY: 409,
    ApiErrorId.ERR_READING_ALREADY_PROCESSED: 409,
    ApiErrorId.ERR_SNOW_THRESHOLD_NOT_MET: 409,
    ApiErrorId.ERR_OPEN_DISPATCH_EXISTS: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
    ApiErrorId.ERR_NO_SKIPPABLE_VISIT: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
