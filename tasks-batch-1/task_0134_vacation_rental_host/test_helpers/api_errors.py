"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can cross-check
the HTTP status automatically from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LISTING_NOT_BOOKABLE = "ERR_LISTING_NOT_BOOKABLE"
    ERR_SCREENING_NOT_PASSED = "ERR_SCREENING_NOT_PASSED"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_MIN_NIGHTS = "ERR_MIN_NIGHTS"
    ERR_DATES_UNAVAILABLE = "ERR_DATES_UNAVAILABLE"
    ERR_RATE_PLAN_OVERLAP = "ERR_RATE_PLAN_OVERLAP"
    ERR_INVALID_CLAIM_AMOUNT = "ERR_INVALID_CLAIM_AMOUNT"
    ERR_PAYOUT_NOT_DUE = "ERR_PAYOUT_NOT_DUE"
    ERR_CLAIM_BLOCKS_PAYOUT = "ERR_CLAIM_BLOCKS_PAYOUT"
    ERR_STALE_CALENDAR_VERSION = "ERR_STALE_CALENDAR_VERSION"
    ERR_RELEASE_BOOKING_BLOCK = "ERR_RELEASE_BOOKING_BLOCK"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_DUPLICATE_EXTERNAL_REF = "ERR_DUPLICATE_EXTERNAL_REF"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LISTING_NOT_BOOKABLE: 409,
    ApiErrorId.ERR_SCREENING_NOT_PASSED: 409,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_MIN_NIGHTS: 422,
    ApiErrorId.ERR_DATES_UNAVAILABLE: 409,
    ApiErrorId.ERR_RATE_PLAN_OVERLAP: 409,
    ApiErrorId.ERR_INVALID_CLAIM_AMOUNT: 422,
    ApiErrorId.ERR_PAYOUT_NOT_DUE: 409,
    ApiErrorId.ERR_CLAIM_BLOCKS_PAYOUT: 409,
    ApiErrorId.ERR_STALE_CALENDAR_VERSION: 412,
    ApiErrorId.ERR_RELEASE_BOOKING_BLOCK: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_DUPLICATE_EXTERNAL_REF: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
