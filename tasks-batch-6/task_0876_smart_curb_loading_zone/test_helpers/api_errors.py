"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_ZONE_NOT_ACTIVE = "ERR_ZONE_NOT_ACTIVE"
    ERR_PERMIT_NOT_ACTIVE = "ERR_PERMIT_NOT_ACTIVE"
    ERR_ZONE_CAPACITY_CONFLICT = "ERR_ZONE_CAPACITY_CONFLICT"
    ERR_SCHEDULE_WINDOW_CONFLICT = "ERR_SCHEDULE_WINDOW_CONFLICT"
    ERR_ZONE_HAS_ACTIVE_RESERVATIONS = "ERR_ZONE_HAS_ACTIVE_RESERVATIONS"
    ERR_NO_OCCUPANCY_SESSION = "ERR_NO_OCCUPANCY_SESSION"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"
    ERR_CANCEL_AFTER_START = "ERR_CANCEL_AFTER_START"
    ERR_MISSING_FIELD = "ERR_MISSING_FIELD"
    ERR_INVALID_PAGINATION = "ERR_INVALID_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_ZONE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PERMIT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ZONE_CAPACITY_CONFLICT: 409,
    ApiErrorId.ERR_SCHEDULE_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_ZONE_HAS_ACTIVE_RESERVATIONS: 409,
    ApiErrorId.ERR_NO_OCCUPANCY_SESSION: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_ENUM: 422,
    ApiErrorId.ERR_CANCEL_AFTER_START: 409,
    ApiErrorId.ERR_MISSING_FIELD: 422,
    ApiErrorId.ERR_INVALID_PAGINATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
