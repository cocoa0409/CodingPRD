    SOURCE_MIX_EXCEEDED = "ERR_SOURCE_MIX_EXCEEDED"
    EVALUATOR_CAPACITY_EXCEEDED = "ERR_EVALUATOR_CAPACITY_EXCEEDED"
    RECOGNITION_THRESHOLD_NOT_MET = "ERR_RECOGNITION_THRESHOLD_NOT_MET"

    def __str__(self) -> str:  # pragma: no cover - convenience only
        return self.value


