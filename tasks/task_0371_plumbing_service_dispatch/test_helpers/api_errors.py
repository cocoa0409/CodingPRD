"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping, register it with the framework so validate_error()
can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_JOB_VERSION = "ERR_STALE_JOB_VERSION"
    ERR_SKILL_INSUFFICIENT = "ERR_SKILL_INSUFFICIENT"
    ERR_LICENSE_REQUIRED = "ERR_LICENSE_REQUIRED"
    ERR_TECH_DOUBLE_BOOKED = "ERR_TECH_DOUBLE_BOOKED"
    ERR_INSPECTOR_CAPACITY_FULL = "ERR_INSPECTOR_CAPACITY_FULL"
    ERR_EMPTY_ESTIMATE = "ERR_EMPTY_ESTIMATE"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_WARRANTY_EXPIRED = "ERR_WARRANTY_EXPIRED"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_JOB_VERSION: 412,
    ApiErrorId.ERR_SKILL_INSUFFICIENT: 409,
    ApiErrorId.ERR_LICENSE_REQUIRED: 409,
    ApiErrorId.ERR_TECH_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_INSPECTOR_CAPACITY_FULL: 409,
    ApiErrorId.ERR_EMPTY_ESTIMATE: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_WARRANTY_EXPIRED: 409,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
