def api_error(error_id, http_status, msg):
    return ApiError(error_id, http_status, msg)


def unauthenticated(msg="Missing or empty X-User-ID / X-User-Role headers"):
    return ApiError(ERR_UNAUTHENTICATED, 401, msg)


def forbidden_role(msg="Role not authorized for this endpoint"):
    return ApiError(ERR_FORBIDDEN_ROLE, 403, msg)


def not_resource_owner(msg="Acting grower does not own this resource"):
    return ApiError(ERR_NOT_RESOURCE_OWNER, 403, msg)


def segregation_of_duties(msg="Segregation of duties violated"):
    return ApiError(ERR_SEGREGATION_OF_DUTIES, 403, msg)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def malformed(msg="Malformed field"):
    return ApiError(ERR_MALFORMED_FIELD, 400, msg)


def conflict(error_id, msg):
    """409 domain errors."""
    return ApiError(error_id, 409, msg)
