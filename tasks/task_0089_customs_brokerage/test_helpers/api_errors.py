"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / Authz (PRD §5)
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # Concurrency / state
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_FILING_ALREADY_EXISTS = "ERR_FILING_ALREADY_EXISTS"
    ERR_SETTLEMENT_ALREADY_ADVANCED = "ERR_SETTLEMENT_ALREADY_ADVANCED"
    ERR_SETTLEMENT_HAS_ADVANCE = "ERR_SETTLEMENT_HAS_ADVANCE"

    # Business — declaration / documents
    ERR_DOC_INCOMPLETE = "ERR_DOC_INCOMPLETE"
    ERR_DOC_INCONSISTENT = "ERR_DOC_INCONSISTENT"
    ERR_DOC_AUTHENTICITY_FLAGGED = "ERR_DOC_AUTHENTICITY_FLAGGED"
    ERR_DOC_MISSING_LICENSE = "ERR_DOC_MISSING_LICENSE"
    ERR_DOC_MISSING_DG = "ERR_DOC_MISSING_DG"
    ERR_DECLARED_VALUE_FLAGGED = "ERR_DECLARED_VALUE_FLAGGED"
    ERR_MANIFEST_MISMATCH = "ERR_MANIFEST_MISMATCH"
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_AGREEMENT_VERSION_DRIFT = "ERR_AGREEMENT_VERSION_DRIFT"
    ERR_AGREEMENT_HAS_OPEN_DECLARATIONS = "ERR_AGREEMENT_HAS_OPEN_DECLARATIONS"
    ERR_AMENDMENT_CAP_REACHED = "ERR_AMENDMENT_CAP_REACHED"
    ERR_INSPECTION_REJECTION_NOT_AMENDABLE = "ERR_INSPECTION_REJECTION_NOT_AMENDABLE"
    ERR_QUERY_DEADLINE_PASSED = "ERR_QUERY_DEADLINE_PASSED"
    ERR_SERVICE_OUT_OF_SCOPE = "ERR_SERVICE_OUT_OF_SCOPE"
    ERR_FEE_SCHEDULE_INVALID = "ERR_FEE_SCHEDULE_INVALID"

    # Business — settlement
    ERR_SETTLEMENT_ZERO_AMOUNT = "ERR_SETTLEMENT_ZERO_AMOUNT"
    ERR_BANK_AMOUNT_MISMATCH = "ERR_BANK_AMOUNT_MISMATCH"

    # Input
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"


# Per PRD §5 Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_FILING_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_SETTLEMENT_ALREADY_ADVANCED: 409,
    ApiErrorId.ERR_SETTLEMENT_HAS_ADVANCE: 409,
    ApiErrorId.ERR_DOC_INCOMPLETE: 409,
    ApiErrorId.ERR_DOC_INCONSISTENT: 409,
    ApiErrorId.ERR_DOC_AUTHENTICITY_FLAGGED: 409,
    ApiErrorId.ERR_DOC_MISSING_LICENSE: 409,
    ApiErrorId.ERR_DOC_MISSING_DG: 409,
    ApiErrorId.ERR_DECLARED_VALUE_FLAGGED: 409,
    ApiErrorId.ERR_MANIFEST_MISMATCH: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_AGREEMENT_VERSION_DRIFT: 409,
    ApiErrorId.ERR_AGREEMENT_HAS_OPEN_DECLARATIONS: 409,
    ApiErrorId.ERR_AMENDMENT_CAP_REACHED: 409,
    ApiErrorId.ERR_INSPECTION_REJECTION_NOT_AMENDABLE: 409,
    ApiErrorId.ERR_QUERY_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_SERVICE_OUT_OF_SCOPE: 409,
    ApiErrorId.ERR_FEE_SCHEDULE_INVALID: 422,
    ApiErrorId.ERR_SETTLEMENT_ZERO_AMOUNT: 409,
    ApiErrorId.ERR_BANK_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_INPUT: 422,
}

# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
