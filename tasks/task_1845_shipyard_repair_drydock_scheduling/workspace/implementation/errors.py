ERR_OWNER_APPROVAL_NOT_REQUIRED = "ERR_OWNER_APPROVAL_NOT_REQUIRED"

# --- Identity-scoped authorization ---
ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
ERR_OWNERSHIP_MISMATCH = "ERR_OWNERSHIP_MISMATCH"

# --- Business safety ---
ERR_HOT_WORK_PERMIT_REQUIRED = "ERR_HOT_WORK_PERMIT_REQUIRED"

# --- Business constraints ---
ERR_VESSEL_EXCEEDS_DOCK_LIMITS = "ERR_VESSEL_EXCEEDS_DOCK_LIMITS"
