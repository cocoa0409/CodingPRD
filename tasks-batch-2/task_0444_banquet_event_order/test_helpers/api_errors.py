"""Error IDs and HTTP status mapping (Banquet Event Order PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ROOM_DOUBLE_BOOKED = "ERR_ROOM_DOUBLE_BOOKED"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_PRICING_MODE_FIELD_MISMATCH = "ERR_PRICING_MODE_FIELD_MISMATCH"
    ERR_PICKUP_EXCEEDS_RESERVED = "ERR_PICKUP_EXCEEDS_RESERVED"
    ERR_BLOCK_INSUFFICIENT_ROOMS = "ERR_BLOCK_INSUFFICIENT_ROOMS"
    ERR_DEPOSIT_UNSETTLED = "ERR_DEPOSIT_UNSETTLED"
    ERR_DEPOSIT_LOCKED = "ERR_DEPOSIT_LOCKED"
    ERR_GUARANTEE_REQUIRED = "ERR_GUARANTEE_REQUIRED"
    ERR_NO_BOOKINGS = "ERR_NO_BOOKINGS"
    ERR_BOOKING_NOT_ALL_DEFINITE = "ERR_BOOKING_NOT_ALL_DEFINITE"
    ERR_EVENT_TERMINAL = "ERR_EVENT_TERMINAL"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ROOM_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_PRICING_MODE_FIELD_MISMATCH: 422,
    ApiErrorId.ERR_PICKUP_EXCEEDS_RESERVED: 422,
    ApiErrorId.ERR_BLOCK_INSUFFICIENT_ROOMS: 409,
    ApiErrorId.ERR_DEPOSIT_UNSETTLED: 409,
    ApiErrorId.ERR_DEPOSIT_LOCKED: 409,
    ApiErrorId.ERR_GUARANTEE_REQUIRED: 422,
    ApiErrorId.ERR_NO_BOOKINGS: 409,
    ApiErrorId.ERR_BOOKING_NOT_ALL_DEFINITE: 409,
    ApiErrorId.ERR_EVENT_TERMINAL: 409,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
