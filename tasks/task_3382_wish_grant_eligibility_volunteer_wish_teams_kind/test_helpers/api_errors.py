    ERR_PLAN_ALREADY_APPROVED = "ERR_PLAN_ALREADY_APPROVED"
    ERR_TREATMENT_WINDOW_INVALID = "ERR_TREATMENT_WINDOW_INVALID"
    # Fiscal rules
    ERR_INSUFFICIENT_DONATION_QTY = "ERR_INSUFFICIENT_DONATION_QTY"
    ERR_CHAPTER_BUDGET_FROZEN = "ERR_CHAPTER_BUDGET_FROZEN"
    ERR_CHAPTER_BUDGET_EXCEEDED = "ERR_CHAPTER_BUDGET_EXCEEDED"
    ERR_COST_ESCALATION_REQUIRED = "ERR_COST_ESCALATION_REQUIRED"


