"""Error IDs and HTTP status mapping (PRD Section 5).

After defining the mapping, registers it with the framework so validate_error()
auto-checks the HTTP status code for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_LOAN_VERSION = "ERR_STALE_LOAN_VERSION"
    ERR_LOAN_NOT_IN_DEFAULT = "ERR_LOAN_NOT_IN_DEFAULT"
    ERR_LIEN_LOAN_NOT_OUTSTANDING = "ERR_LIEN_LOAN_NOT_OUTSTANDING"
    ERR_DEVICE_LOAN_NOT_DELINQUENT = "ERR_DEVICE_LOAN_NOT_DELINQUENT"
    ERR_APR_CAP_EXCEEDED = "ERR_APR_CAP_EXCEEDED"
    ERR_TERM_OUT_OF_BOUNDS = "ERR_TERM_OUT_OF_BOUNDS"
    ERR_RENEWAL_LIMIT_REACHED = "ERR_RENEWAL_LIMIT_REACHED"
    ERR_REDEMPTION_GRACE_ACTIVE = "ERR_REDEMPTION_GRACE_ACTIVE"
    ERR_COMMAND_WINDOW_OVERLAP = "ERR_COMMAND_WINDOW_OVERLAP"
    ERR_ASSIGNMENT_WINDOW_OVERLAP = "ERR_ASSIGNMENT_WINDOW_OVERLAP"
    ERR_LTV_EXCEEDED = "ERR_LTV_EXCEEDED"
    ERR_INSUFFICIENT_PAYMENT = "ERR_INSUFFICIENT_PAYMENT"
    ERR_ACTIVE_REPO_EXISTS = "ERR_ACTIVE_REPO_EXISTS"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"
    ERR_BORROWER_BARRED = "ERR_BORROWER_BARRED"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_LOAN_VERSION: 412,
    ApiErrorId.ERR_LOAN_NOT_IN_DEFAULT: 409,
    ApiErrorId.ERR_LIEN_LOAN_NOT_OUTSTANDING: 409,
    ApiErrorId.ERR_DEVICE_LOAN_NOT_DELINQUENT: 409,
    ApiErrorId.ERR_APR_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_TERM_OUT_OF_BOUNDS: 422,
    ApiErrorId.ERR_RENEWAL_LIMIT_REACHED: 409,
    ApiErrorId.ERR_REDEMPTION_GRACE_ACTIVE: 409,
    ApiErrorId.ERR_COMMAND_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_ASSIGNMENT_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_LTV_EXCEEDED: 422,
    ApiErrorId.ERR_INSUFFICIENT_PAYMENT: 422,
    ApiErrorId.ERR_ACTIVE_REPO_EXISTS: 409,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
    ApiErrorId.ERR_BORROWER_BARRED: 403,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
