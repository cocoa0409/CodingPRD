"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping, register it with the framework so that
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_INSPECTION_PREREQUISITE_NOT_MET = "ERR_INSPECTION_PREREQUISITE_NOT_MET"
    ERR_BUSINESS_NOT_IN_GOOD_STANDING = "ERR_BUSINESS_NOT_IN_GOOD_STANDING"
    ERR_LICENSE_NOT_TRANSFERABLE = "ERR_LICENSE_NOT_TRANSFERABLE"
    ERR_ZONING_DENIED = "ERR_ZONING_DENIED"
    ERR_RENEWAL_WINDOW_CLOSED = "ERR_RENEWAL_WINDOW_CLOSED"
    ERR_REVOCATION_THRESHOLD_NOT_REACHED = "ERR_REVOCATION_THRESHOLD_NOT_REACHED"
    ERR_OUTSTANDING_FEES = "ERR_OUTSTANDING_FEES"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DUPLICATE_ACTIVITY_CODE = "ERR_DUPLICATE_ACTIVITY_CODE"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INSPECTION_ALREADY_RECORDED = "ERR_INSPECTION_ALREADY_RECORDED"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_INSPECTION_PREREQUISITE_NOT_MET: 409,
    ApiErrorId.ERR_BUSINESS_NOT_IN_GOOD_STANDING: 409,
    ApiErrorId.ERR_LICENSE_NOT_TRANSFERABLE: 409,
    ApiErrorId.ERR_ZONING_DENIED: 409,
    ApiErrorId.ERR_RENEWAL_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_REVOCATION_THRESHOLD_NOT_REACHED: 409,
    ApiErrorId.ERR_OUTSTANDING_FEES: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE_ACTIVITY_CODE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INSPECTION_ALREADY_RECORDED: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
