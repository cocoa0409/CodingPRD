DEFAULT_MESSAGE = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing or invalid.",
    "ERR_UNAUTHORIZED": "The caller's role may not perform this operation.",
    "ERR_NOT_RESOURCE_OWNER": "The caller does not own the addressed resource.",
    "ERR_SEGREGATION_OF_DUTIES": "The same user may not perform both sides of this control.",
    "ERR_INVALID_REQUEST": "The request payload or query is malformed.",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super(ApiError, self).__init__(message or error_id)
        self.error_id = error_id
        self.message = message or DEFAULT_MESSAGE.get(error_id, error_id)
        self.http_status = http_status or ERROR_STATUS.get(error_id, 400)
