"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can auto-check
HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_LANE_TIME_CONFLICT = "ERR_LANE_TIME_CONFLICT"
    ERR_ANALYZER_CAPACITY = "ERR_ANALYZER_CAPACITY"
    ERR_CLASS_PROFILE_MISSING = "ERR_CLASS_PROFILE_MISSING"
    ERR_OBD_NOT_APPLICABLE = "ERR_OBD_NOT_APPLICABLE"
    ERR_INSPECTION_INCOMPLETE = "ERR_INSPECTION_INCOMPLETE"
    ERR_RECORD_NOT_PASSED = "ERR_RECORD_NOT_PASSED"
    ERR_CERTIFICATE_EXISTS = "ERR_CERTIFICATE_EXISTS"
    ERR_REPAIR_LIMIT_NOT_MET = "ERR_REPAIR_LIMIT_NOT_MET"
    ERR_REINSPECTION_LIMIT = "ERR_REINSPECTION_LIMIT"
    ERR_LINE_NOT_ELIGIBLE = "ERR_LINE_NOT_ELIGIBLE"
    ERR_EMPTY_BATCH = "ERR_EMPTY_BATCH"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_LANE_TIME_CONFLICT: 409,
    ApiErrorId.ERR_ANALYZER_CAPACITY: 409,
    ApiErrorId.ERR_CLASS_PROFILE_MISSING: 409,
    ApiErrorId.ERR_OBD_NOT_APPLICABLE: 409,
    ApiErrorId.ERR_INSPECTION_INCOMPLETE: 409,
    ApiErrorId.ERR_RECORD_NOT_PASSED: 409,
    ApiErrorId.ERR_CERTIFICATE_EXISTS: 409,
    ApiErrorId.ERR_REPAIR_LIMIT_NOT_MET: 409,
    ApiErrorId.ERR_REINSPECTION_LIMIT: 409,
    ApiErrorId.ERR_LINE_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_EMPTY_BATCH: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
