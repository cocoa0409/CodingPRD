"""Error IDs and HTTP status mapping (PRD section 5).

After defining the mapping, register it with the framework so validate_error()
auto-checks the HTTP status code that accompanies each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_HEARING_ROOM_CONFLICT = "ERR_HEARING_ROOM_CONFLICT"
    ERR_STALE_REGION_VERSION = "ERR_STALE_REGION_VERSION"
    ERR_STALE_LICENSE_VERSION = "ERR_STALE_LICENSE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_APPLICANT_DISQUALIFIED = "ERR_APPLICANT_DISQUALIFIED"
    ERR_ZONING_NOT_CLEARED = "ERR_ZONING_NOT_CLEARED"
    ERR_BACKGROUND_NOT_PASSED = "ERR_BACKGROUND_NOT_PASSED"
    ERR_PROTEST_WINDOW_CLOSED = "ERR_PROTEST_WINDOW_CLOSED"
    ERR_PROTEST_WINDOW_OPEN = "ERR_PROTEST_WINDOW_OPEN"
    ERR_PROTEST_UNRESOLVED = "ERR_PROTEST_UNRESOLVED"
    ERR_SERVER_CAPACITY_EXCEEDED = "ERR_SERVER_CAPACITY_EXCEEDED"
    ERR_TRAINING_INCOMPLETE = "ERR_TRAINING_INCOMPLETE"
    ERR_RENEWAL_WINDOW_NOT_OPEN = "ERR_RENEWAL_WINDOW_NOT_OPEN"
    ERR_OUTSTANDING_FINE = "ERR_OUTSTANDING_FINE"
    ERR_DEMERIT_THRESHOLD = "ERR_DEMERIT_THRESHOLD"
    ERR_FEE_UNPAID = "ERR_FEE_UNPAID"
    ERR_QUOTA_EXHAUSTED = "ERR_QUOTA_EXHAUSTED"
    ERR_TRANSFER_TYPE_INVALID = "ERR_TRANSFER_TYPE_INVALID"
    ERR_PREMISE_TERM_CONFLICT = "ERR_PREMISE_TERM_CONFLICT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_HEARING_ROOM_CONFLICT: 409,
    ApiErrorId.ERR_STALE_REGION_VERSION: 412,
    ApiErrorId.ERR_STALE_LICENSE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_APPLICANT_DISQUALIFIED: 422,
    ApiErrorId.ERR_ZONING_NOT_CLEARED: 422,
    ApiErrorId.ERR_BACKGROUND_NOT_PASSED: 422,
    ApiErrorId.ERR_PROTEST_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_PROTEST_WINDOW_OPEN: 422,
    ApiErrorId.ERR_PROTEST_UNRESOLVED: 422,
    ApiErrorId.ERR_SERVER_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_TRAINING_INCOMPLETE: 422,
    ApiErrorId.ERR_RENEWAL_WINDOW_NOT_OPEN: 422,
    ApiErrorId.ERR_OUTSTANDING_FINE: 422,
    ApiErrorId.ERR_DEMERIT_THRESHOLD: 422,
    ApiErrorId.ERR_FEE_UNPAID: 422,
    ApiErrorId.ERR_QUOTA_EXHAUSTED: 422,
    ApiErrorId.ERR_TRANSFER_TYPE_INVALID: 422,
    ApiErrorId.ERR_PREMISE_TERM_CONFLICT: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
