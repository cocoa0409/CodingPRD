"""Error identifiers and their HTTP status codes (PRD Section 5).

Registered with the framework so ``validate_error`` cross-checks the HTTP
status automatically for every asserted error.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_IDEMPOTENCY_CONFLICT = "ERR_IDEMPOTENCY_CONFLICT"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"
    ERR_MEMBER_POSTURE = "ERR_MEMBER_POSTURE"
    ERR_ABUSE_LOCK = "ERR_ABUSE_LOCK"
    ERR_TEMPORAL_VIOLATION = "ERR_TEMPORAL_VIOLATION"
    ERR_WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_REFERENTIAL_BLOCK = "ERR_REFERENTIAL_BLOCK"
    ERR_LIMIT_EXCEEDED = "ERR_LIMIT_EXCEEDED"
    ERR_DISPUTE_AMOUNT_EXCEEDS = "ERR_DISPUTE_AMOUNT_EXCEEDS"
    ERR_INSUFFICIENT_FUNDS = "ERR_INSUFFICIENT_FUNDS"
    ERR_NOT_QUALIFYING = "ERR_NOT_QUALIFYING"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_IDEMPOTENCY_CONFLICT: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ALREADY_TERMINAL: 409,
    ApiErrorId.ERR_MEMBER_POSTURE: 409,
    ApiErrorId.ERR_ABUSE_LOCK: 422,
    ApiErrorId.ERR_TEMPORAL_VIOLATION: 422,
    ApiErrorId.ERR_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_REFERENTIAL_BLOCK: 422,
    ApiErrorId.ERR_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_DISPUTE_AMOUNT_EXCEEDS: 422,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS: 422,
    ApiErrorId.ERR_NOT_QUALIFYING: 422,
}

set_error_http_status_map(HTTP_STATUS_CODES)
