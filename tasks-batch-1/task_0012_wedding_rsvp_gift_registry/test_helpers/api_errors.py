"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_WEDDING_ARCHIVED = "ERR_WEDDING_ARCHIVED"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_KIDS_MEAL_PAIRING = "ERR_KIDS_MEAL_PAIRING"
    ERR_KIDS_SEATING_VIOLATION = "ERR_KIDS_SEATING_VIOLATION"
    ERR_PLUS_ONE_NOT_ALLOWED = "ERR_PLUS_ONE_NOT_ALLOWED"
    ERR_CROSS_WEDDING_REFERENCE = "ERR_CROSS_WEDDING_REFERENCE"
    ERR_MEAL_FULL = "ERR_MEAL_FULL"
    ERR_TABLE_FULL = "ERR_TABLE_FULL"
    ERR_ALREADY_SEATED = "ERR_ALREADY_SEATED"
    ERR_RSVP_DEADLINE_PASSED = "ERR_RSVP_DEADLINE_PASSED"
    ERR_DUPLICATE_EXTERNAL_PURCHASE = "ERR_DUPLICATE_EXTERNAL_PURCHASE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_WEDDING_ARCHIVED: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_KIDS_MEAL_PAIRING: 422,
    ApiErrorId.ERR_KIDS_SEATING_VIOLATION: 422,
    ApiErrorId.ERR_PLUS_ONE_NOT_ALLOWED: 422,
    ApiErrorId.ERR_CROSS_WEDDING_REFERENCE: 422,
    ApiErrorId.ERR_MEAL_FULL: 422,
    ApiErrorId.ERR_TABLE_FULL: 422,
    ApiErrorId.ERR_ALREADY_SEATED: 422,
    ApiErrorId.ERR_RSVP_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_DUPLICATE_EXTERNAL_PURCHASE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}


# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
