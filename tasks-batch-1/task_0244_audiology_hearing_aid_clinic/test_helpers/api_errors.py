"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DUPLICATE_MODEL_CODE = "ERR_DUPLICATE_MODEL_CODE"
    ERR_EVALUATION_PATIENT_MISMATCH = "ERR_EVALUATION_PATIENT_MISMATCH"
    ERR_NOT_A_CANDIDATE = "ERR_NOT_A_CANDIDATE"
    ERR_DEVICE_NOT_INDICATED = "ERR_DEVICE_NOT_INDICATED"
    ERR_TRIAL_EXPIRED = "ERR_TRIAL_EXPIRED"
    ERR_BENEFIT_EXPIRED = "ERR_BENEFIT_EXPIRED"
    ERR_BENEFIT_INACTIVE = "ERR_BENEFIT_INACTIVE"
    ERR_RETURN_WINDOW_CLOSED = "ERR_RETURN_WINDOW_CLOSED"
    ERR_TRIAL_NOT_CLOSED = "ERR_TRIAL_NOT_CLOSED"
    ERR_OUTSIDE_WARRANTY_WINDOW = "ERR_OUTSIDE_WARRANTY_WINDOW"
    ERR_CYCLE_NOT_DUE = "ERR_CYCLE_NOT_DUE"
    ERR_FIRMWARE_MISMATCH = "ERR_FIRMWARE_MISMATCH"
    ERR_RECALL_NOT_REMEDIATED = "ERR_RECALL_NOT_REMEDIATED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DUPLICATE_MODEL_CODE: 409,
    ApiErrorId.ERR_EVALUATION_PATIENT_MISMATCH: 422,
    ApiErrorId.ERR_NOT_A_CANDIDATE: 422,
    ApiErrorId.ERR_DEVICE_NOT_INDICATED: 422,
    ApiErrorId.ERR_TRIAL_EXPIRED: 422,
    ApiErrorId.ERR_BENEFIT_EXPIRED: 422,
    ApiErrorId.ERR_BENEFIT_INACTIVE: 422,
    ApiErrorId.ERR_RETURN_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_TRIAL_NOT_CLOSED: 422,
    ApiErrorId.ERR_OUTSIDE_WARRANTY_WINDOW: 422,
    ApiErrorId.ERR_CYCLE_NOT_DUE: 422,
    ApiErrorId.ERR_FIRMWARE_MISMATCH: 422,
    ApiErrorId.ERR_RECALL_NOT_REMEDIATED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
