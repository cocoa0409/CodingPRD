def register_error_status_map():
    """Hand the catalogue to the framework's error validator."""
    set_error_http_status_map(ERROR_HTTP_STATUS)


def ladder_rank(error_id):
    """Position of an identifier in the rule ladder; unknown ids sort last."""
    try:
        return RULE_LADDER.index(error_id)
    except ValueError:
        return len(RULE_LADDER)


register_error_status_map()
