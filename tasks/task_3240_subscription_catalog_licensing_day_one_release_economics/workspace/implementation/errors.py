"""Error catalog for the Subscription Catalog Licensing API (PRD section 5)."""


class ApiError(Exception):
    """Carries the error id, HTTP status and human-readable message."""

    def __init__(self, error_id, status, message):
        super().__init__(message)
        self.error_id = error_id
        self.status = status
        self.message = message


