"""Error catalogue: the API's error identifiers and their HTTP statuses.

The identifier-to-status mapping below mirrors the PRD §5 catalogue exactly.
Importing this module registers the mapping with the framework validators, so
`validate_error(response, ApiErrorId.ERR_X)` also checks the HTTP status code.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth & shape
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED_ROLE = "ERR_UNAUTHORIZED_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    # Timed entry passes & screening
