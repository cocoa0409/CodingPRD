"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_HELPER_NOT_APPROVED = "ERR_HELPER_NOT_APPROVED"
    ERR_CREW_FULL = "ERR_CREW_FULL"
    ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
    ERR_HELPER_UNAVAILABLE = "ERR_HELPER_UNAVAILABLE"
    ERR_TRUCK_UNAVAILABLE = "ERR_TRUCK_UNAVAILABLE"
    ERR_CLAIM_EXCEEDS_COVERAGE = "ERR_CLAIM_EXCEEDS_COVERAGE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_QUOTE_NOT_ACTIVE = "ERR_QUOTE_NOT_ACTIVE"
    ERR_NO_CREW_CHECKED_IN = "ERR_NO_CREW_CHECKED_IN"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_HELPER_NOT_APPROVED: 409,
    ApiErrorId.ERR_CREW_FULL: 409,
    ApiErrorId.ERR_QUOTE_EXPIRED: 409,
    ApiErrorId.ERR_HELPER_UNAVAILABLE: 409,
    ApiErrorId.ERR_TRUCK_UNAVAILABLE: 409,
    ApiErrorId.ERR_CLAIM_EXCEEDS_COVERAGE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_QUOTE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_NO_CREW_CHECKED_IN: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
