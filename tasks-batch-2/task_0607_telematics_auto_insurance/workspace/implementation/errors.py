"""Error catalogue (PRD §5 / SCAFFOLD §1.6).

Every error_id maps to its HTTP status verbatim from the PRD error table.
"""


class ApiError(Exception):
    def __init__(self, error_id: str, message: str = None):
        self.error_id = error_id
        self.http_status = ERROR_HTTP_STATUS[error_id]
        self.message = message or ERROR_MESSAGES.get(error_id, error_id)
        super().__init__(self.message)


