"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, register it with the framework so validate_error()
can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NO_CHARGE_TO_REFUND = "ERR_NO_CHARGE_TO_REFUND"
    ERR_DOCUMENTS_INCOMPLETE = "ERR_DOCUMENTS_INCOMPLETE"
    ERR_TRIP_WINDOW_OVERLAP = "ERR_TRIP_WINDOW_OVERLAP"
    ERR_SLA_EXPIRED = "ERR_SLA_EXPIRED"
    ERR_TRIP_AT_CAPACITY = "ERR_TRIP_AT_CAPACITY"
    ERR_REWORK_LIMIT_REACHED = "ERR_REWORK_LIMIT_REACHED"
    ERR_TRIP_NOT_RETURNED = "ERR_TRIP_NOT_RETURNED"
    ERR_CREDIT_LIMIT_EXCEEDED = "ERR_CREDIT_LIMIT_EXCEEDED"
    ERR_INVALID_TRANSACTION_FIELDS = "ERR_INVALID_TRANSACTION_FIELDS"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_NO_CHARGE_TO_REFUND: 409,
    ApiErrorId.ERR_DOCUMENTS_INCOMPLETE: 409,
    ApiErrorId.ERR_TRIP_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_SLA_EXPIRED: 409,
    ApiErrorId.ERR_TRIP_AT_CAPACITY: 409,
    ApiErrorId.ERR_REWORK_LIMIT_REACHED: 409,
    ApiErrorId.ERR_TRIP_NOT_RETURNED: 409,
    ApiErrorId.ERR_CREDIT_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_INVALID_TRANSACTION_FIELDS: 422,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
