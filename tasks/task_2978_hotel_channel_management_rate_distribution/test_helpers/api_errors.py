"""Error catalogue for the Hotel Channel Distribution API.

Every declared error identifier together with the HTTP status the contract's
error table pairs it with. Registering the mapping with the shared validators
lets ``validate_error`` cross-check the status automatically, so a test only has
to name the identifier it expects.
"""

from enum import Enum
from typing import Dict

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    """Declared error identifiers, grouped by the validation priority that emits them."""

    # Priorities 1-2: credentials.
    UNAUTHENTICATED = "ERR_UNAUTHENTICATED"

    # Priorities 3, 5 and 6: role, ownership and override authority.
    ROLE_NOT_PERMITTED = "ERR_ROLE_NOT_PERMITTED"
    CHANNEL_OWNERSHIP_VIOLATION = "ERR_CHANNEL_OWNERSHIP_VIOLATION"
    OVERRIDE_NOT_PERMITTED = "ERR_OVERRIDE_NOT_PERMITTED"

    # Priority 13: segregation of duties.
    SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"

    # Priority 7: request shape.
    INVALID_REQUEST = "ERR_INVALID_REQUEST"

    # Priorities 4 and 8: path and body identifier resolution.
    PROPERTY_NOT_FOUND = "ERR_PROPERTY_NOT_FOUND"
    ROOM_TYPE_NOT_FOUND = "ERR_ROOM_TYPE_NOT_FOUND"
    INVENTORY_DAY_NOT_FOUND = "ERR_INVENTORY_DAY_NOT_FOUND"
    CHANNEL_NOT_FOUND = "ERR_CHANNEL_NOT_FOUND"
    CONNECTION_NOT_FOUND = "ERR_CONNECTION_NOT_FOUND"
    RATE_PLAN_NOT_FOUND = "ERR_RATE_PLAN_NOT_FOUND"
    CHANNEL_MAPPING_NOT_FOUND = "ERR_CHANNEL_MAPPING_NOT_FOUND"
    ALLOCATION_NOT_FOUND = "ERR_ALLOCATION_NOT_FOUND"
    RESTRICTION_NOT_FOUND = "ERR_RESTRICTION_NOT_FOUND"
    PROMOTION_NOT_FOUND = "ERR_PROMOTION_NOT_FOUND"
    BATCH_NOT_FOUND = "ERR_BATCH_NOT_FOUND"
    JOB_NOT_FOUND = "ERR_JOB_NOT_FOUND"
    RESERVATION_NOT_FOUND = "ERR_RESERVATION_NOT_FOUND"

    # Priority 10: optimistic concurrency echoes.
    STALE_ROOM_TYPE_VERSION = "ERR_STALE_ROOM_TYPE_VERSION"
    STALE_RATE_PLAN_VERSION = "ERR_STALE_RATE_PLAN_VERSION"

    # Priority 11: state legality.
    RATE_PLAN_STATE_INVALID = "ERR_RATE_PLAN_STATE_INVALID"
    MAPPING_STATE_INVALID = "ERR_MAPPING_STATE_INVALID"
    CONNECTION_STATE_INVALID = "ERR_CONNECTION_STATE_INVALID"
    PROMOTION_STATE_INVALID = "ERR_PROMOTION_STATE_INVALID"
    ALLOCATION_STATE_INVALID = "ERR_ALLOCATION_STATE_INVALID"
    RESTRICTION_STATE_INVALID = "ERR_RESTRICTION_STATE_INVALID"
    BATCH_NOT_DISPATCHABLE = "ERR_BATCH_NOT_DISPATCHABLE"
    JOB_NOT_RETRYABLE = "ERR_JOB_NOT_RETRYABLE"
    RESERVATION_NOT_CANCELLABLE = "ERR_RESERVATION_NOT_CANCELLABLE"

    # Priorities 12, 14 and 15: connectivity, parity and prerequisites.
    CONNECTION_NOT_SELLABLE = "ERR_CONNECTION_NOT_SELLABLE"
    CONTENT_PARITY_BLOCKED = "ERR_CONTENT_PARITY_BLOCKED"
    CHANNEL_MAPPING_MISSING = "ERR_CHANNEL_MAPPING_MISSING"
    CHANNEL_CONNECTION_MISSING = "ERR_CHANNEL_CONNECTION_MISSING"
    INVENTORY_DAY_NOT_OPEN = "ERR_INVENTORY_DAY_NOT_OPEN"

    # Priority 9: single-property scope.
    PROPERTY_SCOPE_MISMATCH = "ERR_PROPERTY_SCOPE_MISMATCH"

    # Priority 16: booking horizon.
    STAY_OUTSIDE_HORIZON = "ERR_STAY_OUTSIDE_HORIZON"
    WINDOW_OUTSIDE_HORIZON = "ERR_WINDOW_OUTSIDE_HORIZON"

    # Priority 21: freeze windows.
    CONNECTION_FROZEN = "ERR_CONNECTION_FROZEN"

    # Priority 17: uniqueness, depth and overlap.
    DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    DERIVATION_DEPTH_EXCEEDED = "ERR_DERIVATION_DEPTH_EXCEEDED"
    RESTRICTION_WINDOW_OVERLAP = "ERR_RESTRICTION_WINDOW_OVERLAP"
    FREEZE_WINDOW_OVERLAP = "ERR_FREEZE_WINDOW_OVERLAP"

    # Priority 18: rate eligibility.
    OPAQUE_RATE_NOT_ALLOWED = "ERR_OPAQUE_RATE_NOT_ALLOWED"
    MEMBER_RATE_NOT_ELIGIBLE = "ERR_MEMBER_RATE_NOT_ELIGIBLE"
    NEGOTIATED_ACCOUNT_MISMATCH = "ERR_NEGOTIATED_ACCOUNT_MISMATCH"
    GEO_MARKET_NOT_SERVED = "ERR_GEO_MARKET_NOT_SERVED"

    # Priority 19: sell restrictions.
    STOP_SELL_ACTIVE = "ERR_STOP_SELL_ACTIVE"
    CLOSED_TO_ARRIVAL = "ERR_CLOSED_TO_ARRIVAL"
    MIN_STAY_NOT_MET = "ERR_MIN_STAY_NOT_MET"

    # Priority 20: capacity.
    OVERBOOKING_CEILING_EXCEEDED = "ERR_OVERBOOKING_CEILING_EXCEEDED"
    OVERBOOK_OVERRIDE_REQUIRED = "ERR_OVERBOOK_OVERRIDE_REQUIRED"
    ALLOCATION_EXCEEDS_CEILING = "ERR_ALLOCATION_EXCEEDS_CEILING"

    # Priorities 22 and 23: analytics.
    ANALYTICS_WINDOW_INVALID = "ERR_ANALYTICS_WINDOW_INVALID"
    NO_ELIGIBLE_CHANNEL = "ERR_NO_ELIGIBLE_CHANNEL"


