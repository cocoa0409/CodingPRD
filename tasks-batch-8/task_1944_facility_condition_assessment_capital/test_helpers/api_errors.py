"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CODE_SEVERITY_TOO_LOW = "ERR_CODE_SEVERITY_TOO_LOW"
    ERR_YEAR_OUT_OF_RANGE = "ERR_YEAR_OUT_OF_RANGE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_REFERENTIAL_CONFLICT = "ERR_REFERENTIAL_CONFLICT"
    ERR_PRECONDITION_UNMET = "ERR_PRECONDITION_UNMET"
    ERR_INVALID_BUDGET = "ERR_INVALID_BUDGET"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_CODE_SEVERITY_TOO_LOW: 422,
    ApiErrorId.ERR_YEAR_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_REFERENTIAL_CONFLICT: 409,
    ApiErrorId.ERR_PRECONDITION_UNMET: 409,
    ApiErrorId.ERR_INVALID_BUDGET: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
