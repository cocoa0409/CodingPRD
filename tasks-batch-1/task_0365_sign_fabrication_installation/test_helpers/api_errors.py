"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() can auto-check
HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PROOF_ALREADY_APPROVED = "ERR_PROOF_ALREADY_APPROVED"
    ERR_REFERENCE_NOT_ELIGIBLE = "ERR_REFERENCE_NOT_ELIGIBLE"
    ERR_ESTIMATE_EXPIRED = "ERR_ESTIMATE_EXPIRED"
    ERR_ESTIMATE_ALREADY_ACCEPTED = "ERR_ESTIMATE_ALREADY_ACCEPTED"
    ERR_CLEARANCE_INSUFFICIENT = "ERR_CLEARANCE_INSUFFICIENT"
    ERR_GROUND_BEARING_FAILED = "ERR_GROUND_BEARING_FAILED"
    ERR_PERMIT_NOT_REQUIRED = "ERR_PERMIT_NOT_REQUIRED"
    ERR_SURVEY_NOT_PASSED = "ERR_SURVEY_NOT_PASSED"
    ERR_PERMIT_NOT_APPROVED = "ERR_PERMIT_NOT_APPROVED"
    ERR_EQUIPMENT_REQUIRED = "ERR_EQUIPMENT_REQUIRED"
    ERR_EQUIPMENT_DOUBLE_BOOKED = "ERR_EQUIPMENT_DOUBLE_BOOKED"
    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_CREW_UNAVAILABLE = "ERR_CREW_UNAVAILABLE"
    ERR_CREW_NOT_CERTIFIED = "ERR_CREW_NOT_CERTIFIED"
    ERR_CHANGE_WINDOW_CLOSED = "ERR_CHANGE_WINDOW_CLOSED"
    ERR_OUT_OF_WARRANTY = "ERR_OUT_OF_WARRANTY"
    ERR_OPEN_CLAIM = "ERR_OPEN_CLAIM"
    ERR_SOURCE_NOT_CLOSED = "ERR_SOURCE_NOT_CLOSED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PROOF_ALREADY_APPROVED: 409,
    ApiErrorId.ERR_REFERENCE_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_ESTIMATE_EXPIRED: 409,
    ApiErrorId.ERR_ESTIMATE_ALREADY_ACCEPTED: 409,
    ApiErrorId.ERR_CLEARANCE_INSUFFICIENT: 409,
    ApiErrorId.ERR_GROUND_BEARING_FAILED: 409,
    ApiErrorId.ERR_PERMIT_NOT_REQUIRED: 409,
    ApiErrorId.ERR_SURVEY_NOT_PASSED: 409,
    ApiErrorId.ERR_PERMIT_NOT_APPROVED: 409,
    ApiErrorId.ERR_EQUIPMENT_REQUIRED: 409,
    ApiErrorId.ERR_EQUIPMENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CREW_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CREW_UNAVAILABLE: 409,
    ApiErrorId.ERR_CREW_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_CHANGE_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_OUT_OF_WARRANTY: 409,
    ApiErrorId.ERR_OPEN_CLAIM: 409,
    ApiErrorId.ERR_SOURCE_NOT_CLOSED: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
