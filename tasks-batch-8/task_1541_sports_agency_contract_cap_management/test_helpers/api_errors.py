"""Error IDs and HTTP status mapping (PRD section 5 Error Code Catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_AGENT_NOT_CERTIFIED = "ERR_AGENT_NOT_CERTIFIED"
    ERR_OWNERSHIP_VIOLATION = "ERR_OWNERSHIP_VIOLATION"
    ERR_WINDOW_CLOSED = "ERR_WINDOW_CLOSED"
    ERR_CAP_WOULD_EXCEED = "ERR_CAP_WOULD_EXCEED"
    ERR_CAP_HARD_LIMIT = "ERR_CAP_HARD_LIMIT"
    ERR_RESOURCE_LOCKED = "ERR_RESOURCE_LOCKED"
    ERR_DUPLICATE_ACTIVE_CONTRACT = "ERR_DUPLICATE_ACTIVE_CONTRACT"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_CLIENT_HAS_ACTIVE_OBLIGATIONS = "ERR_CLIENT_HAS_ACTIVE_OBLIGATIONS"
    ERR_OPEN_GRIEVANCE = "ERR_OPEN_GRIEVANCE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_AGENT_NOT_CERTIFIED: 422,
    ApiErrorId.ERR_OWNERSHIP_VIOLATION: 422,
    ApiErrorId.ERR_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_CAP_WOULD_EXCEED: 422,
    ApiErrorId.ERR_CAP_HARD_LIMIT: 422,
    ApiErrorId.ERR_RESOURCE_LOCKED: 409,
    ApiErrorId.ERR_DUPLICATE_ACTIVE_CONTRACT: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_CLIENT_HAS_ACTIVE_OBLIGATIONS: 409,
    ApiErrorId.ERR_OPEN_GRIEVANCE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
