"""Error IDs and HTTP status mapping (PRD §5).

After defining the map this module registers it with the framework so that
validate_error() can cross-check HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_EMPTY_CREDENTIALS = "ERR_EMPTY_CREDENTIALS"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PRIOR_AUTH_REQUIRED = "ERR_PRIOR_AUTH_REQUIRED"
    ERR_INSUFFICIENT_AUTH_UNITS = "ERR_INSUFFICIENT_AUTH_UNITS"
    ERR_SCREENING_NOT_CLEARED = "ERR_SCREENING_NOT_CLEARED"
    ERR_CENTER_QUALITY_HOLD = "ERR_CENTER_QUALITY_HOLD"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CRITICAL_RESULT_REQUIRED = "ERR_CRITICAL_RESULT_REQUIRED"
    ERR_RADIOLOGIST_NOT_CREDENTIALED = "ERR_RADIOLOGIST_NOT_CREDENTIALED"
    ERR_TECH_NOT_CREDENTIALED = "ERR_TECH_NOT_CREDENTIALED"
    ERR_ROOM_MODALITY_MISMATCH = "ERR_ROOM_MODALITY_MISMATCH"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_ROOM_DOUBLE_BOOKED = "ERR_ROOM_DOUBLE_BOOKED"
    ERR_TECH_DOUBLE_BOOKED = "ERR_TECH_DOUBLE_BOOKED"
    ERR_NO_ACCEPTED_SERIES = "ERR_NO_ACCEPTED_SERIES"
    ERR_SERIES_STILL_CAPTURING = "ERR_SERIES_STILL_CAPTURING"
    ERR_REJECT_REASON_REQUIRED = "ERR_REJECT_REASON_REQUIRED"
    ERR_ALREADY_CLAIMED = "ERR_ALREADY_CLAIMED"
    ERR_NOT_ASSIGNED_TECH = "ERR_NOT_ASSIGNED_TECH"
    ERR_NOT_ASSIGNED_RADIOLOGIST = "ERR_NOT_ASSIGNED_RADIOLOGIST"
    ERR_TOO_EARLY_TO_CHECK_IN = "ERR_TOO_EARLY_TO_CHECK_IN"
    ERR_REPORT_NOT_FINAL = "ERR_REPORT_NOT_FINAL"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_EMPTY_CREDENTIALS: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PRIOR_AUTH_REQUIRED: 402,
    ApiErrorId.ERR_INSUFFICIENT_AUTH_UNITS: 422,
    ApiErrorId.ERR_SCREENING_NOT_CLEARED: 409,
    ApiErrorId.ERR_CENTER_QUALITY_HOLD: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_CRITICAL_RESULT_REQUIRED: 409,
    ApiErrorId.ERR_RADIOLOGIST_NOT_CREDENTIALED: 422,
    ApiErrorId.ERR_TECH_NOT_CREDENTIALED: 422,
    ApiErrorId.ERR_ROOM_MODALITY_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_ROOM_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_TECH_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_NO_ACCEPTED_SERIES: 409,
    ApiErrorId.ERR_SERIES_STILL_CAPTURING: 409,
    ApiErrorId.ERR_REJECT_REASON_REQUIRED: 422,
    ApiErrorId.ERR_ALREADY_CLAIMED: 409,
    ApiErrorId.ERR_NOT_ASSIGNED_TECH: 403,
    ApiErrorId.ERR_NOT_ASSIGNED_RADIOLOGIST: 403,
    ApiErrorId.ERR_TOO_EARLY_TO_CHECK_IN: 409,
    ApiErrorId.ERR_REPORT_NOT_FINAL: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
