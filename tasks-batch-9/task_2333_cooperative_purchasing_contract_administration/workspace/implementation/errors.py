"""Error catalogue (PRD section 5) and the exception type carrying it."""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super(ApiError, self).__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status or CATALOG.get(error_id, 400)
        self.message = message if message else DEFAULT_MESSAGES.get(
            error_id, error_id.replace("ERR_", "").replace("_", " ").lower()
        )


def fail(error_id, message=None):
    raise ApiError(error_id, message)


