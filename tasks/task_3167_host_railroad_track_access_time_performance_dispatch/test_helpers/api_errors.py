"""Error identifiers and their HTTP status mapping (PRD error catalogue).

Registered with the framework at import time so ``validate_error`` checks the
HTTP status automatically once the error id matches.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_RUN_PASSAGES_OPEN = "ERR_RUN_PASSAGES_OPEN"
    ERR_MAINTENANCE_CONFLICT = "ERR_MAINTENANCE_CONFLICT"
    ERR_SEGMENT_OCCUPANCY_CONFLICT = "ERR_SEGMENT_OCCUPANCY_CONFLICT"
    ERR_SCHEDULE_INFEASIBLE = "ERR_SCHEDULE_INFEASIBLE"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_EQUIPMENT_ALLOWANCE_EXCEEDED = "ERR_EQUIPMENT_ALLOWANCE_EXCEEDED"
    ERR_REFERENTIAL_INTEGRITY = "ERR_REFERENTIAL_INTEGRITY"
    ERR_SETTLEMENT_PERIOD_INVALID = "ERR_SETTLEMENT_PERIOD_INVALID"
    ERR_FUNDING_PERIOD_OVERLAP = "ERR_FUNDING_PERIOD_OVERLAP"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_RUN_PASSAGES_OPEN: 409,
    ApiErrorId.ERR_MAINTENANCE_CONFLICT: 409,
    ApiErrorId.ERR_SEGMENT_OCCUPANCY_CONFLICT: 409,
    ApiErrorId.ERR_SCHEDULE_INFEASIBLE: 422,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_EQUIPMENT_ALLOWANCE_EXCEEDED: 409,
    ApiErrorId.ERR_REFERENTIAL_INTEGRITY: 422,
    ApiErrorId.ERR_SETTLEMENT_PERIOD_INVALID: 422,
    ApiErrorId.ERR_FUNDING_PERIOD_OVERLAP: 409,
}

set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
