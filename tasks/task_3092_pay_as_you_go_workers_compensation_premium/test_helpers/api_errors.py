"""Error identifiers and their HTTP status codes (PRD §5).

Registers the mapping with the framework so ``validate_error()`` auto-checks the
HTTP status of any error response.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_MONOPOLISTIC_STATE_EXCLUDED = "ERR_MONOPOLISTIC_STATE_EXCLUDED"
    ERR_CLASS_CODE_NOT_ON_POLICY = "ERR_CLASS_CODE_NOT_ON_POLICY"
    ERR_PAYROLL_PERIOD_OVERLAP = "ERR_PAYROLL_PERIOD_OVERLAP"
    ERR_RATING_TABLE_OVERLAP = "ERR_RATING_TABLE_OVERLAP"
    ERR_RETRO_WINDOW_INVALID = "ERR_RETRO_WINDOW_INVALID"
    ERR_BILLING_SUSPENDED = "ERR_BILLING_SUSPENDED"
    ERR_IDEMPOTENCY_CONFLICT = "ERR_IDEMPOTENCY_CONFLICT"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_TAX_FILING_MISSING = "ERR_TAX_FILING_MISSING"
    ERR_DUPLICATE_INVOICE = "ERR_DUPLICATE_INVOICE"
    ERR_POLICY_NOT_ACTIVE = "ERR_POLICY_NOT_ACTIVE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_MONOPOLISTIC_STATE_EXCLUDED: 422,
    ApiErrorId.ERR_CLASS_CODE_NOT_ON_POLICY: 422,
    ApiErrorId.ERR_PAYROLL_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_RATING_TABLE_OVERLAP: 409,
    ApiErrorId.ERR_RETRO_WINDOW_INVALID: 422,
    ApiErrorId.ERR_BILLING_SUSPENDED: 409,
    ApiErrorId.ERR_IDEMPOTENCY_CONFLICT: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_TAX_FILING_MISSING: 422,
    ApiErrorId.ERR_DUPLICATE_INVOICE: 409,
    ApiErrorId.ERR_POLICY_NOT_ACTIVE: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
