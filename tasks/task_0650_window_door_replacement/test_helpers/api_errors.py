"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_PROJECT_OWNER = "ERR_NOT_PROJECT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_QUOTE_VERSION = "ERR_STALE_QUOTE_VERSION"
    ERR_CONSULTATION_NOT_MEASURED = "ERR_CONSULTATION_NOT_MEASURED"
    ERR_NO_OPENINGS = "ERR_NO_OPENINGS"
    ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
    ERR_PROJECT_ALREADY_CONTRACTED = "ERR_PROJECT_ALREADY_CONTRACTED"
    ERR_PERMIT_NOT_APPROVED = "ERR_PERMIT_NOT_APPROVED"
    ERR_GOODS_NOT_READY = "ERR_GOODS_NOT_READY"
    ERR_CREW_JURISDICTION_MISMATCH = "ERR_CREW_JURISDICTION_MISMATCH"
    ERR_CREW_WINDOW_CONFLICT = "ERR_CREW_WINDOW_CONFLICT"
    ERR_CREW_CAPACITY_EXCEEDED = "ERR_CREW_CAPACITY_EXCEEDED"
    ERR_FINANCING_OVER_QUOTE = "ERR_FINANCING_OVER_QUOTE"
    ERR_REFERRER_NOT_COMPLETED = "ERR_REFERRER_NOT_COMPLETED"
    ERR_PROJECT_NOT_COMPLETED = "ERR_PROJECT_NOT_COMPLETED"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_PROJECT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_QUOTE_VERSION: 412,
    ApiErrorId.ERR_CONSULTATION_NOT_MEASURED: 409,
    ApiErrorId.ERR_NO_OPENINGS: 422,
    ApiErrorId.ERR_QUOTE_EXPIRED: 409,
    ApiErrorId.ERR_PROJECT_ALREADY_CONTRACTED: 409,
    ApiErrorId.ERR_PERMIT_NOT_APPROVED: 409,
    ApiErrorId.ERR_GOODS_NOT_READY: 409,
    ApiErrorId.ERR_CREW_JURISDICTION_MISMATCH: 422,
    ApiErrorId.ERR_CREW_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_CREW_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_FINANCING_OVER_QUOTE: 422,
    ApiErrorId.ERR_REFERRER_NOT_COMPLETED: 409,
    ApiErrorId.ERR_PROJECT_NOT_COMPLETED: 409,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
