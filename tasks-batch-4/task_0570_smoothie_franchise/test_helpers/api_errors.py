"""Error IDs and their HTTP status codes (PRD §5).

The mapping is registered with the framework so validate_error() can
auto-check the HTTP status for a given error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STORE_NOT_OPEN = "ERR_STORE_NOT_OPEN"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ALLERGEN_CONFLICT = "ERR_ALLERGEN_CONFLICT"
    ERR_NO_ACTIVE_SUBSCRIPTION = "ERR_NO_ACTIVE_SUBSCRIPTION"
    ERR_INVALID_WINDOW = "ERR_INVALID_WINDOW"
    ERR_VEHICLE_UNAVAILABLE = "ERR_VEHICLE_UNAVAILABLE"
    ERR_VEHICLE_DOUBLE_BOOKED = "ERR_VEHICLE_DOUBLE_BOOKED"
    ERR_CATERING_CAPACITY_EXCEEDED = "ERR_CATERING_CAPACITY_EXCEEDED"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_SUBSCRIPTION_EXISTS = "ERR_SUBSCRIPTION_EXISTS"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_RECONCILIATION_EXISTS = "ERR_RECONCILIATION_EXISTS"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STORE_NOT_OPEN: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ALLERGEN_CONFLICT: 422,
    ApiErrorId.ERR_NO_ACTIVE_SUBSCRIPTION: 409,
    ApiErrorId.ERR_INVALID_WINDOW: 422,
    ApiErrorId.ERR_VEHICLE_UNAVAILABLE: 409,
    ApiErrorId.ERR_VEHICLE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CATERING_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_SUBSCRIPTION_EXISTS: 409,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 422,
    ApiErrorId.ERR_RECONCILIATION_EXISTS: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
