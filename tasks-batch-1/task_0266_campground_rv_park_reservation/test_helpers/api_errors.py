"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_SITE_VERSION = "ERR_STALE_SITE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_RATE_PLAN_TYPE_MISMATCH = "ERR_RATE_PLAN_TYPE_MISMATCH"
    ERR_MAX_STAY_EXCEEDED = "ERR_MAX_STAY_EXCEEDED"
    ERR_SITE_UNAVAILABLE = "ERR_SITE_UNAVAILABLE"
    ERR_MAINTENANCE_CONFLICT = "ERR_MAINTENANCE_CONFLICT"
    ERR_DATE_OVERLAP = "ERR_DATE_OVERLAP"
    ERR_SEASON_OVERLAP = "ERR_SEASON_OVERLAP"
    ERR_PAYMENT_AMOUNT_INVALID = "ERR_PAYMENT_AMOUNT_INVALID"
    ERR_PAYMENT_ALREADY_SETTLED = "ERR_PAYMENT_ALREADY_SETTLED"
    ERR_ADDON_LOCKED = "ERR_ADDON_LOCKED"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"
    ERR_CLOCK_INVALID = "ERR_CLOCK_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_SITE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_RATE_PLAN_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_MAX_STAY_EXCEEDED: 422,
    ApiErrorId.ERR_SITE_UNAVAILABLE: 409,
    ApiErrorId.ERR_MAINTENANCE_CONFLICT: 409,
    ApiErrorId.ERR_DATE_OVERLAP: 409,
    ApiErrorId.ERR_SEASON_OVERLAP: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_INVALID: 422,
    ApiErrorId.ERR_PAYMENT_ALREADY_SETTLED: 409,
    ApiErrorId.ERR_ADDON_LOCKED: 409,
    ApiErrorId.ERR_VALIDATION_FAILED: 422,
    ApiErrorId.ERR_CLOCK_INVALID: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
