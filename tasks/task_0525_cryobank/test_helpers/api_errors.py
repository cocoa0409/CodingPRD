"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_RETEST_NOT_NEGATIVE = "ERR_RETEST_NOT_NEGATIVE"
    ERR_QUARANTINE_NOT_ELAPSED = "ERR_QUARANTINE_NOT_ELAPSED"
    ERR_FDA_INELIGIBLE = "ERR_FDA_INELIGIBLE"
    ERR_GENETIC_SCREENING_INCOMPLETE = "ERR_GENETIC_SCREENING_INCOMPLETE"
    ERR_CONSENT_MISSING = "ERR_CONSENT_MISSING"
    ERR_FAMILY_LIMIT_REACHED = "ERR_FAMILY_LIMIT_REACHED"
    ERR_INVENTORY_NOT_LISTED = "ERR_INVENTORY_NOT_LISTED"
    ERR_INSUFFICIENT_VIALS = "ERR_INSUFFICIENT_VIALS"
    ERR_STALE_INVENTORY_VERSION = "ERR_STALE_INVENTORY_VERSION"
    ERR_REGISTRY_NO_SHIPMENT = "ERR_REGISTRY_NO_SHIPMENT"
    ERR_CONSENT_NOT_ACKNOWLEDGED = "ERR_CONSENT_NOT_ACKNOWLEDGED"
    ERR_ACTIVE_RESERVATION_EXISTS = "ERR_ACTIVE_RESERVATION_EXISTS"
    ERR_GRACE_NOT_ELAPSED = "ERR_GRACE_NOT_ELAPSED"
    ERR_ROOM_WINDOW_CONFLICT = "ERR_ROOM_WINDOW_CONFLICT"
    ERR_DEWAR_WINDOW_CONFLICT = "ERR_DEWAR_WINDOW_CONFLICT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_RETEST_NOT_NEGATIVE: 422,
    ApiErrorId.ERR_QUARANTINE_NOT_ELAPSED: 422,
    ApiErrorId.ERR_FDA_INELIGIBLE: 422,
    ApiErrorId.ERR_GENETIC_SCREENING_INCOMPLETE: 422,
    ApiErrorId.ERR_CONSENT_MISSING: 422,
    ApiErrorId.ERR_FAMILY_LIMIT_REACHED: 422,
    ApiErrorId.ERR_INVENTORY_NOT_LISTED: 422,
    ApiErrorId.ERR_INSUFFICIENT_VIALS: 422,
    ApiErrorId.ERR_STALE_INVENTORY_VERSION: 412,
    ApiErrorId.ERR_REGISTRY_NO_SHIPMENT: 422,
    ApiErrorId.ERR_CONSENT_NOT_ACKNOWLEDGED: 422,
    ApiErrorId.ERR_ACTIVE_RESERVATION_EXISTS: 409,
    ApiErrorId.ERR_GRACE_NOT_ELAPSED: 422,
    ApiErrorId.ERR_ROOM_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_DEWAR_WINDOW_CONFLICT: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
