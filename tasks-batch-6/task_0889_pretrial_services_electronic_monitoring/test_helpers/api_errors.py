"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DEFENDANT_NOT_ACTIVE = "ERR_DEFENDANT_NOT_ACTIVE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CONDITION_NOT_ORDERED = "ERR_CONDITION_NOT_ORDERED"
    ERR_ASSESSMENT_NOT_APPROVED = "ERR_ASSESSMENT_NOT_APPROVED"
    ERR_CURFEW_WINDOW_OVERLAP = "ERR_CURFEW_WINDOW_OVERLAP"
    ERR_SLOT_CAPACITY_EXCEEDED = "ERR_SLOT_CAPACITY_EXCEEDED"
    ERR_PRECONDITION_TIME_NOT_REACHED = "ERR_PRECONDITION_TIME_NOT_REACHED"
    ERR_NO_DEVICE_AVAILABLE = "ERR_NO_DEVICE_AVAILABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_ENUM = "ERR_INVALID_ENUM"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DEFENDANT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_CONDITION_NOT_ORDERED: 409,
    ApiErrorId.ERR_ASSESSMENT_NOT_APPROVED: 409,
    ApiErrorId.ERR_CURFEW_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_SLOT_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_PRECONDITION_TIME_NOT_REACHED: 409,
    ApiErrorId.ERR_NO_DEVICE_AVAILABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_ENUM: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
