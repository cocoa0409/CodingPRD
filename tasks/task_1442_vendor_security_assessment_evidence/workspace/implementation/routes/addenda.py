"""ContractAddendum lifecycle (PRD §3.7): REQUIRED -> DRAFTED -> SIGNED, or
REQUIRED -> WAIVED. Addenda are generated by evidence-review completion, not
authored directly.
"""
from flask import Blueprint, request

import db
import errors
import helpers
import util
from errors import ApiError
from middleware import body, paginate, require_roles, scope_vendor_or_403
from response import ok, ok_list
from serializers import serialize

bp = Blueprint("addenda", __name__, url_prefix="/vsa/vendors/<vid>/addenda")


def _resolve(vid, aid):
    vendor = helpers.get_vendor(vid)
    scope_vendor_or_403(vid)
    addendum = helpers.get_vendor_child(db.addenda, vendor, aid,
                                        "ContractAddendum")
    return vendor, addendum


@bp.get("")
@require_roles("RiskAnalyst", "SecurityApprover", "VendorContact")
def list_addenda(vid):
    helpers.get_vendor(vid)
    scope_vendor_or_403(vid)
    items = [a for a in db.addenda.values() if a["vendor_id"] == vid]
    status = request.args.get("status")
    if status is not None:
        items = [a for a in items if a["status"] == status]
    page, limit, offset, total = paginate(items)
    return ok_list([serialize("addendum", a) for a in page], limit, offset, total)


@bp.post("/<aid>/draft")
@require_roles("RiskAnalyst")
def draft_addendum(vid, aid):
    vendor, addendum = _resolve(vid, aid)
    if addendum["status"] != "REQUIRED":
        raise ApiError(errors.ERR_INVALID_STATE, 409,
                       "Only a REQUIRED addendum can be drafted")
    addendum["status"] = "DRAFTED"
    helpers.touch("addenda", addendum)
    return ok(serialize("addendum", addendum))


@bp.post("/<aid>/sign")
@require_roles("VendorContact")
def sign_addendum(vid, aid):
    vendor, addendum = _resolve(vid, aid)
    if addendum["status"] != "DRAFTED":
        raise ApiError(errors.ERR_INVALID_STATE, 409,
                       "Only a DRAFTED addendum can be signed")
    data = body()
    signed_at = data.get("signed_at")
    if not util.is_dt(signed_at):
        raise ApiError(errors.ERR_INVALID_REQUEST, 422,
                       "signed_at is required and must be an ISO 8601 datetime")
    if util.parse_dt(signed_at) > util.now():
        raise ApiError(errors.ERR_INVALID_REQUEST, 422,
                       "signed_at cannot lie in the future")
    addendum["signed_at"] = util.iso(util.parse_dt(signed_at))
    addendum["status"] = "SIGNED"
    helpers.touch("addenda", addendum)
    return ok(serialize("addendum", addendum))


@bp.post("/<aid>/waive")
@require_roles("SecurityApprover")
def waive_addendum(vid, aid):
    vendor, addendum = _resolve(vid, aid)
    if addendum["status"] != "REQUIRED":
        raise ApiError(errors.ERR_INVALID_STATE, 409,
                       "Only a REQUIRED addendum can be waived")
    data = body()
    waived_reason = data.get("waived_reason")
    if not isinstance(waived_reason, str) or not waived_reason:
        raise ApiError(errors.ERR_INVALID_REQUEST, 422,
                       "waived_reason must be non-empty")
    addendum["waived_reason"] = waived_reason
    addendum["status"] = "WAIVED"
    helpers.touch("addenda", addendum)
    return ok(serialize("addendum", addendum))
