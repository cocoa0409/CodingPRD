"""Error classes and error ID constants.

Error IDs and HTTP statuses are taken verbatim from SCAFFOLD.yaml §1.6 and
PRD §5 error catalogue.
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalog: error_id -> (http_status, default message)
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
ERR_CLAIM_NOT_COVERED = "ERR_CLAIM_NOT_COVERED"
ERR_REFERRAL_NOT_ELIGIBLE = "ERR_REFERRAL_NOT_ELIGIBLE"
ERR_BACKUP_REQUIRES_SUMP = "ERR_BACKUP_REQUIRES_SUMP"
ERR_FINANCING_UNRESOLVED = "ERR_FINANCING_UNRESOLVED"
ERR_FINANCE_LIMIT_EXCEEDED = "ERR_FINANCE_LIMIT_EXCEEDED"
ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
ERR_CREW_CAPACITY_EXCEEDED = "ERR_CREW_CAPACITY_EXCEEDED"
ERR_TRANSFER_LIMIT_REACHED = "ERR_TRANSFER_LIMIT_REACHED"
ERR_VISIT_CLAIM_MISMATCH = "ERR_VISIT_CLAIM_MISMATCH"
ERR_VISIT_TOO_CLOSE = "ERR_VISIT_TOO_CLOSE"
ERR_OPEN_CLAIMS_BLOCK_CLOSE = "ERR_OPEN_CLAIMS_BLOCK_CLOSE"
ERR_VALIDATION = "ERR_VALIDATION"
ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"

HTTP_STATUS = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN_ROLE: 403,
    ERR_NOT_FOUND: 404,
    ERR_FK_NOT_FOUND: 422,
    ERR_INVALID_REQUEST: 400,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 412,
    ERR_QUOTE_EXPIRED: 409,
    ERR_CLAIM_NOT_COVERED: 422,
    ERR_REFERRAL_NOT_ELIGIBLE: 422,
    ERR_BACKUP_REQUIRES_SUMP: 422,
    ERR_FINANCING_UNRESOLVED: 409,
    ERR_FINANCE_LIMIT_EXCEEDED: 422,
    ERR_CREW_DOUBLE_BOOKED: 409,
    ERR_CREW_CAPACITY_EXCEEDED: 409,
    ERR_TRANSFER_LIMIT_REACHED: 422,
    ERR_VISIT_CLAIM_MISMATCH: 422,
    ERR_VISIT_TOO_CLOSE: 409,
    ERR_OPEN_CLAIMS_BLOCK_CLOSE: 409,
    ERR_VALIDATION: 422,
    ERR_PAGINATION_INVALID: 400,
}


def err(error_id, message=None):
    return ApiError(error_id, HTTP_STATUS[error_id], message)
