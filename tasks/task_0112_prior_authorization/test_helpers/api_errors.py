"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth / RBAC — PRD §2.1
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Existence — PRD §2.7
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_PRIOR_REQUEST_NOT_FOUND = "ERR_PRIOR_REQUEST_NOT_FOUND"

    # State / concurrency — PRD §2.6 + §3.12
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"

    # Business safety — PRD §3.2
    ERR_CATALOG_RETIRED = "ERR_CATALOG_RETIRED"
    ERR_PATIENT_INACTIVE = "ERR_PATIENT_INACTIVE"
    ERR_PROVIDER_SUSPENDED = "ERR_PROVIDER_SUSPENDED"

    # Business constraint — PRD §3.2 / §3.3 / §3.4 / §3.9
    ERR_EXPEDITED_JUSTIFICATION_REQUIRED = (
        "ERR_EXPEDITED_JUSTIFICATION_REQUIRED"
    )
    ERR_EVIDENCE_INSUFFICIENT = "ERR_EVIDENCE_INSUFFICIENT"
    ERR_EVIDENCE_REUSE_MISMATCH = "ERR_EVIDENCE_REUSE_MISMATCH"
    ERR_PRIOR_REQUEST_NOT_EXPIRED = "ERR_PRIOR_REQUEST_NOT_EXPIRED"
    ERR_RESUBMISSION_ALREADY_EXISTS = "ERR_RESUBMISSION_ALREADY_EXISTS"
    ERR_INVALID_APPROVED_UNITS = "ERR_INVALID_APPROVED_UNITS"
    ERR_DENIAL_REASON_REQUIRED = "ERR_DENIAL_REASON_REQUIRED"

    # Appeal — PRD §3.11
    ERR_APPEAL_TIER_ROLE_MISMATCH = "ERR_APPEAL_TIER_ROLE_MISMATCH"
    ERR_APPEAL_TIER_OUT_OF_ORDER = "ERR_APPEAL_TIER_OUT_OF_ORDER"
    ERR_APPEAL_ALREADY_FILED = "ERR_APPEAL_ALREADY_FILED"
    ERR_APPEAL_DEADLINE_EXPIRED = "ERR_APPEAL_DEADLINE_EXPIRED"

    # Peer-to-peer — PRD §3.5
    ERR_PEER_REVIEW_ALREADY_SCHEDULED = (
        "ERR_PEER_REVIEW_ALREADY_SCHEDULED"
    )
    ERR_PEER_REVIEW_TIME_CONFLICT = "ERR_PEER_REVIEW_TIME_CONFLICT"
    ERR_INVALID_P2P_OUTCOME = "ERR_INVALID_P2P_OUTCOME"

    # Clinical evidence — PRD §3.3
    ERR_EVIDENCE_SIZE_INVALID = "ERR_EVIDENCE_SIZE_INVALID"
    ERR_EVIDENCE_DUPLICATE_URI = "ERR_EVIDENCE_DUPLICATE_URI"


# PRD §5 Error Code Catalogue.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_PRIOR_REQUEST_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_CATALOG_RETIRED: 409,
    ApiErrorId.ERR_PATIENT_INACTIVE: 409,
    ApiErrorId.ERR_PROVIDER_SUSPENDED: 409,
    ApiErrorId.ERR_RESUBMISSION_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_APPEAL_ALREADY_FILED: 409,
    ApiErrorId.ERR_PEER_REVIEW_ALREADY_SCHEDULED: 409,
    ApiErrorId.ERR_PEER_REVIEW_TIME_CONFLICT: 409,
    ApiErrorId.ERR_EVIDENCE_DUPLICATE_URI: 409,
    ApiErrorId.ERR_EXPEDITED_JUSTIFICATION_REQUIRED: 422,
    ApiErrorId.ERR_EVIDENCE_INSUFFICIENT: 422,
    ApiErrorId.ERR_EVIDENCE_REUSE_MISMATCH: 422,
    ApiErrorId.ERR_PRIOR_REQUEST_NOT_EXPIRED: 422,
    ApiErrorId.ERR_INVALID_APPROVED_UNITS: 422,
    ApiErrorId.ERR_DENIAL_REASON_REQUIRED: 422,
    ApiErrorId.ERR_APPEAL_TIER_ROLE_MISMATCH: 403,
    ApiErrorId.ERR_APPEAL_TIER_OUT_OF_ORDER: 422,
    ApiErrorId.ERR_APPEAL_DEADLINE_EXPIRED: 422,
    ApiErrorId.ERR_EVIDENCE_SIZE_INVALID: 422,
    ApiErrorId.ERR_INVALID_P2P_OUTCOME: 422,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
