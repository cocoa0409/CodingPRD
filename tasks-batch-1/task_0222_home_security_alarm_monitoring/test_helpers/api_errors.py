"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can auto-check
the HTTP status code for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_ACCOUNT_OWNER = "ERR_NOT_ACCOUNT_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_TEST_MODE_ACTIVE = "ERR_TEST_MODE_ACTIVE"
    ERR_COMMUNICATOR_OFFLINE = "ERR_COMMUNICATOR_OFFLINE"
    ERR_CELLULAR_NOT_ENTITLED = "ERR_CELLULAR_NOT_ENTITLED"
    ERR_SENSOR_LIMIT_EXCEEDED = "ERR_SENSOR_LIMIT_EXCEEDED"
    ERR_DUPLICATE_ZONE = "ERR_DUPLICATE_ZONE"
    ERR_PERMIT_ALREADY_ACTIVE = "ERR_PERMIT_ALREADY_ACTIVE"
    ERR_DUPLICATE_PERMIT_NUMBER = "ERR_DUPLICATE_PERMIT_NUMBER"
    ERR_OPEN_DISPATCH = "ERR_OPEN_DISPATCH"
    ERR_TEST_MODE_ALREADY_OPEN = "ERR_TEST_MODE_ALREADY_OPEN"
    ERR_SIGNAL_DEBOUNCED = "ERR_SIGNAL_DEBOUNCED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_ACCOUNT_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_TEST_MODE_ACTIVE: 409,
    ApiErrorId.ERR_COMMUNICATOR_OFFLINE: 409,
    ApiErrorId.ERR_CELLULAR_NOT_ENTITLED: 422,
    ApiErrorId.ERR_SENSOR_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_DUPLICATE_ZONE: 409,
    ApiErrorId.ERR_PERMIT_ALREADY_ACTIVE: 409,
    ApiErrorId.ERR_DUPLICATE_PERMIT_NUMBER: 409,
    ApiErrorId.ERR_OPEN_DISPATCH: 409,
    ApiErrorId.ERR_TEST_MODE_ALREADY_OPEN: 409,
    ApiErrorId.ERR_SIGNAL_DEBOUNCED: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
