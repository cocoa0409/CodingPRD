"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can auto-check
the HTTP status code that accompanies each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EMPTY_HOUSEHOLD = "ERR_EMPTY_HOUSEHOLD"
    ERR_NOT_VERIFIED = "ERR_NOT_VERIFIED"
    ERR_NO_ELIGIBLE_DETERMINATION = "ERR_NO_ELIGIBLE_DETERMINATION"
    ERR_APPLICATION_NOT_APPROVED = "ERR_APPLICATION_NOT_APPROVED"
    ERR_COVERAGE_OVERLAP = "ERR_COVERAGE_OVERLAP"
    ERR_REDETERMINATION_WINDOW_OVERLAP = "ERR_REDETERMINATION_WINDOW_OVERLAP"
    ERR_REDETERMINATION_IN_PROGRESS = "ERR_REDETERMINATION_IN_PROGRESS"
    ERR_DETERMINATION_INELIGIBLE = "ERR_DETERMINATION_INELIGIBLE"
    ERR_CONTINUOUS_COVERAGE_LOCK = "ERR_CONTINUOUS_COVERAGE_LOCK"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_TERMINATED = "ERR_NOT_TERMINATED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EMPTY_HOUSEHOLD: 409,
    ApiErrorId.ERR_NOT_VERIFIED: 409,
    ApiErrorId.ERR_NO_ELIGIBLE_DETERMINATION: 409,
    ApiErrorId.ERR_APPLICATION_NOT_APPROVED: 409,
    ApiErrorId.ERR_COVERAGE_OVERLAP: 409,
    ApiErrorId.ERR_REDETERMINATION_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_REDETERMINATION_IN_PROGRESS: 409,
    ApiErrorId.ERR_DETERMINATION_INELIGIBLE: 409,
    ApiErrorId.ERR_CONTINUOUS_COVERAGE_LOCK: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_NOT_TERMINATED: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
