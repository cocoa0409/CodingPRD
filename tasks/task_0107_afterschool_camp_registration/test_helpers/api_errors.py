"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_FAMILY_MISMATCH = "ERR_FAMILY_MISMATCH"

    # Existence — PRD §2.6
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"

    # Generic input — PRD §5
    ERR_VALIDATION = "ERR_VALIDATION"

    # Business — PRD §3.2 / §3.4 / §3.5 / §3.6 / §3.8
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_INVALID_WEEK_INDEX = "ERR_INVALID_WEEK_INDEX"
    ERR_AGE_OUT_OF_RANGE = "ERR_AGE_OUT_OF_RANGE"
    ERR_MEDICAL_AUTH_REQUIRED = "ERR_MEDICAL_AUTH_REQUIRED"
    ERR_PICKUP_AUTH_REQUIRED = "ERR_PICKUP_AUTH_REQUIRED"
    ERR_EMERGENCY_CONTACT_REQUIRED = "ERR_EMERGENCY_CONTACT_REQUIRED"
    ERR_AUTHORIZATION_NOT_ACTIVE = "ERR_AUTHORIZATION_NOT_ACTIVE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DUPLICATE_ENROLLMENT = "ERR_DUPLICATE_ENROLLMENT"
    ERR_WEEKLY_CAPACITY_FULL = "ERR_WEEKLY_CAPACITY_FULL"
    ERR_SCHOLARSHIP_INELIGIBLE = "ERR_SCHOLARSHIP_INELIGIBLE"
    ERR_SCHOLARSHIP_EXHAUSTED = "ERR_SCHOLARSHIP_EXHAUSTED"
    ERR_EMERGENCY_CONTACT_PRIORITY_TAKEN = (
        "ERR_EMERGENCY_CONTACT_PRIORITY_TAKEN"
    )
    ERR_RAINY_POOL_EXHAUSTED = "ERR_RAINY_POOL_EXHAUSTED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_FAMILY_HAS_FUTURE_ENROLLMENTS = "ERR_FAMILY_HAS_FUTURE_ENROLLMENTS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_FAMILY_MISMATCH: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_INVALID_WEEK_INDEX: 422,
    ApiErrorId.ERR_AGE_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_MEDICAL_AUTH_REQUIRED: 422,
    ApiErrorId.ERR_PICKUP_AUTH_REQUIRED: 422,
    ApiErrorId.ERR_EMERGENCY_CONTACT_REQUIRED: 422,
    ApiErrorId.ERR_AUTHORIZATION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DUPLICATE_ENROLLMENT: 409,
    ApiErrorId.ERR_WEEKLY_CAPACITY_FULL: 409,
    ApiErrorId.ERR_SCHOLARSHIP_INELIGIBLE: 422,
    ApiErrorId.ERR_SCHOLARSHIP_EXHAUSTED: 409,
    ApiErrorId.ERR_EMERGENCY_CONTACT_PRIORITY_TAKEN: 409,
    ApiErrorId.ERR_RAINY_POOL_EXHAUSTED: 422,
    ApiErrorId.ERR_STALE_VERSION: 409,
    ApiErrorId.ERR_FAMILY_HAS_FUTURE_ENROLLMENTS: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
