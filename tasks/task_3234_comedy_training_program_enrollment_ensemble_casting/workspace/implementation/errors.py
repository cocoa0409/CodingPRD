def raise_err(const, message=None):
    error_id, status = const
    raise ApiError(error_id, message or error_id, status)


def not_found(msg="resource not found"):
    raise_err(ERR_NOT_FOUND, msg)


def invalid_state(msg="invalid state for requested transition"):
    raise_err(ERR_INVALID_STATE, msg)


def invalid_request(msg="missing or malformed field"):
    raise_err(ERR_INVALID_REQUEST, msg)
