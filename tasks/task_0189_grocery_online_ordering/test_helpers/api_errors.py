"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

The mapping is registered with the framework at import time so validate_error()
auto-checks each error_id's HTTP status.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # request / auth
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_MISSING_USER_CONTEXT = "ERR_MISSING_USER_CONTEXT"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    # existence
    ERR_STORE_NOT_FOUND = "ERR_STORE_NOT_FOUND"
    ERR_CUSTOMER_NOT_FOUND = "ERR_CUSTOMER_NOT_FOUND"
    ERR_PRODUCT_NOT_FOUND = "ERR_PRODUCT_NOT_FOUND"
    ERR_SLOT_NOT_FOUND = "ERR_SLOT_NOT_FOUND"
    ERR_PICKER_NOT_FOUND = "ERR_PICKER_NOT_FOUND"
    ERR_ORDER_NOT_FOUND = "ERR_ORDER_NOT_FOUND"
    ERR_LINE_NOT_FOUND = "ERR_LINE_NOT_FOUND"
    ERR_SUBSTITUTION_NOT_FOUND = "ERR_SUBSTITUTION_NOT_FOUND"
    # referential / cross-store
    ERR_CROSS_STORE_REFERENCE = "ERR_CROSS_STORE_REFERENCE"
    ERR_PRODUCT_DISCONTINUED = "ERR_PRODUCT_DISCONTINUED"
    ERR_CUSTOMER_SUSPENDED = "ERR_CUSTOMER_SUSPENDED"
    ERR_STORE_CLOSED = "ERR_STORE_CLOSED"
    # order / line / substitution / slot state
    ERR_INVALID_ORDER_STATE = "ERR_INVALID_ORDER_STATE"
    ERR_ORDER_NOT_PICKING = "ERR_ORDER_NOT_PICKING"
    ERR_ORDER_NOT_STAGED = "ERR_ORDER_NOT_STAGED"
    ERR_ORDER_ALREADY_HANDED_OFF = "ERR_ORDER_ALREADY_HANDED_OFF"
    ERR_LINE_NOT_PENDING = "ERR_LINE_NOT_PENDING"
    ERR_LINE_NOT_PICKED = "ERR_LINE_NOT_PICKED"
    ERR_SUBSTITUTION_NOT_PROPOSED = "ERR_SUBSTITUTION_NOT_PROPOSED"
    ERR_SLOT_CLOSED = "ERR_SLOT_CLOSED"
    # capacity / concurrency / overlap / constraints
    ERR_SLOT_VERSION_STALE = "ERR_SLOT_VERSION_STALE"
    ERR_SLOT_FULL = "ERR_SLOT_FULL"
    ERR_SLOT_WINDOW_OVERLAP = "ERR_SLOT_WINDOW_OVERLAP"
    ERR_PICKER_WINDOW_CONFLICT = "ERR_PICKER_WINDOW_CONFLICT"
    ERR_LINES_NOT_RESOLVED = "ERR_LINES_NOT_RESOLVED"
    ERR_NOTHING_TO_STAGE = "ERR_NOTHING_TO_STAGE"
    ERR_INVALID_PICK_QUANTITY = "ERR_INVALID_PICK_QUANTITY"
    # safety / temporal / fiscal
    ERR_AGE_VERIFICATION_REQUIRED = "ERR_AGE_VERIFICATION_REQUIRED"
    ERR_AGE_VERIFICATION_FAILED = "ERR_AGE_VERIFICATION_FAILED"
    ERR_COLD_CHAIN_EXPIRED = "ERR_COLD_CHAIN_EXPIRED"
    ERR_PAYMENT_NOT_CAPTURED = "ERR_PAYMENT_NOT_CAPTURED"
    ERR_EBT_NOT_ACCEPTED = "ERR_EBT_NOT_ACCEPTED"
    ERR_SUBSTITUTION_NOT_ALLOWED = "ERR_SUBSTITUTION_NOT_ALLOWED"
    ERR_SUBSTITUTION_PRICE_EXCEEDED = "ERR_SUBSTITUTION_PRICE_EXCEEDED"


