"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_TIME_RANGE = "ERR_INVALID_TIME_RANGE"
    ERR_ENGINEER_REQUIRED = "ERR_ENGINEER_REQUIRED"
    ERR_ROOM_UNAVAILABLE = "ERR_ROOM_UNAVAILABLE"
    ERR_LOCKOUT_CONFLICT = "ERR_LOCKOUT_CONFLICT"
    ERR_GEAR_UNAVAILABLE = "ERR_GEAR_UNAVAILABLE"
    ERR_ENGINEER_UNAVAILABLE = "ERR_ENGINEER_UNAVAILABLE"
    ERR_DEPOSIT_MISMATCH = "ERR_DEPOSIT_MISMATCH"
    ERR_BALANCE_MISMATCH = "ERR_BALANCE_MISMATCH"
    ERR_DUPLICATE_EMAIL = "ERR_DUPLICATE_EMAIL"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_SESSION_NOT_DELIVERABLE = "ERR_SESSION_NOT_DELIVERABLE"
    ERR_CANCEL_TOO_LATE = "ERR_CANCEL_TOO_LATE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_TIME_RANGE: 422,
    ApiErrorId.ERR_ENGINEER_REQUIRED: 422,
    ApiErrorId.ERR_ROOM_UNAVAILABLE: 409,
    ApiErrorId.ERR_LOCKOUT_CONFLICT: 409,
    ApiErrorId.ERR_GEAR_UNAVAILABLE: 409,
    ApiErrorId.ERR_ENGINEER_UNAVAILABLE: 409,
    ApiErrorId.ERR_DEPOSIT_MISMATCH: 422,
    ApiErrorId.ERR_BALANCE_MISMATCH: 422,
    ApiErrorId.ERR_DUPLICATE_EMAIL: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_SESSION_NOT_DELIVERABLE: 409,
    ApiErrorId.ERR_CANCEL_TOO_LATE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
