"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ROOM_VERSION = "ERR_STALE_ROOM_VERSION"
    ERR_STALE_RESERVATION_VERSION = "ERR_STALE_RESERVATION_VERSION"
    ERR_TIMING_WINDOW = "ERR_TIMING_WINDOW"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_ROOM_TYPE_MISMATCH = "ERR_ROOM_TYPE_MISMATCH"
    ERR_ROOM_DOUBLE_BOOKED = "ERR_ROOM_DOUBLE_BOOKED"
    ERR_EXTENSION_CONFLICT = "ERR_EXTENSION_CONFLICT"
    ERR_ROOM_NOT_AVAILABLE = "ERR_ROOM_NOT_AVAILABLE"
    ERR_NOT_QUEUE_HEAD = "ERR_NOT_QUEUE_HEAD"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ROOM_VERSION: 412,
    ApiErrorId.ERR_STALE_RESERVATION_VERSION: 412,
    ApiErrorId.ERR_TIMING_WINDOW: 409,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_ROOM_TYPE_MISMATCH: 422,
    ApiErrorId.ERR_ROOM_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_EXTENSION_CONFLICT: 409,
    ApiErrorId.ERR_ROOM_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_NOT_QUEUE_HEAD: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
