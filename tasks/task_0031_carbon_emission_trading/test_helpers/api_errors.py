"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth / RBAC / existence
    ERR_AUTH_REQUIRED = "ERR_AUTH_REQUIRED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_OWNERSHIP_VIOLATION = "ERR_OWNERSHIP_VIOLATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State / OCC
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"

    # Concurrency / uniqueness
    ERR_OBJECTION_ALREADY_PENDING = "ERR_OBJECTION_ALREADY_PENDING"
    ERR_DECLARATION_ALREADY_SUBMITTED = "ERR_DECLARATION_ALREADY_SUBMITTED"

    # Business
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_PENALTY_OVERDUE = "ERR_PENALTY_OVERDUE"
    ERR_WINDOW_CLOSED = "ERR_WINDOW_CLOSED"
    ERR_VERIFIER_CONFLICT_OF_INTEREST = "ERR_VERIFIER_CONFLICT_OF_INTEREST"
    ERR_SUPPORTING_DOCUMENT_REQUIRED = "ERR_SUPPORTING_DOCUMENT_REQUIRED"
    ERR_CCER_CAP_EXCEEDED = "ERR_CCER_CAP_EXCEEDED"
    ERR_BORROW_CAP_EXCEEDED = "ERR_BORROW_CAP_EXCEEDED"
    ERR_INVALID_ORDER = "ERR_INVALID_ORDER"
    ERR_INVALID_RATIO = "ERR_INVALID_RATIO"

    # Generic structural
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_REQUIRED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_OWNERSHIP_VIOLATION: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 409,
    ApiErrorId.ERR_OBJECTION_ALREADY_PENDING: 409,
    ApiErrorId.ERR_DECLARATION_ALREADY_SUBMITTED: 409,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 409,
    ApiErrorId.ERR_PENALTY_OVERDUE: 409,
    ApiErrorId.ERR_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_VERIFIER_CONFLICT_OF_INTEREST: 422,
    ApiErrorId.ERR_SUPPORTING_DOCUMENT_REQUIRED: 422,
    ApiErrorId.ERR_CCER_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_BORROW_CAP_EXCEEDED: 422,
    ApiErrorId.ERR_INVALID_ORDER: 422,
    ApiErrorId.ERR_INVALID_RATIO: 422,
    ApiErrorId.ERR_INVALID_INPUT: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
