# The catalogue is referred to by two equivalent spellings across the suite: the
# short member name (`ApiErrorId.UNAUTHENTICATED`) and the wire identifier itself
# (`ApiErrorId.ERR_UNAUTHENTICATED`). Expose the wire identifier as a class-level
# alias of the same member so both spellings resolve to one object.
for _member in list(ApiErrorId):
    setattr(ApiErrorId, _member.value, _member)
del _member


