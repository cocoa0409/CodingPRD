"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth / RBAC - PRD §2.1, §5.
    ERR_AUTH_HEADER_MISSING = "ERR_AUTH_HEADER_MISSING"
    ERR_AUTH_HEADER_INVALID = "ERR_AUTH_HEADER_INVALID"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_PROVIDER_SUSPENDED = "ERR_PROVIDER_SUSPENDED"

    # Existence - PRD §2.5, §5.
    ERR_PATIENT_NOT_FOUND = "ERR_PATIENT_NOT_FOUND"
    ERR_DOSE_NOT_FOUND = "ERR_DOSE_NOT_FOUND"
    ERR_LOT_NOT_FOUND = "ERR_LOT_NOT_FOUND"
    ERR_PRODUCT_NOT_FOUND = "ERR_PRODUCT_NOT_FOUND"
    ERR_ADVERSE_EVENT_NOT_FOUND = "ERR_ADVERSE_EVENT_NOT_FOUND"
    ERR_CERTIFICATE_NOT_FOUND = "ERR_CERTIFICATE_NOT_FOUND"
    ERR_PROVIDER_NOT_FOUND = "ERR_PROVIDER_NOT_FOUND"

    # State checks - PRD §2.6, §5.
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LOT_RECALLED = "ERR_LOT_RECALLED"
    ERR_LOT_EXHAUSTED = "ERR_LOT_EXHAUSTED"
    ERR_CERTIFICATE_DUPLICATE = "ERR_CERTIFICATE_DUPLICATE"
    ERR_VAERS_ALREADY_SUBMITTED = "ERR_VAERS_ALREADY_SUBMITTED"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Business rules - PRD §2.6, §5.
    ERR_ALLERGY_CONTRAINDICATION = "ERR_ALLERGY_CONTRAINDICATION"
    ERR_AGE_OUT_OF_RANGE = "ERR_AGE_OUT_OF_RANGE"
    ERR_MIN_INTERVAL_VIOLATION = "ERR_MIN_INTERVAL_VIOLATION"
    ERR_ADMIN_TIME_OUT_OF_RANGE = "ERR_ADMIN_TIME_OUT_OF_RANGE"
    ERR_LOT_PRODUCT_MISMATCH = "ERR_LOT_PRODUCT_MISMATCH"
    ERR_DOSE_PATIENT_MISMATCH = "ERR_DOSE_PATIENT_MISMATCH"
    ERR_ONSET_OUT_OF_WINDOW = "ERR_ONSET_OUT_OF_WINDOW"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_VAERS_NOT_REPORTABLE = "ERR_VAERS_NOT_REPORTABLE"

    # Generic - PRD §5.
    ERR_VALIDATION = "ERR_VALIDATION"


# PRD §5 Error Code Catalogue — explicit HTTP status mapping.
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_HEADER_MISSING: 401,
    ApiErrorId.ERR_AUTH_HEADER_INVALID: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_PROVIDER_SUSPENDED: 403,
    ApiErrorId.ERR_PATIENT_NOT_FOUND: 404,
    ApiErrorId.ERR_DOSE_NOT_FOUND: 404,
    ApiErrorId.ERR_LOT_NOT_FOUND: 404,
    ApiErrorId.ERR_PRODUCT_NOT_FOUND: 404,
    ApiErrorId.ERR_ADVERSE_EVENT_NOT_FOUND: 404,
    ApiErrorId.ERR_CERTIFICATE_NOT_FOUND: 404,
    ApiErrorId.ERR_PROVIDER_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LOT_RECALLED: 409,
    ApiErrorId.ERR_LOT_EXHAUSTED: 409,
    ApiErrorId.ERR_CERTIFICATE_DUPLICATE: 409,
    ApiErrorId.ERR_VAERS_ALREADY_SUBMITTED: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_ALLERGY_CONTRAINDICATION: 422,
    ApiErrorId.ERR_AGE_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_MIN_INTERVAL_VIOLATION: 422,
    ApiErrorId.ERR_ADMIN_TIME_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_LOT_PRODUCT_MISMATCH: 422,
    ApiErrorId.ERR_DOSE_PATIENT_MISMATCH: 422,
    ApiErrorId.ERR_ONSET_OUT_OF_WINDOW: 422,
    ApiErrorId.ERR_SOD_VIOLATION: 422,
    ApiErrorId.ERR_VAERS_NOT_REPORTABLE: 422,
    ApiErrorId.ERR_VALIDATION: 400,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
