"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_REVIEWER_PAYER_MISMATCH = "ERR_REVIEWER_PAYER_MISMATCH"
    ERR_OPEN_P2P_BLOCKS_DECISION = "ERR_OPEN_P2P_BLOCKS_DECISION"
    ERR_NO_EVIDENCE = "ERR_NO_EVIDENCE"
    ERR_P2P_SLOT_CONFLICT = "ERR_P2P_SLOT_CONFLICT"
    ERR_PAST_DEADLINE = "ERR_PAST_DEADLINE"
    ERR_DUPLICATE_ACTIVE_AUTH = "ERR_DUPLICATE_ACTIVE_AUTH"
    ERR_INVALID_DECISION_FIELDS = "ERR_INVALID_DECISION_FIELDS"
    ERR_APPEAL_NOT_ELIGIBLE = "ERR_APPEAL_NOT_ELIGIBLE"
    ERR_INVALID_SUPERSEDE_TARGET = "ERR_INVALID_SUPERSEDE_TARGET"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_REVIEWER_PAYER_MISMATCH: 422,
    ApiErrorId.ERR_OPEN_P2P_BLOCKS_DECISION: 409,
    ApiErrorId.ERR_NO_EVIDENCE: 422,
    ApiErrorId.ERR_P2P_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_PAST_DEADLINE: 409,
    ApiErrorId.ERR_DUPLICATE_ACTIVE_AUTH: 409,
    ApiErrorId.ERR_INVALID_DECISION_FIELDS: 422,
    ApiErrorId.ERR_APPEAL_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_INVALID_SUPERSEDE_TARGET: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
