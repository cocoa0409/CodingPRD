"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DSHEA_DISEASE_CLAIM = "ERR_DSHEA_DISEASE_CLAIM"
    ERR_PRACTITIONER_AUTH_REQUIRED = "ERR_PRACTITIONER_AUTH_REQUIRED"
    ERR_LOT_NOT_SELLABLE = "ERR_LOT_NOT_SELLABLE"
    ERR_CUSTOMER_SUSPENDED = "ERR_CUSTOMER_SUSPENDED"
    ERR_BUNDLE_PRODUCT_MISMATCH = "ERR_BUNDLE_PRODUCT_MISMATCH"
    ERR_INVALID_QUANTITY = "ERR_INVALID_QUANTITY"
    ERR_INVALID_CADENCE = "ERR_INVALID_CADENCE"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_RECOMMENDATION_OVERLAP = "ERR_RECOMMENDATION_OVERLAP"
    ERR_SUBSCRIPTION_WINDOW_CONFLICT = "ERR_SUBSCRIPTION_WINDOW_CONFLICT"
    ERR_RETURN_QUANTITY_EXCEEDS = "ERR_RETURN_QUANTITY_EXCEEDS"
    ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DSHEA_DISEASE_CLAIM: 422,
    ApiErrorId.ERR_PRACTITIONER_AUTH_REQUIRED: 403,
    ApiErrorId.ERR_LOT_NOT_SELLABLE: 409,
    ApiErrorId.ERR_CUSTOMER_SUSPENDED: 409,
    ApiErrorId.ERR_BUNDLE_PRODUCT_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_QUANTITY: 422,
    ApiErrorId.ERR_INVALID_CADENCE: 422,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 409,
    ApiErrorId.ERR_RECOMMENDATION_OVERLAP: 409,
    ApiErrorId.ERR_SUBSCRIPTION_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_RETURN_QUANTITY_EXCEEDS: 422,
    ApiErrorId.ERR_INSUFFICIENT_POINTS: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
