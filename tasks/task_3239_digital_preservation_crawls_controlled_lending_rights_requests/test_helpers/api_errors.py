    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SO_DUTY_VIOLATION = "ERR_SO_DUTY_VIOLATION"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PATRON_SUSPENDED = "ERR_PATRON_SUSPENDED"
    ERR_WORK_UNAVAILABLE = "ERR_WORK_UNAVAILABLE"
    ERR_ITEM_NOT_LENDABLE = "ERR_ITEM_NOT_LENDABLE"
    ERR_WAITLIST_PRIORITY = "ERR_WAITLIST_PRIORITY"
    ERR_WORK_ALREADY_BORROWED = "ERR_WORK_ALREADY_BORROWED"
    ERR_LOAN_CAP_REACHED = "ERR_LOAN_CAP_REACHED"
    ERR_ACCESS_CREDENTIAL_REQUIRED = "ERR_ACCESS_CREDENTIAL_REQUIRED"
    ERR_SCHEDULE_NOT_DUE = "ERR_SCHEDULE_NOT_DUE"
    ERR_CRAWL_EXCLUDED = "ERR_CRAWL_EXCLUDED"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_LOAN_NOT_RENEWABLE = "ERR_LOAN_NOT_RENEWABLE"
    ERR_RENEWAL_WINDOW_EXCEEDED = "ERR_RENEWAL_WINDOW_EXCEEDED"
    ERR_GRANT_EXHAUSTED = "ERR_GRANT_EXHAUSTED"
