"""Error catalogue.

HTTP statuses are taken from PRD.md section 5 (the error catalogue), which is the
literal contract and wins over SCAFFOLD.yaml wherever the two disagree.
"""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(error_id)
        self.error_id = error_id
        self.http_status = http_status if http_status is not None else STATUS.get(error_id, 400)
        self.message = message if message else DEFAULT_MESSAGES.get(error_id, error_id)


