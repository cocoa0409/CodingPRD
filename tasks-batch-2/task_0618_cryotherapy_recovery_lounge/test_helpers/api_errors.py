"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CONTRAINDICATION_BLOCK = "ERR_CONTRAINDICATION_BLOCK"
    ERR_WAIVER_REQUIRED = "ERR_WAIVER_REQUIRED"
    ERR_ROOM_UNAVAILABLE = "ERR_ROOM_UNAVAILABLE"
    ERR_SHIFT_OVERLAP = "ERR_SHIFT_OVERLAP"
    ERR_NO_TECHNICIAN_ON_DUTY = "ERR_NO_TECHNICIAN_ON_DUTY"
    ERR_INTRO_ALREADY_USED = "ERR_INTRO_ALREADY_USED"
    ERR_NOT_AN_UPGRADE = "ERR_NOT_AN_UPGRADE"
    ERR_INSUFFICIENT_CREDITS = "ERR_INSUFFICIENT_CREDITS"
    ERR_LOCATION_CLOSED = "ERR_LOCATION_CLOSED"
    ERR_SERVICE_INACTIVE = "ERR_SERVICE_INACTIVE"
    ERR_FREEZE_CYCLES_INVALID = "ERR_FREEZE_CYCLES_INVALID"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"
    ERR_DUPLICATE_SUBSCRIPTION = "ERR_DUPLICATE_SUBSCRIPTION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CONTRAINDICATION_BLOCK: 422,
    ApiErrorId.ERR_WAIVER_REQUIRED: 422,
    ApiErrorId.ERR_ROOM_UNAVAILABLE: 409,
    ApiErrorId.ERR_SHIFT_OVERLAP: 409,
    ApiErrorId.ERR_NO_TECHNICIAN_ON_DUTY: 409,
    ApiErrorId.ERR_INTRO_ALREADY_USED: 409,
    ApiErrorId.ERR_NOT_AN_UPGRADE: 409,
    ApiErrorId.ERR_INSUFFICIENT_CREDITS: 422,
    ApiErrorId.ERR_LOCATION_CLOSED: 409,
    ApiErrorId.ERR_SERVICE_INACTIVE: 409,
    ApiErrorId.ERR_FREEZE_CYCLES_INVALID: 400,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
    ApiErrorId.ERR_DUPLICATE_SUBSCRIPTION: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
