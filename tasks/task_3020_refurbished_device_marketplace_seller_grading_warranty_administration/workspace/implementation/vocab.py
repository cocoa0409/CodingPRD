def battery_deduct(health):
    """Scaffold battery_deduct_bands: >=85 -> 0; 80..84 -> 2500; 70..79 -> 6000; else 12000."""
    if health >= 85:
        return 0
    if health >= 80:
        return 2500
    if health >= 70:
        return 6000
    return 12000