"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_UNIT_TOO_SMALL = "ERR_UNIT_TOO_SMALL"
    ERR_DUPLICATE_ORDINAL = "ERR_DUPLICATE_ORDINAL"
    ERR_PRECOOL_INCOMPLETE = "ERR_PRECOOL_INCOMPLETE"
    ERR_FSMA_NOT_REGISTERED = "ERR_FSMA_NOT_REGISTERED"
    ERR_SANITARY_TRAINING_LAPSED = "ERR_SANITARY_TRAINING_LAPSED"
    ERR_SANITATION_UNDOCUMENTED = "ERR_SANITATION_UNDOCUMENTED"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_CLAIM_NOT_ELIGIBLE = "ERR_CLAIM_NOT_ELIGIBLE"
    ERR_READING_SHAPE = "ERR_READING_SHAPE"
    ERR_STOP_WINDOW_OVERLAP = "ERR_STOP_WINDOW_OVERLAP"
    ERR_READING_OFFSET_DUPLICATE = "ERR_READING_OFFSET_DUPLICATE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_ASSET_TAG = "ERR_DUPLICATE_ASSET_TAG"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_UNIT_TOO_SMALL: 422,
    ApiErrorId.ERR_DUPLICATE_ORDINAL: 422,
    ApiErrorId.ERR_PRECOOL_INCOMPLETE: 422,
    ApiErrorId.ERR_FSMA_NOT_REGISTERED: 422,
    ApiErrorId.ERR_SANITARY_TRAINING_LAPSED: 422,
    ApiErrorId.ERR_SANITATION_UNDOCUMENTED: 422,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_CLAIM_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_READING_SHAPE: 422,
    ApiErrorId.ERR_STOP_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_READING_OFFSET_DUPLICATE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE_ASSET_TAG: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
