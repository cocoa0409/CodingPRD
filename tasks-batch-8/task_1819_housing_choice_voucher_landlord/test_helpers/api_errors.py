"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_NOT_OWNER = "ERR_NOT_OWNER"
    ERR_LANDLORD_SUSPENDED = "ERR_LANDLORD_SUSPENDED"
    ERR_INCREASE_TOO_EARLY = "ERR_INCREASE_TOO_EARLY"
    ERR_SCHEDULE_IN_PAST = "ERR_SCHEDULE_IN_PAST"
    ERR_VOUCHER_SIZE_MISMATCH = "ERR_VOUCHER_SIZE_MISMATCH"
    ERR_UNIT_ALREADY_UNDER_CONTRACT = "ERR_UNIT_ALREADY_UNDER_CONTRACT"
    ERR_INVALID_AMOUNT = "ERR_INVALID_AMOUNT"
    ERR_RENT_NOT_REASONABLE = "ERR_RENT_NOT_REASONABLE"
    ERR_FAIL_REQUIRES_ITEMS = "ERR_FAIL_REQUIRES_ITEMS"
    ERR_OPEN_REPAIR_ITEMS = "ERR_OPEN_REPAIR_ITEMS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_NOT_OWNER: 403,
    ApiErrorId.ERR_LANDLORD_SUSPENDED: 409,
    ApiErrorId.ERR_INCREASE_TOO_EARLY: 422,
    ApiErrorId.ERR_SCHEDULE_IN_PAST: 422,
    ApiErrorId.ERR_VOUCHER_SIZE_MISMATCH: 422,
    ApiErrorId.ERR_UNIT_ALREADY_UNDER_CONTRACT: 409,
    ApiErrorId.ERR_INVALID_AMOUNT: 422,
    ApiErrorId.ERR_RENT_NOT_REASONABLE: 422,
    ApiErrorId.ERR_FAIL_REQUIRES_ITEMS: 422,
    ApiErrorId.ERR_OPEN_REPAIR_ITEMS: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
