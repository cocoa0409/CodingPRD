"""Error catalog for the Fresh-Cut Produce Processing API.

Every declared error identifier together with the HTTP status it must be
returned with. Registering the mapping with the shared validators lets
``validate_error`` cross-check the status automatically, so a test only has to
name the identifier it expects.

The grouping comments follow the global validation order: authentication,
request shape, path existence, body foreign keys, stale versions, lifecycle
state, segregation of duties, then the food-safety, referential, temporal,
business and balance tiers.
"""

