    ERR_BLOCK_HAS_BOOKINGS = "ERR_BLOCK_HAS_BOOKINGS"
    # Temporal
    ERR_TIME_WINDOW_CONFLICT = "ERR_TIME_WINDOW_CONFLICT"
    # Folio
    ERR_FOLIO_OUTSTANDING = "ERR_FOLIO_OUTSTANDING"
    # Uniqueness / range
    ERR_DUPLICATE_CATEGORY_CODE = "ERR_DUPLICATE_CATEGORY_CODE"
    ERR_DUPLICATE_CABIN_NUMBER = "ERR_DUPLICATE_CABIN_NUMBER"
    ERR_DECK_OUT_OF_RANGE = "ERR_DECK_OUT_OF_RANGE"
    # Concurrency
    ERR_STALE_SAILING_VERSION = "ERR_STALE_SAILING_VERSION"


