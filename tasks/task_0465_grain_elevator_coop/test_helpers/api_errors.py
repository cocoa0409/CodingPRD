"""Error IDs and HTTP status mapping (PRD §5).

After defining the map, register it with the framework so validate_error()
auto-checks HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_COMMODITY_MISMATCH = "ERR_COMMODITY_MISMATCH"
    ERR_LEG_ALREADY_FIXED = "ERR_LEG_ALREADY_FIXED"
    ERR_NO_CURRENT_PRICE = "ERR_NO_CURRENT_PRICE"
    ERR_CONTRACT_NOT_PRICED = "ERR_CONTRACT_NOT_PRICED"
    ERR_CONTRACT_OVERFILL = "ERR_CONTRACT_OVERFILL"
    ERR_INSUFFICIENT_BUSHELS = "ERR_INSUFFICIENT_BUSHELS"
    ERR_PROGRAM_MISMATCH = "ERR_PROGRAM_MISMATCH"
    ERR_MARGIN_CALL_UNMET = "ERR_MARGIN_CALL_UNMET"
    ERR_CONTRACT_HAS_SETTLEMENTS = "ERR_CONTRACT_HAS_SETTLEMENTS"
    ERR_EMPTY_PATRONAGE_POOL = "ERR_EMPTY_PATRONAGE_POOL"
    ERR_RESOURCE_WINDOW_CONFLICT = "ERR_RESOURCE_WINDOW_CONFLICT"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_COMMODITY_MISMATCH: 409,
    ApiErrorId.ERR_LEG_ALREADY_FIXED: 409,
    ApiErrorId.ERR_NO_CURRENT_PRICE: 409,
    ApiErrorId.ERR_CONTRACT_NOT_PRICED: 409,
    ApiErrorId.ERR_CONTRACT_OVERFILL: 409,
    ApiErrorId.ERR_INSUFFICIENT_BUSHELS: 409,
    ApiErrorId.ERR_PROGRAM_MISMATCH: 409,
    ApiErrorId.ERR_MARGIN_CALL_UNMET: 409,
    ApiErrorId.ERR_CONTRACT_HAS_SETTLEMENTS: 409,
    ApiErrorId.ERR_EMPTY_PATRONAGE_POOL: 409,
    ApiErrorId.ERR_RESOURCE_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
