    ERR_INSTRUCTOR_EXPERTISE_MISMATCH = "ERR_INSTRUCTOR_EXPERTISE_MISMATCH"
    ERR_INSTRUCTOR_UNAVAILABLE = "ERR_INSTRUCTOR_UNAVAILABLE"
    ERR_CLASSROOM_CONFLICT = "ERR_CLASSROOM_CONFLICT"
    ERR_ONLINE_ROOM_CAPACITY_EXCEEDED = "ERR_ONLINE_ROOM_CAPACITY_EXCEEDED"
