"""Error identifiers and their HTTP status codes.

The mapping is registered with the framework at import time so that
``validate_error()`` can cross-check the HTTP status automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_RESPOND_AMOUNT_TOO_LOW = "ERR_RESPOND_AMOUNT_TOO_LOW"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_MERCHANT_NOT_FOUND = "ERR_MERCHANT_NOT_FOUND"
    ERR_NO_RISK_STATE = "ERR_NO_RISK_STATE"
    ERR_POOL_INSUFFICIENT_RESERVE = "ERR_POOL_INSUFFICIENT_RESERVE"
    ERR_PRIVACY_VIOLATION = "ERR_PRIVACY_VIOLATION"
    ERR_MERCHANT_RISK_SUPPRESSED = "ERR_MERCHANT_RISK_SUPPRESSED"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SUPPRESS_ALREADY_TERMINAL = "ERR_SUPPRESS_ALREADY_TERMINAL"
    ERR_BATCH_SEQ_NOT_MONOTONE = "ERR_BATCH_SEQ_NOT_MONOTONE"
    ERR_COMPLAINT_ALREADY_ENROLLED = "ERR_COMPLAINT_ALREADY_ENROLLED"
    ERR_TEMPORAL_OVERLAP = "ERR_TEMPORAL_OVERLAP"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_RESPOND_AMOUNT_TOO_LOW: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_MERCHANT_NOT_FOUND: 404,
    ApiErrorId.ERR_NO_RISK_STATE: 409,
    ApiErrorId.ERR_POOL_INSUFFICIENT_RESERVE: 402,
    ApiErrorId.ERR_PRIVACY_VIOLATION: 403,
    ApiErrorId.ERR_MERCHANT_RISK_SUPPRESSED: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SUPPRESS_ALREADY_TERMINAL: 409,
    ApiErrorId.ERR_BATCH_SEQ_NOT_MONOTONE: 409,
    ApiErrorId.ERR_COMPLAINT_ALREADY_ENROLLED: 409,
    ApiErrorId.ERR_TEMPORAL_OVERLAP: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)