class ApiError(Exception):
    def __init__(self, error_id, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or _default_message(error_id)
        self.http_status = ERROR_STATUS.get(error_id, 400)


def _default_message(error_id):
    return error_id.replace("ERR_", "").replace("_", " ").lower().capitalize() + "."


def invalid(field=None, detail=None):
    if detail:
        return ApiError("ERR_INVALID_REQUEST", detail)
    if field:
        return ApiError("ERR_INVALID_REQUEST", "Invalid or missing field '%s'." % field)
    return ApiError("ERR_INVALID_REQUEST")
