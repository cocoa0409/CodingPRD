"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping it is registered with the framework so that
validate_error() can auto-check the HTTP status for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SCREENING_FAILED = "ERR_SCREENING_FAILED"
    ERR_APPLICANT_NOT_APPROVED = "ERR_APPLICANT_NOT_APPROVED"
    ERR_UNIT_NOT_AVAILABLE = "ERR_UNIT_NOT_AVAILABLE"
    ERR_DEPOSIT_REQUIRED = "ERR_DEPOSIT_REQUIRED"
    ERR_LEASE_NOT_ENDED = "ERR_LEASE_NOT_ENDED"
    ERR_LEASE_OVERLAP = "ERR_LEASE_OVERLAP"
    ERR_EVICTION_WINDOW_OVERLAP = "ERR_EVICTION_WINDOW_OVERLAP"
    ERR_LEASE_STILL_ACTIVE = "ERR_LEASE_STILL_ACTIVE"
    ERR_CANNOT_WAIVE_RENT = "ERR_CANNOT_WAIVE_RENT"
    ERR_CURE_WINDOW_CLOSED = "ERR_CURE_WINDOW_CLOSED"
    ERR_CURE_WINDOW_OPEN = "ERR_CURE_WINDOW_OPEN"
    ERR_ARREARS_NOT_CLEARED = "ERR_ARREARS_NOT_CLEARED"
    ERR_OPEN_WORK_ORDERS = "ERR_OPEN_WORK_ORDERS"
    ERR_ACTUAL_COST_REQUIRED = "ERR_ACTUAL_COST_REQUIRED"
    ERR_TRUST_INSUFFICIENT = "ERR_TRUST_INSUFFICIENT"
    ERR_NOTHING_TO_DISTRIBUTE = "ERR_NOTHING_TO_DISTRIBUTE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SCREENING_FAILED: 409,
    ApiErrorId.ERR_APPLICANT_NOT_APPROVED: 409,
    ApiErrorId.ERR_UNIT_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_DEPOSIT_REQUIRED: 409,
    ApiErrorId.ERR_LEASE_NOT_ENDED: 409,
    ApiErrorId.ERR_LEASE_OVERLAP: 409,
    ApiErrorId.ERR_EVICTION_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_LEASE_STILL_ACTIVE: 409,
    ApiErrorId.ERR_CANNOT_WAIVE_RENT: 409,
    ApiErrorId.ERR_CURE_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_CURE_WINDOW_OPEN: 409,
    ApiErrorId.ERR_ARREARS_NOT_CLEARED: 409,
    ApiErrorId.ERR_OPEN_WORK_ORDERS: 409,
    ApiErrorId.ERR_ACTUAL_COST_REQUIRED: 422,
    ApiErrorId.ERR_TRUST_INSUFFICIENT: 409,
    ApiErrorId.ERR_NOTHING_TO_DISTRIBUTE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
