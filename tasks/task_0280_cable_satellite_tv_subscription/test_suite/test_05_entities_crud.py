"""Entity CRUD, defaults, computed fields, retrieval, listing, and not-found
breadth coverage (corner-design `entities` section).
"""
import pytest

from test_helpers import (
    validate_success,
    validate_error,
    validate_paginated,
    assert_account,
    TEST_USERS,
    create_package,
    create_prospect_account,
    activate_first_subscription,
    api_client,
)

ADMIN = TEST_USERS["billing_admin_headers"]
CSA = TEST_USERS["customer_service_agent_headers"]


def test_create_account_returns_defaults(api):
    """PRD §3.2: "A freshly created account starts with `lifecycle_status` of `PROSPECT`,
    `promo_status` of `NONE`, a `tenure_months` of 0, a null `active_package_id`, and a null
    `cancellation_effective_cycle`."

    Design: Corner/entities/create_account_returns_201_with_defaults
    """
    res = api.create_account(
        {"customer_name": "New Cust", "service_state_code": "CA", "contract_term_months": 0}, CSA
    )
    account = validate_success(res, 201)
    assert_account(account)
    assert account["lifecycle_status"] == "PROSPECT"
    assert account["promo_status"] == "NONE"
    assert account["version"] == 1
    assert account["tenure_months"] == 0


def test_get_account_returns_stored_entity(api):
    """PRD §2.4: "Every persisted resource carries an `id`: a server-minted UUID with no type
    prefix, generated by the system and never supplied by the client."

    Design: Corner/entities/get_account_returns_stored_entity
    """
    created = validate_success(
        api.create_account({"customer_name": "Stored", "service_state_code": "NY", "contract_term_months": 0}, CSA),
        201,
    )
    fetched = validate_success(api.get_account(created["id"], CSA), 200)
    assert fetched["customer_name"] == "Stored"
    assert fetched["id"] == created["id"]


def test_list_accounts_paginated_envelope(api):
    """PRD §2.3: "List responses carry the pagination fields `limit`, `offset`, `total_count`,
    and `has_more` inside the `meta` object of the envelope."

    Design: Corner/entities/list_accounts_paginated_envelope
    """
    for name in ("L1", "L2"):
        validate_success(
            api.create_account({"customer_name": name, "service_state_code": "CA", "contract_term_months": 0}, CSA),
            201,
        )
    data, meta = validate_paginated(api.list_accounts(ADMIN, params={"limit": 1, "offset": 0}))
    assert meta["total_count"] >= 2
    assert meta["has_more"] is True
    assert len(data) == 1


def test_get_nonexistent_account_returns_not_found(api):
    """PRD §2.6: "The account named first in the path is checked before any sub-resource; if it
    does not exist the request fails with `ERR_ACCOUNT_NOT_FOUND` (HTTP 404) before the server
    even looks for the sub-resource."

    Design: Corner/entities/get_account_nonexistent_returns_not_found
    """
    res = api.get_account("00000000-0000-4000-8000-000000000000", CSA)
    validate_error(res, "ERR_ACCOUNT_NOT_FOUND", expected_status=404)


