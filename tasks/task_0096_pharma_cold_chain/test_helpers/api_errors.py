"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth
    ERR_AUTH_MISSING_ROLE = "ERR_AUTH_MISSING_ROLE"
    ERR_AUTH_MISSING_USER = "ERR_AUTH_MISSING_USER"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"

    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State preconditions
    ERR_RECEIPT_NOT_PENDING = "ERR_RECEIPT_NOT_PENDING"
    ERR_RECEIPT_NOT_INSPECTED = "ERR_RECEIPT_NOT_INSPECTED"
    ERR_RECEIPT_NOT_QUARANTINED = "ERR_RECEIPT_NOT_QUARANTINED"
    ERR_SHIPMENT_STATE_INVALID = "ERR_SHIPMENT_STATE_INVALID"
    ERR_RECALL_NOT_DRAFT = "ERR_RECALL_NOT_DRAFT"
    ERR_RECALL_STATE_INVALID = "ERR_RECALL_STATE_INVALID"
    ERR_DEVIATION_STATE_INVALID = "ERR_DEVIATION_STATE_INVALID"
    ERR_CAPA_STATE_INVALID = "ERR_CAPA_STATE_INVALID"
    ERR_BIN_UNAVAILABLE = "ERR_BIN_UNAVAILABLE"
    ERR_ZONE_FROZEN = "ERR_ZONE_FROZEN"

    # Business safety
    ERR_UNQUALIFIED_SUPPLIER = "ERR_UNQUALIFIED_SUPPLIER"
    ERR_UNQUALIFIED_PRODUCT = "ERR_UNQUALIFIED_PRODUCT"
    ERR_EXPIRED_LOT = "ERR_EXPIRED_LOT"
    ERR_TEMP_PRECHECK_FAIL = "ERR_TEMP_PRECHECK_FAIL"
    ERR_LOGGER_DATA_INVALID = "ERR_LOGGER_DATA_INVALID"

    # Business constraint
    ERR_PACKAGING_MISMATCH = "ERR_PACKAGING_MISMATCH"
    ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
    ERR_FEFO_VIOLATION = "ERR_FEFO_VIOLATION"
    ERR_NO_FEFO_LOT = "ERR_NO_FEFO_LOT"
    ERR_NO_ELIGIBLE_BIN = "ERR_NO_ELIGIBLE_BIN"
    ERR_BIN_CAPACITY_EXCEEDED = "ERR_BIN_CAPACITY_EXCEEDED"
    ERR_ZONE_CAPACITY_EXCEEDED = "ERR_ZONE_CAPACITY_EXCEEDED"
    ERR_QUANTITY_INVALID = "ERR_QUANTITY_INVALID"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_RECALL_SCOPE_EMPTY = "ERR_RECALL_SCOPE_EMPTY"
    ERR_RETURN_SCOPE_INVALID = "ERR_RETURN_SCOPE_INVALID"
    ERR_TEMP_EVENT_TIME_INVALID = "ERR_TEMP_EVENT_TIME_INVALID"
    ERR_RECALL_DEADLINE_INVALID = "ERR_RECALL_DEADLINE_INVALID"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"


