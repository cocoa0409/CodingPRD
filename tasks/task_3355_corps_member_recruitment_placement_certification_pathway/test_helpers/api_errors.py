    ERR_PATHWAY_NOT_FOUND = "ERR_PATHWAY_NOT_FOUND"
    ERR_MEMBER_NOT_FOUND = "ERR_MEMBER_NOT_FOUND"
    ERR_PLACEMENT_NOT_FOUND = "ERR_PLACEMENT_NOT_FOUND"
    ERR_MILESTONE_NOT_FOUND = "ERR_MILESTONE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"
    ERR_OFFER_EXPIRED = "ERR_OFFER_EXPIRED"
    ERR_DISTRICT_NOT_ACTIVE = "ERR_DISTRICT_NOT_ACTIVE"
