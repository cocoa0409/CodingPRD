def not_found(what="Resource"):
    return ApiError(ERR_NOT_FOUND, 404, f"{what} not found")


def validation(msg):
    return ApiError(ERR_VALIDATION, 400, msg)


def invalid_state(msg):
    return ApiError(ERR_INVALID_STATE, 409, msg)
