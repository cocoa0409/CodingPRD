"""Error catalogue for the Affordable Housing Equity Syndication API.

Every error identifier in PRD section 5 with its HTTP status code.
"""


class ApiError(Exception):
    """Carries an error_id, a human message and the HTTP status to emit."""

    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


