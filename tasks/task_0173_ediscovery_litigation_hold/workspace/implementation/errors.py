"""Error catalog and ApiError exception."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error ID constants with HTTP status mappings (from PRD §5 / scaffold §1.6).
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_SEGREGATION_OF_DUTIES = ("ERR_SEGREGATION_OF_DUTIES", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_BATCH_NOT_COMPLETED = ("ERR_BATCH_NOT_COMPLETED", 409)
ERR_CUSTODIAN_NOT_ACKNOWLEDGED = ("ERR_CUSTODIAN_NOT_ACKNOWLEDGED", 409)
ERR_PRIVILEGED_DOCUMENT = ("ERR_PRIVILEGED_DOCUMENT", 422)
ERR_DOCUMENT_NOT_UNIQUE = ("ERR_DOCUMENT_NOT_UNIQUE", 422)
ERR_SCOPE_DATE_OVERLAP = ("ERR_SCOPE_DATE_OVERLAP", 409)
ERR_DUPLICATE_CUSTODIAN_EMAIL = ("ERR_DUPLICATE_CUSTODIAN_EMAIL", 409)
ERR_INVALID_DATE_RANGE = ("ERR_INVALID_DATE_RANGE", 422)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_HOLD_HAS_NO_CUSTODIANS = ("ERR_HOLD_HAS_NO_CUSTODIANS", 409)
ERR_VALIDATION_OUT_OF_RANGE = ("ERR_VALIDATION_OUT_OF_RANGE", 422)
ERR_BATCH_NOT_FULLY_REVIEWED = ("ERR_BATCH_NOT_FULLY_REVIEWED", 409)
ERR_EMPTY_BATCH = ("ERR_EMPTY_BATCH", 409)
ERR_EMPTY_PRODUCTION_SET = ("ERR_EMPTY_PRODUCTION_SET", 409)


def err(code_tuple, message=None):
    error_id, http_status = code_tuple
    return ApiError(error_id, http_status, message)
