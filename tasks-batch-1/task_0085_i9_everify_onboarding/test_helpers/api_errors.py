"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EVERIFY_CASE_EXISTS = "ERR_EVERIFY_CASE_EXISTS"
    ERR_DOCUMENT_NOT_OWNED = "ERR_DOCUMENT_NOT_OWNED"
    ERR_SECTION1_INCOMPLETE = "ERR_SECTION1_INCOMPLETE"
    ERR_DOCUMENT_COMBINATION_INVALID = "ERR_DOCUMENT_COMBINATION_INVALID"
    ERR_DOCUMENT_EXPIRED = "ERR_DOCUMENT_EXPIRED"
    ERR_STEM_WINDOW_MISSED = "ERR_STEM_WINDOW_MISSED"
    ERR_REFERRAL_WINDOW_CLOSED = "ERR_REFERRAL_WINDOW_CLOSED"
    ERR_LATE_REASON_REQUIRED = "ERR_LATE_REASON_REQUIRED"
    ERR_STALE_ONBOARDING_VERSION = "ERR_STALE_ONBOARDING_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EVERIFY_CASE_EXISTS: 409,
    ApiErrorId.ERR_DOCUMENT_NOT_OWNED: 422,
    ApiErrorId.ERR_SECTION1_INCOMPLETE: 422,
    ApiErrorId.ERR_DOCUMENT_COMBINATION_INVALID: 422,
    ApiErrorId.ERR_DOCUMENT_EXPIRED: 422,
    ApiErrorId.ERR_STEM_WINDOW_MISSED: 422,
    ApiErrorId.ERR_REFERRAL_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_LATE_REASON_REQUIRED: 422,
    ApiErrorId.ERR_STALE_ONBOARDING_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
