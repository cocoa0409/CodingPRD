"""Error catalogue (PRD §5) and the ApiError exception type.

Every error_id and HTTP status is taken verbatim from the PRD error catalogue.
"""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# PRD §5 error catalogue — (error_id -> http status)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_UNAUTHORIZED = ("ERR_UNAUTHORIZED", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_REFERENCE_NOT_FOUND = ("ERR_REFERENCE_NOT_FOUND", 422)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INCOMPLETE_LSIR_DOMAINS = ("ERR_INCOMPLETE_LSIR_DOMAINS", 422)
ERR_INVALID_OVERRIDE = ("ERR_INVALID_OVERRIDE", 422)
ERR_OFFICER_ROLE_MISMATCH = ("ERR_OFFICER_ROLE_MISMATCH", 422)
ERR_DUPLICATE_KEY = ("ERR_DUPLICATE_KEY", 409)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_SEGREGATION_OF_DUTIES = ("ERR_SEGREGATION_OF_DUTIES", 409)
ERR_LEVEL_TOO_LOW_FOR_CONDITION = ("ERR_LEVEL_TOO_LOW_FOR_CONDITION", 409)
ERR_WINDOW_NOT_CLOSED = ("ERR_WINDOW_NOT_CLOSED", 409)
ERR_CHECKIN_WINDOW_OVERLAP = ("ERR_CHECKIN_WINDOW_OVERLAP", 409)
ERR_TRANSFER_ALREADY_OPEN = ("ERR_TRANSFER_ALREADY_OPEN", 409)
ERR_SUPERVISEE_CLOSED = ("ERR_SUPERVISEE_CLOSED", 409)
ERR_NOT_ELIGIBLE_FOR_TERMINATION = ("ERR_NOT_ELIGIBLE_FOR_TERMINATION", 409)
ERR_PAYMENT_EXCEEDS_BALANCE = ("ERR_PAYMENT_EXCEEDS_BALANCE", 422)
ERR_OUTSTANDING_BALANCE = ("ERR_OUTSTANDING_BALANCE", 409)
ERR_TRANSFER_BLOCKED_HIGH_RISK = ("ERR_TRANSFER_BLOCKED_HIGH_RISK", 409)
ERR_STALE_SUPERVISEE_VERSION = ("ERR_STALE_SUPERVISEE_VERSION", 412)
ERR_VALIDATION = ("ERR_VALIDATION", 422)


def err(spec, message=None):
    """Raise an ApiError from a (error_id, http) tuple."""
    return ApiError(spec[0], spec[1], message)
