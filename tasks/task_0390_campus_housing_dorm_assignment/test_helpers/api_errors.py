"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework at import time so validate_error()
auto-checks the HTTP status code that accompanies each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_DATE_RANGE = "ERR_INVALID_DATE_RANGE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PRECONDITION_NOT_MET = "ERR_PRECONDITION_NOT_MET"
    ERR_GENDER_INCOMPATIBLE = "ERR_GENDER_INCOMPATIBLE"
    ERR_STUDENT_ON_HOLD = "ERR_STUDENT_ON_HOLD"
    ERR_BREAK_OVERLAP = "ERR_BREAK_OVERLAP"
    ERR_BREAK_CAPACITY_EXCEEDED = "ERR_BREAK_CAPACITY_EXCEEDED"
    ERR_GROUP_SIZE_INVALID = "ERR_GROUP_SIZE_INVALID"
    ERR_UNSETTLED_CHARGES = "ERR_UNSETTLED_CHARGES"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_ROOM_OCCUPIED = "ERR_ROOM_OCCUPIED"
    ERR_DUPLICATE_MEMBERSHIP = "ERR_DUPLICATE_MEMBERSHIP"
    ERR_DUPLICATE_APPLICATION = "ERR_DUPLICATE_APPLICATION"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_DATE_RANGE: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PRECONDITION_NOT_MET: 409,
    ApiErrorId.ERR_GENDER_INCOMPATIBLE: 409,
    ApiErrorId.ERR_STUDENT_ON_HOLD: 409,
    ApiErrorId.ERR_BREAK_OVERLAP: 409,
    ApiErrorId.ERR_BREAK_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_GROUP_SIZE_INVALID: 409,
    ApiErrorId.ERR_UNSETTLED_CHARGES: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_ROOM_OCCUPIED: 409,
    ApiErrorId.ERR_DUPLICATE_MEMBERSHIP: 409,
    ApiErrorId.ERR_DUPLICATE_APPLICATION: 409,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
