    ERR_SLOT_QUOTA_EXHAUSTED = "ERR_SLOT_QUOTA_EXHAUSTED"
    ERR_DAILY_QUOTA_EXHAUSTED = "ERR_DAILY_QUOTA_EXHAUSTED"
    ERR_MUSEUM_CLOSED_ON_DATE = "ERR_MUSEUM_CLOSED_ON_DATE"
    ERR_PASS_EXPIRED = "ERR_PASS_EXPIRED"
    ERR_SCREENING_THROUGHPUT_FULL = "ERR_SCREENING_THROUGHPUT_FULL"
    # Exhibition ticketing
    ERR_SALE_NOT_OPEN = "ERR_SALE_NOT_OPEN"
    ERR_PRESALE_MEMBER_ONLY = "ERR_PRESALE_MEMBER_ONLY"
    ERR_MEMBER_LAPSED = "ERR_MEMBER_LAPSED"
    ERR_TICKET_QUOTA_EXHAUSTED = "ERR_TICKET_QUOTA_EXHAUSTED"
    ERR_REFUND_WINDOW_CLOSED = "ERR_REFUND_WINDOW_CLOSED"
    ERR_VISIT_DATE_MISMATCH = "ERR_VISIT_DATE_MISMATCH"
    # Education programs, docents, reservations
    ERR_GROUP_TOO_LARGE = "ERR_GROUP_TOO_LARGE"
    ERR_PROGRAM_DAY_MISMATCH = "ERR_PROGRAM_DAY_MISMATCH"
    ERR_PROGRAM_NOT_SCHEDULED = "ERR_PROGRAM_NOT_SCHEDULED"
    ERR_DOCENT_NOT_CERTIFIED = "ERR_DOCENT_NOT_CERTIFIED"
    ERR_GALLERY_SCHEDULE_CONFLICT = "ERR_GALLERY_SCHEDULE_CONFLICT"
    # Loans & condition reports
    ERR_OBJECT_NOT_IN_COLLECTION = "ERR_OBJECT_NOT_IN_COLLECTION"
    ERR_LOAN_PERIOD_CONFLICT = "ERR_LOAN_PERIOD_CONFLICT"
    ERR_COURIER_REQUIRED = "ERR_COURIER_REQUIRED"
    ERR_INDEMNITY_MINIMUM_NOT_MET = "ERR_INDEMNITY_MINIMUM_NOT_MET"
    ERR_INDEMNITY_REQUIRES_COURIER = "ERR_INDEMNITY_REQUIRES_COURIER"
    ERR_STALE_LOAN_VERSION = "ERR_STALE_LOAN_VERSION"
    ERR_CONDITION_REPORT_REQUIRED = "ERR_CONDITION_REPORT_REQUIRED"
    # Committee review
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_CULTURAL_PROPERTY_REVIEW_PENDING = "ERR_CULTURAL_PROPERTY_REVIEW_PENDING"
    ERR_OBJECT_ON_ACTIVE_LOAN = "ERR_OBJECT_ON_ACTIVE_LOAN"
    ERR_STALE_REVIEW_VERSION = "ERR_STALE_REVIEW_VERSION"
    # Funds & expenditures
    ERR_FUND_FROZEN = "ERR_FUND_FROZEN"
    ERR_FUND_ACTIVITY_NOT_PERMITTED = "ERR_FUND_ACTIVITY_NOT_PERMITTED"
    ERR_INSUFFICIENT_FUND_AVAILABLE = "ERR_INSUFFICIENT_FUND_AVAILABLE"
    ERR_NOT_TRUST_FUND = "ERR_NOT_TRUST_FUND"
    # Research access
    ERR_RESEARCH_VISIT_CONFLICT = "ERR_RESEARCH_VISIT_CONFLICT"
    ERR_OBJECT_RESERVED_FOR_LOAN = "ERR_OBJECT_RESERVED_FOR_LOAN"


