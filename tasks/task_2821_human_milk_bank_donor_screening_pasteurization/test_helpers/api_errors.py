"""Error identifiers and the single HTTP status each is ever returned with.

The PRD states that "the status code paired with it here is the only status that
identifier is ever returned with", so the mapping below is registered with the
framework validators and `validate_error` can then be called without an
explicit expected status.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


