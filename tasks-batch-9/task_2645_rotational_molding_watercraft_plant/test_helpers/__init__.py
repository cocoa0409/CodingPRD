"""Test support package for the rotational moulding watercraft plant service.

Every name a test needs is re-exported here, so test modules import from
``test_helpers`` alone. The layers are:

* ``types`` - TypedDicts for the sixteen entities PRD.md section 2.8 defines
  plus the computed projections of PRD.md sections 3.7, 3.8 and 2.5.
* ``api_errors`` - the error identifiers of PRD.md section 5 and their
  HTTP statuses, registered with the validation framework on import.
* ``api_client`` - one method per endpoint, plus accessors that unwrap the
  response envelope of PRD.md section 2.2.
* ``constants`` - the enumerations, thresholds and rounding scales the
  calculations of PRD.md section 3 depend on.
* ``test_users`` - request headers for the eight roles of PRD.md section 2.1.
* ``factories`` - one payload builder per endpoint body.
* ``assertions`` - decimal, invariant and projection checks.
* ``fixtures`` - composite setups that drive the workflows of PRD.md
  section 3 to a named state.

Names re-exported from ``prd_bench_local_runner.testing`` (the response
envelope validators, race helpers and shared constants) are also available
here so a test needs a single import line.
"""

