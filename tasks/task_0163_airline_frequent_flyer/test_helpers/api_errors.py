    ERR_UPGRADE_INVENTORY_EXHAUSTED = "ERR_UPGRADE_INVENTORY_EXHAUSTED"
    ERR_IDEMPOTENCY_CONFLICT = "ERR_IDEMPOTENCY_CONFLICT"
    ERR_EMAIL_CONFLICT = "ERR_EMAIL_CONFLICT"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

