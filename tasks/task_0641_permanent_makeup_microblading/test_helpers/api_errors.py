"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping it is registered with the framework so that
validate_error() can auto-check HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_AGE_NOT_VERIFIED = "ERR_AGE_NOT_VERIFIED"
    ERR_CONSENT_MISSING = "ERR_CONSENT_MISSING"
    ERR_PATCH_TEST_FAILED = "ERR_PATCH_TEST_FAILED"
    ERR_COOLING_OFF_VIOLATION = "ERR_COOLING_OFF_VIOLATION"
    ERR_MEDICAL_CLEARANCE_REQUIRED = "ERR_MEDICAL_CLEARANCE_REQUIRED"
    ERR_CLIENT_BLOCKED = "ERR_CLIENT_BLOCKED"
    ERR_LICENSE_INVALID = "ERR_LICENSE_INVALID"
    ERR_NO_STERILE_KIT = "ERR_NO_STERILE_KIT"
    ERR_TOUCHUP_WINDOW_CLOSED = "ERR_TOUCHUP_WINDOW_CLOSED"
    ERR_REFRESH_NOT_DUE = "ERR_REFRESH_NOT_DUE"
    ERR_REDO_NOT_ELIGIBLE = "ERR_REDO_NOT_ELIGIBLE"
    ERR_DEPOSIT_AMOUNT_MISMATCH = "ERR_DEPOSIT_AMOUNT_MISMATCH"
    ERR_VALIDATION_RANGE = "ERR_VALIDATION_RANGE"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_AGE_NOT_VERIFIED: 422,
    ApiErrorId.ERR_CONSENT_MISSING: 422,
    ApiErrorId.ERR_PATCH_TEST_FAILED: 422,
    ApiErrorId.ERR_COOLING_OFF_VIOLATION: 422,
    ApiErrorId.ERR_MEDICAL_CLEARANCE_REQUIRED: 422,
    ApiErrorId.ERR_CLIENT_BLOCKED: 422,
    ApiErrorId.ERR_LICENSE_INVALID: 422,
    ApiErrorId.ERR_NO_STERILE_KIT: 422,
    ApiErrorId.ERR_TOUCHUP_WINDOW_CLOSED: 422,
    ApiErrorId.ERR_REFRESH_NOT_DUE: 422,
    ApiErrorId.ERR_REDO_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_DEPOSIT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_VALIDATION_RANGE: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
