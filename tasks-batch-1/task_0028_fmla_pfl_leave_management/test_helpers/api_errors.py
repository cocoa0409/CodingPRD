"""Error IDs and HTTP status mapping (PRD §5).

After defining the mapping, registers it with the framework so
`validate_error()` can cross-check HTTP status codes automatically.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_ENTITY_NOT_FOUND = "ERR_REFERENCED_ENTITY_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EMPLOYEE_TERMINATED = "ERR_EMPLOYEE_TERMINATED"
    ERR_CERTIFICATION_INCOMPLETE = "ERR_CERTIFICATION_INCOMPLETE"
    ERR_INTERMITTENT_CERT_REQUIRED = "ERR_INTERMITTENT_CERT_REQUIRED"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INELIGIBLE = "ERR_INELIGIBLE"
    ERR_INTERVAL_OVERLAP = "ERR_INTERVAL_OVERLAP"
    ERR_INTERMITTENT_FREQUENCY_EXCEEDED = "ERR_INTERMITTENT_FREQUENCY_EXCEEDED"
    ERR_INTERMITTENT_HOURS_EXCEEDED = "ERR_INTERMITTENT_HOURS_EXCEEDED"
    ERR_RECERT_TOO_SOON = "ERR_RECERT_TOO_SOON"
    ERR_INVALID_PAYMENT_AMOUNT = "ERR_INVALID_PAYMENT_AMOUNT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_ENTITY_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EMPLOYEE_TERMINATED: 409,
    ApiErrorId.ERR_CERTIFICATION_INCOMPLETE: 409,
    ApiErrorId.ERR_INTERMITTENT_CERT_REQUIRED: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INELIGIBLE: 422,
    ApiErrorId.ERR_INTERVAL_OVERLAP: 409,
    ApiErrorId.ERR_INTERMITTENT_FREQUENCY_EXCEEDED: 409,
    ApiErrorId.ERR_INTERMITTENT_HOURS_EXCEEDED: 422,
    ApiErrorId.ERR_RECERT_TOO_SOON: 409,
    ApiErrorId.ERR_INVALID_PAYMENT_AMOUNT: 422,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
