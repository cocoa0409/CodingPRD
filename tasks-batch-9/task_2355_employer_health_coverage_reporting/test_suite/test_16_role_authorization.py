"""Role-based access control across workforce, statement and consent endpoints.

The acting role is checked immediately after authentication, so these scenarios
are built so that only the role (or, for the employee role, the acting identity)
can be the reason a call is refused.

The harness empties the database and relaunches the API before every single
test, so each test builds its own world from the PRD's own endpoints.
"""

import pytest

from test_helpers import (
    ApiErrorId,
    TEST_USERS,
    factories as f,
    fixtures,
    make_employee_self_service_headers,
    validate_error,
    validate_paginated,
    validate_success,
)

BA = TEST_USERS["benefits_admin"]
PREPARER_1 = TEST_USERS["preparer"]

FURNISHING_WINDOW_INSTANT = "2027-02-01T00:00:00Z"


