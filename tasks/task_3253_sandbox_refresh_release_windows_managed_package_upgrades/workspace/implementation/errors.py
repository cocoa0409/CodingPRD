"""Error catalogue for the Org Platform Admin API.

Every error id below is the literal identifier declared in the PRD's error
catalogue (§5); the HTTP status attached to each is the one the PRD maps to it.
"""


class ApiError(Exception):
    """An API failure carrying the error id, message and HTTP status."""

    def __init__(self, error_id, message, http_status):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


