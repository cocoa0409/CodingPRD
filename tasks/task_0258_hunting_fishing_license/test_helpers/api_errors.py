"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_POOL_VERSION = "ERR_STALE_POOL_VERSION"
    ERR_DRAW_REQUIRED = "ERR_DRAW_REQUIRED"
    ERR_EDUCATION_REQUIRED = "ERR_EDUCATION_REQUIRED"
    ERR_MINIMUM_AGE = "ERR_MINIMUM_AGE"
    ERR_RESIDENCY_RESTRICTED = "ERR_RESIDENCY_RESTRICTED"
    ERR_ENTRY_CLOSED = "ERR_ENTRY_CLOSED"
    ERR_DUPLICATE_ENTRY = "ERR_DUPLICATE_ENTRY"
    ERR_SEASON_NOT_OPEN = "ERR_SEASON_NOT_OPEN"
    ERR_BAG_LIMIT_EXCEEDED = "ERR_BAG_LIMIT_EXCEEDED"
    ERR_DUPLICATE_SKU = "ERR_DUPLICATE_SKU"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_POOL_VERSION: 412,
    ApiErrorId.ERR_DRAW_REQUIRED: 409,
    ApiErrorId.ERR_EDUCATION_REQUIRED: 409,
    ApiErrorId.ERR_MINIMUM_AGE: 409,
    ApiErrorId.ERR_RESIDENCY_RESTRICTED: 409,
    ApiErrorId.ERR_ENTRY_CLOSED: 409,
    ApiErrorId.ERR_DUPLICATE_ENTRY: 409,
    ApiErrorId.ERR_SEASON_NOT_OPEN: 409,
    ApiErrorId.ERR_BAG_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_DUPLICATE_SKU: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
