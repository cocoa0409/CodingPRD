def raise_err(err, message):
    error_id, http_status = err
    raise ApiError(error_id, http_status, message)


def invalid_request(message):
    raise_err(ERR_INVALID_REQUEST, message)


def not_found(message="resource not found"):
    raise_err(ERR_NOT_FOUND, message)


def forbidden(message="forbidden"):
    raise_err(ERR_FORBIDDEN, message)


def invalid_state(message="invalid state"):
    raise_err(ERR_INVALID_STATE, message)
