"""Error IDs and their HTTP status codes (PRD §5), registered with the framework
so ``validate_error()`` cross-checks the status automatically."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_REFERRAL_NOT_ACTIVE = "ERR_REFERRAL_NOT_ACTIVE"
    ERR_PLACEMENT_NOT_ACTIVE = "ERR_PLACEMENT_NOT_ACTIVE"
    ERR_WAIVER_REQUIRED = "ERR_WAIVER_REQUIRED"
    ERR_SITE_NOT_ACCEPTING = "ERR_SITE_NOT_ACCEPTING"
    ERR_INSURANCE_INVALID = "ERR_INSURANCE_INVALID"
    ERR_SUPERVISOR_SITE_MISMATCH = "ERR_SUPERVISOR_SITE_MISMATCH"
    ERR_SELF_APPROVAL = "ERR_SELF_APPROVAL"
    ERR_SESSION_OVERLAP = "ERR_SESSION_OVERLAP"
    ERR_SUPERVISOR_DOUBLE_BOOKED = "ERR_SUPERVISOR_DOUBLE_BOOKED"
    ERR_SITE_CAPACITY_EXCEEDED = "ERR_SITE_CAPACITY_EXCEEDED"
    ERR_HOURS_EXCEED_OUTSTANDING = "ERR_HOURS_EXCEED_OUTSTANDING"
    ERR_VERIFIED_HOURS_EXCEED_CLAIMED = "ERR_VERIFIED_HOURS_EXCEED_CLAIMED"
    ERR_CHECKOUT_BEFORE_CHECKIN = "ERR_CHECKOUT_BEFORE_CHECKIN"
    ERR_NO_REMAINING_HOURS = "ERR_NO_REMAINING_HOURS"
    ERR_STALE_REFERRAL_VERSION = "ERR_STALE_REFERRAL_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_PAGINATION_INVALID: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_REFERRAL_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PLACEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_WAIVER_REQUIRED: 409,
    ApiErrorId.ERR_SITE_NOT_ACCEPTING: 409,
    ApiErrorId.ERR_INSURANCE_INVALID: 409,
    ApiErrorId.ERR_SUPERVISOR_SITE_MISMATCH: 422,
    ApiErrorId.ERR_SELF_APPROVAL: 403,
    ApiErrorId.ERR_SESSION_OVERLAP: 409,
    ApiErrorId.ERR_SUPERVISOR_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_SITE_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_HOURS_EXCEED_OUTSTANDING: 422,
    ApiErrorId.ERR_VERIFIED_HOURS_EXCEED_CLAIMED: 422,
    ApiErrorId.ERR_CHECKOUT_BEFORE_CHECKIN: 422,
    ApiErrorId.ERR_NO_REMAINING_HOURS: 409,
    ApiErrorId.ERR_STALE_REFERRAL_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
