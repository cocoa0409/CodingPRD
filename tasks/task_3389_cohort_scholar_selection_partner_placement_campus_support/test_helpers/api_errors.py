    ERR_COLLEGE_NOT_ACTIVE = "ERR_COLLEGE_NOT_ACTIVE"
    ERR_SCHOLAR_NOT_ELIGIBLE = "ERR_SCHOLAR_NOT_ELIGIBLE"
    # Nomination window (tier 9)
    ERR_NOMINATION_WINDOW_CLOSED = "ERR_NOMINATION_WINDOW_CLOSED"
    # Uniqueness / overlap / referential consistency (tier 10)
    ERR_DUPLICATE_EVALUATION = "ERR_DUPLICATE_EVALUATION"
