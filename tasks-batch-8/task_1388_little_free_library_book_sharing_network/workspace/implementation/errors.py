def raise_err(error_id: str, message: str) -> None:
    raise ApiError(error_id, HTTP_STATUS[error_id], message)


def raise_body_ref_err(error_id: str, message: str) -> None:
    """Body-referenced entities that do not resolve are rejected with HTTP 422
    carrying the matching (entity-specific) not-found error id (PRD §2.6)."""
    raise ApiError(error_id, 422, message)
