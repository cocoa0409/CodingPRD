"""Error IDs and HTTP status mapping (PRD §5).

Registered with the framework so validate_error() auto-checks status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Validation / Auth (PRD §5)
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_TEMPLATE_PERMISSION_DENIED = "ERR_TEMPLATE_PERMISSION_DENIED"

    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # State / OCC (409)
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_TEMPLATE_NOT_PUBLISHED = "ERR_TEMPLATE_NOT_PUBLISHED"
    ERR_PARTY_NOT_ACTIVE = "ERR_PARTY_NOT_ACTIVE"
    ERR_CONTRACT_EXPIRED = "ERR_CONTRACT_EXPIRED"
    ERR_DUPLICATE_REMINDER = "ERR_DUPLICATE_REMINDER"
    ERR_WORKFLOW_LOCKED = "ERR_WORKFLOW_LOCKED"
    ERR_REINITIATE_INVALID = "ERR_REINITIATE_INVALID"

    # Business rule violations (422)
    ERR_AUTH_FACTORS_INSUFFICIENT = "ERR_AUTH_FACTORS_INSUFFICIENT"
    ERR_DELEGATION_INVALID = "ERR_DELEGATION_INVALID"
    ERR_TIMESTAMP_HASH_MISMATCH = "ERR_TIMESTAMP_HASH_MISMATCH"
    ERR_TIMESTAMP_DRIFT_EXCEEDED = "ERR_TIMESTAMP_DRIFT_EXCEEDED"
    ERR_LEGAL_REP_REQUIRES_MFA = "ERR_LEGAL_REP_REQUIRES_MFA"
    ERR_NOTARY_REFERENCE_REQUIRED = "ERR_NOTARY_REFERENCE_REQUIRED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_VALIDATION_FAILED: 400,
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_TEMPLATE_PERMISSION_DENIED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_TEMPLATE_NOT_PUBLISHED: 409,
    ApiErrorId.ERR_PARTY_NOT_ACTIVE: 409,
    ApiErrorId.ERR_CONTRACT_EXPIRED: 409,
    ApiErrorId.ERR_DUPLICATE_REMINDER: 409,
    ApiErrorId.ERR_WORKFLOW_LOCKED: 409,
    ApiErrorId.ERR_REINITIATE_INVALID: 409,
    ApiErrorId.ERR_AUTH_FACTORS_INSUFFICIENT: 422,
    ApiErrorId.ERR_DELEGATION_INVALID: 422,
    ApiErrorId.ERR_TIMESTAMP_HASH_MISMATCH: 422,
    ApiErrorId.ERR_TIMESTAMP_DRIFT_EXCEEDED: 422,
    ApiErrorId.ERR_LEGAL_REP_REQUIRES_MFA: 422,
    ApiErrorId.ERR_NOTARY_REFERENCE_REQUIRED: 422,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
