"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_NOT_FOUND = "ERR_REFERENCED_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_PRIMARY = "ERR_DUPLICATE_PRIMARY"
    ERR_PLAN_AREA_MISMATCH = "ERR_PLAN_AREA_MISMATCH"
    ERR_SEP_WINDOW_CLOSED = "ERR_SEP_WINDOW_CLOSED"
    ERR_SEP_NOT_APPROVED = "ERR_SEP_NOT_APPROVED"
    ERR_NO_BENCHMARK_PLAN = "ERR_NO_BENCHMARK_PLAN"
    ERR_APTC_EXCEEDS_MAX = "ERR_APTC_EXCEEDS_MAX"
    ERR_OVERLAPPING_COVERAGE = "ERR_OVERLAPPING_COVERAGE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_PRIMARY: 409,
    ApiErrorId.ERR_PLAN_AREA_MISMATCH: 409,
    ApiErrorId.ERR_SEP_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_SEP_NOT_APPROVED: 409,
    ApiErrorId.ERR_NO_BENCHMARK_PLAN: 409,
    ApiErrorId.ERR_APTC_EXCEEDS_MAX: 409,
    ApiErrorId.ERR_OVERLAPPING_COVERAGE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
