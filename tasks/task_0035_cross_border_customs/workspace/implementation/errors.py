def raise_err(error_id: str, message: str = None):
    """Convenience: raise APIError using catalogued HTTP status."""
    status = ERROR_HTTP.get(error_id, 400)
    if message is None:
        message = error_id
    raise APIError(error_id, message, status)


def auth_missing(msg: str = "Missing or invalid X-User-ID / X-User-Role header"):
    return APIError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, msg, 400)


def forbidden(msg: str = "Role not authorized for this endpoint"):
    return APIError(ERR_FORBIDDEN_FOR_ROLE, msg, 403)


def not_found(msg: str = "Resource not found"):
    return APIError(ERR_NOT_FOUND, msg, 404)


def invalid_request(msg: str = "Invalid request body"):
    return APIError(ERR_INVALID_REQUEST, msg, 400)


def invalid_state(msg: str = "Operation not legal in current state"):
    return APIError(ERR_INVALID_STATE_TRANSITION, msg, 409)
