def missing_context():
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER,
                    "X-User-ID or X-User-Role header missing, or role not a declared role", 400)


def forbidden(msg="Role not permitted on this endpoint"):
    return ApiError(ERR_FORBIDDEN_ROLE, msg, 403)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, msg, 404)


def validation(msg="Request validation failed"):
    return ApiError(ERR_VALIDATION, msg, 400)
