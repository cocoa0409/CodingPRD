"""API error class and error-id constants."""
from __future__ import annotations


# --- Error IDs (verbatim from SCAFFOLD §1.6 / PRD §5) ---
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
ERR_APPLICATION_NOT_FOUND = "ERR_APPLICATION_NOT_FOUND"
ERR_APPLICANT_NOT_FOUND = "ERR_APPLICANT_NOT_FOUND"
ERR_SUBRESOURCE_NOT_FOUND = "ERR_SUBRESOURCE_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_VERSION = "ERR_STALE_VERSION"
ERR_UDAAP_BLOCKED = "ERR_UDAAP_BLOCKED"
ERR_TRID_WAITING_PERIOD = "ERR_TRID_WAITING_PERIOD"
ERR_DTI_FRONTEND_TOO_HIGH = "ERR_DTI_FRONTEND_TOO_HIGH"
ERR_EXTENSION_CAP_EXCEEDED = "ERR_EXTENSION_CAP_EXCEEDED"
ERR_INVALID_EXTEND_DAYS = "ERR_INVALID_EXTEND_DAYS"
ERR_LOCK_EXPIRED = "ERR_LOCK_EXPIRED"
ERR_LOCK_DURATION_CAP_EXCEEDED = "ERR_LOCK_DURATION_CAP_EXCEEDED"
ERR_UDAAP_REASONS_INVALID = "ERR_UDAAP_REASONS_INVALID"
ERR_CD_REDISCLOSE_REQUIRED = "ERR_CD_REDISCLOSE_REQUIRED"
ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


_HTTP_FOR: dict[str, int] = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNAUTHORIZED: 403,
    ERR_APPLICATION_NOT_FOUND: 404,
    ERR_APPLICANT_NOT_FOUND: 404,
    ERR_SUBRESOURCE_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_STALE_VERSION: 412,
    ERR_UDAAP_BLOCKED: 422,
    ERR_TRID_WAITING_PERIOD: 422,
    ERR_DTI_FRONTEND_TOO_HIGH: 422,
    ERR_EXTENSION_CAP_EXCEEDED: 422,
    ERR_INVALID_EXTEND_DAYS: 422,
    ERR_LOCK_EXPIRED: 422,
    ERR_LOCK_DURATION_CAP_EXCEEDED: 422,
    ERR_UDAAP_REASONS_INVALID: 422,
    ERR_CD_REDISCLOSE_REQUIRED: 422,
    ERR_SOD_VIOLATION: 403,
    ERR_INVALID_REQUEST: 400,
}


class ApiError(Exception):
    def __init__(self, error_id: str, message: str, http_status: int | None = None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else _HTTP_FOR.get(error_id, 500)
