"""Error classes and error ID constants."""


class APIError(Exception):
    def __init__(self, error_id: str, message: str, http_status: int):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status


# Error catalog (id -> http_status)
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_REFERENCE = "ERR_INVALID_REFERENCE"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_IDENTITY_NOT_VERIFIED = "ERR_IDENTITY_NOT_VERIFIED"
ERR_BACKGROUND_CHECK_REQUIRED = "ERR_BACKGROUND_CHECK_REQUIRED"
ERR_SKILL_MISMATCH = "ERR_SKILL_MISMATCH"
ERR_RECRUITMENT_CLOSED = "ERR_RECRUITMENT_CLOSED"
ERR_TIME_CONFLICT = "ERR_TIME_CONFLICT"
ERR_DISTANCE_EXCEEDED = "ERR_DISTANCE_EXCEEDED"
ERR_DUPLICATE_SKILL_DECLARATION = "ERR_DUPLICATE_SKILL_DECLARATION"
ERR_DUPLICATE_APPLICATION = "ERR_DUPLICATE_APPLICATION"
ERR_QUOTA_EXCEEDED = "ERR_QUOTA_EXCEEDED"
ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
ERR_INSUFFICIENT_POINTS = "ERR_INSUFFICIENT_POINTS"
ERR_NEGATIVE_HOURS = "ERR_NEGATIVE_HOURS"
ERR_NOT_ELIGIBLE = "ERR_NOT_ELIGIBLE"
ERR_CERTIFICATE_ALREADY_ISSUED = "ERR_CERTIFICATE_ALREADY_ISSUED"
ERR_CHECK_IN_PROOF_FAILED = "ERR_CHECK_IN_PROOF_FAILED"
ERR_INVALID_INPUT = "ERR_INVALID_INPUT"
ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"


def err(error_id: str, message: str = "") -> APIError:
    """Construct an APIError with the appropriate HTTP status."""
    mapping = {
        ERR_UNAUTHENTICATED: 401,
        ERR_FORBIDDEN: 403,
        ERR_NOT_FOUND: 404,
        ERR_INVALID_REFERENCE: 422,
        ERR_INVALID_STATE: 409,
        ERR_IDENTITY_NOT_VERIFIED: 403,
        ERR_BACKGROUND_CHECK_REQUIRED: 403,
        ERR_SKILL_MISMATCH: 422,
        ERR_RECRUITMENT_CLOSED: 409,
        ERR_TIME_CONFLICT: 409,
        ERR_DISTANCE_EXCEEDED: 422,
        ERR_DUPLICATE_SKILL_DECLARATION: 409,
        ERR_DUPLICATE_APPLICATION: 409,
        ERR_QUOTA_EXCEEDED: 409,
        ERR_INSUFFICIENT_STOCK: 409,
        ERR_INSUFFICIENT_POINTS: 409,
        ERR_NEGATIVE_HOURS: 422,
        ERR_NOT_ELIGIBLE: 422,
        ERR_CERTIFICATE_ALREADY_ISSUED: 409,
        ERR_CHECK_IN_PROOF_FAILED: 422,
        ERR_INVALID_INPUT: 422,
        ERR_VERSION_CONFLICT: 409,
    }
    return APIError(error_id, message or error_id, mapping[error_id])
