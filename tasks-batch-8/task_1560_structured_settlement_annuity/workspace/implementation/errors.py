def err(error_id, http_status, message):
    return ApiError(error_id, message, http_status)


def bad_request(error_id, message):
    return ApiError(error_id, message, 400)


def forbidden(error_id, message):
    return ApiError(error_id, message, 403)


def not_found(error_id, message):
    return ApiError(error_id, message, 404)


def conflict(error_id, message):
    return ApiError(error_id, message, 409)


def precondition(error_id, message):
    return ApiError(error_id, message, 412)


def unprocessable(error_id, message):
    return ApiError(error_id, message, 422)
