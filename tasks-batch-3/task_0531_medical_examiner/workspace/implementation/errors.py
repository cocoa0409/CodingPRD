"""Error catalog. Each entry maps error_id -> HTTP status (from PRD §5 / scaffold §1.6)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error IDs (exact names from scaffold §1.6 / PRD §5)
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
ERR_SEGREGATION_VIOLATION = "ERR_SEGREGATION_VIOLATION"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_CASE_DECLINED = "ERR_CASE_DECLINED"
ERR_MANNER_INCONSISTENT = "ERR_MANNER_INCONSISTENT"
ERR_AUTOPSY_INCOMPLETE = "ERR_AUTOPSY_INCOMPLETE"
ERR_EXAM_NOT_DUE = "ERR_EXAM_NOT_DUE"
ERR_COOLER_FULL = "ERR_COOLER_FULL"
ERR_COOLER_OUT_OF_SERVICE = "ERR_COOLER_OUT_OF_SERVICE"
ERR_PATHOLOGIST_DOUBLE_BOOKED = "ERR_PATHOLOGIST_DOUBLE_BOOKED"
ERR_RELEASE_BLOCKED = "ERR_RELEASE_BLOCKED"
ERR_KIN_UNVERIFIED = "ERR_KIN_UNVERIFIED"
