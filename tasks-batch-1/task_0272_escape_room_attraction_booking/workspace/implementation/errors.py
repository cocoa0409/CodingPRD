"""Error classes and error-id constants from the PRD error catalogue."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalogue (PRD §5)
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_STALE_SLOT_VERSION = ("ERR_STALE_SLOT_VERSION", 412)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_AGE_REQUIREMENT_NOT_MET = ("ERR_AGE_REQUIREMENT_NOT_MET", 409)
ERR_WAIVER_NOT_SIGNED = ("ERR_WAIVER_NOT_SIGNED", 409)
ERR_GROUP_SIZE_INVALID = ("ERR_GROUP_SIZE_INVALID", 409)
ERR_SLOT_OVERLAP = ("ERR_SLOT_OVERLAP", 409)
ERR_NO_GAMEMASTER_AVAILABLE = ("ERR_NO_GAMEMASTER_AVAILABLE", 409)
ERR_NO_SHOW_LIMIT_REACHED = ("ERR_NO_SHOW_LIMIT_REACHED", 409)
ERR_GIFT_CARD_UNUSABLE = ("ERR_GIFT_CARD_UNUSABLE", 409)
ERR_OUTSIDE_OPERATING_HOURS = ("ERR_OUTSIDE_OPERATING_HOURS", 409)
ERR_DUPLICATE_RESOURCE = ("ERR_DUPLICATE_RESOURCE", 409)
ERR_ROOM_RETIRED = ("ERR_ROOM_RETIRED", 409)
ERR_VALIDATION_PAGINATION = ("ERR_VALIDATION_PAGINATION", 422)


def err(spec, message=None):
    return ApiError(spec[0], spec[1], message)
