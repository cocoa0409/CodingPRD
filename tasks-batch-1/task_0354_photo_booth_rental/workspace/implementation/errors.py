"""Error classes and error ID constants (PRD §5 error catalogue)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Error catalogue — PRD §5 / SCAFFOLD §1.6
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN = ("ERR_FORBIDDEN", 403)
ERR_NOT_BOOKING_OWNER = ("ERR_NOT_BOOKING_OWNER", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 422)
ERR_DUPLICATE_KEY = ("ERR_DUPLICATE_KEY", 409)
ERR_QTY_OUT_OF_RANGE = ("ERR_QTY_OUT_OF_RANGE", 422)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_BOOKING_LOCKED = ("ERR_BOOKING_LOCKED", 409)
ERR_STALE_VERSION = ("ERR_STALE_VERSION", 412)
ERR_BOOTH_INTERVAL_CONFLICT = ("ERR_BOOTH_INTERVAL_CONFLICT", 409)
ERR_NO_BOOTH_AVAILABLE = ("ERR_NO_BOOTH_AVAILABLE", 409)
ERR_ATTENDANT_INTERVAL_CONFLICT = ("ERR_ATTENDANT_INTERVAL_CONFLICT", 409)
ERR_NO_ATTENDANT_AVAILABLE = ("ERR_NO_ATTENDANT_AVAILABLE", 409)
ERR_DEPOSIT_AMOUNT_MISMATCH = ("ERR_DEPOSIT_AMOUNT_MISMATCH", 422)
ERR_BALANCE_AMOUNT_MISMATCH = ("ERR_BALANCE_AMOUNT_MISMATCH", 422)
ERR_REFUND_AMOUNT_MISMATCH = ("ERR_REFUND_AMOUNT_MISMATCH", 422)
ERR_GALLERY_EMPTY = ("ERR_GALLERY_EMPTY", 409)


def err(code_tuple, message=None):
    error_id, http_status = code_tuple
    return ApiError(error_id, http_status, message)
