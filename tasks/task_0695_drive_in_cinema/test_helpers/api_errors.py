"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SHOWTIME_CONFIG_INVALID = "ERR_SHOWTIME_CONFIG_INVALID"
    ERR_SHOWTIME_OVERLAP = "ERR_SHOWTIME_OVERLAP"
    ERR_RENTAL_CONFLICT = "ERR_RENTAL_CONFLICT"
    ERR_PASS_INVALID = "ERR_PASS_INVALID"
    ERR_PASS_EXHAUSTED = "ERR_PASS_EXHAUSTED"
    ERR_ITEM_UNAVAILABLE = "ERR_ITEM_UNAVAILABLE"
    ERR_LOT_FULL = "ERR_LOT_FULL"
    ERR_PERSON_CAPACITY_EXCEEDED = "ERR_PERSON_CAPACITY_EXCEEDED"
    ERR_NO_FM_CHANNEL = "ERR_NO_FM_CHANNEL"
    ERR_GATE_CODE_MISMATCH = "ERR_GATE_CODE_MISMATCH"
    ERR_CHECKIN_WINDOW_CLOSED = "ERR_CHECKIN_WINDOW_CLOSED"
    ERR_COMPLETE_TOO_EARLY = "ERR_COMPLETE_TOO_EARLY"
    ERR_SWEEP_TOO_EARLY = "ERR_SWEEP_TOO_EARLY"
    ERR_WEATHER_FEATURES_INVALID = "ERR_WEATHER_FEATURES_INVALID"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SHOWTIME_CONFIG_INVALID: 422,
    ApiErrorId.ERR_SHOWTIME_OVERLAP: 409,
    ApiErrorId.ERR_RENTAL_CONFLICT: 409,
    ApiErrorId.ERR_PASS_INVALID: 422,
    ApiErrorId.ERR_PASS_EXHAUSTED: 409,
    ApiErrorId.ERR_ITEM_UNAVAILABLE: 409,
    ApiErrorId.ERR_LOT_FULL: 409,
    ApiErrorId.ERR_PERSON_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_NO_FM_CHANNEL: 409,
    ApiErrorId.ERR_GATE_CODE_MISMATCH: 409,
    ApiErrorId.ERR_CHECKIN_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_COMPLETE_TOO_EARLY: 409,
    ApiErrorId.ERR_SWEEP_TOO_EARLY: 409,
    ApiErrorId.ERR_WEATHER_FEATURES_INVALID: 422,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
