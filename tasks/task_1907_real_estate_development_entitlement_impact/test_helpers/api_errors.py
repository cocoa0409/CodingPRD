    ERR_PROJECT_NOT_ACTIVE = "ERR_PROJECT_NOT_ACTIVE"
    ERR_APPLICATION_NOT_APPROVED = "ERR_APPLICATION_NOT_APPROVED"
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"
    # temporal
    ERR_TEMPORAL_WINDOW_VIOLATION = "ERR_TEMPORAL_WINDOW_VIOLATION"
    ERR_INSUFFICIENT_NOTICE = "ERR_INSUFFICIENT_NOTICE"
    ERR_HEARING_NOT_YET = "ERR_HEARING_NOT_YET"
    ERR_APPEAL_WINDOW_CLOSED = "ERR_APPEAL_WINDOW_CLOSED"
    ERR_REFERENDUM_WINDOW_CLOSED = "ERR_REFERENDUM_WINDOW_CLOSED"
    ERR_DECISION_DEADLINE_PASSED = "ERR_DECISION_DEADLINE_PASSED"
    ERR_VESTING_LAPSED = "ERR_VESTING_LAPSED"
    # referential
    ERR_REFERENTIAL_VIOLATION = "ERR_REFERENTIAL_VIOLATION"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_DISCIPLINE_MISMATCH = "ERR_DISCIPLINE_MISMATCH"
    ERR_REVISION_MISMATCH = "ERR_REVISION_MISMATCH"
