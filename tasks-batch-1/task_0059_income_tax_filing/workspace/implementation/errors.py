ERR_ALREADY_EFILED = ("ERR_ALREADY_EFILED", 409)
ERR_ORIGINAL_NOT_FILED = ("ERR_ORIGINAL_NOT_FILED", 409)
ERR_PAYMENT_PERIOD_OVERLAP = ("ERR_PAYMENT_PERIOD_OVERLAP", 409)
ERR_CORRECTION_WINDOW_OVERLAP = ("ERR_CORRECTION_WINDOW_OVERLAP", 409)


def err(spec, message=None):
    return ApiError(spec[0], spec[1], message)
