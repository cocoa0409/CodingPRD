"""Error IDs and HTTP status mapping — PRD §5.

The mapping is registered with the framework at import time so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    # Existence — PRD §2.4
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    # Schema — PRD §5
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"
    # Concurrency — PRD §2.5
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    # Duty-event ordering / state — PRD §3.3, §3.7
    ERR_DUTY_EVENT_OUT_OF_ORDER = "ERR_DUTY_EVENT_OUT_OF_ORDER"
    ERR_DRIVER_NOT_BOUND = "ERR_DRIVER_NOT_BOUND"
    ERR_LOG_ALREADY_CERTIFIED = "ERR_LOG_ALREADY_CERTIFIED"
    ERR_LOG_NOT_YET_CERTIFIABLE = "ERR_LOG_NOT_YET_CERTIFIABLE"
    ERR_EDIT_WINDOW_EXPIRED = "ERR_EDIT_WINDOW_EXPIRED"
    # Bind / unbind — PRD §3.2
    ERR_DRIVER_ALREADY_BOUND = "ERR_DRIVER_ALREADY_BOUND"
    ERR_VEHICLE_ALREADY_BOUND = "ERR_VEHICLE_ALREADY_BOUND"
    ERR_INVALID_DUTY_STATUS_FOR_BIND = "ERR_INVALID_DUTY_STATUS_FOR_BIND"
    ERR_CROSS_CARRIER_BIND = "ERR_CROSS_CARRIER_BIND"
    ERR_ELD_NOT_CERTIFIED = "ERR_ELD_NOT_CERTIFIED"
    # HOS limits — PRD §3.4, §3.5
    ERR_ELEVEN_HOUR_LIMIT_EXCEEDED = "ERR_ELEVEN_HOUR_LIMIT_EXCEEDED"
    ERR_FOURTEEN_HOUR_WINDOW_EXCEEDED = "ERR_FOURTEEN_HOUR_WINDOW_EXCEEDED"
    ERR_CYCLE_LIMIT_EXCEEDED = "ERR_CYCLE_LIMIT_EXCEEDED"
    ERR_INSUFFICIENT_REST = "ERR_INSUFFICIENT_REST"
    # Event-body validations — PRD §3.3, §3.6
    ERR_ANNOTATION_REQUIRED = "ERR_ANNOTATION_REQUIRED"
    ERR_VEHICLE_MISMATCH = "ERR_VEHICLE_MISMATCH"
    ERR_EXEMPTION_NOT_ACTIVE = "ERR_EXEMPTION_NOT_ACTIVE"
    ERR_ODOMETER_DECREASED = "ERR_ODOMETER_DECREASED"
    # Violation lifecycle — PRD §3.8
    ERR_INVALID_VIOLATION_STATE = "ERR_INVALID_VIOLATION_STATE"


# PRD §5 — Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_INPUT: 400,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DUTY_EVENT_OUT_OF_ORDER: 409,
    ApiErrorId.ERR_DRIVER_NOT_BOUND: 409,
    ApiErrorId.ERR_DRIVER_ALREADY_BOUND: 409,
    ApiErrorId.ERR_VEHICLE_ALREADY_BOUND: 409,
    ApiErrorId.ERR_INVALID_DUTY_STATUS_FOR_BIND: 409,
    ApiErrorId.ERR_CROSS_CARRIER_BIND: 422,
    ApiErrorId.ERR_ELD_NOT_CERTIFIED: 422,
    ApiErrorId.ERR_VEHICLE_MISMATCH: 422,
    ApiErrorId.ERR_ELEVEN_HOUR_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_FOURTEEN_HOUR_WINDOW_EXCEEDED: 409,
    ApiErrorId.ERR_CYCLE_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_REST: 409,
    ApiErrorId.ERR_ANNOTATION_REQUIRED: 422,
    ApiErrorId.ERR_EXEMPTION_NOT_ACTIVE: 422,
    ApiErrorId.ERR_ODOMETER_DECREASED: 422,
    ApiErrorId.ERR_LOG_ALREADY_CERTIFIED: 409,
    ApiErrorId.ERR_LOG_NOT_YET_CERTIFIABLE: 422,
    ApiErrorId.ERR_EDIT_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_INVALID_VIOLATION_STATE: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
