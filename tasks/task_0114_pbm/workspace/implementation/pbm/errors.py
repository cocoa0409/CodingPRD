ERR_FORBIDDEN = "ERR_FORBIDDEN"
ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
ERR_MEMBER_NOT_ACTIVE = "ERR_MEMBER_NOT_ACTIVE"
ERR_PA_REQUIRED = "ERR_PA_REQUIRED"
ERR_PA_DENIED = "ERR_PA_DENIED"
ERR_PA_REVOKED = "ERR_PA_REVOKED"
ERR_PA_EXPIRED = "ERR_PA_EXPIRED"
ERR_PA_MISMATCH = "ERR_PA_MISMATCH"
ERR_PA_REVISION_LIMIT = "ERR_PA_REVISION_LIMIT"
ERR_STEP_THERAPY_NOT_SATISFIED = "ERR_STEP_THERAPY_NOT_SATISFIED"
ERR_SPECIALTY_CHANNEL_REQUIRED = "ERR_SPECIALTY_CHANNEL_REQUIRED"
ERR_CHANNEL_DAYS_SUPPLY_MISMATCH = "ERR_CHANNEL_DAYS_SUPPLY_MISMATCH"
ERR_REFILL_TOO_SOON = "ERR_REFILL_TOO_SOON"
ERR_DRUG_NOT_ON_FORMULARY = "ERR_DRUG_NOT_ON_FORMULARY"
ERR_COPAY_CARD_MISMATCH = "ERR_COPAY_CARD_MISMATCH"
ERR_COPAY_CARD_EXHAUSTED = "ERR_COPAY_CARD_EXHAUSTED"
ERR_CLAWBACK_WINDOW_EXPIRED = "ERR_CLAWBACK_WINDOW_EXPIRED"
ERR_OOP_BELOW_DEDUCTIBLE = "ERR_OOP_BELOW_DEDUCTIBLE"
ERR_VALIDATION = "ERR_VALIDATION"


ERROR_HTTP = {
    ERR_UNAUTHENTICATED: 401,
    ERR_FORBIDDEN: 403,
    ERR_RESOURCE_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_VERSION_CONFLICT: 409,
    ERR_MEMBER_NOT_ACTIVE: 409,
    ERR_PA_REQUIRED: 422,
    ERR_PA_DENIED: 422,
    ERR_PA_REVOKED: 422,
    ERR_PA_EXPIRED: 422,
    ERR_PA_MISMATCH: 422,
    ERR_PA_REVISION_LIMIT: 422,
    ERR_STEP_THERAPY_NOT_SATISFIED: 422,
    ERR_SPECIALTY_CHANNEL_REQUIRED: 422,
    ERR_CHANNEL_DAYS_SUPPLY_MISMATCH: 422,
    ERR_REFILL_TOO_SOON: 409,
    ERR_DRUG_NOT_ON_FORMULARY: 422,
    ERR_COPAY_CARD_MISMATCH: 422,
    ERR_COPAY_CARD_EXHAUSTED: 409,
    ERR_CLAWBACK_WINDOW_EXPIRED: 422,
    ERR_OOP_BELOW_DEDUCTIBLE: 422,
    ERR_VALIDATION: 422,
}


class APIError(Exception):
    """Domain error carrying a stable error_id and HTTP status."""

    def __init__(self, error_id: str, message: str, http_status: Optional[int] = None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status if http_status is not None else ERROR_HTTP.get(error_id, 422)


def api_error(error_id: str, message: str) -> APIError:
    return APIError(error_id, message, ERROR_HTTP.get(error_id, 422))
