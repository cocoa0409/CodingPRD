"""Error classes and error-ID constants (PRD §5 error catalogue)."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message):
        super().__init__(message)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message


ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
ERR_INVALID_STATE = "ERR_INVALID_STATE"
ERR_STALE_PROJECT_VERSION = "ERR_STALE_PROJECT_VERSION"
ERR_SAFETY_LEVEL_INSUFFICIENT = "ERR_SAFETY_LEVEL_INSUFFICIENT"
ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
ERR_PAYLOAD_CHECK_FAILED = "ERR_PAYLOAD_CHECK_FAILED"
ERR_BRAND_OUT_OF_SCOPE = "ERR_BRAND_OUT_OF_SCOPE"
ERR_OUTSIDE_SESSION_WINDOW = "ERR_OUTSIDE_SESSION_WINDOW"
ERR_GUARANTEE_WINDOW_VIOLATION = "ERR_GUARANTEE_WINDOW_VIOLATION"
ERR_TRAINER_SCHEDULE_CONFLICT = "ERR_TRAINER_SCHEDULE_CONFLICT"
ERR_SUPERSEDE_TARGET_INVALID = "ERR_SUPERSEDE_TARGET_INVALID"
ERR_DUPLICATE_CODE = "ERR_DUPLICATE_CODE"
ERR_RETENTION_OVERRELEASE = "ERR_RETENTION_OVERRELEASE"
ERR_RETENTION_BALANCE_MISMATCH = "ERR_RETENTION_BALANCE_MISMATCH"
ERR_MAINTENANCE_WINDOW_INVALID = "ERR_MAINTENANCE_WINDOW_INVALID"
ERR_GATE_PRECONDITION_UNMET = "ERR_GATE_PRECONDITION_UNMET"


def bad_request(message):
    return ApiError(ERR_INVALID_REQUEST, 400, message)


def not_found(message="Resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, message)


def invalid_state(message):
    return ApiError(ERR_INVALID_STATE, 409, message)


def unprocessable(error_id, message):
    return ApiError(error_id, 422, message)
