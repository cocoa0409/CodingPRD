def not_found(msg="The referenced resource does not exist."):
    return ApiError(ERR_NOT_FOUND, msg)


def invalid_state(msg="The resource is not in the state this operation requires."):
    return ApiError(ERR_INVALID_STATE, msg)


def forbidden(msg="The acting role is not permitted to perform this operation."):
    return ApiError(ERR_FORBIDDEN, msg)


def invalid_request(msg="The request body is malformed or carries an unknown value."):
    return ApiError(ERR_INVALID_REQUEST, msg)