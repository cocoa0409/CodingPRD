"""
Test helpers for the Long-Term Acute Care Hospital admission and length-of-stay API.

A test file needs one import line:

    from test_helpers import (
        api_client, factories, fixtures, ApiErrorId, UserRole,
        validate_success, validate_error, get_success_data,
    )

Everything the suite uses is re-exported here — the framework primitives from
`prd_bench_local_runner.testing` alongside this package's own clients, factories,
scenario builders, assertions, constants and identities — so no test file has to know
which module a helper lives in.

Importing this package also registers the specification's error-id-to-HTTP-status map with
the framework, which is what lets `validate_error(response, ApiErrorId.ERR_INVALID_STATE)`
check the status code without the test restating 409.
"""

