"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CIRCLE_FROZEN = "ERR_CIRCLE_FROZEN"
    ERR_CIRCLE_RESTRICTED = "ERR_CIRCLE_RESTRICTED"
    ERR_WELLNESS_EXPIRED = "ERR_WELLNESS_EXPIRED"
    ERR_DISPATCH_ALREADY_STAGED = "ERR_DISPATCH_ALREADY_STAGED"
    ERR_TRIP_NOT_OPEN = "ERR_TRIP_NOT_OPEN"
    ERR_CONSENT_NOT_GRANTED = "ERR_CONSENT_NOT_GRANTED"
    ERR_MINOR_CONSENT_LOCKED = "ERR_MINOR_CONSENT_LOCKED"
    ERR_PRIVACY_SELF_ONLY = "ERR_PRIVACY_SELF_ONLY"
    ERR_PLACE_CONFIG_INVALID = "ERR_PLACE_CONFIG_INVALID"
    ERR_FIX_CLOCK_SKEW = "ERR_FIX_CLOCK_SKEW"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_ROLE_INCOMPATIBLE = "ERR_ROLE_INCOMPATIBLE"
    ERR_PLACE_OVERLAP = "ERR_PLACE_OVERLAP"
    ERR_ASSISTANCE_UNITS_EXHAUSTED = "ERR_ASSISTANCE_UNITS_EXHAUSTED"
    ERR_NO_IDENTITY_CREDIT = "ERR_NO_IDENTITY_CREDIT"
    ERR_CRASH_BELOW_THRESHOLD = "ERR_CRASH_BELOW_THRESHOLD"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CIRCLE_FROZEN: 409,
    ApiErrorId.ERR_CIRCLE_RESTRICTED: 409,
    ApiErrorId.ERR_WELLNESS_EXPIRED: 409,
    ApiErrorId.ERR_DISPATCH_ALREADY_STAGED: 409,
    ApiErrorId.ERR_TRIP_NOT_OPEN: 409,
    ApiErrorId.ERR_CONSENT_NOT_GRANTED: 409,
    ApiErrorId.ERR_MINOR_CONSENT_LOCKED: 403,
    ApiErrorId.ERR_PRIVACY_SELF_ONLY: 403,
    ApiErrorId.ERR_PLACE_CONFIG_INVALID: 422,
    ApiErrorId.ERR_FIX_CLOCK_SKEW: 422,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_ROLE_INCOMPATIBLE: 409,
    ApiErrorId.ERR_PLACE_OVERLAP: 409,
    ApiErrorId.ERR_ASSISTANCE_UNITS_EXHAUSTED: 402,
    ApiErrorId.ERR_NO_IDENTITY_CREDIT: 402,
    ApiErrorId.ERR_CRASH_BELOW_THRESHOLD: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
