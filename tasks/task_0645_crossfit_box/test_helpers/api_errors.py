"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_PLAN_SHAPE_INVALID = "ERR_PLAN_SHAPE_INVALID"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_MEMBERSHIP_NOT_OWNED = "ERR_MEMBERSHIP_NOT_OWNED"
    ERR_RESERVATION_SUSPENDED = "ERR_RESERVATION_SUSPENDED"
    ERR_FOUNDATIONS_NOT_COMPLETED = "ERR_FOUNDATIONS_NOT_COMPLETED"
    ERR_RESERVATION_WINDOW_CLOSED = "ERR_RESERVATION_WINDOW_CLOSED"
    ERR_DROP_IN_NOT_ALLOWED = "ERR_DROP_IN_NOT_ALLOWED"
    ERR_DUPLICATE_RESERVATION = "ERR_DUPLICATE_RESERVATION"
    ERR_SESSION_TIME_CONFLICT = "ERR_SESSION_TIME_CONFLICT"
    ERR_COACH_DOUBLE_BOOKED = "ERR_COACH_DOUBLE_BOOKED"
    ERR_NO_PUNCHES_REMAINING = "ERR_NO_PUNCHES_REMAINING"
    ERR_ROSTER_FULL = "ERR_ROSTER_FULL"
    ERR_COACH_NOT_CERTIFIED = "ERR_COACH_NOT_CERTIFIED"
    ERR_STALE_SESSION_VERSION = "ERR_STALE_SESSION_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_PLAN_SHAPE_INVALID: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_MEMBERSHIP_NOT_OWNED: 409,
    ApiErrorId.ERR_RESERVATION_SUSPENDED: 409,
    ApiErrorId.ERR_FOUNDATIONS_NOT_COMPLETED: 409,
    ApiErrorId.ERR_RESERVATION_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_DROP_IN_NOT_ALLOWED: 409,
    ApiErrorId.ERR_DUPLICATE_RESERVATION: 409,
    ApiErrorId.ERR_SESSION_TIME_CONFLICT: 409,
    ApiErrorId.ERR_COACH_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_NO_PUNCHES_REMAINING: 409,
    ApiErrorId.ERR_ROSTER_FULL: 409,
    ApiErrorId.ERR_COACH_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_STALE_SESSION_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
