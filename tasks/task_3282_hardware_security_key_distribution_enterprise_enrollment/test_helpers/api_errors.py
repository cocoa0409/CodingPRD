"""Error IDs and HTTP status mapping (PRD error catalogue)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DUPLICATE = "ERR_DUPLICATE"
    ERR_PHISHABLE_PATH_FORBIDDEN = "ERR_PHISHABLE_PATH_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_PROTOCOL_MISMATCH = "ERR_PROTOCOL_MISMATCH"
    ERR_GRANT_WINDOW = "ERR_GRANT_WINDOW"
    ERR_ORDER_STATE = "ERR_ORDER_STATE"
    ERR_INSUFFICIENT_CREDITS = "ERR_INSUFFICIENT_CREDITS"
    ERR_NO_ELIGIBLE_KEY = "ERR_NO_ELIGIBLE_KEY"
    ERR_EMPTY_FLEET = "ERR_EMPTY_FLEET"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DUPLICATE: 409,
    ApiErrorId.ERR_PHISHABLE_PATH_FORBIDDEN: 422,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 422,
    ApiErrorId.ERR_PROTOCOL_MISMATCH: 422,
    ApiErrorId.ERR_GRANT_WINDOW: 422,
    ApiErrorId.ERR_ORDER_STATE: 409,
    ApiErrorId.ERR_INSUFFICIENT_CREDITS: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_KEY: 422,
    ApiErrorId.ERR_EMPTY_FLEET: 422,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
