def bad_request(message):
    return ApiError(400, ERR_INVALID_REQUEST, message)


def not_found(message="resource not found"):
    return ApiError(404, ERR_RESOURCE_NOT_FOUND, message)


def invalid_state(message="transition not defined from current state"):
    return ApiError(409, ERR_INVALID_STATE, message)
