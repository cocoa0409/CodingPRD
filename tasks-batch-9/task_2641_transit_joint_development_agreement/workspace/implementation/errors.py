DEFAULT_MESSAGE = {
    "ERR_UNAUTHENTICATED": "Authentication headers are missing or invalid",
    "ERR_FORBIDDEN_ROLE": "Role may not perform this operation",
    "ERR_NOT_RESOURCE_OWNER": "Developer is not the owner of this resource",
    "ERR_SEGREGATION_OF_DUTIES": "The submitting operator may not also board-approve this agreement",
    "ERR_INVALID_REQUEST": "Request is not well formed",
}


class ApiError(Exception):
    def __init__(self, error_id, message=None):
        self.error_id = error_id
        self.http_status = ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGE.get(error_id, error_id)
        super().__init__(self.message)


def fail(error_id, message=None):
    raise ApiError(error_id, message)
