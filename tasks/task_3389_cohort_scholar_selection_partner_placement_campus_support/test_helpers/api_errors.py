    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    # State preconditions (PRD §2.7 tier 8)
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_NOMINEE_NOT_IN_ROUND = "ERR_NOMINEE_NOT_IN_ROUND"
    ERR_COHORT_NOT_FORMING = "ERR_COHORT_NOT_FORMING"
