def missing_context(msg="X-User-ID or X-User-Role header missing/invalid"):
    return ApiError(ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER, 400, msg)


def unauthorized_role(msg="Role not permitted for endpoint"):
    return ApiError(ERR_UNAUTHORIZED_ROLE, 403, msg)


def forbidden(msg="Entity-backed identity mismatch"):
    return ApiError(ERR_FORBIDDEN, 403, msg)


def not_found(msg="Referenced resource id does not exist or parent chain mismatched"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def invalid_request(msg="Missing required field, invalid enum value, or malformed input"):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)
