    ERR_PLAN_NOT_ACTIVE = "ERR_PLAN_NOT_ACTIVE"
    ERR_PLAN_NOT_DRAFT = "ERR_PLAN_NOT_DRAFT"
    ERR_PLAN_FROZEN = "ERR_PLAN_FROZEN"
    ERR_FREEZE_PRECONDITION_VIOLATED = "ERR_FREEZE_PRECONDITION_VIOLATED"

