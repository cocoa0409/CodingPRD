"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_MISSING_OR_INVALID_USER_CONTEXT = "ERR_MISSING_OR_INVALID_USER_CONTEXT"
    ERR_FORBIDDEN_FOR_ROLE = "ERR_FORBIDDEN_FOR_ROLE"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ORDER_NOT_DRAFT = "ERR_ORDER_NOT_DRAFT"
    ERR_PROOF_NOT_APPROVED = "ERR_PROOF_NOT_APPROVED"
    ERR_ORDER_EMPTY = "ERR_ORDER_EMPTY"
    ERR_BLANK_INSUFFICIENT = "ERR_BLANK_INSUFFICIENT"
    ERR_ORDER_NOT_CONFIRMED = "ERR_ORDER_NOT_CONFIRMED"
    ERR_PRESS_WINDOW_CONFLICT = "ERR_PRESS_WINDOW_CONFLICT"
    ERR_STATION_OVERSUBSCRIBED = "ERR_STATION_OVERSUBSCRIBED"
    ERR_INVALID_GOOD_UNITS = "ERR_INVALID_GOOD_UNITS"
    ERR_RUN_SHORT = "ERR_RUN_SHORT"
    ERR_ORDER_NOT_FULFILLED = "ERR_ORDER_NOT_FULFILLED"
    ERR_ALREADY_INVOICED = "ERR_ALREADY_INVOICED"
    ERR_NOT_INVOICED = "ERR_NOT_INVOICED"
    ERR_ORDER_NOT_CANCELLABLE = "ERR_ORDER_NOT_CANCELLABLE"
    ERR_INVALID_REORDER_SOURCE = "ERR_INVALID_REORDER_SOURCE"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_OR_INVALID_USER_CONTEXT: 400,
    ApiErrorId.ERR_FORBIDDEN_FOR_ROLE: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ORDER_NOT_DRAFT: 409,
    ApiErrorId.ERR_PROOF_NOT_APPROVED: 409,
    ApiErrorId.ERR_ORDER_EMPTY: 409,
    ApiErrorId.ERR_BLANK_INSUFFICIENT: 409,
    ApiErrorId.ERR_ORDER_NOT_CONFIRMED: 409,
    ApiErrorId.ERR_PRESS_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_STATION_OVERSUBSCRIBED: 409,
    ApiErrorId.ERR_INVALID_GOOD_UNITS: 400,
    ApiErrorId.ERR_RUN_SHORT: 409,
    ApiErrorId.ERR_ORDER_NOT_FULFILLED: 409,
    ApiErrorId.ERR_ALREADY_INVOICED: 409,
    ApiErrorId.ERR_NOT_INVOICED: 409,
    ApiErrorId.ERR_ORDER_NOT_CANCELLABLE: 409,
    ApiErrorId.ERR_INVALID_REORDER_SOURCE: 409,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
}

# Build a plain-string keyed map so validate_error() (which receives raw error_id
# strings from the API) can cross-check HTTP status by string identity.
_STRING_STATUS_MAP = {k.value: v for k, v in HTTP_STATUS_CODES.items()}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(_STRING_STATUS_MAP)
