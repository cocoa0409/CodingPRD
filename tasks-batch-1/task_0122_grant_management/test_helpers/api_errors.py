"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_AWARD_NOT_ACTIVE = "ERR_AWARD_NOT_ACTIVE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_AUDIT_UNRESOLVED = "ERR_AUDIT_UNRESOLVED"
    ERR_CLOSEOUT_PRECONDITIONS = "ERR_CLOSEOUT_PRECONDITIONS"
    ERR_ALLOCATION_MISMATCH = "ERR_ALLOCATION_MISMATCH"
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_CEILING_EXCEEDED = "ERR_CEILING_EXCEEDED"
    ERR_BUDGET_WOULD_EXCEED = "ERR_BUDGET_WOULD_EXCEED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE = "ERR_DUPLICATE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_AWARD_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_AUDIT_UNRESOLVED: 409,
    ApiErrorId.ERR_CLOSEOUT_PRECONDITIONS: 409,
    ApiErrorId.ERR_ALLOCATION_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_PERIOD: 422,
    ApiErrorId.ERR_CEILING_EXCEEDED: 409,
    ApiErrorId.ERR_BUDGET_WOULD_EXCEED: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_DUPLICATE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
