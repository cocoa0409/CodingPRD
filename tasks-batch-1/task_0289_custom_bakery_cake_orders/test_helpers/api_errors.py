"""Error IDs and HTTP status mapping (PRD Section 5).

After defining the mapping, register it with the framework so validate_error()
can auto-check HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_ORDER_OWNER = "ERR_NOT_ORDER_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
    ERR_DIETARY_CONFLICT = "ERR_DIETARY_CONFLICT"
    ERR_OPTION_NOT_ALLOWED = "ERR_OPTION_NOT_ALLOWED"
    ERR_LEAD_TIME_NOT_MET = "ERR_LEAD_TIME_NOT_MET"
    ERR_PAST_ORDER_CUTOFF = "ERR_PAST_ORDER_CUTOFF"
    ERR_ROUTE_WINDOW_CONFLICT = "ERR_ROUTE_WINDOW_CONFLICT"
    ERR_PROOF_NOT_APPROVED = "ERR_PROOF_NOT_APPROVED"
    ERR_PRODUCTION_DAY_FULL = "ERR_PRODUCTION_DAY_FULL"
    ERR_INSUFFICIENT_CREDIT = "ERR_INSUFFICIENT_CREDIT"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_LINE_IMMUTABLE = "ERR_LINE_IMMUTABLE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION_PAGINATION = "ERR_VALIDATION_PAGINATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_ORDER_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ORDER_VERSION: 412,
    ApiErrorId.ERR_DIETARY_CONFLICT: 422,
    ApiErrorId.ERR_OPTION_NOT_ALLOWED: 422,
    ApiErrorId.ERR_LEAD_TIME_NOT_MET: 422,
    ApiErrorId.ERR_PAST_ORDER_CUTOFF: 422,
    ApiErrorId.ERR_ROUTE_WINDOW_CONFLICT: 409,
    ApiErrorId.ERR_PROOF_NOT_APPROVED: 409,
    ApiErrorId.ERR_PRODUCTION_DAY_FULL: 409,
    ApiErrorId.ERR_INSUFFICIENT_CREDIT: 422,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_LINE_IMMUTABLE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION_PAGINATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
