"""Error IDs and HTTP status mapping (PRD §5).

Registers the mapping with the framework so validate_error() auto-checks
HTTP status codes.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_RESOURCE_NOT_AVAILABLE = "ERR_RESOURCE_NOT_AVAILABLE"
    ERR_CARD_NOT_ACTIVE = "ERR_CARD_NOT_ACTIVE"
    ERR_PATRON_BLOCKED = "ERR_PATRON_BLOCKED"
    ERR_RESERVATION_CONFLICT = "ERR_RESERVATION_CONFLICT"
    ERR_LIMIT_EXCEEDED = "ERR_LIMIT_EXCEEDED"
    ERR_NO_LICENSE_AVAILABLE = "ERR_NO_LICENSE_AVAILABLE"
    ERR_STALE_RESOURCE_VERSION = "ERR_STALE_RESOURCE_VERSION"
    ERR_TITLE_WITHDRAWN = "ERR_TITLE_WITHDRAWN"
    ERR_HOLD_NOT_READY = "ERR_HOLD_NOT_READY"
    ERR_PICKUP_EXPIRED = "ERR_PICKUP_EXPIRED"
    ERR_NOT_YET_DUE = "ERR_NOT_YET_DUE"
    ERR_RENEWAL_LIMIT = "ERR_RENEWAL_LIMIT"
    ERR_RENEWAL_BLOCKED_BY_HOLD = "ERR_RENEWAL_BLOCKED_BY_HOLD"
    ERR_VALIDATION_PARAM = "ERR_VALIDATION_PARAM"
    ERR_INVALID_ACTION = "ERR_INVALID_ACTION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_RESOURCE_NOT_AVAILABLE: 409,
    ApiErrorId.ERR_CARD_NOT_ACTIVE: 409,
    ApiErrorId.ERR_PATRON_BLOCKED: 409,
    ApiErrorId.ERR_RESERVATION_CONFLICT: 409,
    ApiErrorId.ERR_LIMIT_EXCEEDED: 409,
    ApiErrorId.ERR_NO_LICENSE_AVAILABLE: 409,
    ApiErrorId.ERR_STALE_RESOURCE_VERSION: 412,
    ApiErrorId.ERR_TITLE_WITHDRAWN: 409,
    ApiErrorId.ERR_HOLD_NOT_READY: 409,
    ApiErrorId.ERR_PICKUP_EXPIRED: 409,
    ApiErrorId.ERR_NOT_YET_DUE: 409,
    ApiErrorId.ERR_RENEWAL_LIMIT: 409,
    ApiErrorId.ERR_RENEWAL_BLOCKED_BY_HOLD: 409,
    ApiErrorId.ERR_VALIDATION_PARAM: 400,
    ApiErrorId.ERR_INVALID_ACTION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
