@bp.route("/fafsa/support-cases", methods=["POST"])
def create_case():
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["SchoolCoordinator"])
    body = validate.get_json_body(required=True)
    validate.check_fields(body, required=["senior_record_id", "case_type"], optional=["notes"])
    senior_record_id = validate.req_string(body, "senior_record_id")
    case_type = validate.req_enum(body, "case_type", core.CASE_TYPES)
    notes = validate.req_string(body, "notes", required=False) or ""

    senior = core.get_senior_or_404(senior_record_id)
    middleware.require_school_scope(auth, senior["school_id"])

    # One non-terminal case per (senior, case_type)
    for c in store.support_cases.values():
        if (
            c["senior_record_id"] == senior["id"]
            and c["case_type"] == case_type
            and c["status"] in core.NON_TERMINAL_CASE_STATUSES
        ):
            errors.raise_error(errors.ERR_CASE_ALREADY_OPEN, "A non-terminal case already exists for this (senior, case_type)")

    case = core.create_support_case(senior, case_type, notes)
    if case_type == "SPECIAL_CIRCUMSTANCE" and senior["dependency_status"] == "DEPENDENT":
        senior["dependency_status"] = "PENDING_REVIEW"
        touch(senior)
    return success_object(core.serialize(case), 201)


