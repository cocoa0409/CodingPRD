"""Error types and the complete error catalogue (PRD §5 / SCAFFOLD Table 6)."""


class ApiError(Exception):
    """API error carrying the §2.2 error-envelope fields."""

    def __init__(self, error_id, message, http_status=None):
        self.error_id = error_id
        self.message = message
        if http_status is None:
            http_status = ERROR_HTTP.get(error_id, 500)
        self.http_status = http_status
        super().__init__(f"{error_id}: {message}")


