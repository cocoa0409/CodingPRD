"""Test helpers for the retail media network API.

Four layers sit behind the test suite:

* `api_client` — one method per documented endpoint, with the business prefix applied
  and the two operational endpoints left unprefixed.
* `api_errors` — every documented error identifier as a constant, its canonical HTTP
  status, and the order in which competing refusals must be reported.
* `factories` — the smallest valid request payload per resource, with overrides.
* `fixtures` — composite builders that walk the approval ladder from an empty database
  up to whatever state a rule is stated against.
* `assertions` / `constants` / `test_users` — the PRD's arithmetic, its named figures,
  and the eight role header builders.

Importing this package re-exports the names a test needs, so a test file can do
`from test_helpers import api_client, NETWORK_ADMIN, build_delivering_world`.
"""

