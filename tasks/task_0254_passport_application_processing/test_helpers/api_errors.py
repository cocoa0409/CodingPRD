"""Error IDs and HTTP status mapping (PRD Section 5).

Registers the error_id -> HTTP status map with the framework so validate_error()
auto-checks the HTTP status code whenever an error_id is asserted.
"""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ALREADY_TERMINAL = "ERR_ALREADY_TERMINAL"
    ERR_SOD_VIOLATION = "ERR_SOD_VIOLATION"
    ERR_PHOTO_INVALID = "ERR_PHOTO_INVALID"
    ERR_GUARDIAN_CONSENT_REQUIRED = "ERR_GUARDIAN_CONSENT_REQUIRED"
    ERR_NAME_CHANGE_EVIDENCE_REQUIRED = "ERR_NAME_CHANGE_EVIDENCE_REQUIRED"
    ERR_FACILITY_SLOT_CONFLICT = "ERR_FACILITY_SLOT_CONFLICT"
    ERR_COUNTER_SLOT_CONFLICT = "ERR_COUNTER_SLOT_CONFLICT"
    ERR_INVALID_INTERVAL = "ERR_INVALID_INTERVAL"
    ERR_DUPLICATE_URGENT_APPOINTMENT = "ERR_DUPLICATE_URGENT_APPOINTMENT"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_FEE_UNPAID = "ERR_FEE_UNPAID"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ALREADY_TERMINAL: 409,
    ApiErrorId.ERR_SOD_VIOLATION: 403,
    ApiErrorId.ERR_PHOTO_INVALID: 422,
    ApiErrorId.ERR_GUARDIAN_CONSENT_REQUIRED: 422,
    ApiErrorId.ERR_NAME_CHANGE_EVIDENCE_REQUIRED: 422,
    ApiErrorId.ERR_FACILITY_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_COUNTER_SLOT_CONFLICT: 409,
    ApiErrorId.ERR_INVALID_INTERVAL: 422,
    ApiErrorId.ERR_DUPLICATE_URGENT_APPOINTMENT: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_FEE_UNPAID: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
