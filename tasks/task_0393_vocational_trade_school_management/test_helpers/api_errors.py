    ERR_AID_OVER_AWARD = "ERR_AID_OVER_AWARD"
    ERR_AGREEMENT_NOT_WITHDRAWN = "ERR_AGREEMENT_NOT_WITHDRAWN"
    ERR_REFUND_ALREADY_SETTLED = "ERR_REFUND_ALREADY_SETTLED"
    # externship
    ERR_SITE_SUSPENDED = "ERR_SITE_SUSPENDED"
    ERR_EXTERNSHIP_WINDOW_CONFLICT = "ERR_EXTERNSHIP_WINDOW_CONFLICT"
    ERR_SITE_CAPACITY_EXCEEDED = "ERR_SITE_CAPACITY_EXCEEDED"
    ERR_EXTERNSHIP_NOT_STARTED = "ERR_EXTERNSHIP_NOT_STARTED"


