"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_PLAYER_SELF_EXCLUDED = "ERR_PLAYER_SELF_EXCLUDED"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_ANNUITY_NOT_ALLOWED = "ERR_ANNUITY_NOT_ALLOWED"
    ERR_ID_VERIFICATION_REQUIRED = "ERR_ID_VERIFICATION_REQUIRED"
    ERR_CLAIM_WINDOW_EXPIRED = "ERR_CLAIM_WINDOW_EXPIRED"
    ERR_ENTRY_NOT_ELIGIBLE = "ERR_ENTRY_NOT_ELIGIBLE"
    ERR_DRAWING_NOT_CLOSED = "ERR_DRAWING_NOT_CLOSED"
    ERR_EMPTY_DRAWING_POOL = "ERR_EMPTY_DRAWING_POOL"
    ERR_RETAILER_NOT_LICENSED = "ERR_RETAILER_NOT_LICENSED"
    ERR_TERMINAL_NOT_ACTIVE = "ERR_TERMINAL_NOT_ACTIVE"
    ERR_TICKET_NOT_CLAIMABLE = "ERR_TICKET_NOT_CLAIMABLE"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_REINSTATE_TOO_EARLY = "ERR_REINSTATE_TOO_EARLY"
    ERR_VALIDATION_FILTER_INVALID = "ERR_VALIDATION_FILTER_INVALID"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_PLAYER_SELF_EXCLUDED: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 409,
    ApiErrorId.ERR_ANNUITY_NOT_ALLOWED: 422,
    ApiErrorId.ERR_ID_VERIFICATION_REQUIRED: 422,
    ApiErrorId.ERR_CLAIM_WINDOW_EXPIRED: 409,
    ApiErrorId.ERR_ENTRY_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_DRAWING_NOT_CLOSED: 409,
    ApiErrorId.ERR_EMPTY_DRAWING_POOL: 409,
    ApiErrorId.ERR_RETAILER_NOT_LICENSED: 409,
    ApiErrorId.ERR_TERMINAL_NOT_ACTIVE: 409,
    ApiErrorId.ERR_TICKET_NOT_CLAIMABLE: 409,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_REINSTATE_TOO_EARLY: 409,
    ApiErrorId.ERR_VALIDATION_FILTER_INVALID: 422,
}

# Build a plain str->int map (enum members are str subclasses, but register
# the raw string keys so validate_error()'s lookup by actual_error_id matches).
_STR_STATUS_MAP = {k.value: v for k, v in HTTP_STATUS_CODES.items()}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(_STR_STATUS_MAP)
