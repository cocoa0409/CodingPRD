"""Error IDs and HTTP status mapping (PRD Section 5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_DUE_DATE_INFEASIBLE = "ERR_DUE_DATE_INFEASIBLE"
    ERR_PRODUCT_INACTIVE = "ERR_PRODUCT_INACTIVE"
    ERR_PROOF_NOT_APPROVED = "ERR_PROOF_NOT_APPROVED"
    ERR_PROMO_INVALID = "ERR_PROMO_INVALID"
    ERR_PROMO_MIN_NOT_MET = "ERR_PROMO_MIN_NOT_MET"
    ERR_COMPONENT_SHORTAGE = "ERR_COMPONENT_SHORTAGE"
    ERR_DEPOSIT_REQUIRED = "ERR_DEPOSIT_REQUIRED"
    ERR_BALANCE_DUE = "ERR_BALANCE_DUE"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"
    ERR_SHIP_WEIGHT_REQUIRED = "ERR_SHIP_WEIGHT_REQUIRED"
    ERR_DUPLICATE_VALUE = "ERR_DUPLICATE_VALUE"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_DUE_DATE_INFEASIBLE: 422,
    ApiErrorId.ERR_PRODUCT_INACTIVE: 409,
    ApiErrorId.ERR_PROOF_NOT_APPROVED: 409,
    ApiErrorId.ERR_PROMO_INVALID: 409,
    ApiErrorId.ERR_PROMO_MIN_NOT_MET: 422,
    ApiErrorId.ERR_COMPONENT_SHORTAGE: 409,
    ApiErrorId.ERR_DEPOSIT_REQUIRED: 409,
    ApiErrorId.ERR_BALANCE_DUE: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 422,
    ApiErrorId.ERR_SHIP_WEIGHT_REQUIRED: 422,
    ApiErrorId.ERR_DUPLICATE_VALUE: 409,
    ApiErrorId.ERR_VALIDATION: 422,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
