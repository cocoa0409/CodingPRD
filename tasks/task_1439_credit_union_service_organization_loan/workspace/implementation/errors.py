def raise_err(pair, message):
    raise APIError(pair[0], pair[1], message)


def not_found(what="Resource"):
    raise_err(ERR_NOT_FOUND, "%s not found" % what)


def invalid_request(message):
    raise_err(ERR_INVALID_REQUEST, message)


def invalid_state(message):
    raise_err(ERR_INVALID_STATE, message)
