"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_LICENSE_INSUFFICIENT = "ERR_LICENSE_INSUFFICIENT"
    ERR_TECH_NOT_ON_CALL = "ERR_TECH_NOT_ON_CALL"
    ERR_ZONE_MISMATCH = "ERR_ZONE_MISMATCH"
    ERR_TECH_DOUBLE_BOOKED = "ERR_TECH_DOUBLE_BOOKED"
    ERR_PERMIT_NOT_PASSED = "ERR_PERMIT_NOT_PASSED"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_ALREADY_INVOICED = "ERR_ALREADY_INVOICED"
    ERR_OPEN_CALLBACK = "ERR_OPEN_CALLBACK"
    ERR_NOT_WARRANTY_COVERED = "ERR_NOT_WARRANTY_COVERED"
    ERR_DUPLICATE = "ERR_DUPLICATE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_LICENSE_INSUFFICIENT: 409,
    ApiErrorId.ERR_TECH_NOT_ON_CALL: 409,
    ApiErrorId.ERR_ZONE_MISMATCH: 409,
    ApiErrorId.ERR_TECH_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_PERMIT_NOT_PASSED: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_ALREADY_INVOICED: 409,
    ApiErrorId.ERR_OPEN_CALLBACK: 409,
    ApiErrorId.ERR_NOT_WARRANTY_COVERED: 409,
    ApiErrorId.ERR_DUPLICATE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
