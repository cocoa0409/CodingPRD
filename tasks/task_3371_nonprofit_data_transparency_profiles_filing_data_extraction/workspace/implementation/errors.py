"""Error catalogue for the nonprofit data transparency API.

Every error id declared in PRD section 5 / SCAFFOLD section 1.6 is registered
here together with its HTTP status.  Handlers raise :class:`ApiError` and the
application-level handler renders the standard error envelope.
"""


class ApiError(Exception):
    """Carries the machine-readable error id, the HTTP status and a message."""

    def __init__(self, error_id, message, http_status=None):
        super().__init__(message)
        self.error_id = error_id
        self.message = message
        self.http_status = http_status or STATUS_BY_ERROR.get(error_id, 400)


