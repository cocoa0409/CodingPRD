    # Auth (PRD section 2.8 steps 1-2, 5)
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    # Schema
    ERR_VALIDATION_FAILED = "ERR_VALIDATION_FAILED"
    # Existence (404 family)
    ERR_CHARGE_NOT_FOUND = "ERR_CHARGE_NOT_FOUND"
    ERR_EMPLOYER_NOT_FOUND = "ERR_EMPLOYER_NOT_FOUND"
    ERR_COMPLAINANT_NOT_FOUND = "ERR_COMPLAINANT_NOT_FOUND"
    ERR_MEDIATION_CASE_NOT_FOUND = "ERR_MEDIATION_CASE_NOT_FOUND"
    ERR_INVESTIGATION_CASE_NOT_FOUND = "ERR_INVESTIGATION_CASE_NOT_FOUND"
    ERR_EVIDENCE_REQUEST_NOT_FOUND = "ERR_EVIDENCE_REQUEST_NOT_FOUND"
    ERR_DETERMINATION_NOT_FOUND = "ERR_DETERMINATION_NOT_FOUND"
    ERR_CONCILIATION_NOT_FOUND = "ERR_CONCILIATION_NOT_FOUND"
    ERR_SYSTEMIC_CASE_NOT_FOUND = "ERR_SYSTEMIC_CASE_NOT_FOUND"
    # State preconditions
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CHARGE_ALREADY_CLOSED = "ERR_CHARGE_ALREADY_CLOSED"
    ERR_CONCILIATION_ACTIVE = "ERR_CONCILIATION_ACTIVE"
    # Confidentiality / segregation of duties
    ERR_CONFIDENTIALITY_SEALED = "ERR_CONFIDENTIALITY_SEALED"
    ERR_DISCLOSURE_FORBIDDEN = "ERR_DISCLOSURE_FORBIDDEN"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    # Business constraints
    ERR_DUPLICATE_AGENCY_STATE = "ERR_DUPLICATE_AGENCY_STATE"
    ERR_SESSION_OVERLAP = "ERR_SESSION_OVERLAP"
    ERR_INTERVIEW_BUFFER_CONFLICT = "ERR_INTERVIEW_BUFFER_CONFLICT"
    ERR_MEDIATION_ROUND_EXHAUSTED = "ERR_MEDIATION_ROUND_EXHAUSTED"
    ERR_DETERMINATION_EXISTS = "ERR_DETERMINATION_EXISTS"
    ERR_OFFER_OUT_OF_TURN = "ERR_OFFER_OUT_OF_TURN"
    # Business-temporal
    ERR_RTS_PREMATURE = "ERR_RTS_PREMATURE"
    ERR_VACATE_WINDOW_EXPIRED = "ERR_VACATE_WINDOW_EXPIRED"
    ERR_SESSION_IN_PAST = "ERR_SESSION_IN_PAST"
    ERR_INCIDENT_DATE_FUTURE = "ERR_INCIDENT_DATE_FUTURE"
    # Optimistic concurrency
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


