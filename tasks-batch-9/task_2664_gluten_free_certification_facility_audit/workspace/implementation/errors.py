"""Error catalogue: error_id -> HTTP status, plus the ApiError exception."""


class ApiError(Exception):
    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message if message is not None else DEFAULT_MESSAGES.get(
            error_id, error_id
        )
        self.http_status = (
            http_status if http_status is not None else ERROR_STATUS.get(error_id, 400)
        )


