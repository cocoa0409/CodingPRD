    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REF_NOT_FOUND = "ERR_REF_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_TRIAGE_EMERGENCY_ROUTED = "ERR_TRIAGE_EMERGENCY_ROUTED"
    ERR_NO_DOCTOR_AVAILABLE = "ERR_NO_DOCTOR_AVAILABLE"
    ERR_PREFERRED_DOCTOR_INELIGIBLE = "ERR_PREFERRED_DOCTOR_INELIGIBLE"
    ERR_DOCTOR_AT_CAPACITY = "ERR_DOCTOR_AT_CAPACITY"
    ERR_DOCTOR_SLOT_OVERLAP = "ERR_DOCTOR_SLOT_OVERLAP"
