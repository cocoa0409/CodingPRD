"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_RETURN_NOT_FOUND = "ERR_RETURN_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_DUPLICATE_CHILD = "ERR_DUPLICATE_CHILD"
    ERR_NO_INCOME_DOCUMENTS = "ERR_NO_INCOME_DOCUMENTS"
    ERR_ITEMIZED_REQUIRES_SCHEDULE_A = "ERR_ITEMIZED_REQUIRES_SCHEDULE_A"
    ERR_RETURN_NOT_COMPUTED = "ERR_RETURN_NOT_COMPUTED"
    ERR_STALE_RETURN_VERSION = "ERR_STALE_RETURN_VERSION"
    ERR_ALREADY_EFILED = "ERR_ALREADY_EFILED"
    ERR_ORIGINAL_NOT_FILED = "ERR_ORIGINAL_NOT_FILED"
    ERR_PAYMENT_PERIOD_OVERLAP = "ERR_PAYMENT_PERIOD_OVERLAP"
    ERR_CORRECTION_WINDOW_OVERLAP = "ERR_CORRECTION_WINDOW_OVERLAP"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_RETURN_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_DUPLICATE_CHILD: 409,
    ApiErrorId.ERR_NO_INCOME_DOCUMENTS: 409,
    ApiErrorId.ERR_ITEMIZED_REQUIRES_SCHEDULE_A: 409,
    ApiErrorId.ERR_RETURN_NOT_COMPUTED: 409,
    ApiErrorId.ERR_STALE_RETURN_VERSION: 412,
    ApiErrorId.ERR_ALREADY_EFILED: 409,
    ApiErrorId.ERR_ORIGINAL_NOT_FILED: 409,
    ApiErrorId.ERR_PAYMENT_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_CORRECTION_WINDOW_OVERLAP: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
