    # --- State / OCC / pinning (PRD §2.5, §2.7) ---
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_PIN_STALE = "ERR_PIN_STALE"
    ERR_CORE_ENTERPRISE_NOT_APPROVED = "ERR_CORE_ENTERPRISE_NOT_APPROVED"
    ERR_CORE_ENTERPRISE_SUSPENDED = "ERR_CORE_ENTERPRISE_SUSPENDED"
