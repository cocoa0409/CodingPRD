class ApiError(Exception):
    """Raised anywhere in the request pipeline; rendered by the app handler."""

    def __init__(self, error_id, message=None, http_status=None):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.message = message or error_id
        self.http_status = http_status or ERROR_HTTP_STATUS.get(error_id, 400)


def api_error(error_id, message=None):
    return ApiError(error_id, message)
