"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping it is registered with the framework so validate_error()
auto-checks the HTTP status code for each error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REDEMPTION = "ERR_INVALID_REDEMPTION"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CARD_RISK_FROZEN = "ERR_CARD_RISK_FROZEN"
    ERR_CARD_RISK_REVIEW = "ERR_CARD_RISK_REVIEW"
    ERR_CARD_ALREADY_REPLACED = "ERR_CARD_ALREADY_REPLACED"
    ERR_EXPIRATION_NOT_ALLOWED = "ERR_EXPIRATION_NOT_ALLOWED"
    ERR_DORMANCY_NOT_DUE = "ERR_DORMANCY_NOT_DUE"
    ERR_WAIVER_OVERLAP = "ERR_WAIVER_OVERLAP"
    ERR_CAMPAIGN_OVERLAP = "ERR_CAMPAIGN_OVERLAP"
    ERR_RELOAD_BELOW_MIN = "ERR_RELOAD_BELOW_MIN"
    ERR_BALANCE_CAP_EXCEEDED = "ERR_BALANCE_CAP_EXCEEDED"
    ERR_INSUFFICIENT_BALANCE = "ERR_INSUFFICIENT_BALANCE"
    ERR_REFUND_EXCEEDS_REDEMPTION = "ERR_REFUND_EXCEEDS_REDEMPTION"
    ERR_NOT_CORPORATE_BUYER = "ERR_NOT_CORPORATE_BUYER"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_REDEMPTION: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CARD_RISK_FROZEN: 409,
    ApiErrorId.ERR_CARD_RISK_REVIEW: 409,
    ApiErrorId.ERR_CARD_ALREADY_REPLACED: 409,
    ApiErrorId.ERR_EXPIRATION_NOT_ALLOWED: 409,
    ApiErrorId.ERR_DORMANCY_NOT_DUE: 409,
    ApiErrorId.ERR_WAIVER_OVERLAP: 409,
    ApiErrorId.ERR_CAMPAIGN_OVERLAP: 409,
    ApiErrorId.ERR_RELOAD_BELOW_MIN: 409,
    ApiErrorId.ERR_BALANCE_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_INSUFFICIENT_BALANCE: 409,
    ApiErrorId.ERR_REFUND_EXCEEDS_REDEMPTION: 409,
    ApiErrorId.ERR_NOT_CORPORATE_BUYER: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
