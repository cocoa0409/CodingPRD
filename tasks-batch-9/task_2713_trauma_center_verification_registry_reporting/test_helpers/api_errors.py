    ABSTRACTION_WINDOW_CLOSED = "ERR_ABSTRACTION_WINDOW_CLOSED"
    INVALID_INTERVAL_DATES = "ERR_INVALID_INTERVAL_DATES"
    SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    DUPLICATE_CASE_MRN = "ERR_DUPLICATE_CASE_MRN"
    DUPLICATE_CONFIGURATION = "ERR_DUPLICATE_CONFIGURATION"
    AGREEMENT_INTERVAL_OVERLAP = "ERR_AGREEMENT_INTERVAL_OVERLAP"
    SURVEYOR_WINDOW_CONFLICT = "ERR_SURVEYOR_WINDOW_CONFLICT"
    READINESS_BELOW_THRESHOLD = "ERR_READINESS_BELOW_THRESHOLD"


