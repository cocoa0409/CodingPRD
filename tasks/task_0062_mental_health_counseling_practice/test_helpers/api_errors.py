"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_CPT_DURATION_MISMATCH = "ERR_CPT_DURATION_MISMATCH"
    ERR_PAYMENT_PATH_INVALID = "ERR_PAYMENT_PATH_INVALID"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SAFETY_PLAN_REQUIRED = "ERR_SAFETY_PLAN_REQUIRED"
    ERR_PATIENT_ON_HOLD = "ERR_PATIENT_ON_HOLD"
    ERR_NO_ACTIVE_LICENSE_IN_STATE = "ERR_NO_ACTIVE_LICENSE_IN_STATE"
    ERR_TELEHEALTH_NOT_AUTHORIZED = "ERR_TELEHEALTH_NOT_AUTHORIZED"
    ERR_COSIGN_REQUIRED = "ERR_COSIGN_REQUIRED"
    ERR_PROMOTION_NOT_ELIGIBLE = "ERR_PROMOTION_NOT_ELIGIBLE"
    ERR_THERAPIST_DOUBLE_BOOKED = "ERR_THERAPIST_DOUBLE_BOOKED"
    ERR_PATIENT_DOUBLE_BOOKED = "ERR_PATIENT_DOUBLE_BOOKED"
    ERR_CLAIM_ALREADY_EXISTS = "ERR_CLAIM_ALREADY_EXISTS"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_CPT_DURATION_MISMATCH: 422,
    ApiErrorId.ERR_PAYMENT_PATH_INVALID: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SAFETY_PLAN_REQUIRED: 409,
    ApiErrorId.ERR_PATIENT_ON_HOLD: 409,
    ApiErrorId.ERR_NO_ACTIVE_LICENSE_IN_STATE: 409,
    ApiErrorId.ERR_TELEHEALTH_NOT_AUTHORIZED: 409,
    ApiErrorId.ERR_COSIGN_REQUIRED: 409,
    ApiErrorId.ERR_PROMOTION_NOT_ELIGIBLE: 409,
    ApiErrorId.ERR_THERAPIST_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_PATIENT_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CLAIM_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
