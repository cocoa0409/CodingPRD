    ERR_PRESCRIPTION_INELIGIBLE = "ERR_PRESCRIPTION_INELIGIBLE"
    ERR_PRESCRIPTION_AMOUNT_INVALID = "ERR_PRESCRIPTION_AMOUNT_INVALID"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_DISPATCH_TARGET_INVALID = "ERR_DISPATCH_TARGET_INVALID"
    ERR_REMINDER_CHANNELS_INVALID = "ERR_REMINDER_CHANNELS_INVALID"
    ERR_QUESTIONNAIRE_EMPTY = "ERR_QUESTIONNAIRE_EMPTY"
