def test_run_cancel_from_material_reserved_recredits_lots():
    """PRD §3.5: "From `MATERIAL_RESERVED`, cancellation performs the
    compensating release exactly as release-materials does — every lot
    re-credited, `consumed_lots` cleared — and additionally moves each custom
    order `SCHEDULED` on the run back to `ACCEPTED` with its
    `production_run_id` cleared to null and its `version` incremented, before
    the run's own `version` increments."

    Design: Corner/state_machines/run_cancel_from_material_reserved_recredits_lots
    """
    kit = standard_kit()
    lock_allocation(kit["allocation"]["id"])
    kit["run"] = reserve_run(kit["run"]["id"])
    assert get_lot(kit["lot"]["id"])["quantity_remaining"] == 990

    cancelled = validate_success(api.cancel_run(kit["run"]["id"], PLANNER))
    assert cancelled["status"] == "CANCELLED"
    assert cancelled["consumed_lots"] == []
    lot = get_lot(kit["lot"]["id"])
    assert lot["quantity_remaining"] == 1000 == lot["quantity_received"]
