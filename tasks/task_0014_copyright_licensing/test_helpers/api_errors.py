"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Auth
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # Existence
    ERR_NOT_FOUND = "ERR_NOT_FOUND"

    # Concurrency / state
    ERR_VERSION_MISMATCH = "ERR_VERSION_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"

    # Work / ownership
    ERR_OWNERSHIP_SHARES_INVALID = "ERR_OWNERSHIP_SHARES_INVALID"
    ERR_OWNERSHIP_PROOF_MISSING = "ERR_OWNERSHIP_PROOF_MISSING"
    ERR_DUPLICATE_CO_OWNER = "ERR_DUPLICATE_CO_OWNER"
    ERR_WORK_NOT_REGISTERED = "ERR_WORK_NOT_REGISTERED"

    # License negotiation
    ERR_NOT_YOUR_TURN = "ERR_NOT_YOUR_TURN"
    ERR_EXCLUSIVE_LICENSE_VIOLATION = "ERR_EXCLUSIVE_LICENSE_VIOLATION"
    ERR_TERRITORY_TERM_OVERLAP = "ERR_TERRITORY_TERM_OVERLAP"

    # Contract / signing
    ERR_LICENSE_NOT_ACCEPTED = "ERR_LICENSE_NOT_ACCEPTED"
    ERR_LICENSE_NOT_EFFECTIVE = "ERR_LICENSE_NOT_EFFECTIVE"
    ERR_SIGNATURE_OUT_OF_ORDER = "ERR_SIGNATURE_OUT_OF_ORDER"
    ERR_DUPLICATE_SIGNATURE = "ERR_DUPLICATE_SIGNATURE"
    ERR_EFFECTIVE_DATE_OUT_OF_TERM = "ERR_EFFECTIVE_DATE_OUT_OF_TERM"

    # Royalties
    ERR_INVALID_PERIOD = "ERR_INVALID_PERIOD"
    ERR_INVALID_REVERSAL = "ERR_INVALID_REVERSAL"
    ERR_PAYMENT_AMOUNT_MISMATCH = "ERR_PAYMENT_AMOUNT_MISMATCH"

    # Pinning
    ERR_PINNED_VERSION_STALE = "ERR_PINNED_VERSION_STALE"
    ERR_PINNED_CERTIFICATE_STALE = "ERR_PINNED_CERTIFICATE_STALE"

    # External events
    ERR_DUPLICATE_EXTERNAL_EVENT = "ERR_DUPLICATE_EXTERNAL_EVENT"

    # Infringement
    ERR_EVIDENCE_MISSING = "ERR_EVIDENCE_MISSING"
    ERR_COMPENSATION_INVALID = "ERR_COMPENSATION_INVALID"

    # Term well-formedness
    ERR_INVALID_TERM = "ERR_INVALID_TERM"

    # Settlement gating
    ERR_HAS_PENDING_SETTLEMENTS = "ERR_HAS_PENDING_SETTLEMENTS"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VERSION_MISMATCH: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_OWNERSHIP_SHARES_INVALID: 422,
    ApiErrorId.ERR_OWNERSHIP_PROOF_MISSING: 422,
    ApiErrorId.ERR_DUPLICATE_CO_OWNER: 409,
    ApiErrorId.ERR_WORK_NOT_REGISTERED: 409,
    ApiErrorId.ERR_NOT_YOUR_TURN: 409,
    ApiErrorId.ERR_EXCLUSIVE_LICENSE_VIOLATION: 409,
    ApiErrorId.ERR_TERRITORY_TERM_OVERLAP: 409,
    ApiErrorId.ERR_LICENSE_NOT_ACCEPTED: 409,
    ApiErrorId.ERR_LICENSE_NOT_EFFECTIVE: 409,
    ApiErrorId.ERR_SIGNATURE_OUT_OF_ORDER: 409,
    ApiErrorId.ERR_DUPLICATE_SIGNATURE: 409,
    ApiErrorId.ERR_EFFECTIVE_DATE_OUT_OF_TERM: 422,
    ApiErrorId.ERR_INVALID_PERIOD: 422,
    ApiErrorId.ERR_INVALID_REVERSAL: 409,
    ApiErrorId.ERR_PAYMENT_AMOUNT_MISMATCH: 409,
    ApiErrorId.ERR_PINNED_VERSION_STALE: 409,
    ApiErrorId.ERR_PINNED_CERTIFICATE_STALE: 409,
    ApiErrorId.ERR_DUPLICATE_EXTERNAL_EVENT: 409,
    ApiErrorId.ERR_EVIDENCE_MISSING: 422,
    ApiErrorId.ERR_COMPENSATION_INVALID: 422,
    ApiErrorId.ERR_INVALID_TERM: 422,
    ApiErrorId.ERR_HAS_PENDING_SETTLEMENTS: 409,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
