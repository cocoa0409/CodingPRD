"""Error IDs and HTTP status mapping — PRD §5.

The mapping is registered with the framework at import time so
validate_error() auto-checks HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_MISSING_AUTH = "ERR_MISSING_AUTH"
    ERR_INVALID_ROLE = "ERR_INVALID_ROLE"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    # Existence — PRD §2.4
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"
    # State / concurrency — PRD §2.5 / §3
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_DUPLICATE_APPEAL = "ERR_DUPLICATE_APPEAL"
    ERR_FEE_ASSESSMENT_EXISTS = "ERR_FEE_ASSESSMENT_EXISTS"
    ERR_NOTICE_ALREADY_CLOSED = "ERR_NOTICE_ALREADY_CLOSED"
    ERR_DUPLICATE_EXEMPTION = "ERR_DUPLICATE_EXEMPTION"
    # Business safety / fairness — PRD §2.8, §3.5, §3.7, §3.8, §3.9
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_INVALID_GLOMAR_BASIS = "ERR_INVALID_GLOMAR_BASIS"
    ERR_MISSING_THIRD_PARTY_NOTICE = "ERR_MISSING_THIRD_PARTY_NOTICE"
    ERR_TOLLING_LIMIT_EXCEEDED = "ERR_TOLLING_LIMIT_EXCEEDED"
    ERR_THIRD_PARTY_DEADLINE_PASSED = "ERR_THIRD_PARTY_DEADLINE_PASSED"
    ERR_APPEAL_WINDOW_EXPIRED = "ERR_APPEAL_WINDOW_EXPIRED"
    ERR_RECORDS_FORBIDDEN_ON_GLOMAR = "ERR_RECORDS_FORBIDDEN_ON_GLOMAR"
    ERR_WAIVER_NOT_ELIGIBLE = "ERR_WAIVER_NOT_ELIGIBLE"
    ERR_FEE_NOT_RESOLVED = "ERR_FEE_NOT_RESOLVED"
    ERR_GLOMAR_WITH_RECORDS = "ERR_GLOMAR_WITH_RECORDS"
    ERR_NO_RESPONSIVE_RECORDS = "ERR_NO_RESPONSIVE_RECORDS"
    # Catch-all schema — PRD §3.10
    ERR_INVALID_INPUT = "ERR_INVALID_INPUT"


# PRD §5 — Error Code Catalogue
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_MISSING_AUTH: 401,
    ApiErrorId.ERR_INVALID_ROLE: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_DUPLICATE_APPEAL: 409,
    ApiErrorId.ERR_FEE_ASSESSMENT_EXISTS: 409,
    ApiErrorId.ERR_NOTICE_ALREADY_CLOSED: 409,
    ApiErrorId.ERR_DUPLICATE_EXEMPTION: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_INVALID_GLOMAR_BASIS: 422,
    ApiErrorId.ERR_MISSING_THIRD_PARTY_NOTICE: 422,
    ApiErrorId.ERR_TOLLING_LIMIT_EXCEEDED: 422,
    ApiErrorId.ERR_THIRD_PARTY_DEADLINE_PASSED: 422,
    ApiErrorId.ERR_APPEAL_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_RECORDS_FORBIDDEN_ON_GLOMAR: 422,
    ApiErrorId.ERR_WAIVER_NOT_ELIGIBLE: 422,
    ApiErrorId.ERR_FEE_NOT_RESOLVED: 422,
    ApiErrorId.ERR_GLOMAR_WITH_RECORDS: 422,
    ApiErrorId.ERR_NO_RESPONSIVE_RECORDS: 422,
    ApiErrorId.ERR_INVALID_INPUT: 400,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
