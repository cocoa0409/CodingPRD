def unauthenticated(msg="Missing or unrecognized authentication headers"):
    return ApiError(ERR_UNAUTHENTICATED, 401, msg)


def unauthorized_role(msg="Role not authorized for this endpoint"):
    return ApiError(ERR_UNAUTHORIZED_ROLE, 403, msg)


def ownership_mismatch(msg="Caller does not own this resource"):
    return ApiError(ERR_OWNERSHIP_MISMATCH, 403, msg)


def not_found(msg="Resource not found"):
    return ApiError(ERR_NOT_FOUND, 404, msg)


def invalid_request(msg="Invalid request"):
    return ApiError(ERR_INVALID_REQUEST, 400, msg)


def stale_version(msg="Stale version"):
    return ApiError(ERR_STALE_VERSION, 412, msg)


def invalid_state(msg="Invalid state for this operation"):
    return ApiError(ERR_INVALID_STATE, 409, msg)
