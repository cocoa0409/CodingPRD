    ERR_RECIPE_NOT_FOUND = "ERR_RECIPE_NOT_FOUND"
    ERR_ADJUSTMENT_NOT_FOUND = "ERR_ADJUSTMENT_NOT_FOUND"
    ERR_WAREHOUSE_NOT_FOUND = "ERR_WAREHOUSE_NOT_FOUND"
    ERR_LOT_NOT_FOUND = "ERR_LOT_NOT_FOUND"
    ERR_FEEDBACK_NOT_FOUND = "ERR_FEEDBACK_NOT_FOUND"

    # ---- request shape / payload ----
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_FEEDBACK_PAYLOAD = "ERR_INVALID_FEEDBACK_PAYLOAD"
    ERR_INVALID_PET_LIST = "ERR_INVALID_PET_LIST"
    ERR_INVALID_CANCEL_REASON = "ERR_INVALID_CANCEL_REASON"
    ERR_INVALID_PAUSE_WINDOW = "ERR_INVALID_PAUSE_WINDOW"

    # ---- state conflicts ----
    ERR_INVALID_SUBSCRIPTION_STATE = "ERR_INVALID_SUBSCRIPTION_STATE"
    ERR_INVALID_ORDER_STATE = "ERR_INVALID_ORDER_STATE"
    ERR_INVALID_ADJUSTMENT_STATE = "ERR_INVALID_ADJUSTMENT_STATE"
    ERR_PET_NOT_ACTIVE = "ERR_PET_NOT_ACTIVE"
    ERR_PAUSE_BLOCKED_IN_TRANSIT = "ERR_PAUSE_BLOCKED_IN_TRANSIT"

