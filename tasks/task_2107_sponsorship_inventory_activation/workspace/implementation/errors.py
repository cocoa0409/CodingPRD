"""Error catalogue (PRD 5. Error Code Catalogue / SCAFFOLD 1.6)."""


class ApiError(Exception):
    """Raised anywhere in a request to abort with the standard error envelope."""

    def __init__(self, error_id, http_status=None, message=None):
        self.error_id = error_id
        self.http_status = http_status if http_status is not None else ERROR_STATUS.get(error_id, 400)
        self.message = message or DEFAULT_MESSAGE.get(error_id, error_id)
        super().__init__(self.message)


