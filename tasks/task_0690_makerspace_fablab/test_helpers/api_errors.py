"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_WAIVER_REQUIRED = "ERR_WAIVER_REQUIRED"
    ERR_CERTIFICATION_REQUIRED = "ERR_CERTIFICATION_REQUIRED"
    ERR_READINESS_NOT_MET = "ERR_READINESS_NOT_MET"
    ERR_RESERVATION_OVERLAP = "ERR_RESERVATION_OVERLAP"
    ERR_CONVERT_TO_MONTHLY = "ERR_CONVERT_TO_MONTHLY"
    ERR_WORKSHOP_FULL = "ERR_WORKSHOP_FULL"
    ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
    ERR_INSUFFICIENT_FUNDS = "ERR_INSUFFICIENT_FUNDS"
    ERR_MACHINE_OUT_OF_SERVICE = "ERR_MACHINE_OUT_OF_SERVICE"
    ERR_DUPLICATE_ENROLLMENT = "ERR_DUPLICATE_ENROLLMENT"
    ERR_DUPLICATE_TIER_CODE = "ERR_DUPLICATE_TIER_CODE"
    ERR_DUPLICATE_SKU = "ERR_DUPLICATE_SKU"
    ERR_WINDOW_NOT_OPEN = "ERR_WINDOW_NOT_OPEN"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_WAIVER_REQUIRED: 409,
    ApiErrorId.ERR_CERTIFICATION_REQUIRED: 409,
    ApiErrorId.ERR_READINESS_NOT_MET: 409,
    ApiErrorId.ERR_RESERVATION_OVERLAP: 409,
    ApiErrorId.ERR_CONVERT_TO_MONTHLY: 409,
    ApiErrorId.ERR_WORKSHOP_FULL: 409,
    ApiErrorId.ERR_INSUFFICIENT_STOCK: 409,
    ApiErrorId.ERR_INSUFFICIENT_FUNDS: 409,
    ApiErrorId.ERR_MACHINE_OUT_OF_SERVICE: 409,
    ApiErrorId.ERR_DUPLICATE_ENROLLMENT: 409,
    ApiErrorId.ERR_DUPLICATE_TIER_CODE: 409,
    ApiErrorId.ERR_DUPLICATE_SKU: 409,
    ApiErrorId.ERR_WINDOW_NOT_OPEN: 409,
    ApiErrorId.ERR_VALIDATION_LIMIT: 400,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
