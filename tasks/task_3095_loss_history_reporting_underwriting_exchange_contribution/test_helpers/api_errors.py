"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCED_NOT_FOUND = "ERR_REFERENCED_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_CARRIER_NOT_ACTIVE = "ERR_CARRIER_NOT_ACTIVE"
    ERR_RECIPROCITY_REQUIRED = "ERR_RECIPROCITY_REQUIRED"
    ERR_PERMISSIBLE_PURPOSE = "ERR_PERMISSIBLE_PURPOSE"
    ERR_CONSUMER_FILE_FROZEN = "ERR_CONSUMER_FILE_FROZEN"
    ERR_DISPUTE_ALREADY_OPEN = "ERR_DISPUTE_ALREADY_OPEN"
    ERR_DISPUTE_OVERDUE = "ERR_DISPUTE_OVERDUE"
    ERR_BATCH_CONSTRAINT = "ERR_BATCH_CONSTRAINT"
    ERR_INQUIRY_CAP_EXCEEDED = "ERR_INQUIRY_CAP_EXCEEDED"
    ERR_EXCHANGE_RULE_EXISTS = "ERR_EXCHANGE_RULE_EXISTS"


HTTP_STATUS_CODES = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCED_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_CARRIER_NOT_ACTIVE: 409,
    ApiErrorId.ERR_RECIPROCITY_REQUIRED: 409,
    ApiErrorId.ERR_PERMISSIBLE_PURPOSE: 403,
    ApiErrorId.ERR_CONSUMER_FILE_FROZEN: 409,
    ApiErrorId.ERR_DISPUTE_ALREADY_OPEN: 409,
    ApiErrorId.ERR_DISPUTE_OVERDUE: 409,
    ApiErrorId.ERR_BATCH_CONSTRAINT: 422,
    ApiErrorId.ERR_INQUIRY_CAP_EXCEEDED: 409,
    ApiErrorId.ERR_EXCHANGE_RULE_EXISTS: 409,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(HTTP_STATUS_CODES)
