"""Error IDs and HTTP status mapping (PRD Section 5).

Registers the mapping with the framework so validate_error() auto-checks the
HTTP status code from the error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_INVALID_TIME_WINDOW = "ERR_INVALID_TIME_WINDOW"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_BOOKING_VERSION = "ERR_STALE_BOOKING_VERSION"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_SPACE_KIND_MISMATCH = "ERR_SPACE_KIND_MISMATCH"
    ERR_SPACE_DOUBLE_BOOKED = "ERR_SPACE_DOUBLE_BOOKED"
    ERR_WALKTHROUGH_CONFLICT = "ERR_WALKTHROUGH_CONFLICT"
    ERR_COORDINATOR_AT_CAPACITY = "ERR_COORDINATOR_AT_CAPACITY"
    ERR_VENDOR_COI_MISSING = "ERR_VENDOR_COI_MISSING"
    ERR_GUARANTEE_DEADLINE_PASSED = "ERR_GUARANTEE_DEADLINE_PASSED"
    ERR_DEPOSIT_NOT_SETTLED = "ERR_DEPOSIT_NOT_SETTLED"
    ERR_BALANCE_OUTSTANDING = "ERR_BALANCE_OUTSTANDING"
    ERR_OVERPAYMENT = "ERR_OVERPAYMENT"
    ERR_RESCHEDULE_IN_PROGRESS = "ERR_RESCHEDULE_IN_PROGRESS"
    ERR_WALKTHROUGH_AFTER_EVENT = "ERR_WALKTHROUGH_AFTER_EVENT"
    ERR_COI_EXPIRES_BEFORE_EVENT = "ERR_COI_EXPIRES_BEFORE_EVENT"
    ERR_VALIDATION_LIMIT = "ERR_VALIDATION_LIMIT"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN_ROLE: 403,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_INVALID_TIME_WINDOW: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_BOOKING_VERSION: 412,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_SPACE_KIND_MISMATCH: 422,
    ApiErrorId.ERR_SPACE_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_WALKTHROUGH_CONFLICT: 409,
    ApiErrorId.ERR_COORDINATOR_AT_CAPACITY: 409,
    ApiErrorId.ERR_VENDOR_COI_MISSING: 409,
    ApiErrorId.ERR_GUARANTEE_DEADLINE_PASSED: 409,
    ApiErrorId.ERR_DEPOSIT_NOT_SETTLED: 402,
    ApiErrorId.ERR_BALANCE_OUTSTANDING: 402,
    ApiErrorId.ERR_OVERPAYMENT: 422,
    ApiErrorId.ERR_RESCHEDULE_IN_PROGRESS: 409,
    ApiErrorId.ERR_WALKTHROUGH_AFTER_EVENT: 422,
    ApiErrorId.ERR_COI_EXPIRES_BEFORE_EVENT: 422,
    ApiErrorId.ERR_VALIDATION_LIMIT: 422,
}


# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
