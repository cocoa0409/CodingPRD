"""Error identifiers and the ApiError exception used across the codebase."""


class ApiError(Exception):
    def __init__(self, error_id: str, http_status: int, message: str = ""):
        super().__init__(message or error_id)
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id


# Auth / role
ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
ERR_UNKNOWN_ROLE = "ERR_UNKNOWN_ROLE"
ERR_FORBIDDEN = "ERR_FORBIDDEN"

# Existence
ERR_NOT_FOUND = "ERR_NOT_FOUND"
ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"

# State
ERR_INVALID_STATE = "ERR_INVALID_STATE"

# OCC
ERR_STALE_ORDER_VERSION = "ERR_STALE_ORDER_VERSION"
ERR_STALE_SKU_VERSION = "ERR_STALE_SKU_VERSION"

# Business
ERR_CLEARANCE_NON_RETURNABLE = "ERR_CLEARANCE_NON_RETURNABLE"
ERR_RENTAL_CATEGORY_INVALID = "ERR_RENTAL_CATEGORY_INVALID"
ERR_SEASONAL_WINDOW_CLOSED = "ERR_SEASONAL_WINDOW_CLOSED"
ERR_EVENT_LEAD_TOO_SHORT = "ERR_EVENT_LEAD_TOO_SHORT"
ERR_DELIVERY_SLOT_CONFLICT = "ERR_DELIVERY_SLOT_CONFLICT"
ERR_RENTAL_OVERLAP_CAPACITY = "ERR_RENTAL_OVERLAP_CAPACITY"
ERR_INSUFFICIENT_STOCK = "ERR_INSUFFICIENT_STOCK"
ERR_HELIUM_INSUFFICIENT = "ERR_HELIUM_INSUFFICIENT"
ERR_REVISION_LIMIT = "ERR_REVISION_LIMIT"
ERR_CLEARANCE_PCT_OUT_OF_RANGE = "ERR_CLEARANCE_PCT_OUT_OF_RANGE"
ERR_DEPOSIT_NOT_APPLICABLE = "ERR_DEPOSIT_NOT_APPLICABLE"
ERR_EVENT_CANCEL_TOO_LATE = "ERR_EVENT_CANCEL_TOO_LATE"
ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"

HTTP = {
    ERR_UNAUTHENTICATED: 401,
    ERR_UNKNOWN_ROLE: 401,
    ERR_FORBIDDEN: 403,
    ERR_NOT_FOUND: 404,
    ERR_FK_NOT_FOUND: 404,
    ERR_INVALID_STATE: 409,
    ERR_STALE_ORDER_VERSION: 412,
    ERR_STALE_SKU_VERSION: 412,
    ERR_CLEARANCE_NON_RETURNABLE: 422,
    ERR_RENTAL_CATEGORY_INVALID: 422,
    ERR_SEASONAL_WINDOW_CLOSED: 422,
    ERR_EVENT_LEAD_TOO_SHORT: 422,
    ERR_DELIVERY_SLOT_CONFLICT: 409,
    ERR_RENTAL_OVERLAP_CAPACITY: 409,
    ERR_INSUFFICIENT_STOCK: 422,
    ERR_HELIUM_INSUFFICIENT: 422,
    ERR_REVISION_LIMIT: 422,
    ERR_CLEARANCE_PCT_OUT_OF_RANGE: 422,
    ERR_DEPOSIT_NOT_APPLICABLE: 422,
    ERR_EVENT_CANCEL_TOO_LATE: 422,
    ERR_INVALID_REQUEST: 400,
}


def raise_error(error_id: str, message: str = "") -> None:
    raise ApiError(error_id, HTTP[error_id], message)
