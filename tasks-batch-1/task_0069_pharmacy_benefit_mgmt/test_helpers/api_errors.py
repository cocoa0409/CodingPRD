"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_SEGREGATION_OF_DUTIES = "ERR_SEGREGATION_OF_DUTIES"
    ERR_INACTIVE_RESOURCE = "ERR_INACTIVE_RESOURCE"
    ERR_INVALID_DAYS_SUPPLY = "ERR_INVALID_DAYS_SUPPLY"
    ERR_SPECIALTY_PHARMACY_REQUIRED = "ERR_SPECIALTY_PHARMACY_REQUIRED"
    ERR_PA_REQUIRED = "ERR_PA_REQUIRED"
    ERR_STEP_THERAPY_NOT_MET = "ERR_STEP_THERAPY_NOT_MET"
    ERR_PA_WINDOW_EXPIRED = "ERR_PA_WINDOW_EXPIRED"
    ERR_REFILL_TOO_SOON = "ERR_REFILL_TOO_SOON"
    ERR_COPAY_CARD_INVALID = "ERR_COPAY_CARD_INVALID"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_SEGREGATION_OF_DUTIES: 403,
    ApiErrorId.ERR_INACTIVE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_DAYS_SUPPLY: 422,
    ApiErrorId.ERR_SPECIALTY_PHARMACY_REQUIRED: 422,
    ApiErrorId.ERR_PA_REQUIRED: 422,
    ApiErrorId.ERR_STEP_THERAPY_NOT_MET: 422,
    ApiErrorId.ERR_PA_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_REFILL_TOO_SOON: 422,
    ApiErrorId.ERR_COPAY_CARD_INVALID: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
}

# Register so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
