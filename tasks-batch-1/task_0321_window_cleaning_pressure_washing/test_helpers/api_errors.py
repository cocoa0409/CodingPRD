"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After defining the mapping, register it with the framework so validate_error()
auto-cross-checks the HTTP status of every asserted error_id.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_REFERENTIAL_MISMATCH = "ERR_REFERENTIAL_MISMATCH"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_QUOTE_EXPIRED = "ERR_QUOTE_EXPIRED"
    ERR_AGREEMENT_NOT_ACTIVE = "ERR_AGREEMENT_NOT_ACTIVE"
    ERR_ROUTE_NOT_PLANNING = "ERR_ROUTE_NOT_PLANNING"
    ERR_VISIT_NOT_COMPLETED = "ERR_VISIT_NOT_COMPLETED"
    ERR_CREW_OFFLINE = "ERR_CREW_OFFLINE"
    ERR_CREW_SKILL_MISSING = "ERR_CREW_SKILL_MISSING"
    ERR_BEFORE_PHOTO_REQUIRED = "ERR_BEFORE_PHOTO_REQUIRED"
    ERR_AFTER_PHOTO_REQUIRED = "ERR_AFTER_PHOTO_REQUIRED"
    ERR_REGION_MISMATCH = "ERR_REGION_MISMATCH"
    ERR_DATE_MISMATCH = "ERR_DATE_MISMATCH"
    ERR_VISIT_WINDOW_OVERLAP = "ERR_VISIT_WINDOW_OVERLAP"
    ERR_NO_WEATHER_HOLD = "ERR_NO_WEATHER_HOLD"
    ERR_ROUTE_CAPACITY_EXCEEDED = "ERR_ROUTE_CAPACITY_EXCEEDED"
    ERR_DEPOSIT_NOT_MET = "ERR_DEPOSIT_NOT_MET"
    ERR_DUPLICATE_INVOICE = "ERR_DUPLICATE_INVOICE"
    ERR_STALE_ROUTE_VERSION = "ERR_STALE_ROUTE_VERSION"
    ERR_OPEN_VISITS_EXIST = "ERR_OPEN_VISITS_EXIST"
    ERR_EMPTY_ROUTE = "ERR_EMPTY_ROUTE"
    ERR_CREW_DOUBLE_BOOKED = "ERR_CREW_DOUBLE_BOOKED"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENTIAL_MISMATCH: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_QUOTE_EXPIRED: 409,
    ApiErrorId.ERR_AGREEMENT_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ROUTE_NOT_PLANNING: 409,
    ApiErrorId.ERR_VISIT_NOT_COMPLETED: 409,
    ApiErrorId.ERR_CREW_OFFLINE: 409,
    ApiErrorId.ERR_CREW_SKILL_MISSING: 422,
    ApiErrorId.ERR_BEFORE_PHOTO_REQUIRED: 422,
    ApiErrorId.ERR_AFTER_PHOTO_REQUIRED: 422,
    ApiErrorId.ERR_REGION_MISMATCH: 422,
    ApiErrorId.ERR_DATE_MISMATCH: 422,
    ApiErrorId.ERR_VISIT_WINDOW_OVERLAP: 409,
    ApiErrorId.ERR_NO_WEATHER_HOLD: 409,
    ApiErrorId.ERR_ROUTE_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_DEPOSIT_NOT_MET: 422,
    ApiErrorId.ERR_DUPLICATE_INVOICE: 409,
    ApiErrorId.ERR_STALE_ROUTE_VERSION: 412,
    ApiErrorId.ERR_OPEN_VISITS_EXIST: 409,
    ApiErrorId.ERR_EMPTY_ROUTE: 422,
    ApiErrorId.ERR_CREW_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_INVALID_REQUEST: 400,
}

# Register with the framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
