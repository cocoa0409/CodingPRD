def not_found(error_id, what):
    return ApiError(error_id, 404, f"{what} not found")


def state_forbids(error_id, what):
    return ApiError(error_id, 409, f"{what} is not in a state that allows this operation")


def invalid_request(message):
    return ApiError(ERR_INVALID_REQUEST, 400, message)
