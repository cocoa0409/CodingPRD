"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_AMOUNT_NOT_POSITIVE = "ERR_AMOUNT_NOT_POSITIVE"
    ERR_CATEGORY_NOT_FOUND = "ERR_CATEGORY_NOT_FOUND"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ACTIVE_IPE_EXISTS = "ERR_ACTIVE_IPE_EXISTS"
    ERR_IPE_NOT_APPROVED = "ERR_IPE_NOT_APPROVED"
    ERR_PROVIDER_INELIGIBLE = "ERR_PROVIDER_INELIGIBLE"
    ERR_AUTHORIZATION_PERIOD_OVERLAP = "ERR_AUTHORIZATION_PERIOD_OVERLAP"
    ERR_PROVIDER_CAPACITY_EXCEEDED = "ERR_PROVIDER_CAPACITY_EXCEEDED"
    ERR_BUDGET_EXCEEDED = "ERR_BUDGET_EXCEEDED"
    ERR_PAYMENT_EXCEEDS_AUTHORIZATION = "ERR_PAYMENT_EXCEEDS_AUTHORIZATION"
    ERR_STABILIZATION_NOT_MET = "ERR_STABILIZATION_NOT_MET"
    ERR_PLACEMENT_TYPE_INVALID = "ERR_PLACEMENT_TYPE_INVALID"
    ERR_NO_SLOT_AVAILABLE = "ERR_NO_SLOT_AVAILABLE"
    ERR_NO_WAITLISTED_CASE = "ERR_NO_WAITLISTED_CASE"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_AMOUNT_NOT_POSITIVE: 422,
    ApiErrorId.ERR_CATEGORY_NOT_FOUND: 422,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ACTIVE_IPE_EXISTS: 409,
    ApiErrorId.ERR_IPE_NOT_APPROVED: 409,
    ApiErrorId.ERR_PROVIDER_INELIGIBLE: 422,
    ApiErrorId.ERR_AUTHORIZATION_PERIOD_OVERLAP: 409,
    ApiErrorId.ERR_PROVIDER_CAPACITY_EXCEEDED: 409,
    ApiErrorId.ERR_BUDGET_EXCEEDED: 409,
    ApiErrorId.ERR_PAYMENT_EXCEEDS_AUTHORIZATION: 409,
    ApiErrorId.ERR_STABILIZATION_NOT_MET: 409,
    ApiErrorId.ERR_PLACEMENT_TYPE_INVALID: 409,
    ApiErrorId.ERR_NO_SLOT_AVAILABLE: 409,
    ApiErrorId.ERR_NO_WAITLISTED_CASE: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
