"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

After definition, the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes without each test
passing them explicitly.
"""
from __future__ import annotations

from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # Auth — PRD §2.1
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_AUTH_FORBIDDEN = "ERR_AUTH_FORBIDDEN"
    ERR_AUTH_IDENTITY_UNKNOWN = "ERR_AUTH_IDENTITY_UNKNOWN"

    # Existence — PRD §2.6
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_FK_NOT_FOUND = "ERR_FK_NOT_FOUND"

    # State — PRD §2.7 / §3
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_INVALID_TRADE_STATE = "ERR_INVALID_TRADE_STATE"

    # Business safety / compliance — PRD §2.7
    ERR_ACCOUNT_FROZEN = "ERR_ACCOUNT_FROZEN"
    ERR_WASH_SALE_VIOLATION = "ERR_WASH_SALE_VIOLATION"
    ERR_SECURITY_NOT_INVESTABLE = "ERR_SECURITY_NOT_INVESTABLE"

    # Business constraint — PRD §3.4 / §3.7 / §3.8
    ERR_INSUFFICIENT_LOT_SHARES = "ERR_INSUFFICIENT_LOT_SHARES"
    ERR_INSUFFICIENT_POSITION_SHARES = "ERR_INSUFFICIENT_POSITION_SHARES"
    ERR_REBALANCE_ALREADY_IN_PROGRESS = "ERR_REBALANCE_ALREADY_IN_PROGRESS"
    ERR_DRIFT_BELOW_THRESHOLD = "ERR_DRIFT_BELOW_THRESHOLD"
    ERR_HARVEST_THRESHOLD_NOT_MET = "ERR_HARVEST_THRESHOLD_NOT_MET"
    ERR_ALLOCATION_INVALID = "ERR_ALLOCATION_INVALID"
    ERR_CORRELATION_INVALID = "ERR_CORRELATION_INVALID"
    ERR_QUESTIONNAIRE_OUT_OF_RANGE = "ERR_QUESTIONNAIRE_OUT_OF_RANGE"
    ERR_TIME_HORIZON_OUT_OF_RANGE = "ERR_TIME_HORIZON_OUT_OF_RANGE"
    ERR_FORM_ALREADY_EXISTS = "ERR_FORM_ALREADY_EXISTS"
    ERR_OPEN_TRADES_FOR_TAX_YEAR = "ERR_OPEN_TRADES_FOR_TAX_YEAR"
    ERR_INSUFFICIENT_CASH = "ERR_INSUFFICIENT_CASH"

    # OCC — PRD §2.5
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"

    # Pagination — PRD §2.3
    ERR_PAGINATION_INVALID = "ERR_PAGINATION_INVALID"

    # Client suspension — PRD §3.1
    ERR_CLIENT_NOT_ACCEPTING_INPUT = "ERR_CLIENT_NOT_ACCEPTING_INPUT"


# PRD §5 — Error Code Catalogue (HTTP status mapping).
HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_AUTH_FORBIDDEN: 403,
    ApiErrorId.ERR_AUTH_IDENTITY_UNKNOWN: 403,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_FK_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_INVALID_TRADE_STATE: 409,
    ApiErrorId.ERR_ACCOUNT_FROZEN: 409,
    ApiErrorId.ERR_WASH_SALE_VIOLATION: 422,
    ApiErrorId.ERR_SECURITY_NOT_INVESTABLE: 422,
    ApiErrorId.ERR_INSUFFICIENT_LOT_SHARES: 422,
    ApiErrorId.ERR_INSUFFICIENT_POSITION_SHARES: 422,
    ApiErrorId.ERR_REBALANCE_ALREADY_IN_PROGRESS: 409,
    ApiErrorId.ERR_DRIFT_BELOW_THRESHOLD: 422,
    ApiErrorId.ERR_HARVEST_THRESHOLD_NOT_MET: 422,
    ApiErrorId.ERR_ALLOCATION_INVALID: 422,
    ApiErrorId.ERR_CORRELATION_INVALID: 422,
    ApiErrorId.ERR_QUESTIONNAIRE_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_TIME_HORIZON_OUT_OF_RANGE: 422,
    ApiErrorId.ERR_FORM_ALREADY_EXISTS: 409,
    ApiErrorId.ERR_OPEN_TRADES_FOR_TAX_YEAR: 409,
    ApiErrorId.ERR_INSUFFICIENT_CASH: 422,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_PAGINATION_INVALID: 422,
    ApiErrorId.ERR_CLIENT_NOT_ACCEPTING_INPUT: 409,
}


# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()},
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
