"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_SAFETY_INTERLOCK = "ERR_SAFETY_INTERLOCK"
    ERR_REFERENTIAL_MISMATCH = "ERR_REFERENTIAL_MISMATCH"
    ERR_TEMPORAL_CONFLICT = "ERR_TEMPORAL_CONFLICT"
    ERR_CAPACITY_EXCEEDED = "ERR_CAPACITY_EXCEEDED"
    ERR_INSUFFICIENT_INVENTORY = "ERR_INSUFFICIENT_INVENTORY"
    ERR_NO_ELIGIBLE_DRIVE_UNIT = "ERR_NO_ELIGIBLE_DRIVE_UNIT"
    ERR_NO_ELIGIBLE_POD = "ERR_NO_ELIGIBLE_POD"
    ERR_VALIDATION = "ERR_VALIDATION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_SAFETY_INTERLOCK: 422,
    ApiErrorId.ERR_REFERENTIAL_MISMATCH: 422,
    ApiErrorId.ERR_TEMPORAL_CONFLICT: 422,
    ApiErrorId.ERR_CAPACITY_EXCEEDED: 422,
    ApiErrorId.ERR_INSUFFICIENT_INVENTORY: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_DRIVE_UNIT: 422,
    ApiErrorId.ERR_NO_ELIGIBLE_POD: 422,
    ApiErrorId.ERR_VALIDATION: 400,
}

# Register with framework so validate_error() auto-checks HTTP status
set_error_http_status_map(HTTP_STATUS_CODES)
