"""Error IDs and HTTP status mapping (PRD §5).

After definition the mapping is registered with the framework so
validate_error() can auto-check HTTP status codes.
"""
from __future__ import annotations
from enum import Enum

from prd_bench_local_runner.testing.validators import (
    set_error_http_status_map,
)


class ApiErrorId(str, Enum):
    # ---- auth / authz (PRD §5) ----
    ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
    ERR_FORBIDDEN = "ERR_FORBIDDEN"

    # ---- existence (PRD §5) ----
    ERR_WORK_ORDER_NOT_FOUND = "ERR_WORK_ORDER_NOT_FOUND"
    ERR_ASSIGNMENT_NOT_FOUND = "ERR_ASSIGNMENT_NOT_FOUND"
    ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
    ERR_REFERENCE_NOT_FOUND = "ERR_REFERENCE_NOT_FOUND"

    # ---- state (PRD §5) ----
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_ASSIGNMENT_NOT_PENDING = "ERR_ASSIGNMENT_NOT_PENDING"
    ERR_ALREADY_PAUSED = "ERR_ALREADY_PAUSED"
    ERR_NOT_PAUSED = "ERR_NOT_PAUSED"
    ERR_SURVEY_NOT_PENDING = "ERR_SURVEY_NOT_PENDING"

    # ---- business safety / referential / temporal / constraint ----
    ERR_ANONYMOUS_PII_LEAK = "ERR_ANONYMOUS_PII_LEAK"
    ERR_SURVEY_CHANNEL_FORBIDDEN = "ERR_SURVEY_CHANNEL_FORBIDDEN"
    ERR_JURISDICTION_NO_DEPARTMENT = "ERR_JURISDICTION_NO_DEPARTMENT"
    ERR_JURISDICTION_MISMATCH = "ERR_JURISDICTION_MISMATCH"
    ERR_OPINIONS_INCOMPLETE = "ERR_OPINIONS_INCOMPLETE"
    ERR_DISAGREEMENT_UNRESOLVED = "ERR_DISAGREEMENT_UNRESOLVED"
    ERR_SUPERVISION_OPEN = "ERR_SUPERVISION_OPEN"
    ERR_REOPEN_WINDOW_EXPIRED = "ERR_REOPEN_WINDOW_EXPIRED"
    ERR_SURVEY_EXPIRED = "ERR_SURVEY_EXPIRED"
    ERR_CATEGORY_UNKNOWN = "ERR_CATEGORY_UNKNOWN"

    # ---- OCC / validation / duplicate ----
    ERR_VERSION_CONFLICT = "ERR_VERSION_CONFLICT"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_DUPLICATE_LINKED = "ERR_DUPLICATE_LINKED"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_AUTH_MISSING: 401,
    ApiErrorId.ERR_FORBIDDEN: 403,
    ApiErrorId.ERR_WORK_ORDER_NOT_FOUND: 404,
    ApiErrorId.ERR_ASSIGNMENT_NOT_FOUND: 404,
    ApiErrorId.ERR_RESOURCE_NOT_FOUND: 404,
    ApiErrorId.ERR_REFERENCE_NOT_FOUND: 422,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_ASSIGNMENT_NOT_PENDING: 409,
    ApiErrorId.ERR_ALREADY_PAUSED: 409,
    ApiErrorId.ERR_NOT_PAUSED: 409,
    ApiErrorId.ERR_SURVEY_NOT_PENDING: 409,
    ApiErrorId.ERR_ANONYMOUS_PII_LEAK: 422,
    ApiErrorId.ERR_SURVEY_CHANNEL_FORBIDDEN: 422,
    ApiErrorId.ERR_JURISDICTION_NO_DEPARTMENT: 422,
    ApiErrorId.ERR_JURISDICTION_MISMATCH: 422,
    ApiErrorId.ERR_OPINIONS_INCOMPLETE: 422,
    ApiErrorId.ERR_DISAGREEMENT_UNRESOLVED: 422,
    ApiErrorId.ERR_SUPERVISION_OPEN: 422,
    ApiErrorId.ERR_REOPEN_WINDOW_EXPIRED: 422,
    ApiErrorId.ERR_SURVEY_EXPIRED: 422,
    ApiErrorId.ERR_CATEGORY_UNKNOWN: 422,
    ApiErrorId.ERR_VERSION_CONFLICT: 409,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_DUPLICATE_LINKED: 409,
}


# Register with framework so validate_error() can cross-check HTTP statuses.
set_error_http_status_map(
    {k.value: v for k, v in HTTP_STATUS_CODES.items()}
)


__all__ = ["ApiErrorId", "HTTP_STATUS_CODES"]
