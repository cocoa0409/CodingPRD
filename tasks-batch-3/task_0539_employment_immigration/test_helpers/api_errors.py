"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue).

Registers the mapping with the framework so validate_error() can cross-check
HTTP status codes automatically.
"""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_DUPLICATE_REGISTRATION = "ERR_DUPLICATE_REGISTRATION"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_PWD_NOT_ISSUED = "ERR_PWD_NOT_ISSUED"
    ERR_LCA_NOT_CERTIFIED = "ERR_LCA_NOT_CERTIFIED"
    ERR_REGISTRATION_NOT_SELECTED = "ERR_REGISTRATION_NOT_SELECTED"
    ERR_PERM_NOT_CERTIFIED = "ERR_PERM_NOT_CERTIFIED"
    ERR_WORKSITE_NOT_COVERED = "ERR_WORKSITE_NOT_COVERED"
    ERR_REGISTRATION_HAS_PETITION = "ERR_REGISTRATION_HAS_PETITION"
    ERR_RECRUITMENT_TOO_SHORT = "ERR_RECRUITMENT_TOO_SHORT"
    ERR_QUIET_PERIOD_NOT_ELAPSED = "ERR_QUIET_PERIOD_NOT_ELAPSED"
    ERR_PERM_VALIDITY_EXPIRED = "ERR_PERM_VALIDITY_EXPIRED"
    ERR_RFE_EXPIRED = "ERR_RFE_EXPIRED"
    ERR_RECRUITMENT_INCOMPLETE = "ERR_RECRUITMENT_INCOMPLETE"
    ERR_RECRUITMENT_STEP_OVERLAP = "ERR_RECRUITMENT_STEP_OVERLAP"
    ERR_EMPLOYMENT_OVERLAP = "ERR_EMPLOYMENT_OVERLAP"
    ERR_WAGE_BELOW_PREVAILING = "ERR_WAGE_BELOW_PREVAILING"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 400,
    ApiErrorId.ERR_DUPLICATE_REGISTRATION: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_PWD_NOT_ISSUED: 409,
    ApiErrorId.ERR_LCA_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_REGISTRATION_NOT_SELECTED: 409,
    ApiErrorId.ERR_PERM_NOT_CERTIFIED: 409,
    ApiErrorId.ERR_WORKSITE_NOT_COVERED: 409,
    ApiErrorId.ERR_REGISTRATION_HAS_PETITION: 409,
    ApiErrorId.ERR_RECRUITMENT_TOO_SHORT: 422,
    ApiErrorId.ERR_QUIET_PERIOD_NOT_ELAPSED: 422,
    ApiErrorId.ERR_PERM_VALIDITY_EXPIRED: 422,
    ApiErrorId.ERR_RFE_EXPIRED: 422,
    ApiErrorId.ERR_RECRUITMENT_INCOMPLETE: 422,
    ApiErrorId.ERR_RECRUITMENT_STEP_OVERLAP: 409,
    ApiErrorId.ERR_EMPLOYMENT_OVERLAP: 409,
    ApiErrorId.ERR_WAGE_BELOW_PREVAILING: 422,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
