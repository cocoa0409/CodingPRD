"""Error catalogue. Each error_id maps to an HTTP status per PRD section 5 /
scaffold 1.6."""


class ApiError(Exception):
    def __init__(self, error_id, http_status, message=None):
        self.error_id = error_id
        self.http_status = http_status
        self.message = message or error_id
        super().__init__(self.message)


# (error_id, http_status) tuples — PRD section 5 / scaffold 1.6
ERR_UNAUTHENTICATED = ("ERR_UNAUTHENTICATED", 401)
ERR_FORBIDDEN_ROLE = ("ERR_FORBIDDEN_ROLE", 403)
ERR_SEGREGATION_OF_DUTIES = ("ERR_SEGREGATION_OF_DUTIES", 403)
ERR_NOT_FOUND = ("ERR_NOT_FOUND", 404)
ERR_INVALID_REQUEST = ("ERR_INVALID_REQUEST", 400)
ERR_INVALID_STATE = ("ERR_INVALID_STATE", 409)
ERR_BASELINE_EXISTS = ("ERR_BASELINE_EXISTS", 409)
ERR_EMPTY_ESTIMATE = ("ERR_EMPTY_ESTIMATE", 422)
ERR_COMPLIANCE_NOT_CLEARED = ("ERR_COMPLIANCE_NOT_CLEARED", 409)
ERR_MATERIAL_NOT_DELIVERED = ("ERR_MATERIAL_NOT_DELIVERED", 409)
ERR_WIND_EXCEEDS_LIMIT = ("ERR_WIND_EXCEEDS_LIMIT", 409)
ERR_CREW_OVERLAP = ("ERR_CREW_OVERLAP", 409)
ERR_SITE_WINDOW_CONFLICT = ("ERR_SITE_WINDOW_CONFLICT", 409)
ERR_DELIVERY_TOO_EARLY = ("ERR_DELIVERY_TOO_EARLY", 409)
ERR_DUAL_SIGNOFF_INCOMPLETE = ("ERR_DUAL_SIGNOFF_INCOMPLETE", 409)
ERR_MILESTONE_INCOMPLETE = ("ERR_MILESTONE_INCOMPLETE", 409)
ERR_DTI_EXCEEDED = ("ERR_DTI_EXCEEDED", 422)
ERR_PRINCIPAL_EXCEEDS_CONTRACT = ("ERR_PRINCIPAL_EXCEEDS_CONTRACT", 422)
ERR_STALE_PROJECT_VERSION = ("ERR_STALE_PROJECT_VERSION", 412)
ERR_OPEN_MILESTONES = ("ERR_OPEN_MILESTONES", 409)
ERR_CANCEL_NOT_ALLOWED = ("ERR_CANCEL_NOT_ALLOWED", 409)
ERR_VALIDATION_RANGE = ("ERR_VALIDATION_RANGE", 422)


def err(code_tuple, message=None):
    error_id, http_status = code_tuple
    return ApiError(error_id, http_status, message)
