def error_http_status(error_id: str) -> int:
    """Return the canonical HTTP status for an error identifier."""
    return ERROR_HTTP_STATUS[error_id]


def error_priority(error_id: str) -> int:
    """Return the refusal-order position of an error identifier (lower wins)."""
    return ERROR_PRECEDENCE.index(error_id)


def register_error_http_statuses() -> None:
    """Teach the validators which HTTP status belongs to each error identifier."""
    set_error_http_status_map(ERROR_HTTP_STATUS)
