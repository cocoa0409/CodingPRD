"""Error IDs and HTTP status mapping (PRD §5 Error Code Catalogue)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_VALIDATION = "ERR_VALIDATION"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_EVALUATION_NOT_FINALIZED = "ERR_EVALUATION_NOT_FINALIZED"
    ERR_CREDENTIAL_MISMATCH = "ERR_CREDENTIAL_MISMATCH"
    ERR_OUTSIDE_AUTH_WINDOW = "ERR_OUTSIDE_AUTH_WINDOW"
    ERR_PROVIDER_DOUBLE_BOOKED = "ERR_PROVIDER_DOUBLE_BOOKED"
    ERR_CLIENT_BUFFER_CONFLICT = "ERR_CLIENT_BUFFER_CONFLICT"
    ERR_DELIVERED_UNITS_INVALID = "ERR_DELIVERED_UNITS_INVALID"
    ERR_UNITS_EXCEEDED = "ERR_UNITS_EXCEEDED"
    ERR_AUTHORIZATION_NOT_ACTIVE = "ERR_AUTHORIZATION_NOT_ACTIVE"
    ERR_SUPERVISION_DEFICIENT = "ERR_SUPERVISION_DEFICIENT"
    ERR_DUPLICATE_CLAIM = "ERR_DUPLICATE_CLAIM"
    ERR_SESSION_NOT_DELIVERED = "ERR_SESSION_NOT_DELIVERED"
    ERR_AUTHORIZATION_NOT_EXPIRABLE = "ERR_AUTHORIZATION_NOT_EXPIRABLE"
    ERR_STALE_VERSION = "ERR_STALE_VERSION"


HTTP_STATUS_CODES: dict = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_VALIDATION: 422,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_EVALUATION_NOT_FINALIZED: 409,
    ApiErrorId.ERR_CREDENTIAL_MISMATCH: 409,
    ApiErrorId.ERR_OUTSIDE_AUTH_WINDOW: 409,
    ApiErrorId.ERR_PROVIDER_DOUBLE_BOOKED: 409,
    ApiErrorId.ERR_CLIENT_BUFFER_CONFLICT: 409,
    ApiErrorId.ERR_DELIVERED_UNITS_INVALID: 422,
    ApiErrorId.ERR_UNITS_EXCEEDED: 409,
    ApiErrorId.ERR_AUTHORIZATION_NOT_ACTIVE: 409,
    ApiErrorId.ERR_SUPERVISION_DEFICIENT: 409,
    ApiErrorId.ERR_DUPLICATE_CLAIM: 409,
    ApiErrorId.ERR_SESSION_NOT_DELIVERED: 409,
    ApiErrorId.ERR_AUTHORIZATION_NOT_EXPIRABLE: 409,
    ApiErrorId.ERR_STALE_VERSION: 412,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
