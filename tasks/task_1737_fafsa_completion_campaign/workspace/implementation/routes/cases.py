@bp.route("/fafsa/completion-reports/<rid>/publish", methods=["POST"])
def publish_report(rid):
    auth = middleware.get_auth()
    middleware.require_roles(auth, ["CampaignAdmin"])
    report = core.get_report_or_404(rid)
    body = validate.get_json_body(required=True)
    validate.check_fields(body, required=["expected_campaign_version"], optional=[])
    expected = validate.req_int(body, "expected_campaign_version")
    campaign = core.get_campaign_or_404(report["campaign_id"])
    if report["status"] != "GENERATED":
        errors.raise_error(errors.ERR_REPORT_NOT_GENERATED, "publish requires GENERATED")
    if campaign["status"] not in ("OPEN", "STATE_GRACE"):
        errors.raise_error(errors.ERR_CAMPAIGN_NOT_OPEN, "publish requires campaign OPEN or STATE_GRACE")
    # OCC
    if campaign["version"] != expected:
        errors.raise_error(errors.ERR_STALE_VERSION, "Campaign version mismatch")

    # Supersede prior PUBLISHED report of this campaign
    for r in store.completion_reports.values():
        if r["id"] != report["id"] and r["campaign_id"] == campaign["id"] and r["status"] == "PUBLISHED":
            r["status"] = "SUPERSEDED"
            touch(r)
    report["status"] = "PUBLISHED"
    touch(report)
    # Recognition tiers recomputed for all schools of the campaign
    core.recompute_recognition_tiers(campaign)
    core.bump_campaign_version(campaign)
    return success_object(core.serialize(report))
