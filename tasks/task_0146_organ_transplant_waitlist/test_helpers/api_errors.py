"""Error IDs and HTTP status mapping (PRD §5)."""
from enum import Enum
from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    ERR_UNAUTHENTICATED = "ERR_UNAUTHENTICATED"
    ERR_UNAUTHORIZED = "ERR_UNAUTHORIZED"
    ERR_NOT_FOUND = "ERR_NOT_FOUND"
    ERR_NOT_RESOURCE_OWNER = "ERR_NOT_RESOURCE_OWNER"
    ERR_INVALID_REQUEST = "ERR_INVALID_REQUEST"
    ERR_DUPLICATE_RESOURCE = "ERR_DUPLICATE_RESOURCE"
    ERR_INVALID_STATE = "ERR_INVALID_STATE"
    ERR_STALE_ORGAN_VERSION = "ERR_STALE_ORGAN_VERSION"
    ERR_NO_FINALIZED_SCORE = "ERR_NO_FINALIZED_SCORE"
    ERR_CANDIDATE_NOT_ACTIVE = "ERR_CANDIDATE_NOT_ACTIVE"
    ERR_ABO_INCOMPATIBLE = "ERR_ABO_INCOMPATIBLE"
    ERR_POSITIVE_CROSSMATCH = "ERR_POSITIVE_CROSSMATCH"
    ERR_SIZE_INCOMPATIBLE = "ERR_SIZE_INCOMPATIBLE"
    ERR_OFFER_WINDOW_CLOSED = "ERR_OFFER_WINDOW_CLOSED"
    ERR_OFFER_WINDOW_OPEN = "ERR_OFFER_WINDOW_OPEN"
    ERR_ISCHEMIA_WINDOW_CLOSED = "ERR_ISCHEMIA_WINDOW_CLOSED"
    ERR_DUPLICATE_OPEN_OFFER = "ERR_DUPLICATE_OPEN_OFFER"
    ERR_NO_NEXT_CANDIDATE = "ERR_NO_NEXT_CANDIDATE"
    ERR_OFFER_NOT_ACCEPTED = "ERR_OFFER_NOT_ACCEPTED"
    ERR_FOLLOWUP_BEFORE_TRANSPLANT = "ERR_FOLLOWUP_BEFORE_TRANSPLANT"
    ERR_REPORT_SUBJECT_INVALID = "ERR_REPORT_SUBJECT_INVALID"
    ERR_ORGAN_TYPE_MISMATCH = "ERR_ORGAN_TYPE_MISMATCH"


HTTP_STATUS_CODES: dict[str, int] = {
    ApiErrorId.ERR_UNAUTHENTICATED: 401,
    ApiErrorId.ERR_UNAUTHORIZED: 403,
    ApiErrorId.ERR_NOT_FOUND: 404,
    ApiErrorId.ERR_NOT_RESOURCE_OWNER: 403,
    ApiErrorId.ERR_INVALID_REQUEST: 422,
    ApiErrorId.ERR_DUPLICATE_RESOURCE: 409,
    ApiErrorId.ERR_INVALID_STATE: 409,
    ApiErrorId.ERR_STALE_ORGAN_VERSION: 412,
    ApiErrorId.ERR_NO_FINALIZED_SCORE: 409,
    ApiErrorId.ERR_CANDIDATE_NOT_ACTIVE: 409,
    ApiErrorId.ERR_ABO_INCOMPATIBLE: 409,
    ApiErrorId.ERR_POSITIVE_CROSSMATCH: 409,
    ApiErrorId.ERR_SIZE_INCOMPATIBLE: 409,
    ApiErrorId.ERR_OFFER_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_OFFER_WINDOW_OPEN: 409,
    ApiErrorId.ERR_ISCHEMIA_WINDOW_CLOSED: 409,
    ApiErrorId.ERR_DUPLICATE_OPEN_OFFER: 409,
    ApiErrorId.ERR_NO_NEXT_CANDIDATE: 409,
    ApiErrorId.ERR_OFFER_NOT_ACCEPTED: 409,
    ApiErrorId.ERR_FOLLOWUP_BEFORE_TRANSPLANT: 422,
    ApiErrorId.ERR_REPORT_SUBJECT_INVALID: 422,
    ApiErrorId.ERR_ORGAN_TYPE_MISMATCH: 409,
}

# Register with framework so validate_error() auto-checks HTTP status.
set_error_http_status_map({k.value: v for k, v in HTTP_STATUS_CODES.items()})
