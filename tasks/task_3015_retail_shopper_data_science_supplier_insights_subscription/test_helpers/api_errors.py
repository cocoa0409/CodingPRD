"""Error identifiers and HTTP status mapping (contract error catalogue).

Registering the mapping with the shared validators lets ``validate_error``
cross-check the HTTP status automatically, so a test only names the identifier
it expects.
"""

from enum import Enum

from prd_bench_local_runner.testing.validators import set_error_http_status_map


class ApiErrorId(str, Enum):
    # Credentials and role authorization.
    MISSING_OR_INVALID_USER_CONTEXT_HEADER = "ERR_MISSING_OR_INVALID_USER_CONTEXT_HEADER"
    FORBIDDEN_ROLE = "ERR_FORBIDDEN_ROLE"

    # Request shape and existence.
    INVALID_REQUEST = "ERR_INVALID_REQUEST"
    RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"

    # State preconditions.
    CONTRACT_NOT_ACTIVE = "ERR_CONTRACT_NOT_ACTIVE"
    GRANT_NOT_QUERYABLE = "ERR_GRANT_NOT_QUERYABLE"
    GRANT_EXPIRED = "ERR_GRANT_EXPIRED"
    GRANT_NOT_APPROVABLE = "ERR_GRANT_NOT_APPROVABLE"
    CYCLE_NOT_OPEN = "ERR_CYCLE_NOT_OPEN"
    CYCLE_NOT_LOCKABLE = "ERR_CYCLE_NOT_LOCKABLE"
    REPORT_NOT_GENERATABLE = "ERR_REPORT_NOT_GENERATABLE"
    REPORT_NOT_CANCELLABLE = "ERR_REPORT_NOT_CANCELLABLE"
    SEGMENT_NOT_SUBMITTABLE = "ERR_SEGMENT_NOT_SUBMITTABLE"
    SEGMENT_NOT_APPROVED = "ERR_SEGMENT_NOT_APPROVED"
    ACTIVATION_NOT_LAUNCHABLE = "ERR_ACTIVATION_NOT_LAUNCHABLE"
    STUDY_INVALID_TRANSITION = "ERR_STUDY_INVALID_TRANSITION"
    DELIVERABLE_NOT_SUBMITTABLE = "ERR_DELIVERABLE_NOT_SUBMITTABLE"
    DELIVERABLE_NOT_REVIEWABLE = "ERR_DELIVERABLE_NOT_REVIEWABLE"
    INVALID_STATE = "ERR_INVALID_STATE"

    # Privacy and segregation of duties.
    SELF_APPROVAL_FORBIDDEN = "ERR_SELF_APPROVAL_FORBIDDEN"
    SEGMENT_EMPTY = "ERR_SEGMENT_EMPTY"
    SEGMENT_BELOW_MINIMUM = "ERR_SEGMENT_BELOW_MINIMUM"

    # Referential business rules.
    CATEGORY_OUT_OF_SCOPE = "ERR_CATEGORY_OUT_OF_SCOPE"
    TIER_INSUFFICIENT = "ERR_TIER_INSUFFICIENT"
    ACCOUNT_HAS_ACTIVE_CONTRACT = "ERR_ACCOUNT_HAS_ACTIVE_CONTRACT"
    MODELED_DERIVATION_FORBIDDEN = "ERR_MODELED_DERIVATION_FORBIDDEN"

    # Temporal business rules.
    WINDOW_OVERLAP = "ERR_WINDOW_OVERLAP"
    CYCLE_GAP_VIOLATION = "ERR_CYCLE_GAP_VIOLATION"

    # Fiscal rules.
    INSUFFICIENT_REPORT_CREDITS = "ERR_INSUFFICIENT_REPORT_CREDITS"
    ALLOWANCE_BELOW_CONSUMED = "ERR_ALLOWANCE_BELOW_CONSUMED"
    ACTIVATION_BUDGET_EXCEEDED = "ERR_ACTIVATION_BUDGET_EXCEEDED"
    INSUFFICIENT_QUERY_BUDGET = "ERR_INSUFFICIENT_QUERY_BUDGET"

    # Redistribution clauses.
    REDISTRIBUTION_RESTRICTED = "ERR_REDISTRIBUTION_RESTRICTED"

    # Optimistic concurrency.
    STALE_CONTRACT_VERSION = "ERR_STALE_CONTRACT_VERSION"
    STALE_SEGMENT_VERSION = "ERR_STALE_SEGMENT_VERSION"


