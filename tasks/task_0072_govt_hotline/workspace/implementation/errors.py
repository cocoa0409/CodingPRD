"""Application errors: AppError exception + error ID constants + HTTP status mapping."""


class AppError(Exception):
    """Raised by services, caught by Flask error handler."""

    def __init__(self, error_id: str, message: str, http_status: int = 400):
        self.error_id = error_id
        self.message = message
        self.http_status = http_status
        super().__init__(message)


# --- Auth / RBAC ---
ERR_AUTH_MISSING = "ERR_AUTH_MISSING"
ERR_FORBIDDEN = "ERR_FORBIDDEN"

# --- Existence ---
ERR_WORK_ORDER_NOT_FOUND = "ERR_WORK_ORDER_NOT_FOUND"
ERR_ASSIGNMENT_NOT_FOUND = "ERR_ASSIGNMENT_NOT_FOUND"
ERR_RESOURCE_NOT_FOUND = "ERR_RESOURCE_NOT_FOUND"
